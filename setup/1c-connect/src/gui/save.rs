/// Адрес публикации для записи: умолчание идёт за каталогом базы, правка в
/// toml переживает его смену.
pub fn carried_base_url(saved: &Connection, new_base_path: &str) -> String {
    if saved.base_url.is_empty() || saved.base_url == cfg::derived_base_url(&saved.base_path) {
        cfg::derived_base_url(new_base_path)
    } else {
        saved.base_url.clone()
    }
}

/// Адрес публикации для записи. Две формы, и они не смешиваются:
///
/// * «уже опубликована» — адрес знает только человек, и пишется ровно то,
///   что он вписал, приведённое к полному (`cfg::full_base_url`). Пустое
///   остаётся пустым: это «не задан», и его видит замок окна, а не выдумка
///   про Apache на 80;
/// * «публикует коннектор» — поля в окне нет, адрес считается от своего
///   порта, а хранимое умолчание по-прежнему едет за каталогом базы
///   (`carried_base_url`). Своё значение переживает и это: переключение
///   туда-обратно не стирает вписанный когда-то чужой адрес.
pub fn base_url_to_write(saved: &Connection, from_form: &str, publication: &str, new_base_path: &str) -> String {
    if publication == "webserver" {
        cfg::full_base_url(from_form)
    } else {
        carried_base_url(saved, new_base_path)
    }
}

/// Каталог выгрузки для записи — тот же приём, что у адреса публикации.
/// `install` дописывает выведенный `<project>\src` в toml, и записанное
/// умолчание обязано и дальше идти за каталогом проекта: иначе смена проекта
/// оставила бы выгрузку в старом месте. Свой каталог (отличается от
/// выведенного) смену `project` переживает. Пустое поле остаётся пустым: там
/// умолчание и так считается при каждом чтении (`Cfg::dump_dir`).
pub fn carried_dump(saved: &Connection, new_project: &str) -> String {
    if saved.dump == cfg::derived_dump(&saved.project) {
        cfg::derived_dump(new_project)
    } else {
        saved.dump.clone()
    }
}

/// Что переехало за переименованием — одной строкой на каждую причину.
/// Правило одно на все переезды: о каждом говорим, ни об одном не молчим
/// (находка ревью задачи 35 — прежде журнал называл только порт публикации,
/// хотя за рабочим местом едут ещё ветка проекта и `origin`, а за каталогом
/// проекта — каталог выгрузки). `Warn`, а не `Ok`: прежний каталог выгрузки
/// остаётся лежать со старым содержимым.
///
/// С задачи 6 плана «тонкий срез ценности» порты сюда больше не попадают:
/// `mcp`/`vrunner`/`web` (`Cfg::ports`) и предпочтение публикации
/// (`derived_http_port`) стали константами и не читают рабочее место вовсе
/// — печатать здесь «порты 7771/7781/7791 переехали» значило бы сообщать
/// человеку о переезде того, что на месте и не трогалось (круговой запрет
/// проекта: молчаливый неверный результат хуже честного отказа). За
/// рабочим местом по-прежнему едут только ветка проекта и `origin`
/// (`project.rs:196-197`) — туннельная половина, которую эта задача не
/// трогает.
pub fn moved_lines(old: &Cfg, new: &Cfg) -> Vec<String> {
    let mut v = Vec::new();
    if old.current().workstation != new.current().workstation {
        v.push(format!(
            "за рабочим местом {} → {} переехали: ветка проекта и origin",
            old.current().workstation,
            new.current().workstation
        ));
    }
    if old.current().project != new.current().project && old.current().dump != new.current().dump {
        v.push(format!("за каталогом проекта переехал каталог выгрузки: {} (прежний остался со старым содержимым)", new.current().dump));
    }
    v
}

/// Чужая карточка, уже держащая ту же базу (по смыслу — `cfg::same_base`, не
/// по строке), если такая есть. Пустой `base_path` не сравниваем вовсе:
/// «путь не задан» — это отказ `Cfg::validate` со своим, понятным словом
/// («base_path — путь к базе»), а не путаница с соседом, у которого путь
/// тоже ещё не заполнен.
fn same_base_conflict<'a>(existing: &'a [Connection], host: &Connection) -> Option<&'a Connection> {
    if host.base_path.trim().is_empty() {
        return None;
    }
    existing.iter().find(|c| c.name != host.name && cfg::same_base(&c.base_path, &host.base_path))
}

/// Чужая карточка, уже держащая папку проекта той же или вложенную (по
/// смыслу — `cfg::folder_conflict`, не по строке), если такая есть. Зеркало
/// `same_base_conflict` выше — тот же приём, задача 6 плана «Модель
/// соединений», решение владельца 1: у документов нет истории, затирание в
/// чужой папке — молчаливая потеря файлов. Пустая папка не сравниваем:
/// «путь не задан» — это отказ `Cfg::validate` своим словом, а не путаница
/// с соседом, у которого папка тоже ещё не заполнена.
fn folder_conflict_owner<'a>(existing: &'a [Connection], host: &Connection) -> Option<&'a Connection> {
    if host.project.trim().is_empty() {
        return None;
    }
    existing.iter().find(|c| c.name != host.name && cfg::folder_conflict(&c.project, &host.project))
}

/// Сменилась ли база, которую обслуживает агент — путь, логин или пароль.
/// Единый список для двух потребителей, которым нужен именно этот,
/// полный: подтверждение перед «Сохранить» (`save_question` →
/// `save_needs_confirm`, вопрос человеку «агент работает с базой X, перейдёт
/// на Y») и перезапуск сеанса — сеанс с новым паролем нужен так же, как с
/// новым путём: агент обязан отвечать из той базы, в которую его только что
/// перевели. У публикации список короче — см. `descriptor_changed`.
pub fn database_changed(a: &Connection, b: &Connection) -> bool {
    a.base_path != b.base_path || a.db_user != b.db_user || a.db_password != b.db_password
}

/// Сменился ли путь базы — единственное, от чего зависит текст `default.vrd`
/// (`publication::vrd`) с задачи 6: логин и пароль дескриптор больше не
/// несёт (замер 29.10, спека «Пароля в дескрипторе публикации не должно быть
/// вовсе»), платформа берёт их из самого запроса. Смена логина или пароля
/// базы дескриптор не трогает — переподнимать публикацию ради неё незачем, и
/// `republish_after_save` смотрит именно на этот, более короткий список, а
/// не на `database_changed`.
pub fn descriptor_changed(a: &Connection, b: &Connection) -> bool {
    a.base_path != b.base_path
}

/// Записать один ключ параметров текстом, не трогая остальной файл — для
/// переключателей меню значка (`mode`, `publication`): правит строку этого
/// ключа в тексте человека (`common::toml_render::set`), тем же приёмом, что
/// `ops_host::write_derived_fields`, а НЕ перерисовывает файл целиком через
/// `render`.
///
/// Почему не `render`/`write_checked` (ревью задачи 2, Important 1):
/// `ui.cfg.current().password`/`db_password` могли прочитаться пустыми на чужом
/// шифртексте (`load_unchecked`, задача 2, — файл переехал на другую машину
/// или под другую учётку). Перерисовка всего файла записала бы это пустое
/// значение заново, стирая настоящий шифртекст человека, причём
/// `write_checked` пропустил бы такую запись молча: пустое после записи
/// читается как пустое, сравнение сошлось бы. То есть ровно в том случае,
/// ради которого сделана вся задача 2, одно нажатие в меню значка стирало бы
/// то, что ещё можно было открыть, вернувшись на свою машину или под свою
/// учётку. Правка одной строки эту категорию случаев закрывает сама: ключ,
/// который сюда не передан, в т.ч. оба пароля, не читается и не пишется
/// вовсе.
///
/// Свежего комплекта (файла параметров ещё нет) это тоже касается:
/// `cfg::EXAMPLE` — ровно то, что дал бы `render` на `Cfg::default()`
/// (`cfg::tests::example_parses_and_equals_defaults`), и строка ключа
/// дописывается в него тем же `set` — без похода за `Store` там, где все
/// пароли и так пусты.
///
/// Зачем нужен отдельный путь (а не `save_host`). На свежем комплекте поля
/// ещё пусты, и `save_host` на них отказывает — а переключатель в меню это
/// **намерение человека, а не действие над базой**: публикацию мы при нём
/// не поднимаем, и связь выключена. Держать такое намерение в памяти
/// нельзя: окно читает файл при каждом показе (`window::reread_and_recheck`),
/// и первое же открытие окна стёрло бы его — ровно это и случилось у
/// владельца 28.10, когда поле «Адрес публикации» не появилось после
/// переключения.
///
/// Всё, что `save_host` делает сверх записи (переезды, переподъём публикации,
/// перезапуск сеанса), здесь не нужно: ни один из этих ключей не меняет ни
/// базу, ни порты, а публикацию переключение разбирает само
/// (`tray::apply_publication`).
pub fn save_tray_key(ui: &mut Ui, key: &str, value: &str) -> Result<(), String> {
    save_tray_keys(ui, &[(key, value)])
}

/// То же, но ПАРОЙ ключей — одной записью на диск (Important 1 круга починки 1
/// задачи 5 плана «Карточка публикации и удаление»).
///
/// **Почему понадобилось.** В ветви отказа `save_host`
/// (`tray::apply_publication`) записывался РОВНО один ключ — публикация, — а
/// выведенный нами адрес снимался только в памяти. На диске оставалась пара
/// «publication = webserver» и наша же догадка в `base_url`: замок молчал
/// (поле непустое — `Cfg::publication_address_missing`), `Cfg::base_url()`
/// отдавал догадку, и проба уходила на ЧУЖОЙ веб-сервер на 80, а окно при
/// следующем показе возвращало догадку и в память.
///
/// **Запись ОДНА, даже когда ключей два** — тот же довод, что у `set_keys`:
/// между двумя записями файл стоял бы в половинчатом состоянии (новая
/// публикация и прежний адрес), то есть ровно в том, от которого эта правка и
/// лечит.
///
/// Проверки годности здесь нет и не нужно (см. докстроку выше): это намерение
/// человека, а не действие над базой, и путь этот существует ровно для того
/// случая, когда `save_host` уже отказал на незаполненных полях.
pub fn save_tray_keys(ui: &mut Ui, keys: &[(&str, &str)]) -> Result<(), String> {
    if keys.is_empty() {
        return Ok(());
    }
    let path = ui.kit.state_path(cfg::FILE);
    // Critical 2 ревью задачи 7: «файла нет» (`NotFound`, туда и годится образец) и «не смогли прочитать» (антивирус держит файл, нет прав, временный отказ диска) — разные причины, а прежний `unwrap_or_else` сливал их в одну и читал любой отказ как «файла нет». Следующая строка пишет текст ПОВЕРХ файла — на чужом отказе это стирало бы оба шифртекста молча, без единого слова в журнал. Любая причина кроме `NotFound` — отказ словами здесь же, до какой-либо записи.
    let text = match std::fs::read_to_string(&path) {
        Ok(t) => t,
        // Файла нет (свежий комплект) — берём образец, но СРАЗУ называем его
        // единственный блок текущим соединением: имя блока в образце —
        // подстановка («Соединение 1»), а писатель ниже ищет свой блок по
        // имени (круг починки 1 задачи 4, находка 1), и на чужом имени
        // человек получил бы отказ там, где его намерение раньше
        // записывалось (наблюдение владельца 28.10).
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            let name = if ui.cfg.current.is_empty() { cfg::FIRST_CONNECTION_NAME } else { ui.cfg.current.as_str() };
            let quoted = format!("{name:?}");
            let rooted = common::toml_render::set(cfg::EXAMPLE, "", "current", &quoted);
            common::toml_render::set_in(&rooted, cfg::CONNECTION, 0, "name", &quoted)
                .ok_or_else(|| format!("{}: в образце нет блока соединения — записывать ключ не во что", cfg::FILE))?
        }
        Err(e) => return Err(format!("{}: файл не прочитан — {e}", path.display())),
    };
    // Ключ идёт в блок ТЕКУЩЕГО соединения, а не в прежнюю секцию `[host]`
    // (задача 4 плана «Модель соединений», находка безопасности): `set` по
    // `[host]` на файле с блоками `[[connection]]` ДОПИСЫВАЛА секцию в конец
    // — записанное не читал никто, а файл с обеими половинами стал отказом
    // при чтении, то есть один щелчок в трее делал настройки нечитаемыми.
    // Довод и разбор прежнего вида файла — в `cfg::set_current`.
    let mut text = text;
    for (key, value) in keys {
        text = cfg::set_current(&text, &ui.cfg, key, &format!("{value:?}"))?;
    }
    write_text(&path, &text).map_err(|e| format!("{e:#}"))?;
    // Синхронизируем только то, что сами только что записали — остальные
    // поля `ui.cfg` не трогаем, они и на диске остались как были.
    for (key, value) in keys {
        match *key {
            "mode" => ui.cfg.current_mut().mode = value.to_string(),
            "publication" => ui.cfg.current_mut().publication = value.to_string(),
            "write" => ui.cfg.current_mut().write = value.to_string(),
            // `base_url` — с круга починки 1 задачи 5: пустой адрес ложится в
            // файл вместе с публикацией (см. докстроку), и не быть его здесь
            // значило бы, что диск и память расходятся на том самом ключе,
            // из-за которого правка и сделана.
            "base_url" => ui.cfg.current_mut().base_url = value.to_string(),
            _ => {}
        }
    }
    Ok(())
}

/// Новая карточка в список — «+ Добавить» у списка (решение владельца 3.11)
/// и ответы онбординга (задача 11), с РАЗНОЙ ролью: кнопка списка ставит
/// умолчание `"accept"` (самый частый случай у человека, уже работающего в
/// окне), онбординг передаст свою. Где база (`base_here`) функция не
/// спрашивает вовсе — топологию человек выбирает позже, уже в самой карточке
/// (ruling задачи 5): поле остаётся умолчанием `Connection::default()` —
/// `true`, «база здесь».
///
/// **Ответ человека — ответ на вопрос «Это соединение», и задаёт ОБЕ оси
/// сразу** (замер на живом окне 9.11): оба ответа, которыми сюда приходят
/// (`link::onboarding_answers` — «Подключаюсь сам» и «Принимаю подключения»),
/// говорят, что конец не один — значит это и РОЛЬ (параметр `role`), и РЕЖИМ
/// (`mode = "tunnel"`, ниже). «Всё на одной машине» (`link::LOCAL_ANSWER`) —
/// третий ответ того же вопроса, и среди ответов заведения его нет вовсе
/// (онбординг и «+ Добавить» предлагают только первые два): локальной
/// заведённая здесь карточка не бывает. До этой правки `mode` оставался
/// умолчанием `Connection::default()` — «local», — и первый же экран после
/// ответа противоречил ответу: человек жал «Принимаю подключения», а карточка
/// показывала переключателем «Это соединение» третий, не заданный им ответ.
///
/// **Новая карточка не становится текущей сама.** Переключение текущего
/// соединения — отдельное действие человека (`Cfg::switch_current`), не
/// побочный эффект добавления: агент, который прямо сейчас отвечает из своей
/// базы, не обязан молча перескочить на пустую.
///
/// **Профиль — от предыдущей карточки** (спека: «умолчание новой карточки —
/// профиль, выбранный для предыдущей»). «Предыдущая» здесь — текущая
/// (`ui.cfg.current()`): то единственное соединение, профиль которого только
/// что видел и правил человек.
///
/// **Имя — `cfg::default_name` от пути базы.** У новой карточки пути ещё
/// нет (его заводят в самой карточке, уже после добавления), и путь всегда
/// пуст — имя выходит «Соединение N» тем же правилом, что и у первого
/// соединения свежего комплекта. Занятость имени смотрим и в ПАМЯТИ
/// (`ui.cfg.connections`), и на ДИСКЕ — тем же приёмом, что `rename` (Review
/// Focus плана): блок, дописанный руками, пока окно было открыто, в `ui.cfg`
/// не виден вовсе, а молчаливое совпадение имён сделало бы файл нечитаемым
/// на следующем чтении (`Cfg::validate`, уникальность имён).
///
/// **Запись — НЕ через `cfg::write_checked`.** Та сверяет список в ПАМЯТИ со
/// списком на ДИСКЕ (`same_connections_on_disk`) и честно отказывает на
/// любом расхождении — а расхождение здесь ровно то, что делает само
/// добавление: в памяти после него одним соединением больше, чем на диске,
/// и так будет всегда, даже когда никто не правил файл руками. Файл читается
/// ОДИН раз (тот же приём, что у `rename`): блоков на диске нет вовсе — а
/// с задачи 15 плана «Интерфейс» (прежняя секция `[host]` убрана как форма
/// файла) это значит ровно одно: свежий комплект до первого «Сохранить» —
/// рисковать там нечем, и список печатается целиком из памяти
/// (`Cfg::render`); блоки есть — дописывается РОВНО один новый блок
/// (`cfg::connection_block`) в конец уже прочитанного текста, не трогая ни
/// байта ни одного соседнего блока.
///
/// **Круг починки 1, Critical ревью.** Печать из памяти (`disk_count == 0`)
/// угрожает чужому паролю ровно там, где его бережёт `write_checked`: если
/// пароль какого-то соединения не расшифровался на этой машине
/// (`load_unchecked`, `ui.cfg.undecryptable`), в памяти он лежит ПУСТОЙ
/// строкой, а `store.seal("password", "")` отдаёт её пустой же — наивная
/// печать записала бы это пустое поле на диск поверх настоящего шифртекста,
/// безвозвратно и молча. Задача 15 забрала у этой угрозы ровно один из двух
/// путей к ней — старую форму файла с уже лежащим на диске чужим паролем;
/// второй (окно прочитало чужой шифртекст пустым, а файл с тех пор никто не
/// трогал) остаётся, и проверка ниже остаётся на месте нарочно: свежий файл
/// теоретически не может нести чужой непрочитанный пароль, но доказывать это
/// заново при каждой правке дороже, чем один дешёвый отказ до записи.
/// Восстановление прежнего литерала (`previous_literal`/`set_named`) сюда не
/// переносится: это была бы третья копия той же тонкой логики (уже дважды
/// живёт в `write_checked`), и она разошлась бы с оригиналом на первой же
/// его правке (ruling координатора). Вместо этого — отказ словами ДО
/// какой-либо записи: человек и так в состоянии, где пароль на этой машине
/// не читается, и ему нужно узнать об этом, а не получить молча испорченный
/// файл. Пост-проверку записи (сверку расшифрованного с расшифрованным, как
/// у `write_checked`) здесь не заводим — тот же довод: отказ до записи уже
/// закрывает этот случай, и заводить третью такую проверку незачем.
pub fn add_connection(ui: &mut Ui, role: &str) -> Result<String, String> {
    let path = ui.kit.state_path(cfg::FILE);
    let text = match std::fs::read_to_string(&path) {
        Ok(t) => t,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
        Err(e) => return Err(format!("{}: файл не прочитан — {e}", path.display())),
    };
    let disk_count = common::toml_render::count(&text, cfg::CONNECTION);
    // Занятость имени — по объединению памяти и диска: находка Important 2
    // круга починки 1 задачи 4 (`rename`), применённая здесь к имени, которое
    // выбирает сама программа, а не человек.
    let mut taken: Vec<&str> = ui.cfg.connections.iter().map(|c| c.name.as_str()).collect();
    let disk_names: Vec<String> = (0..disk_count).filter_map(|n| common::toml_render::get_in(&text, cfg::CONNECTION, n, "name")).collect();
    for n in &disk_names {
        if !taken.contains(&n.as_str()) {
            taken.push(n.as_str());
        }
    }
    let name = cfg::default_name("", &taken);
    // `mode` — «tunnel», не умолчание `Connection::default()` («local»): см.
    // докстроку функции, «Ответ человека — ответ на вопрос «Это соединение»».
    let new = Connection {
        name: name.clone(),
        profile: ui.cfg.current().profile.clone(),
        role: role.to_string(),
        mode: "tunnel".into(),
        ..Connection::default()
    };

    let mut after = ui.cfg.clone();
    after.connections.push(new.clone());
    // Та же защита, что у `rename` и `save_host`: список в памяти правится
    // первым и проверяется до какой-либо записи на диск.
    //
    // Но спрашиваются ТОЛЬКО правила списка (`validate_list`), не полнота
    // полей текущей карточки (решение ведущего, вторая волна починки по
    // ревью всей ветки). Новая карточка заводится ПУСТОЙ нарочно — поля
    // человек вписывает в ней и жмёт «Сохранить», где и стоит полная
    // проверка, — а на пустом списке она вдобавок становится ТЕКУЩЕЙ
    // (`Cfg::current()` на пустом корневом `current` отдаёт первую), и
    // `validate()` отказывал «base_path — путь к базе» прямо в ответ на
    // первое нажатие онбординга: первый экран продукта на свежем комплекте
    // был тупиком. Тот же принцип, что у точечных писателей
    // (`breaks_connection`): отказ — за СВОЮ порчу, а заведение карточки не
    // портит ничего. Парные запреты списка при этом целы: вторая карточка к
    // той же базе или в ту же папку отказывает, как и раньше.
    after.validate_list().map_err(|e| format!("{e:#}"))?;

    let store = store_for(&ui.kit)?;
    let written = if disk_count == 0 {
        // Critical ревью круга починки 1: печать из памяти перезаписала бы
        // чужой непрочитанный шифртекст пустой строкой (см. докстроку выше)
        // — отказ словами раньше, чем `render` вообще позван.
        if !ui.cfg.undecryptable.is_empty() {
            let mut names: Vec<&str> = Vec::new();
            for u in &ui.cfg.undecryptable {
                if !names.contains(&u.connection.as_str()) {
                    names.push(&u.connection);
                }
            }
            let plural = names.len() > 1;
            let quoted = names.iter().map(|n| format!("«{n}»")).collect::<Vec<_>>().join(", ");
            // Слово «карточек/карточки» и местоимение «их/её» — числом этого
            // отказа; существительное с глаголом причины («пароль
            // зашифрован» / «пароли зашифрованы») — числом той же переменной
            // `plural`, но из ОДНОГО источника (`cfg::undecryptable_reason`,
            // круг починки 1 задачи 7 плана «Карточка публикации и
            // удаление»): до этого здесь лежал второй, свой литерал тех же
            // слов — переформулировка `cfg::UNDECRYPTABLE_REASON` обновляла
            // бы только отказ про одну карточку, а этот, про несколько,
            // молча расходился бы с ним дальше. Хвост «введите {password}
            // заново» тоже числом `plural` — иначе внутри одной фразы
            // подлежащее было бы множественным, а дополнение в конце —
            // единственным (Minor 1 того же круга).
            let (word, them, password) =
                if plural { ("карточек", "их", "пароли") } else { ("карточки", "её", "пароль") };
            return Err(format!(
                "добавить карточку сейчас нельзя: у {word} {quoted} {} — откройте {them} в окне, введите {password} заново и повторите «Добавить»",
                cfg::undecryptable_reason(plural)
            ));
        }
        after.render(&store)?
    } else {
        let mut t = text;
        if !t.ends_with('\n') {
            t.push('\n');
        }
        t.push_str(&cfg::connection_block(&new, &store)?);
        t
    };
    write_text(&path, &written).map_err(|e| format!("{e:#}"))?;
    ui.cfg = after;
    Ok(name)
}

/// Подложка секретов: боевая (`Store::system`, DPAPI на Windows) в работе,
/// файловая (`Store::file`) под тестом (ревью задачи 2, Important 2) —
/// спека прямо запрещает звать DPAPI из тестов (он привязан к пользователю
/// машины, на которой идёт CI, а `build.yml` гоняет весь набор и на
/// `windows-latest`). `#[cfg(test)]` — тот же приём, что уже стоит у
/// `gui::with_params_file`: срабатывает только внутри юнит-тестов этого же
/// крейта, не в собранной программе.
#[cfg(test)]
fn store_for(kit: &Kit) -> Result<secrets::Store, String> {
    Ok(secrets::Store::file(kit.state()))
}

#[cfg(not(test))]
fn store_for(kit: &Kit) -> Result<secrets::Store, String> {
    secrets::Store::system(kit.state())
}

/// Поля формы, пустые ровно там, где прежний пароль не расшифровался
/// (`undecryptable`, из `ui.cfg` — список последнего `load_unchecked`,
/// задача 2). Такое пустое поле не значит «сотрите» — его отдала пустым сама
/// программа, человек его не трогал, — а значит «я не знаю, что сюда
/// вписать». Непустое поле (новый пароль введён) по-прежнему заменяет всё,
/// как раньше: проверка здесь только по тому, что форма отдала пустую
/// строку для имени, которое и так в списке.
///
/// Спрашивается только про СВОЮ карточку (задача 10): список называет
/// соединение у каждой находки, и чужие в этом решении не участвуют вовсе —
/// за них отвечает сама запись (`cfg::write_checked`), а здесь решается
/// ровно одно: ввёл ли человек пароль заново в форме.
fn fields_to_keep(host: &Connection, undecryptable: &[cfg::Undecryptable]) -> Vec<&'static str> {
    let mine = |field: &str| undecryptable.iter().any(|u| u.connection == host.name && u.field == field);
    let mut keep = Vec::new();
    if host.password.is_empty() && mine("password") {
        keep.push("password");
    }
    if host.db_password.is_empty() && mine("db_password") {
        keep.push("db_password");
    }
    keep
}

/// Имя сохранённого поля словами человека, с большой буквы — предложение начинается им (`kept_password_line`). Слова — не своя копия `panel::undecryptable_line`: обе зовут одно и то же `cfg::secret_field_name` (ревью задачи 7, Important 4 — до этого здесь лежала собственная, независимо набранная пара строк).
fn field_label(field: &str) -> String {
    let name = cfg::secret_field_name(field);
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
        None => String::new(),
    }
}

/// Строка журнала про то, что «Сохранить» не тронула пароль, хоть поле и
/// пустое: подлежащее у каждого предложения — «пароль» (муж., ед. ч.) в
/// обоих словах (`field_label`), поэтому склеенные подряд предложения не
/// путают число и род, даже когда полей два. `None` — нечего сохранять
/// нетронутым, обычная запись сделала всё как попросили.
fn kept_password_line(keep: &[&'static str]) -> Option<Line> {
    if keep.is_empty() {
        return None;
    }
    let text = keep
        .iter()
        .map(|&f| format!("{} не расшифрован — он оставлен прежним; чтобы заменить, введите новый.", field_label(f)))
        .collect::<Vec<_>>()
        .join(" ");
    Some(Line { kind: Kind::Warn, text })
}

/// Сохранить параметры сервера. Списка инструментов, каталога выгрузки,
/// режима публикации (его пишет подменю трея), её порта и адреса Gitea среды
/// в окне нет: берём их из текущих параметров, иначе пустые
/// значения из формы затёрли бы toml. Каталог проекта — из формы, и за ним
/// едут умолчания: адрес публикации (`carried_base_url`) и каталог выгрузки
/// (`carried_dump`). Порт публикации (`host.http_port`) переносится как
/// есть — с задачи 6 плана «тонкий срез ценности» он не считается от
/// рабочего места и переносить его под новое имя не от чего. О каждом
/// переезде — строка в журнал (`moved_lines`).
///
/// **Пароль, который сюда пришёл пустым, потому что не расшифровался
/// (задача 4, ревью), не записывается пустым.** Сценарий ровно тот, ради
/// которого писана задача 4: файл переехал на другую машину, окно сказало
/// об этом словами, а человек правит что-то совсем другое (путь к базе,
/// рабочее место) и жмёт «Сохранить» — без этой защиты форма отдала бы
/// пустой пароль, обычная запись зашифровала бы пустую строку, и шифртекст,
/// который ещё можно было открыть под прежней учёткой, исчез бы безвозвратно.
///
/// Сама подстановка прежнего шифртекста живёт у записи
/// (`cfg::write_checked`), а не здесь: с задачи 10 «Сохранить» пишет ВЕСЬ
/// список, и беречь надо в том числе пароль ЧУЖОЙ карточки — той, которую
/// человек не правил вовсе, — а кто чего не прочитал, сказано в самой `Cfg`
/// (`cfg::Undecryptable`: соединение и поле). Здесь остаётся ровно одно
/// решение, которого запись принять не может: ввёл ли человек пароль заново
/// в форме (`fields_to_keep`). Непустое поле заменяет всё, как раньше, и
/// находка для него снимается — иначе запись вернула бы прежний шифртекст
/// поверх только что введённого пароля.
pub fn save_host(ui: &mut Ui, mut host: Connection) -> Result<(), String> {
    let old_host = ui.cfg.current().clone();
    // Имя соединения переносится, как и всё, чего в форме нет: поля имени в
    // окне пока не существует (его заводит план интерфейса), а безымянное
    // соединение `validate()` не пропустит — «Сохранить» отказывало бы про
    // имя, которого человек не вводил. Пусто у прежнего — значит соединения
    // не было вовсе (первая настройка свежего комплекта), и имя выводится из
    // каталога базы тем же правилом, что и при чтении прежнего `[host]`.
    host.name = if old_host.name.is_empty() { cfg::default_name(&host.base_path, &[]) } else { old_host.name.clone() };
    host.gitea = ui.cfg.current().gitea.clone();
    host.dump = carried_dump(ui.cfg.current(), &host.project);
    host.platform = ui.cfg.current().platform.clone();
    host.configuration = ui.cfg.current().configuration.clone();
    // Круг починки 1/5 задачи 9, находка автоматического ревью
    // безопасности: `profile` — поле карточки (решение владельца 7), а в
    // этом списке переносимых полей его не было — поля для его правки в
    // окне нет (заводит план интерфейса), и форма всё равно собирает
    // `Connection` с пустым `profile`. Без переноса ЛЮБОЕ «Сохранить»
    // обнуляло бы ручную правку профиля в файле — до круга починки
    // обнулённый `profile` читался бы как `business` ЛИШЬ если старое
    // `toolset` тоже пусто, а иначе откатывался на него и МОЛЧА расширял
    // или сужал действующий набор инструментов до того, что там
    // осталось — находка автоматического ревью была именно про эту связку.
    // Перенос `profile` здесь не даёт этой паре полей разойтись вовсе.
    host.profile = ui.cfg.current().profile.clone();
    // Та же причина и тот же приём, что у `profile` выше: поля для правки
    // роли в окне пока нет (заводят будущие задачи плана «Модель
    // соединений», задача 13 — только само поле модели), а форма собирает
    // `Connection` с пустым `role`. Без переноса ЛЮБОЕ «Сохранить» обнуляло
    // бы ручную правку роли в файле до умолчания `accept`.
    host.role = ui.cfg.current().role.clone();
    host.write = ui.cfg.current().write.clone();
    host.tools = ui.cfg.current().tools.clone();
    host.mode = ui.cfg.current().mode.clone();
    host.publication = ui.cfg.current().publication.clone();
    host.http_port = ui.cfg.current().http_port;
    // **Топология — тем же переносом, что `role` выше** (Critical круга
    // починки 1 задачи 14): `panel::host_of` всегда собирает форму как «база
    // здесь» — поля для правки топологии в окне нет, — а запись ниже
    // заменяет соединение целиком. Без этой строки карточка «база на той
    // стороне» молча переворачивалась в «база здесь».
    host.base_here = ui.cfg.current().base_here;
    // И вместе с топологией — ПОЛЯ, которых карточка не показывает вовсе.
    // Состав спрашиваем у того же `panel::shown_fields`, которым поля
    // рисуются и сравниваются («изменилось ли»), и теперь — у настоящей
    // топологии и настоящего режима карточки, перенесённых выше. Чего
    // карточка не показывает, того форма не несёт: в полях окна остаётся
    // то, что лежало там от ранее открытой карточки, и запись унесла бы
    // чужой путь к базе в toml, а пустое поле стёрло бы адрес среды, из-за
    // которого `validate()` потом отказывал про строку, которой на экране
    // нет. Переносы `dump`/`platform`/`mode`/… выше — та же мысль, только
    // про поля, которых в окне нет ни в одной топологии.
    let shown = panel::shown_fields(&host);
    let saved = ui.cfg.current().clone();
    if !shown.contains(&"server") {
        host.server = saved.server;
    }
    if !shown.contains(&"workstation") {
        host.workstation = saved.workstation;
    }
    if !shown.contains(&"password") {
        host.password = saved.password;
    }
    if !shown.contains(&"base_path") {
        host.base_path = saved.base_path;
    }
    if !shown.contains(&"db_user") {
        host.db_user = saved.db_user;
    }
    if !shown.contains(&"db_password") {
        host.db_password = saved.db_password;
    }
    if !shown.contains(&"base_url") {
        host.base_url = saved.base_url;
    }
    let typed = host.base_url.clone();
    host.base_url = base_url_to_write(ui.cfg.current(), &typed, &host.publication, &host.base_path);
    // Задача 5 плана «Модель соединений», решение владельца 8: учебная
    // лицензия 1С даёт ОДИН сеанс на базу — вторая карточка к той же базе
    // получила бы отказ ПЛАТФОРМЫ, а не нашей программы, и не поняла бы,
    // откуда беда. С задачи 10 `cfg.validate()` ниже проверяет весь список и
    // тот же запрет в нём ловит (до неё она видела ровно одно соединение,
    // `Cfg::of_one(host)`, и соседей не знала вовсе) — но говорит про это
    // словами МОДЕЛИ («соединение»), а человек на экране видит карточки.
    // Своя проверка остаётся затем, чтобы отказ окна был на языке окна, и
    // чтобы он прозвучал раньше прочих жалоб на список. Сравнение — по
    // смыслу (`cfg::same_base`), не по строке, и только с ЧУЖИМИ карточками:
    // та же самая карточка (то же имя) сравнивается со своей прежней базой
    // на каждое «Сохранить», и это не конфликт.
    if let Some(other) = same_base_conflict(&ui.cfg.connections, &host) {
        // Круг починки 1, Minor: внутри ОДНОЙ фразы человеку — одно слово про
        // одну сущность (найдено ревью). Между файлами слова законно разные
        // (модель говорит «соединение», окно — «карточка», так их зовут
        // контракт и спека интерфейса), но на экране человек видит только
        // карточки — обе половины этой фразы говорят «карточка».
        return Err(format!("карточка «{}»: эта база уже занята карточкой «{}» — одна база, одна карточка", host.name, other.name));
    }
    // Задача 6 плана «Модель соединений», решение владельца 1: у
    // документов нет истории, и затирание файлов в чужой папке —
    // молчаливая их потеря, а не неудобство. Тот же приём, что у проверки
    // базы выше, и по той же причине: отказ окна — словами окна, раньше
    // жалоб `Cfg::validate` на список целиком.
    if let Some(other) = folder_conflict_owner(&ui.cfg.connections, &host) {
        return Err(format!(
            // Хвост фразы — словом ОКНА, как и обе её первые половины
            // (находка 4 ревью всей ветки: он был взят из словаря модели —
            // «одному соединению», — и фраза называла одну сущность двумя
            // словами разом). Тот же запрет в модели (`cfg::validate`)
            // говорит «соединение» всеми тремя местами.
            "карточка «{}»: папка проекта уже занята карточкой «{}» — папка принадлежит одной карточке",
            host.name, other.name
        ));
    }
    let keep = fields_to_keep(&host, &ui.cfg.undecryptable);
    // Записывается ВЕСЬ список, а правится в нём ОДНО соединение — текущее
    // (задача 10). Прежде здесь строилась `Cfg::of_one(host)`, и на диск
    // уходило одно соединение: у человека с двумя карточками вторая исчезала
    // при первом же сохранении, то есть цель плана («человек может завести
    // второе соединение») на практике не выполнялась вовсе.
    //
    // Имя текущего ставится вслед за правкой: на первой настройке свежего
    // комплекта список был пуст, `current_mut()` создал соединение под своим
    // именем («Соединение 1»), а у сохранённого имя выведено из каталога
    // базы — без этой строки корневой `current` называл бы то, чего в файле
    // нет, и следующее чтение говорило бы об опечатке, которой человек не
    // делал.
    let mut cfg = ui.cfg.clone();
    let name = host.name.clone();
    *cfg.current_mut() = host;
    cfg.current = name.clone();
    // `undecryptable` должен и дальше говорить правду, и теперь он говорит её
    // про КАЖДУЮ карточку: у текущей поле осталось тем же непрочитанным
    // шифртекстом, что и было (`keep`), если человек не ввёл пароль заново, —
    // иначе показ окна решил бы, что беда прошла сама; у чужих карточек
    // находки не трогаются вовсе, и именно по ним запись (`write_checked`)
    // узнаёт, чей шифртекст беречь.
    cfg.undecryptable.retain(|u| u.connection != name || keep.contains(&u.field.as_str()));
    cfg.validate().map_err(|e| format!("{e:#}"))?;
    let store = store_for(&ui.kit)?;
    cfg::write_checked(&ui.kit, &cfg, &store)?;
    // Улаживание порта — ПОСЛЕ записи (находка 5 ревью круга 3). Стояло до
    // неё, и неудавшееся «Сохранить» успевало переписать `ports.state`:
    // человек менял рабочее место и заодно портил путь базы, `validate()`
    // отказывал, toml оставался прежним — а запомненная пара уже уехала на
    // новое предпочтение, которого в файле человека нет. Пока настройки не
    // записаны, запоминать выбор не за что.
    //
    // Круг исправления задачи 1: «Сохранить» держит СВОЮ `Cfg` (копию
    // `ui.cfg` с правкой выше) — не ту, что перечитывание
    // (`gui::window::reread_and_recheck`) или начальный запуск
    // (`gui::launch`); без своего вызова она осталась бы с
    // `resolved_http_port: None` до следующего перечитывания файла.
    ops_host::settle_chosen_http_port(&mut cfg, &ui.kit);
    // Переезды — не молчком, и все до одного: см. `moved_lines`. Строка
    // собирается здесь, после улаживания, именно затем, чтобы назвать
    // доставшийся порт, а не предпочтение (находка 6). `ui.cfg` — ещё
    // прежняя: её заменяет `ui.cfg = cfg` ниже.
    let moved = moved_lines(&ui.cfg, &cfg);
    let base_path = cfg.current().base_path.clone();
    // Дескриптор публикации (`publication::vrd`) с задачи 6 несёт только
    // путь базы — переподнимать публикацию при смене логина или пароля
    // больше незачем: платформа и так берёт их из запроса, а не из
    // дескриптора. `descriptor_changed`, а не `database_changed` — у них
    // разные списки полей не по ошибке (см. доку обеих).
    let base_changed = descriptor_changed(cfg.current(), &old_host);
    // То же сравнение, что решает, светится ли «Сохранить» (`panel::fields_differ`):
    // поля, которых окно не показывает (в т.ч. `mode`), сеанс не перезапускают
    // здесь — смена режима в трее поднимает его сама, отдельным путём
    // (`tray::on_menu`), и лишний перезапуск в довесок к тому был бы только
    // лишней строкой в журнал и лишним миганием портов.
    let changed = panel::fields_differ(cfg.current(), &old_host, &cfg.current().mode, &cfg.current().publication);
    // В памяти окна — тот же полный список, что только что ушёл на диск:
    // `cfg` выше и есть `ui.cfg` с правкой в ОДНОМ соединении (задача 10),
    // поэтому замена целиком ничего у человека не стирает. До задачи 10
    // здесь переносилось одно текущее соединение, потому что `cfg` несла
    // ровно его, а `ui.cfg = cfg` стирал бы все прочие карточки (круг
    // починки 1, находка B).
    //
    // Сеансовое уходит вместе с ним и тем же присваиванием: какие пароли не
    // открылись и какой порт публикации достался этой записи.
    ui.cfg = cfg;
    for text in moved {
        note_line(ui, Line { kind: Kind::Warn, text });
    }
    if let Some(line) = kept_password_line(&keep) {
        note_line(ui, line);
    }
    // Публикация не должна молчать про старую базу: иначе агент отвечает из
    // прежней, пока кто-нибудь не перезапустит HTTP-сервис руками (находка
    // целостного ревью) — до следующего вызова она обязана смотреть на
    // новую. `ensure_publication` сама решает «auto»/«webserver» и когда уже
    // «сделано» — здесь только зовём её, не повторяя эту логику.
    if republish_after_save(base_changed, ui.session.is_some()) {
        ensure_publication_now(ui);
    }
    if changed && ui.session.is_some() {
        if ui.cfg.current().mode == "local" {
            // Локальный режим: слушатели подняты на весь срок жизни процесса
            // и не трогаются переключателем/«Сохранить» (см. `launch`) —
            // спека прямо требует, чтобы смена базы была незаметна для Zed:
            // слушатели и уже принятые соединения не рвутся, следующий вызов
            // агента просто уходит в новую базу. `Serve::dispatch` берёт её
            // из этой же общей ячейки на каждое новое соединение — полный
            // перезапуск сеанса (`restart_session`) здесь не нужен и раньше
            // был блокирующей находкой целостного ревью (человеку пришлось
            // бы переподключать два сервера в Zed руками).
            if let Some(s) = &ui.session {
                s.update_cfg(ui.cfg.clone());
            }
            note_line(ui, Line { kind: Kind::Say, text: format!("MCP: параметры обновлены, база {base_path}") });
        } else {
            restart_session(ui, base_path);
        }
    }
    // Почва могла сдвинуться (база, логин, пароль, порт публикации) —
    // вердикт «дойдёт ли агент до базы» устарел, пересчитываем. Здесь же
    // пересчитывается замок, и если правка убрала холодное условие (стёрли
    // пользователя базы), `refresh_gate` сам гасит обслуживание и говорит об
    // этом в журнал — своей ветки «Сохранить» для этого больше не держит.
    // Спросили об этом раньше, до записи (`save_needs_confirm`): молчать
    // нельзя, агент остаётся без обслуживания.
    run_readiness(ui);
    Ok(())
}

/// Переименовать карточку словами человека — слова, не база: имя базы у трёх
/// заказчиков выглядит одинаково, а имя карточки заводит сам человек, чтобы
/// различать их глазами (задача 4 плана «Интерфейс»).
///
/// **Имя хранится ДВАЖДЫ** — в собственном блоке карточки и, если это
/// текущая карточка, ещё и в корневом ключе `current` файла: переименование
/// текущей обязано переписать оба места за один проход, иначе файл остался
/// бы со ссылкой на имя, которого в списке больше нет.
///
/// **Почему не `cfg::write_checked`.** Та запись сверяет имена соединений в
/// памяти с именами на диске (`cfg::same_connections_on_disk`) и честно
/// отказывает на любом расхождении — ровно на том, что делает само
/// переименование (имя в памяти меняется, а на диске до записи остаётся
/// прежним). Эта проверка защищает от правки файла руками мимо программы, а
/// не от собственного действия программы, и переименование здесь правит
/// ОДИН ключ текста (`cfg::set_current`) плюс, при необходимости, корневой
/// `current` — тем же приёмом, что `save_tray_key`, одной записью на диск, не
/// двумя.
///
/// **Главная мина (Review Focus плана).** Адресация по имени на двух
/// одноимённых блоках чинит ПЕРВЫЙ — поэтому занятое имя обязано отказать
/// раньше любой записи, а не молчаливо переехать в чужую карточку.
/// `Cfg::by_name` — точное совпадение по списку в памяти, той же мерки, что
/// уже проверяет «Сохранить» для базы и папки проекта (`same_base_conflict`,
/// `folder_conflict_owner`).
///
/// **Круг починки 1, находка Important 2.** Проверки по памяти одной мало:
/// блок `to` мог появиться в файле рукой, пока окно открыто, и `ui.cfg` об
/// этом ещё не знает. Молча разрешить такую запись значило бы дописать в
/// файл ВТОРОЙ блок с тем же именем — следующее чтение отвергло бы файл
/// целиком (`Cfg::validate`, уникальность имён), то есть окно вовсе не
/// открылось бы: хуже, чем неудобный отказ у соседних проверок
/// (`same_base_conflict`/`folder_conflict_owner`). Поэтому занятость имени
/// смотрим и в самом ФАЙЛЕ (`cfg::block_in`) — на том же тексте, который
/// читаем для записи, второго чтения не заводим.
pub fn rename(ui: &mut Ui, from: &str, to: &str) -> Result<(), String> {
    let to = to.trim();
    if to.is_empty() {
        return Err("имя карточки не может быть пустым или состоять из одних пробелов".to_string());
    }
    // «Нет такой карточки» отвечает на другой вопрос, чем «переименование на
    // своё же имя» ниже, и обязан прозвучать первым (Minor 3 круга починки 1
    // задачи 7): до этой правки ранний `Ok(())` ниже стоял раньше этой
    // проверки, и `rename(ui, "Нет", "Нет")` молча удавался бы, хотя
    // карточки «Нет» в списке нет вовсе — отказ, который человек обязан
    // услышать, подменился тишиной только потому, что имена совпали.
    ui.cfg.by_name(from).ok_or_else(|| {
        format!("{}: в списке нет карточки «{from}» — настройки на диске изменились, перечитайте их и повторите", cfg::FILE)
    })?;
    // Переименование карточки на её же нынешнее имя — не правка, а её
    // отсутствие. Из ОКНА этот случай недостижим (`Panel::write` зовёт
    // `rename` только когда поле имени и правда изменилось, `renamed = typed
    // != self.original.name`) — но функция `pub`, и её гарантия не может
    // зависеть от того, как ведёт себя единственный сегодняшний вызывающий:
    // прямой вызов с тем же именем (другой вызывающий, тест) — законный
    // входной случай, не ошибка программиста, и читать с диска да писать
    // обратно под него незачем. Сравнение — ДО проверки занятости имени
    // ниже и ДО любого чтения файла.
    if to == from {
        return Ok(());
    }
    if let Some(other) = ui.cfg.by_name(to) {
        if other.name != from {
            return Err(format!("имя «{to}» уже занято карточкой «{}» — имена карточек обязаны быть разными", other.name));
        }
    }
    let path = ui.kit.state_path(cfg::FILE);
    let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: файл не прочитан — {e}", path.display()))?;
    // Находка Important 2 круга починки 1: тот же запрет, что выше, но по
    // файлу, а не по памяти. Переименование на своё же нынешнее имя сюда уже
    // не доходит — ранний `Ok(())` выше отсекает его раньше любого чтения
    // файла, — но `to != from` оставлен и здесь: само по себе верное
    // утверждение, которое дешевле оставить явным, чем снимать и доказывать
    // заново при следующей правке этого места.
    if to != from && cfg::block_in(&text, to).is_ok() {
        return Err(format!("имя «{to}» уже занято карточкой «{to}» — имена карточек обязаны быть разными"));
    }
    // Список в памяти правится первым и проверяется до какой-либо записи на
    // диск — но правилами СПИСКА (`validate_list`), не полнотой полей
    // карточки (решение ведущего, третья волна починки по ревью всей ветки).
    //
    // **Почему не полная проверка.** Переименование меняет ИМЯ и ничего
    // больше, а свои проверки имени у него уже есть — пустое имя, занятое
    // имя по памяти И по диску (выше). Полнота полей — дело «Сохранить»
    // (`save_host`), и спрашивать её здесь значило запереть первую карточку
    // намертво: `panel::Panel::write` зовёт `rename` ПЕРВЫМ и на его отказе
    // останавливает всё (записывать поля под именем, которого человек не
    // получил, не за что), а `rename` проверяет `ui.cfg`, куда поля из формы
    // ещё не попали — их туда кладёт `save_host`, до которого дело не
    // доходит. Человек на первом экране заводил карточку, вписывал имя И
    // путь к базе, жал «Сохранить» — и читал отказ «base_path — путь к базе»
    // про поле, которое только что заполнил. Первую карточку нельзя было
    // назвать вовсе.
    //
    // Правила списка при этом целы все: переименование в имя, которое
    // сделает список негодным (два блока к одной базе, вложенные папки,
    // заведённые в файле руками), отказывает, как раньше.
    //
    // `switch_current` полную проверку СОХРАНЯЕТ, и это не недосмотр:
    // сделать текущей негодную карточку — значит сломать командную строку и
    // сеанс, которые работают с `current()`.
    let mut after = ui.cfg.clone();
    {
        let c = after.connections.iter_mut().find(|c| c.name == from).ok_or_else(|| {
            format!("{}: в списке нет карточки «{from}» — настройки на диске изменились, перечитайте их и повторите", cfg::FILE)
        })?;
        c.name = to.to_string();
    }
    // Непрочитанный шифртекст адресуется по имени карточки (`Undecryptable::connection`,
    // `cfg::blocking_undecryptable`) — имя едет вместе с ним, иначе находка
    // молча перестала бы относиться к переименованной карточке.
    for u in after.undecryptable.iter_mut() {
        if u.connection == from {
            u.connection = to.to_string();
        }
    }
    let renaming_current = after.current == from;
    if renaming_current {
        after.current = to.to_string();
    }
    after.validate_list().map_err(|e| format!("{e:#}"))?;

    let quoted = format!("{to:?}");
    // Адрес — ПО ИМЕНИ переименовываемой карточки, а не текущей: карточка,
    // раскрытая в списке, не всегда текущая (задача 2). `cfg::set_current`
    // читает из переданной `Cfg` только `current` — временная подмена этого
    // одного поля адресует её ровно туда же, куда адресует `set_named`.
    let mut addr = ui.cfg.clone();
    addr.current = from.to_string();
    let mut text = cfg::set_current(&text, &addr, "name", &quoted)?;
    if renaming_current {
        text = common::toml_render::set(&text, "", "current", &quoted);
    }
    write_text(&path, &text).map_err(|e| format!("{e:#}"))?;
    ui.cfg = after;
    Ok(())
}

/// Переключить текущее соединение из окна (задача 6 плана «Интерфейс») —
/// то единственное действие, которым человек сам выбирает, с какой карточкой
/// работает агент: переключение не побочный эффект ничьего другого действия
/// (тот же довод, что у «новая карточка не становится текущей сама» в
/// `add_connection`).
///
/// **Имя ищет и проверяет `Cfg::switch_current`** — тем же кодом, что команда
/// `1c-connect use`: тот же отказ на пустом списке и на имени, которого нет.
/// Второго способа искать имя здесь не заводим.
///
/// **Пустой `base_path` у карточки с базой на той стороне — не повод
/// отказать** (Review Focus плана, задача 6): замок в `Connection::validate`
/// снят именно для этого случая, и `after.validate()` здесь служит другой
/// цели — не пропустить ПОЛОМАННУЮ карточку, которая становится текущей:
/// соседний негодный блок молчит, пока не стал текущим, а здесь становится
/// им прямо сейчас.
///
/// **Запись — корневой ключ `current`, тем же приёмом, что у переименования
/// текущей (`rename`):** правится прямо в тексте файла
/// (`common::toml_render::set`, секция `""` — ключ лежит в корне, не внутри
/// блока соединения). Файл читается один раз, блоки соединений не трогаются
/// ни на байт.
pub fn switch_current(ui: &mut Ui, name: &str) -> Result<(), String> {
    let mut after = ui.cfg.clone();
    after.switch_current(name)?;
    after.validate().map_err(|e| format!("{e:#}"))?;

    let path = ui.kit.state_path(cfg::FILE);
    let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: файл не прочитан — {e}", path.display()))?;
    let text = common::toml_render::set(&text, "", "current", &format!("{name:?}"));
    write_text(&path, &text).map_err(|e| format!("{e:#}"))?;

    ui.cfg = after;
    note_line(ui, Line { kind: Kind::Ok, text: format!("Текущее соединение — «{name}»") });
    Ok(())
}

/// Карточка по имени или отказ словами — общее начало четырёх точечных
/// писателей (`set_profile`/`set_role`/`set_mode`/`set_base_here`): им нужна
/// не только проверка «есть ли такая», но и сама карточка — на ней считается
/// годность задуманной правки (`breaks_connection`).
fn connection_named(ui: &Ui, name: &str) -> Result<Connection, String> {
    ui.cfg.by_name(name).cloned().ok_or_else(|| format!("{}: в списке нет карточки «{name}»", cfg::FILE))
}

/// Последняя ли это карточка в списке — предикат живёт ровно в одном месте
/// (ruling ведущего задачи 2 плана «Карточка публикации и удаление»):
/// проводка окна (задача 3) зовёт тот же `is_last_connection`, не считая
/// длину списка заново своим вторым чтением.
pub fn is_last_connection(ui: &Ui) -> bool {
    ui.cfg.connections.len() == 1
}

/// Можно ли удалить карточку по имени — чистая проверка предусловий, без
/// единого похода на диск и без правки чего-либо. `Some` — слова отказа,
/// `None` — удалять можно. Её же зовёт проводка окна (задача 3): прежде чем
/// спросить у человека подтверждение, нет смысла спрашивать про действие,
/// которое и так откажет.
///
/// **Порядок проверок — по важности для человека**, не по дешевизне:
/// * нет такой карточки — отказ про опечатку в имени, раньше всего прочего
///   (`connection_named`, то же слово, что у точечных писателей);
/// * идёт операция, проверка или публикация — слово называет, что именно,
///   тем же `tray::busy_now_word`, что у отказа «Сделать текущим» (ruling
///   круга починки 5 задачи 16): второй фразы с тем же смыслом не заводим;
/// * и только последней — что карточка текущая, а рядом есть кому стать
///   текущей вместо неё («Buh» никуда не удаляется — её сначала надо
///   сместить). Эта причина менее важна, чем идущая работа, и названа
///   последней — человеку важнее услышать про работу, которая идёт прямо
///   сейчас.
///
/// Последняя оставшаяся карточка удаляется, даже будучи текущей
/// (`is_last_connection`) — иначе список застревал бы навсегда с одной
/// записью, которую нельзя убрать.
///
/// **Занятость — тем же счётом, что у «Сделать текущим»** (`tray::mode_change_blocked`,
/// Minor 5 ревью круга починки 1): своей копии тройного `||` не завожу —
/// второй счёт того же самого молча разошёлся бы с ним, когда у трея
/// появится четвёртое поле занятости.
///
/// **Карточка текущая — сравнением с `ui.cfg.current().name`, а не с
/// `ui.cfg.current`** (Important 3 ревью круга починки 1). Пустой корневой
/// `current` — законный вид файла (блоки без строки `current` в корне), и
/// тогда текущее соединение — первое по списку (`Cfg::current()`), а не
/// «карточка с именем „“». Сравнение с полем `current` этого бы не увидело
/// и молча пропускало бы этот отказ ровно в таком законном виде файла —
/// удаление первой (фактически текущей, с живым сеансом) карточки проходило
/// бы в обход предусловия.
pub fn delete_blocked_reason(ui: &Ui, name: &str) -> Option<String> {
    if let Err(e) = connection_named(ui, name) {
        return Some(e);
    }
    if tray::mode_change_blocked(ui) {
        return Some(tray::busy_refusal(ui, "удаление"));
    }
    if ui.cfg.current().name == name && !is_last_connection(ui) {
        return Some(format!("«{name}» — текущее соединение: сделайте текущим другое и повторите удаление"));
    }
    None
}

/// Удалить карточку соединения из настроек (задача 2 плана «Карточка
/// публикации и удаление», решение владельца 4.11, дословно: «давать, папку
/// не трогать») — вырезает её запись из файла параметров и из `ui.cfg`.
/// Папку проекта и базу эта функция не трогает и не может: удаляется только
/// запись в настройках, а не то, что она описывает.
///
/// **Предусловия — отдельной чистой проверкой, до какого-либо похода на
/// диск** (`delete_blocked_reason`): тот же приём, что у четырёх точечных
/// писателей (`breaks_connection`) — отказ обязан прозвучать раньше первого
/// байта записи, а не после.
///
/// **Уборка публикации — ДО записи, не после.** Причина не та же, что у
/// `tray::apply_switch_current` (там порядок обратный: запись первая,
/// гашение прежней публикации — после, и неудача гашения там лишь строка
/// `Warn`, потому что переключение уже состоялось). Здесь порядок ровно
/// противоположный нарочно (круг починки 1, Critical 1 ревью, решение
/// ведущего): удаление ПОСЛЕДНЕЙ карточки уносит из `ui.cfg` путь и порт,
/// по которым `publication::Paths::of` находит свой httpd (`find_1cv8`,
/// `resolve_http_port`) — без этих настроек ни выключение (`gui::link`),
/// ни выход (`gui::quit`) не смогут повторить гашение НИКОГДА, и процесс
/// осиротеет до перезагрузки машины, держа папку комплекта. Поэтому гашение
/// пробуется ПЕРВЫМ, пока настройки ещё целы, и на отказе удаление
/// отказывает ЦЕЛИКОМ (см. ниже) — файл в этом случае не тронут вовсе, и
/// попытку можно повторить.
///
/// `Ctx` для гашения — снимок СТАРОГО `Cfg` (`super::quiet_ctx_with`),
/// сделанный пока удаляемая карточка ещё на месте: `stop_own_publication`
/// читает `ctx.cfg.current()`, и собери `Ctx` ПОСЛЕ правки `ui.cfg`, он
/// смотрел бы уже не на удаляемую карточку.
///
/// Уборка пробуется только когда ОБА условия верны (Important 2 ревью круга
/// починки 1, тот же счёт, что у `mod.rs::quit`/`tray::publication_after_switch`:
/// `stop_old = base_changed && raised_publication`): это ПОСЛЕДНЯЯ карточка
/// (`is_last_connection`) — удаление нетекущей или текущей-при-живых-соседях
/// своего httpd не поднимает и не гасит вовсе, трогать его не из чего, — и
/// признак `ui.raised_publication` поднят — иначе машина без своего httpd
/// (признак и так ложный) ловила бы отказ про `bin/httpd.exe`, которого нет,
/// ради гашения того, что мы и не поднимали.
///
/// Признак `ui.raised_publication` снимается ТОЛЬКО по настоящей удаче
/// (`Ok(true)`): на «и так не наша публикация» (`Ok(false)`, не должно
/// случаться при согласованном признаке) он не трогается, а на отказе
/// (`Err`) ОТКАЗЫВАЕТ вся функция (см. выше) — так что признак остаётся как
/// был уже просто потому, что до его правки дело не доходит.
///
/// **Сеанс в этой функции не гасится.** `Ui` без `App` сеансом не управляет
/// (`gui::link::stop_session` просит именно его) — перед удалением
/// последней карточки сеанс гасит проводка окна (задача 3), тем же путём,
/// что у смены режима, ДО вызова этой функции.
pub fn delete_connection(ui: &mut Ui, name: &str) -> Result<(), String> {
    if let Some(why) = delete_blocked_reason(ui, name) {
        return Err(why);
    }
    let last = is_last_connection(ui);
    if last && ui.raised_publication {
        let old_cfg = ui.cfg.clone();
        let ctx = super::quiet_ctx_with(ui, old_cfg);
        match ops_host::stop_own_publication(&ctx) {
            Ok(true) => ui.raised_publication = false,
            Ok(false) => {} // признак и факт разошлись бы — не трогаем, разберётся следующая попытка
            Err(e) => {
                // Critical 1 ревью круга починки 1 (решение ведущего): файла
                // ещё не тронули — отказываем целиком, пока настройки, по
                // которым ещё можно гасить публикацию, целы (см. докстроку
                // функции).
                return Err(format!(
                    "HTTP-сервис базы не остановлен: {e:#}. Удаление отменено, настройки оставлены как были — повторите, или \
                     выйдите из программы: выход гасит публикацию, пока настройки ещё целы"
                ));
            }
        }
    }

    let path = ui.kit.state_path(cfg::FILE);
    let text = std::fs::read_to_string(&path).map_err(|e| format!("{}: файл не прочитан — {e}", path.display()))?;
    let mut text = cfg::remove_named(&text, name)?;
    // Minor 7 ревью круга починки 1 (решение ведущего): «последняя» для
    // ПРАВКИ КОРНЯ решается по ТЕКСТУ, который сейчас пишем, а не по
    // списку в памяти (`last` выше — он только про предусловие и про
    // гашение публикации, то есть про то, что видит человек в окне).
    // Иначе блок, дописанный в файл рукой уже после загрузки и неизвестный
    // `ui.cfg`, остался бы в тексте, а корневой `current` всё равно
    // обнулился бы — хотя в тексте есть блок, на который можно сослаться.
    let no_blocks_left = common::toml_render::count(&text, cfg::CONNECTION) == 0;
    if no_blocks_left {
        // Удалённая карточка была названа корневым `current` — её блока в
        // файле уже нет, и ключ обязан стать пустым тем же текстовым
        // приёмом, что `switch_current` пишет непустое имя: секция `""` —
        // ключ лежит в корне файла, не в блоке соединения.
        text = common::toml_render::set(&text, "", "current", "\"\"");
    }
    write_text(&path, &text).map_err(|e| format!("{e:#}"))?;

    ui.cfg.connections.retain(|c| c.name != name);
    // Находки про НЕПРОЧИТАННЫЙ шифртекст уходят вместе с карточкой
    // (Important 2 ревью всей ветки) — ровно там же, где она уходит из
    // списка, и ровно так же, как у соседей: `save_host` чистит свои
    // (`cfg.undecryptable.retain`), `rename` везёт их за новым именем.
    // Иначе находка про удалённую карточку оставалась бы висеть, и
    // онбординг на опустевшем списке становился тупиком: `add_connection`
    // отказывает словами «у карточки «Buh» пароль зашифрован — откройте её
    // в окне и введите заново», а карточки «Buh» уже нет и открыть её
    // негде.
    ui.cfg.undecryptable.retain(|u| u.connection != name);
    if no_blocks_left {
        ui.cfg.current = String::new();
    }
    note_line(
        ui,
        Line {
            kind: Kind::Ok, text: format!("Соединение «{name}» удалено. Папка и база остались на месте")
        },
    );
    Ok(())
}

/// Отказ точечного переключателя, когда правка САМА делает соединение
/// негодным (Important 2 ревью всей ветки). Четыре писателя ниже пишут один
/// ключ мимо `save_host` и годности не спрашивали вовсе: профиль
/// «Разработчик» при пустой папке исходников и «база здесь» при пустом пути
/// к базе делали ТЕКУЩЕЕ соединение негодным молча, в момент щелчка — потом
/// командная строка отвергала весь файл (`Cfg::validate`), а следующее
/// «Сохранить» отказывало про поле, которого человек не трогал.
///
/// **Проверяется ОДНО соединение (`Connection::validate`), а не список.**
/// `Cfg::validate` тянет за собой парный запрет по папкам, а задача 7
/// нарочно от него ушла: смена профиля у карточки, чья папка «занята»
/// соседом, обязана пройти.
///
/// **Отказ — только за СВОЮ порчу: было годно, стало негодно.** Уже негодная
/// карточка переключателю не укор — свежая стоит с пустым путём к базе
/// (`Connection::default`: `base_here` уже `true`), и безусловная проверка
/// отказывала бы на ней про поле, которого человек ещё не заполнял, то есть
/// ровно той бедой, от которой эта проверка и заводится. Выбор профиля на
/// свежем комплекте обязан срабатывать — так же, как переключатель режима в
/// значке (`tray::unsaved_switch_line`: пишем и говорим словами, а не
/// запираем).
///
/// **Ось «где база» (`base_here`) переключается ВСЕГДА — исключение, а не
/// забытая проверка** (решение ведущего, правка 2 повторного ревью волны).
/// Эта ось не просто меняет поле: она решает, КАКИЕ ПОЛЯ карточка вообще
/// показывает (`panel::shown_fields`), и щелчок «Здесь» — это и есть тот
/// щелчок, которым человек открывает себе поле пути к базе. Спрашивая у него
/// полноту, проверка запирала пару сама на себя: карточка с базой на той
/// стороне получала отказ про пустой `base_path`, а поля пути на экране не
/// было — оно появляется только ПОСЛЕ переключения. Перенести базу на свою
/// машину из окна было нельзя вовсе, и отказ опять называл поле, которого
/// экран не показывает (тот же разряд, что Critical 1 этой волны).
///
/// Так уже живёт свежая карточка: `base_here = true` с пустым путём —
/// законное состояние, и заведение её разрешено (`add_connection` →
/// `Cfg::validate_list`). Неполноту карточки и здесь ловит «Сохранить», а
/// пока она неполна — замок окна (`gate::cold_gate`) честно говорит, чего не
/// хватает, и обслуживать не даёт.
///
/// Три остальных писателя (`set_profile`, `set_role`, `set_mode`) проверку
/// СОХРАНЯЮТ: ни одна из их осей не открывает полей, которыми карточку
/// дополняют, — там довод прежний и верный.
fn breaks_connection(before: &Connection, after: &Connection) -> Option<String> {
    if before.base_here != after.base_here {
        return None;
    }
    if before.validate().is_err() {
        return None;
    }
    after.validate().err().map(|e| format!("переключение не записано: {e:#} — впишите это поле и повторите"))
}

/// Протолкнуть новые параметры в ЖИВОЙ сеанс после удачной точечной записи
/// (Important 3 ревью всей ветки): ребёнок моста берёт набор инструментов,
/// вид конфигурации и потолок записи из общей ячейки сеанса
/// (`bridge::mcp_command` на `Session::cfg_now`), и без этого толчка смена
/// профиля не сужала набор у УЖЕ РАБОТАЮЩЕГО агента. Пока окно прятало себя
/// по потере фокуса, это пряталось за перечитыванием файла на следующем
/// показе (`gui::adopt_cfg`) — задача 12 автоскрытие убрала, и окно может
/// висеть открытым сколько угодно.
///
/// Только ТЕКУЩАЯ карточка: сеанс работает с ней одной (`Cfg::current`), и
/// правка соседней ему не про что. Режима не спрашиваем — `update_cfg` «не
/// повредит и в туннельном» (её докстрока), и тем же приёмом её зовёт
/// `tray::apply_access`. Перезапуска сеанса здесь нет и не нужно: ни один из
/// четырёх ключей не меняет транспорт, а тот один, что меняет (`mode`
/// текущей карточки), идёт мимо этих писателей — через `tray::apply_mode`.
fn push_to_session(ui: &Ui, name: &str) {
    if name != ui.cfg.current().name {
        return;
    }
    if let Some(s) = &ui.session {
        s.update_cfg(ui.cfg.clone());
    }
}

/// Значение одного ключа карточки, УЖЕ разобранное и проверенное — то, чем
/// `set_keys` думает о правке после первого прохода по входу, и то, что
/// после записи на диск применяется к `ui.cfg` без единого пути к ошибке
/// (Minor 2 круга починки 1: раньше применение после записи могло отказать
/// тем же `apply_key`, которым размечалась и копия ДО записи — сегодня это
/// недостижимо лишь потому, что те же ключи уже прошли проверку выше, а не
/// потому, что путь к ошибке не существует). `Bool` — отдельный вариант, не
/// `Str("true")`: будь он строкой, печать в toml снова встала бы перед тем
/// же выбором «кавычки или нет» уже ПОСЛЕ разбора, то есть ровно там, где
/// Important 1 нашла непроверенную развилку.
enum KeyValue {
    Str(String),
    Bool(bool),
}

/// Разобрать и проверить одно значение по имени ключа — единственное место,
/// где входная строка превращается в `KeyValue` или в отказ. `base_here`
/// разбирается строго (`str::parse::<bool>`, Important 2 круга починки 1):
/// прежняя `value == "true"` принимала что угодно, молча читая любое чужое
/// значение («yes», опечатку) как `false`, — на диск при этом уходил бы
/// неразбираемый токен (`base_here = yes`), а в памяти оседало неверное
/// булево: диск и память расходились бы молча, без единого слова отказа.
/// Неизвестный ключ — тоже отказ здесь, до какой-либо записи.
fn parse_key(key: &str, value: &str) -> Result<KeyValue, String> {
    match key {
        "profile" | "role" | "mode" | "publication" | "base_url" => Ok(KeyValue::Str(value.to_string())),
        "base_here" => value
            .parse::<bool>()
            .map(KeyValue::Bool)
            .map_err(|_| format!("set_keys: base_here — ожидалось true или false, получено «{value}»")),
        _ => Err(format!("set_keys: неизвестный ключ «{key}»")),
    }
}

/// Применить уже разобранное значение к карточке — ПОСЛЕ `parse_key`, и
/// только после него: сигнатура без `Result` — то, чем в коде видна
/// невозможность отказа на этом шаге (Minor 2), а не комментарий об этом.
/// Несовпадение ключа и варианта `KeyValue` недостижимо: `parse_key` выше —
/// единственное место, где они связываются, и связывает их верно.
fn apply_parsed(c: &mut Connection, key: &str, value: &KeyValue) {
    match (key, value) {
        ("profile", KeyValue::Str(v)) => c.profile = v.clone(),
        ("role", KeyValue::Str(v)) => c.role = v.clone(),
        ("mode", KeyValue::Str(v)) => c.mode = v.clone(),
        ("publication", KeyValue::Str(v)) => c.publication = v.clone(),
        ("base_url", KeyValue::Str(v)) => c.base_url = v.clone(),
        ("base_here", KeyValue::Bool(v)) => c.base_here = *v,
        // Промах — ГРОМКИЙ (Minor 4 ревью всей ветки). Сегодня он
        // недостижим (`parse_key` — единственное место, где ключ и вариант
        // связываются), но `set_keys` стал единственным писателем шести
        // ключей, и молчаливое `_ => {}` здесь означало бы «файл записан, а
        // память — нет»: диск и окно расходятся, и ни одна строка об этом не
        // говорит. Паника на седьмом ключе, добавленном в `parse_key` и
        // забытом здесь, случится у разработчика на первом же тесте, а не у
        // человека в окне.
        _ => unreachable!("apply_parsed: ключ «{key}» разобран, но не применён — добавьте его сюда рядом с разбором в parse_key"),
    }
}

/// Разобранное значение ключа как TOML-литерал — развилка, которая раньше
/// жила в каждом из четырёх писателей по отдельности и до круга починки 1
/// не была закрыта ни одним тестом (Important 1): `Bool` пишется словом без
/// кавычек (так его и разбирает `Connection` — в кавычках файл остаётся
/// читаемым В ПАМЯТИ ЭТОЙ программой, но следующая загрузка `toml::from_str`
/// отвергает его целиком, потому что `base_here` там больше не булево), `Str`
/// — строкой, в кавычках.
fn toml_literal(value: &KeyValue) -> String {
    match value {
        KeyValue::Bool(v) => v.to_string(),
        KeyValue::Str(v) => format!("{v:?}"),
    }
}

/// Записать несколько ключей ОДНОГО соединения ОДНОЙ записью на диск — общее
/// ядро четырёх точечных писателей ниже (`set_profile`/`set_role`/
/// `set_mode`/`set_base_here`), каждый из которых правит только свой ключ и
/// теперь — однострочная обёртка над этим.
///
/// Тело — то же, что раньше было у каждого из них по отдельности, только
/// ключей несколько: `connection_named` → разобрать и применить ВСЕ правки к
/// копии карточки (`parse_key`/`apply_parsed`) → одна проверка годности на
/// весь результат (`breaks_connection`, а не по разу на каждый ключ) →
/// прочитать файл ОДИН раз → `cfg::set_named` по каждому РАЗОБРАННОМУ ключу
/// подряд на одном и том же тексте → одна запись → обновить `ui.cfg` уже
/// разобранными значениями (без повторного разбора — Minor 2) и толкнуть
/// правку в живой сеанс (`push_to_session`).
///
/// **Пустой список ключей — не правка, а её отсутствие** (Minor 1 круга
/// починки 1): до него функция всё равно читала файл, писала его обратно
/// без единого отличия и толкала правку в сеанс — запись без правки, лишняя
/// работа и лишняя строка в историю файла на диске (у него нет версий, но
/// незачем трогать и то, что можно не трогать).
///
/// **Запись — ОДНА, даже когда ключей несколько.** Без этого правка пары
/// ключей смотрела бы на файл дважды: прочитала бы его, записала первый
/// ключ, прочитала заново и записала второй. Между двумя записями человек
/// успевает увидеть файл в половинчатом состоянии — записан только один из
/// двух ключей задуманной правки, — а если он в эту же секунду правит файл
/// руками, это уже не видимость, а настоящая несогласованность. Следующему
/// писателю это нужно буквально (задача 5 плана «Карточка публикации и
/// удаление»): публикация пишет `publication` и, в одном случае, пустой
/// `base_url` — два ключа одной правки, и писать их двумя записями подряд
/// нельзя по той же причине. Та же беда уже жила в окне до этой задачи:
/// `panel::set_card_topology_kind`, уходя из локального режима, писала роль и
/// режим двумя точечными записями подряд — отложенная мелочь прошлой ветки, и
/// эта задача сводит её на один вызов `set_keys`.
pub fn set_keys(ui: &mut Ui, name: &str, keys: &[(&str, &str)]) -> Result<(), String> {
    if keys.is_empty() {
        return Ok(());
    }
    let before = connection_named(ui, name)?;
    let mut after = before.clone();
    // Разбор — ОДИН раз на весь вызов (Minor 2): дальше, и для записи в
    // текст, и для синхронизации `ui.cfg` после неё, читается уже этот
    // список, а не исходные строки — второго похода к `parse_key`, который
    // мог бы отказать ПОСЛЕ записи, в коде не существует вовсе.
    let mut parsed: Vec<(&str, KeyValue)> = Vec::with_capacity(keys.len());
    for &(key, value) in keys {
        let v = parse_key(key, value)?;
        apply_parsed(&mut after, key, &v);
        parsed.push((key, v));
    }
    // Годность считается на РЕЗУЛЬТАТ всей правки, а не на каждый ключ по
    // отдельности — пара «роль + режим» от `panel::set_card_topology_kind`
    // проверяется как одно целое, тем же приёмом, что было у каждого из
    // четырёх писателей на своём одном ключе.
    if let Some(why) = breaks_connection(&before, &after) {
        return Err(why);
    }

    let path = ui.kit.state_path(cfg::FILE);
    let mut text = std::fs::read_to_string(&path).map_err(|e| format!("{}: файл не прочитан — {e}", path.display()))?;
    for (key, value) in &parsed {
        text = cfg::set_named(&text, name, key, &toml_literal(value))?;
    }
    write_text(&path, &text).map_err(|e| format!("{e:#}"))?;

    // Синхронизируем только карточку, которую сами только что записали —
    // тот же приём, что `save_tray_key` применяет к текущей. `apply_parsed`
    // здесь без `Result` — применение уже разобранного и уже провалидного не
    // может отказать (Minor 2): после удачной записи на диск второй отказ
    // здесь оставил бы диск и память в разных состояниях молча.
    if let Some(c) = ui.cfg.connections.iter_mut().find(|c| c.name == name) {
        for (key, value) in &parsed {
            apply_parsed(c, key, value);
        }
    }
    push_to_session(ui, name);
    Ok(())
}

/// Сменить профиль карточки по имени (задача 7 плана «Интерфейс») — второй
/// переключатель карточки, после `switch_current`, и тем же приёмом: профиль
/// меняет подпись папки и набор инструментов ЭТОГО соединения
/// (`panel::folder_label`, `panel::profile_label`, `Connection::toolset`), а
/// не папку и не соседей.
///
/// **Почему не `save_host`.** Полная запись карточки проверяет список
/// целиком (`Cfg::validate`, в том числе `folder_conflict` между соседями) —
/// а профиль чужой папки не касается вовсе (Review Focus плана): смена
/// профиля у карточки, чья папка уже «занята» соседом по правилу конфликта,
/// обязана пройти. Поэтому запись — ОДИН ключ, тем же приёмом, что
/// `save_tray_key` пишет для текущего соединения, и без похода в
/// `Cfg::validate`: годность спрашивается у САМОГО соединения
/// (`breaks_connection` → `Connection::validate`), а не у списка. Тело — общее
/// ядро `set_keys` (задача 4 плана «Карточка публикации и удаление»): эта
/// функция — однострочная обёртка над ним.
///
/// Значение проверяется тем же правилом, что читает его обратно
/// (`Connection::toolset` — список допустимых один, опечатка отказывает
/// словами раньше записи).
pub fn set_profile(ui: &mut Ui, name: &str, profile: &str) -> Result<(), String> {
    let probe = Connection { profile: profile.to_string(), ..Connection::default() };
    probe.toolset()?;
    set_keys(ui, name, &[("profile", profile)])
}

/// Переключатель «Это соединение» у карточки (задача 16 плана «Интерфейс») —
/// третий, после `switch_current` и `set_profile`, и тем же приёмом: один
/// ключ (`role`) у ИМЕНОВАННОЙ карточки, не обязательно текущей (карточка,
/// раскрытая в списке, текущей быть не обязана — `panel::link_card`).
///
/// Значение проверяется тем же правилом, что читает его обратно
/// (`Connection::role` — список допустимых один, опечатка отказывает словами
/// раньше записи, а не молчаливым откатом на умолчание).
///
/// `mode` этот переключатель не трогает: третий ответ того же вопроса
/// («Всё на одной машине») — это `mode`, а не роль (ruling шага 4 брифа).
/// Пишет его либо соседняя точечная функция (`set_mode`, для нетекущей
/// карточки), либо тревный `apply_mode` (для текущей, через
/// `panel::set_card_mode`/`tray::request_current_mode_change`,
/// Important 3 ревью круга починки 1: смена транспорта ТЕКУЩЕГО соединения
/// обязана перецикливать сеанс, а точечная запись этого не делает). Роль
/// сама сеанса не держит — она пишется точечно всегда, независимо от
/// того, текущая карточка или нет.
///
/// Тело — однострочная обёртка над общим ядром `set_keys` (задача 4 плана
/// «Карточка публикации и удаление»).
pub fn set_role(ui: &mut Ui, name: &str, role: &str) -> Result<(), String> {
    let probe = Connection { role: role.to_string(), ..Connection::default() };
    probe.role()?;
    set_keys(ui, name, &[("role", role)])
}

/// `mode` именованной карточки — точечная запись для НЕТЕКУЩЕГО
/// соединения (`panel::set_card_mode`): у него нет сеанса, который надо
/// перецикливать, и полный путь трея (`tray::apply_mode`) здесь был бы
/// работой, которой никто не просил. У ТЕКУЩЕГО соединения тот же
/// переключатель идёт другим путём — `tray::request_current_mode_change`,
/// который сам решает между записью и вопросом о гашении обслуживания
/// (Important 3 ревью круга починки 1 задачи 16: до него карточка меняла
/// транспорт текущего соединения в обход сеанса, замка и значка).
///
/// Своей проверки допустимых значений отдельной функцией-геттером у `mode`
/// нет (в отличие от `role`/`toolset`) — допустимые два значения проверяет
/// сам переключатель карточки, набор закрытый и строится не из ввода
/// человека, а отказ здесь всё равно стоит до записи, а не после.
///
/// Тело — однострочная обёртка над общим ядром `set_keys` (задача 4 плана
/// «Карточка публикации и удаление»): ровно тем ядром, которым раньше была
/// сама эта функция, пока остальные три не свелись на неё же.
pub fn set_mode(ui: &mut Ui, name: &str, mode: &str) -> Result<(), String> {
    if !matches!(mode, "local" | "tunnel") {
        return Err(format!("mode: неизвестный режим «{mode}»; допустимые значения: local, tunnel"));
    }
    set_keys(ui, name, &[("mode", mode)])
}

/// Переключатель «Где база» у карточки (задача 16 плана «Интерфейс») — тем
/// же приёмом, что `set_role`/`set_profile`: один ключ (`base_here`) у
/// ИМЕНОВАННОЙ карточки. Состав полей карточки (`panel::shown_fields`)
/// считается от соединения заново при каждой отрисовке — переключение
/// обязано попасть в `ui.cfg` до следующего показа, и синхронизация внутри
/// `set_keys` ровно это и делает.
///
/// Тело — однострочная обёртка над общим ядром `set_keys` (задача 4 плана
/// «Карточка публикации и удаление»); `bool` здесь переводится в слово,
/// которое `toml_literal` внутри `set_keys` пишет без кавычек — так его и
/// разбирает `Connection`.
pub fn set_base_here(ui: &mut Ui, name: &str, base_here: bool) -> Result<(), String> {
    set_keys(ui, name, &[("base_here", if base_here { "true" } else { "false" })])
}

/// Кто публикует базу — точечная запись у ИМЕНОВАННОЙ карточки (задача 5
/// плана «Карточка публикации и удаление»). Публикация стала полем карточки, а
/// не одним переключателем на машину (решение владельца 1.11: «это поле
/// соединения, и пункт меню убран вовсе») — переключатель в значке один, а баз
/// на машине несколько, и он молча правил ту, что оказалась текущей.
///
/// **Два ключа одной правкой.** Уходя в «публикует платформа 1С», сюда же
/// попадает пустой `base_url` — тем же доводом, что записан у
/// `tray::apply_publication`: выведенный от каталога базы адрес
/// (`cfg::derived_base_url`, признак — `cfg::is_derived_address`) в toml
/// написали МЫ, а не человек, и принять нашу догадку за его ответ нельзя —
/// проба по ней ушла бы на чужой веб-сервер. Карточка такой адрес и показывает
/// пустым полем (`panel::shown_base_url`), значит и в файле его быть не
/// должно. Писать их двумя записями подряд нельзя (докстрока `set_keys`):
/// между ними файл стоял бы с новой публикацией и прежним адресом.
///
/// Своей уборки httpd здесь нет и не нужно: сеанс держит только ТЕКУЩЕЕ
/// соединение, и у него тот же переключатель идёт другим путём —
/// `tray::request_current_publication_change` (гашение своей публикации,
/// вопрос человеку, перецикл сеанса), тем же приёмом, что `mode`.
///
/// Допустимые значения проверяются здесь, до записи, как у `set_mode`: тот же
/// набор, что читает их обратно (`Connection::validate`). На `breaks_connection`
/// одного этого не свалить — уже негодной карточке он отказа не даёт вовсе, и
/// опечатка легла бы в файл молча.
pub fn set_publication(ui: &mut Ui, name: &str, publication: &str) -> Result<(), String> {
    if !matches!(publication, "auto" | "webserver") {
        return Err(format!("publication: неизвестное значение «{publication}»; допустимые значения: auto, webserver"));
    }
    let mut keys: Vec<(&str, &str)> = vec![("publication", publication)];
    if publication == "webserver" && cfg::is_derived_address(&connection_named(ui, name)?) {
        keys.push(("base_url", ""));
    }
    set_keys(ui, name, &keys)
}

/// Чистое ядро вопроса «погасит ли „Сохранить“ обслуживание»: замок был
/// открыт, обслуживание живо, а на новых параметрах условия не хватает.
/// Заперто и до правки — гасить нечего, вопрос не нужен.
pub fn locks_gate(gate_before: Option<&str>, gate_after: Option<String>, serving: bool) -> Option<String> {
    if gate_before.is_some() || !serving {
        return None;
    }
    gate_after
}

/// То же на живых параметрах. Полей, которых окно не показывает, в форме нет —
/// пустой режим берём из текущих параметров, как это делает сама `save_host`:
/// иначе туннельная проверка адреса среды применилась бы к локальному рабочему
/// месту. Непустой режим — это смена режима из трея, и спрашивать надо как
/// раз про новый: замки у режимов разные (туннелю нужны адрес среды, пароль
/// и имя рабочего места, локальному — нет). «Было» берём из кэша `ui.gate`
/// (он пересчитывается по тем же событиям и его же читает `toggle_link`), на
/// диск ходим ровно раз — за «станет»: нажатие «Сохранить» не должно стоить
/// шести обходов `Program Files` на главном потоке окна.
pub fn save_locks_gate(ui: &Ui, new_host: &Connection) -> Option<String> {
    let serving = ui.enabled.load(Ordering::Relaxed) && ui.session.is_some();
    if !serving || ui.gate.is_some() {
        return None;
    }
    let mut host = new_host.clone();
    if host.mode.is_empty() {
        host.mode = ui.cfg.current().mode.clone();
    }
    locks_gate(ui.gate.as_deref(), gate_now(&ui.kit, &Cfg::of_one(host)), serving)
}

/// О чём спросить перед «Сохранить», и спрашивать ли вообще: готовый текст
/// диалога или `None`. Один расчёт на нажатие — и «нужен ли вопрос», и «какой
/// текст» отвечает он же, а не два одинаковых похода на диск подряд.
/// Погасшее обслуживание важнее смены базы: оно оставляет агента без ответа
/// вовсе.
pub(crate) fn save_question(ui: &Ui, new_host: &Connection) -> Option<(String, String)> {
    if let Some(why) = save_locks_gate(ui, new_host) {
        return Some(confirm_gate_text(&why));
    }
    let live = ui.enabled.load(Ordering::Relaxed) && ui.session.is_some();
    if database_changed(new_host, ui.cfg.current()) && live {
        return Some(confirm_text(&ui.cfg.current().base_path, &new_host.base_path));
    }
    None
}

/// Нужно ли спросить перед «Сохранить»: база меняется (`database_changed` выше — путь, логин И пароль; у публикации список короче, `descriptor_changed`, не этот же самый — с задачи 6 логин и пароль дескриптор не несёт, см. доку обеих; Important 3 ревью задачи 7: прежняя строка здесь утверждала обратное), агент прямо сейчас может отвечать (`enabled` — его читает мост на каждый вызов, в обоих режимах, не только в локальном), и сеанс жив (`ui.session`). Любая другая правка — каталог проекта, режим, рабочее место — сохраняется без вопроса, как и было задумано (заказчик просил вопрос именно и только в этом сочетании, 2026-10-20).
///
/// Второй повод спросить — тот же диалог: правка убирает холодное условие и тем гасит обслуживание (`save_locks_gate`). Заказчик требовал вопроса именно в этом сочетании: цель спеки — чтобы смена параметров была незаметной для Zed, а тут агент остаётся без обслуживания.
pub fn save_needs_confirm(ui: &Ui, new_host: &Connection) -> bool {
    save_question(ui, new_host).is_some()
}

/// Имя базы для диалога — последний компонент пути («Buh» для C:\Bases\Buh),
/// как 1С-разработчик называет базу в разговоре; полный путь уходит в
/// detail, не в это имя. Пустой/корневой путь без компонента — путь целиком,
/// лишь бы в диалоге не было пустой строки.
pub fn base_label(path: &str) -> &str {
    // Правило имени — общее (`cfg::base_name`, там же и причина, почему режем
    // сами). Своё здесь только то, что делать без имени: в диалоге пустой
    // строки быть не должно, поэтому показываем путь целиком.
    let name = cfg::base_name(path);
    if name.is_empty() {
        path
    } else {
        name
    }
}

/// Текст диалога подтверждения: два предложения (что сейчас, что станет
/// после, и сам вопрос) и деталь с обоими полными путями.
pub fn confirm_text(old_path: &str, new_path: &str) -> (String, String) {
    let message = format!(
        "Агент сейчас работает с базой «{}», после сохранения перейдёт на «{}». Сохранить?",
        base_label(old_path),
        base_label(new_path)
    );
    (message, format!("{old_path} → {new_path}"))
}

/// Текст того же диалога, когда правка не меняет базу, а гасит обслуживание:
/// называем последствие и причину, а не одно «Сохранить?».
pub fn confirm_gate_text(why: &str) -> (String, String) {
    ("После сохранения MCP выключатся — агент перестанет отвечать. Сохранить?".to_string(), format!("включать будет нечего: {why}"))
}

/// Текст своего диалога у «Сделать текущим» (круг починки 3 задачи 16) —
/// факт тот же, что у `confirm_text` (сеанс переходит с одной базы на
/// другую), а слово действия — своё. Прежний текст звал кнопку «Сохранить»,
/// хотя человек нажимал «Сделать текущим» — неправда, которая хуже
/// отсутствия вопроса вовсе: она учит жать «да» не читая (ruling
/// координатора). Называем явно: какая карточка станет текущей (у
/// разработчика с десятью заказчиками это не праздный вопрос), чем грозит
/// (агент перестанет отвечать по прежней базе — сеанс перезапустится на
/// новую) и чем кончится отказ (всё останется как было). Без слов
/// «ошибка»/«сбой»: переключение — не поломка.
pub fn confirm_switch_current_text(name: &str, old_path: &str, new_path: &str) -> (String, String) {
    let message = format!(
        "Текущей станет карточка «{name}»: агент перестанет отвечать по прежней базе — сеанс перезапустится на новую. Отмена оставит всё как было. Сделать текущим?"
    );
    (message, format!("{old_path} → {new_path}"))
}

/// Диалог перед «Сохранить», когда база меняется под живым и включённым MCP
/// (см. `save_needs_confirm`) — иначе `proceed` зовётся сразу, без вопроса.
/// Платформенный диалог (`Window::prompt`), тот же приём, что у выбора
/// каталога (`Panel::pick_dir`): `dialog_open` не даёт открыть диалог второй
/// раз, пока первый ещё без ответа; ответ приходит в своём потоке задачи —
/// главный поток ничего не ждёт. `proceed` зовётся ровно раз («да», или
/// вопроса не было) либо никогда (отказ — поля окна остаются как человек их
/// оставил, здесь ничего не трогаем).
///
/// Тонкая обёртка над `confirm_database_change_with_text` со словами
/// «Сохранить»/«Сохранить?» — умолчание для вызывающих, которым подходят
/// именно они (запись карточки, смена режима, смена публикации). У кого
/// слова другие (переключение текущего, круг починки 3 задачи 16) — тот
/// зовёт функцию ниже напрямую, со своими.
pub fn confirm_database_change(
    window: &mut Window,
    cx: &mut App,
    new_host: &Connection,
    proceed: impl FnOnce(&mut Window, &mut App) + 'static,
) {
    // Один диалог на оба повода (спека: «тот же диалог подтверждения, что уже
    // спрашивает при смене базы»), и один расчёт на нажатие: текст приходит
    // вместе с ответом «спрашивать ли».
    let Some((message, detail)) = save_question(cx.global::<Ui>(), new_host) else {
        proceed(window, cx);
        return;
    };
    ask_yes_no(window, cx, &message, &detail, "Да, сохранить", "Нет, не сохранять", false, proceed);
}

/// То же решение «спрашивать ли» (`save_question`, тот же расчёт, что у
/// `confirm_database_change`) и тот же механизм диалога (`ask_yes_no` —
/// одна дверь на окно, ответ в своей задаче), но со СВОИМИ словами и
/// подписями кнопок — круг починки 3 задачи 16: у действий, которые ведут к
/// одному и тому же факту («сеанс не продолжит работать со старой базой»),
/// формулировки события разные (сохранить / сменить режим / сделать
/// текущим), и текст обязан называть то, что человек нажал, а не слово
/// «Сохранить» для всех разом. Решение «спрашивать» не удваивается: оно
/// всё так же одно на действие.
// Восемь — тот же счёт, что у `ask_yes_no`, по той же причине: платформенный
// диалог целиком (окно, текст, деталь, две подписи кнопок) и продолжение.
// Группировать нечего.
#[allow(clippy::too_many_arguments)]
pub fn confirm_database_change_with_text(
    window: &mut Window,
    cx: &mut App,
    new_host: &Connection,
    message: &str,
    detail: &str,
    yes: &'static str,
    no: &'static str,
    proceed: impl FnOnce(&mut Window, &mut App) + 'static,
) {
    if save_question(cx.global::<Ui>(), new_host).is_none() {
        proceed(window, cx);
        return;
    }
    ask_yes_no(window, cx, message, detail, yes, no, false, proceed);
}

/// Спросить человека «да или нет» платформенным диалогом и сделать `proceed`
/// только на «да». Общая обвязка для всех таких вопросов: один открытый
/// диалог на окно (`dialog_open`), ответ приходит в своей задаче — главный
/// поток ничего не ждёт, — и молчаливых выходов отсюда нет: человек нажал и
/// обязан узнать, почему ничего не случилось.
// Восемь — это платформенный диалог целиком: два текста, две подписи
// кнопок, признак опасного действия и продолжение. Группировать нечего.
#[allow(clippy::too_many_arguments)]
pub fn ask_yes_no(
    window: &mut Window,
    cx: &mut App,
    message: &str,
    detail: &str,
    yes: &'static str,
    no: &'static str,
    destructive: bool,
    proceed: impl FnOnce(&mut Window, &mut App) + 'static,
) {
    if cx.global::<Ui>().dialog_open {
        // Молчать нельзя: человек нажал кнопку и обязан узнать, почему ничего
        // не произошло. Молчаливый выход отсюда и был вторым тупиком той же
        // кнопки. В журнал, не в `set_status` (Important 5 ревью круга
        // задачи 11): подвал с 9.11 левый слот не показывает вовсе, и строка,
        // которая жила только в `ui.status`, была ответом, которого человек
        // не мог увидеть нигде.
        note_line(cx.global_mut::<Ui>(), Line { kind: Kind::Warn, text: "Сначала ответьте на уже открытый вопрос".into() });
        return;
    }
    cx.global_mut::<Ui>().dialog_open = true;
    // Диалог свой, а не платформенный (`Window::prompt`): тот приходит в теме
    // системы и с заголовком «Warning», поверх тёмного окна — чужая дверь в
    // своём доме (замечание владельца 28.10). Свой рисуется той же темой, что
    // и окно, и не отнимает у него фокус — значит и прятаться окну не от чего.
    let (message, detail) = (message.to_string(), detail.to_string());
    // `open_alert_dialog` берёт `Fn`, а согласие даётся один раз: продолжение
    // кладётся в ячейку и забирается первым же «да».
    let once = std::rc::Rc::new(std::cell::RefCell::new(Some(proceed)));
    let danger = destructive;
    window.open_alert_dialog(cx, move |alert, _, _| {
        let once = once.clone();
        alert
            .confirm()
            .title(message.clone())
            .description(detail.clone())
            .ok_text(yes)
            .cancel_text(no)
            // Красная кнопка там, где действие отнимает сделанное: то же
            // правило, что развело пункты меню по разрядам.
            .ok_variant(if danger { ButtonVariant::Danger } else { ButtonVariant::Primary })
            .on_ok(move |_, window, cx| {
                cx.global_mut::<Ui>().dialog_open = false;
                if let Some(proceed) = once.borrow_mut().take() {
                    proceed(window, cx);
                }
                true
            })
            .on_cancel(move |_, _, cx| {
                cx.global_mut::<Ui>().dialog_open = false;
                true
            })
    });
}

/// Поднять/проверить HTTP-сервис на уже записанных `ui.cfg`: после смены
/// базы («Сохранить», см. выше), при включении MCP (`toggle_link`) и при
/// старте с «подключаться при запуске» (`launch`). `ensure_publication` сама
/// идемпотентна и решает режим, но пробует связь с таймаутом в 3 с, в режиме
/// «webserver» ходит в сеть за версией расширения, а после запуска своего
/// httpd ждёт его готовности — всё это в своём потоке, а не на главном
/// потоке окна (находка повторного ревью: окно подвисало на эти секунды).
/// Ответ идёт `Ev::Publish`: журнал на отказе и карточка — в `handle`, не
/// здесь, иначе карточка соврала бы, что всё в порядке, пока агент отвечает
/// с ошибкой.
/// Поднимать ли HTTP-сервис базы после записи параметров. Условий два, и
/// второе появилось по замечанию заказчика 2026-10-21: «сохранил — в журнале
/// сообщение об успешном поднятии http сервера, хотя я даже не пытался
/// включить MCP».
///
/// Переменился путь базы (`descriptor_changed`, не `database_changed` — с
/// задачи 6 логин и пароль дескриптор не несёт, переподнимать публикацию
/// ради них незачем) — старый дескриптор указывает не туда, и сервис обязан
/// посмотреть на новую, иначе агент отвечал бы из прежней базы. Но нужно это
/// только тому, кто сейчас обслуживает: при выключенном переключателе мост
/// отказывает ещё до публикации, и поднимать её — работа, которой никто не
/// просил, да ещё и объявленная в журнале как успех. Включат MCP —
/// `ensure_publication` сходит сама.
pub fn republish_after_save(descriptor_changed: bool, serving: bool) -> bool {
    descriptor_changed && serving
}

/// Подъём публикации в своём потоке. Голос к базе он берёт не здесь, а внутри
/// `ops_host::extension_reach` — в единственном месте, которое правда говорит
/// с базой (Important 2 ревью круга 2): мьютекс вокруг потока можно отменить,
/// убрав одну строку, а дорогу к базе мимо `extension_reach` не проложить.
///
/// Здесь же ставится отметка «публикация поднимается» (`ui.publishing`) — в
/// том же месте, где заводится поток, как у щелчка агента: пока она стоит,
/// расчёт готовности не идёт вовсе (`start_facts`), и человек не читает «не
/// всё готово» про порт, который мы сами в эту секунду и поднимаем.
pub fn ensure_publication_now(ui: &mut Ui) {
    let ctx = ctx_for(ui);
    let tx = ui.tx.clone();
    let started = Instant::now();
    ui.publishing = Some(started);
    std::thread::spawn(move || {
        let r = ops_host::ensure_publication(&ctx).map_err(|e| format!("{e:#}"));
        let _ = tx.unbounded_send(Ev::Publish { started, r });
    });
}

