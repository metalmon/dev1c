//! Разрешение на работу — файл в каталоге состояния (`Kit::state`), а не флаг в памяти окна: скоро у рабочего места несколько процессов (окно, `connect`, `serve`, будущая подкоманда `mcp`), и только диск виден им всем.
//!
//! Закрыто по умолчанию: разрешение — это ровно `"on"` в файле, и только при живом владельце рабочего места; всё непонятное (файла нет, он пуст, в нём чужое слово, владельца не видно) означает «нельзя» — тем же правилом, каким живёт гейт в `gui/gate.rs`.
//!
//! Живость владельца — не флаг на диске (тот не переживает `taskkill`), а
//! вопрос живому экземпляру через управляющую дверь
//! (`single_instance::is_serving`). Спрашивающий при этом ничем не владеет и
//! ничего не занимает даже на микросекунду — иначе два читателя (`watch` и
//! прямой `read`, два процесса подкоманды `mcp`) заверяли бы живость друг
//! друга (находка ревью задачи 2).
//!
//! Круг исправления после ревью `717c873`/`e1ff800`: `window_alive` (теперь
//! `connector_alive`) смотрела в замок РАБОЧЕГО МЕСТА, в ключе которого было
//! имя рабочего места. «Сохранить» меняет его у открытого окна без
//! перезапуска (`gui/save.rs`), замок оставался под старым именем до выхода
//! процесса — после переименования эта проверка видела бы «владельца нет»
//! при живом окне, и MCP молча считались бы выключенными.
//!
//! Круг правок 2 задачи 14 довёл это до конца: признак обслуживания был
//! вторым объектом ядра про то же самое, и на Windows — без префикса, то
//! есть видимым только в своём сеансе. Теперь вопрос один и задаётся
//! держателю: жив ли он и обслуживает ли. Между сеансами одной учётной
//! записи это работает, а объект ядра не работал — ровно тот случай, что у
//! окна из задачи планировщика и человека из своего сеанса.

use crate::single_instance;
use common::kit::{write_text, Kit};
use std::path::PathBuf;

/// Имя файла признака в каталоге состояния — рядом с `install.state` и `1c-connect.log`.
const FILE: &str = "allow";

/// Путь к файлу признака для этого рабочего места.
pub fn path(kit: &Kit) -> PathBuf {
    kit.state_path(FILE)
}

/// Решение, читать ли разрешение как «да» — чистая функция без диска, чтобы все углы (пустой файл, чужое слово, отсутствие владельца) проверялись без файловой системы. `file` — содержимое, как его прочитал `read` (`None`, если файла нет); `connector_alive` — результат проверки признака обслуживания. Разрешение — это `connector_alive` и буквально `"on"` после обрезки пробелов, ничего больше: поэтому «выключено» и опечатка в файле — то же самое, что файла нет вовсе.
pub fn decide(file: Option<&str>, connector_alive: bool) -> bool {
    connector_alive && file.map(|s| s.trim() == "on").unwrap_or(false)
}

/// Записать признак: `on` при разрешённой работе, `off` — когда владелец её снял или выходит. Возвращает ошибку, а не проглатывает её сама: непрошедший `off` оставляет на диске «on» при уже мёртвом или выключенном владельце — то есть разрешение, которое никто не давал, а не безопасный исход, и о нём обязан узнать вызывающий (окно — в журнал, см. `gui::quit`/`gui::link`), а не тишина (минорная находка ревью задачи 2).
pub fn write(kit: &Kit, on: bool) -> anyhow::Result<()> {
    write_text(&path(kit), if on { "on\n" } else { "off\n" })
}

/// Жив ли тот, кто обслуживает это рабочее место, прямо сейчас —
/// `single_instance::is_serving`, которая смотрит на признак, не занимая
/// его: занятый признак проверкой сам превратил бы её в держателя на те же
/// микросекунды, и соседняя проверка (другой процесс `mcp`, или `watch`
/// рядом с прямым `read`) увидела бы «занято» и сочла бы владельца живым,
/// хотя настоящего уже нет (находка ревью задачи 2). Имя не об «оконном
/// процессе» конкретно: признак берут поровну окно, `connect` и `serve`
/// (`main.rs`, `gui/mod.rs`) — вопрос один, «обслуживает ли кто-то это
/// рабочее место», и headless `serve` отвечает на него так же честно, как
/// окно.
pub(crate) fn connector_alive() -> bool {
    // Не спросилось (учётная запись не узналась) — то же самое непонятное,
    // что и чужое слово в файле: закрыто по умолчанию. Живого нет —
    // `is_serving` и так отдаёт `false`, отказом это не считается.
    single_instance::is_serving().unwrap_or(false)
}

/// Прочитать разрешение прямо сейчас: файл с диска плюс живость владельца,
/// через `decide`. Живость даёт вызывающий — и это не украшение, а шов:
/// настоящая живость спрашивается у двери (`connector_alive`), а имя двери
/// настоящей копии тест занять не вправе; проверить же он обязан именно
/// связку «файл плюс живой», а не `decide` в отрыве от неё (находка ревью
/// задачи 2: единственная строка, которая и есть дверь, не была покрыта
/// ничем).
///
/// Зовущий один — `ops_host::mcp_tick`, и он же носит живость от самого
/// `run_mcp`: вопрос «жив ли коннектор» в подкоманде `mcp` задаётся в одном
/// месте.
pub(crate) fn read_with(kit: &Kit, alive: impl FnOnce() -> bool) -> bool {
    let file = std::fs::read_to_string(path(kit)).ok();
    decide(file.as_deref(), alive())
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Строка, уникальная на каждый вызов (счётчик плюс pid) — как `unique` в
    /// `single_instance.rs`, иначе параллельные тесты этого файла спорили бы
    /// за один каталог состояния или за один ключ замка.
    fn unique(tag: &str) -> String {
        use std::sync::atomic::{AtomicU64, Ordering};
        static N: AtomicU64 = AtomicU64::new(0);
        let n = N.fetch_add(1, Ordering::Relaxed);
        format!("{tag}-{}-{n}", std::process::id())
    }

    fn tempdir() -> PathBuf {
        let p = std::env::temp_dir().join(unique("allow-test"));
        std::fs::create_dir_all(&p).unwrap();
        p
    }

    fn kit_in(dir: PathBuf) -> Kit {
        Kit::at(dir)
    }

    #[test]
    fn no_window_means_no_work() {
        assert!(!decide(None, false));
    }

    #[test]
    fn a_stale_allow_file_does_not_allow() {
        // Окно сняли taskkill: файл остался «on», но замок свободен.
        assert!(!decide(Some("on"), false));
    }

    #[test]
    fn the_switch_decides_while_the_window_lives() {
        assert!(decide(Some("on"), true));
        assert!(!decide(Some("off"), true));
        // Чего не понимаем — запрещаем: файл чужой или полузаписанный.
        assert!(!decide(Some(""), true));
        assert!(!decide(Some("вкл"), true));
        assert!(!decide(None, true));
    }

    #[test]
    fn a_written_flag_reads_back() {
        let kit = kit_in(tempdir());
        write(&kit, true).unwrap();
        assert_eq!(std::fs::read_to_string(path(&kit)).unwrap().trim(), "on");
        write(&kit, false).unwrap();
        assert_eq!(std::fs::read_to_string(path(&kit)).unwrap().trim(), "off");
    }

    /// Живой коннектор на время теста — тот же приём, что в
    /// `orphan.rs`/`ops_host.rs` (не общий, дублирован тем же порядком, что
    /// и `unique` выше — мелкие тестовые помощники в этом крейте не делят на
    /// несколько модулей).
    /// Живой экземпляр на время теста: его роль играет открытая управляющая
    /// дверь, объявившая обслуживание, — то же самое, что делает настоящий
    /// коннектор (`single_instance::acquire` плюс `Door::show`). Своё имя
    /// двери на каждый прогон: занять имя настоящей копии тест не вправе.
    fn a_serving_connector(kit: &Kit) -> (String, crate::door::Door) {
        let name = crate::door::door_name(&unique("allow-door"));
        let door = crate::door::open_at(&name, kit).expect("дверь открылась");
        door.show(crate::door::StatusView { serving: true, cards: None });
        (name, door)
    }

    /// Важная находка ревью задачи 2: единственная строка, которая и есть
    /// дверь (живость внутри `read`), не была покрыта ничем — тесты `decide`
    /// проходили при любой её поломке. Здесь живого играет настоящая
    /// управляющая дверь: объявила обслуживание — `read` обязан увидеть «on»
    /// как разрешение; перестала — тот же файл с тем же «on» больше не
    /// разрешение.
    ///
    /// Круг исправления после ревью `717c873`/`e1ff800`: раньше тест держал
    /// замок РАБОЧЕГО МЕСТА, которым `window_alive` ошибочно и смотрела, —
    /// то есть ключ, в котором было имя рабочего места.
    ///
    /// Круг правок 2 задачи 14: прежде здесь ждали в цикле до двух секунд,
    /// потому что снятый `flock` успевал ещё разок прочитаться как живой и
    /// тест падал примерно в одном прогоне из трёх. Дверь отвечает из памяти
    /// держателя, и ждать нечего: перемена видна следующим же вопросом.
    #[test]
    fn read_follows_the_connector_not_just_the_file() {
        let kit = kit_in(tempdir());
        write(&kit, true).unwrap();
        let (name, door) = a_serving_connector(&kit);
        let alive = || crate::door::serving_at(&name);
        assert!(read_with(&kit, alive), "коннектор обслуживает — файл «on» должен читаться как разрешение");
        door.show(crate::door::StatusView { serving: false, cards: None });
        assert!(!read_with(&kit, alive), "коннектор не обслуживает — тот же файл «on» больше не разрешение");
    }
}
