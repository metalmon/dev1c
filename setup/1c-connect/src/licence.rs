//! Заглушка под лицензию. Настоящей лицензии ещё нет, но место под неё нужно
//! уже сейчас — и нужно, чтобы она действительно останавливала работу, иначе
//! заглушка ничего не проверяет (спека, п. 9 «Порядок работ»). Всё живёт
//! здесь: одна зашитая дата, одно состояние на дату и один текст отказа —
//! когда появится настоящая лицензия, менять придётся только этот модуль.
//!
//! Состояние считается чистой функцией от **переданной** даты, а не от часов:
//! иначе тест на «день после срока» пришлось бы ставить переводом времени
//! машины. На часы смотрит только `today()`.
//!
//! Подменять часы мы не мешаем: это заглушка, а не защита от злого умысла.

/// До какого числа коннектор обслуживает работу, **включительно**: 22 декабря
/// 2026 — ещё рабочий день, «перестаёт работать» значит с 23-го. Решение
/// заказчика 2026-10-20. Единственное место, где записан срок.
pub const UNTIL: (i32, u32, u32) = (2026, 12, 22);

/// За сколько дней до срока предупреждаем заранее. Без предупреждения человек
/// узнаёт о сроке в тот момент, когда уже не может работать.
const WARN_DAYS: i64 = 14;

/// Текст отказа — один и тот же у моста, у разовых команд и в окне: человек
/// обязан увидеть, что случилось и до какого числа срок был. Дата вписана
/// словами, потому что это `const`; что она не разошлась с `UNTIL`, держит
/// тест `the_refusal_names_the_deadline`.
pub const REFUSAL: &str = "срок действия 1c-connect истёк 22.12.2026 — работа не обслуживается, обратитесь к поставщику";

/// Состояние заглушки на дату.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum State {
    /// До срока далеко, говорить человеку нечего.
    Valid,
    /// Срок ещё не вышел, но осталось `days` дней (`WARN_DAYS` и меньше);
    /// `days == 0` — тот самый последний рабочий день.
    Soon { days: u32 },
    /// Срок вышел: работу не обслуживаем.
    Expired,
}

/// Срок в виде, который читает человек: `22.12.2026`.
pub fn until_text() -> String {
    let (y, m, d) = UNTIL;
    format!("{d:02}.{m:02}.{y}")
}

/// Состояние на переданную дату — та самая чистая функция, вокруг которой
/// держится весь модуль.
pub fn state_on(y: i32, m: u32, d: u32) -> State {
    let left = days_from_civil(UNTIL.0, UNTIL.1, UNTIL.2) - days_from_civil(y, m, d);
    if left < 0 {
        State::Expired
    } else if left <= WARN_DAYS {
        State::Soon { days: left as u32 }
    } else {
        State::Valid
    }
}

/// Местная дата машины — единственное место, которое смотрит на часы.
///
/// Часовой пояс не вычитаем: в дереве нет ни `chrono`, ни `time`, а тащить их
/// ради одной даты незачем (так же поступает `gui::clock` вне Windows). Это
/// не безразлично, и вот как: считаем по UTC, поэтому восточнее Гринвича срок
/// кончится позже местной полуночи (в Москве — на три часа в пользу
/// человека), а западнее последний рабочий день обрежется на столько же часов
/// раньше срока. Сдвиг на часы принят сознательно — ради него не стоит двух
/// платформенных веток с `unsafe` (`GetLocalTime`/`localtime_r`); настоящая
/// лицензия, когда появится, будет считать это место иначе.
pub fn today() -> (i32, u32, u32) {
    let secs = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0);
    civil_from_days((secs / 86_400) as i64)
}

/// Состояние на сегодня: `today()` плюс `state_on`. Зовут мост, команды и
/// окно — чтобы они не повторяли эти две строки каждый у себя.
pub fn state_now() -> State {
    let (y, m, d) = today();
    state_on(y, m, d)
}

/// Дата → номер дня от 1970-01-01 (алгоритм Хиннанта `days_from_civil`).
/// Нужен, чтобы вычесть одну дату из другой: календарь со всеми его
/// високосными годами тут считается один раз и честно.
fn days_from_civil(y: i32, m: u32, d: u32) -> i64 {
    // Год начинается в марте — тогда високосный день оказывается последним
    // днём года и выпадает из формулы месяцев.
    let y = i64::from(y) - i64::from(m <= 2);
    let era = if y >= 0 { y } else { y - 399 } / 400;
    let yoe = y - era * 400;
    let doy = (153 * (i64::from(m) + if m > 2 { -3 } else { 9 }) + 2) / 5 + i64::from(d) - 1;
    let doe = yoe * 365 + yoe / 4 - yoe / 100 + doy;
    era * 146_097 + doe - 719_468
}

/// Номер дня от 1970-01-01 → дата (обратный ход того же алгоритма).
fn civil_from_days(z: i64) -> (i32, u32, u32) {
    let z = z + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    ((y + i64::from(m <= 2)) as i32, m as u32, d as u32)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// «Действует» здесь значит «работу обслуживаем», а не `State::Valid`:
    /// за день до срока человек уже предупреждён, и это `Soon`.
    #[test]
    fn a_day_before_the_deadline_is_valid() {
        let s = state_on(2026, 12, 21);
        assert_ne!(s, State::Expired);
        assert_eq!(s, State::Soon { days: 1 });
    }

    /// Срок включительно: «после 22.12» значит с 23-го, 22-е ещё рабочий день.
    #[test]
    fn the_deadline_day_itself_is_valid() {
        let s = state_on(2026, 12, 22);
        assert_ne!(s, State::Expired);
        assert_eq!(s, State::Soon { days: 0 });
    }

    #[test]
    fn a_day_after_is_expired() {
        assert_eq!(state_on(2026, 12, 23), State::Expired);
        // И через год после срока — тоже: шага «снова заработало» нет.
        assert_eq!(state_on(2027, 12, 23), State::Expired);
    }

    #[test]
    fn two_weeks_before_warns_with_days_left() {
        assert_eq!(state_on(2026, 12, 8), State::Soon { days: 14 });
        // За день до начала предупреждения — ещё тихо.
        assert_eq!(state_on(2026, 12, 7), State::Valid);
    }

    #[test]
    fn a_year_before_is_quiet() {
        assert_eq!(state_on(2025, 12, 22), State::Valid);
    }

    /// Единственная проверка часов: больше о `today()` сказать нечего, не
    /// переводя время машины.
    #[test]
    fn today_matches_the_system_date() {
        let (y, m, d) = today();
        assert!(y >= 2026, "год {y}");
        assert!((1..=12).contains(&m), "месяц {m}");
        assert!((1..=31).contains(&d), "день {d}");
    }

    /// Перевод секунд в календарь — единственный путь от часов к дате, и
    /// ошибись он на день, срок сдвинулся бы молча. Круговой ход сам по себе
    /// прошёл бы и при согласованном сдвиге обеих сторон, поэтому рядом —
    /// якорь на начале эпохи и високосный день.
    #[test]
    fn the_calendar_converts_both_ways() {
        assert_eq!(civil_from_days(0), (1970, 1, 1));
        assert_eq!(days_from_civil(1970, 1, 1), 0);
        for (y, m, d) in [(2024, 2, 29), (2026, 12, 22), (2026, 12, 23)] {
            assert_eq!(civil_from_days(days_from_civil(y, m, d)), (y, m, d), "{y}-{m}-{d}");
        }
        // 2024 високосный — 29 февраля и 1 марта соседние дни; 2026 нет.
        assert_eq!(days_from_civil(2024, 3, 1) - days_from_civil(2024, 2, 29), 1);
        assert_eq!(days_from_civil(2026, 3, 1) - days_from_civil(2026, 2, 28), 1);
        // Переход через год: 23.12.2026 на день дальше срока.
        assert_eq!(days_from_civil(2027, 1, 1) - days_from_civil(2026, 12, 22), 10);
    }

    /// Дата записана в `REFUSAL` словами — тест держит её в согласии с `UNTIL`.
    #[test]
    fn the_refusal_names_the_deadline() {
        assert!(REFUSAL.contains(&until_text()), "{REFUSAL}");
    }
}
