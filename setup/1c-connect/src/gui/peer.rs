    /// Разговоры по карточкам: пустая строка — разговор, чья карточка не
    /// опознана.
    fn named(names: &[&str]) -> Vec<Option<CardId>> {
        names.iter().map(|n| (!n.is_empty()).then(|| CardId::from(*n))).collect()
    }

    /// Отзыв во время разговора обязан снять поток ЭТОЙ карточки — и только
    /// его.
    ///
    /// Падал так: живые разговоры лежали под ключом «имя карточки + сторона»,
    /// где имя добывалось перебором по признаку базы. Совпало не то имя —
    /// поток не находился, и человек, нажавший «Отозвать», получал запись об
    /// отзыве и живой поток сверху. Отзыв перестаёт быть немедленным ровно
    /// там, где это важнее всего.
    #[test]
    fn revoking_during_a_talk_cuts_that_cards_stream() {
        let talks = named(&["Ромашка", "Василёк", "Ромашка"]);
        assert_eq!(cut_these(&talks, &"Ромашка".into()), vec![0, 2]);
        // Соседняя карточка той же стороны не трогается: человек снял доступ
        // к одной базе, а не ко всем.
        assert_eq!(cut_these(&talks, &"Василёк".into()), vec![1]);
        // Отзыв карточки, у которой живого разговора нет, не режет ничего.
        assert_eq!(cut_these(&talks, &"Пион".into()), Vec::<usize>::new());
    }

    /// Отзыв по стороне, чья карточка не опознана, тоже обязан рвать.
    ///
    /// Падал так: безымянный разговор лежал под ПУСТЫМ именем, и отзыв по
    /// настоящему имени карточки его не находил никогда — то есть именно тот
    /// поток, про который мы меньше всего знаем, переживал отзыв.
    #[test]
    fn a_stream_with_no_card_name_is_cut_too() {
        let talks = named(&["", "Василёк"]);
        assert_eq!(cut_these(&talks, &"Ромашка".into()), vec![0], "безымянный режется любым отзывом этой стороны");
        assert_eq!(cut_these(&talks, &"Василёк".into()), vec![0, 1], "и вместе с названным — тоже");
    }

    /// Отзыв ОДНОЙ карточки не режет разговоры соседних — ни одного, сколько
    /// бы их у этой стороны ни было.
    ///
    /// Падало так: за потоком стороны, вернувшейся БЕЗ имени карточки,
    /// числились все базы партнёра сразу (`enroll::Outcome::Already` приносил
    /// список), и отзыв любой из них резал такой поток целиком. У человека с
    /// пятью карточками к одному партнёру каждый поток был «за всеми» — то есть
    /// отзыв одной карточки рвал связь по остальным четырём, прямо против
    /// спеки. Теперь у потока карточка одна (`Talk::card`), и резать соседей
    /// отзыву нечем.
    #[test]
    fn revoking_one_card_leaves_the_other_talks_of_the_same_party_alone() {
        let five = named(&["Ромашка", "Василёк", "Пион", "Лютик", "Мята"]);
        assert_eq!(cut_these(&five, &"Пион".into()), vec![2], "режется ровно один разговор — той карточки, что отозвали");
        assert_eq!(cut_these(&five, &"Мята".into()), vec![4]);
        // Отзыв карточки, у которой живого разговора нет, не режет ничего.
        assert_eq!(cut_these(&five, &"Ирис".into()), Vec::<usize>::new());
    }

    /// Щель между решением человека и записью вожжей: разговор, у которого
    /// разрешения уже нет, не держится.
    ///
    /// Падал так: проверки после записи вожжей не было вовсе. `accept_side`
    /// вернул «зачислен», вожжи ещё не записаны — и отзыв, попавший в эти
    /// микросекунды, не находил чего рвать; поток переживал собственный отзыв
