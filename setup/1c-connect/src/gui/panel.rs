/// спековское «Передайте эту строку тому, кто подключается: он вставит её у
/// себя» для тела карточки онбординга. Указатель ревью задачи 11 требовал
/// свести к одной формулировке, и выбрана эта — по двум причинам. Первая:
/// «эту строку» показывает пальцем на строку кода, которой на экране нет и
/// не будет до протокола подключения (кода и тикета в этой ветке нет
/// вовсе), а здесь предложение объясняет ОТСУТСТВИЕ кнопки, и показывать
/// пальцем ему не на что. Вторая: «код» — то же слово, что в пункте меню
/// «Показать код» и в обоих ответах онбординга, а «строка» заводит второе
/// слово для той же вещи.
///
/// Константа, а не литерал: когда протокол принесёт тело карточки с кодом,
/// предложение возьмут отсюда, а не напишут третий раз своими словами.
pub const PASS_THE_CODE: &str = "Передайте код на ту сторону — оттуда и подключатся.";

/// Главная кнопка «Связи»: ровно один предмет (решение владельца 3.11) —
/// открытая карточка (`selected`), а нет открытой — текущее соединение
/// (`resolve_selected`, тот же откат, что держит карточку при исчезнувшей
/// строке, задача 2). Подпись решает ОДНО состояние предмета зараз, по
/// порядку:
///
/// 1. список пуст — предмета нет, кнопки нет (третий способ завести
///    соединение на первом экране — лишний орган там, где человек впервые,
///    задача 11 отвечает за сам онбординг);
/// 2. предмет НЕ текущее соединение — «Сделать текущим» (единственная
///    подпись, которую задача 14 к списку задачи 8 добавила; сама подпись
///    не новая — её слово в продукте уже есть). Исключение одно: разошлось
///    ОДНО имя (`Dirty::NameOnly`) — тогда «Сохранить», см. ниже;
/// 3. правка важнее всего — её потеря дороже, чем недосказанное состояние
///    связи («Сохранить», подсказку отдаёт тот же `save_hint`, что уже
///    объясняет недоступность на вкладке);
/// 4. локальный режим — это выключатель обслуживания MCP, а не связь
///    («Включить»/«Выключить»);
/// 5. соединение зовёт само (`role() == "dial"`) и не подключено —
///    «Подключиться»;
/// 6. соединение принимает подключения и ждёт — набирать код там, а не
///    здесь: кнопка заперта и называет состояние (`link::row`), а `why`
///    говорит, где действие («Разрешить» в подвале не появляется вовсе,
///    решение владельца 1.11 — оно всплывающим окном, а упущенное
///    возвращается кнопкой внутри карточки);
/// 7. всё прочее (уже подключено, рвётся, переподключается — транспорта эта
///    задача не касается вовсе) — кнопка заперта и называет то же состояние;
///    объяснять нечего сверх этого — левый слот подвала уже говорит причину
///    через `reason` (`foot_left_text`), второй копии доводов не заводим.
///
/// **Ветки 6 и 7 не исчезают, а запираются** (спека «Интерфейс»: «иначе
/// заперта и называет состояние», живой прогон 9.11). Слово состояния — из
/// того же словаря, что уже красит строку списка (`link::row`), а не
/// придуманное здесь заново: тот же вопрос «что сейчас происходит»,
/// заданный кнопкой вместо строки, и второго словаря для него не заводим.
///
/// **Почему ветка 2 стоит выше ветки связи** (указатель 2 ревью: признак
/// связи читает `ui.link.is_up()` — состояние ТЕКУЩЕГО соединения, а не
/// открытой карточки). Связь в продукте одна на машину и принадлежит
/// текущему соединению; живого состояния на карточку нет вовсе (`link::list`
/// получает его заглушкой-поиском по имени). Поэтому «Подключиться» у
/// НЕтекущей карточки нажималось бы, а подключало текущую — та же мина, что
/// заглушка `UNWIRED` в меню, только тише. Выход не в докстроке «почему так
/// терпимо», а в том, что ниже ветки 2 `ui.link` читается ТОЛЬКО когда
/// предмет и есть текущее соединение: тогда это его состояние по
/// построению.
///
/// Правка полей нетекущей карточки при этом не теряется — она ждёт, и `why`
/// говорит, чего ждёт («Поля правятся у текущего соединения»): став текущей,
/// карточка тут же получает «Сохранить» (поля и точка отсчёта `original` от
/// переключения не двигаются). Это же снимает и вторую беду, которой ветка 3
/// грозила бы без неё: `save_host` пишет ТЕКУЩЕЕ соединение, и «Сохранить» у
/// нетекущей карточки уехало бы в чужой блок toml.
///
/// **Имя — исключение, и ровно по этому доводу** (Important 2 круга починки
/// 1): `save::rename` адресуется ПО ИМЕНИ карточки, в чужой блок уехать не
/// может, и запрет записи нетекущей ему не нужен. Поэтому «Переименовать»
/// у карточки заказчика перестало быть тупиком: переключать базу агента ради
/// косметики больше не надо. Вместе с полями имя снова ждёт переключения —
/// их пишет `save_host`, и разделять одну запись на две половины с разной
/// судьбой мы не станем.
///
/// Второго органа переключения это не заводит: в меню «Связи» пункта
/// «Сделать текущим» нет (спека: «Переключение текущего — одно действие,
/// построенное одним кодом, а не два органа управления»).
pub fn main_button(ui: &Ui, selected: &str, dirty: Dirty) -> Button {
    if ui.cfg.connections.is_empty() {
        return Button { subject: String::new(), label: "", why: None, act: None };
    }
    let c = resolve_selected(&ui.cfg, selected);
    let subject = c.name.clone();
    // Подсказка, почему «Сохранить» недоступна, — одна на оба случая записи
    // ниже: её даёт тот же `save_hint`, что объясняет недоступность кнопки
    // на вкладке.
    let save = |subject: String| {
        let hint = save_hint(true, ui.busy.is_some(), ui.progress.as_ref().map(|r| r.which));
        Button { subject, label: "Сохранить", why: hint, act: Some(LinkAct::Save) }
    };
    if c.name != ui.cfg.current().name {
        // Отличается ОДНО имя — «Сохранить» и у нетекущей карточки
        // (Important 2 круга починки 1): `save::rename` пишет по имени
        // карточки и в чужой блок не уедет, то есть защита, ради которой
        // запись нетекущей запрещена, здесь не нужна вовсе. Заставлять
        // человека переключать базу агента ради косметики не за что.
        if dirty == Dirty::NameOnly {
            return save(subject);
        }
        let why = (dirty == Dirty::Fields).then(|| "Поля правятся у текущего соединения.".to_string());
        return Button { subject, label: "Сделать текущим", why, act: Some(LinkAct::MakeCurrent) };
    }
    if dirty != Dirty::No {
        return save(subject);
    }
    if c.mode == "local" {
        let label = if ui.link.is_up() { "Выключить" } else { "Включить" };
        return Button { subject, label, why: None, act: Some(LinkAct::Toggle) };
    }
    if ui.link.is_up() {
        // Подключено/рвётся/переподключается — не наш случай (транспорта не
        // трогаем). Кнопка не пропадает: заперта (`act: None`) и называет
        // состояние словом `link::row` — причина уже сказана в левом слоте
        // подвала (`reason`), второй раз её здесь не произносим (`why: None`).
        return Button { subject, label: link::row(c, true, Some(&ui.link)).state, why: None, act: None };
    }
    if matches!(c.role(), Ok("dial")) {
        return Button { subject, label: "Подключиться", why: None, act: Some(LinkAct::Toggle) };
    }
    // Принимающему подключаться не к кому — связь не его действие. Кнопка
    // заперта и называет состояние тем же словом, что строка списка
    // (`link::row`), а не пропадает (спека «иначе заперта и называет
    // состояние»); `why` всё равно говорит, куда передать код.
    Button { subject, label: link::row(c, true, Some(&ui.link)).state, why: Some(PASS_THE_CODE.to_string()), act: None }
}

/// Высота строки левого слота подвала при размере текста 13 и число строк,
/// которые слот резервирует всегда — даже когда текст в одну. Две строки по
/// 16 px — ровно высота кнопки рядом (`Button` размера Medium, `h_8` =
/// 32 px), и подвал не растёт по тексту: подбор высоты окна
/// (`window::needs_fit`) построен на неизменной высоте подвала, а растущая
/// плашка заставляла окно подпрыгивать. Третья строка не переносится, а
/// режется многоточием; полный текст — подсказкой по наведению.
pub const FOOT_LINE: f32 = 16.;
pub const FOOT_LINES: usize = 2;

/// Левый слот подвала: ровно один текст, не два (заказчик 2026-10-20: «возле
/// нижней кнопки почему-то две надписи стало»). Порядок, кто в нём говорит:
///
/// 1. настоящее сообщение (итог сохранения, ошибка) — человек только что
///    нажал и ждёт ответа;
/// 2. причина текущего состояния (`reason`: отказ, замок, провал вердикта) —
///    она про то, почему работа не идёт;
/// 3. подсказка, почему «Сохранить» недоступна, — она про кнопку, и своя
///    подсказка по наведению у кнопки есть и без слота;
/// 4. путь комплекта — когда сказать больше нечего.
///
/// Пункты 2 и 3 стояли наоборот, и причина не показывалась почти никогда:
/// «Связь» — вкладка по умолчанию, поля на ней не тронуты, а `save_hint`
/// тогда на нетронутых полях всегда говорил «Нечего сохранять». Человек
/// видел оранжевую точку, «Не всё готово» и этот пересказ рядом — и ничего
/// о том, что именно не готово (находка S3 итогового ревью). Саму подпись
/// 25.10.2026 убрали, но порядок остался: подсказка про кнопку слабее
/// причины, по которой работа не идёт.
///
/// Раскладка по двум строкам, обрезка третьей и подсказка по наведению —
/// дело `render`, здесь только выбор источника.
///
/// Текст уходит через `gui::capitalized` — та же заглавная, что у карточек и
/// журнала. Путь комплекта она не трогает (первое слово с `:` и `\`).
pub fn foot_left_text(status: Option<&Line>, reason: Option<&str>, hint: Option<&str>, kit_path: &str) -> (String, bool) {
    let (text, bad) = if let Some(l) = status {
        (l.text.clone(), matches!(l.kind, Kind::Fail))
    } else if let Some(why) = reason {
        (why.to_string(), false)
    } else if let Some(h) = hint {
        (h.to_string(), false)
    } else {
        (kit_path.to_string(), false)
    };
    (gui::capitalized(&text), bad)
}

/// Строки вкладки «Инструменты» по набору фактов — тому самому, из которого
/// выведен вердикт карточки и который печатает «Проверить». Один факт — одна
/// строка, и ни одной своей: ни отбора, ни добавок, ни пересказа. Прежде
/// вкладка спрашивала `run::status` сама, своими пробами и в свои секунды, —
/// отсюда и бралось «расширение не установлено» при живом расширении 0.4.8
/// рядом с зелёной карточкой (спека, «Зачем»).
///
/// Цвет точки — по исходу факта (`Check::outcome`), и это единственное, что
/// строка о факте решает:
///
/// * провал — красная: это то, что человек чинит;
/// * занято — жёлтая: подождать или закрыть базу, чинить нечего;
/// * сведение (`Check::note`) — серая: факту сказать нечего (чужой дескриптор
///   публикации, комплект на носителе, открытый сеанс 1С), и зелёным оно не
///   бывает — зелёное значит «проверено и сошлось»;
/// * пройденный — зелёная.
///
/// `Option<Dot>` в кортеже — ради общей раскладки с `project_rows` (там
/// `None` у подсказки, которая не факт); у факта точка есть всегда.
pub fn fact_rows(facts: &[Check]) -> Vec<(Option<Dot>, String, String)> {
    facts.iter().map(|c| shown_row(Some(fact_dot(c)), &c.what, &gui::fact_detail(c))).collect()
}

/// Строка карточки, готовая к показу: и заголовок, и подробность — с
/// заглавной (`gui::capitalized`). Одно место на оба списка вкладки, чтобы
/// «репозиторий» и «Не зафиксировано» не стояли рядом разной орфографией
/// (снимок владельца 31.10). Имена фактов при этом остаются строчными
/// константами: заглавная живёт только в показе.
fn shown_row(d: Option<Dot>, title: &str, detail: &str) -> (Option<Dot>, String, String) {
    (d, gui::capitalized(title), gui::capitalized(detail))
}

/// Слова по состоянию `Found` — не найден, настроен, записи нет, занято чужим
/// (имена через запятую, когда их несколько). Раздела в окне у них больше нет
/// вовсе (управление локальными агентами переехало в трей 29.10), и живут эти
/// слова здесь ровно по одной причине: их зовёт `setup_line` в `mod.rs`,
/// печатая в журнал отказ или нежданный итог щелчка галочки. Прежняя докстрока
/// ссылалась на раздел «Редакторы» во вкладке «Инструменты», которого нет (пункт 6
/// ревью целого).
pub(super) fn found_text(f: &editors::Found) -> String {
    match f {
        editors::Found::Missing => "не найден на этой машине".to_string(),
        editors::Found::Absent => "найден, серверы не настроены".to_string(),
        editors::Found::Ours => "настроен".to_string(),
        editors::Found::Foreign(names) => format!("запись {} занята чужой командой — не меняем", names.join(", ")),
    }
}

/// Слова по состоянию `Found` для половины «скиллы» (задача 5) — тот же
/// словарь, что у `found_text`, но своей формулировкой там, где смысл другой:
/// `Foreign` у скиллов — это каталог, который человек правил на месте или
/// положил сам, а не «запись, занятая чужой командой» (находка ревью 31.10,
/// `panel.rs:386`: прежняя фраза про запись и команду для скилла была бы
/// неправдой — там ни записи, ни команды нет, есть только каталог на диске).
///
/// Имена в `Foreign` — от `skills::foreign_label`, и несут объяснение не
/// поровну: короткое (просто имя) означает ровно одну причину — человек
/// правил поставленный нами скилл на месте, и ЕЙ, в отличие от записи MCP,
/// нигде больше взяться негде; длинное (имя и подсказка в скобках) уже несёт
/// своё объяснение целиком — отпечатка не было вовсе, причину одним словом
/// не назвать, `foreign_label` сама решила быть подробной.
///
/// Круговое ревью, круг 2, пункт 3 (поправка к кругу 1): для КОРОТКОЙ формы
/// словарь обязан называть причину сам — без неё человек в САМОМ ЧАСТОМ
/// случае («скилл: не удалось поставить — каталог 1c») не узнаёт вовсе,
/// почему. Для ДЛИННОЙ формы ничего не добавляем — она уже объяснила себя,
/// и вторая объяснялка сверху была бы дублированием (находка круга 1).
/// Различаем по признаку самой строки: у длинной формы в имени есть `(` —
/// других источников откуда скобка попала бы в простое имя скилла, нет
/// (`skills::valid_skill_name` их не пускает).
pub(super) fn skill_found_text(f: &editors::Found) -> String {
    match f {
        // `skills::install`/`remove` никогда не отдают `Missing` —
        // это исход про РЕДАКТОРА («агента на машине нет»), а у скилла
        // такого вопроса не бывает (докстрока `skills::kit_skill_names`:
        // комплект без каталога `skills/` — отказ словами, не `Missing`).
        // Ветка остаётся ради исчерпывающего разбора общего `editors::Found`
        // — он один на обе половины галочки, и подставной `_ =>` вместо
        // неё тихо проглотил бы будущий пятый вариант перечисления.
        editors::Found::Missing => "не найден на этой машине".to_string(),
        editors::Found::Absent => "не поставлен".to_string(),
        editors::Found::Ours => "поставлен".to_string(),
        editors::Found::Foreign(names) => {
            let parts: Vec<String> =
                names.iter().map(|n| if n.contains('(') { n.clone() } else { format!("{n} — правили на месте, не трогаем") }).collect();
            format!("каталог {}", parts.join(", "))
        }
    }
}

/// Предмет вкладки «Инструменты»: проект, база, публикация, расширение, дескриптор,
/// инструменты, `mcp-1c` в комплекте. По именам-константам `verify`, а не по
/// текстам — переименованный факт ломает сборку, а не тихо исчезает со вкладки.
///
/// `KIT` здесь с 31.10 (спека, повод 1): вкладка обещает именем сказать про
/// комплект, и доехал ли в нём `mcp-1c` — первое, что человек идёт туда
/// узнать. В зелёном виде он прежде на вкладку не попадал вовсе.
const PROJECT_SUBJECT: [&str; 6] = [
    crate::verify::PROJECT,
    crate::verify::BASE,
    crate::verify::PUBLICATION,
    crate::verify::EXTENSION,
    crate::verify::DESCRIPTOR,
    crate::verify::TOOLS,
];

/// Что из набора идёт на вкладку «Инструменты». Два правила, и первое нерушимо:
///
/// 1. **все факты с незелёным исходом** — плохие и занятые, независимо от
///    имени: поверхность не имеет права знать о проблемах меньше набора;
/// 2. сверх них — только факты по предмету самой вкладки (`PROJECT_SUBJECT`).
///
/// Платформа, Gitea, носитель, порты и прочее общее в зелёном виде на вкладку
/// не идут: их место в полном наборе после «Проверить». Решение владельца
/// 26.10.2026 на моё же сомнение из отчёта по задачам 7+8: девятнадцать
/// фактов под вкладкой «Инструменты» — хуже для человека, а четырнадцать зелёных
/// строк говорят, когда сказать нечего (STATUS 21–27).
///
/// Отбор живёт ЗДЕСЬ, а не в `fact_rows`: та обязана отдавать ровно то, что
/// ей передали — один набор, одни строки, без своего мнения.
pub fn project_facts(facts: &[Check]) -> Vec<Check> {
    facts.iter().filter(|c| c.outcome() != Outcome::Good || PROJECT_SUBJECT.contains(&c.what.as_str())).cloned().collect()
}

/// Из какого списка вкладка берёт факты: полный набор, пока он есть, иначе —
/// состояние комплекта (`Ui::kit_facts`, спека 31.10, повод 1).
///
/// Набора нет в двух случаях: MCP выключены и первый расчёт ещё не вернулся.
/// В оба вкладка всё равно обязана сказать про комплект, и это ровно то, что
/// она про него знает. Как только набор есть — говорит он: те же два факта о
/// комплекте уже внутри него, и два списка показали бы их дважды.
///
/// Роняет набор при выключении `sync_tray` — единственная воронка всех
/// переходов, что меняют почву под значком; `apply_facts` набор только
/// применяет. Эта неточность в прежней докстроке и была причиной пустой
/// вкладки: кит-проход завели там, где набор РАССЧИТЫВАЕТСЯ
/// (`facts::start_full_pass`), а не там, где он РОНЯЕТСЯ, и щелчок
/// переключателем при открытом окне оставлял вкладку ни с чем (круг
/// исправления 31.10, пункт 2).
pub fn tab_facts<'a>(facts: &'a [Check], kit_facts: &'a [Check]) -> &'a [Check] {
    if facts.is_empty() {
        kit_facts
    } else {
        facts
    }
}

fn fact_dot(c: &Check) -> Dot {
    match c.outcome() {
        Outcome::Bad => Dot::Down,
        Outcome::Busy => Dot::Busy,
        // `info` — сведение внутри `Good`: ни пройденный, ни проваленный.
        Outcome::Good if c.info => Dot::Off,
        Outcome::Good => Dot::Up,
    }
}

/// Вкладка «Инструменты», пока `refresh_project` не ответил. Состояние строго
/// временное — ответ приходит всегда, даже когда поток упал (`guarded`
/// отдаёт `Ev::Project` с причиной), — поэтому здесь говорим, что
/// происходит, а не читаем лекцию о том, где задаётся каталог. Прежний текст
/// («install раскладывает git») был вдвойне плох: он объяснял человеку
/// устройство нашей установки вместо того, чтобы назвать своё состояние.
const PROJECT_EMPTY: &str = "Читаю состояние проекта…";

/// Что сказать, когда вкладке «Инструменты» сказать нечего обоими списками
/// сразу. Чистая функция от двух признаков — вид её только печатает.
///
/// Молчание каждого списка по отдельности законно и объяснено у своего места
/// (набор ещё не считали; раскладка проекта не разобрана — об этом уже
/// говорит факт «проект»). Но вместе они дают ПУСТУЮ ВКЛАДКУ, и человек
/// читает её не как «я ещё ничего не назвал», а как «инструментов нет, и
/// включать нечего» — заказчик 31.10.2026 спросил ровно это. Поверхность не
/// имеет права молчать целиком: у вкладки всегда есть что сказать хотя бы о
/// себе самой.
fn nothing_to_show(facts_empty: bool, rows_empty: bool) -> Option<String> {
    (facts_empty && rows_empty).then(|| "Пока нечего показать: укажите базу на «Связи», затем нажмите «Проверить».".to_string())
}

/// Строки вкладки «Инструменты»: кружок, заголовок, подробность. Чистая — вид
/// только раскладывает её по слоям. Кружка нет (`None`) у подсказки: она
/// не факт о проекте, а объяснение, и рисуется мелким текстом.
/// Три карточки вместо семи полей, и ни одной, которой нечего сказать.
///
/// Было: текстовый отчёт `project_status` разбивался по строкам, и каждая
/// строка становилась карточкой с серой точкой — «ветка dev1»,
/// «репозиторий», «ветка рабочего места», «последний коммит»,
/// «неотправленных коммитов», «изменено», «ConfigDumpInfo.xml». Семь
/// одинаковых плашек, в которых «ветка» стояла дважды (куда смотрит HEAD и
/// какая задана в параметрах), а точки не значили ничего. Заказчик
/// 25.10.2026: «не очень понятно, что там пишется и для чего; возможно,
/// часть таких параметров надо одной карточкой».
///
/// Стало — по вопросам, на которые человек сюда и приходит:
/// 1. где мой проект (путь, ветка, репозиторий) — одной карточкой;
/// 2. есть ли что отправлять (и сколько) — точка говорит состояние, а не
///    украшает строку;
/// 3. что было отправлено последним — только если коммиты уже есть.
///
/// Остальное молчит, пока не станет важным: совпадающие ветки не
/// показываются двумя строками, а `ConfigDumpInfo.xml` упоминается, только
/// когда его нет.
pub fn project_rows(v: Option<&ProjectView>) -> Vec<(Option<Dot>, String, String)> {
    let Some(v) = v else { return vec![(None, PROJECT_EMPTY.into(), String::new())] };
    let Some(f) = v.facts.as_ref() else {
        // Неразобранная раскладка — дело набора, а не вкладки: факт «проект»
        // уже стоит выше, своими словами и СО СВОИМ советом. Карточка
        // повторяла его чужим заголовком (каталогом, с которым всё в
        // порядке), жёлтой точкой «подожди» там, где ждать нечего, и общим
        // советом «Параметры → Проект», который при пустом адресе среды
        // отправлял человека не на ту страницу (находка владельца 26.10).
        // Молчим: сказать сверх набора нечего.
        //
        // Занятость — единственное исключение: мьютекс проекта держит наша
        // же выгрузка, и в наборе этого нет.
        return if v.busy { vec![shown_row(Some(Dot::Busy), "Проект занят", &v.why)] } else { Vec::new() };
    };
    // 1. Репозиторий — куда поедет отправка. Каталог и ветку здесь не
    //    повторяем: их уже сказал факт «проект» из набора, и две карточки
    //    подряд с одним и тем же текстом человек читает как ошибку.
    //
    //    Пусто — отправлять некуда: локальный репозиторий, у которого человек
    //    не заводил origin. Карточка с пустым адресом говорила бы о
    //    репозитории, которого нет; молчим, как молчим и о нераспознанной
    //    раскладке выше.
    let mut rows = Vec::new();
    if !f.repo.is_empty() {
        rows.push((Some(Dot::Up), "репозиторий".into(), f.repo.clone()));
    }
    // Ветка в параметрах разошлась с тем, где человек стоит, — это и есть
    // единственный повод показать обе: отправка пойдёт не туда, куда он
    // смотрит. Пустая `want_branch` — локальный режим: ветку там выбирает
    // человек, расходиться ей не с чем.
    if !f.want_branch.is_empty() && f.branch != f.want_branch {
        rows.push((
            Some(Dot::Warn),
            "Ветка разошлась с параметрами".into(),
            format!("в параметрах {}, отправка пойдёт туда", f.want_branch),
        ));
    }
    // 2. Есть ли что отправлять. Точка здесь — настоящее состояние.
    rows.push(unsent_row(f));
    // 3. Последняя отправка — только когда есть что показывать.
    if !f.last.is_empty() {
        rows.push((Some(Dot::Off), "Последний коммит".into(), f.last.clone()));
    }
    // Индекс выгрузки — только когда его нет: это предупреждение о том, что
    // следующая загрузка пойдёт долго, а не факт на каждый день.
    if !f.index {
        rows.push((Some(Dot::Warn), "Первая загрузка будет полной".into(), "в выгрузке нет ConfigDumpInfo.xml".into()));
    }
    rows.into_iter().map(|(d, title, detail)| shown_row(d, &title, &detail)).collect()
}

/// Карточка «есть ли что отправлять». Числа со склонением (`common::word`):
/// «1 коммит», «3 коммита», «5 коммитов» — иначе отчёт выглядит машинным.
///
/// Заголовок — про отправку только там, где она есть. В локальном режиме
/// («обмена нет»: агент правит те самые файлы, которые читает загрузка)
/// «Всё отправлено» было бы ложью про механизм, которого нет, а работа всё
/// равно доходит до базы — там речь только о том, зафиксирована ли она.
fn unsent_row(f: &crate::project::Facts) -> (Option<Dot>, String, String) {
    let (good, bad) = if f.exchange {
        ("Всё отправлено", "Не отправлено")
    } else {
        ("Всё зафиксировано", "Не зафиксировано")
    };
    if !f.unsent() {
        return (Some(Dot::Up), good.into(), String::new());
    }
    let mut parts = Vec::new();
    match f.ahead.as_str() {
        // Отправлять некуда — неотправленного не бывает: остаётся только то,
        // что не закоммичено.
        "" => {}
        // Ветки на сервере ещё нет: считать нечего, и «все коммиты» честнее
        // любого числа.
        "все" => parts.push("ветка ещё не отправлялась".to_string()),
        n => {
            if let Ok(k) = n.parse::<u64>() {
                if k > 0 {
                    parts.push(common::word::count(k, "коммит", "коммита", "коммитов"));
                }
            }
        }
    }
    if f.changed > 0 {
        parts.push(format!("{} не закоммичено", common::word::count(f.changed as u64, "файл", "файла", "файлов")));
    }
    (Some(Dot::Warn), bad.into(), parts.join(", "))
}

/// Строка журнала о пароле, который не открылся (задача 4; замысел — «Анти-цели», «человек остался без доступа и не понял почему»): причина — зашифрован другим пользователем или на другой машине, и что делать — ввести заново, с названием каждого такого поля словами человека (`cfg::secret_field_name` — одна формулировка с `gui::save::field_label`, ревью задачи 7, Important 4) и той же причиной, что у командной строки (`cfg::undecryptable_reason`). `None` — список пуст, расшифровка прошла у обоих полей.
///
/// Строку показывает `mod.rs` (`adopt_cfg`) один раз на загрузку параметров, а не на каждый показ окна: оно перечитывает файл при каждом открытии (`window::reread_and_recheck`), и без отдельной метки «уже сказано» тот же нерасшифрованный пароль сыпался бы в журнал на каждый клик по значку трея.
pub fn undecryptable_line(bad: &[cfg::Undecryptable]) -> Option<Line> {
    if bad.is_empty() {
        return None;
    }
    // Карточка называется по имени (задача 10), и предложение на карточку —
    // одно: до неё строка перечисляла одни поля, и человек с двумя
    // карточками читал «введите пароль рабочего места и пароль рабочего
    // места заново» — два раза об одном и том же, ни слова о том, у кого
    // именно беда. Находки приходят подряд по соединениям (их и собирают
    // обходом списка), поэтому хватает склейки соседних, без сортировки.
    let mut by_card: Vec<(&str, Vec<&str>)> = Vec::new();
    for u in bad {
        let field = cfg::secret_field_name(&u.field);
        match by_card.last_mut() {
            Some((card, fields)) if *card == u.connection => fields.push(field),
            _ => by_card.push((&u.connection, vec![field])),
        }
    }
    let text = by_card
        .iter()
        .map(|(card, fields)| format!("Карточка «{card}»: {} — введите {} заново.", cfg::undecryptable_reason(false), fields.join(" и ")))
        .collect::<Vec<_>>()
        .join(" ");
    Some(Line { kind: Kind::Warn, text })
}

/// Поля карточки соединения, которые реально показывает ТОПОЛОГИЯ — не режим
/// машины (спека, «Что показывает карточка соединения»). Ветвление по двум
/// осям: где база (`base_here`) и локально ли соединение (`mode == "local"`).
/// Роль (`Connection::role`) в этот список не входит: она решает, показывать
/// код для той стороны или поле для кода, а этих блоков в карточке пока нет
/// вовсе — они придут с протоколом (поправка 3.11 брифа задачи 3).
///
/// База на той стороне — своих полей базы здесь нет вовсе: ни пути, ни
/// пользователя с паролем, ни адреса публикации (он тоже свойство конца с
/// базой). Остаётся только папка (`project`) — она есть у каждого соединения
/// на обеих сторонах.
///
/// База здесь — состав решает локальность: на одной машине адресу среды,
/// паролю и имени рабочего места взяться неоткуда, им нужна удалённая
/// сторона, которой в локальном случае нет вовсе. Всё, что не `"local"`, —
/// режим `tunnel`.
///
/// Отрисовка рядов и сравнение «изменилось ли» (`fields_differ`) ходят только
/// через этот список.
pub fn shown_fields(c: &Connection) -> &'static [&'static str] {
    if !c.base_here {
        return &["project"];
    }
    match (c.mode == "local", c.publication == "webserver") {
        (true, false) => &["base_path", "db_user", "db_password", "project"],
        (true, true) => &["base_path", "db_user", "db_password", "project", "base_url"],
        (false, false) => &["server", "workstation", "password", "base_path", "db_user", "db_password", "project"],
        (false, true) => &["server", "workstation", "password", "base_path", "db_user", "db_password", "project", "base_url"],
    }
}

/// Слова вместо пустоты у карточки, чья база на той стороне — тот же приём,
/// что у `nothing_to_show`: поверхность без полей базы обязана сказать об
/// этом словами, а не молчать пустыми строками (спека, «Что показывает
/// карточка соединения»). `None` — база здесь, подсказка не нужна.
pub fn base_fields_note(c: &Connection) -> Option<&'static str> {
    (!c.base_here).then_some("Поля базы приходят с той стороны")
}

/// Строка пустой «Связи» над двумя ОТВЕТАМИ (`link::onboarding_answers`).
/// Решение владельца 9.11 на живом прогоне: вопрос «Кто кому подключается?»
/// убран совсем («так не пишут») — остаётся только факт, а отвечать на него
/// человек решает, читая сами ответы, не вопрос над ними.
pub const ONBOARDING_ASK: &str = "Соединений пока нет.";

/// Элемент тела вкладки «Связь», в порядке показа — чистый итог, без
/// виджетов. Отрисовка по нему подставляет строки и своего не решает
/// ничего: иначе порядок списка, место раскрытой карточки и наличие
/// «+ Добавить» проверялись бы только глазами на живом окне.
pub enum Body {
    /// Пустая «Связь»: один вопрос и два ответа на него (задача 11).
    Ask(&'static str),
    /// Подпись ответа и `role`, с которым он заводит первую карточку.
    Answer(&'static str, &'static str),
    /// Подпись группы списка.
    Caption(&'static str),
    /// Строка соединения; `true` — под ней раскрыта карточка.
    Row(link::Row, bool),
    /// «+ Добавить» — у СПИСКА, а не в подвале (указатель 5 ревью): подвал
    /// держит ровно одно главное действие над открытой карточкой, а
    /// добавление относится к списку целиком.
    Add,
}

/// Тело вкладки «Связь» целиком: онбординг на пустом списке, иначе список
/// соединений (`link::list`, её порядок и группировку) с карточкой у
/// выбранной строки и «+ Добавить» в конце.
///
/// **Отметка «текущее» снимается, когда соединение одно** (спека, «Одно окно
/// на двоих»: отметка рисуется тогда и только тогда, когда выбор
/// действительно есть; «у бухгалтера соединение одно — слово „текущее“ он не
/// встретит никогда»). `link::row` ставит признак у текущего всегда, и это
/// правильно — он про модель; гашение отметки — про экран, и живёт здесь.
///
/// **Карточка раскрывается у ОДНОЙ строки**, даже если в файле, правленном
/// руками, два соединения с одним именем (Review Focus плана): список
/// показывает оба, а карточка — у первого. Иначе один и тот же набор полей
/// нарисовался бы дважды и человек правил бы наугад.
pub fn link_body(cfg: &cfg::Cfg, link: &dyn Fn(&str) -> Option<State>, selected: &str) -> Vec<Body> {
    if link::onboarding_shown(cfg) {
        let mut out = vec![Body::Ask(ONBOARDING_ASK)];
        out.extend(link::onboarding_answers().into_iter().map(|(label, role)| Body::Answer(label, role)));
        return out;
    }
    let open = resolve_selected(cfg, selected).name.clone();
    let alone = cfg.connections.len() < 2;
    let mut opened = false;
    let mut out: Vec<Body> = link::list(cfg, link)
        .into_iter()
        .map(|e| match e {
            link::Entry::Caption(c) => Body::Caption(c),
            link::Entry::Row(mut r) => {
                let here = !opened && r.name == open;
                opened |= here;
                if alone {
                    r.current = false;
                }
                Body::Row(r, here)
            }
        })
        .collect();
    out.push(Body::Add);
    out
}

