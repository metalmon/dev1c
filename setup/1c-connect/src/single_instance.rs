//! У рабочего места один владелец (спека): окно (`--tray`/без аргументов),
//! `connect` и `serve` держат порты, замок проекта (`project::hold`, по папке
//! с задачи 7 плана «Модель соединений») и, с недавнего, свою публикацию
//! базы — второй долгоживущий процесс не должен отнимать их у первого.
//! Разовые команды (`status`, `export`, `import`, `check`, `install`,
//! `example` и прочие) этот замок не трогают: они и так serialised через
//! `project::hold`, а задержать их здесь означало бы поломать обычную работу
//! человека.
//!
//! **Единица замка — одна копия на УЧЁТНУЮ ЗАПИСЬ в пределах машины.** Ни
//! комплект, ни сеанс в неё не входят: терминальный сервер, где у одной
//! учётной записи несколько сеансов, — обычный случай, и два комплекта у
//! одного человека — тоже. Поведение одно на всех осях; разной бывает только
//! опора под ним, и она живёт в одном названном месте — в адресе
//! управляющей двери (`door::pipe_path` на Windows, `door::sock_path` на
//! Linux). Выше этого адреса про платформу не знает ни замок, ни его тесты.
//!
//! **Замок — это и есть управляющая дверь (`door`), второго механизма нет**
//! (задача 14). Взять замок — открыть дверь: на Windows
//! `first_pipe_instance(true)` ручается, что имени не держит никто, а
//! именованный канал живёт в ОБЩЕМ пространстве имён машины и сеансом не
//! ограничен; на Linux то же делает `bind` сокета в каталоге времени
//! выполнения учётной записи, с пробой живого перед тем, как снять остаток
//! прошлого запуска. Спросить, жив ли держатель, — постучать (`is_held`):
//! ответила дверь, значит за ней кто-то есть. Это строже прежнего, где
//! открывшийся дескриптор объекта доказывал лишь существование объекта.
//!
//! Переживаемость краха остаётся главным свойством: имя канала система
//! снимает вместе с процессом, даже убитым (`taskkill /F`, обрыв питания), а
//! осиротевший файл сокета `door::open_at` отличает от живого пробой и
//! снимает сам.
//!
//! **Чего здесь больше нет и почему.** Замок держал именованный МЬЮТЕКС
//! (`CreateMutexW` без префикса), а объект ядра без префикса виден только в
//! сеансе создателя — то есть единицей он считал «сеанс × учётку». На этом
//! сгорел день 15.11: вход по ssh под той же учётной записью, под которой на
//! рабочем столе жило окно, завёл отдельный сеанс, получил свой мьютекс,
//! поднял вторую копию — показать окно она не смогла, но осталась жить и
//! заняла место, после чего настоящее окно не открывалось вовсе и молча.
//! `Global\` мьютексу не помог бы: его создание требует привилегии
//! `SeCreateGlobalPrivilege`, которой у обычного пользователя терминального
//! сервера нет. Советный `flock` на каталоге состояния тоже ушёл из замка —
//! он считал единицей комплект; признаком «этот процесс обслуживает данный
//! комплект» (`acquire_serving`) он остался, и это другой вопрос.
//!
//! Вторая копия не умирает молча. На Windows она ПРОСИТ первую показать своё
//! окно (`request_show` → `serve_show_requests`, именованное событие ядра) и
//! уходит; просьбу некому принять (голова `serve`, `connect`, сборка без
//! окна, первая копия в ДРУГОМ сеансе) — печатает причину (`TAKEN`) и
//! выходит с ошибкой. На Linux — только вторая половина: просить там нечем,
//! сразу сообщение и отказ.
//!
//! **Просьба показать окно — не управляющая дверь, и путать их нельзя.**
//! Событие ядра без атрибутов безопасности видно только внутри сеанса
//! создателя, и для разговора между сеансами одной учётной записи не годится
//! вовсе. Поэтому замком оно и не стало: отказ второй копии из чужого сеанса
//! выходит словами, а не молчаливым подъёмом. Разговор команд с живым
//! экземпляром идёт дверью (`door`, задача 5 плана «Сопряжение переезжает в
//! бек»); эта просьба осталась тем, чем была, — одним сигналом «покажи окно»
//! от второй копии к первой, и только в пределах одного сеанса.

use common::kit::Kit;

/// Без символов, опасных для имени объекта ядра или файла (пробелы,
/// кириллица, `\`/`/`) — они гасятся в `_`. Чистят ею ПУТИ, и только их:
/// ключ признака обслуживания (`serving_mutex_name`) и ключ файлового замка
/// проекта (`file_lock`). Из ключа ЗАМКА она ушла задачей 14 — гашение
/// теряет различия, и две разные учётные записи могли дать один ключ (см.
/// `account`); у пути потери безобиднее, потому что путь к тому же моменту
/// уже назван нами самими.
fn clean(s: &str) -> String {
    s.chars().map(|c| if c.is_ascii_alphanumeric() || c == '-' { c } else { '_' }).collect()
}

/// Ключ замка — учётная запись ТЕМ, что различает её без потерь: SID на
/// Windows, uid на Linux. Это и есть «учётная запись» из спеки, а не её
/// приблизительный пересказ.
///
/// **Чем был плох пересказ.** Прежде ключ строился как `clean(USERNAME)`:
/// всё, кроме латиницы и цифр, гасилось в `_` ради имени мьютекса. Значит
/// «Пользователь 1» и «Пользователь_1» давали ОДИН ключ — одна учётная
/// запись запирала другую, а человек читал «уже запущен» и шёл искать свой
/// процесс, которого нет. SID и uid терять нечего: у SID в записи только
/// латиница, цифры и дефис, у uid — цифры, и оба годятся и в имя канала, и в
/// имя файла как есть.
///
/// Рабочее место в ключе не участвует с задачи 6 (имя из toml человек меняет
/// на ходу — замок на него смотреть не вправе), сеанс — с задачи 14: одна
/// копия на учётную запись в пределах МАШИНЫ, сколько бы сеансов человек ни
/// открыл и сколько бы баз ни обслуживал внутри (контракт подключения:
/// несколько баз живут карточками в одном приложении, а не копиями
/// программы).
///
/// Не узнали — это отказ, а не запасной ключ: замок с общим «не знаю» в
/// ключе запирал бы разные учётные записи друг о друга, то есть делал бы
/// ровно ту беду, против которой заведён.
///
/// **Спрашивается тем же, чем продукт уже отвечает на «чей это процесс»** —
/// `holder::current_owner` (SID на Windows, десятичный uid из `/proc/<pid>`
/// на Linux). Своего способа узнать себя здесь нет и быть не должно: им
/// сверяют держателя порта (`publication`), им же дверь проверяет
/// собеседника (`door::server_is_ours`), и третий ответ на тот же вопрос
/// разошёлся бы с первыми двумя молча — ровно то, из-за чего эта задача и
/// завелась.
pub fn account() -> std::io::Result<String> {
    crate::holder::current_owner()
        .ok_or_else(|| std::io::Error::other("не удалось узнать вашу учётную запись — замок и управляющая дверь без неё не заводятся"))
}

#[cfg(windows)]
pub struct Guard(windows_sys::Win32::Foundation::HANDLE);

#[cfg(windows)]
impl Drop for Guard {
    fn drop(&mut self) {
        // SAFETY: `self.0` — дескриптор, полученный этим же `Guard` из
        // `CreateMutexW` и ещё не закрытый (второй раз `Drop` не зовут).
        unsafe { windows_sys::Win32::Foundation::CloseHandle(self.0) };
    }
}

// Дескриптор мьютекса — просто ссылка на объект ядра, переносить его между
// потоками безопасно (как и `Job` в job.rs).
#[cfg(windows)]
unsafe impl Send for Guard {}
#[cfg(windows)]
unsafe impl Sync for Guard {}

/// Общая часть приёма замка на Windows: `CreateMutexW` по готовому имени.
/// Вынесена, чтобы её звали оба замка, различающиеся только тем, как
/// построено имя — `acquire_serving` (учётная запись и путь комплекта) и
/// `project::file_lock` (ключ — сам путь, через `pub(crate) fn file_lock`
/// ниже). Замок рабочего места сюда больше не ходит: он держится дверью
/// (задача 14).
#[cfg(windows)]
fn acquire_mutex(name: &str) -> std::io::Result<Option<Guard>> {
    use std::ffi::OsStr;
    use std::os::windows::ffi::OsStrExt;
    use windows_sys::Win32::Foundation::{CloseHandle, GetLastError, ERROR_ALREADY_EXISTS};
    use windows_sys::Win32::System::Threading::CreateMutexW;
    let wide: Vec<u16> = OsStr::new(name).encode_wide().chain(std::iter::once(0)).collect();
    // SAFETY: обычный вызов kernel32 с нуль-терминированной строкой, живущей
    // на стеке этого вызова; без атрибутов безопасности — именованный объект
    // по умолчанию виден только в сессии вызывающего, что уже отделяет
    // разных пользователей друг от друга.
    let h = unsafe { CreateMutexW(std::ptr::null(), 1, wide.as_ptr()) };
    if h.is_null() {
        // Та же причина, что и у файлового замка на Linux ниже (`lock_error`):
        // голый `Permission denied (os error N)` без единого слова о том, что
        // вообще делалось, ничего человеку не говорит.
        let e = std::io::Error::last_os_error();
        return Err(std::io::Error::new(e.kind(), format!("не удалось взять замок (системный мьютекс {name}): {e}")));
    }
    // `GetLastError` — первым же следующим вызовом, до любого другого Win32
    // API: иначе он рассказал бы не про `CreateMutexW`.
    let already = unsafe { GetLastError() } == ERROR_ALREADY_EXISTS;
    if already {
        unsafe { CloseHandle(h) };
        return Ok(None);
    }
    Ok(Some(Guard(h)))
}

/// Имя мьютекса «этот процесс обслуживает данный комплект» — отдельный
/// объект от замка рабочего места (тот держится дверью, см. `acquire`), и
/// нарочно: ключ — учётная запись и ПУТЬ комплекта (`lock_target`), рабочего
/// места в нём нет вовсе.
///
/// **Учётную запись сюда даёт тот же `account`, что и замку** (круг правок
/// 1 задачи 14). Прежде здесь стоял `clean(USERNAME)` — то есть на вопрос
/// «чья это копия» в одной задаче отвечали ДВА разных способа, точный у
/// двери и приблизительный здесь, и расхождение между ними не показалось бы
/// никому до первой учётной записи, чьё имя чистка теряет. Пути это не
/// касается: он к этому моменту назван нами самими, и `clean` на нём — про
/// имя объекта ядра, а не про учётную запись.
///
/// Круг исправления после ревью: сторож по коннектору (`orphan::guard_owner`)
/// сперва смотрел в тот же замок, что держит окно, — а ключ того замка нёс
/// тогда имя рабочего места. Оно не заморожено: «Сохранить»
/// меняет его у открытого окна без перезапуска (спека, `gui/save.rs`,
/// `moved_lines` — ветка проекта, порты и прочее едут за новым именем).
/// Сторож спрашивал замок уже под новым именем, видел «не держат» и уводил
/// мост насмерть при живом коннекторе — ровно та беда, против которой
/// заведена спячка (`bridge::EpochEnd::Dormant`), только с другой стороны.
/// Замораживать имя на старте моста не лечит: мост, запущенный ПОСЛЕ
/// переименования, смотрел бы на замок, которого никто не держит, увидел
/// `Owner::NotYet` и остался бы жить вечно.
///
/// Значит привязка не должна зависеть от того, что меняется на ходу. Путь
/// комплекта (`lock_target`) не меняется без перезапуска самого коннектора
/// — вот и весь ключ.
#[cfg(windows)]
fn serving_mutex_name(account: &str, kit: &Kit) -> String {
    format!("1c-connect-serving-{account}-{}", clean(&lock_target(kit).display().to_string()))
}

/// Закрепить «этот процесс обслуживает данный комплект» — объектом ядра,
/// держать до выхода (ранний `drop` снимает признак раньше срока). Зовётся
/// РЯДОМ с `acquire` (`main.rs::connect`/`serve`, `gui::launch`), не вместо
/// него — у двух объектов разный смысл: `acquire` — «этот коннектор
/// единственный у этой учётной записи на машине», этот — «комплект, который
/// сторож моста обязан увидеть живым».
///
/// `None` — тот же комплект уже обслуживает другой процесс этого
/// пользователя (включая случай, не защищённый замком рабочего места: тот
/// же комплект поднят дважды под разными именами, потому что toml
/// переименовали руками между запусками, не закрыв первый) — редкий и
/// предсуществующий случай, который эта правка не обязана новым отказом
/// запрещать; вызывающий просто не держит признак, и сторож у НЕГО не
/// заведётся на пользу (увидит `Owner::NotYet` и будет жить заглушкой).
#[cfg(windows)]
pub fn acquire_serving(kit: &Kit) -> std::io::Result<Option<Guard>> {
    acquire_mutex(&serving_mutex_name(&account()?, kit))
}

/// Видит ли сторож коннектора (`orphan::guard_owner`), что комплект сейчас
/// кем-то обслуживается — без попытки занять признак: `OpenMutexW` по тому
/// же имени, что строит `serving_mutex_name`. Дескриптор открылся — объект
/// жив и держит его чей-то процесс (закрываем тотчас, нам нужен только
/// факт), `ERROR_FILE_NOT_FOUND` — признака нет. Своего захвата здесь нет
/// вовсе, поэтому два читателя не заверяют живость друг друга, застав один
/// тик другого (находка ревью задачи 2).
#[cfg(windows)]
pub fn is_serving(kit: &Kit) -> std::io::Result<bool> {
    use std::ffi::OsStr;
    use std::os::windows::ffi::OsStrExt;
    use windows_sys::Win32::Foundation::{CloseHandle, ERROR_FILE_NOT_FOUND};
    use windows_sys::Win32::System::Threading::{OpenMutexW, SYNCHRONIZATION_SYNCHRONIZE};
    let name = serving_mutex_name(&account()?, kit);
    let wide: Vec<u16> = OsStr::new(&name).encode_wide().chain(std::iter::once(0)).collect();
    // SAFETY: обычный вызов kernel32 с нуль-терминированной строкой, живущей на стеке этого вызова; `OpenMutexW` не создаёт объект и не берёт владение им — только открывает дескриптор на уже существующий, если такой есть.
    let h = unsafe { OpenMutexW(SYNCHRONIZATION_SYNCHRONIZE, 0, wide.as_ptr()) };
    if h.is_null() {
        let e = std::io::Error::last_os_error();
        if e.raw_os_error() == Some(ERROR_FILE_NOT_FOUND as i32) {
            return Ok(false);
        }
        return Err(std::io::Error::new(e.kind(), format!("не удалось проверить признак обслуживания (мьютекс {name}): {e}")));
    }
    // SAFETY: `h` — дескриптор, который только что отдал `OpenMutexW`.
    unsafe { CloseHandle(h) };
    Ok(true)
}

/// Замок проекта (`project::file_lock`) на Windows: тот же приём, что у
/// замка рабочего места — именованный мьютекс, живущий, пока жив процесс,
/// независимо от того, как он кончился. Ключ строится из пути, а не из
/// пользователя и рабочего места: файл замка и так свой на каждое рабочее
/// место (`<state>/project.lock`), второй ключ не добавил бы ничего, а
/// собственный префикс (`1c-connect-file-`, в отличие от
/// `1c-connect-instance-` у замка рабочего места) не даёт случайно столкнуться
/// именам из двух разных целей.
/// ponytail: ключ — путь, прогнанный через `clean`, без канонизации; два
/// разных пути, отличающихся только заменяемыми символами, теоретически
/// могли бы совпасть. Другого пути к файлу замка, кроме как из
/// `set_lock_target`, у программы нет, так что потолок не достигается.
#[cfg(windows)]
pub(crate) fn file_lock(path: &std::path::Path) -> std::io::Result<Option<Guard>> {
    acquire_mutex(&format!("1c-connect-file-{}", clean(&path.display().to_string())))
}

/// Замок живёт, пока жив дескриптор: файл здесь держат, а не читают —
/// `flock` снимается закрытием. Поэтому поле и не читается никем.
#[cfg(not(windows))]
pub struct Guard(#[allow(dead_code)] std::fs::File);

/// Оборачивает отказ открыть замок в читаемую причину: по какому пути, и
/// голый текст системной ошибки в хвосте — для диагностики, не для первого
/// взгляда. Общая для обоих вызовов `open` ниже: `acquire_serving` открывает
/// существующий каталог состояния только на чтение (прав на запись там и не
/// нужно, отказ обычно значит, что `ops_host::ensure_state` не создал сам
/// каталог), а `file_lock` создаёт свой файл и пишет в него.
#[cfg(not(windows))]
fn lock_error(path: &std::path::Path, e: std::io::Error) -> std::io::Error {
    std::io::Error::new(e.kind(), format!("не удалось взять замок: {} — файл не открылся: {e}", path.display()))
}

/// Общая часть приёма замка на Linux: советный `flock` на уже открытом
/// дескрипторе. Вынесена, чтобы её звали оба замка — `acquire_serving`
/// (открывает только на чтение то, что не пишет сам) и `project::file_lock`
/// (создаёт свой файл, если его ещё нет, — см. ниже).
#[cfg(not(windows))]
fn acquire_flock(file: std::fs::File) -> std::io::Result<Option<Guard>> {
    use std::os::unix::io::AsRawFd;
    // SAFETY: обычный вызов libc на дескрипторе только что открытого файла;
    // LOCK_NB не блокирует поток — занято, значит просто отказ, а не ожидание.
    let r = unsafe { libc::flock(file.as_raw_fd(), libc::LOCK_EX | libc::LOCK_NB) };
    if r == 0 {
        return Ok(Some(Guard(file)));
    }
    let err = std::io::Error::last_os_error();
    if err.raw_os_error() == Some(libc::EWOULDBLOCK) {
        Ok(None)
    } else {
        Err(err)
    }
}

/// Закрепить «этот процесс обслуживает данный комплект» на Linux: советный
/// `flock` на том, что мы никогда не пишем — каталоге состояния комплекта
/// (`lock_target`). Занимается открытым на ЧТЕНИЕ дескриптором живого
/// процесса и снимается ядром, когда дескриптор закрывается — обычным уходом
/// `File` из области видимости (`Drop` ничего не пишет сам, добавлять его
/// незачем). Открытие на чтение, а не на запись, — единственное, что даёт
/// признаку работать даже на общем комплекте, смонтированном только для
/// чтения: `flock` занимается самим дескриптором, а не правом писать через
/// него. Каталог, а не файл параметров: toml человеку прямо предлагают
/// править, а редактор, сохраняющий через временный файл и `rename`, меняет
/// inode — отметка осталась бы висеть на отвязанном inode. Каталог
/// открывается тем же `OpenOptions`, что файл: `flock` всё равно, что за
/// дескриптором.
///
/// `user` здесь не участвует и участвовать не может: каталог состояния уже
/// свой у каждой учётной записи (`ops_host::state_dir` живёт в её
/// `HOME`/`XDG_DATA_HOME`), и вписать учётку второй раз — в путь, который её
/// и так несёт, — значило бы завести вторую меру на тот же вопрос. На
/// Windows мьютексу путь ничего не говорит, и там учётка в ключе названа
/// прямо (`serving_mutex_name`). Это разница примитивов, а не поведения:
/// вопрос «тот же ли это комплект у той же учётной записи» на обеих осях
/// один.
#[cfg(not(windows))]
pub fn acquire_serving(kit: &Kit) -> std::io::Result<Option<Guard>> {
    let lock_on = lock_target(kit);
    let file = std::fs::OpenOptions::new().read(true).open(&lock_on).map_err(|e| lock_error(&lock_on, e))?;
    acquire_flock(file)
}

/// Держит ли кто-то признак обслуживания БЕЗ попытки занять его: `/proc/locks` по устройству и inode пути — тем же приёмом, что `holder.rs` берёт держателя порта в образе среды, где нет ни `ss`, ни `netstat`. В отличие от `acquire_serving` здесь не берётся даже совместный `flock` на основном пути — чтение `/proc/locks` не трогает отметку вовсе, и два читателя (`allow::watch` и прямой `allow::read`, два процесса подкоманды `mcp`) не видят тика друг друга как «владелец жив» (находка ревью задачи 2: раньше проверка сама звала захват, и доля секунды, что один проверяющий держал `flock`, была для соседнего проверяющего «занято — значит жив»).
///
/// Содержимое `/proc/locks` — параметром: `None` значит
/// «прочитать не удалось». Шов нужен затем, что совпадение по номеру inode
/// проверяется тестом детерминированно, а дождаться настоящего
/// переиспользования номера от файловой системы нельзя (за 200 попыток ext4
/// его не отдала ни разу).
///
/// **Совпадение в `/proc/locks` — ещё не владение.** `flock` на УДАЛЁННОМ
/// каталоге живёт до закрытия дескриптора и остаётся в списке со своим
/// `(dev, ino)`, а номер inode ядро вправе отдать новому каталогу. Поэтому
/// положительный ответ списка подтверждается пробой самого пути; отказ
/// принимается как есть — он ничего не стоит и никого не отмечает.
#[cfg(not(windows))]
fn held_with(lock_on: &std::path::Path, locks: Option<&str>) -> std::io::Result<bool> {
    use std::os::unix::fs::MetadataExt;
    let meta = std::fs::metadata(lock_on).map_err(|e| lock_error(lock_on, e))?;
    if let Some(locks) = locks {
        if !parse_proc_locks(locks, meta.dev(), meta.ino()) {
            return Ok(false);
        }
    }
    // ponytail: разделяемый `flock` не конфликтует с другим читателем вроде нас самих, но конфликтует с `LOCK_EX` владельца. Потолок — своё окно между этой попыткой и самым стартом владельца (до его собственного `flock`), в которое проверка отдаст «свободно» при уже бегущем, но не успевшем взять замок процессе; закрыть его нечем, и `/proc/locks` этого тоже не закрывал.
    let file = std::fs::OpenOptions::new().read(true).open(lock_on).map_err(|e| lock_error(lock_on, e))?;
    use std::os::unix::io::AsRawFd;
    let fd = file.as_raw_fd();
    // SAFETY: `fd` — дескриптор только что открытого файла; `LOCK_NB` не блокирует поток.
    let r = unsafe { libc::flock(fd, libc::LOCK_SH | libc::LOCK_NB) };
    if r == 0 {
        // SAFETY: тот же дескриптор — снимаем свою же пробную отметку.
        unsafe { libc::flock(fd, libc::LOCK_UN) };
        Ok(false)
    } else {
        let err = std::io::Error::last_os_error();
        if err.raw_os_error() == Some(libc::EWOULDBLOCK) {
            Ok(true)
        } else {
            Err(err)
        }
    }
}

/// Видит ли сторож коннектора (`orphan::guard_owner`), что комплект сейчас
/// кем-то обслуживается — тот же вопрос и тот же ответ, что на Windows,
/// только спрошенный у `flock`, который держит `acquire_serving`. `user` не
/// участвует по той же причине, что и там: учётную запись несёт сам путь.
#[cfg(not(windows))]
pub fn is_serving(kit: &Kit) -> std::io::Result<bool> {
    held_with(&lock_target(kit), std::fs::read_to_string("/proc/locks").ok().as_deref())
}

/// Строка `/proc/locks` вида `1: FLOCK ADVISORY WRITE 2206 08:01:7092817 0 EOF` — `true`, если устройство и inode совпадают с тем, что держит `acquire_serving` (тот берёт только `LOCK_EX`, значит режим в строке всегда `WRITE`): `major:minor` ядро печатает раздельно, `libc::makedev` складывает их в то же число, которым `MetadataExt::dev` называет устройство — собирать формулу самим незачем.
#[cfg(not(windows))]
pub fn parse_proc_locks(out: &str, dev: u64, ino: u64) -> bool {
    out.lines().any(|l| {
        let f: Vec<&str> = l.split_whitespace().collect();
        if f.len() < 6 || f[1] != "FLOCK" || f[3] != "WRITE" {
            return false;
        }
        let mut id = f[5].split(':');
        let (Some(maj), Some(min), Some(inode)) = (id.next(), id.next(), id.next()) else { return false };
        // `major`/`minor` — ШЕСТНАДЦАТЕРИЧНЫЕ: ядро печатает их как
        // `%02x:%02x` (`lock_get_status`), и десятичное чтение молча давало
        // чужое устройство на любом minor от 0x0a (а на `3f` не давало
        // ничего). Inode в той же строке — десятичный (`%lu`).
        let (Ok(maj), Ok(min), Ok(inode)) = (u32::from_str_radix(maj, 16), u32::from_str_radix(min, 16), inode.parse::<u64>()) else {
            return false;
        };
        libc::makedev(maj, min) as u64 == dev && inode == ino
    })
}

/// Замок проекта (`project::file_lock`) на Linux: `flock` на файле
/// `<state>/project.lock` — своём, не на каталоге состояния, который уже
/// держит признак обслуживания (занять его второй раз значило бы запереть
/// само окно). В отличие от `acquire_serving` файл создаём, если его ещё нет:
/// каталог состояния гарантирован `ops_host::ensure_state`, а этот файл —
/// нет, его первым создаёт первый же процесс, который взял замок.
#[cfg(not(windows))]
pub(crate) fn file_lock(path: &std::path::Path) -> std::io::Result<Option<Guard>> {
    let file =
        std::fs::OpenOptions::new().create(true).truncate(false).read(true).write(true).open(path).map_err(|e| lock_error(path, e))?;
    acquire_flock(file)
}

/// Имя события «покажи окно» — единственное место, где оно строится (тот же довод, что у `door::door_name`: вторая формулировка имени смотрела бы не на тот объект ядра). Ключ тот же, что у замка: просят ровно ту копию, которая этот замок и держит.
#[cfg(windows)]
fn show_event_name(key: &str) -> String {
    format!("1c-connect-show-{key}")
}

/// Нуль-терминированная широкая строка — её хочет каждый именованный объект ядра здесь. `pub(crate)`: того же требуют права управляющей двери (`door::Rights`, SDDL строкой), а второй такой же перевод рядом был бы ровно «две меры на один вопрос».
#[cfg(windows)]
pub(crate) fn wide(s: &str) -> Vec<u16> {
    use std::os::windows::ffi::OsStrExt;
    std::ffi::OsStr::new(s).encode_wide().chain(std::iter::once(0)).collect()
}

/// Попросить первую копию показать своё окно: `true` — просьба принята (событие есть, сигнал послан), `false` — принять её некому.
///
/// **Почему просьба, а не подъём чужого окна своими руками.** До этой правки вторая копия искала окно первой сама: `EnumWindows`, первое попавшееся верхнеуровневое окно процесса с тем же образом, `ShowWindow(SW_RESTORE)`. Замер 10.11 на релизной сборке: верхнеуровневых окон у процесса ЧЕТЫРЕ, и когда флайаут закрыт — а это обычное состояние программы, живущей значком в трее, — настоящего окна среди них нет вовсе, зато первым перечисление отдаёт скрытое служебное окно библиотеки значка (класс `tray_icon_app`, 1920x1010). `ShowWindow` делал его видимым: человек, запустивший программу второй раз, получал чёрный прямоугольник во весь экран вместо окна, а вторая копия уходила через `exit(0)`, считая, что окно показала.
///
/// Угадывать чужое окно нечем и не нужно: нарисовать его умеет только GPUI внутри первой копии, значит просить надо ПРОГРАММУ, а не Windows, — и поднимает она его тем же путём (`gui::window::show_window`), которым поднимает по щелчку значка.
///
/// `OpenEventW`, а не `CreateEventW`: события нет — значит просьбу никто не слушает (`serve_show_requests` не заведена: голова `serve`/`connect`, сборка без окна), и честный отказ словами лучше молчаливого выхода в никуда.
#[cfg(windows)]
fn request_show(key: &str) -> bool {
    use windows_sys::Win32::Foundation::CloseHandle;
    use windows_sys::Win32::System::Threading::{OpenEventW, SetEvent, EVENT_MODIFY_STATE};
    let name = wide(&show_event_name(key));
    // SAFETY: обычный вызов kernel32 с нуль-терминированной строкой, живущей на стеке этого вызова.
    let h = unsafe { OpenEventW(EVENT_MODIFY_STATE, 0, name.as_ptr()) };
    if h.is_null() {
        return false;
    }
    // SAFETY: `h` только что получен от `OpenEventW` и ещё не закрыт.
    let ok = unsafe { SetEvent(h) };
    unsafe { CloseHandle(h) };
    ok != 0
}

/// Принимать просьбы «покажи окно» от вторых копий — свой поток на всё время работы, `show` зовётся на каждую просьбу. `false` — событие не завелось, и вторая копия тогда честно откажет словами, а не промолчит.
///
/// Событие с АВТОСБРОСОМ (`manual_reset = 0`): сигнал снимает сам ждущий, и две просьбы подряд дают два показа, а не один залипший навсегда.
///
/// Дескриптор заводится ЗДЕСЬ, до возврата, а не внутри потока: иначе просьба, пришедшая в ту долю секунды, пока поток ещё не завёл событие, пришла бы в пустоту — и человек прочёл бы отказ там, где должно было открыться окно. В поток он уезжает `Guard`-ом — тем же, что носит дескриптор замка, и ровно затем, что `Guard` `Send` и закрывает дескриптор за собой.
///
/// Полностью эту щель заводом здесь не закрыть: замок берётся раньше, чем строится значок (`gui::tray::build` — единственный зовущий), и вторая копия, запущенная между ними, получит честный отказ словами. Это и есть верный исход: окна в этот миг нет ни у кого, показывать нечего.
#[cfg(windows)]
pub fn serve_show_requests(show: impl Fn() + Send + 'static) -> bool {
    match account() {
        Ok(key) => serve_show_requests_with(&key, show),
        // Учётную запись не узнали — но сюда мы и не дошли бы: тем же вопросом её спрашивает замок (`acquire`), и его отказ приходит раньше. Молчать всё равно нельзя, а просьбы принимать нечем.
        Err(e) => {
            eprintln!("просьбы «покажи окно» от второй копии приниматься не будут: {e}");
            false
        }
    }
}

/// То же, но ключ даёт вызывающий — им проверяется тест: на машине может идти настоящая копия, и тест, занявший её имя события, отнимал бы у неё приём просьб.
#[cfg(windows)]
fn serve_show_requests_with(key: &str, show: impl Fn() + Send + 'static) -> bool {
    use windows_sys::Win32::Foundation::WAIT_OBJECT_0;
    use windows_sys::Win32::System::Threading::{CreateEventW, WaitForSingleObject, INFINITE};
    let name = show_event_name(key);
    let w = wide(&name);
    // SAFETY: обычный вызов kernel32 с нуль-терминированной строкой на стеке; без атрибутов безопасности — именованный объект виден только в сеансе вызывающего, ровно как мьютекс замка.
    let h = unsafe { CreateEventW(std::ptr::null(), 0, 0, w.as_ptr()) };
    if h.is_null() {
        eprintln!(
            "просьбы «покажи окно» от второй копии приниматься не будут: событие {name} не заведено — {}",
            std::io::Error::last_os_error()
        );
        return false;
    }
    let guard = Guard(h);
    std::thread::spawn(move || {
        // Замыкание обязано утащить `Guard` ЦЕЛИКОМ, а не поле `guard.0`: захват по частям (edition 2021) взял бы голый дескриптор, который не `Send` сам по себе, — `Send` обещан именно обёртке. Эта строка и есть то обещание, иначе сборка отказывает.
        let guard = guard;
        loop {
            // SAFETY: дескриптор жив всё время потока — его держит `guard`, переехавший сюда вместе с замыканием.
            if unsafe { WaitForSingleObject(guard.0, INFINITE) } != WAIT_OBJECT_0 {
                return;
            }
            show();
        }
    });
    true
}

/// На Linux просить некого: сигнала «покажи окно» между процессами здесь нет (управляющая дверь — `door` — возит вопросы команд, а не просьбы к окну), а в headless-сборке без фичи `gui` нет и самого окна — вторая копия сразу получает отказ с сообщением.
#[cfg(not(windows))]
pub fn serve_show_requests(_show: impl Fn() + Send + 'static) -> bool {
    false
}

#[cfg(not(windows))]
fn request_show(_key: &str) -> bool {
    false
}

/// На чём держим признак обслуживания: каталог состояния комплекта. На
/// Windows он входит в ИМЯ мьютекса (`serving_mutex_name`), на Linux им
/// самим держится `flock` (`acquire_serving`). Замок рабочего места сюда не
/// смотрит вовсе: его единица — учётная запись, а не комплект (задача 14).
pub fn lock_target(kit: &Kit) -> std::path::PathBuf {
    kit.state().to_path_buf()
}

/// Взять замок — одна копия на УЧЁТНУЮ ЗАПИСЬ в пределах машины (задача 14:
/// ни комплект, ни сеанс в единицу не входят) — или решить, что делать со
/// второй копией: бесшумно уступить (первая копия приняла просьбу показать
/// окно — Windows, тот же сеанс) либо вернуть читаемую причину отказа.
///
/// Замок — это открытая управляющая дверь, и возвращается она же: держите её
/// до конца процесса. Приём стуков переживёт ранний `drop` (его держит
/// собственный поток двери), но рассказывать двери о новостях станет некому.
///
/// `ask_first_copy_to_show` — просить ли первую копию показать окно вместо отказа. Это ответ ОКНУ: человек щёлкнул по ярлыку второй
/// раз, и ему всплывает уже запущенное — тишина с нулевым кодом здесь и есть то, что он просил. Командной строке (`connect`,
/// `serve`) отвечать так нельзя: человеку всплыло бы чужое окно вместо запрошенного обслуживания, а планировщику или службе достался
/// бы нулевой код при том, что эта копия не обслуживает никого. Им — слова и ненулевой код.
pub fn acquire(kit: &Kit, ask_first_copy_to_show: bool) -> anyhow::Result<crate::door::Door> {
    acquire_at(&account()?, kit, ask_first_copy_to_show)
}

/// То же, но учётную запись называет вызывающий — ею проверяется тест: на
/// машине может идти настоящая копия, и тест, занявший её дверь, отнял бы у
/// неё и приём команд, и сам замок (тот же довод, что у
/// `serve_show_requests_with`).
///
/// Три исхода, и все три — поведение, одинаковое на осях: дверь открылась
/// (замок наш), имя занято (`AddrInUse` — единственный вид отказа, который
/// обе оси называют одинаково, см. `door::NAME_TAKEN`), и любая другая беда
/// — замок не взят, и молчать о ней нельзя. Отказ открыть дверь смертелен
/// нарочно: доказать, что копия одна, больше нечем, а стартовать «наверное
/// единственным» — ровно тот отказ 15.11, против которого задача и заведена.
fn acquire_at(account: &str, kit: &Kit, ask_first_copy_to_show: bool) -> anyhow::Result<crate::door::Door> {
    let name = crate::door::door_name(account);
    match crate::door::open_at(&name, kit) {
        Ok(door) => Ok(door),
        Err(e) if e.kind() == std::io::ErrorKind::AddrInUse => {
            let holder = crate::door::who_answers(&name);
            if holder == crate::door::Knocked::Ours && ask_first_copy_to_show && request_show(account) {
                // Просьба идёт по ТОМУ ЖЕ ключу, по которому только что не
                // дался замок: кого замок не пустил, ту копию и просим
                // показать окно — второго правила «какая копия первая» в
                // модуле нет. Первая копия в ДРУГОМ сеансе просьбы не
                // услышит (событие ядра сеансом и ограничено), и тогда
                // человек получает слова — это верный исход, а не щель:
                // показывать окно в чужой сеанс всё равно некуда.
                std::process::exit(0);
            }
            let why = name_taken(holder);
            // Посторонний за нашим именем — событие для человека, и след о
            // нём обязан остаться: тем же приёмом, что `gate::refuse_to_serve`,
            // слова живут один раз и уходят и в журнал, и наружу. Обычную
            // вторую копию в журнал не пишем: она не происшествие, а
            // повседневность, и её слова человек и так читает на экране.
            if holder == crate::door::Knocked::Stranger {
                crate::journal::write(kit, crate::journal::Kind::Fail, why);
            }
            anyhow::bail!("{why}")
        }
        Err(e) => anyhow::bail!("не удалось взять замок (управляющая дверь {name}): {e}"),
    }
}

/// Имя замка занято — и человеку говорится, КЕМ. Два исхода, два разных
/// текста, и слить их в один нельзя: «уже запущен» про посторонний процесс —
/// это ложь, по которой человек пойдёт искать свою копию, которой нет.
///
/// `Nobody` — имя занято, а доказать, что держит его посторонний, не вышло
/// (достучаться не удалось вовсе). Чего не доказали, того не утверждаем:
/// такой случай получает обычные слова второй копии.
fn name_taken(holder: crate::door::Knocked) -> &'static str {
    match holder {
        crate::door::Knocked::Stranger => STRANGER_HOLDS,
        _ => TAKEN,
    }
}

/// Отказ второй копии словами, и текст один на все случаи: раньше в
/// туннельном режиме он называл рабочее место по имени — «рабочее место dev2
/// занято», — а в локальном поле пусто по замыслу, и человек читал «рабочее
/// место  занято» (находка аудита 30.10). Называть поле нечем и не для чего:
/// замок на него не смотрит вовсе.
///
/// «В этом сеансе» ушло задачей 14, и это не причёсывание: вторая копия
/// получает отказ в ЛЮБОМ сеансе этой учётной записи — ровно то, чего не
/// случилось 15.11, когда запуск по ssh при живом окне на рабочем столе
/// поднял вторую копию вместо отказа. Слова обязаны говорить то, что замок
/// делает, иначе человек ищет вторую копию не там.
const TAKEN: &str = "коннектор уже запущен под этой учётной записью — закройте его перед повторным запуском";

/// Имя замка занял ПОСТОРОННИЙ процесс — не наша копия, и человеку это
/// сказано прямо: искать свою копию ему незачем, её нет. Команд такой двери
/// отдавать нельзя, и мы их и не отдаём (`door::server_is_ours` на клиенте),
/// но поднять свой экземпляр под занятым именем тоже не выйдет — иначе
/// набранная команда достучалась бы до самозванца.
const STRANGER_HOLDS: &str = "имя управляющей двери занял посторонний процесс — это не ваша копия программы, и запускаться под \
                              занятым именем нельзя; сообщите нам, своих команд такой двери отдавать не надо";

/// Жив ли держатель замка этой учётной записи — СПРОСИВ его, а не посмотрев,
/// существует ли объект. Отозвалась дверь и ядро подтвердило, что за ней
/// НАША учётная запись, — держатель жив; это строже прежнего `OpenMutexW`,
/// где открывшийся дескриптор доказывал лишь существование объекта ядра.
/// Посторонний под тем же именем — не держатель нашего замка, и ответ про
/// него `false`.
///
/// Сама ничем не владеет и ничего не занимает даже на микросекунду, поэтому
/// два проверяющих не заверяют живость друг друга, застав один тик другого
/// (находка ревью задачи 2).
pub fn is_held(account: &str) -> bool {
    crate::door::who_answers(&crate::door::door_name(account)) == crate::door::Knocked::Ours
}

/// Взять признак обслуживания лучшим усилием, рядом с `acquire`
/// (`main.rs::connect`/`serve`, `gui::launch`) — держать до конца процесса,
/// переменная остаётся на стеке вызывающей функции. Пользователя не просит
/// Учётную запись параметром не просит — её знает `account`, и спрашивать
/// её у зовущих значило бы заводить второй ответ на вопрос «чья это копия»
/// (круг правок 1 задачи 14: строка пользователя ездила отсюда до
/// `ops_host::run_mcp` и обратно, и ни одному из зовущих она не была нужна
/// ни для чего другого).
///
/// Неудача (тот же комплект уже обслуживает другой процесс этого
/// пользователя под другим именем рабочего места — предсуществующий случай,
/// см. `acquire_serving`; или системная ошибка) не останавливает запуск:
/// признака без него нет, и сторож моста по коннектору
/// (`orphan::guard_owner`) просто не заведётся ему на пользу — увидит
/// `Owner::NotYet` и будет жить заглушкой, не хуже поведения без сторожа
/// вовсе.
///
/// Одно тело на обе оси, без `#[cfg]`: до задачи 14 на Linux здесь стоял
/// `None` — признак держался попутно замком рабочего места, который и сам
/// стоял `flock`-ом на том же каталоге. Замок уехал на дверь, и держать
/// признак стало некому; теперь его берут здесь обе оси, и разница осталась
/// только в примитиве (`acquire_serving`).
pub fn hold_serving(kit: &Kit) -> Option<Guard> {
    match acquire_serving(kit) {
        Ok(g) => g,
        Err(e) => {
            eprintln!("признак «обслуживает этот комплект» не закрепился: {e} — сторож моста по коннектору не заведётся ему на пользу");
            None
        }
    }
}

