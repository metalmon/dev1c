    /// У возврата база ОДНА: названная им, если он её назвал, единственная
    /// зачисленная, если выбора нет, и отказ словами, если выбирать нечем.
    ///
    /// Падало так: `hello_ok` отдавал весь список, и у того, кто ведёт учёт
    /// живых разговоров, поток числился за всеми карточками сразу. Отзыв
    /// ОДНОЙ карточки резал такой поток целиком — прямо против спеки
    /// (`revoked`: «отзыв одной карточки не должен рвать связь по четырём
    /// остальным»). Первый круг починки закрыл половину — ту, где карточка
    /// названа; вторая осталась жить на безымянном возврате, и у человека с
    /// пятью карточками к одному партнёру отзыв одной резал все пять потоков.
    #[tokio::test]
    async fn a_returning_side_gets_one_base_or_words_but_never_a_list() {
        let two = |book: &mut Book, peer: EndpointId, _state: &std::path::Path| {
            book.enroll(&"b1".into(), peer, "Разработчик", true).unwrap();
            book.enroll(&"b2".into(), peer, "Разработчик", true).unwrap();
            vec![Card { name: "Ромашка".into(), base: fields("b1", true) }, Card { name: "Василёк".into(), base: fields("b2", true) }]
        };

        let mut talk = Alone::new("returns-named", Decision::Allow { write: true }, two).await;
        Frame::write(&mut talk.w, &returning(Some("b2"))).await.unwrap();
        let answered = Frame::read(&mut talk.r).await;
        let Ok(Msg::HelloOk { bases, .. }) = &answered else {
            panic!("возврату отвечают hello_ok, а не отказом: {answered:?}")
        };
        assert_eq!(bases.len(), 1, "названа одна карточка — в ответе одна: {bases:?}");
        assert_eq!(bases[0].id, "b2".into(), "и именно та, которую назвали");
        let (out, _book, asked) = talk.done().await;
        let Ok(Outcome::Already(mine)) = &out else { panic!("возврат — это `Already`: {out:?}") };
        assert_eq!(mine.id, "b2".into(), "и наружу уходит ровно та карточка, за которой поток и числится");
        assert_eq!(asked, 0, "возврат человека не спрашивает: личность доказал iroh");

        // А возврат, карточку НЕ назвавший при нескольких зачисленных базах,
        // получает отказ СЛОВАМИ. Прежде ему отвечали всем списком, и поток
        // числился за всеми базами партнёра сразу: отзыв одной карточки резал
        // связь по остальным, а у человека с пятью карточками к одному партнёру
        // — все пять потоков разом, потому что каждый был «за всеми».
        let mut talk = Alone::new("returns-unnamed", Decision::Allow { write: true }, two).await;
        Frame::write(&mut talk.w, &returning(None)).await.unwrap();
        let answered = Frame::read(&mut talk.r).await;
        let Ok(Msg::Refuse(no)) = &answered else {
            panic!("ждали отказ словами, а не список, из которого никто не выберет: {answered:?}")
        };
        assert_eq!(no.code, code::NO_BASE, "{no:?}");
        assert!(no.text.contains("не ясно, к какой базе"), "сказано, чего не знаем: {}", no.text);
        assert!(no.text.contains("новый код"), "и что делать — код свяжет карточку с базой заново: {}", no.text);
        let (out, _book, _asked) = talk.done().await;
        assert!(matches!(out, Ok(Outcome::NotEnrolled(_))), "{out:?}");

        // Но когда зачисленная база ОДНА, выбирать не из чего — и безымянный
        // возврат получает её: зовущая сторона запомнит признак и дальше назовёт
        // карточку сама. Так эта беда и залечивается сама собой у того, у кого
        // карточка к партнёру одна.
        let mut talk = Alone::new("returns-unnamed-one", Decision::Allow { write: true }, |book, peer, _state| {
            book.enroll(&"b1".into(), peer, "Разработчик", true).unwrap();
            vec![Card { name: "Ромашка".into(), base: fields("b1", true) }, Card { name: "Василёк".into(), base: fields("b2", true) }]
        })
        .await;
        Frame::write(&mut talk.w, &returning(None)).await.unwrap();
        let answered = Frame::read(&mut talk.r).await;
        let Ok(Msg::HelloOk { bases, .. }) = &answered else { panic!("выбора нет — отвечаем базой: {answered:?}") };
        assert_eq!(bases.len(), 1, "и она одна: {bases:?}");
        assert_eq!(bases[0].id, "b1".into());
        let (out, _book, _asked) = talk.done().await;
        assert!(matches!(out, Ok(Outcome::Already(_))), "{out:?}");
    }

