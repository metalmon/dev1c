pub const LOCAL_ANSWER: (&str, &str) = ("Всё на одной машине", "local");

/// Ответы третьего переключателя карточки — кто публикует базу (задача 5
/// плана «Карточка публикации и удаление»): пары «значение в toml, слова
/// человеку». Значения прежние (`Connection::publication`, их читает
/// `Cfg::base_url` и проверяет `Connection::validate`), слова называют дело, а
/// не механику: что публикуется и кто это делает.
///
/// **Почему словарь живёт здесь, а не в `panel.rs` или `tray.rs`** — та же
/// находка Important 2 ревью круга починки 1, из-за которой здесь же лежат
/// `onboarding_answers`/`LOCAL_ANSWER`: слова, заведённые заново у каждого, кто
/// их показывает, расходятся на первой же правке. Их показывают двое —
/// переключатель карточки (`panel::publication_switch_label`) и строка
/// журнала о смене публикации (`tray::apply_publication`). Подменю значка,
/// которое раньше было третьим читателем, решением владельца 1.11 убрано
/// вовсе («публикация — поле соединения, и пункт меню убран вовсе»).
pub fn publication_answers() -> [(&'static str, &'static str); 2] {
    [("auto", "Публикует коннектор"), ("webserver", "Публикует платформа 1С")]
}

/// Слова про публикацию по значению из toml — тот же поиск по словарю выше,
/// который до задачи 5 трижды переписывали на месте (дважды в
/// `tray::apply_publication`, по разу на каждую ветвь записи). Неизвестное
/// значение читается как умолчание «публикует коннектор» — тем же приёмом, что
/// `panel::profile_label` у набора инструментов: отказать здесь нечему, слово
/// нужно показать, а опечатку в файле ловит `Connection::validate` словами.
pub fn publication_label(publication: &str) -> &'static str {
    let [auto, webserver] = publication_answers();
    if publication == webserver.0 {
        webserver.1
    } else {
        auto.1
    }
}

/// Онбординг кончается СОСТОЯНИЕМ, а не флагом (спека: «Кончается онбординг
/// состоянием, а не флагом») — первое соединение заведено, значит он
/// кончился. Ключа «онбординг пройден» в настройках не заводим: список
/// соединений и есть эта памятка.
pub fn onboarding_shown(cfg: &Cfg) -> bool {
    cfg.connections.is_empty()
}

/// Весь список вкладки «Связь»: подписи групп вперемешку со строками
/// соединений, в порядке показа.
///
/// Список смешанный, и в этом его главное свойство (вопрос владельца 3.11:
/// «на первом экране будут же все режимы отображаться, где-то мы сервер,
/// где-то сами подключаемся»). Два правила:
///
/// 1. Подписи групп («Принимаю подключения», «Подключаюсь сам», «На этой
///    машине», порядок неизменный) появляются, только когда ролей в списке
///    больше одной. Одна роль ни на что не отвечает и съедает высоту окна
///    380×420.
/// 2. Соединение, ждущее разрешения, — первая строка списка, выше всех
///    подписей: диалог человек мог закрыть не решив, и возвращать его
///    должно самое заметное место. Группа при этом его не теряет — подпись
///    всё равно показывается (решает полный список, а не то, что осталось
///    под ней видимым), просто сама строка стоит не под ней.
// Проведена в продуктовый код задачей 14 (`panel::link_body` зовёт её на
// каждую отрисовку вкладки «Связь») — глушитель `dead_code`, стоявший здесь,
// пока вызывающего не было, снят: иначе он спрятал бы будущую регрессию
// (Minor ревью всей ветки).
pub fn list(cfg: &Cfg, link: &dyn Fn(&str) -> Option<State>) -> Vec<Entry> {
    let current = cfg.current() as *const Connection;
    let category = |c: &Connection| -> usize {
        if c.mode == "local" {
            2
        } else if matches!(c.role(), Ok("dial")) {
            1
        } else {
            0
        }
    };

    let mut waiting = Vec::new();
    let mut groups: [Vec<Row>; 3] = [Vec::new(), Vec::new(), Vec::new()];
    let mut present = [false; 3];
    for c in &cfg.connections {
        let cat = category(c);
        present[cat] = true;
        let r = row(c, std::ptr::eq(c, current), link(&c.name).as_ref());
        if r.state == "ждёт разрешения" {
            waiting.push(r);
        } else {
            groups[cat].push(r);
        }
    }

    let show_captions = present.iter().filter(|p| **p).count() > 1;
    const CAPTIONS: [&str; 3] = ["Принимаю подключения", "Подключаюсь сам", "На этой машине"];

    let mut out: Vec<Entry> = waiting.into_iter().map(Entry::Row).collect();
    for (cat, present) in present.into_iter().enumerate() {
        if !present {
            continue;
        }
        if show_captions {
            out.push(Entry::Caption(CAPTIONS[cat]));
        }
        out.extend(std::mem::take(&mut groups[cat]).into_iter().map(Entry::Row));
    }
    out
}

/// Строка перехода сеанса — тексты как в сегодняшнем `gui.rs::set_link`.
/// Начало и конец видны и в журнале: туннель сам пишет только про поднятую
/// связь и обрывы, а отказ возвращает ошибкой. `Connecting` — по режиму:
/// адрес среды, пароль и имя рабочего места в локальном режиме скрыты в
/// «Связи» (`panel::shown_fields`) и ничего не значат — печатать их в
/// журнал всё равно было бы находкой целостного ревью (строка говорила про
/// туннель, которого там нет).
pub fn link_line(l: &State, host: &Connection, mode: &str) -> Option<Line> {
    match l {
        State::Connecting => {
            let text = if mode == "local" {
                "включаю MCP".to_string()
            } else {
                format!("подключаюсь к {} как {}", host.server, host.workstation)
            };
            Some(Line { kind: Kind::Say, text })
        }
        State::Failed(why) => Some(Line { kind: Kind::Fail, text: why.clone() }),
        State::Off => Some(Line { kind: Kind::Say, text: "отключено".into() }),
        State::Up { .. } | State::Retrying(_) => None,
    }
}

/// `Ev::Link(gen, ..)` стоит применять только если `gen` — поколение сеанса,
/// текущее прямо сейчас; иначе это хвост уже остановленного или уже
/// замещённого сеанса.
pub fn link_is_current(ui: &Ui, gen: u64) -> bool {
    gen == ui.session_gen
}

/// Холодный замок на текущих параметрах — общая функция, не своя
/// (`crate::gate::gate_now`): подкоманде `1c-connect mcp` он нужен тем же
/// путём, без второй формулировки причин отказа. Отдельно от `refresh_gate`
/// ниже, потому что `launch` считает замок до того, как `Ui` вообще
/// появился — начальное значение переключателя уже обязано его слушаться.
pub use crate::gate::gate_now;

/// Пересчитать замок и донести причину до моста: пока замок заперт, отказ
/// агенту несёт её текстом (`bridge::disabled_text`), иначе ни агент, ни
/// человек не узнают, что править.
pub fn refresh_gate(ui: &mut Ui) {
    // Замок именно **защёлкивается**: был открыт — стал заперт. Замок,
    // запертый и до пересчёта, обслуживание уже погасил этим же местом, и
    // гасить второй раз (и говорить второй раз) незачем.
    let was_open = ui.gate.is_none();
    ui.gate = gate_now(&ui.kit, &ui.cfg);
    // Защёлкнувшийся замок гасит обслуживание — здесь, в единственном месте,
    // где он защёлкивается, а не у каждого вызывающего по-своему. Иначе
    // замок правил бы одни слова в отказе: человек правит toml руками,
    // условие пропадает, окно на показе перечитывает файл и пересчитывает
    // ворота — карточка говорит «MCP выключены», а агента продолжают
    // обслуживать, потому что флаг никто не снял (находка ревью задачи 24).
    //
    // Обратное ворота не делают: условие вернулось — переключатель
    // отпирается сам (`panel::switch_locked` смотрит на `ui.gate`), но
    // обслуживание включает человек, а не пересчёт за его спиной.
    if was_open {
        if let Some(why) = ui.gate.clone() {
            if ui.enabled.load(Ordering::Relaxed) {
                douse_serving(ui);
                note_line(ui, Line { kind: Kind::Warn, text: format!("MCP выключены: {why}") });
            }
        }
    }
    // Замок доезжает до трея всегда, а не только когда что-то погасил
    // (находка S2): пункт «Включить MCP» обязан запираться и отпираться
    // ровно тогда же, когда переключатель в окне. Раньше `sync_tray` стояла
    // только внутри `douse_serving`, и открывшийся замок (вписали
    // пользователя базы) оставлял пункт серым до следующей операции, а
    // защёлкнувшийся при выключенных MCP — нажимаемым.
    sync_tray(ui, Instant::now());
}

/// Погасить обслуживание вызовов, не спрашивая никого: правка убрала холодное
/// условие. Снять один флаг мало — карточка и переключатель читают `ui.link`, и
/// без этой строки человек видел бы зелёное «MCP включены» и переключатель,
/// который нарисован включённым, но на щелчок не отвечает (находка ревью).
///
/// В локальном режиме слушатели остаются поднятыми (они живут весь срок жизни
/// процесса), гаснет только обслуживание — ровно то же, что делает ручное
/// выключение переключателя. В туннельном обслуживание и есть сеанс, поэтому
/// он опускается целиком, тем же приёмом, что `stop_session` (ей нужен `cx`,
/// а здесь его нет).
pub fn douse_serving(ui: &mut Ui) {
    ui.enabled.store(false, Ordering::Relaxed);
    // Непрошедшая запись — не тишина: она оставляет на диске «on» при уже выключенном обслуживании, то есть разрешение, которого человек не давал (минорная находка ревью задачи 2).
    if let Err(e) = crate::allow::write(&ui.kit, false) {
        note_line(ui, Line { kind: Kind::Warn, text: format!("признак разрешения не записан: {e:#}") });
    }
    if ui.cfg.current().mode == "local" {
        ui.link = local_display("local", false, ui.link.clone());
    } else {
        ui.session_gen += 1;
        if let Some(s) = ui.session.take() {
            std::thread::spawn(move || {
                let _ = s.stop();
            });
        }
        ui.link = State::Off;
    }
    sync_tray(ui, Instant::now());
}

/// Включать ли обслуживание при запуске: галочка «подключаться при запуске»
/// замок не обходит (спека: «Автозапуск не обходит замок»). В локальном
/// режиме это начальное значение переключателя, в туннельном — ещё и
/// поднимать ли сеанс.
pub fn autostart_enabled(gate: Option<&str>, autoconnect_on: bool) -> bool {
    autoconnect_on && gate.is_none()
}

/// Строка журнала о запертом переключателе при запуске. Сказать надо в обоих
/// случаях — человек видит серую точку и запертый переключатель и обязан
/// прочитать причину, — но СЛОВА разные, и в этом вся правка.
///
/// Заказчик 31.10.2026: «что значит „MCP не включены при запуске“? у меня
/// галочки включать при запуске не стояло». Прежний текст был один на оба
/// случая и обещал попытку, которой не было: при снятой галочке программа
/// ничего не включала и не могла не включить. Теперь при снятой галочке
/// строка говорит ровно то же, что подвал окна («Нельзя включить: …»), а про
/// запуск — только когда запуск и правда просили.
pub fn gate_line(why: &str, autoconnect_on: bool) -> Line {
    let text = if autoconnect_on {
        format!("MCP не включены при запуске: {why}")
    } else {
        format!("Включить MCP пока нельзя: {why}")
    };
    Line { kind: Kind::Warn, text }
}

/// Отказ публикации: гасит обслуживание и говорит, что показать. Спека
/// называет этот ряд красным («Отказ занять порт или поднять публикацию» →
/// «Не подключён»), поэтому выбран первый из двух выходов: карточка остаётся
/// красной, а настоящее обслуживание подводится под показанное, а не
/// наоборот.
///
/// Раньше отказ только красил карточку: `enabled` оставался поднятым, мост
/// продолжал обслуживать вызовы под красным «Не подключён», а первый щелчок
/// по переключателю **выключал** обслуживание вместо того, чтобы включить, —
/// показанное и настоящее разошлись (находка S6 итогового ревью). Теперь
/// щелчок после отказа означает «попробовать снова»: `toggle_link` поднимет
/// флаг и позовёт публикацию заново.
///
/// Цена названа прямо: инструменты, которым публикация не нужна
/// (`cf_decompile`/`cf_load` через `vrunner-mcp`), на время отказа тоже не
/// обслуживаются. Это следствие обещания карточки: красное значит «не
/// работает», а не «работает наполовину».
///
/// **Красное не лечится само, и это нарочно** (ревью N5). Удавшаяся
/// публикация (скажем, после «Сохранить») карточку не зеленит: `enabled`
/// снят здесь, а поднимать обслуживание за спиной человека программа не
/// умеет нигде — тем же правилом живёт замок («обратное ворота не делают:
/// условие вернулось — переключатель отпирается сам, но обслуживание
/// включает человек», см. `refresh_gate`). Красная карточка в это время не
/// врёт: вызовы правда не обслуживаются. Выход один и он на виду —
/// переключатель нарисован выключенным, причина в подвале и в подсказке, и
/// один щелчок означает «попробовать снова». Не надо «чинить» это
/// самозеленением: оно вернёт ровно тот дефект, против которого писан
/// раздел спеки «Зелёный значит „работает“» — экран, обещающий работу,
/// которую никто не подтверждал.
pub fn publication_failure(ui: &mut Ui, why: &str) -> State {
    ui.enabled.store(false, Ordering::Relaxed);
    if let Err(e) = crate::allow::write(&ui.kit, false) {
        note_line(ui, Line { kind: Kind::Warn, text: format!("признак разрешения не записан: {e:#}") });
    }
    State::Failed(format!("публикация: {why}"))
}

/// Обслуживаются ли вызовы агента прямо сейчас — по тому самому флагу,
/// который мост читает на каждый вызов. В туннельном режиме нужен ещё и
/// поднятый сеанс: без него вызову некуда ехать.
///
/// Раньше туннель смотрел только на сеанс, и флаг с ним расходился: замок,
/// защёлкнувшийся при смене режима, гасил флаг, а сеанс поднимался следом
/// безусловно — карточка показывала зелёное «Подключён», мост отказывал
/// каждому вызову, и первый щелчок по переключателю не включал обслуживание,
/// а останавливал туннель (находка S5 итогового ревью).
pub fn serving(ui: &Ui) -> bool {
    ui.enabled.load(Ordering::Relaxed) && (ui.cfg.current().mode == "local" || ui.link.is_on())
}

/// Перезапустить сеанс после удачной записи параметров (только туннельный
/// режим — там порты живут внутри SSH, и подменить базу под уже идущим
/// сеансом нечем): старому потоку просят остановиться (в своём потоке, не
/// блокируя этот), новый поднимают сразу с уже записанными параметрами —
/// тем же флагом `enabled`, он живёт дольше сеанса. Переход в
/// «подключаюсь»/«подключён» придёт позже обычным `Ev::Link`, здесь —
/// только одна строка в журнал про сам факт перезапуска.
pub fn restart_session(ui: &mut Ui, base_path: String) {
    ui.session_gen += 1;
    let gen = ui.session_gen;
    if let Some(s) = ui.session.take() {
        std::thread::spawn(move || {
            let _ = s.stop();
        });
    }
    let ctx = ctx_for(ui);
    let (cfg, kit, tx, enabled, editor_mcp) = (ui.cfg.clone(), ui.kit.clone(), ui.tx.clone(), ui.enabled.clone(), ui.editor_mcp.clone());
    let session = session::start_with_enabled(cfg, kit, ctx.sink, enabled, editor_mcp, move |l| {
        let _ = tx.unbounded_send(Ev::Link(gen, l));
    });
    ui.session = Some(session);
    note_line(ui, Line { kind: Kind::Say, text: format!("MCP перезапущены: база {base_path}") });
}

/// Почему обслуживание не идёт — одной строкой для отказа агенту. Порядок
/// тот же, что у карточки: сперва замок (включать нечего), потом отказ,
/// который обслуживание погасил (занят порт, не поднялась публикация).
/// Обслуживание идёт — причины нет; выключил человек — причины тоже нет, и
/// отказ советует прежнее «включите переключатель», что в этом случае и
/// правда (`bridge::disabled_text`).
pub fn off_reason(ui: &Ui) -> Option<String> {
    if serving(ui) {
        return None;
    }
    ui.gate.clone().or_else(|| match &ui.link {
        State::Failed(why) => Some(why.clone()),
        _ => None,
    })
}

/// Переход сеанса: в состояние, в журнал, в трей, перерисовать окно.
pub fn set_link(cx: &mut App, l: State) {
    let host = cx.global::<Ui>().cfg.current().clone();
    let line = link_line(&l, &host, &host.mode);
    let ui = cx.global_mut::<Ui>();
    ui.link = l.clone();
    if let Some(line) = line {
        note_line(ui, line);
    }
    sync_tray(ui, Instant::now());
    cx.refresh_windows();
}

/// Автоподключение при запуске: ключ состояния комплекта `autoconnect`,
/// нет записи — выключено.
pub fn autoconnect(kit: &Kit) -> bool {
    kit.state_get("autoconnect").as_deref() == Some("1")
}

/// Нужен ли новый сеанс. Живой второго поверх себя не хочет — в том числе в
/// окно между `session::start_with_enabled` и первым `Connecting`, когда
/// `link` ещё `Off`. А кончившийся сам (`Session::finished`: отказ bind на
/// старте локального транспорта, упавший туннель) — хочет: иначе «включить»
/// молча ничего не делает, и человек заперт в красном до перезапуска
/// процесса (находка владельца 26.10 на стенде).
///
/// Показанный отказ считается концом наравне с `done`: поток успевает
/// сказать `Failed` раньше, чем уронит рантайм и отдаст `done`
/// (см. `session::start_with_enabled`), и щелчок, попавший в это окно, не
/// должен проваливаться молча. Сохранённый текст (`Ui::bind_failed`) тут не
/// при чём вовсе — отказ следствие, а не причина.
pub fn needs_session(ui: &mut Ui) -> bool {
    if matches!(ui.link, State::Failed(_)) {
        return true;
    }
    match ui.session.as_mut() {
        Some(s) => s.finished(),
        None => true,
    }
}

/// Тексты ошибок — дословно из сегодняшнего `gui.rs::start_session`.
pub fn start_session(ui: &mut Ui) -> Result<(), String> {
    let params = ui.kit.state_path(cfg::FILE);
    if !params.exists() {
        return Err(format!("нет файла параметров {} — заполните поля и нажмите «Сохранить»", params.display()));
    }
    if !needs_session(ui) {
        return Ok(());
    }
    // Прежний отказ bind больше не наш: сеанс, которому он принадлежал,
    // кончился, и новый ещё ничего о портах не сказал. Скажет сам —
    // `Ev::Link` заведёт новый текст (держатель мог смениться) или снимет
    // его совсем, поднявшись.
    ui.bind_failed = None;
    // Новый сеанс — новое поколение: хвост от прежнего (если он всё ещё
    // договаривает) будет отбрасываться в `handle` по несовпадению.
    ui.session_gen += 1;
    let gen = ui.session_gen;
    let ctx = ctx_for(ui);
    let (cfg, kit, tx, enabled, editor_mcp) = (ui.cfg.clone(), ui.kit.clone(), ui.tx.clone(), ui.enabled.clone(), ui.editor_mcp.clone());
    let session = session::start_with_enabled(cfg, kit, ctx.sink, enabled, editor_mcp, move |l| {
        let _ = tx.unbounded_send(Ev::Link(gen, l));
    });
    ui.session = Some(session);
    Ok(())
}

/// Остановить сеанс (блокирующе — в своём потоке) и сразу показать «отключено».
pub fn stop_session(cx: &mut App) {
    let ui = cx.global_mut::<Ui>();
    // Хвостовой `Ev::Link` от останавливаемого сеанса (тот всё ещё может
    // договаривать в своём потоке) должен отбрасываться — он уже не про
    // текущее поколение.
    ui.session_gen += 1;
    if let Some(s) = ui.session.take() {
        std::thread::spawn(move || {
            let _ = s.stop();
        });
    }
    set_link(cx, State::Off);
}

/// Переключатель в локальном режиме не трогает сеанс — слушатели уже подняты
/// и остаются поднятыми (см. `launch`), меняется только то, отвечают ли
/// вызовы агента. Возвращает новое состояние флага.
pub fn flip_enabled_only(ui: &mut Ui) -> bool {
    let on = !ui.enabled.load(Ordering::Relaxed);
    ui.enabled.store(on, Ordering::Relaxed);
    if let Err(e) = crate::allow::write(&ui.kit, on) {
        note_line(ui, Line { kind: Kind::Warn, text: format!("признак разрешения не записан: {e:#}") });
    }
    on
}

/// Экран показывает «MCP выключены», пока снят флаг обслуживания, даже если
/// сеанс ещё договаривает своё в потоке: подменяем `Connecting`/`Up` на
/// `Off`. Отказ (`Failed`) виден всегда — о нём человек обязан узнать.
///
/// С 26.10 выключение в локальном режиме ОТПУСКАЕТ слушатели (выключено
/// значит выключено), так что расхождение показанного с настоящим здесь
/// короткое — только пока останавливается поток сеанса.
pub fn local_display(mode: &str, enabled: bool, l: State) -> State {
    if mode == "local" && !enabled {
        match l {
            State::Up { .. } | State::Connecting => State::Off,
            other => other,
        }
    } else {
        l
    }
}

pub fn toggle_link(cx: &mut App) {
    // Замок — один на окно и на трей, и держится он здесь, в общем месте: и
    // переключатель, и пункт меню приходят сюда. Запирается только включение —
    // выключить обслуживание можно всегда (замок мог защёлкнуться под живым
    // сеансом, например правкой toml руками).
    if !serving(cx.global::<Ui>()) {
        if let Some(why) = cx.global::<Ui>().gate.clone() {
            note_line(cx.global_mut::<Ui>(), Line { kind: Kind::Warn, text: crate::gui::panel::gate_text(&why) });
            cx.refresh_windows();
            return;
        }
    }
    if cx.global::<Ui>().cfg.current().mode == "local" {
        let ui = cx.global_mut::<Ui>();
        let on = flip_enabled_only(ui);
        // Набор прошлого состояния переключателя старый на экране не держим
        // синхронно (задача 5: «Пошёл новый расчёт — старый не возвращаем»):
        // «Выключено» и так не читает `ui.verdict` вовсе (`card` сворачивает
        // по `link`/`enabled` раньше), а «Включаю…» — свой исход карточки,
        // не читающий вердикт, пока `link` не станет `Up`. К этому моменту
        // `run_readiness` (ниже/в `Ev::Publish`) уже в полёте и заменит его
        // настоящим ответом; задержка — тот же компромисс, что и у такта.
        if !on {
            // **Выключено значит выключено** (спека, «Не цели»): выключенный
            // коннектор НЕ держит порты рабочего места. Прежде слушатели
            // оставались поднятыми весь срок процесса, и человек, выключив
            // MCP здесь, не мог включить их на другой машине с тем же именем
            // рабочего места — порты были заняты выключенным коннектором, и
            // отпускал их только выход из программы. Владелец 26.10: «это
            // значит выключено, а не что всё равно держит порты».
            //
            // Цена, принятая сознательно: `nc` агента в Zed умирает вместе
            // со слушателем, и после обратного включения MCP-серверы там
            // придётся поднять заново. Пока обслуживание выключено, они всё
            // равно получали только отказы — держать ради них занятый порт
            // чужого рабочего места не за что.
            // `stop_session` сама говорит «отключено» (`set_link`) — второй
            // раз строку не пишем: в журнале шли пары одинаковых строк на
            // один щелчок (находка владельца 26.10).
            stop_session(cx);
            // Свой httpd — тоже наш, и выключение забирает его с собой: он
            // слушает порт публикации и держит каталог комплекта, а служит
            // одному агенту, которого мы только что перестали обслуживать.
            // Иначе «выключено» снова значило бы «кроме вот этого» — тот
            // самый подводный камень, которого догма не допускает. Чужой
            // веб-сервер (`publication = "webserver"`) не трогаем, и гасим
            // только то, что подняли сами (`raised_publication`).
            //
            // Удача молчит: «отключено» рядом уже сказано, а вторая строка
            // про внутренности человеку ничего не добавляет. Отказ — говорим:
            // порт остался занятым, и он это увидит.
            let ui = cx.global_mut::<Ui>();
            if ui.raised_publication {
                ui.raised_publication = false;
                let ctx = quiet_ctx(ui);
                if let Err(e) = ops_host::stop_own_publication(&ctx) {
                    note_line(cx.global_mut::<Ui>(), Line { kind: Kind::Warn, text: format!("HTTP-сервис базы не остановлен: {e:#}") });
                }
            }
            // Прежний отказ bind больше не наш: порты мы отпустили, и
            // следующее включение пробует занять их заново.
            cx.global_mut::<Ui>().bind_failed = None;
            return;
        }
        // «Включить» значит «работай»: живой сеанс `start_session` не трогает
        // (слушатели держат порты весь срок процесса — см. `launch`), а
        // кончившийся поднимает заново — именно это человек и имеет в виду,
        // щёлкая переключателем после «порт занят»: держатель мог уже уйти
        // (находка владельца 26.10 — прежде здесь был тупик до перезапуска
        // процесса).
        if let Err(e) = start_session(cx.global_mut::<Ui>()) {
            window::show_window(cx);
            note_line(cx.global_mut::<Ui>(), Line { kind: Kind::Fail, text: e });
            cx.refresh_windows();
            return;
        }
        // «Включаю…» объявляет сам поднятый сеанс (`Ev::Link(Connecting)`,
        // приходит тут же) — руками его здесь больше не ставим: пока
        // переключатель в локальном режиме сеанса не трогал, строку писал
        // только этот вызов, а теперь её пишут оба, и в журнале шли пары
        // одинаковых строк на один щелчок (находка владельца 26.10).
        //
        // Карточка при этом не зеленеет раньше времени: до `Up` она говорит
        // «Включаю…», а публикация идёт своим потоком.
        ensure_publication_now(cx.global_mut::<Ui>());
        return;
    }
    let on = cx.global::<Ui>().link.is_on();
    // Флаг обслуживания идёт за сеансом и в туннельном режиме. Раньше он
    // писался только в `launch` (начальным значением), и это было терпимо,
    // пока в «выключено» попадал лишь тот, кто сам снял «подключаться при
    // запуске». С замком туда попадает и обычное рабочее место — а выйти
    // оттуда было нечем: человек чинил условие, поднимал туннель, карточка
    // говорила «Подключён», а каждый вызов агента получал отказ с причиной,
    // которой уже нет (находка ревью).
    cx.global::<Ui>().enabled.store(!on, Ordering::Relaxed);
    if let Err(e) = crate::allow::write(&cx.global::<Ui>().kit, !on) {
        note_line(cx.global_mut::<Ui>(), Line { kind: Kind::Warn, text: format!("признак разрешения не записан: {e:#}") });
    }
    if on {
        stop_session(cx);
        return;
    }
    match start_session(cx.global_mut::<Ui>()) {
        Ok(()) => ensure_publication_now(cx.global_mut::<Ui>()),
        Err(e) => {
            window::show_window(cx);
            note_line(cx.global_mut::<Ui>(), Line { kind: Kind::Fail, text: e });
            cx.refresh_windows();
        }
    }
}

