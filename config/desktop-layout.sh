#!/bin/sh
# Новые значки — ПОД старыми, а не между ними.
#
#   desktop-layout <дом> <владелец> <группа>
#
# xfdesktop помнит, где лежит каждый значок, в
# ~/.config/xfce4/desktop/icons.screen0.yaml. Появившийся ярлык он кладёт в
# первое свободное место сверху — и старые значки переезжают вниз. Для
# человека это мелочь, а для онборда нет: стрелки берут координаты из этого
# самого файла, а xfdesktop пишет его не сразу. Пока запись на диске отстаёт,
# стрелка показывает на соседний значок — ровно то, что заказчик видел
# 26.10.2026, когда на стол приехал «Чат с моделью» и встал второй строкой,
# сдвинув Gitea и Zed.
#
# Поэтому: значки, которых в раскладке ещё нет, дописываем НИЖЕ самой нижней
# занятой строки. Чужие записи не трогаем вовсе — ни порядок, ни координаты;
# человек, разложивший стол по-своему, своей раскладки не теряет.
#
# В свежем доме раскладку задаём САМИ, порядком ниже. Оставлять это xfdesktop
# нельзя: он сортирует по-своему, и на чистом доме коннектор вставал ПЕРВЫМ,
# выше Gitea и Zed (замерено 26.10.2026 запуском xfdesktop на Xvfb). Порядок
# на столе — часть стенда, который показывают заказчику, а не случайность
# сортировки. То, что заранее написанный файл xfdesktop уважает, проверено
# там же: он сохранил заданные строки, хотя идентификатор монитора был чужой.
#
# Строки закреплены за ИМЕНАМИ, а не за тем, что уже лежит на столе: ярлык
# 1С появляется позже остальных (его кладёт `1c-stand seed` при первом входе),
# и без брони он уехал бы в конец. Запись о файле, которого ещё нет, xfdesktop
# игнорирует — на этом же держится его собственная уборка устаревших записей.
ORDER='1c-start.desktop gitea.desktop dev.zed.Zed.desktop model-chat.desktop 1c-connect.desktop'
set -u

home=${1:?дом}
owner_u=${2:?владелец}
owner_g=${3:?группа}

layout="$home/.config/xfce4/desktop/icons.screen0.yaml"

# Пишем не root'ом, а САМИМ владельцем дома: тогда права проверяет ядро, а не
# наши проверки. Иначе предсказуемое имя временного файла в каталоге, который
# правит пользователь, — это подъём прав: подложил на его место ссылку на
# чужой файл, и root записал через неё (нашло ревью 26.10.2026). Имя временного
# файла всё равно случайное, а `mv -T` не идёт по ссылке — переименование
# заменяет саму ссылку, в отличие от `cp` и `install`.
write_as_owner() { # $1 — куда; содержимое на stdin
    runuser -u "$owner_u" -- sh -c '
        d=${1%/*}
        t=$(mktemp "$d/.layout.XXXXXX") || exit 1
        if cat > "$t" && chmod 0644 "$t"; then mv -T "$t" "$1"; else rm -f "$t"; exit 1; fi
    ' _ "$1"
}

# Только обычный файл: симлинк наружу и каталог на этом месте — не наше дело.
[ ! -L "$layout" ] || exit 0
[ -d "$home/Desktop" ] || exit 0

# Точка входа работает под root, а дом правит сам пользователь: любой из
# промежуточных каталогов может оказаться ссылкой наружу, и тогда запись
# root'ом ушла бы в чужой файл. Проверки одного `-L` на сам файл мало —
# подменяют каталог выше. Поэтому разрешаем путь, только если он разворачивается
# ВНУТРЬ того же дома; та же защита стоит у ~/.pi и ~/.config/zed.
home_real=$(realpath -q "$home") || exit 0
for d in "$home/.config" "$home/.config/xfce4" "$home/.config/xfce4/desktop" "$home/Desktop"; do
    [ ! -L "$d" ] || exit 0
    [ -e "$d" ] || continue
    real=$(realpath -q "$d") || exit 0
    case "$real/" in "$home_real"/*) ;; *) exit 0 ;; esac
done

# Раскладка есть, но в ней ТОЛЬКО наши значки — значит её писал не человек, а
# xfdesktop, и порядок в ней случаен. Выравниваем по образу. Это не та
# «чужая расстановка», которую нельзя трогать: чужой её делает хоть один
# значок, положенный человеком, — тогда работает ветка ниже, и мы лишь
# дописываем недостающее вниз.
#
# Нужно это вот зачем: дома живут в томе и переживают смену образа. Без этого
# стенд, поднятый ещё до появления ярлыка чата, навсегда оставался бы с ним
# посередине — заказчик видел это дважды и оба раза спрашивал, почему порядок
# не поменялся (26.10.2026).
if [ -f "$layout" ]; then
    foreign=0
    for p in $(sed -n 's/^[ ]*"\(.*\)":[ ]*$/\1/p' "$layout"); do
        [ "$p" = "$home" ] && continue
        known=0
        for name in $ORDER; do
            [ "$p" = "$home/Desktop/$name" ] && known=1 && break
        done
        [ "$known" = 1 ] || { foreign=1; break; }
    done
    [ "$foreign" = 0 ] && runuser -u "$owner_u" -- rm -f "$layout" && say_aligned=1
fi

# Раскладки ещё нет — пишем свою, с закреплёнными строками. Геометрия и
# идентификатор монитора здесь условные: xfdesktop перепишет их своими при
# первом входе, СОХРАНИВ наши строки (проверено на Xvfb). Значок дома —
# нулевая строка, как его кладёт сам xfdesktop.
if [ ! -f "$layout" ]; then
    runuser -u "$owner_u" -- mkdir -p "$home/.config/xfce4/desktop" || exit 0
    { printf '%s\n' 'configs:' '- level: 0' '  monitors:' '  - id: "dev1c-default"' \
        '    display_name: "dev1c"' '    geometry:' '      x: 0' '      y: 0' \
        '      width: 1920' '      height: 1080' '  icons:'
      printf '    "%s":\n      row: 0\n      col: 0\n' "$home"
      n=0
      for name in $ORDER; do
          n=$((n + 1))
          printf '    "%s/Desktop/%s":\n      row: %d\n      col: 0\n' "$home" "$name" "$n"
      done
    } | write_as_owner "$layout" \
        && echo "раскладка стола ${say_aligned:+выровнена по образу}${say_aligned:-задана образом}: $ORDER ($home)"
    exit 0
fi

# Какие ярлыки на столе ещё не упомянуты в раскладке.
missing=
for f in "$home"/Desktop/*.desktop; do
    [ -f "$f" ] || continue
    grep -q "\"$f\":" "$layout" && continue
    missing="$missing$f
"
done
[ -n "$missing" ] || exit 0

tmp=$(mktemp) || exit 0
# Блок `icons:` может быть не один (несколько мониторов) — каждый со своей
# нумерацией строк, поэтому максимум считаем внутри блока. Блок кончается
# строкой с отступом не больше, чем у самого `icons:`, или концом файла.
awk -v list="$missing" '
function flush(   i, p) {
    if (!in_icons) return
    for (i = 1; i <= n; i++) {
        p = F[i]
        if (p == "" || (p in seen)) continue
        max++
        printf "%*s\"%s\":\n", key_indent, "", p
        printf "%*srow: %d\n", key_indent + 2, "", max
        printf "%*scol: %d\n", key_indent + 2, "", col
    }
    in_icons = 0
}
BEGIN { n = split(list, F, "\n") }
{
    line = $0
    indent = match(line, /[^ ]/) - 1
    if (line ~ /^[ ]*icons:[ ]*$/) {
        flush()
        in_icons = 1; key_indent = indent + 2; max = -1; col = 0
        delete seen
        print; next
    }
    if (in_icons) {
        if (line ~ /^[ ]*$/) { print; next }
        if (indent <= key_indent - 2) { flush(); print; next }
        if (match(line, /^[ ]*"[^"]+":[ ]*$/)) {
            p = line; sub(/^[ ]*"/, "", p); sub(/":[ ]*$/, "", p); seen[p] = 1
        }
        if (match(line, /^[ ]*row:[ ]*[0-9]+[ ]*$/)) {
            r = line; sub(/^[ ]*row:[ ]*/, "", r); r += 0
            if (r > max) max = r
        }
        if (match(line, /^[ ]*col:[ ]*[0-9]+[ ]*$/)) {
            c = line; sub(/^[ ]*col:[ ]*/, "", c); col = c + 0
        }
        print; next
    }
    print
}
END { flush() }
' "$layout" > "$tmp" || { rm -f "$tmp"; exit 0; }

# Пустой или укоротившийся результат не ставим: раскладка — чужие данные, и
# потерять её молча хуже, чем оставить значок не на месте.
[ -s "$tmp" ] || { rm -f "$tmp"; exit 0; }
[ "$(wc -c <"$tmp")" -ge "$(wc -c <"$layout")" ] || { rm -f "$tmp"; exit 0; }

write_as_owner "$layout" < "$tmp" \
    && echo "раскладка стола: $(echo "$missing" | grep -c . ) новых значка(ов) дописаны вниз ($home)"
rm -f "$tmp"
