#!/bin/sh
# Раскладка сеанса: us и ru, переключение Alt+Shift.
#
# Одно место на оба случая — старт сеанса (автозапуск XFCE,
# config/keyboard-autostart.desktop) и **переподключение по RDP**
# (/etc/xrdp/reconnectwm.sh). Второй случай и есть находка заказчика
# 2026-10-22: отключиться от сеанса не выходя из него, подключиться снова —
# и русской раскладки нет. Причина: xrdp при каждом подключении задаёт
# раскладку по данным клиента, а наши us,ru применялись только однажды, при
# старте сеанса: автозапуск второй раз не выполняется, xfce4-settings-daemon
# свои настройки заново не применяет.
#
# Значения правятся здесь и только здесь; `config/keyboard-layout.xml`
# (настройки xfconf) должен им соответствовать.
set -eu

# Переподключение зовёт нас без окружения сеанса — экран называем сами.
[ -n "${DISPLAY:-}" ] || DISPLAY=:10.0
export DISPLAY

# xrdp задаёт свою раскладку в момент подключения; делаем это после него.
[ "${1:-}" = "--after-reconnect" ] && sleep 2

setxkbmap -layout us,ru -variant , -option grp:alt_shift_toggle
# Отпечаток применённого — чтобы при следующей жалобе смотреть факт, а не
# гадать, дошла ли команда.
setxkbmap -query > /tmp/xkb-applied.log 2>&1 || true
