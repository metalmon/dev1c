    #[cfg(unix)]
    #[test]
    fn the_device_in_proc_locks_is_hexadecimal_not_decimal() {
        let line = "1: FLOCK ADVISORY WRITE 565 08:30:16571 0 EOF\n";
        assert!(parse_proc_locks(line, libc::makedev(8, 0x30) as u64, 16571), "minor 0x30 — это 48, и держат именно его");
        assert!(!parse_proc_locks(line, libc::makedev(8, 30) as u64, 16571), "десятичное чтение minor даёт чужое устройство");

        let lettered = "6: FLOCK ADVISORY WRITE 163 00:3f:591 0 EOF\n";
        assert!(parse_proc_locks(lettered, libc::makedev(0, 0x3f) as u64, 591), "буквы в minor — тоже шестнадцатеричные");
    }

    /// Признак обслуживания у разных комплектов — разный: сторож моста
    /// (`orphan::guard_owner`) обязан видеть живым ИМЕННО свой комплект, а не
    /// соседний той же учётной записи.
    ///
    /// Без `#[cfg]` и на обеих осях: до задачи 14 это свойство проверялось
    /// двумя разными тестами (на Linux — каталогом, на Windows — ключом), и
    /// расхождение между ними никого бы не насторожило. Путь комплекта
    /// участвует в обоих примитивах (`serving_mutex_name` берёт его в имя,
    /// `acquire_serving` на Linux держит `flock` на нём самом), поэтому
    /// утверждение одно.
    #[test]
    fn the_serving_mark_of_one_kit_never_collides_with_another() {
        let a = existing_dir("kit-a");
        let b = existing_dir("kit-b");
        let ga = acquire_serving(&Kit::at(&a)).unwrap().expect("первый комплект свободен");
        let gb = acquire_serving(&Kit::at(&b)).unwrap();
        assert!(gb.is_some(), "признак другого комплекта не должен видеть признак первого");
        // Отпускаем ДО удаления каталогов: `flock` на удалённом каталоге
        // остаётся в `/proc/locks` со своим номером inode, а ядро отдаёт этот
        // номер следующему созданному каталогу — соседний тест
        // (`allow::read_follows_the_connector`) ловил такую запись как
        // «владелец жив» примерно в одном параллельном прогоне из трёх.
        drop(ga);
        drop(gb);
        let _ = std::fs::remove_dir_all(&a);
        let _ = std::fs::remove_dir_all(&b);
    }

    /// **Признак обслуживания и замок отвечают на «чья это копия» ОДНИМ
    /// ключом** (красный тест круга правок 1 задачи 14).
    ///
    /// До этого круга замок перешёл на `account` (SID/uid), а признак
    /// остался на `clean(USERNAME)` — в одной задаче про единицу завелись
    /// две меры, точная и приблизительная, и разошлись бы они молча, на
    /// первой же учётной записи, чьё имя чистка теряет. Тест стоит на том,
    /// что взявший и спрашивающий обязаны считать учётную запись одним и тем
    /// же способом: разведи их — и `is_serving` перестанет видеть то, что
    /// взял `hold_serving`, то есть сторож моста (`orphan::guard_owner`)
    /// уведёт мост при живом коннекторе.
    ///
    /// Без `#[cfg]` и на обеих осях: ключ у примитивов разный (имя мьютекса
    /// там, путь `flock` тут), а вопрос один.
    #[test]
    fn the_serving_mark_and_the_lock_count_the_account_the_same_way() {
        let (_dir, kit) = kit_for_test();
        assert!(!is_serving(&kit).unwrap(), "признак никто не брал");
        let held = hold_serving(&kit).expect("признак свободен в начале теста");
        assert!(is_serving(&kit).unwrap(), "взявший и спрашивающий обязаны считать учётную запись одним способом");
        drop(held);
        assert!(!is_serving(&kit).unwrap(), "признак отпущен — и видно это тем же ключом");
    }

    #[test]
    fn the_serving_mark_lives_in_the_state_not_in_the_kit() {
        // Признак обслуживания на Linux держится на каталоге состояния
        // (`lock_target`). Он обязан лежать в состоянии пользователя и
        // никогда внутри общего комплекта (тот — только для чтения и один на
        // всех). Windows эта задача не трогает: там состояние по-прежнему при
        // комплекте.
        if cfg!(windows) {
            return;
        }
        let kit = crate::ops_host::wire_state(Kit::at(std::path::Path::new("/opt/dev1c-kit")));
        let lock_on = lock_target(&kit);
        assert!(!lock_on.starts_with(&kit.root), "{}", lock_on.display());
        assert!(lock_on.starts_with(crate::ops_host::state_dir()), "{}", lock_on.display());
    }
