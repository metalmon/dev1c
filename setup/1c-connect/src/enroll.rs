/// кавычек вокруг пустоты: сторона себя не назвала. Кавычки у названного стоят нарочно — имя сочиняет та сторона, и в кавычках видно,
/// где кончаются наши слова и начинаются её (вся защита — в докстроке `gui::save::permission_question`).
pub fn who_says(says_name: &SaysName) -> String {
    if says_name.is_empty() {
        "Компьютер без имени".to_string()
    } else {
        format!("«{says_name}»")
    }
}

