    /// **Одна копия — на учётную запись и на машину: ни комплект, ни сеанс в
    /// единицу не входят** (красный тест задачи 14, буквально из брифа).
    ///
    /// Без `#[cfg]` и на обеих осях нарочно: до этой задачи поведение на
    /// каждой оси проверялось своим набором, и расхождение между ними —
    /// Windows считал единицей «сеанс × учётку», Linux комплект — не ловил
    /// никто. Комплекты здесь РАЗНЫЕ, и это главное утверждение: прежний
    /// `flock` на каталоге состояния дал бы второй копии замок.
    ///
    /// Сеанс этим тестом не проверить ни на одной оси — два сеанса одной
