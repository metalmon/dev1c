//! Слова, которые приходится согласовывать с числом.
//!
//! Числа печатаются почти в каждой строке обеих программ, и «1 слота» в
//! отчёте заказчика читается так же, как опечатка в договоре: всё остальное
//! после этого кажется сделанным наспех.

/// Форма слова при числе: 1 слот, 2 слота, 5 слотов.
pub fn plural<'a>(n: u64, one: &'a str, few: &'a str, many: &'a str) -> &'a str {
    // Одиннадцать–четырнадцать проверяются первыми: у них последняя цифра
    // обманчива (11 — «слотов», хотя заканчивается на единицу).
    match (n % 100, n % 10) {
        (11..=14, _) => many,
        (_, 1) => one,
        (_, 2..=4) => few,
        _ => many,
    }
}

/// Число вместе со словом: `count(3, "слот", "слота", "слотов")` → «3 слота».
pub fn count(n: u64, one: &str, few: &str, many: &str) -> String {
    format!("{n} {}", plural(n, one, few, many))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_number_agrees_with_the_word_next_to_it() {
        let s = |n| count(n, "слот", "слота", "слотов");
        assert_eq!(s(1), "1 слот");
        assert_eq!(s(2), "2 слота");
        assert_eq!(s(5), "5 слотов");
        assert_eq!(s(21), "21 слот");
        assert_eq!(s(0), "0 слотов");
        // Второй десяток — исключение: по последней цифре вышло бы «11 слот».
        assert_eq!(s(11), "11 слотов");
        assert_eq!(s(12), "12 слотов");
        assert_eq!(s(114), "114 слотов");
    }

    #[test]
    fn the_words_we_actually_print_are_covered() {
        assert_eq!(count(1, "файл", "файла", "файлов"), "1 файл");
        assert_eq!(count(3, "агент", "агента", "агентов"), "3 агента");
        assert_eq!(count(1, "агент", "агента", "агентов"), "1 агент");
        assert_eq!(count(5, "проверка", "проверки", "проверок"), "5 проверок");
    }
}
