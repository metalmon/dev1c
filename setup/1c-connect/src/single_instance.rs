    /// Сеанс держателя спрашивается у ДВЕРИ, и это замер, а не рассуждение: замок взят — значит держим его мы, и сеанс обязан
    /// выйти наш. Падает он, если развалилась любая из трёх опор — стук, `GetNamedPipeServerProcessId` и `ProcessIdToSessionId`,
    /// — а чистое правило (`words_for_other_session`) про них не знает вовсе.
