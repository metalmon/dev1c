//! Узел этой машины: принимает входящие заявки и звонит зовущими карточками.
//!
//! Живёт в беке и окна не знает. Рассказывает о себе своим словарём (`peer_out::Out`), а кто его слушает — дело слушателя: сегодня это окно (`gui::launch`), завтра — `serve` из командной строки. До плана «Сопряжение переезжает в бек» узел стоял в `gui/`, и половина его шапки была про экран; переезд 15.11 это снял, и ни одной строки поведения при этом не поменялось.
//!
//! Проводка, и только она. Протокол (`enroll`), удержание потока (`channel`) и книга допуска (`enrolled`) написаны и проверены до этого файла; здесь они встречаются: узел поднимается, входящая заявка уезжает в `Out::Enroll` и ждёт ответа, а зовущая карточка звонит и возвращается после обрыва.
//!
//! **Почему своим потоком с своим рантаймом.** Подъём узла (`Node::with`) открывает сокет и выходит в сеть, `accept`/`dial` висят часами, а звать его из главного потока клиента нельзя: у окна этот поток — GPUI, и всё, что на нём ждёт, — это замершее окно. Приём тот же, которым живёт сеанс (`session::start_with_enabled`), и причина та же.
//!
//! **Один узел на процесс, а не по узлу на карточку.** Ключ узла — личность
//! МАШИНЫ (`node.rs`, `node.key` в каталоге состояния), и второй узел здесь
//! означал бы вторую личность у одного рабочего места. Принимающие карточки
//! и зовущие делят его: первым он нужен, чтобы принимать, вторым — чтобы
//! звонить.
//!
//! **Решения человека остаются у человека.** Этот поток не решает, пускать ли кого-то: он выпускает заявку наружу (`peer_out::Out::Enroll`) и ждёт ответа по одноразовому каналу (`enroll::Pending`). Как спросят человека — не его дело: в окне это диалог с отпечатком и кнопками (`gui::save::ask_permission`), в командной строке — `1c-connect requests`/`allow`/`decline` (задача 7 плана «Сопряжение переезжает в бек»), и второго мнения о допуске здесь нет.
//!
//! **Две копии на одной машине этот код умеет, а программа — пока нет.**
//! Канал, зачисление и код с петлёй рассчитаны ровно на этот случай
//! (`ticket::direct_with_loopback`), и двум копиям с РАЗНЫМИ каталогами
//! состояния они дают путь без интернета и без брандмауэра. Но вторую копию
//! не пускает замок единственного экземпляра: `single_instance::account`
//! заведён на учётную запись ОС, а не на каталог состояния, — и второй запуск уходит до того, как дойдёт сюда. Пускать ли
//! два экземпляра с разными каталогами, решает владелец: замок стоит там не
//! случайно (один `httpd.pid` на пользователя, одни порты рабочего места),
//! и снимать его «чтобы проверить» нельзя. Пока решения нет, этот путь
//! проверяется двумя машинами либо двумя учётными записями Windows.

