    /// `is_held` СПРАШИВАЕТ держателя, а не смотрит на существование
    /// объекта, и при этом ничем не владеет: держатель остаётся держателем
    /// всё время теста (находка ревью задачи 2 — проверка живости, которая
    /// сама занимает замок хоть на микросекунду, для соседнего проверяющего
    /// становится «занято — значит жив»).
    ///
    /// Без `#[cfg]` и на обеих осях: вопрос «жив ли держатель» один, и
    /// ответом на него больше не служат два разных объекта.
    #[test]
    fn is_held_asks_the_door_and_the_asking_takes_nothing() {
        let (_dir, kit) = kit_for_test();
        let user = unique("is-held");
        assert!(!is_held(&user), "никто не держал — владельца нет");
        let _held = acquire_at(&user, &kit, false).expect("замок свободен");
        assert!(is_held(&user), "владелец держит — is_held обязана увидеть это, спросив его");
        // Если бы `is_held` сама занимала замок, вторая попытка взять его
        // отказала бы по ДРУГОЙ причине или, хуже, далась бы. Держатель один
        // и тот же до конца теста.
        assert!(is_held(&user), "второй вопрос отвечает так же — спрашивающий ничего не отнял");
    }

    /// **Признак обслуживания и замок — ОДИН механизм**, и тест сверяет
    /// именно это (круг правок 2: прежняя его версия обещала сверку с
    /// замком, а сверяла взявшего и спрашивающего внутри самого признака).
    ///
    /// Дверь, которую отдал `acquire_at`, — это и есть взятый замок; что она
    /// обслуживает, читается тем же путём, которым читает `serves_our_kit`.
    /// Разведи их снова на два объекта — и первое же утверждение упадёт.
    ///
    /// Средний шаг важнее крайних: замок ВЗЯТ, а обслуживание ещё не
    /// объявлено — и ответ «нет». Он и отличает вопрос «жив ли держатель»
    /// (`is_held`, им живёт сторож моста) от вопроса «обслуживает ли он мой
    /// комплект» (`serves_our_kit`, им живёт разрешение агенту); сольёт их
    /// кто-нибудь в один — упадёт здесь.
    ///
    /// Без `#[cfg]` и на обеих осях.
    #[test]
    fn the_serving_mark_is_the_lock_itself() {
        let (_dir, kit) = kit_for_test();
        let account = unique("serving");
        let name = crate::door::door_name(&account);
        assert_eq!(crate::door::served_at(&name, &kit), crate::door::Served::No, "замка никто не держал — и обслуживать некому");
        let door = acquire_at(&account, &kit, false).expect("замок свободен");
        assert!(is_held(&account), "замок взят — держатель отвечает");
        assert_eq!(crate::door::served_at(&name, &kit), crate::door::Served::No, "замок взят, но обслуживание ещё не объявлено");
        door.show(crate::door::StatusView { serving: true, cards: None, kit: None });
        assert_eq!(
            crate::door::served_at(&name, &kit),
            crate::door::Served::Mine,
            "держатель объявил обслуживание — и видно это тем же ключом, что держит замок"
        );
        door.show(crate::door::StatusView { serving: false, cards: None, kit: None });
        assert_eq!(crate::door::served_at(&name, &kit), crate::door::Served::No, "выключил — видно сразу, без ожидания");
    }
