    /// Файл, который уже существует и открыт быть не может. Нужен одному
    /// тесту про права, а он только для Unix.
    #[cfg(unix)]
    fn existing_file(tag: &str) -> std::path::PathBuf {
        let p = std::env::temp_dir().join(format!("{}.toml", unique(tag)));
        std::fs::write(&p, "").unwrap();
        p
    }

    /// Отказ открыть замок называет ПУТЬ, а не отдаёт голый
    /// `Permission denied (os error 13)`: голая системная ошибка без единого
    /// слова о том, что вообще делалось, человеку не говорит ничего.
    ///
    /// Сторож вернулся в круге правок 4. Прежний стоял на замке рабочего
    /// места, который задача 14 увела на дверь; `lock_error` при этом
    /// осталась — её зовёт замок проекта, — а тест ушёл вместе со старым
    /// зовущим, и заодно оставил `existing_file` без зовущего (а она под
    /// `#[cfg(unix)]`, то есть на этой машине невидима: на линуксовом гейте
    /// CI это `dead_code` и красная сборка).
    #[cfg(unix)]
    #[test]
    fn a_permission_failure_names_the_path() {
        use std::os::unix::fs::PermissionsExt;
        let file = existing_file("perm");
        std::fs::set_permissions(&file, std::fs::Permissions::from_mode(0o000)).unwrap();
        // ponytail: в контейнере тесты иногда бегут от root — тогда права не
        // проверяются вовсе, и это не повод валить тест: просто ничего не
        // утверждаем про текст ошибки, раз её и не было.
        if let Err(err) = file_lock(&file) {
            let msg = err.to_string();
            assert!(msg.contains(&file.display().to_string()), "путь должен быть назван: {msg}");
        }
        std::fs::set_permissions(&file, std::fs::Permissions::from_mode(0o644)).unwrap();
        let _ = std::fs::remove_file(&file);
    }

