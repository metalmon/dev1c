/// Процесс httpd и его Job Object — держим на весь процесс коннектора, не
/// только на время вызова `start()`. Это наш собственный ребёнок (не
/// служба — без `-k`, см. `start`), поэтому Job действительно может его
/// убить: крах самого коннектора (не штатный «quit», а паника или снятие из
/// диспетчера задач) всё равно гасит httpd — ядро убивает всех, кто остался
/// в Job, когда закрывается последний описатель
/// (`JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE`, `crate::job::Job::new`).
#[cfg(windows)]
struct WindowsHttpd {
    child: std::process::Child,
    _job: job::Job,
}

#[cfg(windows)]
static WINDOWS_HTTPD: Mutex<Option<WindowsHttpd>> = Mutex::new(None);

/// Запуск без консольного окна: httpd — обычное консольное приложение, и
/// без этого флага каждый его запуск и остановка открывают человеку чёрное
/// окно поверх всего. Тот же приём, что у `common::docker::quiet`.
#[cfg(windows)]
fn no_window(cmd: &mut std::process::Command) {
    use std::os::windows::process::CommandExt;
    const CREATE_NO_WINDOW: u32 = 0x0800_0000;
    cmd.creation_flags(CREATE_NO_WINDOW);
}

/// Итог сверки личности процесса из pid-файла перед остановкой — ТРИ исхода,
/// не два: важно не только «гасить или нет», но и можно ли забыть сам
/// pid-файл как мёртвую запись (тем же правилом, что у `refuse_unless_ours`,
/// круг 5 исправления задачи 1).
///
/// - `Stop` — личность подтверждена, это наш httpd.
/// - `Foreign` — личность подтверждена ЧУЖОЙ: процесса нет вовсе (мёртв или
///   не хватило прав посмотреть), образ другой, или владелец другой. Во всех
///   трёх случаях запись в pid-файле мёртвая для НАС, и её можно забыть —
///   встать на неё больше нечему (решение ведущего, пункт 5 находки).
/// - `Unknown` — ни подтвердить, ни исключить не вышло (владельца не
///   добыть ни у кого из двоих). Закрываемся, а не открываемся: не гасим, но
///   и файл не трогаем — вдруг это и правда наш процесс.
///
/// Чистая функция, без похода в систему: добыча сведений
/// (`holder::image_of_pid`, `holder::owner_of_pid`) отдельно от решения, тем
/// же приёмом, что `ensure_state_decision`/`env_missing_of` в `ops_host.rs`.
///
/// **Отступление от буквального текста брифа задачи 7** (тот предлагал
/// сверять только имя образа): цена ошибки здесь — не утечка пароля
/// словами, а СНЯТИЕ ЧУЖОЙ ПРОГРАММЫ, и находка автоматической проверки
/// безопасности по кругу 4/5 (см. `holder::image_of_pid`/`owner_of_pid`)
/// прямо называет эту задачу третьим потребителем ОБОИХ барьеров: образ
/// один не держит — комплект лежит в корне диска, и сосед по терминальному
/// серверу запускает НАШ ЖЕ `httpd.exe` со своим конфигом, путь образа
/// совпадает идеально. Владелец — барьер, который без наших учётных данных
/// не обойти.
// Тексты `Foreign`/`Unknown` читают только тесты (`should_stop_*` ниже) —
// `kill_tracked` после самого решения отличает друг от друга лишь то, чистит
// ли он pid-файл, а причину не печатает никуда (нет журнала без `ctx`, а
// плодить его здесь ради одной строки — лишнее: порт, занятый не нами,
// `revert_apply` и так называет отдельным предупреждением).
#[cfg(windows)]
#[derive(Debug)]
#[allow(dead_code)]
enum StopDecision {
    Stop,
    Foreign(String),
    Unknown(String),
}

#[cfg(windows)]
fn should_stop(image: Option<&Path>, owner: Option<&str>, expected: &OurHttpd) -> StopDecision {
    let Some(image) = image else {
        return StopDecision::Foreign("процесс из pid-файла не опознать (его уже нет, или не хватило прав посмотреть)".to_string());
    };
    if !holder::same_image(&expected.image, image) {
        return StopDecision::Foreign(format!(
            "это не наш httpd — его образ {}, наш {}",
            image.display(),
            expected.image.display()
        ));
    }
    match (expected.owner.as_deref(), owner) {
        (Some(e), Some(o)) if !holder::same_owner(e, o) => {
            StopDecision::Foreign(format!("владелец процесса не совпал (его {o}, наш {e}) — это не наш httpd, даже если запущен нашим файлом"))
        }
        (Some(_), Some(_)) => StopDecision::Stop,
        _ => StopDecision::Unknown("не удалось установить владельца — сверять не с чем".to_string()),
    }
}

/// Абсолютный путь системного инструмента (каталог — `GetSystemDirectoryW`,
/// не угаданная строка и не `%SystemRoot%`) — круг исправления ревью: вызов
/// по одному короткому имени (`Command::new("taskkill")`) искал бы программу
/// по `PATH`, а `PATH` — список снаружи процесса, который сосед способен
/// подвинуть так, что по имени найдётся чужой `taskkill.exe` раньше
/// системного; для операции, которая СНИМАЕТ ПРОЦЕСС, доверять поиску по
/// имени нельзя. `%SystemRoot%` не годится по той же причине — переменная
/// среды приходит снаружи процесса; `GetSystemDirectoryW` — системный
/// вызов, не переменная, и называет каталог, из которого Windows запускает
/// свои инструменты сама.
///
/// `None` — каталог не добыть (практически невозможная машина); вызывающий
/// обязан отказать словами, а не угадывать путь.
#[cfg(windows)]
fn system_tool(name: &str) -> Option<PathBuf> {
    use windows_sys::Win32::System::SystemInformation::GetSystemDirectoryW;
    let mut buf = [0u16; 1024];
    let len = unsafe { GetSystemDirectoryW(buf.as_mut_ptr(), buf.len() as u32) };
    if len == 0 || len as usize >= buf.len() {
        return None;
    }
    Some(PathBuf::from(String::from_utf16_lossy(&buf[..len as usize])).join(name))
}

/// Процесс умер в ответ на снятие? Опрашиваем `holder::image_of_pid` — тем
/// же системным вызовом, которым добывали личность: пока он отдаёт `Some`,
/// процесс жив. Таймаут — 2 с, с запасом: `taskkill /F` убивает синхронно
/// изнутри себя, редкий случай промедления (система занята) не повод висеть
/// дольше.
#[cfg(windows)]
fn wait_for_death(pid: u32) -> bool {
    for _ in 0..20 {
        if holder::image_of_pid(pid).is_none() {
            return true;
        }
        std::thread::sleep(std::time::Duration::from_millis(100));
    }
    false
}

/// Применяет решение `should_stop` к pid-файлу — круг исправления ревью:
/// прежде `kill_tracked` выбрасывал исход снятия (`let _ = kill.output();`)
/// и забывал pid-файл БЕЗУСЛОВНО для `Stop`, даже когда снять не вышло —
/// единственная запись, по которой мёртвый-не-до-конца процесс можно было
/// опознать, исчезала, а следующий `start()` написал бы свежую, оставив
/// прежний httpd неопознаваемым навсегда. И `Unknown` некому было сказать
/// словами — отказ проглатывался молча.
///
/// Теперь: `Stop` забывает файл ТОЛЬКО когда `kill` подтвердил смерть
/// (вызывает его и сообщает исход, а не угадывает по коду возврата
/// `taskkill`, который и для «уже нет такого процесса» может быть
/// успешным); не подтвердил — отказ словами, файл остаётся как есть.
/// `Unknown` теперь тоже отказ словами, а не молчание. `Foreign` — как и
/// был: мёртвая для нас запись забывается, процесс не трогаем.
///
/// `kill` — параметром (`impl FnOnce(u32) -> bool`, true — подтверждена
/// смерть), а не прямой вызов `taskkill` внутри: тест подаёт свой исход, не
/// требуя процесса, который и правда сопротивляется `taskkill` (такой
/// непросто и небезопасно устроить в юнит-тесте) — тот же приём, что у
/// `wait_until` рядом (условие параметром).
#[cfg(windows)]
fn apply_stop_decision(decision: StopDecision, pid: u32, pid_file: &Path, kill: impl FnOnce(u32) -> bool) -> Result<(), String> {
    match decision {
        StopDecision::Stop => {
            if kill(pid) {
                forget_stale_pid_file(pid_file);
                Ok(())
            } else {
                Err(format!("процесс pid {pid} не остановлен — taskkill не подтвердил смерть, pid-файл оставлен как есть"))
            }
        }
        StopDecision::Foreign(_) => {
            forget_stale_pid_file(pid_file);
            Ok(())
        }
        StopDecision::Unknown(reason) => Err(reason),
    }
}

/// Гасит отслеженный httpd, а если он не отслежен в этом процессе (коннектор
/// перезапустился без чистого выхода, или гасим публикацию прошлого сеанса)
/// — по pid-файлу, проверив личность процесса (`should_stop`) прежде чем
/// кого-либо убивать.
///
/// **`-k stop` здесь не живёт вовсе — замер, не теория.** 2.11.2026 поднял
/// httpd из комплекта на выброшенном порту 47901 конфигом нашей же формы и
/// позвал `httpd.exe -f <conf> -k stop`: он напечатал «The 'Apache2.4'
/// service is not started» и ничего не сделал — консольный экземпляр
/// (`-f <conf>`, без `-k start`) не слушает команды службы, потому что
/// службой не является. Родителя пришлось снимать принудительно, а рабочий
/// ребёнок остался сиротой и жил, пока я не снял и его. На Linux `-k stop`
/// остаётся (см. `stop` ниже) — туда публикацией действительно ведает
/// система (`apache2 -k start` демонизируется в системную сессию).
///
/// **Гасим дерево, не один pid.** `mpm_winnt` держит два процесса —
/// родителя (его pid и лежит в `PidFile`) и рабочего ребёнка; слушающим
/// сокетом владеет РОДИТЕЛЬ (замер: `PidFile` = 23668,
/// `Get-NetTCPConnection -State Listen -LocalPort 47901 | Select
/// OwningProcess` = 23668), а ребёнок — его прямой потомок и переживает
/// смерть родителя (измерено тем же замером). `taskkill /PID <pid> /T /F` —
/// штатное средство Windows для дерева процессов, прав администратора не
/// требует для процесса в своей же сессии; писать обход `Toolhelp32` самим
/// незачем (`taskkill` и есть тот обход, готовый).
///
/// Только Windows: на Linux остановкой ведает `-k stop` по своему файлу
/// идентификатора — там им действительно ведает система.
///
/// Возвращает отказ словами — круг исправления ревью: прежде исход
/// `taskkill` выбрасывался (`let _ = kill.output();`), а `Unknown` от
/// `should_stop` было некому сказать. Теперь оба случая — `Err` с причиной,
/// и вызывающий (`stop`) обязан довести её до человека, не проглотить.
#[cfg(windows)]
fn kill_tracked(p: &Paths, expected: &OurHttpd) -> Result<(), String> {
    if let Some(mut h) = WINDOWS_HTTPD.lock().unwrap().take() {
        let _ = h.child.kill();
        let _ = h.child.wait();
        return Ok(());
    }
    let Some(pid) = our_httpd_pid(&p.pid) else {
        return Ok(()); // pid-файла нет или он не число — гасить нечего.
    };
    let image = holder::image_of_pid(pid);
    let owner = holder::owner_of_pid(pid);
    let decision = should_stop(image.as_deref(), owner.as_deref(), expected);
    apply_stop_decision(decision, pid, &p.pid, |pid| {
        let Some(taskkill) = system_tool("taskkill.exe") else { return false };
        let mut kill = std::process::Command::new(&taskkill);
        kill.args(["/PID", &pid.to_string(), "/T", "/F"]);
        no_window(&mut kill);
        let _ = kill.output();
        wait_for_death(pid)
    })
}

/// Поднимает HTTP-сервис: httpd.exe — наш прямой ребёнок, в консольном
/// режиме (`-f <conf>`, без `-k`) — с `-k start` httpd передаёт работу
/// диспетчеру служб, и выживший процесс нам уже не принадлежит, а Job-бэкстоп
/// держит нечего. Идемпотентно: уже отслеженный процесс сперва гасится —
/// повторный вызов после смены базы не падает на «порт занят».
///
/// `lifetime` решает, что происходит с httpd, когда этот процесс
/// заканчивается (штатно или крахом): `Detached` — ничего, сервис остаётся
/// жить сам по себе (`child` просто роняется — `Drop` у `std::process::Child`
/// закрывает только наш хэндл, самого процесса не касается); `WithCaller` —
/// кладём в Job Object с `JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE`, и уход
/// последнего хэндла (конец этого процесса) гасит httpd вместе с ним.
#[cfg(windows)]
pub fn start(p: &Paths, lifetime: Lifetime, kit_root: &Path) -> Result<(), String> {
    use std::process::Stdio;
    kill_tracked(p, &OurHttpd::of(kit_root))?;
    let bin = httpd_binary(p);
    let mut cmd = std::process::Command::new(&bin);
    // В /dev/null, не в пайп: пайп, который некому вычитывать, блокирует
    // демона навсегда, если тот решит в него что-то написать — а мы либо не
    // ждём выхода вовсе (сервер должен остаться жить), либо ждём только
    // короткую паузу ниже.
    cmd.args(["-f", &p.conf.to_string_lossy()]).stdout(Stdio::null()).stderr(Stdio::null());
    no_window(&mut cmd);
    let mut child = cmd.spawn().map_err(|e| format!("{} не запустился: {e}", bin.display()))?;
    // Короткая пауза — дать серверу шанс упасть сразу (битый конфиг, занятый
    // порт), прежде чем считать процесс запущенным и уходить.
    std::thread::sleep(std::time::Duration::from_millis(300));
    if let Ok(Some(status)) = child.try_wait() {
        return Err(format!("httpd завершился сразу (код {:?}): {}", status.code(), error_log_tail(&p.log, 5)));
    }
    match lifetime {
        Lifetime::Detached => {
            // Публикация базы, не ребёнок установщика: намеренно не кладём
            // процесс ни в Job, ни в WINDOWS_HTTPD — выход этого процесса (в
            // т.ч. крах) httpd не касается. Остановить его позже сможет
            // kill_tracked() по pid-файлу (`should_stop` + `taskkill /T`).
            drop(child);
        }
        Lifetime::WithCaller => {
            let Some(job) = job::Job::new() else { return Err("не удалось создать Job Object для httpd".to_string()) };
            // Отказ назначения здесь — не отказ запуска: httpd уже слушает, и
            // врать «не запустился» нельзя. Вторая линия у него своя, в
            // отличие от ребёнка моста: процесс лежит в `WINDOWS_HTTPD`, и
            // именно оттуда его гасит `kill_tracked` первым делом (`kill()` +
            // `wait()`), раньше, чем дело дойдёт до pid-файла. Поэтому
            // значение намеренно выброшено, а не оставлено молчать по
            // забывчивости.
            let _ = job.assign_std(&child);
            *WINDOWS_HTTPD.lock().unwrap() = Some(WindowsHttpd { child, _job: job });
        }
    }
    Ok(())
}

/// Гасит сервис. Отслеженный в этом же процессе (`WINDOWS_HTTPD`) — наш
/// собственный ребёнок, `kill()` плюс `wait()` и есть проверка «процесс
/// действительно остановлен» (`wait()` возвращает только после выхода).
/// Иначе — по pid-файлу (`kill_tracked`/`apply_stop_decision`): `Err` словами,
/// если снять не вышло или личность не установить, — не угадывание и не
/// молчаливый успех. Про занятый порт эта функция не говорит ничего: тот,
/// кто там окажется после подтверждённого снятия, — не наша забота здесь
/// (см. `httpd_responds` выше).
#[cfg(windows)]
pub fn stop(p: &Paths, kit_root: &Path) -> Result<(), String> {
    kill_tracked(p, &OurHttpd::of(kit_root))
}

