/// Сколько ждём выхода в сеть, прежде чем выдавать код.
///
/// Ждём, потому что до выхода в сеть узел не знает ни своего релея, ни
/// адресов, которыми его видно, — а код, выданный раньше, донёс бы до той
/// стороны один ключ, то есть дозвон только поиском через серверы n0. Ждём
/// НЕ бесконечно: машина без интернета в сеть не выйдет никогда, а код по
/// петле ей всё равно нужен (мерка готовности — две копии на одной машине).
const ONLINE_WAIT: Duration = Duration::from_secs(10);

/// Как эту машину найти снаружи — ровно то, что уезжает в код подключения.
///
/// Считается один раз, когда узел вышел в сеть, и живёт в `Peer` под замком:
/// код выдаётся на главном потоке окна (`panel::issue_code`), а знает это
/// только поток узла.
#[derive(Debug, Clone, Default)]
pub struct Reach {
    pub relay: Option<String>,
    pub direct: Vec<String>,
}

/// Ручка на поток узла — то, что живёт в `Ui` и чем окно его просит.
///
/// Остановки у потока нет нарочно, тем же доводом, которым её нет у
/// `channel::keep_calling`: принимать входящие надо всё время, пока программа
/// работает, а «выключить обслуживание» — это про вызовы агента
/// (`Ui::enabled`), не про то, доходит ли до человека заявка на зачисление.
/// Поток кончается с процессом.
#[derive(Clone)]
pub struct Peer {
    cmd: tokio::sync::mpsc::UnboundedSender<Cmd>,
    reach: Arc<Mutex<Option<Reach>>>,
}

/// Что окно умеет попросить у потока узла.
enum Cmd {
    /// Позвонить зовущей карточкой. Пустой `code` — переподключение по
    /// запомненному партнёру (`Partners`), непустой — первая заявка.
    Dial { card: CardId, name: String, code: String },
    /// Снять поток зачисленной стороны ПРЯМО СЕЙЧАС, сказав ей словами.
    ///
    /// Иначе отзыв действовал бы только на следующем круге той стороны, а
    /// спека требует немедленности: `Book::enrolled_to` читает диск на каждое
    /// подключение именно затем, чтобы «Отозвать» срабатывало сразу, — и
    /// живой поток, который переживает отзыв, эту немедленность отменяет.
    Revoke { card: CardId, peer: EndpointId },
    /// Попрощаться со ВСЕМИ живыми разговорами — программа уходит.
    ///
    /// Канал, закрытый молча, читается той стороной как ОБРЫВ (`channel::
    /// hold` отдаёт `Gone::Broken` на любую ошибку чтения), а обрыв она
    /// повторяет: `keep_calling` звонит снова и показывает «подключается
    /// снова» — вечно, потому что звонить уже некуда. Прощание словами
    /// превращает это в `Stopped::Farewell`: круги прекращаются, и человек
    /// читает «Та сторона закрыла программу».
    ///
    /// `done` — обычный `std::sync::mpsc`, а не `oneshot`: ждёт его ГЛАВНЫЙ
    /// поток окна на выходе, и ждать он умеет только по-настоящему, со
    /// сроком.
    ByeAll { done: std::sync::mpsc::Sender<()> },
}

impl Peer {
    /// Как нас найти — для кода подключения. `None` — узел ещё не поднялся
    /// или не вышел в сеть; код тогда выдаётся без адресов, как и до этой
    /// задачи.
    pub fn reach(&self) -> Option<Reach> {
        self.reach.lock().unwrap_or_else(|e| e.into_inner()).clone()
    }

    /// Позвонить карточкой. Отказ — только «поток узла кончился», то есть
    /// случай, в котором звонить нечем вовсе.
    pub fn dial(&self, card: &CardId, name: &str, code: &str) -> Result<(), String> {
        self.cmd
            .send(Cmd::Dial { card: card.clone(), name: name.to_string(), code: code.to_string() })
            .map_err(|_| "Программа не вышла в сеть — подключиться нечем. Перезапустите её.".to_string())
    }

    /// Снять живой поток отозванной стороны. Молча: запись об отзыве уже
    /// сделана и уже сказана словами (`panel::revoke_party`), а живого потока
    /// у этой стороны могло и не быть вовсе — тогда снимать нечего, и это не
    /// беда.
    pub fn revoked(&self, card: &CardId, peer: EndpointId) {
        let _ = self.cmd.send(Cmd::Revoke { card: card.clone(), peer });
    }

    /// Попрощаться со всеми живыми разговорами и ДОЖДАТЬСЯ, пока прощания
    /// уедут. `false` — срок вышел, а кто-то ещё не договорил.
    ///
    /// Ждать обязательно: прощание — это записанный кадр, а записанный кадр
    /// выбрасывается, если процесс уйдёт раньше, чем та сторона признает его
    /// доехавшим (`channel::settle`, и вся беда, ради которой он заведён).
    /// Ждать НЕ бесконечно по тому же правилу, которым живут остальные
    /// ожидания выхода: застрявшее прощание не должно держать «Выход».
    ///
    /// Потока узла нет (его не подняли или он кончился) — прощаться не с кем
    /// и не чем, и это успех, а не отказ: иначе каждый выход без узла стоил
    /// бы человеку полного срока ожидания впустую.
    pub fn bye_all(&self, wait: Duration) -> bool {
        let (done, waited) = std::sync::mpsc::channel();
        if self.cmd.send(Cmd::ByeAll { done }).is_err() {
            return true;
        }
        waited.recv_timeout(wait).is_ok()
    }
}

/// Поднимает поток узла и отдаёт ручку на него.
///
/// Возвращается сразу: сам узел поднимается в потоке, и о том, поднялся ли он,
/// говорит строка журнала. Иначе открытие окна ждало бы сеть.
pub fn start(kit: &Kit, tx: UnboundedSender<Ev>) -> Peer {
    let (cmd, rx) = tokio::sync::mpsc::unbounded_channel();
    let reach = Arc::new(Mutex::new(None));
    let (kit_in, reach_in, tx_in) = (kit.clone(), reach.clone(), tx.clone());
    std::thread::spawn(move || {
        let rt = match tokio::runtime::Runtime::new() {
            Ok(rt) => rt,
            Err(e) => {
                say(&tx_in, Kind::Fail, format!("Не удалось выйти в сеть: {e}"));
                return;
            }
        };
        rt.block_on(serve(kit_in, tx_in, reach_in, rx));
    });
    Peer { cmd, reach }
}

/// Вся жизнь потока узла: поднять, объявить себя, принимать входящие,
/// звонить зовущими карточками.
async fn serve(kit: Kit, tx: UnboundedSender<Ev>, reach: Arc<Mutex<Option<Reach>>>, mut cmds: tokio::sync::mpsc::UnboundedReceiver<Cmd>) {
    let node = match Node::start(kit.state()).await {
        Ok(node) => node,
        Err(e) => {
            say(&tx, Kind::Fail, e);
            return;
        }
    };
    // Срок, а не бесконечное ожидание: без интернета `online` не вернётся
    // никогда, а принимать по петле и по локальной сети узел умеет уже сейчас.
    let _ = tokio::time::timeout(ONLINE_WAIT, node.endpoint().online()).await;
    let seen = look(&node);
    *reach.lock().unwrap_or_else(|e| e.into_inner()) = Some(seen);
    let channels = Channels::default();
    let live = Live::default();
    tokio::spawn(accepting(node.clone(), channels.clone(), kit.clone(), tx.clone(), live.clone()));
    let mut calls: HashMap<CardId, tokio::task::JoinHandle<()>> = HashMap::new();
    // Карточки, у которых партнёр уже записан, звонят САМИ, без щелчка:
    // человек разрешил подключение однажды, и перезапуск программы не повод
    // просить его нажать «Подключиться» ещё раз (спека контракта,
    // «Что хранится после»).
    match Partners::open(kit.state()) {
        Ok(partners) => {
            // Имя карточки берётся из настроек и нужно ТОЛЬКО для слов в журнал: сопоставляется карточка ключом, который партнёр и
            // назвал. Карточки в настройках уже нет (её удалили, а партнёр остался) — зовём ключом вместо имени: честнее, чем молчать.
            let names = card_names(&kit);
            for (card, _) in partners.all() {
                let name = names.get(&card).cloned().unwrap_or_else(|| card.to_string());
                start_call(&node, &channels, &kit, &tx, &mut calls, Dialling { id: card, name }, String::new());
            }
        }
        Err(e) => say(&tx, Kind::Fail, e),
    }
    while let Some(cmd) = cmds.recv().await {
        match cmd {
            Cmd::Dial { card, name, code } => start_call(&node, &channels, &kit, &tx, &mut calls, Dialling { id: card, name }, code),
            Cmd::Revoke { card, peer } => {
                // Признак базы для слов отзыва — это и есть ключ отзываемой карточки (решение владельца 10.11). Прежде он искался
                // перебором по настройкам (чтение файла плюс поиск по имени), и на непрочитанных настройках или переименованной
                // карточке уезжал пустым. Искать больше нечего: он уже на руках.
                for reins in live.cut(peer, &card) {
                    let card = card.clone();
                    tokio::spawn(async move { reins.revoke(&card, REVOKED_TEXT).await });
                }
            }
            // Прощания идут ВМЕСТЕ, а не одно за другим: каждое ждёт
            // подтверждения до `channel::FAREWELL_PATIENCE`, и очередь из
            // пяти зачисленных сторон стоила бы человеку пяти сроков на
            // «Выходе» (минорная находка ревью задачи 8). Ответ уходит
            // ПОСЛЕ: тот, кто ждёт, ждёт именно договорённости.
            Cmd::ByeAll { done } => {
                let all = live.drain();
                futures::future::join_all(all.into_iter().map(|reins| reins.bye(Refuse::new(code::CLOSED, channel::WINDOW_CLOSED)))).await;
                let _ = done.send(());
            }
        }
    }
}

/// Слова отзыва той стороне. Причина и совет, как велит раздел «Ошибки»
/// спеки: без совета причина человеку не нужна.
const REVOKED_TEXT: &str =
    "Вам больше не разрешают подключаться к этой базе.\nЧеловек за тем компьютером снял разрешение для этого рабочего места.\n\
                            Позвоните ему и попросите новый код, если доступ нужен снова.";

/// Один живой разговор принимающей стороны: вожжи его управляющего потока и
/// карточка, которую он обслуживает.
///
/// `card` — `Option`, и это не удобство, а честность: имя карточки местное и
/// по каналу не ездит, мы сопоставляем его обратно по признаку базы, и
/// сопоставление может не сойтись (человек правил карточки под живым
/// разговором, настройки не прочлись). Пустая строка на этом месте врала бы,
/// что карточка известна и называется «», — и отзыв по такому потоку не
/// находил бы его никогда.
struct Talk {
    /// Номер разговора — им он и снимается с учёта. Нужен затем, что у одной
    /// стороны к одной карточке может идти не один поток (переподключение,
    /// чей прежний поток ещё не осыпался), и снимать надо СВОЙ, а не
    /// «какой-нибудь с тем же именем».
    id: u64,
    /// Карточка, которую обслуживает этот поток, — ОДНА, и это свойство типа.
    ///
    /// Прежде здесь лежал список: сторона, зачисленная к нескольким карточкам
    /// этой машины, возвращалась одним потоком, и `enroll::Outcome::Already`
    /// приносил несколько баз сразу. Поток числился за всеми ними, и отзыв
    /// любой из них резал его целиком — то есть отзыв одной карточки рвал связь
    /// по остальным, прямо против спеки. Теперь `Already` несёт ОДНУ базу, и
    /// списка здесь больше нет: делить у потока нечего, потому что делить не из
    /// чего.
    ///
    /// `None` — карточка не опознана вовсе; такой поток режется любым отзывом этой стороны (`cut_these`).
    ///
    /// **Сегодня этого значения здесь НЕ БЫВАЕТ, и сказано это прямо** (Important повторного ревью всей ветки: мёртвая защита, описанная
    /// как живая, — хуже, чем снятая). Ключ карточки приходит из исхода зачисления (`enroll::Outcome`), а тот собирается по тому же самому
    /// списку принимающих карточек, в котором его потом и ищут (`serving`): один снимок, одно чтение настроек, и промахнуться нечем.
    ///
    /// Остаётся он не на всякий случай, а потому, что ТИПОМ это не выражено: чтобы `None` стало невыразимым, исход зачисления должен нести
    /// саму карточку, а не её ключ, — и до тех пор `serving` возвращает `Option`, который кто-то обязан разобрать. Разобран он так, как
    /// разбирается всякое «не знаю» на вопросе о допуске в этом проекте: поток, про который нельзя доказать, что он обслуживает ДРУГУЮ
    /// карточку, держать после отзыва не за что (`cut_these`, `keep_holding`). То есть защита мёртвая, но не бесплатная ошибка: оживи этот
    /// путь — и он пойдёт в сторону запрета.
    card: Option<CardId>,
    reins: Reins,
}

/// Живые разговоры принимающей стороны — по СТОРОНЕ, а не по карточке.
///
/// **Почему по стороне (находка проверки безопасности на коммит задачи 9).**
/// Прежде ключом была пара «имя карточки + ключ стороны», а имя бралось
/// перебором по признаку базы и при неудаче оказывалось пустым. Поток,
/// заведённый под пустым или не тем именем, при отзыве не находился и
/// переживал собственный отзыв — то есть отзыв перестаёт быть немедленным
/// ровно в том случае, когда он важнее всего. Ключ стороны подделать нельзя:
/// его доказал сам iroh.
///
/// Отзыв режет каждый поток ЭТОЙ стороны, который держит отозванную
/// карточку, — и те, у которых имени нет вовсе: поток, про который нельзя
/// доказать, что он обслуживает другую карточку, держать после отзыва не за
/// что. Соседние стороны и соседние карточки той же стороны не трогаются
/// (к одной карточке зачисляют сколько угодно сторон, решение владельца
/// 1.11, и отзыв адресуется ОДНОЙ — той, чей отпечаток человек видел).
///
/// Обычный `std::sync::Mutex`, не `tokio`: его держат на одно взятие-изъятие
/// без единого `await` внутри, а сама отправка прощания идёт уже снаружи
/// замка.
#[derive(Clone, Default)]
struct Live {
    talks: Arc<Mutex<HashMap<EndpointId, Vec<Talk>>>>,
    next: Arc<std::sync::atomic::AtomicU64>,
}

impl Live {
    /// Запомнить разговор. Возвращает его номер — им он и снимается
    /// (`forget`).
    fn remember(&self, peer: EndpointId, card: Option<CardId>, reins: Reins) -> u64 {
        let id = self.next.fetch_add(1, Ordering::SeqCst);
        self.talks.lock().unwrap_or_else(|e| e.into_inner()).entry(peer).or_default().push(Talk { id, card, reins });
        id
    }

    /// Снять разговор с учёта — присмотр за ним кончился. Уже снятого
    /// (отзывом) здесь нет, и это не беда.
    ///
    /// Вожжи возвращаются наружу, а не падают здесь: падать им положено ВНЕ
    /// замка — их `Drop` ничего не ждёт, но держать чужой замок дольше
    /// нужного незачем.
    fn forget(&self, peer: EndpointId, id: u64) -> Option<Reins> {
        let mut held = self.talks.lock().unwrap_or_else(|e| e.into_inner());
        let rows = held.get_mut(&peer)?;
        let at = rows.iter().position(|t| t.id == id)?;
        let gone = rows.remove(at);
        if rows.is_empty() {
            held.remove(&peer);
        }
        Some(gone.reins)
    }

    /// Вожжи всех разговоров этой стороны, которые отзыв карточки обязан
    /// снять (`cut_these` решает, какие именно). Снятые тут же уходят с
    /// учёта: второй отзыв той же карточки резать уже нечего.
    fn cut(&self, peer: EndpointId, card: &CardId) -> Vec<Reins> {
        let mut held = self.talks.lock().unwrap_or_else(|e| e.into_inner());
        let Some(rows) = held.get_mut(&peer) else {
            return Vec::new();
        };
        let doomed = cut_these(&rows.iter().map(|t| t.card.clone()).collect::<Vec<_>>(), card);
        // С конца: удаление по месту не должно сдвигать места, которые ещё
        // предстоит удалить.
        let mut out: Vec<Reins> = doomed.into_iter().rev().map(|at| rows.remove(at).reins).collect();
        if rows.is_empty() {
            held.remove(&peer);
        }
        out.reverse();
        out
    }

    /// Забрать ВСЕ живые разговоры всех сторон — программа уходит, и дальше
    /// присмотра за ними не будет ни у кого.
    ///
    /// Книга пустеет тем же движением: уходя, мы прощаемся ровно один раз, а
    /// вожжи, оставшиеся в книге после прощания, — это вожжи потока, которого
    /// уже нет.
    fn drain(&self) -> Vec<Reins> {
        let mut held = self.talks.lock().unwrap_or_else(|e| e.into_inner());
        held.drain().flat_map(|(_, rows)| rows.into_iter().map(|t| t.reins)).collect()
    }

    /// Есть ли ещё живой разговор под этим номером. Нужно одному читателю —
    /// проверке щели между решением человека и записью вожжей
    /// (`answering`): если отзыв уже забрал наш разговор, рвать его второй
    /// раз не надо.
    fn alive(&self, peer: EndpointId, id: u64) -> bool {
        let held = self.talks.lock().unwrap_or_else(|e| e.into_inner());
        held.get(&peer).is_some_and(|rows| rows.iter().any(|t| t.id == id))
    }
}

/// Какие разговоры одной стороны режет отзыв карточки `card` — чистое
/// решение, и всё, что в отзыве можно решать неверно, решается здесь.
///
/// Режутся два случая: разговор ЭТОЙ карточки и разговор, карточка которого
/// неизвестна (`None`). Второй — не перестраховка: карточка сопоставляется
/// обратно по признаку базы, и не сошлась она только там, где настройки под
/// живым разговором изменились или не прочлись. Про такой поток нельзя
/// доказать, что он обслуживает ДРУГУЮ карточку, а отзыв обязан действовать
/// сразу — значит держать его после отзыва не за что.
///
/// Разговоры соседних карточек той же стороны не трогаются вовсе: человек
/// снял доступ к одной базе, а не ко всем. Прежде это было неправдой для
/// потоков, за которыми числилось несколько карточек: отзыв любой из них резал
/// такой поток целиком. Числиться за несколькими поток больше не может
/// (`Talk::card`), и правило держится типом, а не обещанием.
fn cut_these(held: &[Option<CardId>], card: &CardId) -> Vec<usize> {
    held.iter().enumerate().filter(|(_, mine)| mine.as_ref().is_none_or(|one| one == card)).map(|(at, _)| at).collect()
}

/// Держать ли только что зачисленный разговор — проверка щели между решением
/// человека и записью вожжей (находка проверки безопасности).
///
/// Щель настоящая: `accept_side` уже вернул «зачислен», а в книге живых
/// разговоров вожжей ещё нет. Отзыв, случившийся в эти микросекунды, не
/// находит чего рвать, запись об отзыве ложится в книгу допуска — и поток
/// живёт дальше, переживая собственный отзыв. Поэтому после записи вожжей
/// допуск спрашивается у книги ЕЩЁ РАЗ, и ответ разбирается здесь: отзыв
/// либо увидит наши вожжи, либо эта проверка увидит отзыв, третьего порядка
/// у двух событий нет.
///
/// Безымянный разговор не держится: проверить его допуск нечем — `enrolled_to`
/// спрашивают ключом карточки, — а «не знаю» на вопросе о допуске значит
/// «нет» везде в этом проекте. Безымянных разговоров сегодня не бывает вовсе
/// (`Talk::card`, там сказано, почему и почему разбор всё-таки стоит), и эта
/// ветка — не живая защита, а сторона, в которую обязан ошибаться невыразимый
/// типом случай.
///
/// На входе — ответ книги по карточке потока: `None` значит «карточка не
/// опознана», `Some(false)` — «разрешение сняли в щель». Прежде здесь лежал
/// список и свёртка «все на месте»: поток мог числиться за несколькими
/// карточками. Числиться так он больше не может (`Talk::card`), и свёртке
/// свернуть нечего.
fn keep_holding(seen: Option<bool>) -> bool {
    seen == Some(true)
}

/// Зовущая карточка для потока звонка: ключ, которым её сопоставляют, и имя, которым о ней говорят человеку.
///
/// Одним значением, а не двумя доводами рядом в каждой подписи: два довода на одно понятие однажды разъезжаются (передал ключ одной,
/// имя другой — и человек читает в журнале не ту карточку), а три функции звонка от них разом перешли предел `clippy::too_many_arguments`
/// — предел и назван затем, чтобы такое заметили.
#[derive(Clone)]
struct Dialling {
    /// Ключ — им карточка сопоставляется везде: партнёр, книга, слово состояния (`cfg::CardId`).
    id: CardId,
    /// Имя — ТОЛЬКО для слов человеку в журнал.
    name: String,
}

/// Заводит звонок карточки, заменяя прежний, если он ещё идёт.
///
/// Замена, а не второй звонок рядом: карточка одна, и два звонка по ней
/// означали бы два управляющих потока, из которых слово состояния показывало
/// бы случайный. Прежняя задача снимается (`abort`), а вместе с ней роняются
/// `Control` и `Hold` — канал закрывается тем же `Drop`, которым он
/// закрывается всегда (`channel::Hold`).
fn start_call(
    node: &Node,
    channels: &Channels,
    kit: &Kit,
    tx: &UnboundedSender<Ev>,
    calls: &mut HashMap<CardId, tokio::task::JoinHandle<()>>,
    card: Dialling,
    code: String,
) {
    let addr = match target(kit, &card.id, &code) {
        Ok(addr) => addr,
        Err(e) => {
            say(tx, Kind::Fail, e);
            return;
        }
    };
    if let Some(old) = calls.remove(&card.id) {
        old.abort();
    }
    let id = card.id.clone();
    let handle = tokio::spawn(calling(node.clone(), channels.clone(), kit.clone(), tx.clone(), card, code, addr));
    calls.insert(id, handle);
}

/// Куда звонить этой карточкой: по вставленному коду либо по запомненному
/// партнёру.
///
/// Пустой код без партнёра — не беда программы, а разговор с человеком:
/// подключаться действительно некуда, и сказать это надо словами, а не
/// молчаливым бездействием кнопки.
fn target(kit: &Kit, card: &CardId, code: &str) -> Result<EndpointAddr, String> {
    if !code.trim().is_empty() {
        return Ok(crate::ticket::Ticket::from_code(code)?.addr());
    }
    let partner = Partners::open(kit.state())?
        .of(card)
        .ok_or("Кода нет, а по этой карточке ещё ни разу не подключались.\nВставьте код, выданный на компьютере с базой.")?;
    Ok(addr_of(&partner))
}

/// Адрес партнёра: ключ плюс подсказки того же вида, что ездят в коде
/// (`Ticket::addr`) и по тому же правилу — не разобралось, значит выброшено,
/// ключ остаётся.
fn addr_of(p: &Partner) -> EndpointAddr {
    let mut addr = EndpointAddr::new(p.key);
    for d in &p.direct {
        if let Ok(s) = d.parse::<std::net::SocketAddr>() {
            addr = addr.with_ip_addr(s);
        }
    }
    if let Some(relay) = &p.relay {
        if let Ok(url) = relay.parse::<iroh::RelayUrl>() {
            addr = addr.with_relay_url(url);
        }
    }
    addr
}

/// Что у зовущей карточки на руках между кругами.
///
/// Две половины одной памяти, и поэтому вместе: по ним решается, чем звонить
/// (`enroll::Call::of`), и решается один раз на круг. Раздельно они жили бы
/// каждая под своим замком, и «есть ли код» снова стало бы второй мерой рядом
/// с первой.
#[derive(Clone, Default)]
struct InHand {
    /// Код подключения, пока он не израсходован. Пустой — зачисление уже есть.
    code: String,
    /// Признак базы той карточки, которой этот поток, — как его назвала та
    /// сторона в `enroll_ok`.
    ///
    /// `None` — не знаем, и тогда та сторона отвечает всем списком своих баз,
    /// а поток числится за всеми ними: отзыв любой из них его режет. Поэтому
    /// признак не только помнится между кругами, но и ЖИВЁТ рядом с партнёром
    /// (`partners.toml`) — иначе первый же перезапуск возвращал бы карточку в
    /// это «не знаю», и отзыв соседней карточки рвал бы её связь.
    card: Option<CardId>,
}

impl InHand {
    /// Чем звонить на этом круге. Решение одно и живёт в `enroll::Call::of`:
    /// длину строки кода здесь никто не меряет.
    fn call(&self) -> enroll::Call<'_> {
        enroll::Call::of(&self.code, self.card.as_ref())
    }

    /// Что остаётся на руках после круга — и были ли мы уже подключены.
    ///
    /// Код гасится РОВНО тогда, когда круг дошёл до «подключено»: он
    /// одноразовый (`Book::spend`), и второй круг с тем же кодом получил бы
    /// «код не найден», то есть переподключение кончилось бы на первом же
    /// обрыве. Недозвон его не расходует — предъявить не успели.
    ///
    /// Отдельным решением, а не строками внутри круга: оба его ответа видны
    /// человеку (опустевший код — он же признак «подключается СНОВА»), и
    /// спросить их надо без двух узлов и рантайма.
    fn after(&mut self, round: &Round, agreed: Option<CardId>) -> bool {
        // Карточку, о которой договорились, помним до следующего круга: со
        // второго круга возврат называет её сам, и та сторона числит поток за
        // ней одной.
        if let Some(id) = agreed {
            self.card = Some(id);
        }
        match round {
            Round::Held(_) => {
                self.code.clear();
                true
            }
            _ => self.code.is_empty(),
        }
    }
}

/// Зовущая сторона одной карточки: круг за кругом, пока звать есть смысл
/// (`channel::keep_calling`).
///
/// **Код предъявляется ОДИН раз.** Он одноразовый (`Book::spend`), и второй
/// круг с тем же кодом получил бы отказ «код не найден», то есть
/// `Stopped::NotEnrolled` — и переподключение, ради которого круги и
/// существуют, кончилось бы на первом же обрыве. Поэтому после удачного
/// зачисления код гасится здесь же, а следующие круги идут возвратом по
/// карточке, которую та сторона назвала нашей.
///
/// Опустевший код — он же признак «мы уже были подключены»: первый
/// недозвон до зачисления остаётся «подключается», а после — «подключается
/// снова». Второго счётчика для этого не нужно.
async fn calling(node: Node, channels: Channels, kit: Kit, tx: UnboundedSender<Ev>, card: Dialling, code: String, addr: EndpointAddr) {
    flow(&tx, &card.id, Some(link::Flow::Calling));
    let hand = Arc::new(Mutex::new(InHand { code, card: known_card(&kit, &card.id) }));
    let stopped = channel::keep_calling(|| {
        let (node, channels, kit, tx, card, addr, hand) =
            (node.clone(), channels.clone(), kit.clone(), tx.clone(), card.clone(), addr.clone(), hand.clone());
        async move {
            // Замок берётся и отпускается до первого ожидания — через `await`
            // его не держим ни разу.
            let mine = hand.lock().unwrap_or_else(|e| e.into_inner()).clone();
            let (round, agreed) = one_round(&node, &channels, &kit, &tx, &card, addr, mine.call()).await;
            let enrolled = hand.lock().unwrap_or_else(|e| e.into_inner()).after(&round, agreed);
            if enrolled && !matches!(round, Round::NotEnrolled(_)) {
                flow(&tx, &card.id, Some(link::Flow::Retrying));
            }
            round
        }
    })
    .await;
    flow(&tx, &card.id, Some(link::Flow::Broken));
    let name = &card.name;
    match stopped {
        Stopped::Farewell(why) => say(&tx, Kind::Say, format!("«{name}»: {}", why.text)),
        Stopped::NotEnrolled(no) => say(&tx, Kind::Warn, format!("«{name}»: {}", no.text)),
    }
}

/// Один круг звонка: дозвониться, открыть управляющий поток, провести
/// зачисление, держать поток, пока та сторона говорит.
///
/// Вторым значением возвращает признак базы той карточки, о которой
/// договорились. Он и есть то, чем следующий круг назовёт свою карточку.
/// `None` — договориться не вышло вовсе (недозвон, отказ): выдумывать признак
/// нельзя, иначе поток числился бы за карточкой, о которой не договаривались.
async fn one_round(
    node: &Node,
    channels: &Channels,
    kit: &Kit,
    tx: &UnboundedSender<Ev>,
    card: &Dialling,
    addr: EndpointAddr,
    call: enroll::Call<'_>,
) -> (Round, Option<CardId>) {
    let channel = match channels.to(node, addr.clone()).await {
        Ok(c) => c,
        Err(e) => return (Round::Failed(e), None),
    };
    let mut control = match channel.call().await {
        Ok(c) => c,
        Err(e) => return (Round::Failed(e), None),
    };
    let out = {
        let (send, recv) = control.halves();
        enroll::dial_side(send, recv, call, &says_name(), Machine::read(kit).ceiling).await
    };
    // База в ответе одна и у зачисления, и у возврата (`Outcome::Already`), то
    // есть угадывать здесь больше нечего: прежде на возврат приезжал список, и
    // при нескольких базах приходилось отвечать «не знаю» — поток числился за
    // всеми ними сразу.
    let (agreed, write) = match &out {
        Ok(enroll::Outcome::Enrolled(base)) => (Some(base.base_id.clone()), base.write),
        Ok(enroll::Outcome::Already(base)) => (Some(base.id.clone()), base.write),
        _ => (None, false),
    };
    match out {
        Err(e) => {
            control.end(None).await;
            (Round::Failed(e), agreed)
        }
        Ok(enroll::Outcome::NotEnrolled(no)) => {
            control.end(None).await;
            (Round::NotEnrolled(no), agreed)
        }
        Ok(_) => {
            // Куда возвращаться после обрыва — запоминается ТОЛЬКО здесь, и
            // только после того, как та сторона признала нас своими. Ключ
            // берётся у канала (`Channel::peer`), а не у кода: это то, что
            // доказал сам iroh, а не то, что было написано в строке.
            remember(kit, tx, &card.id, channel.peer(), &addr, agreed.as_ref());
            flow(tx, &card.id, Some(link::Flow::Up));
            // Право записи называется словами КАЖДЫЙ круг, а не только на
            // первом зачислении: потолок той машины складывается заново на
            // каждом подключении, и «переключённый потолок доедет следующим
            // подключением» (спека) человек читает здесь. Это же и
            // единственный читатель поля `write` у возврата — без него оно
            // уезжало бы в никуда.
            say(tx, Kind::Ok, format!("«{}»: подключено, {}", card.name, access_word(write)));
            // Разбирать сказанное по живому потоку здесь нечего: всё, что
            // кончает соединение, `hold` разбирает сам (`bye`, `revoked`), а
            // сообщения «что-то изменилось на стороне базы» в этой версии нет
            // — оно было в таблице спеки и не отправлялось ниоткуда, и честно
            // снятая строка лучше пустого обещания (`wire::KNOWN`).
            let gone = channel::hold(control.ear(), |_| {}).await;
            // Единственный выход из соединения — через `end`, и на этом пути
            // тоже: сказать нам нечего (`None`), но написанное до этого
            // обязано доехать прежде, чем канал закроется.
            control.end(None).await;
            (Round::Held(gone), agreed)
        }
    }
}

/// Приём входящих: канал → управляющий поток → разговор зачисления.
///
/// Сам цикл — в `channel::accept_all`: три задачи, канал живёт дольше любого
/// своего потока, поток — дольше разговора по нему. Здесь остаётся только то,
/// что к проводу не относится: куда писать о беде, которую той стороне
/// сказать нечем (её конца у нас уже нет), и чем разговаривать.
///
/// Своей копии этого цикла здесь больше нет. Она жила тут ровно потому, что
/// `accept_all` не отдавала разговору ключ той стороны, без которого
/// `enroll::accept_side` не решает допуск; теперь отдаёт, и одно правило
/// живёт в одном месте.
async fn accepting(node: Node, channels: Channels, kit: Kit, tx: UnboundedSender<Ev>, live: Live) {
    let noted = tx.clone();
    channel::accept_all(
        &node,
        &channels,
        move |why| say(&noted, Kind::Warn, why),
        move |control, peer| answering(kit.clone(), tx.clone(), live.clone(), control, peer),
    )
    .await;
}

/// Один разговор зачисления на принимающей стороне: заявка в окно, решение
/// человека обратно, и дальше держим поток.
///
/// **Книга открывается своя, на этот разговор.** Так и задумано
/// (`enrolled::Book` — «окно и отдельный процесс держат разные `Book` на один
/// файл»): каждая правка перечитывает файл под межпроцессным замком, поэтому
/// снимок в памяти окна и снимок здесь не спорят. Решение о допуске читает
/// диск (`Book::enrolled_to`), и отзыв в окне действует немедленно.
///
/// **Вожжи зачисленного разговора кладутся в `live`** (`channel::reins`):
/// по ним «Отозвать разрешение» снимает поток в ту же секунду, а не на
/// следующем круге той стороны. Снимаются они оттуда ровно тогда, когда
/// присмотр кончился, — и уронённые вожжи досылают написанное и закрывают
/// поток сами (`channel::settle`).
///
/// **Чего здесь ещё нет.** Прощание при выключении обслуживания
/// (`channel::SERVING_OFF`). Слова и вожжи для него готовы, не хватает зова из
/// переключателя обслуживания (`gui::link`) — а он в чужом файле, и этой
/// задачей не правится. Пока зова нет, та сторона читает обрыв вместо
/// причины, и это единственное, что в `bye` ещё не доехало: прощание при
/// закрытии окна (`channel::WINDOW_CLOSED`) уходит залпом с «Выхода»
/// (`Cmd::ByeAll`).
async fn answering(kit: Kit, tx: UnboundedSender<Ev>, live: Live, mut control: crate::channel::Control, peer: EndpointId) {
    let mut book = match Book::open(kit.state()) {
        Ok(book) => book,
        Err(e) => {
            say(&tx, Kind::Fail, e);
            return;
        }
    };
    let cards = Machine::read(&kit).cards;
    let ask = |request: enroll::Request| {
        let tx = tx.clone();
        async move {
            let (answer, wait) = futures::channel::oneshot::channel();
            if tx.unbounded_send(Ev::Enroll(Pending { request, answer: Some(answer) })).is_err() {
                // Окна больше нет — спрашивать некого, и это не отказ
                // человека, а отсутствие человека.
                return enroll::Decision::NoAnswer;
            }
            // Уронённый передатчик (окно закрыли, заявку вытеснила новая от
            // той же стороны) — тот же третий ответ: решения не было.
            wait.await.unwrap_or(enroll::Decision::NoAnswer)
        }
    };
    let out = {
        let (send, recv) = control.halves();
        enroll::accept_side(send, recv, peer, &mut book, &cards, ask).await
    };
    let out = match out {
        Ok(out) => out,
        Err(e) => {
            say(&tx, Kind::Warn, e);
            control.end(None).await;
            return;
        }
    };
    // База, о которой договорились, — ОДНА и у зачисления, и у возврата
    // (`enroll::Outcome`, там и довод): поток у карточки свой, и числить его за
    // всеми базами партнёра значит рвать отзывом одной связь по остальным.
    let (agreed, write): (CardId, bool) = match &out {
        enroll::Outcome::Enrolled(base) => (base.base_id.clone(), base.write),
        enroll::Outcome::Already(base) => (base.id.clone(), base.write),
        enroll::Outcome::NotEnrolled(no) => {
            say(&tx, Kind::Say, no.text.clone());
            control.end(None).await;
            return;
        }
    };
    // Наша карточка по ключу, о котором договорились (`serving`, там и довод).
    // Неопознанный разговор учитывается как неопознанный и режется любым
    // отзывом этой стороны (`cut_these`).
    let served = serving(cards.accepting(), &agreed);
    // Слово состояния — только там, где карточка известна: завести строку
    // состояния для карточки, которой в списке нет, значило бы показать
    // человеку карточку-призрак.
    let shown = served.as_ref().map_or_else(|| "карточка не опознана".to_string(), |c| c.name.clone());
    if let Some(c) = &served {
        flow(&tx, c.id(), Some(link::Flow::Up));
    }
    // Право записи — то, что ПОЛУЧИЛОСЬ после сложения потолков: человек видит
    // в журнале, чем эта сторона сейчас может пользоваться, а не чем ей
    // когда-то разрешили.
    say(&tx, Kind::Ok, format!("«{shown}»: подключено, {}", access_word(write)));
    let (reins, mut recv) = channel::reins(control);
    let id = live.remember(peer, served.as_ref().map(|c| c.id().clone()), reins);
    // Щель между решением человека и записью вожжей: спрашиваем допуск ЕЩЁ
    // РАЗ, уже после записи. Отзыв, случившийся в эти микросекунды, либо
    // увидит наши вожжи и порвёт поток сам, либо не увидит — и тогда его
    // увидит эта проверка. Третьего порядка у двух событий нет.
    let seen = served.as_ref().map(|c| book.enrolled_to(c.id(), peer).ok().flatten().is_some());
    if !keep_holding(seen) {
        // Рвём только СВОЙ разговор и только если отзыв не забрал его раньше:
        // иначе второе прощание ушло бы в поток, которого уже нет.
        if live.alive(peer, id) {
            if let Some(reins) = live.forget(peer, id) {
                reins.revoke(&agreed, REVOKED_TEXT).await;
            }
        }
        if let Some(c) = &served {
            flow(&tx, c.id(), Some(link::Flow::Broken));
        }
        say(&tx, Kind::Warn, format!("«{shown}»: разрешение сняли прямо во время разговора — связь закрыта"));
        return;
    }
    let gone = channel::hold(&mut recv, |_| {}).await;
    // Вожжи уходят с учёта и падают здесь: их задача письма дошлёт написанное
    // и снимет поток сама. Если отзыв успел забрать их раньше — забирать
    // нечего, и это не беда.
    drop(live.forget(peer, id));
    if let Some(c) = &served {
        flow(&tx, c.id(), Some(link::Flow::Broken));
    }
    match gone {
        Gone::Farewell(why) => say(&tx, Kind::Say, format!("«{shown}»: {}", why.text)),
        Gone::Broken(why) => say(&tx, Kind::Say, format!("«{shown}»: {}", why.text)),
    }
}

/// Что эта машина объявляет той стороне: принимающие карточки и потолок
/// записи — ОДНИМ чтением настроек и одной мерой.
///
/// **Почему вместе, а не двумя функциями.** Прежде карточки читались терпимо
/// (`load_unchecked`), а потолок — строго (`load` с `validate`): та же пара
/// разных мер на один файл, которую чинил `c32f2c4`, уцелевшая через
/// пятьдесят строк. Цена была не теоретической: у нового человека настройки
/// полузаполнены всегда, строгое чтение отвергало файл целиком, и на провод
/// всегда уезжало «только чтение», пока в меню стояло «Полный», — запись
/// молча не давалась, и причину не называл никто. Одна вещь, читающая файл
/// один раз, делает вторую меру невыразимой: читать здесь больше нечем.
///
/// Читается с диска на каждый входящий разговор и на каждый круг звонка, а не
/// берётся снимком при запуске: человек правит карточки и щёлкает потолок в
/// окне, и разговор обязан видеть то, что в файле сейчас. Цена — одно чтение
/// toml на подключение, то есть раз в минуты.
struct Machine {
    /// Карточки этого рабочего места, которые ПРИНИМАЮТ подключения, — или
    /// признание, что настроек мы не прочитали (`enroll::Cards`, там и довод,
    /// почему это тип, а не пустой список).
    cards: enroll::Cards,
    /// Потолок записи — свойство МАШИНЫ (`wire::Ceiling`, контракт: «Чего в
    /// соединении НЕТ»): тот же переключатель, что живёт в меню значка, и он
    /// действует на все карточки разом.
    ceiling: Ceiling,
}

impl Machine {
    fn read(kit: &Kit) -> Machine {
        match crate::secrets::Store::system(kit.state()) {
            Ok(store) => Machine::read_with(kit, &store),
            Err(e) => Machine::silent(format!("Настройки соединений не прочитались: не открылось хранилище паролей: {e}")),
        }
    }

    /// То же, но подложку секретов даёт вызывающий — ей проверяются тесты (тот
    /// же приём и тот же довод, что у `Cfg::load_with`: DPAPI из тестов не
    /// зовём).
    ///
    /// Мера чтения выбирается здесь, одной строкой на обе половины: вернуть
    /// сюда строгое `load_with` — и покраснеют оба теста, и про карточки, и
    /// про потолок. Сломанный toml остаётся отказом и здесь: `load_unchecked`
    /// снимает проверку заполненности, а не проверку читаемости.
    fn read_with(kit: &Kit, store: &crate::secrets::Store) -> Machine {
        match crate::cfg::Cfg::load_unchecked_with(kit, store) {
            Ok(cfg) => Machine::of(&cfg),
            // Хвост с ключом toml снимается: эти слова идут в ЖУРНАЛ ОКНА, тот
            // самый читатель, ради которого хвост и заводился
            // (`cfg::said_in_window`). Сюда приезжает, среди прочего, отказ
            // разбора потолка записи — с хвостом «[write; допустимые
            // значения…]», то есть ровно тем, чего человек в окне не видит и
            // что ему там говорить не о чем.
            Err(e) => Machine::silent(format!("Настройки соединений не прочитались: {}", crate::cfg::said_in_window(&format!("{e}")))),
        }
    }

    /// Чистая половина: из УЖЕ прочитанных настроек.
    ///
    /// Потолок машины складывается в поле `write` КАЖДОЙ карточки, а не одной
    /// текущей. Прежде он не складывался вовсе: `allows_write` карточки — её
    /// собственное поле, а потолок машины спрашивался отдельно и только у
    /// текущей, то есть у нетекущей принимающей карточки объявленное на
    /// проводе право записи не знало о потолке ничего. Запрет любой стороны
    /// сильнее разрешения другой (решение владельца 1.11), и сложить их здесь
    /// — единственное место, где это ещё можно сделать до провода.
    ///
    /// **Карточки раскладываются на ТРИ кучи, и выпасть из всех карточка не может.** Прежде отбор принимающих стоял ФИЛЬТРОМ перед
    /// раскладкой, и карточка, переключённая человеком в «Подключаюсь сам» (`role = "dial"`) или в «Всё на одной машине» (`mode =
    /// "local"`), выпадала из обеих куч молча. По её живому коду та сторона слышала «карточку, для которой выдали этот код, на том
    /// компьютере удалили» — третья дорога к той же лжи, которую на этой ветке чинили уже дважды, и корнем снова была не строка, а
    /// потерянная карточка. Третья куча (`Cards::not_accepting`) эту дорогу закрывает: о каждой карточке есть что сказать словами, а
    /// фильтра, который молча теряет, в этом месте больше нет.
    ///
    /// **Вторая куча — по тому, где база.** Прежде отбор
    /// смотрел только на вид соединения и роль, а `base_here` не спрашивал
    /// вовсе — и карточка, у которой базы здесь НЕТ, объявляла себя базой на
    /// проводе: уезжала в `hello_ok` со своими полями (имя базы от пустого
    /// пути, публикация этой машины), зачисляла к себе стороны и обслуживала
    /// их. Человек с базой на той стороне при этом отпечатка не видел и
    /// ничего не разрешал. Это случай второй спеки (база у ЗОВУЩЕЙ стороны),
    /// которого эта сборка не умеет; путь к нему из окна открыт (меню
    /// «База — на той стороне»), а половины протокола нет.
    ///
    /// Отложены, а не выброшены: выброшенная карточка — это код, выданный в
    /// окне по ней, который получает «карточку удалили». Той же ложью, за
    /// которую чинится `Cards::Unreadable`, только другой дорогой. По
    /// отложенным `accept_side` отказывает СВОИМИ словами.
    ///
    /// Спрашивается `base_is_here()`, а не сырой `base_here` (правило cfg.rs,
    /// круг починки 1 задачи 12): застрявшее в файле `base_here = false` у
    /// локальной карточки не вправе решать за человека, у которого
    /// переключателя на экране нет.
    fn of(cfg: &crate::cfg::Cfg) -> Machine {
        // Без сравнения строк: вид потолка в настройках — `read_write` или
        // `read_only`, и одно `== "full"` на этом месте уже стоило продукту
        // всей записи (`access()` такого значения не производит никогда, то
        // есть потолок всегда выходил «только чтение»). Один `bool` от того,
        // кого об этом спрашивают все остальные, разойтись словарём не может.
        let ceiling = if cfg.allows_write() { Ceiling::Full } else { Ceiling::ReadOnly };
        let (mut accepting, mut base_elsewhere, mut not_accepting) = (Vec::new(), Vec::new(), Vec::new());
        for c in &cfg.connections {
            let card = enroll::Card {
                name: c.name.clone(),
                base: BaseFields {
                    base_id: c.id(),
                    base_name: crate::cfg::base_name(&c.base_path).into(),
                    // Действующее право, а не своя складка половин: складывать их
                    // умеет ровно одна `Cfg::may_write`, и второе место сложения —
                    // это второй словарь одного понятия, который однажды разойдётся
                    // с первым (на этой ветке так уже было с потолком и с чтением
                    // настроек).
                    write: cfg.may_write(c),
                },
            };
            // ОДИН разбор на три кучи, и четвёртой дороги — «нигде» — у карточки
            // нет: `else` здесь невыразим, а `push` обязателен в каждой ветке.
            // Прежде отбор стоял фильтром перед раскладкой, и «Подключаюсь сам»
            // вместе с «Всё на одной машине» выпадали из обеих куч молча.
            // Спрашивается `link::waits_for_incoming` — она объявляет себя
            // единственным местом этого вопроса, и переписанное своими руками
            // правило здесь было четвёртой его копией.
            let accepts = crate::gui::link::waits_for_incoming(c);
            match (accepts, c.base_is_here()) {
                (false, _) => not_accepting.push(card),
                (true, true) => accepting.push(card),
                (true, false) => base_elsewhere.push(card),
            }
        }
        Machine { cards: enroll::Cards::Read { accepting, base_elsewhere, not_accepting }, ceiling }
    }

    /// Настройки не прочитались вовсе — и так об этом и говорится, своими словами в наш журнал и тремя строками той стороне
    /// (`enroll::Cards::Unreadable`).
    ///
    /// Прежде здесь стоял ПУСТОЙ СПИСОК карточек, и он был неправдой дважды: той стороне уезжало «карточку удалили» про машину, где её не
    /// удаляли, а в наш журнал не ложилось ничего. Причина берётся та, что отдал отказ чтения: по ней видно, сломан ли toml или не открылась
    /// подложка секретов, — и это ровно то, за чем человека просят посмотреть журнал.
    ///
    /// «Только чтение» остаётся верным по своему правилу: по умолчанию инструментов, пишущих в базу, нет (решение владельца 1.11), и
    /// неизвестность не повод выдавать больше, чем разрешено.
    fn silent(why: String) -> Machine {
        Machine { cards: enroll::Cards::Unreadable(why), ceiling: Ceiling::ReadOnly }
    }
}

/// Имена карточек по их ключам — ТОЛЬКО для слов в журнал.
///
/// Зовущие карточки поднимают звонки по файлу партнёров, а там от карточки только ключ — и это верно: имя человек правит когда хочет.
/// Но строка ««Ромашка»: подключено» нужна человеку именем, а не шестнадцатью байтами hex.
///
/// Чтение терпимое (`load_unchecked`) и одним разом на весь подъём звонков: настройки не прочлись — имён просто нет, и звонки от этого
/// не отменяются, допуск дала та сторона, а не наш файл.
fn card_names(kit: &Kit) -> HashMap<CardId, String> {
    crate::cfg::Cfg::load_unchecked(kit).map(|cfg| cfg.connections.iter().map(|c| (c.id(), c.name.clone())).collect()).unwrap_or_default()
}

/// Какую НАШУ карточку обслуживает этот разговор — по ключу, о котором договорились на проводе.
///
/// Отдаёт карточку ЦЕЛИКОМ, а не её имя: вызывающему нужны оба ответа разом — ключ (по нему спрашивается допуск и кладутся вожжи) и имя
/// (его читает человек в журнале). Собирать имя по ключу вторым проходом значило бы искать дважды то, что уже нашли.
///
/// Отдельной функцией, а не строкой внутри разговора: у этого решения есть неверный ответ, и однажды оно его дало — пара карточек с
/// одним знаком возвращала ОБЕ, и поток числился за карточкой, о которой не договаривались. С ключом карточки вместо считанного от пути
/// к базе знака этого случая больше нет: ключи разных карточек различны всегда (`cfg::Cfg`, разводка близнецов при разборе).
///
/// `None` — не сошлась ни одна; выдумывать карточку нельзя, и такой поток режется любым отзывом этой стороны (`cut_these` знает про
/// неопознанные).
fn serving(cards: &[enroll::Card], agreed: &CardId) -> Option<enroll::Card> {
    cards.iter().find(|c| c.id() == agreed).cloned()
}

/// Право записи — словами человека, а не флажком.
///
/// «Разрешено только читать» человек может прочитать коллеге по телефону, а
/// `write = false` — не может. Одна вещь на оба конца (зовущий читает это о
/// себе, принимающий — о той стороне): два места со своими словами об одном
/// праве однажды разойдутся, и человек прочтёт в двух строках журнала разное
/// об одном и том же.
fn access_word(write: bool) -> &'static str {
    if write {
        "разрешено читать и записывать"
    } else {
        "разрешено только читать"
    }
}

/// Как эта машина называет себя той стороне. Её слова, не проверенный факт, —
/// и показываются они с этой пометкой (`save::permission_question`).
///
/// Имя компьютера, а не имя карточки: карточка названа человеком по ТОЙ
/// стороне («Ромашка» у разработчика — это заказчик), и прислать его обратно
/// значило бы назваться его же словами о нас. Имя не узналось — пустая
/// строка, и в окне это честное «Себя не назвала».
fn says_name() -> String {
    sysinfo::System::host_name().unwrap_or_default()
}

/// Какую карточку эта зовущая помнит с прошлого раза — признак базы, который
/// та сторона назвала ей в прошлом разговоре.
///
/// Берётся с диска, а не начинается с «не знаю»: перезапуск программы — не
/// повод забыть то, о чём уже договорились. Без этого первый круг после
/// перезапуска шёл бы возвратом БЕЗ имени, та сторона отвечала бы всем списком
/// своих баз, и поток числился бы за всеми ними — то есть отзыв соседней
/// карточки рвал бы и эту связь.
///
/// Отказ чтения — то же «не знаю», и это верно: признак не называется наугад.
/// Старого признака от ДРУГОЙ машины здесь быть не может — `Partners::remember`
/// снимает его сам, когда ключ той стороны сменился.
fn known_card(kit: &Kit, card: &CardId) -> Option<CardId> {
    Partners::open(kit.state()).ok().and_then(|p| p.base_id_of(card))
}

/// Запоминает, куда карточке возвращаться. Отказ записи — строка в журнал, а
/// не конец подключения: это подключение уже живёт, а потеряно будет лишь
/// возвращение после перезапуска.
fn remember(kit: &Kit, tx: &UnboundedSender<Ev>, card: &CardId, peer: EndpointId, addr: &EndpointAddr, agreed: Option<&CardId>) {
    let partner = Partner {
        key: peer,
        relay: addr.relay_urls().next().map(|u| u.to_string()),
        direct: addr.ip_addrs().map(|a| a.to_string()).collect(),
    };
    // Признак базы пишется ВМЕСТЕ с партнёром и в этом порядке: сперва партнёр
    // (он сбрасывает признак, если ключ той стороны сменился), потом признак
    // этого разговора. Обратный порядок стирал бы только что записанное.
    let wrote = Partners::open(kit.state()).and_then(|mut p| {
        p.remember(card, &partner)?;
        match agreed {
            Some(id) => p.remember_base_id(card, id),
            None => Ok(()),
        }
    });
    if let Err(e) = wrote {
        say(tx, Kind::Warn, format!("Подключение живёт, но запомнить его не удалось: {e}"));
    }
}

/// Что узел знает о себе — плюс своя петля (`ticket::direct_with_loopback`,
/// там и довод, почему петля обязательна).
fn look(node: &Node) -> Reach {
    let addr = node.ticket_parts();
    let seen: Vec<std::net::SocketAddr> = addr.ip_addrs().copied().collect();
    let relay = addr.relay_urls().next().map(|u| u.to_string());
    Reach { relay, direct: crate::ticket::direct_with_loopback(&seen, &node.endpoint().bound_sockets()) }
}

/// Строка в журнал окна из потока узла. Прямой дороги к `note_line` отсюда
/// нет и быть не может — она просит `&mut Ui`, то есть главный поток.
fn say(tx: &UnboundedSender<Ev>, kind: Kind, text: impl Into<String>) {
    let _ = tx.unbounded_send(Ev::Line(Line { kind, text: text.into() }));
}

/// Новое состояние управляющего потока карточки — в окно. Слово человеку из
/// него делает `link::contract_of`/`contract_word`, здесь только факт.
fn flow(tx: &UnboundedSender<Ev>, card: &CardId, now: Option<link::Flow>) {
    let _ = tx.unbounded_send(Ev::Flow(card.clone(), now));
}

/// Проверяются здесь два решения, и оба — про обход отзыва (находки
/// автоматической проверки безопасности на коммит задачи 9). Остальное в этом
