///
/// Случая два, и человеку оба названы: либо программа уже запущена (обычное), либо имя занял чужой процесс (тогда наш бек дверь не откроет вовсе — и это верный исход, самозванец не должен получить ни одной команды).
pub const NAME_TAKEN: &str = "имя управляющей двери уже занято: его держит либо вторая копия программы, либо чужой процесс — закройте первую копию, а если её нет, сообщите нам: своих команд такой двери отдавать нельзя";

/// Дверь держит не наш процесс — отказ КЛИЕНТУ. Команда в этом случае не отдаёт чужому ни вопроса, ни тем более разрешения человека.
pub const STRANGER_DOOR: &str = "под именем управляющей двери отвечает чужая учётная запись — это не ваш экземпляр программы; закройте её и сообщите нам, команд этой двери не отдавайте";

/// Приём стуков кончился — строка в журнал на стороне бека, на обеих осях и одними словами. Поток приёма уходит молча (отказ `connect` на Windows, отказ `accept` на Linux), и дверь после этого жива только именем: набранные команды будут читать «бек не запущен» при живом беке, а причины не узнает никто. Это и есть тот `kit`, который Windows прежде принимала параметром с подчёркиванием и не использовала.
pub const DOOR_STOPPED: &str = "управляющая дверь перестала принимать стуки — набранные команды до этого экземпляра больше не достучатся; остановите его и запустите снова";

/// В дверь стучалась чужая учётная запись — строка в журнал на стороне бека. Молча закрывать дверь нельзя: это единственный след события, по которому человек потом разберётся.
pub const STRANGER_KNOCK: &str = "в управляющую дверь стучалась чужая учётная запись — ответа она не получила";

/// Сколько клиент ждёт ответа. Живой отвечает из памяти и мгновенно, так что срок здесь — не про скорость, а про то, чтобы зависший бек не держал набранную команду навсегда: `Frame::read` нарочно без своего срока (см. его докстроку), срок ставит вызывающий.
const ASK_WAIT: Duration = Duration::from_secs(5);

/// Сколько отмерено самому ЗВОНКУ — одна мера, из которой выведены все остальные сроки вокруг него (`Ask::wait` у двери, ожидание клиента, строка предупреждения `main.rs::DIAL_MINUTES`). Звонок ждёт ЧЕЛОВЕКА у чужого экрана, и сроки у этого ожидания уже посчитаны зачислением: принимающая сторона отмеряет на решение `DECISION`, зовущая — его же плюс `PATIENCE` на саму пересылку (см. их докстроки). Своего числа здесь не заводим — оно разошлось бы с их при первой же правке сроков.
pub const DIAL_WAIT: Duration = crate::enroll::DECISION.saturating_add(crate::enroll::PATIENCE);

/// О чём клиент спрашивает живого. `Status` первый, потому что ничего не меняет; `Peers` и `Revoke` последние — их нарочно отложили на после того, как круг сопряжения замкнулся (задача 9).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum Ask {
    Status,
    /// Выдать карточке новый код подключения. `card` — имя карточки; `None` — текущее соединение.
    ///
    /// Всегда перевыпуск, а не «показать»: строку уже выданного кода команда отдать не может — её нет нигде, кроме памяти живого (`codes::Codes`), и второй набранный `code` человек набирает ровно затем, зачем нажимает «Выдать новый код» в окне. Прежние коды карточки при этом гаснут (`Book::reissue`), и это то же самое правило, что на экране.
    Code {
        card: Option<String>,
    },
    /// Позвонить по коду и ДОЖДАТЬСЯ исхода. `card` — имя зовущей карточки; `None` — текущее соединение.
    Dial {
        code: String,
        card: Option<String>,
    },
    /// Кто сейчас просит разрешения подключиться. Ничего не меняет, как и `Status`, — но спрашивается у держателя: заявки живут в его
    /// памяти (`enroll::Requests`), на диске их нет и быть не может.
    Requests,
    /// Ответить одной заявке — решением человека и ничьим больше (закон 6 спеки: автоматического разрешения в продукте нет).
    ///
    /// Адресуется ОТПЕЧАТКОМ той стороны, а не номером в списке: номер сдвигается между двумя набранными командами, а отпечаток не
    /// меняется — и по телефону голосом сверяют именно его (спека, раздел 5, пункт 5).
    ///
    /// Отпечаток принимается полный и сокращённый, но однозначен только полный: сокращение подбирается перебором, и совпавшие двое
    /// получают отказ словами (`enroll::Requests::answer`, обзор безопасности 16.11).
    Answer {
        fingerprint: String,
        /// Имя карточки, если человек его назвал: одна сторона законно стучится в несколько карточек, и отпечаток их не различает
        /// вовсе. `None` — карточка не названа, и тогда заявка обязана найтись по отпечатку одна.
        card: Option<String>,
        said: Said,
    },
    /// Кому РАЗРЕШЕНО подключаться прямо сейчас — книга допуска словами. Ничего не меняет, как `Status` и `Requests`.
    ///
    /// Спрашивается у держателя, хотя книга и лежит на диске: соседний `Revoke` без живого всё равно не сделать (отозвать — значит и
    /// оборвать живой поток той стороны), а список и отзыв человек читает и набирает подряд. Дай им разные источники — и строка,
    /// которую он копирует, однажды будет не о том, что сейчас в книге.
    ///
    /// `card` — имя карточки; `None` — все карточки настроек. Текущее соединение здесь НЕ подставляется (в отличие от `Code` и
    /// `Dial`): те делают одно дело одной карточкой, а этот рассказывает, и умолчанием «только текущая» он прятал бы от человека
    /// разрешения соседних карточек ровно тогда, когда тот пришёл посмотреть, кому он что дал.
    Peers {
        card: Option<String>,
    },
    /// Забрать у ОДНОЙ стороны данное ей разрешение — и оборвать её живой поток в ту же секунду.
    ///
    /// Адресуется ПАРОЙ, и обе половины обязательны. Разрешение принадлежит паре «карточка + сторона» (`enrolled::Book::revoke`), и
    /// одна сторона законно зачислена к нескольким карточкам: отзыв по одному отпечатку снял бы не то, что человек видел в списке.
    /// Карточка здесь не `Option` по той же причине, по какой у `Ask::Answer` она `Option`: там без неё заявка чаще всего находится
    /// одна, а здесь «все карточки» — обычное положение дел, и выбирать за человека нельзя.
    Revoke {
        card: String,
        fingerprint: String,
    },
}

/// Что человек ОТВЕТИЛ заявке — и только то, что он правда отвечает: пускаю или не пускаю.
///
/// **Третьего ответа зачисления здесь нет, и это запрет типом, а не уговор** (замечание ревью круга правок 2). У `enroll::Decision`
/// случая три, и третий — `NoAnswer`, «закрыл диалог, не решив»: он нужен ОКНУ, у которого диалог закрывается крестиком, и значит он
/// «решения не было». Проехав дверью, он выглядел бы ответом: `Pending::answer` забрал бы канал (второй раз ответить стало бы
/// нечем), человеку сказали бы «просьба никуда не делась», а команда ушла бы с нулём — молчаливый успех при заявке, на которую
/// никто не ответил. Команды, которая его шлёт, в продукте нет; этот тип делает так, что её и не напишут.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Said {
    Allow,
    Deny,
}

impl From<Said> for crate::enroll::Decision {
    fn from(said: Said) -> crate::enroll::Decision {
        match said {
            Said::Allow => crate::enroll::Decision::Allow,
            Said::Deny => crate::enroll::Decision::Deny,
        }
    }
}

impl Ask {
    /// Сколько ждут ответа на ЭТОТ вопрос — мера одна на обе стороны двери: клиент и держатель отмеряют её по одному выражению, и разойтись им негде.
    ///
    /// **Звонок — особый, и не на вкус.** Он ждёт ЧЕЛОВЕКА у чужого экрана: принимающая сторона отмеряет на решение `enroll::DECISION`, зовущая — его же плюс `PATIENCE` (см. их докстроки), и пять секунд обычного вопроса обрывали бы разговор ровно там, где человек тянется к мыши.
    ///
    /// **Сроков вокруг звонка ТРИ, и каждый следующий длиннее предыдущего на `ASK_WAIT`.** Внутри — само дело (`dial_for` ждёт узел ровно `DIAL_WAIT`), вокруг него — дверь (вот эта мера), вокруг неё — клиент (`ask_at` берёт `wait() + ASK_WAIT`). Порядок обязан быть строгим, и запас взят не на глазок: дело начинается на миллисекунды ПОЗЖЕ, чем дверь завела свой срок (чтение настроек с диска, `spawn_blocking`), и при равных сроках срок двери истекал бы первым ВСЕГДА.
    ///
    /// Чем это куплено (находка ревью круга 1, Major 1). Истёкший срок двери — это оборванный разговор: клиент читает «живой экземпляр не ответил (причина: closed)», то есть **диагноз о своём беке там, где виновата та машина**. Настоящие слова («ответа так и не было, проверьте, запущена ли программа на том компьютере») лежат в `dial_for` и были бы недостижимы. Ровно так и срывается утренний живой прогон: человек звонит, та сторона молчит, а программа винит его собственную.
    fn wait(&self) -> Duration {
        match self {
            // Заявки и ответ на заявку живого не ЖДУТ: список лежит у него в памяти, а ответ — это одна посылка в уже открытый канал
            // решения. Своего срока им не заводим (решение ведущего, задача 7): мера обычного вопроса на то и обычная.
            // Книга допуска тоже не ЖДЁТ: оба вопроса о ней — чтение и правка файла под межпроцессным замком, дело на миллисекунды.
            Ask::Status | Ask::Code { .. } | Ask::Requests | Ask::Answer { .. } | Ask::Peers { .. } | Ask::Revoke { .. } => ASK_WAIT,
            Ask::Dial { .. } => DIAL_WAIT.saturating_add(ASK_WAIT),
        }
    }

    /// Сколько ждёт ответа КЛИЕНТ: срок самого дела у двери плюс обычный срок обмена. Одно выражение на `ask_at` и на тест, который сторожит порядок сроков: записанная дважды формула была бы второй мерой на тот же вопрос, и регрессию внешней ноги не поймал бы никто (находка ревью задачи 6).
    fn client_wait(&self) -> Duration {
        self.wait().saturating_add(ASK_WAIT)
    }
}

/// Что живой отвечает. Случай на случай с `Ask`: вопрос без ответа и ответ без вопроса этой дверью не ходят.
///
/// **Отказ САМОГО дела едет внутрь ответа, а не наружу `Result`.** Наружный отказ `ask` — про дверь: живого нет, дверь чужая, не ответил. «Такой карточки нет», «код выдавать некому», «по этому коду подключиться нельзя» — это ответы живого, он их и произносит; смешать их в один `Result` значило бы, что команда не отличит «бек не запущен» от «бек ответил отказом», а человеку это разные беды.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum Answer {
    Status(StatusView),
    Code(Result<crate::codes::Issued, String>),
    Dialled(Result<crate::enroll::Outcome, String>),
    /// Кто просит разрешения. `Err` — спросить было не у кого (узел ещё не поднялся): пустой список здесь значил бы «никто не просит»,
    /// а это незнание, не пустота, — та же разница типом, что у `StatusView::cards`.
    Requests(Result<Vec<RequestView>, String>),
    /// Ответ на заявку отдан — он же ответ на отзыв разрешения. Внутри — слова человеку в обе стороны: `Ok` печатается как есть,
    /// `Err` значит «не сделано» и уводит команду ненулевым кодом (тот же приём, что у `dialled_words`).
    ///
    /// Один вид на два вопроса нарочно: у обоих ответ — это ровно «сделано, и вот что сказать человеку» либо «не сделано, и вот
    /// почему», и разводить их двумя видами значило бы заводить второй вид без второго вопроса.
    Done(Result<String, String>),
    /// Кому разрешено подключаться. `Err` — спросить не вышло (книга не прочиталась, карточки с таким именем нет): пустой список
    /// здесь значил бы «никому не разрешено», а это незнание, не пустота, — та же разница типом, что у `Requests`.
    Peers(Result<Vec<PartyView>, String>),
}

/// Одна заявка словами для списка: к какой карточке стучатся, отпечаток той стороны, как она себя назвала и сколько у человека
/// осталось на ответ. Ровно то, что названо в спеке шагом четвёртым зачисления, и ничего сверх.
///
/// Готовые слова, а не сырые поля: отпечаток считает `enroll::short_key`, самоназвание — `enroll::who_says`, и обе строки едут отсюда
/// такими же, какими их показывает окно в диалоге разрешения (`gui::save::permission_question`). Второго словаря на то же самое в
/// командной строке не заводится (решение 7 задачи 7).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct RequestView {
    /// Имя карточки, к которой пришла заявка, — локальное, как его видит человек в списке.
    pub card: String,
    /// Отпечаток той стороны ЦЕЛИКОМ — он же однозначный АДРЕС для `allow`/`decline`.
    ///
    /// Печатается он нарочно, хотя глазам длинен (обзор безопасности 16.11): коротким сокращением ответить однозначно НЕЛЬЗЯ — его
    /// подбирают перебором за секунды, и две заявки с одинаковым хвостом получают отказ вместо ответа. Чем-то же отвечать человеку
    /// надо, и это «что-то» обязано лежать у него перед глазами.
    pub fingerprint: String,
    /// Тот же отпечаток коротким видом (`enroll::short_key`) — для ГОЛОСА: его и сверяют по телефону. Адресом он не является.
    pub short: String,
    /// Как та сторона себя назвала — её слова, а не проверенный факт.
    pub says_name: String,
    /// Сколько осталось человеку на ответ (`enroll::DECISION` минус прошедшее).
    pub left: Duration,
}

/// Одна зачисленная сторона словами: к какой карточке допущена, отпечаток, как она себя назвала и что ей действующе дано. То же, что
/// показывает карточка в окне (`gui::panel::PartyRow`), и теми же словами.
///
/// Готовые слова, а не сырые поля, — тот же довод, что у `RequestView`: самоназвание считает `enroll::who_says`, короткий отпечаток
/// `enroll::short_key`, право записи `peer::access_label` (все три меры, и он же называет, какая сторона ограничила). Второго словаря
/// на то же самое в командной строке не заводится.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct PartyView {
    /// Имя карточки, к которой зачислена эта сторона, — локальное, как его видит человек в списке.
    pub card: String,
    /// Отпечаток ЦЕЛИКОМ — он же однозначный АДРЕС для `revoke`. Печатается нарочно, хотя глазам длинен: коротким сокращением
    /// отозвать однозначно НЕЛЬЗЯ (тот же довод и та же находка обзора безопасности, что у `RequestView::fingerprint`).
    pub fingerprint: String,
    /// Тот же отпечаток коротким видом (`enroll::short_key`) — для ГОЛОСА. Адресом он не является.
    pub short: String,
    /// Как сторона себя назвала при зачислении — её слова, а не проверенный факт.
    pub says_name: String,
    /// Что ей ДЕЙСТВУЮЩЕ дано, с указанием, какая сторона ограничила (`peer::access_label`).
    pub access: String,
}

/// То, что о себе рассказывает живой экземпляр, и ТОЛЬКО это: обслуживает ли он сейчас и что со связью по карточкам. Ни одного поля про запас: кому разрешено подключаться — отдельный вопрос с отдельным ответом (`Ask::Peers`), и повторять его здесь значило бы завести вторую меру на то же самое.
///
/// Чего здесь нет нарочно: всего, что `status` и так читает с диска (соединение, находки разбора, таблица фактов). Дверь нужна ровно для того, чего на диске НЕТ, — и комплект, появившийся здесь кругом правок 3, не исключение: на диске лежит комплект СПРАШИВАЮЩЕГО, а узнать надо, какой обслуживает ЖИВОЙ.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct StatusView {
    /// Поднято ли обслуживание вызовов агента прямо сейчас.
    pub serving: bool,
    /// Какой комплект обслуживает держатель — его каталог состояния в
    /// каноническом виде (`kit_mark`). Заполняет это поле САМА дверь — и
    /// с рождения (`Door::new`), и на каждом снимке (`Door::show`), — а не
    /// держатель: у держателя его не спрашивают, чтобы он не мог ошибиться
    /// или забыть, и в литералах снимка стоит `None`.
    ///
    /// Зачем оно (круг правок 3 задачи 14). Дверь принадлежит УЧЁТНОЙ
    /// ЗАПИСИ — замок считает единицей её, и это верно. Но живая копия
    /// обслуживает ОДИН комплект, и вопрос «обслуживается ли мой» —
    /// другой вопрос: `1c-connect mcp --kit B` при коннекторе на комплекте
    /// A услышал бы «жив» про чужой комплект, и агент получил бы разрешение
    /// там, где его базы не обслуживает никто.
    ///
    /// `None` значит ровно одно: по ту сторону двери сборка ДРУГОЙ ВЕРСИИ,
    /// которая этого поля не шлёт (`serde(default)`). Своей дверью этот
    /// случай невыразим — ни в какую щель, включая самую первую: дверь
    /// ставит комплект раньше, чем начинает отвечать (`Door::new`, там же
    /// довод).
    #[serde(default)]
    pub kit: Option<String>,
    /// Карточки, которым есть что сказать о связи. Карточка без состояния контракта в список не попадает вовсе: слово «не подключено» ставит строке экран (`gui::link::row`), и второй его копии здесь не будет.
    ///
    /// **`Option`, а не просто список, и это разница ТИПОМ, а не соглашением (решение ведущего, круг правок 1).** `None` — живой экземпляр о связи не сообщает: снимок по умолчанию (а его человек как раз ВИДИТ — дверь отвечает с первой миллисекунды, а первый `show` случается после холодного набора фактов) либо сборка другой версии по ту сторону двери. Поле `kit` эту щель не делит: его дверь заполняет с рождения (`Door::new`). Все живые экземпляры кладут `Some`: `serve` и `connect` — общим снимком (`main::status_view`), окно — своим (`gui::link::door_view`, задача 9: прежде оно клало `None`, потому что класть было нечего). `Some` с пустым списком — связей правда нет. Человеку эти два случая говорятся РАЗНЫМИ словами (`status_lines`), а пустой список, который на самом деле незнание, этим типом просто невыразим — поэтому и не нужно соглашения, которое кто-нибудь однажды не прочтёт.
    pub cards: Option<Vec<CardState>>,
}

/// Одна карточка словами: как человек её назвал и что сейчас со связью. Слово — из `contract::contract_word` и ниоткуда больше; складывает его тот, кто дверь держит, а не дверь.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CardState {
    pub name: String,
    pub word: String,
}

/// Что живой УМЕЕТ, а не только рассказывает. Ставится держателем (`Door::answers`) и зовётся на каждый вопрос, кроме `Status`: тот дверь отвечает из своего снимка сама.
///
/// Обычное замыкание, а не трейт: исполнитель один на оба пути подъёма (`door::serves`), и интерфейс с единственной реализацией был бы лишним этажом. `Send + Sync` — потому что зовут его из потока приёма, а ставит главный.
pub type Serves = Arc<dyn Fn(Ask) -> Answer + Send + Sync>;

/// Сторона бека: держит приём, пока жива. Клонируется ручкой на ту же дверь — держателю нужно и оставить её на стеке, и отдать копию в замыкание, которое рассказывает ей о новостях (`show`).
#[derive(Clone)]
pub struct Door {
    view: Arc<Mutex<StatusView>>,
    serves: Arc<Mutex<Option<Serves>>>,
    /// Комплект, который обслуживает держатель этой двери, — меткой
    /// (`kit_mark`). Дверь знает его с рождения (`open_at` открывают ПО
    /// комплекту) и подставляет в каждый снимок сама: спрашивать его у
    /// держателя значило бы дать ему ошибиться.
    kit: String,
}

impl Door {
    /// Рассказать двери, что отвечать. Дверь — почтовый ящик, а не дознаватель: спрашивать живое состояние ей негде (у окна оно внутри GPUI, у `serve` — в замыкании сеанса), поэтому держатель сам кладёт сюда снимок всякий раз, когда тот меняется.
    pub fn show(&self, view: StatusView) {
        // Комплект ставит дверь, а не держатель: что бы он ни положил в это поле, правда одна — тот комплект, по которому дверь и открыли.
        let view = StatusView { kit: Some(self.kit.clone()), ..view };
        // Отравленный замок — не повод валить ответ: внутри только снимок, и прочитать его после чужой паники не опаснее, чем до.
        *self.view.lock().unwrap_or_else(|e| e.into_inner()) = view;
    }

    /// Научить дверь ДЕЛАТЬ, а не только рассказывать. Ставится один раз, когда у держателя появился узел: до того отвечать на `code` и `dial` ему нечем, и он честно говорит об этом словами (`peer::NOT_READY`), а не молчит.
    ///
    /// Отдельно от `open` ровно по этой причине: дверь открывается ПЕРВЫМ делом, раньше узла и сеанса (иначе `status` читал бы «бек не запущен» у живого бека), а узел поднимается потоком и не мгновенно.
    pub fn answers(&self, serves: Serves) {
        *self.serves.lock().unwrap_or_else(|e| e.into_inner()) = Some(serves);
    }

    fn snapshot(&self) -> StatusView {
        self.view.lock().unwrap_or_else(|e| e.into_inner()).clone()
    }

    fn doer(&self) -> Option<Serves> {
        self.serves.lock().unwrap_or_else(|e| e.into_inner()).clone()
    }

    /// Комплект стоит в снимке С ПЕРВОЙ МИЛЛИСЕКУНДЫ, а не с первого `show`, и это не украшение (Important 2 ревью всей работы).
    ///
    /// Дверь принимает стуки раньше, чем держатель наберёт первый снимок: `open_at` поднимает поток приёма до возврата, а `show`
    /// случается только после холодного набора фактов. Набранный в эту щель `status` читал бы умолчание `StatusView`, то есть
    /// `kit: None`, и печатал бы «обслуживает другой комплект — какой именно, не сообщает» ПРО СЕБЯ ЖЕ. Ложь от живого, а ей верят
    /// больше, чем диску.
    ///
    /// Чинится здесь, а не подстановкой в `snapshot`: дверь открывают ПО комплекту (`open_at`), значит она его знает с рождения —
    /// и поле, которое всё равно заполняет только она, честнее завести сразу заполненным, чем чинить на каждом чтении. Выражение
    /// одно и то же, что у `show`, и оно же одно на оба места.
    fn new(kit: &Kit) -> Door {
        let kit = kit_mark(kit);
        let view = StatusView { kit: Some(kit.clone()), ..StatusView::default() };
        Door { view: Arc::new(Mutex::new(view)), serves: Arc::new(Mutex::new(None)), kit }
    }
}

/// Строки, которыми живой экземпляр рассказывает о себе человеку, — здесь, а не в `main.rs`, ровно затем, чтобы их проверял тест: разницу «о связи пока не сообщает» и «связей нет» человек обязан ПРОЧЕСТЬ словами, а не вывести из пустоты (ограничение «молчаливого ответа не бывает»).
///
/// Слово предмета — общая константа `SUBJECT`, а не своя: выключатель на экране, журнал и проверки называют его одними знаками, и `status` не имеет права назвать его иначе.
pub fn status_lines(v: &StatusView, mine: &Kit) -> Vec<String> {
    let on = if v.serving { "включён" } else { "выключен" };
    let mut out = vec![format!("Отвечает живой экземпляр: {} {on}.", crate::SUBJECT)];
    // Живой есть, но комплект у него ДРУГОЙ — и это первое, что человеку надо
    // прочесть: без этой строки всё сказанное ниже он отнёс бы к своему
    // комплекту, а оно про чужой. Слова общие с мостом (`ANOTHER_KIT`),
    // второго текста на тот же случай нет.
    // Молчать здесь нельзя ни в одном из двух случаев. Мост в этот самый миг
    // пишет в журнал «чужой комплект» — и `status`, промолчав, оставил бы
    // человека думать, что напечатанное ниже про его комплект. Сама сверка —
    // у `another_kit` и больше нигде.
    if let Some(why) = another_kit(v, mine) {
        out.push(format!("  {why}"));
    }
    match &v.cards {
        None => out.push("  о состоянии связи он пока не сообщает".into()),
        Some(cards) if cards.is_empty() => out.push("  ни одна карточка сейчас не связана".into()),
        Some(cards) => out.extend(cards.iter().map(|c| format!("  {:<16} {}", c.name, c.word))),
    }
    out
}

/// Живой экземпляр ответил не на тот вопрос. Беда проводки, а не человека, но молчать о ней нельзя: случай говорит, что по эту и ту сторону двери разные сборки программы.
pub const WRONG_ANSWER: &str = "живой экземпляр ответил не на тот вопрос — похоже, он другой версии; остановите его и запустите снова";

/// Что живой УМЕЕТ — одно место на оба пути подъёма (`gui::launch` и `fn serve` в сборке без окна): клиенты у двери одни, и делать по их вопросам положено одно и то же.
///
/// Берёт ровно то, чего нет на диске: ручку на живой узел и общий запас выданных кодов. Настройки, наоборот, читаются с диска на каждый вопрос — правда про соединения живёт в файле, и человек правит его при живом беке.
pub fn serves(kit: Kit, peer: crate::peer::Peer, codes: crate::codes::Codes, requests: crate::enroll::Requests) -> Serves {
    Arc::new(move |q| match q {
        // Снимок отдаёт сама дверь (`reply`), сюда `Status` не доходит; умолчание здесь — «ничего не знаю», и выдумывать за дверь нечего.
        Ask::Status => Answer::Status(StatusView::default()),
        Ask::Code { card } => Answer::Code(issue_for(&kit, &peer, &codes, card.as_deref())),
        Ask::Dial { code, card } => Answer::Dialled(dial_for(&kit, &peer, &code, card.as_deref())),
        // Уборка — ПЕРЕД обоими вопросами о заявках, и это не прихоть: мёртвая заявка, оставшаяся в списке, не только показывается
        // живой, но и мешает ответить соседней — отпечаток у них может быть один (`enroll::Requests::answer`). Окно чистит список
        // тиком, а у бека тика нет вовсе: здесь его тик — набранная команда.
        Ask::Requests => {
            sweep(&kit, &requests);
            Answer::Requests(Ok(waiting_now(&requests)))
        }
        Ask::Answer { fingerprint, card, said } => {
            sweep(&kit, &requests);
            Answer::Done(answer_for(&requests, &codes, &fingerprint, card.as_deref(), said))
        }
        // Книга допуска живёт на диске, и оба эти вопроса читают её оттуда заново — ровно как настройки выше и по тому же доводу:
        // правда про разрешения в файле, а человек правит его (и отзывает из окна) при живом беке.
        Ask::Peers { card } => Answer::Peers(peers_for(&kit, card.as_deref())),
        Ask::Revoke { card, fingerprint } => Answer::Done(revoke_for(&kit, &peer, &card, &fingerprint)),
    })
}

/// Убрать из списка то, чему там уже не место, и СКАЗАТЬ о пропавших заявках словами — в журнал, потому что экрана у бека нет.
///
/// Молчать нельзя по той же причине, по которой не молчит окно: заявка, на которую человек собирался ответить, исчезает, и без
/// строки он не узнает, почему. Слова общие с окном (`enroll::request_gone`), второго текста на тот же случай нет.
fn sweep(kit: &Kit, requests: &crate::enroll::Requests) {
    for card in requests.prune(std::time::Instant::now()) {
        crate::journal::write(kit, crate::journal::Kind::Say, &crate::enroll::request_gone(&card));
    }
}

/// Кто просит разрешения ПРЯМО СЕЙЧАС — только те заявки, на которые ещё можно ответить (`Pending::reachable`).
///
/// Истёкшая и отвеченная живыми не показываются, и мера у этого одна, та же, что у экрана: заявка, которой некуда ответить, не
/// поднимает строку первой и не зажигает «Разрешить». Своего счётчика срока здесь нет — `left` только рассказывает, сколько от
/// `enroll::DECISION` осталось (см. `Pending::left`).
pub fn waiting_now(requests: &crate::enroll::Requests) -> Vec<RequestView> {
    requests
        .lock()
        .iter()
        .filter(|p| p.reachable())
        .map(|p| {
            let full = p.request.peer.to_string();
            RequestView {
                card: p.request.card_name.clone(),
                short: crate::enroll::short_key(&full),
                fingerprint: full,
                says_name: crate::enroll::who_says(&p.request.says_name),
                left: p.left(),
            }
        })
        .collect()
}

/// Ответить заявке по отпечатку и сделать то, что из ответа следует.
///
/// Следствие ровно одно и оно общее с окном: дошедшее РАЗРЕШЕНИЕ гасит код карточки (`codes::Codes::forget` — там правило целиком).
/// Книгу допуска здесь не трогают вовсе: разрешение записывает сам разговор на шаге пятом, и второго места записи в продукте нет.
///
/// Слова — у окна (`enroll::answered`), и вид возврата говорит о коде выхода: `Err` значит «сделать не удалось» (заявки нет, их две,
/// отвечать уже некуда), и набранная команда уходит ненулевым кодом — тем же правилом, что `dial`.
pub fn answer_for(
    requests: &crate::enroll::Requests,
    codes: &crate::codes::Codes,
    fingerprint: &str,
    card: Option<&str>,
    said: Said,
) -> Result<String, String> {
    let d: crate::enroll::Decision = said.into();
    let done = requests.answer(fingerprint, card, d).map_err(str::to_string)?;
    if done.sent && d == crate::enroll::Decision::Allow {
        codes.forget(&done.card);
    }
    let (kind, text) = crate::enroll::answered(&done.name, d, done.sent);
    if done.sent {
        Ok(text)
    } else {
        // Разряд складывает `answered`, и спорить с ним нечем: беда — это «не сделано», и человеку на неё нужен ненулевой код.
        debug_assert_eq!(kind, crate::journal::Kind::Warn);
        Err(text)
    }
}

/// Карточки с таким именем в настройках нет — ОДНИ слова на оба вопроса о книге допуска (`peers` и `revoke`). Разрешения числятся за
/// карточкой, и без неё обеим командам сказать человеку нечего, кроме этого.
///
/// Свои слова, а не `codes::gone`: тот про выдачу кода и кончается «код выдавать некому» — приписывать его сюда значило бы сказать
/// человеку, пришедшему за списком разрешений, про код, которого он не просил.
fn no_such_card(card: &str) -> String {
    format!("Карточки «{card}» в настройках нет — разрешения числятся за карточкой, и без неё их не показать и не отозвать.")
}

/// Отпечаток не называет ни одной зачисленной стороны ЭТОЙ карточки. Отказ про опечатку, и он нарочно другой, чем «их несколько»
/// (то же правило, что у заявок: `enroll::NO_SUCH_REQUEST` против `AMBIGUOUS_FINGERPRINT`) — смешай их, и человек, набравший
/// отпечаток с ошибкой, искал бы вторую зачисленную сторону, которой нет.
pub const NO_SUCH_PARTY: &str = "У этой карточки нет зачисленной стороны с таким отпечатком — проверьте отпечаток и имя карточки: обе \
                                 строки печатает 1c-connect peers.";

/// Описанию отвечает НЕ ОДНА зачисленная сторона этой карточки — выбирать за человека нельзя.
///
/// Случай редкий и ровно тот, ради которого сверка идёт равенством, а не хвостом (обзор безопасности 16.11): полный ключ у зачисленных
/// к одной карточке сторон разный всегда (пара «карточка + ключ» в книге одна), а вот коротким сокращением в четыре знака двое совпасть
/// могут — и подгоняются эти четыре знака за секунды. Здесь подгонка получает видимый отказ, а человек — совет назвать ключ целиком.
pub const AMBIGUOUS_PARTY: &str = "Этому описанию отвечает сразу несколько зачисленных сторон — которую из них отзывать, отсюда не \
                                   видно.\nНазовите отпечаток ЦЕЛИКОМ: его печатает 1c-connect peers.";

/// Кому разрешено подключаться — из книги допуска, прочитанной с диска прямо сейчас.
///
/// Карточки берутся из НАСТРОЕК, а не из книги (`Book::cards`), и это не недосмотр: `revoke` адресуется ИМЕНЕМ карточки, а у ключа,
/// осиротевшего после правки `id` руками, имени нет вовсе — показать его значило бы напечатать строку, которую нечем набрать. Про такие
/// записи человеку говорит окно отдельными словами (`gui::save::note_orphans`), и второго рассказа о них здесь не заводится.
pub fn peers_for(kit: &Kit, card: Option<&str>) -> Result<Vec<PartyView>, String> {
    let cfg = settings(kit)?;
    let book = crate::enrolled::Book::open(kit.state())?;
    let asked: Vec<&crate::cfg::Connection> = match card {
        Some(name) => vec![cfg.by_name(name).ok_or_else(|| no_such_card(name))?],
        None => cfg.connections.iter().collect(),
    };
    Ok(asked.iter().flat_map(|c| book.of(&c.id()).into_iter().map(|p| party_view(&cfg, c, &p))).collect())
}

/// Одна зачисленная сторона готовыми словами — одно место, где они складываются.
fn party_view(cfg: &crate::cfg::Cfg, c: &crate::cfg::Connection, p: &crate::enrolled::Party) -> PartyView {
    let full = p.key.to_string();
    PartyView {
        card: c.name.clone(),
        short: crate::enroll::short_key(&full),
        fingerprint: full,
        // Самоназвание в книге уже вычищено (`wire::SaysName`), но СЛОВА о нём — «Компьютер без имени» и кавычки вокруг названного —
        // одни на диалог разрешения, список заявок и этот список (`enroll::who_says`), и второго их вида здесь нет.
        says_name: crate::enroll::who_says(&crate::wire::SaysName::new(&p.says_name)),
        access: crate::peer::access_label(cfg, c, p.peer_write).to_string(),
    }
}

/// Забрать у ОДНОЙ стороны разрешение — ровно то же дело, что делает кнопка «Отозвать разрешение» в карточке
/// (`gui::panel::revoke_party`), и теми же двумя действиями: запись из книги и живой поток этой стороны.
///
/// **Оба действия обязаны случиться вместе.** Запись без обрыва потока — это отзыв, который начнёт действовать неизвестно когда:
/// спека говорит «отправляется и тут же рвёт потоки этой базы», и зачисленная сторона, чей поток пережил отзыв, продолжает ходить в
/// базу по уже снятому разрешению. Обрыв без записи — наоборот, досада: та сторона вернётся на следующем круге и будет впущена.
///
/// Сторона ищется среди зачисленных к НАЗВАННОЙ карточке, и ищется тем же сличителем, что заявки (`enroll::names`): человек набирает
/// ту же строку, которую видит в списке, и правило «что считается названным» у обоих одно. Совпало больше одной — отказ словами, а не
/// выбор первой.
pub fn revoke_for(kit: &Kit, peer: &crate::peer::Peer, card: &str, fingerprint: &str) -> Result<String, String> {
    let cfg = settings(kit)?;
    let key = cfg.by_name(card).map(crate::cfg::Connection::id).ok_or_else(|| no_such_card(card))?;
    let mut book = crate::enrolled::Book::open(kit.state())?;
    let hits: Vec<crate::enrolled::Party> = book.of(&key).into_iter().filter(|p| crate::enroll::names(&p.key, fingerprint)).collect();
    let [one] = &hits[..] else {
        return Err(if hits.is_empty() { NO_SUCH_PARTY } else { AMBIGUOUS_PARTY }.to_string());
    };
    book.revoke(&key, one.key)?;
    // Живой поток этой стороны снимается в ту же секунду, а не на её следующем круге, — см. довод в докстроке выше. Узел о такой
    // стороне может не знать вовсе (она сейчас не на связи), и это не беда: вожжи просто нечего дёргать.
    peer.revoked(&key, one.key);
    Ok(crate::enrolled::revoked_words(card, one.key))
}

/// Список заявок человеку — строками, и здесь, а не в `main.rs`: тот же довод, что у `status_lines`, — слова проверяет тест.
///
/// Пустой список получает СЛОВА, а не пустоту: молчаливый ответ человек прочёл бы как «команда не сработала» (ограничение
/// «молчаливого ответа не бывает»).
///
/// **Отпечатка два, и у каждого своё дело** (обзор безопасности 16.11). Короткий — для ГОЛОСА: его называют по телефону, и четырёх
/// знаков для «тот ли это, кого я жду» довольно. Полный — для ОТВЕТА: коротким ответить однозначно нельзя, он подбирается перебором
/// за секунды, и две заявки с одинаковым хвостом получат отказ (`enroll::AMBIGUOUS_FINGERPRINT`). Поэтому готовая команда с полным
/// ключом печатается строкой — человеку её копировать, а не переписывать глазами.
pub fn request_lines(v: &[RequestView]) -> Vec<String> {
    if v.is_empty() {
        return vec!["Разрешения сейчас никто не просит.".into()];
    }
    let mut out = vec![format!("Просят разрешения подключиться ({}):", v.len())];
    for r in v {
        out.push(String::new());
        out.push(format!("  «{}» · {} · осталось {} мин", r.card, r.says_name, r.left.as_secs().div_ceil(60)));
        out.push(format!("  сверить голосом: {}", r.short));
        // Имя карточки — в готовой строке ВСЕГДА, а не когда «понадобится»: ключ заявки это пара (отпечаток, карточка), и одна
        // сторона законно просит разрешения сразу по нескольким. Печатай строку без имени — человек получал бы отказ «их
        // несколько» ровно в том случае, ради которого список и читают.
        out.push(format!("  ответить: 1c-connect allow {} \"{}\"", r.fingerprint, r.card));
        out.push("            (или decline вместо allow)".into());
    }
    out
}

/// Список зачисленных человеку — строками, и здесь, а не в `main.rs`: тот же довод, что у `request_lines`, — слова проверяет тест.
///
/// Пустой список получает СЛОВА, и слова эти знают, о чём спрашивали: назвал человек карточку — о ней и сказано. Ответь «подключаться
/// никто не вправе» на вопрос про одну карточку — и человек прочёл бы это про все свои, то есть про разрешения, которые у него есть.
///
/// Готовая строка отзыва печатается с ПОЛНЫМ ключом и с именем карточки — обе половины адреса (`Ask::Revoke`), и обе всегда: ключ
/// коротким видом не однозначен (его подбирают), а карточку `revoke` требует и не угадывает.
pub fn peer_lines(v: &[PartyView], card: Option<&str>) -> Vec<String> {
    if v.is_empty() {
        return vec![match card {
            Some(c) => format!("«{c}»: подключаться пока никому не разрешено."),
            None => "Подключаться пока никому не разрешено.".to_string(),
        }];
    }
    let mut out = vec![format!("Разрешено подключаться ({}):", v.len())];
    for p in v {
        out.push(String::new());
        out.push(format!("  «{}» · {} · {}", p.card, p.says_name, p.access));
        out.push(format!("  сверить голосом: {}", p.short));
        out.push(format!("  отозвать: 1c-connect revoke {} \"{}\"", p.fingerprint, p.card));
    }
    out
}

/// Настройки соединений — с ДИСКА на каждый вопрос, а не из памяти держателя: правда про соединения живёт в файле, и человек правит его при живом беке.
fn settings(kit: &Kit) -> Result<crate::cfg::Cfg, String> {
    crate::cfg::Cfg::load_unchecked(kit).map_err(|e| format!("Настройки соединений не прочитались: {e:#}"))
}

/// Имя карточки, о которой спрашивают, — названное либо текущее соединение.
fn named(cfg: &crate::cfg::Cfg, card: Option<&str>) -> String {
    card.map_or_else(|| cfg.current().name.clone(), str::to_string)
}

fn issue_for(kit: &Kit, peer: &crate::peer::Peer, codes: &crate::codes::Codes, card: Option<&str>) -> Result<crate::codes::Issued, String> {
    let cfg = settings(kit)?;
    crate::codes::issue(kit, &cfg, Some(peer), codes, &named(&cfg, card), true)
}

/// Позвонить и ДОЖДАТЬСЯ исхода (решение ведущего: человеку в консоли нужен ответ, а не обещание).
///
/// Срок — `DIAL_WAIT`, то есть ровно срок самого разговора: ждать дольше нечего (на той стороне к этому времени кончился срок решения), а меньше значило бы бросить трубку раньше человека у чужого экрана. Дверь вокруг отмеряет на `ASK_WAIT` больше — этот срок обязан истечь ПЕРВЫМ, иначе сказанные ниже слова до человека не доедут вовсе (см. `Ask::wait`, там беда целиком).
fn dial_for(kit: &Kit, peer: &crate::peer::Peer, code: &str, card: Option<&str>) -> Result<crate::enroll::Outcome, String> {
    let cfg = settings(kit)?;
    let name = named(&cfg, card);
    let key = cfg.by_name(&name).map(crate::cfg::Connection::id).ok_or_else(|| crate::codes::gone(&name))?;
    peer.dial_waiting(&key, &name, code)?
        .recv_timeout(DIAL_WAIT)
        .map_err(|_| format!("«{name}»: ответа так и не было. Проверьте, запущена ли программа на том компьютере, и позвоните снова."))?
}

/// Исход звонка СЛОВАМИ. `Err` — «не сделано»: команда называет причину и уходит ненулевым кодом (решение ведущего; у `status` это не так — он печатает то, за чем пришли).
///
/// Слова берутся у ЗАЧИСЛЕНИЯ и нигде не сочиняются: отказ уже произнесён той стороной (`Refuse::text`), и второй словарь исходов — ровно то, против чего эта ветка и воюет. Своё здесь одно — имя карточки впереди, тем же видом, каким о ней говорит журнал окна.
pub fn dialled_words(card: &str, o: &crate::enroll::Outcome) -> Result<String, String> {
    match o {
        // Обе пары говорят человеку одно и то же: подключено, и вот с каким доступом. Разница между ними — чья база, а это про
        // устройство связи, а не про то, чем кончился звонок.
        crate::enroll::Outcome::Enrolled(base) | crate::enroll::Outcome::EnrolledHere(base) => {
            Ok(format!("«{card}»: подключено, {}", crate::peer::access_word(base.write)))
        }
        crate::enroll::Outcome::Already(base) => Ok(format!("«{card}»: подключено, {}", crate::peer::access_word(base.write))),
        crate::enroll::Outcome::NotEnrolled(no) => Err(format!("«{card}»: {}", no.text)),
    }
}

/// Имя двери — единственное место, где оно строится (тот же довод, что у `single_instance::show_event_name`: вторая формулировка смотрела бы не на тот объект). Ключ — `single_instance::account`, тот же, что у замка, и это буквально один ключ: дверь и есть замок.
///
/// Чистки имени здесь нет и не нужно: SID и uid состоят из латиницы, цифр и дефиса, и годятся в имя канала и в имя файла как есть. Гашение, которое стояло тут прежде, теряло различия и схлопывало разные учётные записи в одну (см. `single_instance::account`).
pub fn door_name(account: &str) -> String {
    format!("1c-connect-door-{account}")
}

/// Кто за дверью под этим именем. Спрашивается тем же `server_is_ours`, которым клиент сторожит себя от самозванца, — второго правила «кто там» в продукте нет.
///
/// **`Nobody` значит «никого не нашли», а не «там свои».** Чужим зовётся только ДОКАЗАННО чужой: соединение состоялось, и ядро назвало за ним не нашу учётную запись. Не достучались вовсе — ни двери, ни доказательства, и обвинять по такому молчанию мы никого не станем: слова про постороннего посылают человека к нам, и ошибаться в них дороже, чем промолчать.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Knocked {
    Ours,
    Stranger,
    Nobody,
}

pub(crate) fn who_answers(name: &str) -> Knocked {
    let Ok(rt) = runtime() else { return Knocked::Nobody };
    rt.block_on(async {
        match knock(name).await {
            Ok(stream) if server_is_ours(&stream).is_ok() => Knocked::Ours,
            Ok(_) => Knocked::Stranger,
            Err(_) => Knocked::Nobody,
        }
    })
}

/// Метка комплекта — его каталог состояния в каноническом виде, и единственное место, где она строится. Правило «тот же ли это путь» берётся у `holder::normal_path` и здесь не сочиняется: второе такое правило разошлось бы с первым при первой же правке.
///
/// Каталог СОСТОЯНИЯ, а не корень комплекта: на Linux состояние живёт отдельно от общего корня (`ops_host::wire_state`), и два рабочих места на одном комплекте различаются именно им.
pub(crate) fn kit_mark(kit: &Kit) -> String {
    crate::holder::normal_path(kit.state())
}

/// Слова человеку, когда живой экземпляр есть, но обслуживает он не тот комплект, о котором спрашивают. Живут один раз и здесь, рядом с вердиктом, — а набирает их на всех `another_kit`: в журнал моста, в вывод `status` и в отказ каждой команде сопряжения (тот же приём, что у `gate::refuse_to_serve`).
pub const ANOTHER_KIT: &str = "коннектор этой учётной записи запущен, но обслуживает другой комплект";

/// Тот же случай, но комплекта живой не назвал вовсе, — сборка по ту сторону двери другой версии. Слова живут ОДИН раз и здесь, по тому же правилу, что соседняя константа: прежде это были два литерала, совпадавшие лишь потому, что их писали двумя руками (находка ревью задачи 14, закрыта задачей 9). Зовущий у них теперь один — `another_kit`, и он же раздаёт их всем (ревью всей работы, Critical 1).
///
/// Функция, а не константа: своей добавки к `ANOTHER_KIT` без склейки на месте не выразить, а склейка на месте и была бы вторым литералом.
///
/// Случай настоящий, но межверсионный: своя дверь комплект называет всегда и с первой миллисекунды (`Door::new`), а `None` приходит только от сборки, которая поля ещё не знает. Живым экземпляром ЭТОЙ сборки ветка не достижима, тестом — достижима и проверена (`status_lines` берёт снимок, а не дверь).
pub fn another_kit_unnamed() -> String {
    format!("{ANOTHER_KIT} — какой именно, он не сообщает (похоже, он другой версии)")
}

/// Обслуживается ли ЭТОТ комплект живым экземпляром учётной записи — три исхода, и средний из них не «нет».
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Served {
    /// Жив, обслуживает, и комплект тот самый.
    Mine,
    /// Жив и обслуживает, но НЕ этот комплект. Внутри — слова человеку: молчаливого «нет» здесь быть не должно, иначе человек ищет мёртвый коннектор вместо живого, который просто занят другим.
    Another(String),
    /// Не отвечает вовсе либо отвечает «не обслуживаю».
    No,
}

/// Обслуживается ли ЭТОТ комплект — признак, который до задачи 14 держался отдельным объектом ядра (именованный мьютекс на Windows, `flock` каталога состояния на Linux).
///
/// **Почему тот объект ушёл.** Он создавался БЕЗ префикса, то есть был виден только в своём сеансе, и единицу считал как «сеанс × учётка × комплект». На машине утреннего прогона окно поднимает задача планировщика — в своём сеансе; человек из своего сеанса спросил бы признак и получил «не обслуживает» при живом и работающем коннекторе: агенты выглядели бы выключенными, а сторож моста (`orphan::guard_owner`) увёл бы мост. Ровно та беда, которую задача чинила этажом выше, оставленная этажом ниже.
///
/// Держатель и так знает, обслуживает ли он: `serving` лежит в его снимке с задачи 5. Значит спрашивать надо его, а не второй объект про то же самое. Ответ вышел строже прежнего: дверь отвечает, только если держатель ЖИВ и обслуживает, а чужую дверь под нашим именем `ask_at` отсекает до первого слова (`STRANGER_DOOR`).
pub(crate) fn served_at(name: &str, mine: &Kit) -> Served {
    let Ok(Answer::Status(v)) = ask_at(name, Ask::Status) else { return Served::No };
    if !v.serving {
        return Served::No;
    }
    match another_kit(&v, mine) {
        None => Served::Mine,
        Some(why) => Served::Another(why),
    }
}

/// **Тот ли это комплект** — единственное место, где снимок живого сверяют с комплектом спрашивающего, и единственное, где на отказ набираются слова. `None` — наш; `Some(слова)` — не наш, и вот что сказать человеку.
///
/// Одна мера на ТРОИХ потребителей: вердикт мосту (`served_at`), строку человеку (`status_lines`) и сторожа у всех команд сопряжения (`ask`). Прежде сверок было две, писаных одна с другой, и они совпадали лишь потому, что их писали в один час; а семь команд не сверяли комплект вовсе (Critical 1 ревью всей работы).
///
/// `None` в снимке — сборка другой версии по ту сторону двери (см. `StatusView::kit`): утверждать за неё «обслуживает наш» нельзя — чего не доказали, того не утверждаем, — и человеку это говорится словами, а не молчаливым «нет».
///
/// **Отказ называет и причину, и что делать** — правило ветки, образец рядом (`gate::refuse_to_serve`: «Устраните причину и запустите её снова»). Прежде отсюда уходил голый диагноз с путём чужого комплекта, и человек у терминала гадал: гасить живого, сменить `--kit` или это поломка. Выходов у него ровно два, и названы оба.
///
/// Фраза одна на обе ветви нарочно и на путь к комплекту не ссылается: в нижней ветви пути НЕТ (живой его не назвал), и «его путь назван выше» было бы там ложью — ровно тем разрядом дефекта, который эта ветка ловит всю дорогу.
fn another_kit(v: &StatusView, mine: &Kit) -> Option<String> {
    let case = match &v.kit {
        Some(k) if *k == kit_mark(mine) => return None,
        // Сказал, какой, и это не наш.
        Some(k) => format!("{ANOTHER_KIT}: {k}"),
        None => another_kit_unnamed(),
    };
    Some(format!("{case}. Работайте с тем комплектом, который он обслуживает, либо остановите живой экземпляр и запустите нужный."))
}

/// Спросить живого — сторона клиента. Своего бека не поднимает и ничем не владеет: нет живого — `NO_BACK_END` словами.
///
/// **Сверка комплекта стоит ЗДЕСЬ, а не у каждой команды** (Critical 1 ревью всей работы). Дверь адресуется учётной записью, а живая
/// копия обслуживает ОДИН комплект; у человека же копий комплекта обычно две — эталонная и рабочая. Набранный `1c-connect --kit B code`
/// при живом коннекторе на A читал бы настройки B, печатал имя карточки из B — а код выдавал бы карточке из A: слова и дело
/// расходятся. То же у `dial`, и хуже у `allow`/`revoke` — решение человека ложилось бы в чужую книгу.
///
/// Проверок семь не заводится нарочно: семь мер на один вопрос — главный разряд дефектов этого дерева, и восьмая команда завелась бы
/// без сверки молча. Сверяет `another_kit`, его же словами и отказываем; второго текста нет.
///
/// **`Status` — единственное исключение, и оно по существу.** Это ровно тот вопрос, ОТВЕТОМ на который и является «чей комплект»:
/// запретив его по чужому комплекту, мы отняли бы у человека единственный способ узнать, кто занял дверь. Он и отвечает про чужой
/// комплект словами (`status_lines`) — ему за этим и звонят.
///
/// Лишний стук стоит одного обмена по локальному каналу и платится один раз на команду; молчаливое действие на чужой комплект стоит
/// дороже.
pub fn ask(mine: &Kit, q: Ask) -> Result<Answer, String> {
    let account = account().map_err(|e| format!("живой экземпляр не спрошен: {e}"))?;
    let name = door_name(&account);
    if matches!(q, Ask::Status) {
        return ask_at(&name, q);
    }
    let Answer::Status(v) = ask_at(&name, Ask::Status)? else { return Err(WRONG_ANSWER.to_string()) };
    if let Some(why) = another_kit(&v, mine) {
        return Err(why);
    }
    ask_at(&name, q)
}

/// Отдельный рантайм на каждую сторону двери: клиент — набранная команда, у которой своего рантайма нет вовсе, а бек открывает дверь до того, как поднимет сеанс (у окна рантайма на главном потоке не будет никогда — там GPUI).
fn runtime() -> io::Result<tokio::runtime::Runtime> {
    tokio::runtime::Builder::new_current_thread().enable_io().enable_time().build()
}

/// Ответ на один стук. Разговор — ровно один вопрос и ровно один ответ: держать канал открытым между вопросами нечего, а закрытый канал на той стороне `Frame::read` отличает от обрыва словами (`code::CLOSED`).
///
/// Сроки здесь двое и разные. Вопроса ждём `ASK_WAIT`: открывший канал и замолчавший иначе запер бы экземпляр канала навсегда (`Frame::read` нарочно без своего срока). Самого дела ждём столько, сколько оно бывает (`Ask::wait`) — звонок ждёт человека у чужого экрана и в пять секунд не укладывается никогда.
async fn answer<S: AsyncRead + AsyncWrite + Unpin>(stream: &mut S, door: &Door) {
    let q: Ask = match tokio::time::timeout(ASK_WAIT, Frame::read(stream)).await {
        Ok(Ok(q)) => q,
        // Молчание и мусор в дверь — не событие для человека: стукнуть в неё может что угодно, а отвечать мы умеем только своим.
        _ => return,
    };
    let Ok(a) = tokio::time::timeout(q.wait(), reply(door, q)).await else {
        // Срок дела вышел — отвечать нечем, и клиент скажет об этом своими словами (его срок на `ASK_WAIT` длиннее, см. `Ask::wait`).
        return;
    };
    let _ = Frame::write(stream, &a).await;
}

/// Что отвечает на вопрос. `Status` — сама дверь из своего снимка: он лежит в ней, и спрашивать его у держателя не у кого. Остальное делает исполнитель держателя (`Serves`), а его ещё может не быть — узел поднимается не мгновенно, и тогда человеку говорится то же самое, что говорит окно в ту же щель.
async fn reply(door: &Door, q: Ask) -> Answer {
    if matches!(q, Ask::Status) {
        return Answer::Status(door.snapshot());
    }
    // Живой есть, а делать ещё нечем: узел поднимается потоком и не мгновенно. Слова — общие с окном (`peer::NOT_READY`), второго текста на тот же случай не заводим.
    let Some(doer) = door.doer() else { return refused(&q, crate::peer::NOT_READY.to_string()) };
    let asked = q.clone();
    // Отдельным потоком блокирующих задач: дело ЖДЁТ (звонок — до пяти с половиной минут), а рантайм двери однопоточный — заняв его собой, звонок запер бы и соседний `status`.
    match tokio::task::spawn_blocking(move || (doer)(q)).await {
        Ok(a) => a,
        // Исполнитель запаниковал. Сказать нечего, кроме правды: дело не сделано, а причина — в журнале, куда паника и легла.
        Err(_) => refused(&asked, "живой экземпляр не справился с командой — что случилось, сказано в его журнале".into()),
    }
}

/// Отказ САМОГО дела — тем видом ответа, которого вопрос ждёт. Вид не выдумывается: ответ без своего вопроса этой дверью не ходит, и клиент, получивший чужой вид, прочёл бы `WRONG_ANSWER` там, где ему сказали дело.
fn refused(q: &Ask, why: String) -> Answer {
    match q {
        // Снимок у `Status` отвечает сама дверь, и до сюда он не доходит; умолчание здесь — «ничего не знаю», и это честнее выдуманного.
        Ask::Status => Answer::Status(StatusView::default()),
        Ask::Code { .. } => Answer::Code(Err(why)),
        Ask::Dial { .. } => Answer::Dialled(Err(why)),
        Ask::Requests => Answer::Requests(Err(why)),
        Ask::Answer { .. } | Ask::Revoke { .. } => Answer::Done(Err(why)),
        Ask::Peers { .. } => Answer::Peers(Err(why)),
    }
}

/// Слова на отказ самого разговора.
///
/// Словарь `wire::Refuse` — словарь СОПРЯЖЕНИЯ, и его ТЕКСТ писан для разговора двух машин: «На том компьютере закрыли связь… подключитесь заново». В двери на том конце не тот компьютер, а свой же процесс на этой машине, и такие слова человека обманывают (находка ревью круга 2 — прежде сюда подставлялся весь текст). Поэтому наружу идут наши слова, а от чужого словаря берётся только КОД — короткое машинное имя причины, годное для диагностики и ничего не обещающее человеку.
fn not_answered(r: &wire::Refuse) -> String {
    format!("живой экземпляр не ответил (причина: {})", r.code.as_str())
}

/// Отказ, который значит «двери нет»: на Windows канала с таким именем не существует (`NotFound`), на Linux сокет есть, а слушателя за ним нет (`ConnectionRefused`) либо файла нет вовсе.
fn no_door(e: &io::Error) -> bool {
    matches!(e.kind(), io::ErrorKind::NotFound | io::ErrorKind::ConnectionRefused)
}

#[cfg(windows)]
type Knock = tokio::net::windows::named_pipe::NamedPipeClient;
#[cfg(not(windows))]
type Knock = tokio::net::UnixStream;

/// Путь именованного канала — имя двери в пространстве имён каналов этой машины.
#[cfg(windows)]
fn pipe_path(name: &str) -> String {
    format!(r"\\.\pipe\{name}")
}

/// Путь сокета: имя двери файлом в каталоге времени выполнения УЧЁТНОЙ ЗАПИСИ, а не комплекта (задача 14).
///
/// Прежде он лежал в `Kit::state`, то есть считал единицей комплект: два комплекта одной учётной записи получали по своей двери, по своему замку и по своей копии программы — а единица продукта одна, и это учётная запись на машине. Заодно это делает правдой довод, за который ревью задачи 5 поставило Critical: «сокет лежит в нашем каталоге» перестало быть выводом и стало замером — каталог заводим и проверяем мы сами (`runtime_dir`).
#[cfg(not(windows))]
fn sock_path(name: &str) -> io::Result<std::path::PathBuf> {
    Ok(runtime_dir()?.join(format!("{name}.sock")))
}

/// Каталог времени выполнения учётной записи. `$XDG_RUNTIME_DIR` — его заводит на вход в систему сам systemd: свой на каждую учётную запись, права 0700, владелец — она же, и чистится при выходе. Нет его (служба, cron, контейнер без systemd) — заводим `$HOME/.cache/1c-connect/run` сами и теми же правами.
///
/// **Общего `/tmp` в этой цепочке нет вовсе, и это не перестраховка.** Запасным каталогом сперва стоял `/tmp/1c-connect-<uid>`, и он отдавал замок соседу по машине одной командой: имя предсказуемо (в нём только uid), сосед заводит каталог первым — и наша проверка владельца отказывает НАВСЕГДА, то есть любой местный пользователь запирает программу чужой учётной записи, ничего не взламывая. Запасной каталог обязан лежать там, где имя принадлежит нам по построению, — в домашнем каталоге.
///
/// **Чужой существующий не принимается молча.** Каталог заводится `mkdir`-ом с правами сразу (`DirBuilder::mode`, без щели между созданием и `chmod`), и отказ «уже есть» — не успех: тогда найденное проверяется `symlink_metadata` — по самому имени, а не по тому, куда оно ведёт (ссылку, подставленную на чужой файл, `metadata` пропустила бы, а права мы поставили бы на её цель). Настоящий каталог и наш по владельцу — только после этого ему ставятся права.
#[cfg(not(windows))]
fn runtime_dir() -> io::Result<std::path::PathBuf> {
    use std::os::unix::fs::{DirBuilderExt, MetadataExt, PermissionsExt};
    if let Some(d) = std::env::var_os("XDG_RUNTIME_DIR").filter(|d| !d.is_empty()) {
        return Ok(std::path::PathBuf::from(d));
    }
    let home = std::env::var_os("HOME")
        .map(std::path::PathBuf::from)
        .filter(|h| h.is_absolute())
        .ok_or_else(|| io::Error::other("ни XDG_RUNTIME_DIR, ни HOME не говорят, где ваш каталог, — управляющую дверь открывать негде"))?;
    let dir = home.join(".cache/1c-connect/run");
    if let Some(up) = dir.parent() {
        std::fs::create_dir_all(up)?;
    }
    match std::fs::DirBuilder::new().mode(0o700).create(&dir) {
        Ok(()) => return Ok(dir),
        Err(e) if e.kind() == io::ErrorKind::AlreadyExists => {}
        Err(e) => return Err(e),
    }
    let found = std::fs::symlink_metadata(&dir)?;
    if !found.is_dir() || !crate::holder::same_owner(&found.uid().to_string(), &account()?) {
        return Err(io::Error::new(
            io::ErrorKind::PermissionDenied,
            format!("{} — не ваш каталог: дверь в нём открывать нельзя, уберите его и запустите снова", dir.display()),
        ));
    }
    std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o700))?;
    Ok(dir)
}

/// Приём — своим потоком со своим рантаймом (тот же приём и та же причина, что у узла и сеанса, см. `peer.rs`): у окна главный поток занят GPUI, а у `serve` — ожиданием Ctrl+C, и ждать стука там нельзя ни тому, ни другому.
///
/// Каждый стук — своей задачей, и потолок «очередь на время одного ответа» снят задачей 6 вместе с поводом так считать: ответом перестал быть один снимок из памяти. `dial` ждёт человека у чужого экрана до пяти с половиной минут (`Ask::wait`), и обслуживай дверь стуки по очереди — набранный рядом `status` всё это время читал бы «бек не запущен» при живом беке. Сроки на разговор остаются и теперь их двое — см. `answer`.
#[cfg(windows)]
pub(crate) fn open_at(name: &str, kit: &Kit) -> io::Result<Door> {
    let path = pipe_path(name);
    // Права назначаются ДО первого экземпляра канала и держатся всё время приёма: каждый следующий экземпляр создаётся с тем же дескриптором, иначе второй и дальнейшие достались бы умолчанию — то есть дверь была бы заперта только до первого стука.
    let rights = Rights::of_account(&account()?)?;
    let rt = runtime()?;
    // Слушатель заводится ЗДЕСЬ, до возврата, а не внутри потока: отказ — занятое имя, запрет прав — обязан достаться тому, кто дверь открывал, а не пропасть в чужом потоке. Тот же довод, что у `single_instance::serve_show_requests`, где дескриптор события заводится до запуска потока.
    let mut server = {
        let _in_rt = rt.enter();
        pipe(&path, &rights, true)?
    };
    let door = Door::new(kit);
    let mine = door.clone();
    let kit = kit.clone();
    std::thread::spawn(move || {
        rt.block_on(async move {
            loop {
                if server.connect().await.is_err() {
                    // Молча уйти нельзя: дверь останется жива именем, а отвечать перестанет — см. `DOOR_STOPPED`.
                    crate::journal::write(&kit, crate::journal::Kind::Fail, DOOR_STOPPED);
                    return;
                }
                // Следующий экземпляр канала — сразу: имя обязано остаться занятым, пока мы заняты этим стуком, иначе клиент, пришедший в эту долю секунды, прочёл бы «бек не запущен» при живом беке.
                let Ok(next) = pipe(&path, &rights, false) else { return };
                let mut taken = std::mem::replace(&mut server, next);
                let mine = mine.clone();
                tokio::spawn(async move { answer(&mut taken, &mine).await });
            }
        })
    });
    Ok(door)
}

/// Дескриптор безопасности двери: полный доступ (`GA`) только нашей учётной записи и SYSTEM, `D:P` — DACL защищён, ничего не наследуется.
///
/// SDDL строкой, а не сборка ACL своими руками: строка читается глазами при разборе беды и вся видна в одном месте, а ручная сборка — три вызова подряд, каждый из которых может соврать молча и оставить дверь открытой.
#[cfg(windows)]
struct Rights(*mut std::ffi::c_void);

// Дескриптор безопасности — просто память, которую мы держим и освобождаем сами; переносить её между потоками безопасно (тот же довод, что у `single_instance::Guard`).
#[cfg(windows)]
unsafe impl Send for Rights {}

#[cfg(windows)]
impl Drop for Rights {
    fn drop(&mut self) {
        // SAFETY: указатель отдал `ConvertStringSecurityDescriptorToSecurityDescriptorW`, он же велит освобождать его `LocalFree`; второй раз `Drop` не зовут.
        unsafe { windows_sys::Win32::Foundation::LocalFree(self.0) };
    }
}

#[cfg(windows)]
impl Rights {
    fn of_account(sid: &str) -> io::Result<Rights> {
        use windows_sys::Win32::Security::Authorization::{ConvertStringSecurityDescriptorToSecurityDescriptorW, SDDL_REVISION_1};
        let sddl = crate::single_instance::wide(&format!("D:P(A;;GA;;;{sid})(A;;GA;;;SY)"));
        let mut sd = std::ptr::null_mut();
        // SAFETY: строка нуль-терминирована и жива до конца вызова; память под дескриптор выделяет сама функция, освобождает `Drop` выше.
        let ok =
            unsafe { ConvertStringSecurityDescriptorToSecurityDescriptorW(sddl.as_ptr(), SDDL_REVISION_1, &mut sd, std::ptr::null_mut()) };
        if ok == 0 {
            let e = std::io::Error::last_os_error();
            return Err(std::io::Error::new(e.kind(), format!("права управляющей двери не собрались (SDDL для {sid}): {e}")));
        }
        Ok(Rights(sd))
    }

    fn attrs(&self) -> windows_sys::Win32::Security::SECURITY_ATTRIBUTES {
        windows_sys::Win32::Security::SECURITY_ATTRIBUTES {
            nLength: std::mem::size_of::<windows_sys::Win32::Security::SECURITY_ATTRIBUTES>() as u32,
            lpSecurityDescriptor: self.0,
            bInheritHandle: 0,
        }
    }
}

/// Один экземпляр канала с нашими правами. `first` — тот самый `first_pipe_instance`: он ручается, что имя не занято никем, и его отказ не молчит, а получает слова (`NAME_TAKEN`) — занятое имя значит либо вторую копию, либо самозванца, и человеку это надо прочесть.
#[cfg(windows)]
fn pipe(path: &str, rights: &Rights, first: bool) -> io::Result<tokio::net::windows::named_pipe::NamedPipeServer> {
    use tokio::net::windows::named_pipe::ServerOptions;
    use windows_sys::Win32::Foundation::{ERROR_ACCESS_DENIED, ERROR_PIPE_BUSY};
    let mut attrs = rights.attrs();
    let mut opts = ServerOptions::new();
    opts.first_pipe_instance(first);
    // SAFETY: `attrs` жив до конца вызова и указывает на дескриптор, который держит `rights`; функция только читает его, себе не оставляя.
    let made = unsafe { opts.create_with_security_attributes_raw(path, std::ptr::from_mut(&mut attrs).cast()) };
    match made {
        Err(e) if first && matches!(e.raw_os_error(), Some(c) if c == ERROR_ACCESS_DENIED as i32 || c == ERROR_PIPE_BUSY as i32) => {
            Err(io::Error::new(io::ErrorKind::AddrInUse, format!("{NAME_TAKEN} ({e})")))
        }
        other => other,
    }
}

/// То же, что на Windows, но сокетом в каталоге времени выполнения учётной записи — см. докстроку выше и заголовок модуля.
#[cfg(not(windows))]
pub(crate) fn open_at(name: &str, kit: &Kit) -> io::Result<Door> {
    use std::os::unix::fs::PermissionsExt;
    use tokio::net::UnixListener;
    let path = sock_path(name)?;
    if path.exists() {
        // Файл есть — два разных случая, и путать их нельзя. За ним ОТВЕЧАЮТ: имя занято (вторая копия либо самозванец), и снимать дверь нельзя — человеку слова (`NAME_TAKEN`), как и на Windows отказ `first_pipe_instance`. Проба — обычным блокирующим `connect`: рантайма для неё не нужно, и ждать она не умеет.
        if std::os::unix::net::UnixStream::connect(&path).is_ok() {
            return Err(io::Error::new(io::ErrorKind::AddrInUse, NAME_TAKEN));
        }
        // Не отвечают — остаток прошлого запуска: `bind` на существующем файле отказал бы «адрес занят», а снять этот файл за нас некому — ядро сокет не убирает (в отличие от `flock`, который держится дескриптором и снимается с процессом).
        let _ = std::fs::remove_file(&path);
    }
    let rt = runtime()?;
    let listener = {
        let _in_rt = rt.enter();
        UnixListener::bind(&path)?
    };
    // Права на сам сокет, а не только на каталог вокруг него: каталог может быть чужим по происхождению (`$XDG_RUNTIME_DIR` заводит systemd), и полагаться на одни его права значило бы снова рассуждать там, где можно замерить. 0600 — стучать вправе только наша учётная запись, и отвечает на это ядро, а не наши догадки (спека, раздел 4).
    //
    // ponytail: между `bind` и этой строкой сокет недолго живёт с правами по умолчанию (umask), и в эту щель чужой успел бы соединиться. Закрыта она не здесь, а `peer_is_ours` на приёме: uid пришедшего сверяется с нашим на КАЖДЫЙ стук. Снимать щель заранее нечем — `umask` общий на процесс, и трогать его ради одного файла значило бы править чужие.
    std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o600))?;
    let door = Door::new(kit);
    let mine = door.clone();
    let kit = kit.clone();
    std::thread::spawn(move || {
        rt.block_on(async move {
            loop {
                let Ok((mut taken, _)) = listener.accept().await else {
                    // Та же строка и та же причина, что на Windows, — см. `DOOR_STOPPED`.
                    crate::journal::write(&kit, crate::journal::Kind::Fail, DOOR_STOPPED);
                    return;
                };
                if !peer_is_ours(&taken) {
                    // Молча закрыть дверь нельзя: эта строка — единственный след события, по которому человек потом разберётся.
                    crate::journal::write(&kit, crate::journal::Kind::Fail, STRANGER_KNOCK);
                    continue;
                }
                let mine = mine.clone();
                tokio::spawn(async move { answer(&mut taken, &mine).await });
            }
        })
    });
    Ok(door)
}

/// Кто пришёл: uid той стороны спрашивается у ЯДРА (`SO_PEERCRED`), а не выводится из наших догадок — то самое «средствами ОС», которым спека отличает канал от порта на петле.
///
/// Не добыли уверенности — значит «не наш»: отказ незнакомцу дешевле разговора с ним. Своё «кто мы» здесь не считается — его говорит `single_instance::account` (круг правок 2: прежде тут стоял свой `libc::getuid()`, то есть пятый по счёту ответ на тот же вопрос, и докстрока соседа напрасно обещала, что второго правила нет).
#[cfg(not(windows))]
fn peer_is_ours(stream: &tokio::net::UnixStream) -> bool {
    use std::os::unix::io::AsRawFd;
    let mut cred: libc::ucred = unsafe { std::mem::zeroed() };
    let mut len = std::mem::size_of::<libc::ucred>() as libc::socklen_t;
    // SAFETY: обычный вызов libc на дескрипторе живого соединения; буфер и его длина — наш стек, и размер объявлен тем же типом, что читает ядро.
    let got = unsafe {
        libc::getsockopt(stream.as_raw_fd(), libc::SOL_SOCKET, libc::SO_PEERCRED, std::ptr::from_mut(&mut cred).cast(), &mut len)
    };
    got == 0 && account().is_ok_and(|me| crate::holder::same_owner(&cred.uid.to_string(), &me))
}

/// Сколько раз клиент перепробует занятый канал. Дверь отвечает по одному стуку и заводит следующий экземпляр канала сразу, так что занято бывает на доли секунды; ждать её ровно столько же, сколько ответа (`ASK_WAIT`), — честнее, чем отказать человеку из-за соседней команды.
#[cfg(windows)]
const BUSY_PAUSE: Duration = Duration::from_millis(50);

#[cfg(windows)]
async fn knock(name: &str) -> io::Result<Knock> {
    use tokio::net::windows::named_pipe::ClientOptions;
    use windows_sys::Win32::Foundation::ERROR_PIPE_BUSY;
    let path = pipe_path(name);
    let tries = (ASK_WAIT.as_millis() / BUSY_PAUSE.as_millis()).max(1);
    for _ in 1..tries {
        match ClientOptions::new().open(&path) {
            // «Занято» — не «двери нет»: все заведённые экземпляры канала сейчас разговаривают, и имя за дверью осталось.
            Err(e) if e.raw_os_error() == Some(ERROR_PIPE_BUSY as i32) => tokio::time::sleep(BUSY_PAUSE).await,
            other => return other,
        }
    }
    ClientOptions::new().open(&path)
}

#[cfg(not(windows))]
async fn knock(name: &str) -> io::Result<Knock> {
    tokio::net::UnixStream::connect(sock_path(name)?).await
}

/// Чей процесс держит дверь, в которую мы только что постучали. Спрашивается у ОС: `GetNamedPipeServerProcessId` отдаёт процесс сервера, а владельца его токена называет `holder::owner_of_pid` — тот же способ, которым продукт уже отвечает на «чей это процесс» и себе (`single_instance::account`), и стражу порта. Второго правила здесь не заводим, и на ОБЕИХ осях: сравнение владельцев — одно (`holder::same_owner`), добыча своего — одна (`account`).
///
/// **Зачем проверка, когда есть дескриптор.** Дескриптор и `first_pipe_instance` держат только тех, кто придёт ПОСЛЕ нас. Самозванец, успевший создать канал ПЕРВЫМ, нашему беку дверь открыть не даст — но клиента примет, и команда отдала бы ему вопрос, а с задачи 7 и разрешение человека. Поэтому обе стороны проверяют друг друга, и это не перестраховка, а два разных случая.
///
/// Своего SID не узнали — тоже отказ: сверять не с чем, а разговаривать с неизвестным дверь не обязана.
#[cfg(windows)]
fn server_is_ours(client: &Knock) -> Result<(), String> {
    let pid = server_pid(client).map_err(|e| format!("{STRANGER_DOOR} (не удалось узнать, чей процесс держит дверь: {e})"))?;
    match (crate::holder::owner_of_pid(pid), account().ok()) {
        (Some(theirs), Some(mine)) if theirs == mine => Ok(()),
        _ => Err(STRANGER_DOOR.to_string()),
    }
}

/// Номер процесса, держащего дверь с той стороны стука, — одно место, где он добывается. Зовущих двое, и вопросы у них разные: чей это процесс (`server_is_ours`, владелец токена) и в каком он сеансе (`holder_pid` ниже, которым живёт слово про чужой сеанс). Второго `GetNamedPipeServerProcessId` рядом быть не должно: это ровно «две меры на один вопрос», и разошлись бы они молча.
#[cfg(windows)]
fn server_pid(client: &Knock) -> io::Result<u32> {
    use std::os::windows::io::AsRawHandle;
    use windows_sys::Win32::System::Pipes::GetNamedPipeServerProcessId;
    let mut pid = 0u32;
    // SAFETY: дескриптор живого клиентского конца канала (его держит `client`), `pid` — наш стек.
    let asked = unsafe { GetNamedPipeServerProcessId(client.as_raw_handle(), &mut pid) };
    if asked == 0 {
        return Err(io::Error::last_os_error());
    }
    Ok(pid)
}

/// Номер процесса, который держит дверь под этим именем, — `None`, если достучаться не вышло или ОС не назвала процесс. Чей он и в каком сеансе — решают выше; здесь только добыча, тем же стуком и тем же `server_pid`, которым дверь сторожит себя от самозванца.
///
/// Единственный зовущий — `single_instance::holder_session`: держателя замка спрашивают, в каком он сеансе, чтобы сказать человеку словами, почему окна не видно (спека, раздел 4).
#[cfg(windows)]
pub(crate) fn holder_pid(name: &str) -> Option<u32> {
    let rt = runtime().ok()?;
    rt.block_on(async { server_pid(&knock(name).await.ok()?).ok() })
}

/// На Linux тот же вопрос задаётся тем же способом, что и на стороне приёма: `SO_PEERCRED` отвечает обеим сторонам соединения, и клиент спрашивает им, чей процесс держит сокет.
///
/// **Прежде здесь стоял `Ok(())` с доводом «сокет лежит в нашем каталоге состояния, куда чужой не пишет», и довод был НЕПРОВЕРЕННЫЙ** (находка ревью круга 2). Дерево его опровергает: `Kit::at` кладёт состояние в корень комплекта, каталог создаётся по umask, 0700 ему никто не ставит, а путь задаётся снаружи (`--kit`, `ONEC_CONNECT_KIT`) и указывает куда угодно. На пути `bind` я такую же опору уже отверг и поставил проверку у ядра — а на клиентском конце оставил рассуждение. Вопрос один («кто на другом конце»), и ответ на него обязан быть один.
#[cfg(not(windows))]
fn server_is_ours(client: &Knock) -> Result<(), String> {
    if peer_is_ours(client) {
        Ok(())
    } else {
        Err(STRANGER_DOOR.to_string())
    }
}

fn ask_at(name: &str, q: Ask) -> Result<Answer, String> {
    let rt = runtime().map_err(|e| format!("живой экземпляр не спрошен: {e}"))?;
    rt.block_on(async {
        let mut stream = knock(name).await.map_err(|e| {
            if no_door(&e) {
                NO_BACK_END.to_string()
            } else {
                format!("дверь живого экземпляра не отворилась на стук: {e}")
            }
        })?;
        // До первого же сказанного слова: вопрос чужому — это уже утечка (а с задачи 7 по этой двери ездит и разрешение человека).
        server_is_ours(&stream)?;
        // Ждём РОВНО столько, сколько живому отмерено на это дело, плюс обычный срок на сам обмен (`Ask::client_wait`): уйди клиент раньше, человек прочёл бы наше «молчит» вместо настоящей причины, которую живой как раз дописывает.
        let waiting = q.client_wait();
        Frame::write(&mut stream, &q).await.map_err(|r| not_answered(&r))?;
        match tokio::time::timeout(waiting, Frame::read::<_, Answer>(&mut stream)).await {
            Ok(Ok(a)) => Ok(a),
            Ok(Err(r)) => Err(not_answered(&r)),
            Err(_) => {
                Err(format!("живой экземпляр молчит дольше {} с: он занят или завис — остановите его и запустите снова", waiting.as_secs()))
            }
        }
    })
}

