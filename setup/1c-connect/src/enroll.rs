    /// **Уборка списка — у держателя, и роняет она ДВОИХ по разным правилам** (замечание ревью круга правок 2: жила она в окне, и
    /// в сборке без окна список не чистился никогда).
    ///
    /// Мёртвая и НЕотвеченная уходит со словами: человек собирался ответить, а заявка исчезла, и без строки он не узнает, почему.
    /// Отвеченная уходит МОЛЧА и не раньше, чем выйдет её собственный срок: столько она прожила бы, не ответь на неё никто, — и
    /// ровно столько второй набранный `allow` обязан читать «уже ответили», а не «такой заявки нет».
    ///
    /// Сними любое из двух правил — и красным станет своя половина теста.
    #[test]
    fn the_sweep_drops_the_dead_with_words_and_the_answered_in_silence() {
        let store = Requests::default();
        // Карточки РАЗНЫЕ и ключом, и именем: вытеснение смотрит на ключ (`Requests::take`), и три заявки с одним ключом схлопнулись
        // бы в одну ещё до уборки.
        let hang = |name: &str| {
            let (tx, rx) = tokio::sync::oneshot::channel::<Decision>();
            store.take(Pending::new(Request { card_name: name.into(), card: name.into(), ..a_request() }, tx));
            rx
        };
        // Первая отвечена человеком, вторая умерла сама (приёмник уронен), третья ждёт.
        let answered = hang("Ромашка");
        store.answer(&a_request().peer.to_string(), Some("Ромашка"), Decision::Allow).expect("на первую ответили");
        drop(answered);
        drop(hang("Клевер"));
        let _alive = hang("Пижма");
        assert_eq!(store.lock().len(), 3, "фикстура: в списке три заявки");

        let now = std::time::Instant::now();
        assert_eq!(store.prune(now), vec!["Клевер".to_string()], "словами провожают только ту, что умерла, не дождавшись ответа");
        let left: Vec<String> = store.lock().iter().map(|p| p.request.card_name.clone()).collect();
        assert_eq!(left, vec!["Ромашка".to_string(), "Пижма".to_string()], "отвеченная свой срок ещё живёт, ждущая — тем более");

        // Срок отвеченной вышел — она уходит, и молча: слова ответа человек уже прочитал.
        let later = now + DECISION + Duration::from_secs(1);
        assert!(store.prune(later).is_empty(), "об отвеченной вслед ничего не говорят");
        let left: Vec<String> = store.lock().iter().map(|p| p.request.card_name.clone()).collect();
        assert_eq!(left, vec!["Пижма".to_string()], "а живая заявка уборкой не задета ни на каком сроке");
    }

    /// Сколько осталось человеку — от `DECISION` и ни от чего больше: своего срока у заявки нет, иначе он разошёлся бы с тем, что
    /// держит `accept_side`, на первой же правке. И решает «показывать ли» не это число, а `reachable`.
    #[test]
    fn the_time_left_is_counted_from_the_one_measure_and_decides_nothing() {
        let (tx, rx) = tokio::sync::oneshot::channel();
        let p = Pending::new(a_request(), tx);
        assert!(p.left() <= DECISION && p.left() > DECISION - Duration::from_secs(60));
        assert!(p.reachable() && !p.answered());
        drop(rx);
        assert!(!p.reachable(), "разговор кончился — ждать её нечего");
        assert!(p.left() > Duration::ZERO, "а срок при этом ещё не вышел: жива заявка или нет, решает не он");
    }

    /// Счётчик вызовов диалога: «человека не беспокоят вовсе» проверяется
    /// только так — не словами отказа, а нулём здесь.
    #[derive(Clone, Default)]
    struct Asked(Arc<AtomicUsize>);

    impl Asked {
        fn count(&self) -> usize {
            self.0.load(Ordering::SeqCst)
        }
    }

    /// Разговор двух узлов в одном процессе: поднять оба, свести по петле,
    /// провести зачисление целиком и вернуть оба исхода.
    ///
    /// Общая обвязка, а не копия в каждом тесте: тестов шесть, и расходятся
    /// они ровно в двух местах — какой код предъявлен и что решит человек.
    async fn talk(
        name: &str,
        prepare: impl FnOnce(&mut Book, EndpointId, &Node, &std::path::Path) -> (String, Vec<Card>),
        answer: Decision,
    ) -> (Result<Outcome, String>, Result<Outcome, String>, Book, Asked, String) {
        let (da, db) = (dir(&format!("{name}-a")), dir(&format!("{name}-b")));
        let caller = Node::start(&da).await.unwrap();
        let base = Node::start(&db).await.unwrap();
        let peer = caller.id();
        let mut book = Book::open(&db).unwrap();
        let (code, cards) = prepare(&mut book, peer, &base, &db);

        let asked = Asked::default();
        let listening = base.clone();
        let (counter, cards_there) = (asked.clone(), Cards::here(cards.clone()));
        let server = tokio::spawn(async move {
            let conn = listening.accept().await.unwrap().unwrap();
            let (mut w, mut r) = conn.accept_bi().await.unwrap();
            let out = accept_side(&mut w, &mut r, peer, &mut book, &cards_there, Ceiling::Full, |_req| async move {
                counter.0.fetch_add(1, Ordering::SeqCst);
                answer
            })
            .await;
            // Соединение держим живым: брошенное здесь закрыло бы канал
            // раньше, чем та сторона дочитает ответ.
            (out, book, conn)
        });

        let conn = tokio::time::timeout(WAIT, caller.dial(by_loopback(&base))).await.expect("дозвон не уложился в срок").unwrap();
        let (mut w, mut r) = conn.open_bi().await.unwrap();
        let mine = tokio::time::timeout(
            WAIT,
            dial_side(&mut w, &mut r, Call::of(&code, None), "Разработчик", Ceiling::Full, Side::WithAgents, None),
        )
        .await
        .expect("зовущая сторона не уложилась в срок");
        let (theirs, book, _held) = tokio::time::timeout(WAIT, server).await.expect("принимающая сторона не уложилась в срок").unwrap();

        caller.close().await;
        base.close().await;
        // Каталоги НЕ удаляем, и это не забывчивость: книга отдаётся наружу
        // живой, а `Book::check` перечитывает файл с диска — удалив каталог
        // здесь, мы бы получили «код не найден» на любой вопрос о тикете, то
        // есть проверки «погашен ли он» молча проходили бы всегда. Стирает
        // за собой `dir`, на входе следующего прогона.
        (mine, theirs, book, asked, code)
    }

    /// Секрет обратно из кода — им проверяется, погашен тикет или жив.
    fn secret_of(code: &str) -> [u8; 32] {
        *Ticket::from_code(code).unwrap().secret
    }

    /// Погашен ли тикет — одним словом вместо трёх вердиктов.
    ///
    /// Спрашивается `verdict`, то есть ровно то, чем книгу спрашивает продукт.
    /// Прежде здесь звалась `Book::check`, и она существовала РАДИ этих
    /// четырёх строк: в продукте её не звал никто, но удалить её мешали они.
    /// Разница между «кода нет» и «код устарел» этим тестам безразлична — им
    /// важно только, сгорел ли код, — поэтому свод делается здесь, а не живёт
    /// второй мерой того же вопроса в самой книге.
    fn spent(book: &Book, secret: &[u8; 32]) -> bool {
        !matches!(book.verdict(secret), Ok(Verdict::Card(_)))
    }

    /// Живой тикет к карточке «Ромашка» — обычная заготовка: так выглядит
    /// шаг первый спеки, когда человек уже выдал код и переслал его.
    fn one_live_ticket(book: &mut Book, _peer: EndpointId, base: &Node, _state: &std::path::Path) -> (String, Vec<Card>) {
        let ticket = Ticket::issue(base.id(), None, vec![]).unwrap();
        book.issue(&"b1".into(), &ticket).unwrap();
        (ticket.to_code(), vec![a_card("Ромашка", "b1", true)])
    }

