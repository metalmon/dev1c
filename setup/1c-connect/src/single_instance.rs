    /// **Бек в ДРУГОМ сеансе назван словами, а не занимает место окна молча** (красный тест задачи 8). Отказ 15.11 начался
    /// именно так: вход по ssh под той же учётной записью поднял вторую копию при живом окне на рабочем столе, показать окно она
    /// не смогла, а место заняла — и настоящее окно на машине не открывалось вовсе и без единого слова.
    ///
    /// Правило здесь отделено от добычи нарочно: двух сеансов одной учётной записи из одного процесса не завести ни на одной оси
    /// (тот же предел, что у межпроцессной меры двери), а решение «какие слова каким исходом выбираются» проверяется и без них —
