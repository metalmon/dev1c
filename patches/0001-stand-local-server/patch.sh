#!/bin/sh
# Заплата 0001 к стенду: установка рабочего места обрывалась на адресе среды.
# Для стендов из комплектов, собранных 26.10.2026 и позже. Образ перекачивать
# не нужно: правится одна строка в настройках рабочего места.
#
# КАК ЗАПУСТИТЬ. Либо в терминале внутри стенда:
#
#     sh patch.sh
#
# либо с машины, где поднят контейнер, одной строкой:
#
#     docker exec -i dev1c sh -s < patch.sh
#
# (если контейнер назван иначе, поставьте его имя вместо dev1c).
#
# ЧТО ЭТО ДЕЛАЕТ. Дописывает поле `server` в файл `1c-connect.toml` каждого
# рабочего места и заново проводит установку расширения mcp-1c в его базу.
# Установка зовёт конфигуратор 1С и занимает минуту-две на рабочее место.
# Копия файла до правки остаётся рядом под именем `1c-connect.toml.before-0001`.
#
# ЧЕГО ЭТА ЗАПЛАТА НЕ ДЕЛАЕТ. Не ходит в сеть — ни одного обращения наружу, ни
# одной загрузки. Не управляет докером. Не трогает ничего, кроме настроек
# рабочих мест и расширения в их базах. Не спрашивает и не хранит паролей и
# ничего никуда не отправляет. Повторный запуск безвреден: уже сделанное
# пропускается.
#
# ЧТО БЫЛО СЛОМАНО. На стенде коннектор работает в локальном режиме: база лежит
# рядом, туннеля нет, и поля `server` в его настройках нет — так их и пишет сам
# стенд. Но проверка настроек и шаг «Окружение» требуют этот адрес безусловно,
# не глядя на режим. Пока у поля было умолчание-образец, проверки его и
# проходили; 26.10.2026 умолчания сделали пустыми — и с этого дня любая
# установка на стенде останавливается на строке «[host]: server — адрес и порт
# через двоеточие» ещё до первого действия. Видно это так: у рабочего места нет
# проекта, нет публикации и нет расширения в базе, а значит у агента в
# редакторе нет инструментов 1С. Отказ при первом старте намеренно не роняет
# контейнер и остаётся строкой в журнале, поэтому человек видит рабочий стол и
# молчащего агента, без объяснения причины.
#
# ПОЧЕМУ ХВАТАЕТ ОДНОЙ СТРОКИ. В локальном режиме значение этого поля не
# используется ничем: туннеля нет, обращений по этому адресу нет. Проверкам
# нужно лишь, чтобы адрес разбирался.
#
# ОТМЕНИТЬ: вернуть сохранённую копию файла. Расширение в базе при этом
# останется — оно там и должно быть.
#
# Настоящая правка (не спрашивать адрес там, где его нет) войдёт в следующий
# комплект. Эта заплата ей не помешает: лишнее поле так и останется никем не
# читанным.
set -eu

ID=0001
# Значение-пустышка. Порт SSH стенда взят лишь затем, чтобы строка выглядела
# осмысленно для того, кто откроет файл; никто по этому адресу не ходит.
ADDR=localhost:3393
# Общий комплект стенда: там лежит mcp-1c, который ставит расширение. Путь к
# нему стенд задаёт переменной сеанса рабочего стола, а заплата идёт мимо
# сеанса — и без этой строки установка ищет комплект рядом с программой и
# останавливается на «комплект неполный».
#
# Именно переменной, а не ключом `--kit`: ключ значит «вот этот комплект
# целиком», и настройки тогда читаются из него же, а не из дома рабочего
# места. Переменная оставляет чтение настроек там, где они лежат.
KIT=${ONEC_CONNECT_KIT:-/opt/dev1c-kit}

[ -x /usr/local/bin/1c-stand ] || {
    echo "Это не стенд: /usr/local/bin/1c-stand не найден." >&2
    echo "Запустите заплату внутри контейнера стенда — см. заголовок файла." >&2
    exit 1
}

# От root (так приходит `docker exec`) обходим все рабочие места; от имени
# рабочего места правим только его дом. Правку в обоих случаях делает САМ
# владелец: файл должен остаться его, иначе окно перестанет его переписывать.
if [ "$(id -u)" = 0 ]; then
    users=$(ls /home)
else
    users=$(id -un)
fi

as_user() { # пользователь, команда
    if [ "$(id -u)" = 0 ]; then su - "$1" -c "$2"; else sh -lc "$2"; fi
}

done_any=0
for u in $users; do
    dir=/home/$u/.local/share/dev1c
    toml=$dir/1c-connect.toml
    [ -f "$toml" ] || continue
    grep -q '^mode = "local"' "$toml" || { echo "$u: не локальный режим — пропускаю"; continue; }
    done_any=1

    if grep -q '^server *=' "$toml"; then
        echo "$u: адрес уже на месте"
    else
        echo "$u: дописываю server = \"$ADDR\" (копия: $toml.before-$ID)"
        as_user "$u" "cp -p '$toml' '$toml.before-$ID' && sed -i '/^mode = /a server = \"$ADDR\"' '$toml'"
    fi

    # Отметка — про то, что заплата приложена, а не про то, что ей нашлась
    # работа: поле могли дописать и руками до неё, и тогда молчаливый пропуск
    # оставил бы стенд без записи о том, что здесь уже побывали.
    as_user "$u" "grep -q '^$ID\$' '$dir/patches.applied' 2>/dev/null || echo '$ID' >> '$dir/patches.applied'"

    echo "$u: установка расширения (конфигуратор, минута-две)"
    # `\$HOME` оставлено нераскрытым нарочно: раскрыть его должен шелл рабочего
    # места, а не тот, из которого запущена заплата (у root это /root).
    as_user "$u" "ONEC_CONNECT_KIT='$KIT' \$HOME/dev1c/1c-connect install -y" 2>&1 | tail -3
done

[ "$done_any" = 1 ] || { echo "Рабочих мест с настройками коннектора не нашлось." >&2; exit 1; }

echo
echo "Готово. Что приложено: cat /home/<место>/.local/share/dev1c/patches.applied"
echo "Проверить рабочее место: его терминал, затем  ~/dev1c/1c-connect check"
