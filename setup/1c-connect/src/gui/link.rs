//! Обслуживание: замок, сеанс и переключатель.
//!
//! `gate_now`/`refresh_gate` считают замок по диску, `toggle_link` включает и
//! гасит, `start_session`/`stop_session` держат сеанс.

use super::*;

/// Строка списка вкладки «Связь»: подпись группы или само соединение.
/// Группировка и порядок — в `list`.
#[derive(Debug)]
pub enum Entry {
    Caption(&'static str),
    Row(Row),
}

/// Одна строка списка: имя дал человек, слово состояния, отметка «текущее»,
/// признак разрешённой записи. `base` заполнено только у текущего
/// соединения — вторая строка только у него (окно 380 точек: двадцать строк
/// у разработчика с десятью заказчиками не поместятся).
#[derive(Debug)]
pub struct Row {
    pub name: String,
    pub state: &'static str,
    pub current: bool,
    pub write: bool,
    pub base: Option<String>,
}

/// Слово состояния и признаки строки одного соединения.
///
/// Локальное соединение (`mode == "local"`) не о связи — подключаться там
/// не к кому, оба конца на этой машине. Оно говорит про слушатели MCP тем
/// же словарём, что уже есть у карточки состояния (`panel::card`,
/// «MCP включены»/«MCP выключены»), в короткой форме: имя соединения строка
/// и так назвала (вопрос владельца 3.11).
///
/// Остальные соединения сворачивают восемь состояний контракта
/// (`2026-11-01-connection-contract.md`) в пять слов спеки. «Нет» своей
/// строки не имеет вовсе — соединения без строки в списке не бывает.
/// «Тикет выдан» и «разрешено» (миг между решением человека и
/// «подключено») отдельного слова не получают.
///
/// `None` — не то же самое, что `Off`/`Connecting` (поправка задачи 16
/// плана `2026-11-03-interface`, брифа «третье, оттуда же»). Живого
/// хранилища состояний на соединение в продукте пока нет: `l` приходит
/// заглушкой-поиском по имени, и она честно отдаёт `None` для ВСЕХ
/// соединений, кроме текущего (`gui::link_body`, которая и держит
/// состояние живого сеанса). Прежде это читалось как «тикет выдан» —
/// «ждёт разрешения» — и правило «ждущие — первой строкой» (`list` ниже)
/// поднимало над подписями групп КАЖДУЮ сохранённую карточку разом,
/// неправда на экране. Правда для «состояния не знаем» — «не подключено»:
/// это слово ничего не обещает и ничего не торопит человека решить.
/// «Ждёт разрешения» остаётся словом состояния «тикет выдан» — оно придёт
/// с протоколом (живым хранилищем состояний), а в заглушке не используется
/// и ни на одном тесте этого файла не встречается через `None`.
pub fn row(c: &Connection, current: bool, l: Option<&State>) -> Row {
    let state = if c.mode == "local" {
        if l.is_some_and(State::is_up) {
            "включено"
        } else {
            "выключено"
        }
    } else {
        match l {
            Some(State::Up { .. }) => "подключено",
            Some(State::Retrying(_)) => "подключается снова",
            Some(State::Failed(_)) => "разорвано",
            Some(State::Off) | Some(State::Connecting) => "ждёт разрешения",
            None => "не подключено",
        }
    };
    let base = if current {
        let name = cfg::base_name(&c.base_path);
        if name.is_empty() {
            None
        } else {
            Some(name.to_string())
        }
    } else {
        None
    };
    Row { name: c.name.clone(), state, current, write: c.allows_write(), base }
}

/// Онбординг: мастера нет (решение владельца 1.11), вместо него пустая
/// «Связь» задаёт один вопрос и даёт на него два ответа. Из ответа следует
/// топология первого соединения — `role`, с которым `save::add_connection`
/// заводит карточку: первый ответ заводит ту, что зовёт (база на той
/// стороне), второй — ту, что ждёт входящих (база здесь). `base_here`
/// человек выбирает уже в самой карточке — ответ про код его не определяет
/// (и заказчик, и разработчик с базой у себя оба могут принимать
/// подключения).
///
/// Слова второго ответа спека пишет как «Я завожу соединение и выдаю код»;
/// здесь он «Код выдаю я» (решение владельца 3.11 — подписи кнопок спека
/// оставляет строителю): так он зеркалит первый — оба про код, в обоих
/// человек говорит про себя, — и из него уходит «завести», которого
/// человек про программу не говорит.
pub fn onboarding_answers() -> [(&'static str, &'static str); 2] {
    [("Подключаюсь сам — у меня есть код", "dial"), ("Принимаю подключения — код выдаю я", "accept")]
}

