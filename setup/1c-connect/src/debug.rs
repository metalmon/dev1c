//! Подробный журнал шагов — по просьбе владельца 15.11, после живого прогона, в котором «не подключается» было всё, что мог
//! сказать продукт.
//!
//! **Зачем отдельный режим, а не всегда.** Шаги рукопожатия человеку не нужны: ему нужен исход и причина, а строки «звоню»,
//! «канал открыт», «говорю hello» в обычном журнале — тот же шум, что повторённый тысячу раз отказ. Но когда связь не
//! складывается, именно они отвечают на единственный вопрос — ДОКУДА дошло.
//!
//! Включается переменной окружения `DEV1C_DEBUG` (любое непустое значение). Переменная, а не ключ командной строки: окно
//! запускают двойным щелчком и задачей планировщика, где ключи добавлять негде, а переменную видно обоим.
//!
//! Читается ОДИН раз за процесс: иначе режим можно было бы включить посреди разговора и получить журнал, собранный наполовину.

use std::sync::OnceLock;

static ON: OnceLock<bool> = OnceLock::new();

/// Включён ли подробный журнал.
pub fn on() -> bool {
    *ON.get_or_init(|| std::env::var("DEV1C_DEBUG").map(|v| !v.trim().is_empty()).unwrap_or(false))
}

/// Слова шага — только в подробном режиме. Возвращает `None`, когда режим выключен: зовущий сам решит, печатать ли, и строка
/// при этом даже не соберётся.
pub fn step(text: impl FnOnce() -> String) -> Option<String> {
    on().then(text)
}

/// Подробность для РАЗБОРА, а не для человека: чужое `{e}` сетевого слоя, длина кадра, байты заголовка. Печатается в поток
/// ошибок и только в подробном режиме.
///
/// Нужна там, где `step` не годится: у `wire::Frame` и `Channel::call` нет канала событий окна, а подробность нужна — иначе
/// выбор «или в текст человеку, или в никуда» снова приведёт `{e}` на экран (`wire::Refuse::event`, там довод целиком).
pub fn aside(text: impl FnOnce() -> String) {
    if let Some(t) = step(text) {
        eprintln!("1c-connect: {t}");
    }
}

#[cfg(test)]
mod tests {
    /// Режим читается один раз за процесс: иначе журнал одного разговора собрался бы наполовину.
    ///
    /// Сама переменная здесь не трогается — тесты идут в одном процессе, и правка окружения в одном из них меняла бы ответ у
    /// соседей. Проверяется то, что проверяемо без неё: выключённый режим строки не собирает вовсе.
    #[test]
    fn a_step_is_not_even_built_when_the_mode_is_off() {
        if super::on() {
            return;
        }
        let mut built = false;
        let text = super::step(|| {
            built = true;
            "шаг".to_string()
        });
        assert!(text.is_none(), "выключенный режим слов не даёт");
        assert!(!built, "и даже не собирает их: строка стоит дорого, а печатать её некуда");
    }
}
