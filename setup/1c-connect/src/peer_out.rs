//! Что узел этой машины рассказывает окну о себе — своим словарём, а не
//! словарём окна.
//!
//! **Почему не `gui::Ev`.** Поток узла (`peer`) рождён до того, как в
//! проекте решили разнести узел и окно по разные стороны (план «Узел
//! перестаёт говорить словарём окна»), и отчитывался тем, что было под рукой
//! — общим `Ev`. У `Ev` варианты про трей, про перестройку меню, про ход
//! долгой операции — вещи, о которых узел знать не должен и не обязан.
//! Замер показал: из всего `Ev` узел пользуется тремя случаями (`Enroll`,
//! `Line`, `Flow`), и только ими. `Out` называет ровно эти три и ничего
//! сверх: раздувать его про запас значило бы тащить ту же беду с другой
//! стороны.
//!
//! **Перевод — дело окна, а не узла.** Строка в журнал приезжает здесь не
//! готовой (`gui::log::Line`), а своими словами (`common::Event`): у окна
//! уже есть один перевод `Event → Line` (`gui::line_of`), и заводить второй
//! в узле значило бы завести вторую меру на один вопрос — тот самый разряд
//! дефектов, который в этом дереве уже ловили не раз.
//!
//! `Pending` — тоже не словарь окна: заявка и канал ответа переехали в
//! `enroll` (задача 2 плана «Пара переезжает в бек»), к `Request` и
//! `Decision`, которые и наполняют их смыслом. Окно получает уже готовый тип
//! и только показывает его (`gui::Pending` — реэкспорт).

use crate::enroll::Pending;

/// Что узел этой машины сообщает окну: три случая, ровно те, которыми узел
/// пользуется сегодня.
#[derive(Debug)]
pub enum Out {
    /// Заявка на зачисление, ждущая решения человека.
    Enroll(Pending),
    /// Строка в журнал — своими словами. Перевод в готовую строку
    /// (`gui::log::Line`) делает окно (`gui::line_of`), а не узел.
    Say(common::Event),
    /// Новое состояние управляющего потока одной карточки.
    Flow(crate::cfg::CardId, Option<Flow>),
}

/// Жизнь управляющего потока одной карточки — ровно то, о чём окну сообщает
/// поток узла (`peer`).
///
/// Четыре случая, а не `bool`: «жив ли поток» не отличает «звоню прямо
/// сейчас» от «оборвалось и больше не звоню», а человеку это разные слова
/// (спека контракта: «подключается», «подключено», «разорвано»,
/// «подключается снова»). Переводит их в состояние контракта
/// `gui::link::contract_of`, и ни одно слово там не придумывается заново.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Flow {
    /// Звоним первый раз: человек вставил код и нажал «Подключиться», либо
    /// карточка поднимается при запуске по запомненному партнёру.
    Calling,
    /// Управляющий поток живёт — зачисление прошло, канал держится.
    Up,
    /// Поток кончился, и звонить больше не будем: та сторона простилась
    /// словами или зачисление кончилось исходом (`channel::Stopped`).
    Broken,
    /// Поток оборвался, и зовущая сторона возвращается сама
    /// (`channel::keep_calling`) — ждём следующего круга.
    Retrying,
}

// Проверка про ПЕРЕВОД, а потому живёт с окном: она зовёт `gui::line_of`, которого в сборке без окна нет вовсе. Гейт здесь ничего не
// прячет — он называет сторону, которой проверка принадлежит.
#[cfg(all(test, feature = "gui"))]
mod tests {
    use super::Out;

    /// Узел говорит СВОИМ словарём: окно переводит его, а не наоборот.
    #[test]
    fn the_node_speaks_its_own_words_and_the_window_translates() {
        let out = Out::Say(common::Event::Fail("не дозвонился".into()));
        let Out::Say(e) = &out else { panic!("{out:?}") };
        assert_eq!(crate::gui::line_of(e).unwrap().text, "не дозвонился");
    }
}
