/// Сколько ждём выхода в сеть, прежде чем выдавать код.
///
/// Ждём, потому что до выхода в сеть узел не знает ни своего релея, ни
/// адресов, которыми его видно, — а код, выданный раньше, донёс бы до той
/// стороны один ключ, то есть дозвон только поиском через серверы n0. Ждём
/// НЕ бесконечно: машина без интернета в сеть не выйдет никогда, а код по
/// петле ей всё равно нужен (мерка готовности — две копии на одной машине).
const ONLINE_WAIT: Duration = Duration::from_secs(10);

/// Как эту машину найти снаружи — ровно то, что уезжает в код подключения.
///
/// Считается один раз, когда узел вышел в сеть, и живёт в `Peer` под замком:
/// код выдаётся на главном потоке окна (`panel::issue_code`), а знает это
/// только поток узла.
#[derive(Debug, Clone, Default)]
pub struct Reach {
    pub relay: Option<String>,
    pub direct: Vec<String>,
}

/// Ручка на поток узла — то, что живёт в `Ui` и чем окно его просит.
///
/// Остановки у потока нет нарочно, тем же доводом, которым её нет у
/// `channel::keep_calling`: принимать входящие надо всё время, пока программа
/// работает, а «выключить обслуживание» — это про вызовы агента
/// (`Ui::enabled`), не про то, доходит ли до человека заявка на зачисление.
/// Поток кончается с процессом.
#[derive(Clone)]
pub struct Peer {
    cmd: tokio::sync::mpsc::UnboundedSender<Cmd>,
    reach: Arc<Mutex<Option<Reach>>>,
}

/// Что окно умеет попросить у потока узла.
enum Cmd {
    /// Позвонить зовущей карточкой. Пустой `code` — переподключение по
    /// запомненному партнёру (`Partners`), непустой — первая заявка.
    ///
    /// `told` — кому рассказать исход первого круга (см. `Told`). Пусто — никому: так звонит окно и так звонят карточки, которые зовут сами при запуске.
    Dial { card: CardId, name: String, code: String, told: Told },
    /// Увести местное соединение агента В КАНАЛ — к той стороне, где база (шаг 4 плана пары B).
    ///
    /// Приходит от местного слушателя (`listen::run`): Zed подключился к нашему порту, а база не здесь. Поток узла открывает поток в
    /// живом канале этой карточки, здоровается заголовком `McpOpen` и дальше просто переливает байты. Правил моста это не касается:
    /// мост стоит на ТОЙ стороне, здесь только труба.
    ///
    /// Соединение едет сюда целиком, потому что канал живёт в этом потоке и больше нигде: второй держатель того же канала был бы
    /// вторым проходом пробивания NAT и вторым разговором с релеем.
    Calls {
        card: CardId,
        kind: crate::ops_host::McpServer,
        stream: tokio::net::TcpStream,
        /// Роняется вместе с концом трубы — по нему слушатель узнаёт, что второй дескриптор этого соединения держать больше незачем.
        done: tokio::sync::oneshot::Sender<()>,
    },
    /// Снять поток зачисленной стороны ПРЯМО СЕЙЧАС, сказав ей словами.
    ///
    /// Иначе отзыв действовал бы только на следующем круге той стороны, а
    /// спека требует немедленности: `Book::enrolled_to` читает диск на каждое
    /// подключение именно затем, чтобы «Отозвать» срабатывало сразу, — и
    /// живой поток, который переживает отзыв, эту немедленность отменяет.
    Revoke { card: CardId, peer: EndpointId },
    /// Попрощаться со ВСЕМИ живыми разговорами — программа уходит.
    ///
    /// Канал, закрытый молча, читается той стороной как ОБРЫВ (`channel::
    /// hold` отдаёт `Gone::Broken` на любую ошибку чтения), а обрыв она
    /// повторяет: `keep_calling` звонит снова и показывает «подключается
    /// снова» — вечно, потому что звонить уже некуда. Прощание словами
    /// превращает это в `Stopped::Farewell`: круги прекращаются, и человек
    /// читает «Та сторона закрыла программу».
    ///
    /// `done` — обычный `std::sync::mpsc`, а не `oneshot`: ждёт его ГЛАВНЫЙ
    /// поток окна на выходе, и ждать он умеет только по-настоящему, со
    /// сроком.
    ByeAll { done: std::sync::mpsc::Sender<()> },
}

/// Слова отказа, когда вызов агента вести некуда: потока узла нет или он кончился.
///
/// Слова ОДНИ на все места, где этот отказ произносится (`Peer::calls`, ручка канала у окна до подъёма узла, фикстура сеанса в
/// тестах): один вопрос — одна мера. Человек в любом из случаев читает одно и то же, потому что случай для него и есть один —
/// связи нет.
pub const NO_NODE: &str = "поток узла не работает — вызовы агента вести некуда";

/// Узла ещё нет вовсе — программа только поднимается. Слова ОДНИ на все места, где этот случай встречается человеку: щелчок «Подключиться» в окне до подъёма узла (`gui::panel::dial_card`) и стук в управляющую дверь в ту же щель, набранным `code` или `dial` (`door::reply`, пока не поставлен `door::serves`).
///
/// **Про «подключаться» здесь больше не сказано, и это не придирка.** Прежде текст кончался словом «подключаться», и на `1c-connect code` человек читал бы «не готова подключаться» там, где просил код: случай один (узла нет), а дел два, и слова обязаны подходить обоим.
///
/// Сторожит общность НЕ сверка константы с константой — такая проверка не упала бы никогда, — а тест окна (`gui::panel::tests::the_window_says_not_ready_in_the_shared_words`): он гонит настоящий щелчок «Подключиться» без узла и сверяет СТРОКУ ЖУРНАЛА с этой константой. Разойдись они — упадёт он.
pub const NOT_READY: &str = "Программа ещё не готова — она только запускается; попробуйте через минуту.";

/// Кому рассказать исход ПЕРВОГО круга звонка — и ровно один раз.
///
/// Нужен он тому, кто набрал `1c-connect dial` и ждёт ответа в консоли (решение ведущего, задача 6: «ждёт исхода и печатает его словами, а не возвращается сразу»). Окну он не нужен: там исход виден строкой журнала и состоянием карточки, и `Peer::dial` его не заводит вовсе.
///
/// **Только ПЕРВЫЙ круг, и это не упрощение.** `channel::keep_calling` повторяет недозвон годами с нарастающей паузой (и правильно делает: сервер заказчика бывает выключен на ночь), а человек в консоли ждёт ответа сейчас. `Option::take` и есть «один раз»: второй круг находит `None` и никому ничего не шлёт, а повторы идут дальше своим чередом — сказанное человеку их не отменяет и не ускоряет.
///
/// `std::sync::mpsc`, а не `oneshot`: ждёт его поток управляющей двери, у которого своего рантайма нет, и ждать он умеет только по-настоящему, со сроком (тот же довод, что у `Cmd::ByeAll`).
/// Исход звонка словами — то, чего ждёт набравший `dial`. `Err` — связи не вышло вовсе (негодный код, недозвон); отказ зачисления сюда не попадает, он ИСХОД (`Outcome::NotEnrolled`).
pub type Dialled = Result<enroll::Outcome, String>;

#[derive(Clone, Default)]
pub struct Told(Arc<Mutex<Option<std::sync::mpsc::Sender<Dialled>>>>);

impl Told {
    /// Рассказать исход — первому, кто спросил, и больше никому.
    fn tell(&self, out: &Dialled) {
        if let Some(tx) = self.0.lock().unwrap_or_else(|e| e.into_inner()).take() {
            let _ = tx.send(out.clone());
        }
    }

    /// Круг не дошёл до разговора вовсе — негодный код, нет адреса, канал не открылся. Для ждущего это такой же ответ, как отказ: `Err` зачисления и значит «связи не вышло», а причина названа словами.
    fn failed(&self, why: &str) {
        self.tell(&Err(why.to_string()));
    }
}

impl Peer {
    /// Как нас найти — для кода подключения. `None` — узел ещё не поднялся
    /// или не вышел в сеть; код тогда выдаётся без адресов, как и до этой
    /// задачи.
    pub fn reach(&self) -> Option<Reach> {
        self.reach.lock().unwrap_or_else(|e| e.into_inner()).clone()
    }

    /// Позвонить карточкой. Отказ — только «поток узла кончился», то есть
    /// случай, в котором звонить нечем вовсе.
    pub fn dial(&self, card: &CardId, name: &str, code: &str) -> Result<(), String> {
        self.ring(card, name, code, Told::default())
    }

    /// То же самое, но с обратной дорогой: получивший приёмник дождётся исхода первого круга словами (`Told`). Так звонит набранный `1c-connect dial` — человеку в консоли нужен ответ, а не обещание (решение ведущего, задача 6).
    pub fn dial_waiting(&self, card: &CardId, name: &str, code: &str) -> Result<std::sync::mpsc::Receiver<Dialled>, String> {
        let (tx, rx) = std::sync::mpsc::channel();
        self.ring(card, name, code, Told(Arc::new(Mutex::new(Some(tx))))).map(|()| rx)
    }

    fn ring(&self, card: &CardId, name: &str, code: &str, told: Told) -> Result<(), String> {
        self.cmd
            .send(Cmd::Dial { card: card.clone(), name: name.to_string(), code: code.to_string(), told })
            .map_err(|_| "Программа не вышла в сеть — подключиться нечем. Перезапустите её.".to_string())
    }

    /// Снять живой поток отозванной стороны. Молча: запись об отзыве уже
    /// сделана и уже сказана словами (`panel::revoke_party`), а живого потока
    /// у этой стороны могло и не быть вовсе — тогда снимать нечего, и это не
    /// беда.
    /// Увести местное соединение агента в канал — к той стороне, где база.
    ///
    /// Зовёт местный слушатель (`listen::run`), когда база не на этой машине. Отказ здесь один и тот же (`NO_NODE`): потока узла
    /// нет — значит и вести некуда. Говорится он НА ВЫЗОВ, а не на весь сеанс вперёд: с задачи 4 плана «Сопряжение переезжает в
    /// бек» ручка канала у сеанса есть всегда, и отказывать заранее стало нечему.
    pub fn calls(
        &self,
        card: &CardId,
        kind: crate::ops_host::McpServer,
        stream: tokio::net::TcpStream,
    ) -> Result<tokio::sync::oneshot::Receiver<()>, String> {
        let (done, ended) = tokio::sync::oneshot::channel();
        self.cmd.send(Cmd::Calls { card: card.clone(), kind, stream, done }).map(|()| ended).map_err(|_| NO_NODE.to_string())
    }

    pub fn revoked(&self, card: &CardId, peer: EndpointId) {
        let _ = self.cmd.send(Cmd::Revoke { card: card.clone(), peer });
    }

    /// Попрощаться со всеми живыми разговорами и ДОЖДАТЬСЯ, пока прощания
    /// уедут. `false` — срок вышел, а кто-то ещё не договорил.
    ///
    /// Ждать обязательно: прощание — это записанный кадр, а записанный кадр
    /// выбрасывается, если процесс уйдёт раньше, чем та сторона признает его
    /// доехавшим (`channel::settle`, и вся беда, ради которой он заведён).
    /// Ждать НЕ бесконечно по тому же правилу, которым живут остальные
    /// ожидания выхода: застрявшее прощание не должно держать «Выход».
    ///
    /// Потока узла нет (его не подняли или он кончился) — прощаться не с кем
    /// и не чем, и это успех, а не отказ: иначе каждый выход без узла стоил
    /// бы человеку полного срока ожидания впустую.
    pub fn bye_all(&self, wait: Duration) -> bool {
        let (done, waited) = std::sync::mpsc::channel();
        if self.cmd.send(Cmd::ByeAll { done }).is_err() {
            return true;
        }
        waited.recv_timeout(wait).is_ok()
    }
}

/// Поднимает поток узла и отдаёт ручку на него.
///
/// Сеть поднимается в потоке, и о том, открылся ли сокет, говорит строка
/// журнала: иначе открытие окна ждало бы сеть. А вот КЛЮЧ приходит сюда уже
/// прочитанным — параметром, и это главное в этой подписи.
///
/// **Почему параметром, а не чтением внутри (правка 24.11, ревью целого).**
/// Прочитай ключ здесь — и отказ родится в точке, из которой до человека
/// дотянуться можно только одним способом на оба запуска. Так и вышло: отказ
/// ключа звал `gui::doom::refuse` прямо из тела подъёма, а оно общее у окна и
/// у набранного `serve`, — и `serve` на машине С РАБОЧИМ СТОЛОМ получал
/// модальное `MessageBoxW` вместо слов в свою консоль, держа при этом замок
/// единственного экземпляра. У задачи планировщика «только при входе
/// пользователя» нажать «ОК» и вовсе некому: ровно замеренное 17.11
/// состояние, которое закон 5 и запрещает.
///
/// Параметр это закрывает УСТРОЙСТВОМ, а не проверкой: узел нельзя поднять, не
/// имея ключа на руках, а взять его можно только у `node::key`, которая
/// отказывает словами. Значит отказ ключа рождается у ЗОВУЩЕГО — в теле,
/// возвращающем `Result`, — и уходит тем единственным путём, который уже
/// развёл окно и консоль (`gui::seen_by_the_person`, `main`). Третьего ответа
/// на вопрос «куда уходит отказ старта» в программе снова нет.
///
/// **Почему ключ — отказ подъёма, а сокет — переживаемая беда (решение
/// 23.11).** Разница не в тяжести, а в том, остаётся ли программа чем-то, что
/// можно починить. Без сокета узел не вышел в сеть сейчас: брандмауэр правят,
/// запуск повторяют, и всё остальное на этой машине работает. Без своего ключа
/// нет ЛИЧНОСТИ машины — ни сопряжения, ни канала, ни ответа второй стороне, —
/// и на этом не работает ничего, за чем программу запускают.
///
/// Довод «окно — то место, где человек и чинит беду» здесь не держит, и это
/// проверено замером, а не рассуждением: спека разрешает открывать окно на
/// незаполненном файле параметров, потому что поля в нём человек ЗАПОЛНЯЕТ, —
/// а запечатанный не для этого сеанса ключ в окне не починить ничем: поля для
/// него нет, кнопки нет, а единственное «лечение» (удалить файл) уничтожает
/// все выданные зачисления. Окно, которое показало бы карточки и не умело
/// ничего, обманывало бы человека молча — ровно третье состояние, запрещённое
/// законом 5 спеки («живой, молчащий и бесполезный», замер 23.11 по ssh: жив
/// на 480-й секунде, `stderr` пуст, работать не может).
///
/// Кто ЧИТАЕТ ключ — тот, кто поднимает узел, и у обоих это строка с `?` в
/// теле, возвращающем `Result`: `gui::launched` (до цикла GPUI — после него
/// отдать `Err` уже нечему) и `main::peer_wiring`. Читают они одной функцией
/// (`node::key`), то есть и правило, и слова у них одни.
///
/// `serves` — обслуживающая половина этой машины (`session::Serving`): поток узла находит в ней мост, когда по каналу приходит поток
/// вызовов. Пусто — доступ к 1С выключен, и вызов получает отказ словами.
pub fn start(kit: &Kit, tx: UnboundedSender<Out>, serves: crate::session::Serving, secret: iroh::SecretKey) -> Peer {
    let (cmd, rx) = tokio::sync::mpsc::unbounded_channel();
    let reach = Arc::new(Mutex::new(None));
    let (kit_in, reach_in, tx_in) = (kit.clone(), reach.clone(), tx.clone());
    std::thread::spawn(move || {
        let rt = match tokio::runtime::Runtime::new() {
            Ok(rt) => rt,
            Err(e) => {
                say(&tx_in, common::Event::Fail(format!("Не удалось выйти в сеть: {e}")));
                return;
            }
        };
        rt.block_on(serve(secret, kit_in, tx_in, reach_in, serves, rx));
    });
    Peer { cmd, reach }
}

/// Вся жизнь потока узла: поднять, объявить себя, принимать входящие,
/// звонить зовущими карточками.
async fn serve(
    secret: iroh::SecretKey,
    kit: Kit,
    tx: UnboundedSender<Out>,
    reach: Arc<Mutex<Option<Reach>>>,
    serves: crate::session::Serving,
    mut cmds: tokio::sync::mpsc::UnboundedReceiver<Cmd>,
) {
    // Остался один повод отказать — сокет, и он переживаемый: слова в журнал
    // (и в консоль у `serve`), а программа живёт и чинится повторным запуском.
    // Ключ сюда приходит уже прочитанным (`start` выше, там и довод).
    let node = match Node::with(secret).await {
        Ok(node) => node,
        Err(e) => {
            say(&tx, common::Event::Fail(e));
            return;
        }
    };
    // Срок, а не бесконечное ожидание: без интернета `online` не вернётся
    // никогда, а принимать по петле и по локальной сети узел умеет уже сейчас.
    let _ = tokio::time::timeout(ONLINE_WAIT, node.endpoint().online()).await;
    let seen = look(&node);
    *reach.lock().unwrap_or_else(|e| e.into_inner()) = Some(seen);
    let channels = Channels::default();
    let live = Live::default();
    tokio::spawn(accepting(node.clone(), channels.clone(), kit.clone(), tx.clone(), live.clone(), serves.clone()));
    let mut calls: HashMap<CardId, tokio::task::JoinHandle<()>> = HashMap::new();
    // Карточки, у которых партнёр уже записан, звонят САМИ, без щелчка:
    // человек разрешил подключение однажды, и перезапуск программы не повод
    // просить его нажать «Подключиться» ещё раз (спека контракта,
    // «Что хранится после»).
    match Partners::open(kit.state()) {
        Ok(partners) => {
            // Имя карточки берётся из настроек и нужно ТОЛЬКО для слов в журнал: сопоставляется карточка ключом, который партнёр и
            // назвал. Карточки в настройках уже нет (её удалили, а партнёр остался) — зовём ключом вместо имени: честнее, чем молчать.
            let names = card_names(&kit);
            for (card, _) in partners.all() {
                let name = names.get(&card).cloned().unwrap_or_else(|| card.to_string());
                start_call(
                    &node,
                    &channels,
                    &kit,
                    &tx,
                    &live,
                    &serves,
                    &mut calls,
                    Dialling { id: card, name },
                    String::new(),
                    Told::default(),
                );
            }
        }
        Err(e) => say(&tx, common::Event::Fail(e)),
    }
    while let Some(cmd) = cmds.recv().await {
        match cmd {
            Cmd::Dial { card, name, code, told } => {
                start_call(&node, &channels, &kit, &tx, &live, &serves, &mut calls, Dialling { id: card, name }, code, told)
            }
            Cmd::Calls { card, kind, stream, done } => {
                let (kit, tx, channels) = (kit.clone(), tx.clone(), channels.clone());
                tokio::spawn(async move {
                    pipe_calls(&kit, &tx, &channels, &card, kind, stream).await;
                    // Конец трубы виден слушателю по `drop` этого конца — сказать словами нечего, важен сам факт.
                    drop(done);
                });
            }
            Cmd::Revoke { card, peer } => {
                // Признак базы для слов отзыва — это и есть ключ отзываемой карточки (решение владельца 10.11). Прежде он искался
                // перебором по настройкам (чтение файла плюс поиск по имени), и на непрочитанных настройках или переименованной
                // карточке уезжал пустым. Искать больше нечего: он уже на руках.
                for reins in live.cut(peer, &card) {
                    let card = card.clone();
                    tokio::spawn(async move { reins.revoke(&card.on_wire(), REVOKED_TEXT).await });
                }
            }
            // Прощания идут ВМЕСТЕ, а не одно за другим: каждое ждёт
            // подтверждения до `channel::FAREWELL_PATIENCE`, и очередь из
            // пяти зачисленных сторон стоила бы человеку пяти сроков на
            // «Выходе» (минорная находка ревью задачи 8). Ответ уходит
            // ПОСЛЕ: тот, кто ждёт, ждёт именно договорённости.
            Cmd::ByeAll { done } => {
                let all = live.drain();
                futures::future::join_all(all.into_iter().map(|reins| reins.bye(Refuse::new(code::CLOSED, channel::WINDOW_CLOSED)))).await;
                let _ = done.send(());
            }
        }
    }
}

/// Слова отзыва той стороне. Причина и совет, как велит раздел «Ошибки»
/// спеки: без совета причина человеку не нужна.
const REVOKED_TEXT: &str =
    "Вам больше не разрешают подключаться к этой базе.\nЧеловек за тем компьютером снял разрешение для этого рабочего места.\n\
                            Позвоните ему и попросите новый код, если доступ нужен снова.";

/// Один живой разговор принимающей стороны: вожжи его управляющего потока и
/// карточка, которую он обслуживает.
///
/// `card` — `Option`, и это не удобство, а честность: имя карточки местное и
/// по каналу не ездит, мы сопоставляем его обратно по признаку базы, и
/// сопоставление может не сойтись (человек правил карточки под живым
/// разговором, настройки не прочлись). Пустая строка на этом месте врала бы,
/// что карточка известна и называется «», — и отзыв по такому потоку не
/// находил бы его никогда.
struct Talk {
    /// Номер разговора — им он и снимается с учёта. Нужен затем, что у одной
    /// стороны к одной карточке может идти не один поток (переподключение,
    /// чей прежний поток ещё не осыпался), и снимать надо СВОЙ, а не
    /// «какой-нибудь с тем же именем».
    id: u64,
    /// Карточка, которую обслуживает этот поток, — ОДНА, и это свойство типа.
    ///
    /// Прежде здесь лежал список: сторона, зачисленная к нескольким карточкам
    /// этой машины, возвращалась одним потоком, и `enroll::Outcome::Already`
    /// приносил несколько баз сразу. Поток числился за всеми ними, и отзыв
    /// любой из них резал его целиком — то есть отзыв одной карточки рвал связь
    /// по остальным, прямо против спеки. Теперь `Already` несёт ОДНУ базу, и
    /// списка здесь больше нет: делить у потока нечего, потому что делить не из
    /// чего.
    ///
    /// `None` — карточка не опознана вовсе; такой поток режется любым отзывом этой стороны (`cut_these`).
    ///
    /// **Сегодня этого значения здесь НЕ БЫВАЕТ, и сказано это прямо** (Important повторного ревью всей ветки: мёртвая защита, описанная
    /// как живая, — хуже, чем снятая). Ключ карточки приходит из исхода зачисления (`enroll::Outcome`), а тот собирается по тому же самому
    /// списку принимающих карточек, в котором его потом и ищут (`enroll::Cards::mine_named`): один снимок, одно чтение настроек, и промахнуться нечем.
    ///
    /// Остаётся он не на всякий случай, а потому, что ТИПОМ это не выражено: чтобы `None` стало невыразимым, исход зачисления должен нести
    /// саму карточку, а не её ключ, — и до тех пор `mine_named` возвращает `Option`, который кто-то обязан разобрать. Разобран он так, как
    /// разбирается всякое «не знаю» на вопросе о допуске в этом проекте: поток, про который нельзя доказать, что он обслуживает ДРУГУЮ
    /// карточку, держать после отзыва не за что (`cut_these`, `keep_holding`). То есть защита мёртвая, но не бесплатная ошибка: оживи этот
    /// путь — и он пойдёт в сторону запрета.
    card: Option<CardId>,
    /// Вожжи — только у ПРИНИМАЮЩЕЙ стороны: ими отзыв рвёт поток, который держит та. У звонящей стороны поток свой, и рвёт
    /// она его сама, когда кончает круг, — здесь `None`, и `cut` такой разговор не трогает.
    reins: Option<Reins>,
    /// Потолок записи ТОЙ машины, услышанный в `hello` ЭТОГО разговора.
    ///
    /// Живёт рядом с допуском нарочно: обе величины приходят из одного кадра и кончаются вместе с потоком. Книга хранит своё
    /// (`Party::peer_write`) для показа в карточке, а потоку вызовов нужна живая — та, что эта сторона объявила сейчас.
    peer: crate::wire::Ceiling,
}

/// Живые разговоры принимающей стороны — по СТОРОНЕ, а не по карточке.
///
/// **Почему по стороне (находка проверки безопасности на коммит задачи 9).**
/// Прежде ключом была пара «имя карточки + ключ стороны», а имя бралось
/// перебором по признаку базы и при неудаче оказывалось пустым. Поток,
/// заведённый под пустым или не тем именем, при отзыве не находился и
/// переживал собственный отзыв — то есть отзыв перестаёт быть немедленным
/// ровно в том случае, когда он важнее всего. Ключ стороны подделать нельзя:
/// его доказал сам iroh.
///
/// Отзыв режет каждый поток ЭТОЙ стороны, который держит отозванную
/// карточку, — и те, у которых имени нет вовсе: поток, про который нельзя
/// доказать, что он обслуживает другую карточку, держать после отзыва не за
/// что. Соседние стороны и соседние карточки той же стороны не трогаются
/// (к одной карточке зачисляют сколько угодно сторон, решение владельца
/// 1.11, и отзыв адресуется ОДНОЙ — той, чей отпечаток человек видел).
///
/// Обычный `std::sync::Mutex`, не `tokio`: его держат на одно взятие-изъятие
/// без единого `await` внутри, а сама отправка прощания идёт уже снаружи
/// замка.
#[derive(Clone, Default)]
struct Live {
    talks: Arc<Mutex<HashMap<EndpointId, Vec<Talk>>>>,
    next: Arc<std::sync::atomic::AtomicU64>,
}

impl Live {
    /// Запомнить разговор. Возвращает его номер — им он и снимается
    /// (`forget`).
    fn remember(&self, peer: EndpointId, card: Option<CardId>, reins: Option<Reins>, theirs: Ceiling) -> u64 {
        let id = self.next.fetch_add(1, Ordering::SeqCst);
        self.talks.lock().unwrap_or_else(|e| e.into_inner()).entry(peer).or_default().push(Talk { id, card, reins, peer: theirs });
        id
    }

    /// **Пускать ли поток ВЫЗОВОВ** от этой стороны к этой карточке.
    ///
    /// Правило одно на обе пары и звучит так: поток вызовов обслуживается тогда и только тогда, когда у этой машины есть ЖИВОЙ
    /// управляющий поток этой карточки к этому ключу. Отсюда два следствия даром, без единой новой строки: отзыв и прощание гасят
    /// потоки вызовов немедленно (управляющий поток снимается с учёта — и допуск исчезает вместе с ним), а второй книги допуска для
    /// вызовов не заводится вовсе.
    ///
    /// **Своей структуры под это нет нарочно** (план пары B звал её `Admit`). Учёт живых разговоров уже хранит ровно эту пару — ключ
    /// стороны и карточку, — и заводить рядом второй список значило бы завести вторую меру на один вопрос: тот самый разряд дефектов,
    /// который на этой ветке ловили шесть раз. Здесь — только имя правила, данное тому, что и так есть.
    ///
    /// Неопознанный разговор (`card: None`) допуска не даёт никому: карточку, о которой не договорились, назвать нечем.
    fn admits(&self, peer: EndpointId, card: &CardId) -> Option<Ceiling> {
        let held = self.talks.lock().unwrap_or_else(|e| e.into_inner());
        held.get(&peer)?.iter().find(|t| t.card.as_ref() == Some(card)).map(|t| t.peer)
    }

    /// Снять разговор с учёта — присмотр за ним кончился. Уже снятого
    /// (отзывом) здесь нет, и это не беда.
    ///
    /// Вожжи возвращаются наружу, а не падают здесь: падать им положено ВНЕ
    /// замка — их `Drop` ничего не ждёт, но держать чужой замок дольше
    /// нужного незачем.
    fn forget(&self, peer: EndpointId, id: u64) -> Option<Reins> {
        // Два `Option` здесь означают разное: внешний — «такого разговора в учёте нет» (его снял отзыв), внутренний — «вожжей у
        // этого разговора не бывает» (звонящая сторона держит поток сама, рвать его отзывом нам нечем).
        let mut held = self.talks.lock().unwrap_or_else(|e| e.into_inner());
        let rows = held.get_mut(&peer)?;
        let at = rows.iter().position(|t| t.id == id)?;
        let gone = rows.remove(at);
        if rows.is_empty() {
            held.remove(&peer);
        }
        gone.reins
    }

    /// Вожжи всех разговоров этой стороны, которые отзыв карточки обязан
    /// снять (`cut_these` решает, какие именно). Снятые тут же уходят с
    /// учёта: второй отзыв той же карточки резать уже нечего.
    fn cut(&self, peer: EndpointId, card: &CardId) -> Vec<Reins> {
        let mut held = self.talks.lock().unwrap_or_else(|e| e.into_inner());
        let Some(rows) = held.get_mut(&peer) else {
            return Vec::new();
        };
        let doomed = cut_these(&rows.iter().map(|t| t.card.clone()).collect::<Vec<_>>(), card);
        // С конца: удаление по месту не должно сдвигать места, которые ещё
        // предстоит удалить.
        let mut out: Vec<Reins> = doomed.into_iter().rev().filter_map(|at| rows.remove(at).reins).collect();
        if rows.is_empty() {
            held.remove(&peer);
        }
        out.reverse();
        out
    }

    /// Забрать ВСЕ живые разговоры всех сторон — программа уходит, и дальше
    /// присмотра за ними не будет ни у кого.
    ///
    /// Книга пустеет тем же движением: уходя, мы прощаемся ровно один раз, а
    /// вожжи, оставшиеся в книге после прощания, — это вожжи потока, которого
    /// уже нет.
    fn drain(&self) -> Vec<Reins> {
        let mut held = self.talks.lock().unwrap_or_else(|e| e.into_inner());
        held.drain().flat_map(|(_, rows)| rows.into_iter().filter_map(|t| t.reins)).collect()
    }

    /// Есть ли ещё живой разговор под этим номером. Нужно одному читателю —
    /// проверке щели между решением человека и записью вожжей
    /// (`answering`): если отзыв уже забрал наш разговор, рвать его второй
    /// раз не надо.
    fn alive(&self, peer: EndpointId, id: u64) -> bool {
        let held = self.talks.lock().unwrap_or_else(|e| e.into_inner());
        held.get(&peer).is_some_and(|rows| rows.iter().any(|t| t.id == id))
    }
}

/// Какие разговоры одной стороны режет отзыв карточки `card` — чистое
/// решение, и всё, что в отзыве можно решать неверно, решается здесь.
///
/// Режутся два случая: разговор ЭТОЙ карточки и разговор, карточка которого
/// неизвестна (`None`). Второй — не перестраховка: карточка сопоставляется
/// обратно по признаку базы, и не сошлась она только там, где настройки под
/// живым разговором изменились или не прочлись. Про такой поток нельзя
/// доказать, что он обслуживает ДРУГУЮ карточку, а отзыв обязан действовать
/// сразу — значит держать его после отзыва не за что.
///
/// Разговоры соседних карточек той же стороны не трогаются вовсе: человек
/// снял доступ к одной базе, а не ко всем. Прежде это было неправдой для
/// потоков, за которыми числилось несколько карточек: отзыв любой из них резал
/// такой поток целиком. Числиться за несколькими поток больше не может
/// (`Talk::card`), и правило держится типом, а не обещанием.
fn cut_these(held: &[Option<CardId>], card: &CardId) -> Vec<usize> {
    held.iter().enumerate().filter(|(_, mine)| mine.as_ref().is_none_or(|one| one == card)).map(|(at, _)| at).collect()
}

/// Держать ли только что зачисленный разговор — проверка щели между решением
/// человека и записью вожжей (находка проверки безопасности).
///
/// Щель настоящая: `accept_side` уже вернул «зачислен», а в книге живых
/// разговоров вожжей ещё нет. Отзыв, случившийся в эти микросекунды, не
/// находит чего рвать, запись об отзыве ложится в книгу допуска — и поток
/// живёт дальше, переживая собственный отзыв. Поэтому после записи вожжей
/// допуск спрашивается у книги ЕЩЁ РАЗ, и ответ разбирается здесь: отзыв
/// либо увидит наши вожжи, либо эта проверка увидит отзыв, третьего порядка
/// у двух событий нет.
///
/// Безымянный разговор не держится: проверить его допуск нечем — `enrolled_to`
/// спрашивают ключом карточки, — а «не знаю» на вопросе о допуске значит
/// «нет» везде в этом проекте. Безымянных разговоров сегодня не бывает вовсе
/// (`Talk::card`, там сказано, почему и почему разбор всё-таки стоит), и эта
/// ветка — не живая защита, а сторона, в которую обязан ошибаться невыразимый
/// типом случай.
///
/// На входе — ответ книги по карточке потока: `None` значит «карточка не
/// опознана», `Some(false)` — «разрешение сняли в щель». Прежде здесь лежал
/// список и свёртка «все на месте»: поток мог числиться за несколькими
/// карточками. Числиться так он больше не может (`Talk::card`), и свёртке
/// свернуть нечего.
fn keep_holding(seen: Option<bool>) -> bool {
    seen == Some(true)
}

/// Зовущая карточка для потока звонка: ключ, которым её сопоставляют, и имя, которым о ней говорят человеку.
///
/// Одним значением, а не двумя доводами рядом в каждой подписи: два довода на одно понятие однажды разъезжаются (передал ключ одной,
/// имя другой — и человек читает в журнале не ту карточку), а три функции звонка от них разом перешли предел `clippy::too_many_arguments`
/// — предел и назван затем, чтобы такое заметили.
#[derive(Clone)]
struct Dialling {
    /// Ключ — им карточка сопоставляется везде: партнёр, книга, слово состояния (`cfg::CardId`).
    id: CardId,
    /// Имя — ТОЛЬКО для слов человеку в журнал.
    name: String,
}

/// Заводит звонок карточки, заменяя прежний, если он ещё идёт.
///
/// Замена, а не второй звонок рядом: карточка одна, и два звонка по ней
/// означали бы два управляющих потока, из которых слово состояния показывало
/// бы случайный. Прежняя задача снимается (`abort`), а вместе с ней роняются
/// `Control` и `Hold` — канал закрывается тем же `Drop`, которым он
/// закрывается всегда (`channel::Hold`).
#[allow(clippy::too_many_arguments)]
fn start_call(
    node: &Node,
    channels: &Channels,
    kit: &Kit,
    tx: &UnboundedSender<Out>,
    live: &Live,
    serves: &crate::session::Serving,
    calls: &mut HashMap<CardId, tokio::task::JoinHandle<()>>,
    card: Dialling,
    code: String,
    told: Told,
) {
    let addr = match target(kit, &card.id, &code) {
        Ok(addr) => addr,
        Err(e) => {
            // Ждущему в консоли — та же причина и сразу: негодный код разбирается ЗДЕСЬ (`Ticket::from_code`), до всякого разговора, и молчать о нём значило бы держать человека полный срок ожидания ответа, которого не будет.
            told.failed(&e);
            say(tx, common::Event::Fail(e));
            return;
        }
    };
    if let Some(old) = calls.remove(&card.id) {
        old.abort();
    }
    let id = card.id.clone();
    let handle = tokio::spawn(calling(
        node.clone(),
        channels.clone(),
        kit.clone(),
        tx.clone(),
        live.clone(),
        serves.clone(),
        card,
        code,
        addr,
        told,
    ));
    calls.insert(id, handle);
}

/// Куда звонить этой карточкой: по вставленному коду либо по запомненному
/// партнёру.
///
/// Пустой код без партнёра — не беда программы, а разговор с человеком:
/// подключаться действительно некуда, и сказать это надо словами, а не
/// молчаливым бездействием кнопки.
fn target(kit: &Kit, card: &CardId, code: &str) -> Result<EndpointAddr, String> {
    if !code.trim().is_empty() {
        return Ok(crate::ticket::Ticket::from_code(code)?.addr());
    }
    let partner = Partners::open(kit.state())?
        .of(card)
        .ok_or("Кода нет, а по этой карточке ещё ни разу не подключались.\nВставьте код, выданный на компьютере с базой.")?;
    Ok(addr_of(&partner))
}

/// Адрес партнёра: ключ плюс подсказки того же вида, что ездят в коде
/// (`Ticket::addr`) и по тому же правилу — не разобралось, значит выброшено,
/// ключ остаётся.
fn addr_of(p: &Partner) -> EndpointAddr {
    let mut addr = EndpointAddr::new(p.key);
    for d in &p.direct {
        if let Ok(s) = d.parse::<std::net::SocketAddr>() {
            addr = addr.with_ip_addr(s);
        }
    }
    if let Some(relay) = &p.relay {
        if let Ok(url) = relay.parse::<iroh::RelayUrl>() {
            addr = addr.with_relay_url(url);
        }
    }
    addr
}

/// Что у зовущей карточки на руках между кругами.
///
/// Две половины одной памяти, и поэтому вместе: по ним решается, чем звонить
/// (`enroll::Call::of`), и решается один раз на круг. Раздельно они жили бы
/// каждая под своим замком, и «есть ли код» снова стало бы второй мерой рядом
/// с первой.
#[derive(Clone, Default)]
struct InHand {
    /// Код подключения, пока он не израсходован. Пустой — зачисление уже есть.
    code: String,
    /// Признак базы той карточки, которой этот поток, — как его назвала та
    /// сторона в `enroll_ok`.
    ///
    /// `None` — не знаем, и тогда та сторона отвечает всем списком своих баз,
    /// а поток числится за всеми ними: отзыв любой из них его режет. Поэтому
    /// признак не только помнится между кругами, но и ЖИВЁТ рядом с партнёром
    /// (`partners.toml`) — иначе первый же перезапуск возвращал бы карточку в
    /// это «не знаю», и отзыв соседней карточки рвал бы её связь.
    /// Ключ ТОЙ стороны — проводный (`wire::CardRef`): он из её пространства имён, и в наше не переводится.
    card: Option<crate::wire::CardRef>,
}

impl InHand {
    /// Чем звонить на этом круге. Решение одно и живёт в `enroll::Call::of`:
    /// длину строки кода здесь никто не меряет.
    fn call(&self) -> enroll::Call<'_> {
        enroll::Call::of(&self.code, self.card.as_ref())
    }

    /// Что остаётся на руках после круга — и были ли мы уже подключены.
    ///
    /// Код гасится РОВНО тогда, когда круг дошёл до «подключено»: он
    /// одноразовый (`Book::spend`), и второй круг с тем же кодом получил бы
    /// «код не найден», то есть переподключение кончилось бы на первом же
    /// обрыве. Недозвон его не расходует — предъявить не успели.
    ///
    /// Отдельным решением, а не строками внутри круга: оба его ответа видны
    /// человеку (опустевший код — он же признак «подключается СНОВА»), и
    /// спросить их надо без двух узлов и рантайма.
    fn after(&mut self, round: &Round, agreed: Option<crate::wire::CardRef>) -> bool {
        // Карточку, о которой договорились, помним до следующего круга: со
        // второго круга возврат называет её сам, и та сторона числит поток за
        // ней одной.
        if let Some(id) = agreed {
            self.card = Some(id);
        }
        match round {
            Round::Held(_) => {
                self.code.clear();
                true
            }
            _ => self.code.is_empty(),
        }
    }
}

/// Зовущая сторона одной карточки: круг за кругом, пока звать есть смысл
/// (`channel::keep_calling`).
///
/// **Код предъявляется ОДИН раз.** Он одноразовый (`Book::spend`), и второй
/// круг с тем же кодом получил бы отказ «код не найден», то есть
/// `Stopped::NotEnrolled` — и переподключение, ради которого круги и
/// существуют, кончилось бы на первом же обрыве. Поэтому после удачного
/// зачисления код гасится здесь же, а следующие круги идут возвратом по
/// карточке, которую та сторона назвала нашей.
///
/// Опустевший код — он же признак «мы уже были подключены»: первый
/// недозвон до зачисления остаётся «подключается», а после — «подключается
/// снова». Второго счётчика для этого не нужно.
#[allow(clippy::too_many_arguments)]
async fn calling(
    node: Node,
    channels: Channels,
    kit: Kit,
    tx: UnboundedSender<Out>,
    live: Live,
    serves: crate::session::Serving,
    card: Dialling,
    code: String,
    addr: EndpointAddr,
    told: Told,
) {
    flow(&tx, &card.id, Some(Flow::Calling));
    let hand = Arc::new(Mutex::new(InHand { code, card: known_card(&kit, &card.id) }));
    // **Неудача круга обязана назвать причину.** Живой прогон 15.11: человек вставил код, нажал «Подключиться», поле очистилось —
    // и больше ничего, ни строки, ни на этой машине, ни на той. `keep_calling` повторяет `Round::Failed` вечно, и до этой правки
    // повторял МОЛЧА: «не дозвонился», «канал не открылся», «разговор сорвался» выглядели для человека одинаково — как ничего.
    //
    // Говорится ОДИН раз на причину, а не на каждый повтор: повторы идут с нарастающей паузой годами, и журнал, в котором одна
    // строка повторена тысячу раз, человек читать не станет — это то же молчание, только шумное. Сменилась причина — скажется
    // новая; круг удался — память об уже сказанном чистится, и следующая беда снова будет названа.
    let said: Arc<Mutex<Option<String>>> = Arc::new(Mutex::new(None));
    let stopped = channel::keep_calling(|| {
        let (node, channels, kit, tx, card, addr, hand) =
            (node.clone(), channels.clone(), kit.clone(), tx.clone(), card.clone(), addr.clone(), hand.clone());
        let (live, serves) = (live.clone(), serves.clone());
        let (said, told) = (said.clone(), told.clone());
        async move {
            // Замок берётся и отпускается до первого ожидания — через `await`
            // его не держим ни разу.
            let mine = hand.lock().unwrap_or_else(|e| e.into_inner()).clone();
            let (round, agreed) = one_round(&node, &channels, &kit, &tx, &live, &serves, &card, addr, mine.call(), &told).await;
            {
                let mut last = said.lock().unwrap_or_else(|e| e.into_inner());
                match &round {
                    Round::Failed(why) if last.as_deref() != Some(why.as_str()) => {
                        say(&tx, common::Event::Warn(format!("«{}»: подключиться не удалось — {why}", card.name)));
                        *last = Some(why.clone());
                    }
                    Round::Failed(_) => {}
                    _ => *last = None,
                }
            }
            let enrolled = hand.lock().unwrap_or_else(|e| e.into_inner()).after(&round, agreed);
            if enrolled && !matches!(round, Round::NotEnrolled(_)) {
                flow(&tx, &card.id, Some(Flow::Retrying));
            }
            round
        }
    })
    .await;
    flow(&tx, &card.id, Some(Flow::Broken));
    let name = &card.name;
    match stopped {
        Stopped::Farewell(why) => say(&tx, common::Event::Say(format!("«{name}»: {}", why.text))),
        Stopped::NotEnrolled(no) => say(&tx, common::Event::Warn(format!("«{name}»: {}", no.text))),
    }
}

/// Один круг звонка: дозвониться, открыть управляющий поток, провести
/// зачисление, держать поток, пока та сторона говорит.
///
/// Вторым значением возвращает признак базы той карточки, о которой
/// договорились. Он и есть то, чем следующий круг назовёт свою карточку.
/// `None` — договориться не вышло вовсе (недозвон, отказ): выдумывать признак
/// нельзя, иначе поток числился бы за карточкой, о которой не договаривались.
#[allow(clippy::too_many_arguments)]
async fn one_round(
    node: &Node,
    channels: &Channels,
    kit: &Kit,
    tx: &UnboundedSender<Out>,
    live: &Live,
    serves: &crate::session::Serving,
    card: &Dialling,
    addr: EndpointAddr,
    call: enroll::Call<'_>,
    told: &Told,
) -> (Round, Option<crate::wire::CardRef>) {
    let note = |tx: &UnboundedSender<Out>, text: Option<String>| {
        if let Some(t) = text {
            say(tx, common::Event::Say(t));
        }
    };
    note(tx, crate::debug::step(|| format!("«{}»: звоню на {}", card.name, crate::enroll::short_key(&addr.id.to_string()))));
    let channel = match channels.to(node, addr.clone()).await {
        Ok(c) => c,
        Err(e) => {
            told.failed(&e);
            return (Round::Failed(e), None);
        }
    };
    note(tx, crate::debug::step(|| format!("«{}»: канал открыт, открываю управляющий поток", card.name)));
    let mut control = match channel.call().await {
        Ok(c) => c,
        Err(e) => {
            told.failed(&e);
            return (Round::Failed(e), None);
        }
    };
    // **Кем выходим на провод и есть ли что сказать о базе** — решает сочетание этой карточки (`cfg::Combo::side`), а не
    // привычка: в паре A здесь агенты и база у принимающей, в паре B база ЗДЕСЬ, и её поля — единственное, откуда та сторона их
    // узнает. Карточка берётся у того же разбора, что отвечает на проводе (`Machine::of`), чтобы признак базы и поля базы приезжали
    // из одного места.
    let machine = Machine::read(kit);
    let mine = machine.cards.mine_named(&card.id.on_wire()).cloned();
    let side = mine.as_ref().map_or(crate::wire::Side::WithAgents, |c| {
        if c.base_here {
            crate::wire::Side::WithBase
        } else {
            crate::wire::Side::WithAgents
        }
    });
    let base = match (side, &mine) {
        (crate::wire::Side::WithBase, Some(c)) => Some(c.on_wire()),
        _ => None,
    };
    note(tx, crate::debug::step(|| format!("«{}»: поток открыт, здороваюсь (сторона {side:?})", card.name)));
    let out = {
        let (send, recv) = control.halves();
        enroll::dial_side(send, recv, call, &says_name(), machine.ceiling, side, base).await
    };
    // База в ответе одна и у зачисления, и у возврата (`Outcome::Already`), то
    // есть угадывать здесь больше нечего: прежде на возврат приезжал список, и
    // при нескольких базах приходилось отвечать «не знаю» — поток числился за
    // всеми ними сразу.
    let (agreed, write) = match &out {
        // Ключ базы приехал ОТ ТОЙ СТОРОНЫ: он в её пространстве имён, и переводить его в наше нечем и незачем — рядом с партнёром
        // он так и лежит (`wire::CardRef`, там довод целиком).
        Ok(enroll::Outcome::Enrolled(base)) => (Some(base.base_id.clone()), base.write),
        // Пара B: база НАША, и ключа той стороны в ответе нет — он ей и не нужен. Им говорят, какую базу открыть (`McpOpen`), а в
        // паре B вызовы идут к нам, и шлёт его та сторона; отзыв делает она же, и наш ключ у неё есть. Право записи при этом
        // приезжает целым: мы его сами и сложили, и ниже по нему кладётся потолок разговору.
        Ok(enroll::Outcome::EnrolledHere(base)) => (None, base.write),
        Ok(enroll::Outcome::Already(base)) => (Some(base.id.clone()), base.write),
        _ => (None, false),
    };
    note(tx, crate::debug::step(|| format!("«{}»: ответ зачисления: {out:?}", card.name)));
    // Ждущему в консоли — ЗДЕСЬ, а не на выходе из круга: `Round::Held` возвращается лишь когда поток уже кончился, то есть удачное зачисление человек прочитал бы не раньше, чем связь оборвётся. Исход разговора известен ровно в этой точке, им и отвечаем (решение ведущего: слова исходов берутся у зачисления, второго словаря нет).
    told.tell(&out);
    match out {
        Err(e) => {
            control.end(None).await;
            (Round::Failed(e), agreed)
        }
        Ok(enroll::Outcome::NotEnrolled(no)) => {
            control.end(None).await;
            (Round::NotEnrolled(no), agreed)
        }
        Ok(_) => {
            // Куда возвращаться после обрыва — запоминается ТОЛЬКО здесь, и
            // только после того, как та сторона признала нас своими. Ключ
            // берётся у канала (`Channel::peer`), а не у кода: это то, что
            // доказал сам iroh, а не то, что было написано в строке.
            remember(kit, tx, &card.id, channel.peer(), &addr, agreed.as_ref());
            flow(tx, &card.id, Some(Flow::Up));
            // Право записи называется словами КАЖДЫЙ круг, а не только на
            // первом зачислении: потолок той машины складывается заново на
            // каждом подключении, и «переключённый потолок доедет следующим
            // подключением» (спека) человек читает здесь. Это же и
            // единственный читатель поля `write` у возврата — без него оно
            // уезжало бы в никуда.
            say(tx, common::Event::Ok(format!("«{}»: подключено, {}", card.name, access_word(write))));
            // Разбирать сказанное по живому потоку здесь нечего: всё, что
            // кончает соединение, `hold` разбирает сам (`bye`, `revoked`), а
            // сообщения «что-то изменилось на стороне базы» в этой версии нет
            // — оно было в таблице спеки и не отправлялось ниоткуда, и честно
            // снятая строка лучше пустого обещания (`wire::KNOWN`).
            // **Пока поток держится, вызовы обслуживает ЭТА сторона** — в паре B база здесь, у звонящего (шаг 6 плана пары B).
            //
            // Допуск у потоков вызовов один на обе пары: «есть живой управляющий поток этой карточки к этому ключу» (`Live::admits`).
            // Поэтому карточка кладётся в тот же учёт, что у принимающей стороны, — вожжей у неё нет (поток держим мы сами), и
            // снимается запись вместе с кругом: кончился круг — кончился и допуск, без второго читателя книги.
            let watch = Watch {
                live,
                peer: channel.peer(),
                // Потолок той стороны она объявила в `hello_ok`, и здесь он уже сложен с нашими двумя мерами (`write` выше):
                // в учёт кладём именно её слово, чтобы мост спросил три меры, а не две.
                id: live.remember(channel.peer(), Some(card.id.clone()), None, if write { Ceiling::Full } else { Ceiling::ReadOnly }),
                _answering: Falls(tokio::spawn(answer_calls(
                    channel.clone(),
                    tx.clone(),
                    live.clone(),
                    serves.clone(),
                    kit.clone(),
                    channel.peer(),
                ))),
            };
            let gone = channel::hold(control.ear(), |_| {}).await;
            // Круг кончился — кончается и обслуживание: страж снимает и запись из учёта, и задачу приёма, и делает это своим `Drop`,
            // то есть и на пути, которого здесь не видно, — `abort` самого круга.
            drop(watch);
            // Единственный выход из соединения — через `end`, и на этом пути
            // тоже: сказать нам нечего (`None`), но написанное до этого
            // обязано доехать прежде, чем канал закроется.
            control.end(None).await;
            (Round::Held(gone), agreed)
        }
    }
}

/// Задача, которая не переживает своего места: `Drop` её роняет.
///
/// **Брошенная `JoinHandle` задачу ОТВЯЗЫВАЕТ, а не роняет.** Отсюда весь разряд находок проверки безопасности 11.11: поток вызовов
/// снимали, а мост с ребёнком под ним продолжал работать; круг звонка снимали `abort`-ом, а задача приёма входящих оставалась жить и
/// отвечать на `McpOpen`. Ручной `abort` в конце функции от этого не спасает — до конца дело может и не дойти.
///
/// Ребёнок уходит за задачей сам: `Job` моста лежит на её стеке, а `JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE` гасит его на `drop`
/// (`job::Job`).
struct Falls(tokio::task::JoinHandle<()>);

impl Drop for Falls {
    fn drop(&mut self) {
        self.0.abort();
    }
}

/// Присмотр ЗВОНЯЩЕЙ стороны: запись в учёте допуска и задача приёма входящих — вместе, и снимаются сами.
///
/// `Drop`, а не две строки после `hold`: круг звонка снимают `abort`-ом (человек вставил другой код, закрыл окно, `start_call`
/// пришёл поверх прежнего), и строки «снять с учёта» тогда просто не исполнились бы — допуск остался бы жить, а приём входящих
/// продолжал бы обслуживать вызовы (находка проверки безопасности 11.11, четвёртая волна).
struct Watch<'a> {
    live: &'a Live,
    peer: EndpointId,
    id: u64,
    _answering: Falls,
}

impl Drop for Watch<'_> {
    fn drop(&mut self) {
        self.live.forget(self.peer, self.id);
    }
}

/// Приём входящих потоков на канале, который открыли МЫ (пара B, шаг 6).
///
/// **Законное начало здесь ровно одно — `McpOpen`.** Зачисление по этому каналу уже состоялось, и состоялось оно в другую сторону:
/// код выдала та сторона, книга допуска её, а у нас база. Поэтому `Hello` сюда приехать может только по ошибке сборки, и отвечаем мы
/// на него тем же отказом словами, каким `enroll` отвечает на кадр не в свою очередь.
///
/// Канал держится потоком, который мы и так держим (`Control`), поэтому ожидание входящего ничего лишнего не продлевает: кончился
/// круг — задачу снимают, и незавершённый `answer` уходит с ней.
async fn answer_calls(
    channel: channel::Channel,
    tx: UnboundedSender<Out>,
    live: Live,
    serves: crate::session::Serving,
    kit: Kit,
    peer: EndpointId,
) {
    // Потоки вызовов держатся НАБОРОМ, а не отпускаются в рантайм: `JoinSet` роняет их своим `Drop`, то есть кончился круг — и
    // ни один открытый вызов его не переживает (находка проверки безопасности 11.11, четвёртая волна). Законченные выметаются тут
    // же, иначе набор растёт без предела за долгий рабочий день.
    let mut streams = tokio::task::JoinSet::new();
    while let Ok(mut control) = channel.answer().await {
        while streams.try_join_next().is_some() {}
        let (tx, live, serves, kit) = (tx.clone(), live.clone(), serves.clone(), kit.clone());
        streams.spawn(async move {
            let first = {
                let (send, recv) = control.halves();
                match enroll::first_frame(send, recv).await {
                    Ok(msg) => msg,
                    Err(e) => {
                        say(&tx, common::Event::Warn(e));
                        control.end(None).await;
                        return;
                    }
                }
            };
            match first {
                crate::wire::Msg::McpOpen { base_id, kind } => {
                    serve_calls(&tx, &live, &serves, &kit, control, peer, &base_id, kind).await;
                }
                other => {
                    let no = crate::wire::Refuse::new(crate::wire::code::UNKNOWN_MESSAGE, enroll::out_of_turn("mcp_open", &other));
                    control.end(Some(no)).await;
                }
            }
        });
    }
}

/// Приём входящих: канал → управляющий поток → разговор зачисления.
///
/// Сам цикл — в `channel::accept_all`: три задачи, канал живёт дольше любого
/// своего потока, поток — дольше разговора по нему. Здесь остаётся только то,
/// что к проводу не относится: куда писать о беде, которую той стороне
/// сказать нечем (её конца у нас уже нет), и чем разговаривать.
///
/// Своей копии этого цикла здесь больше нет. Она жила тут ровно потому, что
/// `accept_all` не отдавала разговору ключ той стороны, без которого
/// `enroll::accept_side` не решает допуск; теперь отдаёт, и одно правило
/// живёт в одном месте.
async fn accepting(node: Node, channels: Channels, kit: Kit, tx: UnboundedSender<Out>, live: Live, serves: crate::session::Serving) {
    let noted = tx.clone();
    channel::accept_all(
        &node,
        &channels,
        move |why| say(&noted, common::Event::Warn(why)),
        move |control, peer| answering(kit.clone(), tx.clone(), live.clone(), serves.clone(), control, peer),
    )
    .await;
}
/// Увести местное соединение агента в канал: открыть поток, поздороваться заголовком и перелить байты. Открывает и переливает
/// `open_calls` ниже; здесь остаётся то, что делать, когда вести вызов НЕКУДА, — сказать причину человеку и агенту.
///
/// **Чего здесь нет нарочно.** Ни одного правила моста: ни белого списка инструментов, ни подмешивания своих, ни пересоздания ребёнка.
/// Мост стоит на той стороне, у базы, и это и есть граница работы — «меняется труба, а не механизм» (спека протокола, раздел «MCP»).
///
/// **Куда вести вызов, решает `enrolled::route`, и решает это ОДИНАКОВО для карточки, которая звонила, и для той, которая звонок
/// приняла.** Кто кому позвонил при знакомстве, не решает, кто потом может спросить базу: достижимость узлов iroh симметрична, а
/// «где база» и «где агенты» — две независимые вещи (спека серверного режима 29.10). Второго списка партнёров под это не заводится:
/// у звонившей карточки ключ и признак базы лежат рядом с партнёром (`Partners::route_of`), у принявшей — в книге допуска, рядом с
/// ключом той стороны и её `side` (`Party::base`); обе памяти уже были, и обе спрашивает одна функция.
async fn pipe_calls(
    kit: &Kit,
    tx: &UnboundedSender<Out>,
    channels: &Channels,
    card: &CardId,
    kind: crate::ops_host::McpServer,
    mut stream: tokio::net::TcpStream,
) {
    // Отказ говорится ДВАЖДЫ и обеими дорогами, какими тут вообще говорят: в журнал — человеку, и в сам поток вызовов — агенту
    // (`bridge::refuse_calls`). Прежде поток молча ронялся, и агент показывал человеку «сервер отключился» вместо названной
    // причины — то же молчание, что отдавало «0 инструментов» (починка 25.11, см. `listen::Bridge`).
    if let Err(no) = open_calls(kit, channels, card, kind, &mut stream).await {
        let words = match &no {
            common::Event::Fail(t) | common::Event::Warn(t) => t.clone(),
            other => format!("{other:?}"),
        };
        say(tx, no);
        crate::bridge::refuse_calls(&mut stream, &words).await;
    }
}

/// Открыть вызовы к той стороне и прокачать их до конца. `Err` — вести вызов некуда, и в нём СЛОВА причины той строгости, какой
/// она есть в журнале: открыть книгу допуска не удалось — отказ (`Fail`), партнёра нет или связь не держится — предупреждение.
async fn open_calls(
    kit: &Kit,
    channels: &Channels,
    card: &CardId,
    kind: crate::ops_host::McpServer,
    stream: &mut tokio::net::TcpStream,
) -> Result<(), common::Event> {
    let partners = Partners::open(kit.state()).map_err(common::Event::Fail)?;
    // Книга открывается ЗДЕСЬ, а не держится снимком: `open` перечитывает файл под замком, и список зачисленных у неё свежий.
    // Решение о ДОПУСКЕ по этому списку не принимается (на это есть `enrolled_to`, читающий диск под каждый вопрос) — здесь
    // решается, куда уходит НАШ вызов, а отозванная сторона отсечётся там, где допуск и спрашивают: у себя (`Admission::of`).
    let book = Book::open(kit.state()).map_err(common::Event::Fail)?;
    let route = crate::enrolled::route(partners.route_of(card), &book.of(card)).map_err(|w| common::Event::Warn(w.to_string()))?;
    let Some(channel) = channels.of(route.key) else {
        return Err(common::Event::Warn("Вызов агента некуда вести: связь с той стороной сейчас не держится.".to_string()));
    };
    let mut control = channel.call().await.map_err(common::Event::Warn)?;
    let opened = {
        let (send, recv) = control.halves();
        match crate::wire::Frame::write(send, &crate::wire::Msg::McpOpen { base_id: route.base, kind }).await {
            Err(e) => Err(e.to_string()),
            // Ответ ждём тем же сроком, что и прочие кадры разговора: молчание той стороны — такой же ответ, как отказ.
            Ok(()) => match enroll::first_frame(send, recv).await {
                Ok(crate::wire::Msg::McpOk) => Ok(()),
                Ok(crate::wire::Msg::Refuse(no)) => Err(no.text.to_string()),
                Ok(other) => Err(format!("та сторона ответила не тем кадром: {other:?}")),
                Err(e) => Err(e),
            },
        }
    };
    if let Err(why) = opened {
        control.end(None).await;
        return Err(common::Event::Warn(why));
    }
    // Половины уезжают в трубу вместе с держателем канала: пока идут вызовы, канал закрыться не вправе.
    let (send, recv, hold) = crate::channel::into_pipe(control);
    let mut theirs = tokio::io::join(recv, send);
    let _ = tokio::io::copy_bidirectional(stream, &mut theirs).await;
    drop(hold);
    Ok(())
}

/// Обслужить поток ВЫЗОВОВ: та сторона открыла его к нашей карточке и назвала, какой из серверов инструментов ей нужен.
///
/// Допущен ли поток, решает `Admission::of` — один вопрос, один ответ, четыре отказа. Здесь остаётся только труба: сказать отказ
/// словами, подтвердить `McpOk`, свести половины канала с мостом и дождаться конца.
///
/// Дальше по этому же потоку идёт сырой json-rpc, и правил моста мы не касаемся: меняется труба, а не механизм.
#[allow(clippy::too_many_arguments)]
async fn serve_calls(
    tx: &UnboundedSender<Out>,
    live: &Live,
    serving: &crate::session::Serving,
    kit: &Kit,
    mut control: crate::channel::Control,
    peer: EndpointId,
    base_id: &crate::wire::CardRef,
    kind: crate::ops_host::McpServer,
) {
    let admitted = match Admission::of(kit, live, serving, peer, base_id) {
        Ok(admitted) => admitted,
        Err(no) => {
            control.end(Some(crate::wire::Refuse::new(no.code(), no.text()))).await;
            return;
        }
    };
    if crate::wire::Frame::write(control.says(), &crate::wire::Msg::McpOk).await.is_err() {
        return;
    }
    say(tx, common::Event::Say(format!("«{}»: агент той стороны открыл вызовы", admitted.card.name)));
    // Половины уезжают в мост вместе с держателем канала: пока идут вызовы, канал закрыться не вправе.
    let (send, recv, hold) = crate::channel::into_pipe(control);
    // **Труба живёт не дольше сеанса И не дольше этого потока.** Мост поднят в потоке узла, а не в потоке сеанса, и уронить его
    // `drop(rt)` сеанса не может: без этого «выключил доступ к 1С» значило бы «выключил для новых», а уже идущие вызовы доживали бы
    // с живым ребёнком под ними. Снятие самого потока вызовов — то же самое с другой стороны: `Falls` роняет задачу своим `Drop`,
    // куда бы эта функция ни вышла, включая `abort` снаружи (находка проверки безопасности 11.11, вторая и четвёртая волны).
    let mut task = Falls(admitted.open.serve().serve(crate::session::Served::Mcp(kind), admitted.incoming(tokio::io::join(recv, send))));
    tokio::select! {
        _ = &mut task.0 => {}
        () = admitted.open.until_stopped() => {}
    }
    drop(task);
    drop(hold);
    say(tx, common::Event::Say(format!("«{}»: вызовы закончились", admitted.card.name)));
}

/// Допуск потока вызовов: один вопрос, один ответ, четыре отказа.
///
/// Прежде четыре проверки стояли подряд в теле `serve_calls`, и у каждой был свой `return` с кодом провода и словами. Каждая по
/// отдельности защищена докстрокой и своей находкой проверки безопасности, но ПОНЯТИЯ «допущен ли этот поток» не было нигде:
/// чтобы его собрать, читающий обходил четыре файла, а отказы лежали отдельно от проверок. И доказать их было нечем — весь разбор
/// требовал живого потока канала, то есть второй машины.
///
/// Здесь это один конструктор без сети: четыре отказа стали четырьмя ветвями одного `Err`, и каждая впервые проверяема.
struct Admission {
    card: crate::enroll::Card,
    open: crate::session::Open,
    /// Потолок записи ТОЙ машины — из того же кадра `hello`, что и допуск, и кончается вместе с ним.
    ///
    /// Приватный нарочно: наружу он отдаётся только `incoming`, то есть уже приклеенным к потоку. Отдельно взять его и потерять
    /// по дороге (дыра 11.11, `f36f5cb`) этим становится невыразимо.
    theirs: Ceiling,
}

/// Почему поток вызовов не допущен — с кодом провода и словами человеку рядом, а не в другом конце файла.
enum Denied {
    /// Карточки с таким ключом у нас нет — либо есть, но её база не здесь.
    NoSuchBase,
    /// Управляющего потока этой карточки к этому ключу нет.
    NotHeld,
    /// Доступ к 1С на этой машине выключен.
    Off,
    /// Карточка не текущая: мост поднят по другой, и её базу чужому вызову не отдают.
    NotCurrent,
}

impl Denied {
    fn code(&self) -> &'static str {
        match self {
            // «Нет такой» и «есть, но не текущая» отвечаются ОДНИМ кодом: по коду та сторона не должна различать, какая из двух
            // причин сработала, — иначе код становится способом перебирать чужие карточки.
            Denied::NoSuchBase | Denied::NotCurrent => crate::wire::code::NO_BASE,
            Denied::NotHeld => crate::wire::code::NOT_ALLOWED,
            Denied::Off => crate::wire::code::MCP_OFF,
        }
    }

    fn text(&self) -> &'static str {
        match self {
            Denied::NoSuchBase => NO_SUCH_BASE,
            Denied::NotHeld => NOT_HELD,
            Denied::Off => MCP_OFF_HERE,
            Denied::NotCurrent => NOT_CURRENT,
        }
    }
}

impl Admission {
    /// Допущен ли поток вызовов к нашей базе — четыре вопроса, задаваемые в этом порядке.
    ///
    /// 1. **Дорога к обслуживанию одна, и она узкая** (`Cards::serving_named`): карточка, чья база ЗДЕСЬ. Разрешение у карточки
    ///    без базы значит «присылайте свою базу моим агентам» — права отдать СВОЮ базу оно не даёт, и путать их нельзя (находка
    ///    проверки безопасности 11.11, вторая волна).
    /// 2. **Жив ли управляющий поток этой карточки к этому ключу** (`Live::admits`). Это и есть всё правило допуска: вторая книга
    ///    разрешений для вызовов не заводится, а отзыв и прощание гасят вызовы сами собой — вместе с управляющим потоком уходит и
    ///    допуск. Оттуда же приезжает потолок той машины: обе величины пришли из одного кадра `hello`.
    /// 3. Включено ли обслуживание (`Serving::now`). Пусто — доступ к 1С выключен, и это ответ, а не беда.
    /// 4. **Мост поднят по ТЕКУЩЕМУ соединению машины, и база в нём — его.** Значит вызов по другой карточке уехал бы в чужую
    ///    базу: допуск спрашивали по одной, а обслужили бы другую (находка проверки безопасности 11.11). Это ограничение движка,
    ///    а не замысла; снимется оно тогда, когда мост научится подниматься ПО КАРТОЧКЕ.
    ///
    /// **Карточки читаются ЗДЕСЬ И СЕЙЧАС, а не снимком начала разговора** (третья волна той же проверки). Управляющий поток
    /// живёт часами: человек успевает переключить у карточки «Где база», и снимок, снятый при его открытии, продолжал бы отдавать
    /// базу, которой у этой карточки больше нет. Поэтому сюда приезжает комплект, а не `Cards`: передать устаревший набор
    /// невыразимо — тем же приёмом, которым чинили `session::Open::is_for`.
    fn of(
        kit: &Kit,
        live: &Live,
        serving: &crate::session::Serving,
        peer: EndpointId,
        base_id: &crate::wire::CardRef,
    ) -> Result<Admission, Denied> {
        Admission::from_cards(Machine::read(kit).cards, live, serving, peer, base_id)
    }

    /// То же, но карточки даёт вызывающий — ими проверяются тесты (тот же приём и тот же довод, что у `Machine::read_with`:
    /// DPAPI из тестов не зовём). Боевой путь зовёт `of`, и подсунуть ему устаревший набор по-прежнему нечем.
    #[cfg(test)]
    fn from_cards_for_test(
        cards: crate::enroll::Cards,
        live: &Live,
        serving: &crate::session::Serving,
        peer: EndpointId,
        base_id: &crate::wire::CardRef,
    ) -> Result<Admission, Denied> {
        Admission::from_cards(cards, live, serving, peer, base_id)
    }

    fn from_cards(
        cards: crate::enroll::Cards,
        live: &Live,
        serving: &crate::session::Serving,
        peer: EndpointId,
        base_id: &crate::wire::CardRef,
    ) -> Result<Admission, Denied> {
        let card = cards.serving_named(base_id).cloned().ok_or(Denied::NoSuchBase)?;
        let theirs = live.admits(peer, card.id()).ok_or(Denied::NotHeld)?;
        let open = serving.now().ok_or(Denied::Off)?;
        if !open.is_for(card.id()) {
            return Err(Denied::NotCurrent);
        }
        Ok(Admission { card, open, theirs })
    }

    /// Поток канала вместе с потолком той машины — единственная дорога, которой потолок выходит из допуска.
    fn incoming<S>(&self, stream: S) -> crate::session::Incoming<S> {
        crate::session::Incoming::FromPeer(stream, self.theirs)
    }
}

/// Карточки с таким ключом у нас нет. Слова те же, какими отвечает зачисление: разницы между «нет такой» и «есть, но не ваша» по ним
/// не видно (та же защита, что у возврата).
const NO_SUCH_BASE: &str = "Такой базы здесь нет.\nПопросите новый код на том компьютере, к которому подключаетесь.";

/// Управляющего потока этой карточки нет — значит и вызовам тут делать нечего.
const NOT_HELD: &str = "Подключение к этой базе не держится.\nПодключитесь заново: без живого подключения вызовы не обслуживаются.";

/// Вызов пришёл по карточке, которая сейчас не текущая: мост поднят по текущей, и её базу чужому вызову не отдают.
const NOT_CURRENT: &str = "Эта база сейчас не обслуживается.\nНа том компьютере работают с другим соединением — попросите переключить \
                           его на нужное.";

/// Обслуживание на этой машине выключено.
const MCP_OFF_HERE: &str = "Доступ к 1С на том компьютере выключен.\nПопросите включить его в окне программы.";

/// Один разговор зачисления на принимающей стороне: заявка в окно, решение
/// человека обратно, и дальше держим поток.
///
/// **Книга открывается своя, на этот разговор.** Так и задумано
/// (`enrolled::Book` — «окно и отдельный процесс держат разные `Book` на один
/// файл»): каждая правка перечитывает файл под межпроцессным замком, поэтому
/// снимок в памяти окна и снимок здесь не спорят. Решение о допуске читает
/// диск (`Book::enrolled_to`), и отзыв в окне действует немедленно.
///
/// **Вожжи зачисленного разговора кладутся в `live`** (`channel::reins`):
/// по ним «Отозвать разрешение» снимает поток в ту же секунду, а не на
/// следующем круге той стороны. Снимаются они оттуда ровно тогда, когда
/// присмотр кончился, — и уронённые вожжи досылают написанное и закрывают
/// поток сами (`channel::settle`).
///
/// **Чего здесь ещё нет.** Прощание при выключении обслуживания
/// (`channel::SERVING_OFF`). Слова и вожжи для него готовы, не хватает зова из
/// переключателя обслуживания (`gui::link`) — а он в чужом файле, и этой
/// задачей не правится. Пока зова нет, та сторона читает обрыв вместо
/// причины, и это единственное, что в `bye` ещё не доехало: прощание при
/// закрытии окна (`channel::WINDOW_CLOSED`) уходит залпом с «Выхода»
/// (`Cmd::ByeAll`).
async fn answering(
    kit: Kit,
    tx: UnboundedSender<Out>,
    live: Live,
    serves: crate::session::Serving,
    mut control: crate::channel::Control,
    peer: EndpointId,
) {
    let mut book = match Book::open(kit.state()) {
        Ok(book) => book,
        Err(e) => {
            say(&tx, common::Event::Fail(e));
            return;
        }
    };
    // Потолок машины объявляется той стороне в `hello_ok`: в паре B складывать право записи будет она, и своего слова о нашем
    // потолке ей взять больше негде (план пары B, раздел 4).
    let Machine { cards, ceiling: ours } = Machine::read(&kit);
    let ask = |request: enroll::Request| {
        let tx = tx.clone();
        async move {
            let (answer, wait) = tokio::sync::oneshot::channel();
            if tx.unbounded_send(Out::Enroll(Pending::new(request, answer))).is_err() {
                // Окна больше нет — спрашивать некого, и это не отказ
                // человека, а отсутствие человека.
                return enroll::Decision::NoAnswer;
            }
            // Уронённый передатчик (окно закрыли, заявку вытеснила новая от
            // той же стороны) — тот же третий ответ: решения не было.
            wait.await.unwrap_or(enroll::Decision::NoAnswer)
        }
    };
    // **У потока два законных начала** (шаг 4 плана пары B): `Hello` — разговор о зачислении, `McpOpen` — поток вызовов к нашему
    // серверу инструментов. Различает их тот, кто читает первый кадр, и это здесь.
    let first = {
        let (send, recv) = control.halves();
        match enroll::first_frame(send, recv).await {
            Ok(msg) => msg,
            Err(e) => {
                say(&tx, common::Event::Warn(e));
                control.end(None).await;
                return;
            }
        }
    };
    if let crate::wire::Msg::McpOpen { base_id, kind } = first {
        serve_calls(&tx, &live, &serves, &kit, control, peer, &base_id, kind).await;
        return;
    }
    let out = {
        let (send, recv) = control.halves();
        enroll::accept_side_with(first, send, recv, peer, &mut book, &cards, ours, ask).await
    };
    let out = match out {
        Ok(out) => out,
        Err(e) => {
            say(&tx, common::Event::Warn(e));
            control.end(None).await;
            return;
        }
    };
    // База, о которой договорились, — ОДНА и у зачисления, и у возврата
    // (`enroll::Outcome`, там и довод): поток у карточки свой, и числить его за
    // всеми базами партнёра значит рвать отзывом одной связь по остальным.
    // Ключ в исходе ПРОВОДНЫЙ (`wire::CardRef`): таким он и уехал той стороне, таким и вернётся в отзыве. Наша карточка достаётся из
    // него одной названной дверью (`Cards::mine_named`) — прямого перевода «проводный ключ → наш» нет вовсе, иначе чужой ключ,
    // совпавший с нашим по одинаковому имени карточки, молча сошёл бы за свой (шаг 2 плана пары B).
    let (agreed, write): (crate::wire::CardRef, bool) = match &out {
        // `EnrolledHere` сюда не приходит никогда, и это не пробел: его называет только ЗОВУЩАЯ половина (`enroll::dial_side`,
        // пара B), а это половина принимающая — она отвечает `Enrolled` своей карточкой в обеих парах.
        enroll::Outcome::Enrolled(base) | enroll::Outcome::EnrolledHere(base) => (base.base_id.clone(), base.write),
        enroll::Outcome::Already(base) => (base.id.clone(), base.write),
        enroll::Outcome::NotEnrolled(no) => {
            say(&tx, common::Event::Say(no.text.clone().into()));
            control.end(None).await;
            return;
        }
    };
    // Наша карточка по ключу, о котором договорились (`Cards::mine_named`, там и довод).
    // Неопознанный разговор учитывается как неопознанный и режется любым
    // отзывом этой стороны (`cut_these`).
    let served = cards.mine_named(&agreed).cloned();
    // Слово состояния — только там, где карточка известна: завести строку
    // состояния для карточки, которой в списке нет, значило бы показать
    // человеку карточку-призрак.
    let shown = served.as_ref().map_or_else(|| "карточка не опознана".to_string(), |c| c.name.clone());
    if let Some(c) = &served {
        flow(&tx, c.id(), Some(Flow::Up));
    }
    // Право записи — то, что ПОЛУЧИЛОСЬ после сложения потолков: человек видит
    // в журнале, чем эта сторона сейчас может пользоваться, а не чем ей
    // когда-то разрешили.
    say(&tx, common::Event::Ok(format!("«{shown}»: подключено, {}", access_word(write))));
    let (reins, mut recv) = channel::reins(control);
    let id =
        live.remember(peer, served.as_ref().map(|c| c.id().clone()), Some(reins), if write { Ceiling::Full } else { Ceiling::ReadOnly });
    // Щель между решением человека и записью вожжей: спрашиваем допуск ЕЩЁ
    // РАЗ, уже после записи. Отзыв, случившийся в эти микросекунды, либо
    // увидит наши вожжи и порвёт поток сам, либо не увидит — и тогда его
    // увидит эта проверка. Третьего порядка у двух событий нет.
    let seen = served.as_ref().map(|c| book.enrolled_to(c.id(), peer).ok().flatten().is_some());
    if !keep_holding(seen) {
        // Рвём только СВОЙ разговор и только если отзыв не забрал его раньше:
        // иначе второе прощание ушло бы в поток, которого уже нет.
        if live.alive(peer, id) {
            if let Some(reins) = live.forget(peer, id) {
                reins.revoke(&agreed, REVOKED_TEXT).await;
            }
        }
        if let Some(c) = &served {
            flow(&tx, c.id(), Some(Flow::Broken));
        }
        say(&tx, common::Event::Warn(format!("«{shown}»: разрешение сняли прямо во время разговора — связь закрыта")));
        return;
    }
    let gone = channel::hold(&mut recv, |_| {}).await;
    // Вожжи уходят с учёта и падают здесь: их задача письма дошлёт написанное
    // и снимет поток сама. Если отзыв успел забрать их раньше — забирать
    // нечего, и это не беда.
    drop(live.forget(peer, id));
    if let Some(c) = &served {
        flow(&tx, c.id(), Some(Flow::Broken));
    }
    match gone {
        Gone::Farewell(why) => say(&tx, common::Event::Say(format!("«{shown}»: {}", why.text))),
        Gone::Broken(why) => say(&tx, common::Event::Say(format!("«{shown}»: {}", why.text))),
    }
}

/// Что эта машина объявляет той стороне: принимающие карточки и потолок
/// записи — ОДНИМ чтением настроек и одной мерой.
///
/// **Почему вместе, а не двумя функциями.** Прежде карточки читались терпимо
/// (`load_unchecked`), а потолок — строго (`load` с `validate`): та же пара
/// разных мер на один файл, которую чинил `c32f2c4`, уцелевшая через
/// пятьдесят строк. Цена была не теоретической: у нового человека настройки
/// полузаполнены всегда, строгое чтение отвергало файл целиком, и на провод
/// всегда уезжало «только чтение», пока в меню стояло «Полный», — запись
/// молча не давалась, и причину не называл никто. Одна вещь, читающая файл
/// один раз, делает вторую меру невыразимой: читать здесь больше нечем.
///
/// Читается с диска на каждый входящий разговор и на каждый круг звонка, а не
/// берётся снимком при запуске: человек правит карточки и щёлкает потолок в
/// окне, и разговор обязан видеть то, что в файле сейчас. Цена — одно чтение
/// toml на подключение, то есть раз в минуты.
struct Machine {
    /// Карточки этого рабочего места, которые ПРИНИМАЮТ подключения, — или
    /// признание, что настроек мы не прочитали (`enroll::Cards`, там и довод,
    /// почему это тип, а не пустой список).
    cards: enroll::Cards,
    /// Потолок записи — свойство МАШИНЫ (`wire::Ceiling`, контракт: «Чего в
    /// соединении НЕТ»): тот же переключатель, что живёт в меню значка, и он
    /// действует на все карточки разом.
    ceiling: Ceiling,
}

impl Machine {
    fn read(kit: &Kit) -> Machine {
        match crate::secrets::Store::system(kit.state()) {
            Ok(store) => Machine::read_with(kit, &store),
            Err(e) => Machine::silent(format!("Настройки соединений не прочитались: не открылось хранилище паролей: {e}")),
        }
    }

    /// То же, но подложку секретов даёт вызывающий — ей проверяются тесты (тот
    /// же приём и тот же довод, что у `Cfg::load_with`: DPAPI из тестов не
    /// зовём).
    ///
    /// Мера чтения выбирается здесь, одной строкой на обе половины: вернуть
    /// сюда строгое `load_with` — и покраснеет
    /// `the_write_ceiling_is_read_by_the_same_measure_as_the_cards` (в его
    /// файле стоит чужое слово из правки руками, и строгое чтение отвергает
    /// такой файл целиком). Сломанный toml остаётся отказом и здесь:
    /// `load_unchecked` снимает проверку ЗНАЧЕНИЙ, а не проверку читаемости —
    /// заполненности она не снимает уже ни у кого, её с 23.11 не спрашивает и
    /// строгая мера (`cfg::Connection::validate`).
    fn read_with(kit: &Kit, store: &crate::secrets::Store) -> Machine {
        match crate::cfg::Cfg::load_unchecked_with(kit, store) {
            Ok(cfg) => Machine::of(&cfg),
            // Печатается ЦЕПОЧКА (`{e:#}`), а не одно верхнее звено. Верхних
            // звеньев здесь всего два — «не прочитать <путь>» и
            // «1c-connect.toml: ошибка в файле параметров», — и человек,
            // прочитав в журнале окна второе из них, не узнавал НИ ОДНОГО
            // поля: причина лежит ниже, в звене от разбора toml, а `{e}` её
            // отбрасывает. Хвост с ключом toml снимается уже с цепочки
            // (`cfg::said_in_window`): в её последнем звене он бывает —
            // разбор отвечает словами человеку и ключом файлу, — а в окне
            // ключу говорить не о чем.
            Err(e) => Machine::silent(format!("Настройки соединений не прочитались: {}", crate::cfg::said_in_window(&format!("{e:#}")))),
        }
    }

    /// Чистая половина: из УЖЕ прочитанных настроек.
    ///
    /// Потолок машины складывается в поле `write` КАЖДОЙ карточки, а не одной
    /// текущей. Прежде он не складывался вовсе: `allows_write` карточки — её
    /// собственное поле, а потолок машины спрашивался отдельно и только у
    /// текущей, то есть у нетекущей принимающей карточки объявленное на
    /// проводе право записи не знало о потолке ничего. Запрет любой стороны
    /// сильнее разрешения другой (решение владельца 1.11), и сложить их здесь
    /// — единственное место, где это ещё можно сделать до провода.
    ///
    /// **Карточки раскладываются на ТРИ кучи, и выпасть из всех карточка не может.** Прежде отбор принимающих стоял ФИЛЬТРОМ перед
    /// раскладкой, и карточка, переключённая человеком в «Подключаюсь сам» (`role = "dial"`) или в «Всё на одной машине» (`mode =
    /// "local"`), выпадала из обеих куч молча. По её живому коду та сторона слышала «карточку, для которой выдали этот код, на том
    /// компьютере удалили» — третья дорога к той же лжи, которую на этой ветке чинили уже дважды, и корнем снова была не строка, а
    /// потерянная карточка. Третья куча (`Cards::not_accepting`) эту дорогу закрывает: о каждой карточке есть что сказать словами, а
    /// фильтра, который молча теряет, в этом месте больше нет.
    ///
    /// **Вторая куча — по тому, где база.** Прежде отбор
    /// смотрел только на вид соединения и роль, а `base_here` не спрашивал
    /// вовсе — и карточка, у которой базы здесь НЕТ, объявляла себя базой на
    /// проводе: уезжала в `hello_ok` со своими полями (имя базы от пустого
    /// пути, публикация этой машины), зачисляла к себе стороны и обслуживала
    /// их. Человек с базой на той стороне при этом отпечатка не видел и
    /// ничего не разрешал. Это случай второй спеки — база у ЗОВУЩЕЙ стороны,
    /// пара B; путь к нему из окна открыт (меню «База — на той стороне»), и с
    /// задачи 7 он проходится целиком обеими половинами: принимающая кладёт
    /// такие карточки в эту кучу и шлёт `enroll_ok` без полей базы, зовущая
    /// разбирает такой ответ по паре (`enroll::dial_side`), а круг на двух
    /// настоящих узлах сторожит тест
    /// `door::tests::pair_b_completes_without_a_window_and_without_a_second_machine`.
    ///
    /// Отложены, а не выброшены: выброшенная карточка — это код, выданный в
    /// окне по ней, который получает «карточку удалили». Той же ложью, за
    /// которую чинится `Cards::Unreadable`, только другой дорогой. По
    /// отложенным `accept_side` отказывает СВОИМИ словами.
    ///
    /// Спрашивается `base_is_here()`, а не сырой `base_here` (правило cfg.rs,
    /// круг починки 1 задачи 12): застрявшее в файле `base_here = false` у
    /// локальной карточки не вправе решать за человека, у которого
    /// переключателя на экране нет.
    fn of(cfg: &crate::cfg::Cfg) -> Machine {
        // Без сравнения строк: вид потолка в настройках — `read_write` или
        // `read_only`, и одно `== "full"` на этом месте уже стоило продукту
        // всей записи (`access()` такого значения не производит никогда, то
        // есть потолок всегда выходил «только чтение»). Один `bool` от того,
        // кого об этом спрашивают все остальные, разойтись словарём не может.
        let ceiling = if cfg.allows_write() { Ceiling::Full } else { Ceiling::ReadOnly };
        let (mut accepting, mut base_elsewhere, mut not_accepting) = (Vec::new(), Vec::new(), Vec::new());
        for c in &cfg.connections {
            let card = enroll::Card {
                name: c.name.clone(),
                // Где база — то, от чего зависит, может ли эта машина обслуживать по карточке вызовы (`Cards::serving_named`).
                base_here: crate::cfg::Combo::of(c).base_is_here(),
                // Ключ — НАШ (`cfg::CardId`). В проводный вид он переводится только на отправку (`Card::on_wire`).
                id: c.id().clone(),
                base_name: crate::cfg::base_name(&c.base_path).into(),
                // Действующее право, а не своя складка половин: складывать их умеет ровно одна `Cfg::may_write`, и второе место
                // сложения — это второй словарь одного понятия, который однажды разойдётся с первым (на этой ветке так уже было с
                // потолком и с чтением настроек).
                write: cfg.may_write(c),
            };
            // ОДИН разбор на три кучи, и четвёртой дороги — «нигде» — у карточки нет: `else` здесь невыразим, а `push` обязателен в
            // каждой ветке. Спрашивается СОЧЕТАНИЕ (`Combo`) — единственное место, где ответы карточки превращаются в «что это такое»;
            // прежде здесь стояла своя пара условий, то есть ещё один читатель той же оси.
            //
            // Нераспознанная роль — в кучу «не принимает»: кода такой карточке не выдают (окно говорит об этом словами), и в зачисление
            // она не идёт.
            match crate::cfg::Combo::of(c) {
                crate::cfg::Combo::AcceptBaseHere => accepting.push(card),
                crate::cfg::Combo::AcceptBaseThere => base_elsewhere.push(card),
                _ => not_accepting.push(card),
            }
        }
        Machine { cards: enroll::Cards::Read { accepting, base_elsewhere, not_accepting }, ceiling }
    }

    /// Настройки не прочитались вовсе — и так об этом и говорится, своими словами в наш журнал и тремя строками той стороне
    /// (`enroll::Cards::Unreadable`).
    ///
    /// Прежде здесь стоял ПУСТОЙ СПИСОК карточек, и он был неправдой дважды: той стороне уезжало «карточку удалили» про машину, где её не
    /// удаляли, а в наш журнал не ложилось ничего. Причина берётся та, что отдал отказ чтения: по ней видно, сломан ли toml или не открылась
    /// подложка секретов, — и это ровно то, за чем человека просят посмотреть журнал.
    ///
    /// «Только чтение» остаётся верным по своему правилу: по умолчанию инструментов, пишущих в базу, нет (решение владельца 1.11), и
    /// неизвестность не повод выдавать больше, чем разрешено.
    fn silent(why: String) -> Machine {
        Machine { cards: enroll::Cards::Unreadable(why), ceiling: Ceiling::ReadOnly }
    }
}

/// Имена карточек по их ключам — ТОЛЬКО для слов в журнал.
///
/// Зовущие карточки поднимают звонки по файлу партнёров, а там от карточки только ключ — и это верно: имя человек правит когда хочет.
/// Но строка ««Ромашка»: подключено» нужна человеку именем, а не шестнадцатью байтами hex.
///
/// Чтение терпимое (`load_unchecked`) и одним разом на весь подъём звонков: настройки не прочлись — имён просто нет, и звонки от этого
/// не отменяются, допуск дала та сторона, а не наш файл.
fn card_names(kit: &Kit) -> HashMap<CardId, String> {
    crate::cfg::Cfg::load_unchecked(kit).map(|cfg| cfg.connections.iter().map(|c| (c.id(), c.name.clone())).collect()).unwrap_or_default()
}

/// Что ДЕЙСТВУЮЩЕ дано зачисленной стороне — итог с указанием, какая сторона ограничила (спека контракта: «в карточке видно не „мой
/// флажок“, а итог с указанием, какая сторона ограничила — иначе человек чинит не то»).
///
/// Сторон ТРИ, и все три здесь названы. Свои две складывает `Cfg::may_write` — единственное место, где потолок этой машины встречается со
/// словом карточки; третья, потолок ТОЙ машины, приходит одним значением из книги допуска (`peer_write`, он же `enrolled::Party::peer_write`:
/// там сказано, почему чужой потолок хранится, а свои спрашиваются заново).
///
/// Порядок разбора — от того, что человек правит ближе всего к себе, к тому, что он не правит вовсе: машина, карточка, та сторона. Запрет
/// машины сильнее и чинится в другом месте (меню значка), и отправлять человека править карточку, когда закрыта машина, значило бы
/// отправить его не туда; а послать его править чужой компьютер, когда дело в его собственном, — не туда вдвойне.
///
/// **Не за фичей `gui` с задачи 9, и по той же причине, по которой оттуда уехал словарь состояний связи:** зачисленные печатает ещё и
/// набранный `1c-connect peers` (`door::peers_for`), а свёртка трёх мер в одно слово обязана быть одна. Окно зовёт её прежним именем
/// (`gui::panel::access_label`).
pub fn access_label(cfg: &crate::cfg::Cfg, c: &crate::cfg::Connection, peer_write: bool) -> &'static str {
    if cfg.may_write(c) && peer_write {
        "Чтение и запись"
    } else if !cfg.allows_write() {
        "Только чтение: на этом компьютере запись в базу запрещена"
    } else if !c.allows_write() {
        "Только чтение: в этом соединении запись в базу не разрешена"
    } else {
        "Только чтение: на том компьютере запись в базу запрещена"
    }
}

/// Право записи — словами человека, а не флажком.
///
/// «Разрешено только читать» человек может прочитать коллеге по телефону, а
/// `write = false` — не может. Одна вещь на оба конца (зовущий читает это о
/// себе, принимающий — о той стороне): два места со своими словами об одном
/// праве однажды разойдутся, и человек прочтёт в двух строках журнала разное
/// об одном и том же.
pub(crate) fn access_word(write: bool) -> &'static str {
    if write {
        "разрешено читать и записывать"
    } else {
        "разрешено только читать"
    }
}

/// Как эта машина называет себя той стороне. Её слова, не проверенный факт, —
/// и показываются они с этой пометкой (`save::permission_question`).
///
/// Имя компьютера, а не имя карточки: карточка названа человеком по ТОЙ
/// стороне («Ромашка» у разработчика — это заказчик), и прислать его обратно
/// значило бы назваться его же словами о нас. Имя не узналось — пустая
/// строка, и в окне это честное «Себя не назвала».
fn says_name() -> String {
    sysinfo::System::host_name().unwrap_or_default()
}

/// Какую карточку эта зовущая помнит с прошлого раза — признак базы, который
/// та сторона назвала ей в прошлом разговоре.
///
/// Берётся с диска, а не начинается с «не знаю»: перезапуск программы — не
/// повод забыть то, о чём уже договорились. Без этого первый круг после
/// перезапуска шёл бы возвратом БЕЗ имени, та сторона отвечала бы всем списком
/// своих баз, и поток числился бы за всеми ними — то есть отзыв соседней
/// карточки рвал бы и эту связь.
///
/// Отказ чтения — то же «не знаю», и это верно: признак не называется наугад.
/// Старого признака от ДРУГОЙ машины здесь быть не может — `Partners::remember`
/// снимает его сам, когда ключ той стороны сменился.
fn known_card(kit: &Kit, card: &CardId) -> Option<crate::wire::CardRef> {
    Partners::open(kit.state()).ok().and_then(|p| p.base_id_of(card))
}

/// Запоминает, куда карточке возвращаться. Отказ записи — строка в журнал, а
/// не конец подключения: это подключение уже живёт, а потеряно будет лишь
/// возвращение после перезапуска.
fn remember(
    kit: &Kit,
    tx: &UnboundedSender<Out>,
    card: &CardId,
    peer: EndpointId,
    addr: &EndpointAddr,
    agreed: Option<&crate::wire::CardRef>,
) {
    let partner = Partner {
        key: peer,
        relay: addr.relay_urls().next().map(|u| u.to_string()),
        direct: addr.ip_addrs().map(|a| a.to_string()).collect(),
    };
    // Признак базы пишется ВМЕСТЕ с партнёром и в этом порядке: сперва партнёр
    // (он сбрасывает признак, если ключ той стороны сменился), потом признак
    // этого разговора. Обратный порядок стирал бы только что записанное.
    let wrote = Partners::open(kit.state()).and_then(|mut p| {
        p.remember(card, &partner)?;
        match agreed {
            Some(id) => p.remember_base_id(card, id),
            None => Ok(()),
        }
    });
    if let Err(e) = wrote {
        say(tx, common::Event::Warn(format!("Подключение живёт, но запомнить его не удалось: {e}")));
    }
}

/// Что узел знает о себе — плюс своя петля (`ticket::direct_with_loopback`,
/// там и довод, почему петля обязательна).
fn look(node: &Node) -> Reach {
    let addr = node.ticket_parts();
    let seen: Vec<std::net::SocketAddr> = addr.ip_addrs().copied().collect();
    let relay = addr.relay_urls().next().map(|u| u.to_string());
    Reach { relay, direct: crate::ticket::direct_with_loopback(&seen, &node.endpoint().bound_sockets()) }
}

/// Строка в журнал из потока узла — своими словами (`common::Event`), а не готовой строкой: перевод в строку делает тот, кто слушает (у окна это `gui::line_of`), узел его не повторяет вторым переводом.
///
/// Второго словаря здесь больше нет. Прежде узел звал `say` словом окна (`gui::log::Kind`) и переводил его в `common::Event` сам — две меры на один вопрос, главный разряд дефектов этого дерева. Мера осталась одна, и зовущие называют событие прямо.
fn say(tx: &UnboundedSender<Out>, e: common::Event) {
    let _ = tx.unbounded_send(Out::Say(e));
}

/// Новое состояние управляющего потока карточки — в окно. Слово человеку из
/// него делает `gui::link::contract_of`/`contract_word`, здесь только факт.
fn flow(tx: &UnboundedSender<Out>, card: &CardId, now: Option<Flow>) {
    let _ = tx.unbounded_send(Out::Flow(card.clone(), now));
}

