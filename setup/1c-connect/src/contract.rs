//! Контракт соединения: восемь состояний связи, которые перечисляет спека `2026-11-01-connection-contract.md`, и слово для каждого человеку. Не за фичей `gui` — ровно для того и переехал: `status` в командной строке назовёт состояние, не поднимая окна, а экран (`gui::link`) берёт отсюда те же функции реэкспортом, подписи которых не изменились.

use crate::cfg::{self, Connection};
use crate::peer_out::Flow;
use crate::session::State;
use common::kit::Kit;

/// Что про соединение знают книга зачислений (`enrolled::Book`) и список висящих заявок — ровно те четыре факта, из которых получается состояние контракта и число в карточке. Больше ничего из книги экрану не нужно, и целиком её сюда не тащим: решение «какое слово показать» обязано зависеть от четырёх названных признаков, а не от всего, что лежит в файле.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct Enroll {
    /// Заявка пришла, и ответа на неё ещё нет: человек либо не успел ответить, либо закрыл диалог не решив — а это НЕ разрешение и НЕ отказ (`enroll::Decision::NoAnswer`). Заявка остаётся висеть, и правило `list` поднимает её строку первой.
    pub waiting: bool,
    /// Человек отклонил. Исход, а не ошибка (спека зачисления, шаг пятый).
    pub declined: bool,
    /// Код подключения выдан и ещё жив (`panel::enroll_facts` считает его по `Ui::codes` и `Ticket::alive`). Книгу зачислений про это не спрашивают вовсе: она ходит на диск под межпроцессным замком, а признак нужен на каждую отрисовку списка — довод целиком в докстроке `enroll_facts`.
    pub code_issued: bool,
    /// Сколько сторон зачислено к этой карточке. Предела здесь нет вовсе — его назначает лицензия 1С, а не программа (решение владельца 1.11).
    pub enrolled: usize,
    /// Что прямо сейчас с управляющим потоком ЭТОЙ карточки. `None` — потока нет и не затевалось.
    ///
    /// Пятый признак, и без него слова состояния не о чем: прежде карточка читала `ui.link` — состояние ТРАНСПОРТА, один SSH-сеанс на всю машину, — а с приходом канала у каждой карточки своя жизнь: одна подключается, вторая держит поток, третья оборвалась и возвращается. Один признак на машину выдавал бы их все одним словом, то есть врал бы про три карточки из четырёх.
    pub flow: Option<Flow>,
}

/// Состояние контракта — все восемь, как их перечисляет `2026-11-01-connection-contract.md` («Состояние — нет, тикет выдан, ждёт разрешения, разрешено, подключено, разорвано, подключается снова; отдельно — отклонено человеком, это исход, а не ошибка»).
///
/// Свой тип, а не `session::State`: тот про ТРАНСПОРТ (поднят ли поток, рвётся ли он), и половине состояний контракта в нём места нет — «тикет выдан» и «ждёт разрешения» случаются до того, как транспорту есть что поднимать, а «отклонено» — вместо этого. Перечисление закрытое нарочно: `contract_word` разбирает его без `_ =>`, и девятое состояние не соберётся молча без слова человеку.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Contract {
    /// Соединения нет.
    No,
    /// Код выдан, заявки по нему ещё не было.
    CodeIssued,
    /// Заявка пришла и ждёт решения человека.
    Waiting,
    /// Человек разрешил; подключение идёт.
    Allowed,
    Up,
    Broken,
    Retrying,
    /// Человек отклонил.
    Declined,
}

/// Все восемь — для обхода в тестах: перечисление закрытое, и этот список обязан совпасть с ним по длине (`contract_word` не имеет `_ =>`, а забытый в массиве случай поймает тест, сверяющий число).
pub const CONTRACT_STATES: [Contract; 8] = [
    Contract::No,
    Contract::CodeIssued,
    Contract::Waiting,
    Contract::Allowed,
    Contract::Up,
    Contract::Broken,
    Contract::Retrying,
    Contract::Declined,
];

/// Слово состояния человеку. `None` — состояние своей строки в списке не получает вовсе.
///
/// Свёртка — ровно та, которую называет спека экрана (`2026-11-01-interface-design.md`, «Строка на соединение»), и ни одного своего решения здесь нет:
///
/// * «нет» своей строки не имеет вовсе — соединения без строки в списке не бывает, поэтому `None`;
/// * «тикет выдан» показывается тем же словом «ждёт разрешения» до прихода заявки: человек ждёт одного и того же — чтобы с той стороны подключились, — и два слова об одном ожидании он различать не обязан;
/// * «разрешено» — миг между решением человека и «подключено», и отдельного слова не получает: его слово — «подключается», то же, что у `State::Connecting` (круг починки 1 задачи 2, Minor 2: `Connecting` это настоящее движение, которое человек видит прямо сейчас, и у него своё слово рядом с «подключается снова» у `Retrying`).
///
/// **«Ждёт разрешения» снова на экране.** В прошлой ветке слово убрали (живой прогон 9.11, находка владельца) — не потому, что оно неверное, а потому, что его предмета не было в программе: подставляли его под `State::Off`, который означает ровно «обслуживание не поднято». Теперь предмет есть — выданный код и висящая заявка (`Enroll` выше), — и слово вернулось вместе с ним. Правило `list` «ждущие — первой строкой» для этого трогать не пришлось, как и обещала его докстрока.
pub fn contract_word(k: Contract) -> Option<&'static str> {
    match k {
        Contract::No => None,
        Contract::CodeIssued | Contract::Waiting => Some("ждёт разрешения"),
        Contract::Allowed => Some("подключается"),
        Contract::Up => Some("подключено"),
        Contract::Broken => Some("разорвано"),
        Contract::Retrying => Some("подключается снова"),
        Contract::Declined => Some("отклонено"),
    }
}

/// Какое состояние контракта у соединения прямо сейчас. `None` — ни одного: обслуживание просто не поднято, и это не состояние контракта, а отсутствие движения (слово для него — «не подключено», его ставит `row`).
///
/// Порядок разбора — по тому, что человеку важнее узнать:
///
/// 1. висящая заявка важнее всего остального: от неё ждут ДЕЙСТВИЯ человека, и она перебивает даже «отклонено» — если после отказа пришла новая заявка, на экране должна стоять она, а не прошлый исход;
/// 2. «отклонено» — исход, и он держится, пока его не сменит новая заявка или живая связь;
/// 3. транспорт — то, что видно прямо сейчас;
/// 4. выданный код — ожидание, когда на проводе ещё ничего не происходит.
///
/// `Enroll::enrolled` здесь не читается нарочно: зачисленная, но сейчас не подключённая сторона — это «не подключено», а не «разрешено». «Разрешено» по спеке миг, и выдавать его словом «подключается» там, где ничего не подключается, значило бы обещать движение, которого нет. Число зачисленных живёт в карточке (`panel::accepting_block`), а не в слове.
///
/// **Поток карточки стоит ВЫШЕ транспорта** (`Enroll::flow`), и это не вкус: транспорт — один SSH-сеанс на машину, прежняя половина продукта, и он ничего не знает о том, держится ли канал ЭТОЙ карточки. Там, где поток есть, он и есть правда о связи; там, где его нет, слово по-прежнему берёт транспорт — он отвечает за сегодняшнюю работу и живёт параллельно.
pub fn contract_of(l: Option<&State>, e: &Enroll) -> Option<Contract> {
    if e.waiting {
        return Some(Contract::Waiting);
    }
    if e.declined {
        return Some(Contract::Declined);
    }
    match e.flow {
        Some(Flow::Calling) => return Some(Contract::Allowed),
        Some(Flow::Up) => return Some(Contract::Up),
        Some(Flow::Broken) => return Some(Contract::Broken),
        Some(Flow::Retrying) => return Some(Contract::Retrying),
        None => {}
    }
    match l {
        Some(State::Up { .. }) => Some(Contract::Up),
        Some(State::Connecting) => Some(Contract::Allowed),
        Some(State::Retrying(_)) => Some(Contract::Retrying),
        Some(State::Failed(_)) => Some(Contract::Broken),
        Some(State::Off) | None => e.code_issued.then_some(Contract::CodeIssued),
    }
}

/// Карточка ЖДЁТ входящих — по роли и по виду соединения, про базу не спрашивая. Это вопрос про то, рисовать ли ей блок кода и подпись «Принимаю подключения», а не про то, состоится ли подключение: роль человек выбрал, и карточка обязана говорить о себе тем, чем он её назвал.
pub fn waits_for_incoming(c: &Connection) -> bool {
    cfg::Combo::of(c).waits_for_incoming()
}

/// Ждёт ли карточка, чтобы с той стороны подключились, — по СОСТОЯНИЮ, а не по показанному слову.
///
/// Это правило `list` «ждущий — первой строкой», и считается оно здесь затем, чтобы `list` не сравнивала показанную строку с литералом «ждёт разрешения»: правка формулировки молча выключила бы правило, и карточка с просто выданным кодом сутками стояла бы выше всех подписей (находка повторного ревью всей ветки). Слово — дело `contract_word`, место строки — дело состояния контракта.
pub fn waits_for_answer(c: &Connection, l: Option<&State>, e: &Enroll) -> bool {
    c.mode != "local" && matches!(contract_of(l, e), Some(Contract::CodeIssued | Contract::Waiting))
}

/// Автоподключение при запуске: ключ состояния комплекта `autoconnect`, нет записи — выключено.
pub fn autoconnect(kit: &Kit) -> bool {
    kit.state_get("autoconnect").as_deref() == Some("1")
}

/// Экран показывает «MCP выключены», пока снят флаг обслуживания, даже если сеанс ещё договаривает своё в потоке: подменяем `Connecting`/`Up` на `Off`. Отказ (`Failed`) виден всегда — о нём человек обязан узнать.
///
/// С 26.10 выключение в локальном режиме ОТПУСКАЕТ слушатели (выключено значит выключено), так что расхождение показанного с настоящим здесь короткое — только пока останавливается поток сеанса.
pub fn local_display(mode: &str, enabled: bool, l: State) -> State {
    if mode == "local" && !enabled {
        match l {
            State::Up { .. } | State::Connecting => State::Off,
            other => other,
        }
    } else {
        l
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::time::Instant;

    /// Слова о состоянии связи складывает бек: `status` в командной строке назовёт их, не поднимая окна.
    #[test]
    fn the_words_for_a_connection_state_are_the_backs_own() {
        assert_eq!(contract_word(Contract::Up), Some("подключено"));
        assert_eq!(CONTRACT_STATES.len(), 8);
        // восемь состояний разбираются без `_ =>`: девятое не соберётся молча
    }

    /// Спека контракта перечисляет восемь состояний (`2026-11-01-connection-contract.md`), и у каждого обязано быть решение, какое слово человек увидит. «Своё слово» здесь значит «решённое», а не «ни с кем не общее»: спека экрана (`2026-11-01-interface-design.md`, «Строка на соединение») сама называет три свёртки, и этот тест их и прибивает — иначе любая из них однажды «починится» в сторону восьми разных слов, которых спека не просила.
    ///
    /// Падал он так: до правки `contract_word` не существовало вовсе, а `row` отдавала «не подключено» на всё, кроме четырёх состояний транспорта — «ждёт разрешения» и «отклонено» на экране не было ни одного.
    #[test]
    fn every_contract_state_has_its_own_word() {
        let expect = [
            // «Нет» своей строки не имеет вовсе: соединения без строки в списке
            // не бывает, и слову этому негде показаться.
            (Contract::No, None),
            // «Тикет выдан» и «ждёт разрешения» — одно ожидание для человека.
            (Contract::CodeIssued, Some("ждёт разрешения")),
            (Contract::Waiting, Some("ждёт разрешения")),
            // «Разрешено» — миг между решением и «подключено», своего слова не
            // получает: его слово то же, что у начавшегося подключения.
            (Contract::Allowed, Some("подключается")),
            (Contract::Up, Some("подключено")),
            (Contract::Broken, Some("разорвано")),
            (Contract::Retrying, Some("подключается снова")),
            (Contract::Declined, Some("отклонено")),
        ];
        assert_eq!(expect.len(), CONTRACT_STATES.len(), "в таблице обязаны стоять все состояния контракта, а не часть");
        for (state, word) in expect {
            assert_eq!(contract_word(state), word, "{state:?}");
        }
        // Свёрток ровно три, и больше их быть не должно: четвёртая — это уже
        // два состояния, которые человек не может различить, не спросив.
        let mut words: Vec<&str> = CONTRACT_STATES.iter().filter_map(|k| contract_word(*k)).collect();
        words.sort_unstable();
        words.dedup();
        assert_eq!(words.len(), 6, "восемь состояний, три свёртки — шесть слов: {words:?}");
    }

    /// Зачисление само по себе не состояние контракта: `contract_of` про него ничего не знает, число зачисленных живёт в карточке, а не в словаре состояний. Половина с тем же `Enroll`, что говорит про строку списка слово «не подключено», — у `row` (`gui::link`).
    #[test]
    fn being_enrolled_is_not_a_contract_state() {
        let enrolled = Enroll { enrolled: 3, ..Default::default() };
        assert_eq!(contract_of(None, &enrolled), None, "зачисление само по себе не состояние контракта");
    }

    /// Комплект для теста `autoconnect`: каталог во временной папке, имя плюс pid процесса — тем же приёмом, что `cfg::tests::tmp`, без внешнего крейта `tempfile`.
    fn kit_for_test() -> Kit {
        let d = std::env::temp_dir().join(format!("onec-connect-contract-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        Kit::at(d)
    }

    #[test]
    fn autoconnect_reads_the_kit_state_with_no_record_meaning_off() {
        let kit = kit_for_test();
        assert!(!autoconnect(&kit));
        kit.state_set("autoconnect", "1").unwrap();
        assert!(autoconnect(&kit));
        kit.state_set("autoconnect", "0").unwrap();
        assert!(!autoconnect(&kit));
    }

    /// Живой прогон 9.11: `State::Off` значит «обслуживание не поднято», и локальному режиму с 26.10 выключение ОТПУСКАЕТ слушатели — экран подменяет показанное на `Off`, а отказ (`Failed`) виден всегда, его прятать нечем.
    #[test]
    fn local_mode_hides_up_behind_the_flag_but_shows_a_failure_regardless() {
        let now = Instant::now();
        assert_eq!(local_display("local", false, State::Up { since: now }), State::Off);
        assert_eq!(local_display("local", false, State::Connecting), State::Off);
        assert_eq!(local_display("local", true, State::Up { since: now }), State::Up { since: now });
        let failed = State::Failed("порт занят".into());
        assert_eq!(local_display("local", false, failed.clone()), failed);
        // Туннельный режим — состояние сеанса идёт как есть, флаг тут ни при чём.
        assert_eq!(local_display("tunnel", false, State::Up { since: now }), State::Up { since: now });
    }
}
