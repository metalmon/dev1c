    /// давали ОДИН ключ, одна учётная запись запирала другую, а человек
    /// читал «уже запущен» и шёл искать свой процесс, которого нет.
    #[test]
    fn two_accounts_that_differ_at_all_never_share_a_lock() {
        assert_ne!(crate::door::door_name("Пользователь 1"), crate::door::door_name("Пользователь_1"));
        assert_ne!(crate::door::door_name("S-1-5-21-1-2-3-1001"), crate::door::door_name("S-1-5-21-1-2-3-1002"));
        assert_eq!(crate::door::door_name("1000"), crate::door::door_name("1000"), "та же учётка — та же дверь");
    }

