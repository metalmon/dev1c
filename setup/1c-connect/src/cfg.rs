    /// Important 5 ревью задачи 7: `passwords_match` сравнивает расшифрованное с расшифрованным, и патч, который подставляет сам пароль ОТКРЫТЫМ ТЕКСТОМ (без префикса `enc1:`), эту проверку проходит — `Store::open` отдаёт значение без префикса как есть, и обе стороны читают одну и ту же строку. Подложка нужна самая обычная, лгущая заглушка не нужна: хватает патча с неверным (не запечатанным) литералом. Без добавленной проверки текста на диске (`sealed_or_empty`) этот тест не падает — падает он именно её удалением.
    #[test]
    fn write_checked_refuses_a_patch_that_writes_the_password_as_plain_text() {
        let s = secrets::Store::file(&tmp("plain-patch"));
        let kit = kit_with("");
        let mut c = filled();
        c.host.password = "дев1".into();
        // Литерал toml, тот же пароль, но без префикса `enc1:` — ровно то, что когда-либо вернул бы чужой код, перепутавший пароль с его шифртекстом.
        let literal = format!("{:?}", c.host.password);
        let err = cfg::write_checked(&kit, &c, &s, &[("password", &literal)]).unwrap_err();
        assert!(err.contains("не зашифрован") || err.contains(secrets::PREFIX), "{err}");
        // Файл всё равно написан (запись печатает раньше, чем отказывает проверка) — но без префикса, и дальше по нему никто не поедет молча.
        let text = std::fs::read_to_string(kit.state_path(cfg::FILE)).unwrap();
        assert!(text.contains("password = \"дев1\""), "{text}");
    }

    /// `sealed_or_empty` сама по себе: пусто и честный шифртекст проходят, открытый текст и битый toml — отказ.
    #[test]
    fn sealed_or_empty_accepts_blank_and_prefixed_and_rejects_plain_text() {
        assert!(sealed_or_empty("[host]\npassword = \"\"\n", "password").is_ok());
        assert!(sealed_or_empty(&format!("[host]\npassword = \"{}deadbeef\"\n", secrets::PREFIX), "password").is_ok());
        assert!(sealed_or_empty("[host]\npassword = \"открытый\"\n", "password").is_err());
    }

    /// `write_checked` не обязан молчать, если запись самого файла не
    /// удалась (здесь — каталог состояния без прав на запись): отказ
    /// обязан дойти до вызывающего словами, а не потеряться на пути.
    #[cfg(unix)]
    #[test]
    fn write_checked_refuses_when_the_file_cannot_be_written() {
        if unsafe { libc::geteuid() } == 0 {
            return;
        }
        use std::os::unix::fs::PermissionsExt;
        let s = secrets::Store::file(&tmp("readback-writefail"));
        let kit = kit_with("");
        // Права снимаем с САМОГО ФАЙЛА, а не с каталога: существующий файл
        // перезаписывается по правам файла, и каталог без `w` этого не
        // запрещает — прежняя фикстура (0o500 на каталоге) отказа не
        // добивалась и тест проходил зелёным мимо своего смысла. Увидеть это
        // было негде: тест `#[cfg(unix)]`, на Windows не компилируется.
        let file = kit.state_path(cfg::FILE);
        std::fs::set_permissions(&file, std::fs::Permissions::from_mode(0o400)).unwrap();
        let mut c = filled();
        c.host.password = "секрет".into();
        let e = cfg::write_checked(&kit, &c, &s, &[]);
        std::fs::set_permissions(&file, std::fs::Permissions::from_mode(0o600)).unwrap();
        let e = e.unwrap_err();
        assert!(e.contains(cfg::FILE), "{e}");
    }

    /// Пустой пароль — не повод `load` отказывать: `seal`/`open` пропускают
    /// пустую строку как есть на любой подложке, и в `undecryptable` она не
    /// попадает (ревью задачи 2, Minor 4).
    #[test]
    fn an_empty_password_does_not_refuse_load() {
        let s = secrets::Store::file(&tmp("empty-pwd-load"));
        let mut c = filled();
        c.host.password = String::new();
        let kit = kit_with(&c.render(&s).unwrap());
        let loaded = Cfg::load_with(&kit, &s).unwrap();
        assert!(loaded.undecryptable.is_empty());
        assert_eq!(loaded.host.password, "");
    }

    /// Прежний файл с одной секцией `[host]` — законный вид настроек, не
    /// устаревший: так выглядят все уехавшие комплекты, включая эталонный.
    /// Список соединений обязан прочитать его как ОДНО соединение, а не
    /// отказать и не отдать пустой список.
    #[test]
    fn an_old_file_with_one_host_section_reads_as_one_connection() {
        let kit = kit_with("[host]\nbase_path = \"C:\\\\Bases\\\\Buh\"\ndb_user = \"mcp\"\n");
        let c = Cfg::load_unchecked(&kit).unwrap();
        assert_eq!(c.connections.len(), 1, "прежний файл — это одно соединение, а не ноль");
        assert_eq!(c.connections[0].name, "Buh", "имя берётся из базы: в прежнем файле его негде взять");
        assert_eq!(c.current, "Buh", "единственное соединение и есть текущее");
        assert!(c.connections[0].base_here, "у прежнего файла база здесь");
    }

    /// Свежий комплект без единой настройки — пустой список, не отказ; а
    /// `current`, называющий соединение, которого нет среди блоков, — отказ
    /// словами с именем, которое не нашлось (человек правил файл руками и
    /// должен узнать, что опечатался, а не получить тихий выбор первого).
    #[test]
    fn an_empty_file_is_an_empty_list_and_a_missing_current_is_a_refusal() {
        let empty = Cfg::load_unchecked(&kit_with("")).unwrap();
        assert!(empty.connections.is_empty(), "свежий комплект — пустой список, не отказ");
        assert_eq!(empty.current, "", "текущего нет, пока нет ни одного соединения");

        let e = Cfg::load_unchecked(&kit_with("current = \"Ромашка\"\n\n[[connection]]\nname = \"Buh\"\n")).unwrap_err();
        assert!(format!("{e:#}").contains("Ромашка"), "отказ называет имя, которого нет: {e:#}");
    }
