//! `host.publication`: коннектор поднимает HTTP-сервис базы сам — своим
//! httpd под пользователем, без Конфигуратора и без прав администратора (см.
//! design «HTTP-сервис базы ведёт коннектор — на обеих ОС»).
//!
//! Атрибуты `default.vrd` ниже обязательны, а не стиль: без них HTTP-сервис
//! держит сеанс между вызовами агента, а учебная лицензия даёт один сеанс
//! «Предприятия» на базу — второй вызов подряд возвращает HTTP 500. Их
//! принимает только элемент `service`; на контейнере платформа отвергает весь
//! файл («Ошибка при разборе»).

use crate::cfg::Cfg;
use crate::holder;
#[cfg(windows)]
use crate::job;
use crate::ops_host;
use common::kit::Kit;
use std::path::{Path, PathBuf};
#[cfg(windows)]
use std::sync::Mutex;

/// Имя HTTP-сервиса и его путь внутри публикации — то же, что ставит
/// расширение (`host.extension`).
const SERVICE_ROOT_URL: &str = "mcp-1c";

/// Экранирует пять спецсимволов XML. Путь базы идёт в атрибут `ib` как
/// есть — кавычка или амперсанд в пути иначе рвут XML, платформа отвергает
/// весь файл, а причина оседает в журнале веб-сервера, не в журнале
/// коннектора: агент просто не видит адреса.
fn xml_escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&apos;"),
            _ => out.push(c),
        }
    }
    out
}

/// Строка подключения к базе внутри дескриптора: файловая — `File="путь"`,
/// клиент-серверная — `Srvr="сервер";Ref="база"` (`cfg::is_server_base`).
///
/// Прежде писалась ТОЛЬКО файловая форма, и клиент-серверной базе доставался
/// `File="сервер\база"`, которого платформа не открывает: человек заполнял
/// поле, параметры его принимали (`validate` такую базу пропускает, а
/// существование каталога для неё намеренно не проверяется), и публикация
/// молча не работала (находка владельца 26.10).
fn ib_connection(cfg: &Cfg) -> String {
    let base = &cfg.host.base_path;
    if crate::cfg::is_server_base(base) {
        let (srvr, rf) = base.split_once('\\').unwrap_or((base.as_str(), ""));
        return format!("Srvr=&quot;{}&quot;;Ref=&quot;{}&quot;;", xml_escape(srvr), xml_escape(rf));
    }
    format!("File=&quot;{}&quot;;", xml_escape(base))
}

/// Текст `default.vrd`: публикация в корень своего порта (`base="/"`, у
/// каждого рабочего места свой порт — корень свободен). Без `Usr`/`Pwd`
/// нарочно, а не по забывчивости (замер 29.10, спека «Пароля в дескрипторе
/// публикации не должно быть вовсе»): с этими атрибутами вызов сервиса БЕЗ
/// всяких учётных данных отвечал `200` — платформа открывала сеанс под
/// записанным пользователем всякому, кто дотянулся до порта. `Usr`/`Pwd`
/// нужны только для анонимного входа; платформа по умолчанию берёт
/// пользователя из самого запроса (Basic-аутентификация), и ровно так
/// ходит каждый наш потребитель (`mcp-1c`, vrunner) — без них тот же вызов
/// без учётных данных отвечает `401`, с верным паролем — `200`. Этот текст
/// никогда не печатается в журнал — только пишется в файл.
pub fn vrd(cfg: &Cfg) -> String {
    format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n\
<point xmlns=\"http://v8.1c.ru/8.2/virtual-resource-system\"\n\
\t\tbase=\"/\" ib=\"{ib}\"\n\
\t\tenable=\"true\">\n\
\t<httpServices publishByDefault=\"true\" publishExtensionsByDefault=\"true\">\n\
\t\t<service name=\"MCPService\" rootUrl=\"{root}\" enable=\"true\"\n\
\t\t\t\treuseSessions=\"dontuse\" sessionMaxAge=\"1\" poolSize=\"1\" poolTimeout=\"1\"/>\n\
\t</httpServices>\n\
</point>\n",
        ib = ib_connection(cfg),
        root = SERVICE_ROOT_URL,
    )
}

/// Убрать свой дескриптор. Зовётся при уходе в чужую публикацию: `stop`
/// гасит только процесс, а `default.vrd` остаётся лежать — вход в него
/// проверяется паролем базы (с задачи 6 анонимного входа у него больше нет),
/// но сам HTTP-сервис на машине, где базу публикует кто-то другой, —
/// лишняя дверь, о которой администратор не знает. Отсутствие файла —
/// успех: уходить уже не из чего.
pub fn remove_descriptor(pub_dir: &Path) -> std::io::Result<()> {
    match std::fs::remove_file(pub_dir.join("default.vrd")) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
        other => other,
    }
}

/// Дескриптор на диске — ровно то, что `vrd(cfg)` написал бы сейчас. Иначе
/// база поменялась (человек нажал «Сохранить»), а HTTP-сервис всё ещё держит
/// старый текст — `state()` обязан увидеть это как расхождение, а не читать
/// совпадение порта за «сделано». Пароль и логин больше не входят в
/// сравнение — их с задачи 6 в дескрипторе нет вовсе, менять их незачем.
pub fn descriptor_matches(pub_dir: &Path, cfg: &Cfg) -> bool {
    std::fs::read_to_string(pub_dir.join("default.vrd")).map(|on_disk| on_disk == vrd(cfg)).unwrap_or(false)
}

/// `GET <base_url>/version` отвечает HTTP (любым статусом) — отличает наш
/// httpd (платформа ответит под опубликованным сервисом, даже пока
/// расширение ещё не поставлено) от чужой программы на том же порту, которая
/// на HTTP не похожа вовсе (reqwest не сможет разобрать ответ как HTTP и
/// вернёт ошибку). Не доказательство владения портом абсолютно во всех
/// случаях (можно представить чужой HTTP-сервер на том же порту), но вместе с
/// `descriptor_matches` — наша конфигурация плюс наш порт — этого достаточно.
///
/// **Голос к базе берётся и здесь** (`ops_host::base_voice`, Important 2
/// финального ревью ветки): это второй из двух запросов, что правда уходят в
/// базу, и он шёл мимо голоса. Окно приходит сюда через
/// `ensure_publication_now` одновременно с группой «база» в `verify::gather` —
/// учебная платформа с единственным сеансом давала на это ложный отказ по
/// числу сеансов, и человек видел «Занято», которого нет. Голос — на сам
/// запрос (клиент собирается до того, как его брать), как в `extension_reach`.
pub fn service_responds(base_url: &str) -> bool {
    let Ok(c) = reqwest::blocking::Client::builder().timeout(std::time::Duration::from_secs(3)).build() else { return false };
    let _voice = crate::ops_host::base_voice();
    c.get(format!("{base_url}/version")).send().is_ok()
}

/// Готовит каталог публикации и пишет в него `default.vrd` с правами только
/// для владельца (Unix) — не потому, что там пароль (с задачи 6 его там нет
/// вовсе), а потому, что путь к базе и состав публикации — чужое дело: на
/// образе три рабочих места (`dev1`/`dev2`/`dev3`) делят диск под разными
/// пользователями, и без ограничения `dev1` читал бы, какую базу и как
/// публикует `dev2`, прямо из `/home/dev2/dev1c/pub/default.vrd`. На Windows
/// ограничивать нечего: каталог живёт под `%LOCALAPPDATA%`, у него уже свой
/// ACL на пользователя — отдельной ветки для Windows здесь нет и не нужно.
pub fn write_vrd(pub_dir: &Path, text: &str) -> Result<(), String> {
    ensure_pub_dir(pub_dir)?;
    common::fsperm::write_owner_only(&pub_dir.join("default.vrd"), text)
}

// `tighten_dir` — без cfg: на Unix она действует, на прочих платформах не
// делает ничего (там каталог уже под ACL пользователя). `mode()` при
// создании действует только на вновь созданные каталоги; если каталог
// остался с прошлого запуска (или с версии до этого фикса) с более широкими
// правами — поджимаем явно, а не оставляем как есть.
fn ensure_pub_dir(dir: &Path) -> Result<(), String> {
    common::fsperm::ensure_private_dir(dir)?;
    common::fsperm::tighten_dir(dir)
}

/// Пути одной публикации: свой httpd (Windows) или системный apache2
/// (образ), свой каталог публикации (`pub_dir` — никогда каталог базы: он
/// может быть только для чтения или на сетевом диске) и журнал/pid рядом.
#[derive(Debug, Clone, PartialEq)]
pub struct Paths {
    /// `ServerRoot`: откуда резолвятся относительные `modules/mod_*.so` и
    /// `conf/mime.types`.
    pub root: PathBuf,
    /// `DocumentRoot` и каталог `default.vrd` — свой, не каталог базы.
    pub pub_dir: PathBuf,
    pub conf: PathBuf,
    pub pid: PathBuf,
    pub log: PathBuf,
    /// Модуль платформы (`_1cws_module`): `wsap24.dll`/`wsap24t.dll` рядом с
    /// `1cv8.exe` на Windows, `wsap24t.so` в образе.
    pub module: PathBuf,
    pub port: u16,
}

/// Модуль платформы рядом с исполняемым файлом 1cv8: `wsap24.dll` у
/// коммерческой сборки, `wsap24t.dll` — у учебной (Windows), `wsap24t.so` — в
/// образе. Чистая функция — каталог называет вызывающий, тест подаёт
/// временный, настоящий 1cv8 искать не нужно.
pub(crate) fn module_in(bin: &Path) -> Result<PathBuf, String> {
    let names: &[&str] = if cfg!(windows) { &["wsap24.dll", "wsap24t.dll"] } else { &["wsap24.so", "wsap24t.so"] };
    names
        .iter()
        .map(|n| bin.join(n))
        .find(|p| p.exists())
        .ok_or_else(|| format!("рядом с платформой в {} нет модуля веб-сервера 1С ({})", bin.display(), names.join("/")))
}

/// Пути, зависящие только от каталога состояния коннектора (`state`) — не от
/// настоящей платформы 1С: вынесены отдельно, чтобы тест считал их с
/// временным каталогом, а не с настоящим `%LOCALAPPDATA%`/`$HOME`.
fn paths_under(state: &Path, root: PathBuf, module: PathBuf, port: u16) -> Paths {
    Paths { root, pub_dir: state.join("pub"), conf: state.join("httpd.conf"), pid: pid_file_in(state), log: state.join("httpd.log"), module, port }
}

/// Путь к pid-файлу нашего httpd — одна формула на троих: дескриптор
/// (`paths_under` выше), проба занятости (`busy_for_choice`) и страж
/// (`guard_own_listener`). Двум последним `Paths` целиком не нужна, и это
/// не мелочь: от ПОРТА этот путь не зависит, значит и страж, и проба строят
/// его, не запуская подбор порта (находка 4 ревью круга 3 — проверка не
/// имеет права переизбирать порт, см. `guard_own_listener`).
pub(crate) fn pid_file_in(state: &Path) -> PathBuf {
    state.join("httpd.pid")
}

/// Две основы публикации, и путать их нельзя: откуда httpd ЗАПУСКАЕТСЯ и куда
/// публикация ПИШЕТ.
///
/// Запускается — из комплекта (`<комплект>/httpd` на Windows, системный
/// apache2 в образе): инструменты работают с места, в профиль не переносится
/// ничего (леджер комплекта, пункт 15). Пишет — только в состояние
/// пользователя, и это не вкусовщина: в `default.vrd` лежит путь к базе и
/// состав публикации (`vrd` выше, пишется «только владельцу») — не секрет
/// с задачи 6 (пароля там больше нет), но и не чужое дело. В комплекте ему
/// нельзя по двум причинам сразу — комплект переезжает на флешке и в общей
/// папке, а в стенде он один на три рабочих места и только для чтения, так
/// что запись туда либо не удастся, либо покажет путь и состав публикации
/// одного человека всем трём.
///
/// Чистая функция ровно затем, чтобы это держал тест: `Paths::of` ниже
/// проверить нечем — ему нужна настоящая платформа на диске.
pub(crate) fn bases(kit_root: &Path, state: &Path) -> (PathBuf, PathBuf) {
    let server = if cfg!(windows) { kit_root.join("httpd") } else { PathBuf::from("/etc/apache2") };
    (server, state.to_path_buf())
}

/// Httpd комплекта — одна функция на всех, кто про него спрашивает: и
/// проверка полноты комплекта (`ops_host::kit_files`), и `Paths::of` ниже.
/// Прежде каждый спрашивал по-своему, и полнота комплекта проверялась тремя
/// разными способами (вопрос владельца 30.10).
pub(crate) fn kit_httpd_exe(kit_root: &Path) -> PathBuf {
    kit_root.join("httpd").join("bin").join("httpd.exe")
}

/// Порт, который и правда идёт в дескриптор публикации (`Paths::port`, он же
/// `Listen` в `httpd.conf`) — выбранный в этом сеансе (`ports::choose`), не
/// `cfg.http_port()` как есть: тот остаётся умолчанием ПЕРВОЙ попытки
/// подбора, а не окончательным ответом (план «тонкий срез ценности», задача
/// 1). Подбирается ровно он один — порты моста этот сеанс не трогает (см.
/// докстроку `ports::Chosen`).
///
/// Проба занятости для подбора идёт отсюда, а не из `ports.rs`: знание «этот
/// порт держит НАШ httpd» живёт здесь, рядом с pid-файлом, — `ports.rs`
/// остаётся чистым, проба у него параметр (находка 2 ревью круга 3, решение
/// ведущего).
///
/// Чистая по каталогу состояния (параметр, не `ops_host::state_dir()` сама
/// по себе) — тем же приёмом, что `paths_under`: тест подаёт временный
/// каталог, не настоящий `%LOCALAPPDATA%`.
///
/// `pub(crate)` и одна на двоих с `ops_host::settle_chosen_http_port_in`
/// нарочно: `base_url()` и `Listen` в `httpd.conf` обязаны назвать ОДИН
/// номер, а два вызова `ports::choose` с разными пробами — это ровно тот
/// способ их развести, от которого в круге 2 пришлось ставить барьер.
pub(crate) fn resolve_http_port(state: &Path, cfg: &Cfg, ours: &OurHttpd) -> Result<u16, String> {
    Ok(crate::ports::choose(state, cfg.first_attempt_ports(), &|p| busy_for_choice(state, p, ours))?.http)
}

/// Что значит «наш httpd» — ожидаемая личность процесса-держателя порта,
/// одним значением на всех, кто спрашивает (страж, проба подбора,
/// улаживание порта). Два признака, и оба нужны:
///
/// - `image` — путь образа. Говорит «это наш бинарь».
/// - `owner` — владелец процесса. Говорит «это НАШ процесс», и это главный
///   барьер: комплект лежит в корне диска, обычные права дают соседу по
///   терминальному серверу выполнить наш `httpd.exe` со своим конфигом —
///   образ тогда совпадает идеально. Запустить его от нашего имени сосед не
///   может (решение ведущего, круг 5 исправления).
///
/// `owner` — `Option`, потому что добыть его может не выйти; `None` здесь
/// значит «не удалось установить», и страж на этом ЗАКРЫВАЕТСЯ отдельным
/// текстом, а не пропускает.
#[derive(Debug, Clone)]
pub struct OurHttpd {
    pub image: PathBuf,
    pub owner: Option<String>,
}

impl OurHttpd {
    /// Ожидаемая личность на этой машине: образ — из комплекта (см.
    /// `our_httpd_image`), владелец — текущий пользователь. Зовётся в бою;
    /// тест строит `OurHttpd` литералом, подставляя своё.
    pub(crate) fn of(kit_root: &Path) -> OurHttpd {
        OurHttpd { image: our_httpd_image(kit_root), owner: holder::current_owner() }
    }
}

/// Образ, который обязан быть у НАШЕГО httpd на этой платформе: на Windows —
/// httpd из комплекта (оттуда он и запускается, `start`), в образе —
/// системный `apache2` (его зовёт Linux-ветка `start`).
pub(crate) fn our_httpd_image(kit_root: &Path) -> PathBuf {
    #[cfg(windows)]
    {
        kit_httpd_exe(kit_root)
    }
    #[cfg(not(windows))]
    {
        let _ = kit_root;
        apache2_on_path().unwrap_or_else(|| PathBuf::from("/usr/sbin/apache2"))
    }
}

/// «Занят» для подбора — занят КЕМ-ТО ДРУГИМ. Порт, который слушает наш
/// собственный httpd (pid из `<состояние>/httpd.pid` совпал с держателем
/// слушающего сокета, `holder::listener_pid`), считается СВОБОДНЫМ: это тот
/// самый порт, который мы и хотим, а не повод уезжать на соседний.
///
/// Без этого различия апгрейд живой установки уезжал с собственного порта
/// (находка 2 ревью): `ports.state` у неё либо нет, либо он прежнего
/// формата, подбор идёт заново, `bind` на 8081 не удаётся — потому что там
/// НАШ httpd, — и `base_url()` после этого называет 8082, где не слушает
/// никто. И это не теория: публикация поднимается `Lifetime::Detached`, без
/// `Job` и без отслеживания, а `httpd -k stop` на запущенном из консоли
/// экземпляре ищет службу `Apache2.4` и не делает ничего (замер ведущего,
/// 2.11.2026) — переживший сеанс httpd на своём порту возможен.
///
/// «Наш держатель» здесь — ровно тот же вопрос, на который отвечает страж, и
/// отвечает на него ОН ЖЕ, одной реализацией: номер из pid-файла, личность
/// процесса по образу (находка автоматической проверки безопасности по кругу
/// 4 — номер подделывается переиспользованием pid, образ нет) и держатель
/// слушающего сокета. Своя копия этого правила разошлась бы с ним при первой
/// же правке, а разойтись им нельзя: подбор решает, на каком порту поднимать
/// httpd, страж — туда ли уходит пароль.
///
/// `.is_err()` здесь не теряет причину (в отличие от находки 3 ревью): проба
/// занятости по природе отвечает «да/нет», ей некому сказать слова, а тот же
/// отказ с теми же числами человек увидит от стража на той же дороге.
fn busy_for_choice(state: &Path, port: u16, ours: &OurHttpd) -> bool {
    crate::ports::port_is_busy(port) && refuse_unless_ours(&pid_file_in(state), port, ours).is_err()
}

impl Paths {
    /// Пути публикации на этой машине: `ServerRoot` — свой httpd из комплекта
    /// (`<комплект>/httpd`, запускается оттуда, где лежит) на Windows,
    /// системный apache2 в образе — то, что уже делает стенд. Всё, что
    /// публикация пишет, — в состоянии пользователя; почему именно так,
    /// сказано у `bases`.
    ///
    /// Круг 4 задачи 5, пункт 3 (решение владельца процесса): отказ словами,
    /// если переменной среды для каталога состояния нет. `state_dir()` эта
    /// функция зовёт САМА, мимо `kit.state()`, а в каталог состояния уезжает
    /// `.vrd`, где строка соединения с базой может нести учётные данные —
    /// место для неё тоже не угадывают. Текст причины общий с `ensure_state`.
    ///
    /// Порт — не `cfg.http_port()` напрямую, а `resolve_http_port` выше:
    /// `cfg::derived_http_port()` — константа с задачи 6 плана «тонкий срез
    /// ценности» (до неё — формула от номера рабочего места, а на пустом
    /// имени, `cfg::number_of` → `None` → `unwrap_or(1)`, тот же результат),
    /// и без подбора вторая бухгалтерка на том же терминальном сервере
    /// садилась бы на тот же порт и не стартовала бы вовсе — ровно это и
    /// чинит подбор.
    pub fn of(cfg: &Cfg, kit: &Kit) -> Result<Paths, String> {
        ops_host::refuse_guessed_state_dir()?;
        let (root, state) = bases(&kit.root, &ops_host::state_dir());
        if cfg!(windows) && !kit_httpd_exe(&kit.root).exists() {
            return Err(format!(
                "в {} нет bin/httpd.exe — скопируйте полный комплект заново (комплект: {})",
                root.display(),
                kit.root.display()
            ));
        }
        let exe = ops_host::find_1cv8(cfg)
            .ok_or_else(|| "платформа 1С не найдена — установите её или укажите переменную ONEC_PLATFORM".to_string())?;
        let bin = exe.parent().ok_or_else(|| format!("у {} нет каталога", exe.display()))?;
        let module = module_in(bin)?;
        let port = resolve_http_port(&state, cfg, &OurHttpd::of(&kit.root))?;
        Ok(paths_under(&state, root, module, port))
    }
}

/// Текст конфигурации httpd: Windows — ровно как в спайке 2026-10-20
/// (минимальный набор из пяти модулей плюс модуль платформы, из комплекта),
/// образ — та же форма, что уже работает в стенде (`config/1c/stand.sh`,
/// функция `publish`): на Debian те пять модулей живут не под `ServerRoot`,
/// явные `modules/mod_*.so` не резолвятся — ведёт `IncludeOptional
/// mods-enabled/*`. Linux-ветка может провалиться — см. `linux_httpd_conf`.
pub fn httpd_conf(p: &Paths) -> Result<String, String> {
    if cfg!(windows) {
        Ok(windows_httpd_conf(p))
    } else {
        linux_httpd_conf(p)
    }
}

fn windows_httpd_conf(p: &Paths) -> String {
    // Явно, а не положившись на скомпилированное умолчание mod_mime —
    // ровно так, как бежал спайк 2026-10-20. Строкой, не `.join()`: эта
    // функция всегда пишет путь по-Windows, даже когда тестовый бинарник
    // собран на Linux (CI может собирать и там) — `.join()` добавил бы
    // '/' вместо '\' на не-Windows таргете и разошёлся бы с эталоном.
    let mime_types = format!("{}\\conf\\mime.types", p.root.display());
    format!(
        "ServerRoot \"{root}\"\n\
ServerName localhost\n\
Listen 127.0.0.1:{port}\n\
PidFile \"{pid}\"\n\
ErrorLog \"{log}\"\n\
LogLevel warn\n\
LoadModule authz_core_module modules/mod_authz_core.so\n\
LoadModule authz_host_module modules/mod_authz_host.so\n\
LoadModule alias_module modules/mod_alias.so\n\
LoadModule mime_module modules/mod_mime.so\n\
LoadModule dir_module modules/mod_dir.so\n\
LoadModule _1cws_module \"{module}\"\n\
TypesConfig \"{mime_types}\"\n\
ThreadsPerChild 16\n\
DocumentRoot \"{pub_dir}\"\n\
<Directory \"{pub_dir}\">\n\
    AllowOverride All\n\
    Options None\n\
    Require all granted\n\
    SetHandler 1c-application\n\
    ManagedApplicationDescriptor \"{pub_dir}/default.vrd\"\n\
</Directory>\n",
        root = p.root.display(),
        port = p.port,
        pid = p.pid.display(),
        log = p.log.display(),
        module = p.module.display(),
        pub_dir = p.pub_dir.display(),
    )
}

/// Образ: форма стенда минус то, что там нет смысла без root — `User`/`Group`
/// (стенд поднимает Apache от root и переключает его на владельца базы;
/// коннектор и так уже запущен от имени рабочего места) — и минус `Alias
/// "/base"` (старая схема публикации в подкаталог, которую отменяет задача
/// 13): здесь, как и на Windows, публикация — в корень своего порта.
/// `ServerLimit 1`/`StartServers 1` и лимиты потоков — не стиль, а то, что
/// держит единственный сеанс «Предприятия» на базу: второй процесс-воркер
/// значил бы второй сеанс, а учебная лицензия его не даёт.
fn linux_httpd_conf(p: &Paths) -> Result<String, String> {
    // `Path::parent()` у однокомпонентного относительного пути отдаёт
    // `Some("")`, не `None` — пустой `DefaultRuntimeDir` молча прошёл бы мимо
    // `.unwrap_or_default()`. Проверяем явно и отказываем читаемой строкой.
    let tools = p
        .pid
        .parent()
        .filter(|d| !d.as_os_str().is_empty())
        .ok_or_else(|| format!("у {} нет каталога — не могу вычислить DefaultRuntimeDir", p.pid.display()))?;
    Ok(format!(
        "ServerRoot \"{root}\"\n\
ServerName localhost\n\
DefaultRuntimeDir \"{tools}\"\n\
PidFile \"{pid}\"\n\
Listen 127.0.0.1:{port}\n\
ErrorLog \"{log}\"\n\
LogLevel warn\n\
IncludeOptional mods-enabled/*.load\n\
IncludeOptional mods-enabled/*.conf\n\
ServerLimit 1\n\
StartServers 1\n\
ThreadsPerChild 16\n\
MinSpareThreads 16\n\
MaxSpareThreads 16\n\
MaxRequestWorkers 16\n\
LoadModule _1cws_module \"{module}\"\n\
DocumentRoot \"{pub_dir}\"\n\
<Directory \"{pub_dir}\">\n\
    AllowOverride All\n\
    Options None\n\
    Require all granted\n\
    SetHandler 1c-application\n\
    ManagedApplicationDescriptor \"{pub_dir}/default.vrd\"\n\
</Directory>\n",
        root = p.root.display(),
        tools = tools.display(),
        pid = p.pid.display(),
        port = p.port,
        log = p.log.display(),
        module = p.module.display(),
        pub_dir = p.pub_dir.display(),
    ))
}

/// Бинарь httpd — используется, чтобы его ЗАПУСТИТЬ (`start` ниже); остановка
/// (`kill_tracked`) по этому пути больше не ходит вовсе (замер 2.11.2026:
/// `-k stop` на консольном экземпляре ничего не останавливает) — она гасит
/// pid, а не бинарь. Основной Linux-путь зовёт системный `apache2` по имени
/// напрямую.
#[cfg(windows)]
fn httpd_binary(p: &Paths) -> PathBuf {
    p.root.join("bin").join("httpd.exe")
}

/// Грубая проверка «порт свободен»: TCP-соединение на петлю не прошло.
fn port_is_free(port: u16) -> bool {
    std::net::TcpStream::connect_timeout(
        &std::net::SocketAddr::from((std::net::Ipv4Addr::LOCALHOST, port)),
        std::time::Duration::from_millis(200),
    )
    .is_err()
}

/// Грубая проверка «на петле кто-то слушает» — не доказательство, что это
/// именно наш httpd (см. `service_responds`/`descriptor_matches` для этого),
/// а только информация: после своей остановки видеть чужую программу на том
/// же порту — не наша ошибка (см. `ops_host::Publication::revert_apply`).
pub fn httpd_responds(port: u16) -> bool {
    !port_is_free(port)
}

/// Pid из `PidFile` httpd — httpd пишет туда свой собственный pid сам, тем
/// же текстом, что `netstat`/`GetExtendedTcpTable` отдают держателя
/// (`holder::listener_pid`). `None` — файла нет или в нём не число: решать,
/// отказ это или нет, остаётся вызывающему (`refuse_unless_ours`,
/// `busy_for_choice`). Параметр — путь к файлу, не `Paths`: обоим
/// вызывающим `Paths` целиком не нужна (см. `pid_file_in`).
fn our_httpd_pid(pid_file: &Path) -> Option<u32> {
    std::fs::read_to_string(pid_file).ok()?.trim().parse().ok()
}

/// Страж перед отправкой пароля базы на локальный порт (находка
/// автоматической проверки безопасности, план «тонкий срез ценности»,
/// задача 1, круг исправления): терминальный сервер держит несколько
/// бухгалтеров в своих сеансах на одной машине, подбор порта (`ports::pick`)
/// обходит занятые на МОМЕНТ подбора, но после него порт мог освободиться и
/// достаться чужому процессу, или изначально принадлежать программе, которая
/// слушает его не через наш подбор вовсе. Слушатель — не обязательно наш
/// httpd просто потому, что это «наш» порт по `Paths`.
///
/// Сравнение — pid из `PidFile` (`our_httpd_pid`) с тем, кто и правда слушает
/// порт сейчас (`holder::listener_pid`, системный вызов/ядро, без
/// `netstat.exe` на каждую пробу — пробы частые). Не совпало или не
/// прочиталось — отказ словами, без какого-либо похода за пароль дальше.
///
/// Сеть тут ни при чём: свой httpd слушает только `127.0.0.1`
/// (`Listen 127.0.0.1:{port}` в `windows_httpd_conf`/`linux_httpd_conf`) —
/// проверка целиком про чужой процесс на ЭТОЙ же машине, не про доступ
/// снаружи.
///
/// **Какой из двух процессов Apache владеет сокетом — измерено, не угадано**
/// (ведущий, 2.11.2026; ревью круга 3 ставило этот вопрос как недоказанный).
/// `mpm_winnt` держит два процесса — родителя и рабочего ребёнка, — а
/// `PidFile` несёт родителя; если бы таблицу слушателей занимал ребёнок,
/// `refuse_unless_ours` отказывала бы ВСЕГДА на каждой живой установке.
/// Замер: httpd из комплекта (`C:\dev1c-connect-kit\httpd\bin\httpd.exe`)
/// поднят на выброшенном порту 47901, `PidFile` = `23668`,
/// `Get-NetTCPConnection -State Listen -LocalPort 47901 | Select
/// OwningProcess` = `23668`; ребёнок (pid 2204, родитель 23668) сокетом НЕ
/// владеет. То есть сравнение ниже на Windows верно как есть. Передоказывать
/// не нужно — цифры здесь.
/// Параметры — pid-файл, порт и ОЖИДАЕМЫЙ ОБРАЗ нашего httpd, а не `Paths`
/// целиком (находка 4 ревью круга 3): собрать `Paths` означало бы пройти
/// через `resolve_http_port`, то есть через ПОДБОР, а подбор пишет на диск.
/// Проверке перед отправкой пароля право переизбрать порт не нужно и вредно.
///
/// Ожидаемая личность (`OurHttpd`) — параметром, а не внутри: в бою её
/// называет `OurHttpd::of`, а тест подаёт собственную (`current_exe` и свой
/// же владелец) и слушает в самом тестовом процессе — иначе правило
/// проверялось бы только отказом, то есть никак.
/// Каждый отказ называет ПОРТ, который проверяли, — все четыре, не только
/// те, где порт и есть причина: человек должен видеть, о каком номере речь
/// (а тест — что страж проверил именно тот порт, который называет
/// `base_url()`, см. `the_guard_checks_exactly_the_port_base_url_names`).
pub fn refuse_unless_ours(pid_file: &Path, port: u16, expected: &OurHttpd) -> Result<(), String> {
    let our_image = &expected.image;
    let Some(ours) = our_httpd_pid(pid_file) else {
        return Err(format!("порт {port}: pid-файл публикации {} не прочитать — пароль базы не отправлен", pid_file.display()));
    };
    // Личность процесса, а не только его номер (находка автоматической
    // проверки безопасности по кругу 4). Номера Windows переиспользует, и
    // сосед, получивший номер из нашего несвежего pid-файла, иначе читался бы
    // как «наш httpd» — см. докстроку `holder::image_of_pid`.
    match holder::image_of_pid(ours) {
        None => {
            forget_stale_pid_file(pid_file);
            return Err(format!(
                "порт {port}: процесс pid {ours} из pid-файла публикации ({}) не опознать — его больше нет (или не хватило прав посмотреть) — файл несвежий и убран, пароль базы не отправлен",
                pid_file.display()
            ));
        }
        Some(image) if !holder::same_image(our_image, &image) => {
            forget_stale_pid_file(pid_file);
            return Err(format!(
                "порт {port}: pid {ours} из pid-файла публикации — не наш httpd, его образ {}, а наш {} — файл несвежий и убран, пароль базы не отправлен",
                image.display(),
                our_image.display()
            ));
        }
        Some(_) => {}
    }
    // Владелец — главный барьер (решение ведущего, круг 5): образ сосед
    // получает даром, запустив наш же httpd из комплекта, а наше имя — нет.
    // Закрываемся, а не открываемся: не удалось установить — отказ, и текст
    // у него свой, не тот, что у «не совпал».
    //
    // Две причины — два текста, и это нарочно: по «не совпал» человек идёт
    // смотреть, кто поднял сервер на его порту, по «не удалось установить» —
    // чинить права на машине. Неизвестность обеих сторон (своей и держателя)
    // слита в одну ветку: внутри неё человеку чинить одно и то же, а две
    // ветки дали бы одну непроверяемую — своего владельца на живой машине не
    // добыть нельзя (замер в докстроке `holder::owner_of_pid`).
    match (expected.owner.as_deref(), holder::owner_of_pid(ours)) {
        (Some(our_owner), Some(owner)) if !holder::same_owner(our_owner, &owner) => {
            forget_stale_pid_file(pid_file);
            return Err(format!(
                "порт {port}: владелец процесса pid {ours} не совпал с текущим пользователем (его {owner}, наш {our_owner}) — это не наш httpd, даже если запущен нашим файлом; файл несвежий и убран, пароль базы не отправлен"
            ));
        }
        (Some(_), Some(_)) => {}
        _ => {
            return Err(format!(
                "порт {port}: не удалось установить владельца (нашего или процесса pid {ours}) — сверять не с чем, пароль базы не отправлен"
            ));
        }
    }
    let Some(listening) = holder::listener_pid(port) else {
        return Err(format!("порт {port} никем не слушается — пароль базы не отправлен"));
    };
    if listening != ours {
        return Err(format!("порт {port} занят не нами (его слушает pid {listening}, у нашего httpd pid {ours}) — пароль базы не отправлен"));
    }
    Ok(())
}

/// Несвежий pid-файл убираем за собой: процесса с таким номером нет вовсе
/// или он не наш httpd — значит, личность в файле мёртвая, и оставлять её
/// нельзя. Иначе сосед, которому система когда-нибудь выдаст тот же номер,
/// встаёт ровно на эту личность (решение ведущего, 2.11.2026, пункт 5
/// находки). Остановка публикации прибирает его своим путём — это задача 7
/// плана; здесь только «не нашли своего, значит файла быть не должно».
///
/// Отказ удаления молчаливый нарочно: файла может не быть уже (две пробы
/// разом), он может быть только для чтения — и ни то, ни другое не меняет
/// ответа стража, который к этому моменту уже решён и будет озвучен словами.
fn forget_stale_pid_file(pid_file: &Path) {
    let _ = std::fs::remove_file(pid_file);
}

/// Дорога, которой зовут все, кто собирается отправить пароль базы на
/// локальный порт (находка автоматической проверки безопасности, круг
/// исправления 2): `verify.rs` и оба живых вызова в `ops_host.rs`
/// (`Extension::state`, `Extension::apply`) заводили бы по своей копии
/// `Paths::of` + `refuse_unless_ours`, и ровно так уже разошлась первая
/// попытка — страж стоял у одного вызывающего из четырёх.
///
/// `"webserver"` — `Ok(())` без похода к `Paths::of` вовсе: адрес там чужой
/// по определению (человек публикует сам), своего httpd и pid-файла для
/// сравнения не существует, и строить `Paths` незачем.
///
/// Иначе — pid-файл публикации и ПОРТ ИЗ `cfg.http_port()`: то самое число,
/// которое называет `base_url()`, то есть адрес, куда пароль и уйдёт.
/// Источник порта один, и поэтому расхождение «страж проверил одно, пароль
/// ушёл на другое» структурно невозможно — барьер `ports_agree`, который
/// стоял здесь в круге 2, больше не нужен; вместо него тест
/// `the_guard_checks_exactly_the_port_base_url_names`.
///
/// `Paths::of` страж не зовёт вовсе (находка 4 ревью круга 3). Звал — и у
/// проверки, которую делают перед КАЖДОЙ отправкой пароля, был побочный
/// эффект записи: `Paths::of` → `resolve_http_port` → `ports::choose`, а тот
/// при разошедшемся предпочтении перезаписывает `ports.state`. То есть
/// проверка имела право сменить выбранный порт у работающего httpd. Путь к
/// pid-файлу от порта не зависит (`pid_file_in`), значит собрать его можно
/// без всякого подбора — что и делается.
///
/// `kit` нужен ровно за одним — путём к НАШЕМУ httpd (`our_httpd_image`),
/// чтобы сверять личность держателя, а не только его номер (находка
/// автоматической проверки безопасности по кругу 4). Ни `Paths::of`, ни
/// подбора порта за этим не стоит: `kit.root` — чистое значение.
pub fn guard_own_listener(cfg: &Cfg, kit: &Kit) -> Result<(), String> {
    if cfg.host.publication != "auto" {
        return Ok(());
    }
    refuse_unless_ours(&pid_file_in(&guard_state_dir()?), cfg.http_port(), &OurHttpd::of(&kit.root))
}

/// Каталог состояния, в котором страж ищет pid-файл: тот же, что у
/// публикации, и без какого-либо подбора порта. Отказ словами на угаданном
/// каталоге — та же причина, что у `Paths::of`/`ensure_state`: не смогли
/// понять, где состояние, — не отправляем пароль.
#[cfg(not(test))]
fn guard_state_dir() -> Result<PathBuf, String> {
    ops_host::refuse_guessed_state_dir()?;
    Ok(ops_host::state_dir())
}

/// В прогоне страж не смотрит на настоящую машину вовсе: каталог берётся из
/// потоко-локальной подмены (`ops_host::with_state_dir_for_test`), а без неё
/// — заведомо несуществующий, то есть страж отказывает «pid-файл публикации
/// не прочитать». Иначе исход теста зависел бы от того, поднята ли на машине
/// разработчика живая публикация: у владельца она поднята, и страж в его
/// прогоне разрешал бы то, что в чужом прогоне запрещает.
#[cfg(test)]
fn guard_state_dir() -> Result<PathBuf, String> {
    Ok(ops_host::test_state_dir::get().unwrap_or_else(|| std::env::temp_dir().join("dev1c-state-dir-not-substituted-in-test")))
}

/// Время жизни поднятого httpd относительно вызвавшего процесса.
///
/// `Detached` — публикация обязана пережить того, кто её поднял: разовая
/// команда `1c-connect install` (или кнопка «Установить» в окне) делает своё
/// дело и выходит/продолжает жить дальше, но сервис — это публикация базы, а
/// не ребёнок установщика, и её не касается ни штатный выход процесса, ни его
/// крах.
///
/// `WithCaller` — сервис обязан умереть вместе с вызвавшим процессом: `serve`
/// держит сеанс до Ctrl+C/SIGTERM, окно — пока открыто, и падение любого из
/// них (не штатный выход, а крах) не должно оставлять сироту на порту со
/// старой конфигурацией, которую больше никто не обслуживает.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lifetime {
    Detached,
    WithCaller,
}

/// Правило владения: сервис, который уже отвечает под сегодняшней
/// конфигурацией, уже у кого-то на привязи — у этого же процесса
/// (`WithCaller`, живое окно или `serve`), у другого окна, у `serve` на
/// соседнем процессе — а разовая `Detached`-команда не может заглянуть в
/// чужую память и узнать, чья это привязка. Поэтому `Detached`, найдя живой
/// и верно настроенный сервис, не трогает его вовсе: убить и поднять заново
/// отвязанным сняло бы привязку впустую, и крах настоящего владельца потом
/// оставил бы ровно того сироту, которого привязка должна предотвращать.
/// `WithCaller` же всегда забирает сервис под себя — это и есть становление
/// владельцем, а не чужая кража.
pub fn detached_should_leave_alone(lifetime: Lifetime, responds: bool, descriptor_matches: bool) -> bool {
    lifetime == Lifetime::Detached && responds && descriptor_matches
}

/// Последние непустые строки журнала ошибок httpd — для сообщения в журнал
/// коннектора, когда старт не удался: причину пишет сам httpd туда, не в
/// stdout/stderr (которые мы теперь не пайпим и не ждём — см. `start`).
fn error_log_tail(log: &Path, n: usize) -> String {
    let text = std::fs::read_to_string(log).unwrap_or_default();
    let lines: Vec<&str> = text.lines().map(str::trim_end).filter(|l| !l.is_empty()).collect();
    lines[lines.len().saturating_sub(n)..].join("\n")
}

