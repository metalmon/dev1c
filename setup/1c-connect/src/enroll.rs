/// Возврат не назвал карточку, а зачисленных баз у этой стороны несколько — выбрать за неё нечем.
///
/// Так выглядит партнёр от прежней сборки или неудавшаяся запись признака базы: с 10.11 зовущая сторона хранит признак рядом с партнёром и
/// после первого удачного круга называет карточку сама. Прежде на это отвечали ВСЕМ списком, и поток числился за всеми базами партнёра
/// сразу — то есть отзыв одной карточки резал связь по остальным, а у человека с пятью карточками к одному партнёру резал все пять потоков
