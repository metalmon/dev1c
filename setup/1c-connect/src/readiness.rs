//! Приговор о готовности агента добираться до базы — без окна: `status` в командной строке читает его тем же путём, что карточка готовности. Половина `gui::facts`, что строит экранные строки (`Line`) или берёт `Ui`/`cx`, здесь не живёт — задача 11 плана «Сопряжение переезжает в бек».

use common::check::{self, Check};
use std::time::{Duration, Instant};

/// Вердикт «дойдёт ли агент до базы» — выведен из ОДНОГО набора фактов (`verify::gather`/`verify::cheap`), а не хранится рядом с ним: два источника правды об одном итоге — ровно та болезнь, против которой писана вся перестройка (задача 5). Пересчитывается по событиям, что могли сдвинуть почву (включение MCP, «Сохранить», конец операции), и по такту (задача 6, `needs_full_pass`) — не только по ним одним, как было раньше. `PartialEq` — ради одного вопроса: сменился ли вердикт (`verdict_line`). Сравнивается он целиком, вместе с фактом-причиной: сменившаяся причина — такая же новость, как сменившееся состояние.
#[derive(Clone, Debug, PartialEq)]
pub enum Verdict {
    /// Обслуживание выключено — набор не считается вовсе (спека: «выключено — ничего не считаем»), и показывать нечего.
    Off,
    /// Обслуживание включено, но набора фактов ещё не было ни разу. Зелёным это не бывает: карточка показывает «Проверяю…» с точкой «занято» (спека: «Зелёной точки до вердикта готовности не бывает»).
    Checking,
    /// Все факты набора — факт сам по себе и есть доказательство.
    Ready,
    /// Первый не прошедший факт — не поломка, а «занято сейчас» (открытый сеанс 1С, наша же долгая операция): точка карточки от неё не красится (`panel::card` трактует `Busy` как `Ready`), в отличие от `NotReady`. Приоритет над `NotReady` обратный тому, что в порядке набора: поломка важнее занятости, и её человек должен увидеть даже при занятой базе.
    Busy(Check),
    /// Первый провалившийся факт — его `what`/`detail`/`hint` и есть причина, которую видит человек в карточке.
    NotReady(Check),
}

/// Вердикт из набора — чистая функция, ни счёта, ни сети: `serving` решает всё («выключено — ничего не считаем»), иначе пустой набор значит «ещё не посчитано» (`Checking`), а непустой разбирается по исходам фактов (`Check::outcome`). Поломка (`Outcome::Bad`) ищется первой и перекрывает занятость (`Outcome::Busy`) независимо от того, какой из двух факторов в наборе встретился раньше: человек должен увидеть сломанное и тогда, когда рядом ещё и занято. `note`/`pass` (оба — `Outcome::Good`) никогда не становятся ни тем, ни другим.
pub fn verdict_of(serving: bool, facts: &[Check]) -> Verdict {
    if !serving {
        return Verdict::Off;
    }
    if facts.is_empty() {
        return Verdict::Checking;
    }
    if let Some(c) = facts.iter().find(|c| c.outcome() == check::Outcome::Bad) {
        return Verdict::NotReady(c.clone());
    }
    if let Some(c) = facts.iter().find(|c| c.outcome() == check::Outcome::Busy) {
        return Verdict::Busy(c.clone());
    }
    Verdict::Ready
}

/// Что говорит «Проверить» при выключенном обслуживании — и когда её нажали выключенной, и когда выключили, пока расчёт шёл (Important 3 финального ревью). Одна формулировка на оба случая: человек читает про своё состояние, а не «Проверка пройдена» при выключенном коннекторе.
pub const CHECK_OFF: &str = "Доступ к 1С выключен — проверять нечего: включите его";

/// Причина, по которой карточка жёлтая (`Dot::Warn`): первый провалившийся факт из `verify::gather`, одной строкой — что не так и что сделать, без «факт N провален» (заказчик 2026-10-20 читает это как 1С-разработчик). Подсказка не дублируется, когда она уже вписана в само `detail` (так у TOOLS-факта «в комплекте нет … — скопируйте заново»), иначе человек видел бы один совет дважды.
pub fn readiness_reason(check: &Check) -> String {
    format!("{}: {}", check.what, fact_detail(check))
}

/// Подробность факта без его имени: что не так и что сделать, одной строкой. Подсказка не дублируется, когда она уже вписана в само `detail`.
///
/// Одно место на причину вердикта (`readiness_reason` — подсказка переключателя, подсказка значка, журнал) и на строку вкладки «Инструменты» (`panel::fact_rows`): два похожих склеивания `detail` с `hint` расходились бы молча, и человек читал бы один и тот же факт двумя разными способами.
pub fn fact_detail(check: &Check) -> String {
    if hint_adds(check) {
        format!("{} — {}", check.detail, check.hint)
    } else {
        check.detail.clone()
    }
}

/// Говорит ли подсказка факта что-то, чего нет в самом `detail`. Одно правило на оба показа подсказки — строкой вкладки (`fact_detail`, через тире) и отдельной строкой журнала (`check_lines`, со своим значком): рендеры разные, а решение «есть ли что добавить» одно. Так у TOOLS-факта («в комплекте нет … — скопируйте заново») совет не показывается дважды.
pub fn hint_adds(check: &Check) -> bool {
    !check.hint.is_empty() && !check.detail.contains(check.hint.as_str())
}

/// Сколько ждать поток готовности, прежде чем считать его потерянным. Бюджет набора — 20 с, и сторож нарочно взят много больше: он не инструмент точности, а предохранитель от залипшей защёлки. Пока он не сработал, второй поток не заводится, так что ошибиться в меньшую сторону хуже — это две пробы инструментов разом.
pub const READINESS_LOST: Duration = Duration::from_secs(5 * 60);

/// Потерян ли идущий расчёт: защёлка стоит дольше всякого разумного срока. `None` у начала — защёлку взвели где-то мимо `start_facts`; считаем потерянным, иначе она осталась бы навсегда.
pub fn readiness_lost(since: Option<Instant>, now: Instant) -> bool {
    match since {
        Some(t) => now.saturating_duration_since(t) > READINESS_LOST,
        None => true,
    }
}

/// Причина жёлтого вердикта человеческими словами, `None` — вердикт не жёлтый. Одна формулировка на журнал и на подсказку значка (`panel::reason` берёт ту же `readiness_reason`, только с большой буквы — он пишет в подсказку переключателя, у подвала с 9.11 для причины слота больше нет).
///
/// Жёлтых вердиктов два, и начало строки у них разное (Critical 2 ревью задач 5+6): «не всё готово» значит починить, «занято» — подождать или закрыть базу. Прежде `Busy` не давал причины вовсе, и ни журнал, ни значок о нём не говорили.
pub fn warn_reason(verdict: &Verdict) -> Option<String> {
    match verdict {
        Verdict::NotReady(c) => Some(format!("не всё готово: {}", readiness_reason(c))),
        Verdict::Busy(c) => Some(format!("занято: {}", readiness_reason(c))),
        _ => None,
    }
}

/// Строка журнала о зелёном вердикте. «Всё готово» — а не «готово»: рядом в журнале стоит «Готово за 2 мин» от конца операции, и два разных события одним словом читались бы как одно.
pub const VERDICT_READY: &str = "всё готово: агент дойдёт до базы";

/// Сколько в наборе плохих фактов — бейдж «Проблем: N» на вкладке «Журнал» и итог строкой журнала (`check_status`). Считается ТОЛЬКО исход «плохо» (решение владельца 25.10): занято — не провал ни в окне, ни в отчёте, человек, работающий в базе, получает 18 из 18 и строку «занято».
///
/// Бейдж берёт живой набор (`Ui::facts`), а не снимок последней проверки: снимок и был тем расхождением, ради которого всё затевалось — зелёная карточка при «Проблем: 2» рядом.
pub fn problem_count(facts: &[Check]) -> usize {
    facts.iter().filter(|c| c.outcome() == check::Outcome::Bad).count()
}

/// Медленный такт: как часто идут весь дешёвый набор (`verify::cheap`) и — если он не изменился — дорогие факты. Открытое окно спрашивает чаще, скрытое реже, но идёт всё равно: иначе набор «протухнет» тихо, пока никто не смотрит. Секундный такт при открытом окне спрашивает ОДНО (число открытых сеансов 1С) — остальные дешёвые факты за секунду не меняются.
pub const SLOW_OPEN: Duration = Duration::from_secs(30);

// `STATUS_LINGER` (сколько итог операции держал слот подвала) ушёл вместе со `status`: держать было нечего и некого — слота нет с 9.11.
pub const SLOW_HIDDEN: Duration = Duration::from_secs(120);

/// Пора ли идти за дорогими (сетевыми) фактами заново — задача 6. Дешёвый такт (`verify::cheap`, без сети) можно звать часто; дорогой — нет, и эта чистая функция решает, когда разница в дешёвом наборе или истёкший срок того стоят.
///
/// Изменившийся дешёвый факт — повод немедленно, независимо от срока: закрыли базу между тактами — агенту может открыться дорога, и держать это знание устаревшим до следующего медленного такта незачем. Иначе — порог по тому, видно ли окно (`SLOW_OPEN`/`SLOW_HIDDEN`): реже, когда никто не смотрит. Пропущенный надолго такт (окно простояло скрытым сутки) не «протухает» сам по себе — `since_full` просто оказывается больше любого порога, и расчёт идёт сразу же, без отдельной ветки.
pub fn needs_full_pass(prev_cheap: &[Check], now_cheap: &[Check], since_full: Duration, window_open: bool) -> bool {
    if prev_cheap != now_cheap {
        return true;
    }
    since_full >= if window_open { SLOW_OPEN } else { SLOW_HIDDEN }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::verify;

    /// Приговор о готовности выносит бек: `status` в командной строке прочитает его, не поднимая окна.
    #[test]
    fn the_verdict_on_readiness_is_reached_without_a_window() {
        // выключенный доступ: приговор говорит о выключенности, а не о провале проверок
        let failing = vec![Check::fail("проект", "не разложен", "1c-connect install")];
        assert_eq!(verdict_of(false, &failing), Verdict::Off);
        // набор с одним провалом: приговор его называет, и `problem_count` считает ровно один
        let facts = vec![Check::pass("база", "есть"), Check::fail("проект", "не разложен", "1c-connect install")];
        assert_eq!(problem_count(&facts), 1);
        match verdict_of(true, &facts) {
            Verdict::NotReady(c) => assert_eq!(c.what, "проект"),
            other => panic!("{other:?}"),
        }
    }

    /// Вердикт из набора — задача 5. `Outcome::Bad` важнее `Outcome::Busy` независимо от того, какой факт в наборе раньше: поломку человек должен увидеть и при занятой базе, а не только свободной.
    #[test]
    fn the_verdict_reads_the_set_in_one_order() {
        let good = Check::pass("база", "есть");
        let busy = Check::busy("в базе открыт сеанс", "1 открыт сеанс 1С", "закройте Предприятие");
        let bad = Check::fail("проект", "не разложен", "1c-connect install");
        assert!(matches!(verdict_of(false, std::slice::from_ref(&good)), Verdict::Off), "выключено — ничего не считаем");
        assert!(matches!(verdict_of(true, &[]), Verdict::Checking));
        assert!(matches!(verdict_of(true, std::slice::from_ref(&good)), Verdict::Ready));
        assert!(matches!(verdict_of(true, &[busy.clone(), good]), Verdict::Busy(_)));
        // Поломка важнее занятости: её человек должен увидеть и при открытой базе.
        assert!(matches!(verdict_of(true, &[busy, bad]), Verdict::NotReady(_)));
    }

    /// Граница спеки 31.10 (повод 1): вкладка «Инструменты» показывает состояние комплекта и при выключенных MCP, а вердикт от этого не меняется — он остаётся `Off` и фактов не читает вовсе. Самый опасный случай и проверяем: комплект НЕПОЛНЫЙ, то есть факт КРАСНЫЙ. Покрасить им значок при выключенном коннекторе значило бы кричать о проблеме там, где человек ничего не включал.
    ///
    /// Своя грань у этого утверждения именно в красноте списка, и она здесь единственная в программе (круг исправления 31.10, пункт 4: ревью сочло утверждение проходящим при любом значении — замерено, это не так). Подмена, от которой оно стоит: перенести в `verdict_of` поиск `Outcome::Bad` ВЫШЕ раннего возврата по `serving` — тогда выключенный коннектор с неполным комплектом отдаёт `NotReady`, и значок краснеет. На той же подмене первая строка `the_verdict_reads_the_set_in_one_order` выше остаётся зелёной: она подставляет список из ОДНОГО ЗЕЛЁНОГО факта, которому и находиться-то раньше сторожа нечем, — то есть две эти строки не дублируют друг друга, а делят случай пополам.
    #[test]
    fn a_red_kit_fact_does_not_colour_the_verdict_while_mcp_are_off() {
        let kit = vec![
            Check::fail(verify::KIT, "файла нет", "комплект неполный — скопируйте заново"),
            Check::fail(verify::TOOLS, "комплект неполный", "скопируйте полный комплект заново"),
        ];
        assert!(kit.iter().all(|c| c.outcome() == common::check::Outcome::Bad), "список обязан быть красным — иначе грани нет");
        assert!(matches!(verdict_of(false, &kit), Verdict::Off), "выключено — вердикт `Off`, какими бы ни были факты комплекта");
    }

    /// Дефект (заказчик 2026-10-20): карточка не должна повторять подсказку, уже вписанную в сам текст факта (TOOLS-Blocked несёт её внутри `detail`, см. `ops_host::tools_state`), и никогда не говорит «факт N провален».
    #[test]
    fn readiness_reason_says_what_and_what_to_do_without_echoing_the_hint() {
        let blocked = Check::fail(
            "инструменты комплекта",
            "в комплекте нет vrunner/, git/ или httpd/ — скопируйте полный комплект заново",
            "скопируйте полный комплект заново",
        );
        let text = readiness_reason(&blocked);
        assert_eq!(text.matches("скопируйте полный комплект заново").count(), 1, "{text}");
        assert!(!text.to_lowercase().contains("факт"), "{text}");

        let web = Check::fail("веб-сервер", "порт 1818 не отвечает", "запустите Apache/IIS, на котором опубликована база");
        let text = readiness_reason(&web);
        assert!(text.contains("порт 1818 не отвечает") && text.contains("запустите Apache/IIS"), "{text}");
    }

    /// Задача 8: бейдж «Проблем: N» считает плохие факты набора. Занято — не провал ни в окне, ни в отчёте (решение владельца 25.10): человек, работающий в базе, получает 18 из 18 и строку «занято». Живёт ли счёт за снимком или за живым набором — проверка `gui::facts::tests` (бейдж держится за `Ui::facts`, а не застывает).
    #[test]
    fn the_badge_counts_only_bad_facts() {
        let facts = vec![
            Check::pass("база", "C:\\Bases\\Buh"),
            Check::note("комплект на носителе", "FAT32"),
            Check::busy("в базе открыт сеанс", "сеансов больше не осталось", "закройте «Предприятие»"),
            Check::fail("проект", "не разложен", "1c-connect install"),
        ];
        assert_eq!(problem_count(&facts), 1);
        // Пустой набор — не «ноль проблем доказано», но и показывать нечего.
        assert_eq!(problem_count(&[]), 0);
    }

    /// Такт и поводы для пересчёта — задача 6. Изменившийся дешёвый факт тянет дорогие независимо от срока; неизменившийся — молчит до срока, который пореже при скрытом окне; а пропущенный надолго такт не «протухает»: `since_full` просто больше любого порога.
    #[test]
    fn a_changed_cheap_fact_pulls_the_expensive_ones() {
        let free = vec![Check::pass("в базе открыт сеанс", "нет")];
        let busy = vec![Check::busy("в базе открыт сеанс", "1 открыт сеанс 1С", "закройте")];
        assert!(needs_full_pass(&busy, &free, Duration::ZERO, true), "закрыли базу — спросить заново");
        assert!(!needs_full_pass(&free, &free, Duration::from_secs(5), true), "ничего не менялось — молчим");
        assert!(needs_full_pass(&free, &free, SLOW_OPEN, true), "медленный такт при открытом окне");
        assert!(!needs_full_pass(&free, &free, SLOW_OPEN, false), "при закрытом окне такт реже");
        assert!(needs_full_pass(&free, &free, SLOW_HIDDEN, false));
        // Окно было скрыто сутки — набор не «протухает»: считаем сразу.
        assert!(needs_full_pass(&free, &free, Duration::from_secs(86_400), false));
    }

    /// Сторож зависшего расчёта (находка S10): бюджет проверяется до факта, а не прерывает его, и поток может не ответить никогда. Залипшая защёлка означала бы вердикт, который больше не посчитается ни разу. Проводка самого сторожа через `start_facts`/`apply_facts` — тест `gui::facts::tests`, здесь только правило срока.
    #[test]
    fn a_lost_readiness_thread_does_not_latch_forever() {
        // Якорь в будущем: на свежей машине `Instant::now() - 5 мин` паникует.
        let now = Instant::now() + Duration::from_secs(3600);
        assert!(!readiness_lost(Some(now), now));
        assert!(!readiness_lost(Some(now), now + READINESS_LOST), "срок ещё не вышел");
        assert!(readiness_lost(Some(now), now + READINESS_LOST + Duration::from_secs(1)));
        assert!(readiness_lost(None, now), "защёлку взвели мимо `start_facts` — ждать нечего");
    }
}
