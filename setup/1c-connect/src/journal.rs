//! Журнал: словарь строк, их вид и запись на диск — закон 2 спеки («книга, учёт разговоров и журнал — одни»). Файл один (`LOG_FILE`), и в него пишет и окно (через `gui::note_line`), и командная строка без окна (через `say`): второй таблицы значков или второго пути на диск этот модуль не заводит.
//!
//! Не за фичей `gui`: до задачи 12 плана «Сопряжение переезжает в бек» журнал писало только окно, и `serve`/отладочный режим командной строки не могли выполнить то, что обещают. `Kind` переехал сюда вместе с записью, потому что перевод разряда в значок (`Kind::mark`) — одна функция, и её зовут и файл, и экран (`gui::panel`); заводить в беке вторую меру значило бы разойтись с экраном.
//!
//! `Line` и перевод `common::Event → Line` (`gui::line_of`) остаются в окне: это решение, что показать на экране, а не что записать на диск, и второго перевода `Event` в строку заводить не стоит — `say` ниже делает тот же разбор для диска, что `line_of` для экрана.
//!
//! По той же причине в окне остаются `gui::Stamped`, `gui::LogEntry`, `gui::entries` и `gui::group_label` — лестница показа, а не запись: закон 8 спеки запрещает работе бека и возвращать `Line`, и нести значение про вид, а эта четвёрка делает ровно это (`Stamped` держит `Line`, `LogEntry`/`entries` собирают ленту ДЛЯ отрисовки, `group_label` кормит только её).

use common::kit::Kit;

/// Разряд строки журнала — словарь ФАЙЛА, а не экрана: варианты называют форму строки на диске, а `mark()` отдаёт знак, который в этот файл и пишется. Экран берёт тот же разряд (реэкспорт `gui::log::Kind`) и красит строку по нему же — вторая мера на тот же вопрос здесь не нужна.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Kind {
    Ok,
    Warn,
    Fail,
    Say,
    /// Заголовок раздела журнала — название операции с часами в заголовке.
    Head,
}

impl Kind {
    /// Значок перед строкой журнала; у `Say` и `Head` строка идёт без значка.
    pub fn mark(self) -> &'static str {
        match self {
            Kind::Ok => "✓",
            Kind::Warn => "!",
            Kind::Fail => "✗",
            Kind::Say | Kind::Head => "",
        }
    }
}

/// Отметка дня и часа у строки журнала: собирает её бек (`day_stamp` ниже), а несёт дальше окно — обёртка `gui::Stamped` в единственном месте, где строка входит в журнал окна (`gui::log::note_line_counting`). Неделя считается с понедельника (0) — обычный порядок для лестницы `gui::group_label` и для «в понедельник» … «в воскресенье».
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Stamp {
    pub year: i32,
    pub month: u32,
    pub day: u32,
    pub weekday: u32,
    pub hour: u32,
    pub minute: u32,
}

impl Stamp {
    /// Время строки для показа — тем же `HH:MM`, каким его уже печатает `clock()` в заголовке операции: двух разных начертаний часа на одном экране быть не должно.
    pub fn hhmm(self) -> String {
        format!("{:02}:{:02}", self.hour, self.minute)
    }
}

pub const LOG_CAP: usize = 2000;

/// Файл журнала рядом с комплектом: та же дозапись, что командная строка ведёт в `setup.log` (`Kit::journal`), но этим видом строк. Пишут сюда без различия окно и командная строка без окна — ровно закон 2 спеки.
pub const LOG_FILE: &str = "1c-connect.log";

/// Местное время `HH:MM` для заголовка раздела. Журнал не гейтится фичей `gui` (закон 2 спеки — он один и доступен из командной строки), и здесь единственный гейт — платформенный, тот же приём, что у `day_stamp` ниже.
#[cfg(windows)]
pub fn clock() -> String {
    use windows_sys::Win32::Foundation::SYSTEMTIME;
    use windows_sys::Win32::System::SystemInformation::GetLocalTime;
    let mut t = SYSTEMTIME { wYear: 0, wMonth: 0, wDayOfWeek: 0, wDay: 0, wHour: 0, wMinute: 0, wSecond: 0, wMilliseconds: 0 };
    unsafe { GetLocalTime(&mut t) };
    format!("{:02}:{:02}", t.wHour, t.wMinute)
}

#[cfg(not(windows))]
pub fn clock() -> String {
    let secs = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0);
    format!("{:02}:{:02}", (secs / 3600) % 24, (secs / 60) % 60)
}

/// Местная дата и час:минута для отметки строки журнала — тем же приёмом, что `clock()` выше (тот же `GetLocalTime`, тот же запасной путь вне Windows), с числом, месяцем, годом и днём недели вдобавок: без них лестницу подписи дня (`gui::group_label`) не свести. Нового зависимого пакета для времени не заводим (решение владельца 9.11) — `chrono` и подобные здесь не нужны.
#[cfg(windows)]
pub fn day_stamp() -> Stamp {
    use windows_sys::Win32::Foundation::SYSTEMTIME;
    use windows_sys::Win32::System::SystemInformation::GetLocalTime;
    let mut t = SYSTEMTIME { wYear: 0, wMonth: 0, wDayOfWeek: 0, wDay: 0, wHour: 0, wMinute: 0, wSecond: 0, wMilliseconds: 0 };
    unsafe { GetLocalTime(&mut t) };
    // `wDayOfWeek`: 0 = воскресенье … 6 = суббота. У нас неделя с понедельника (0) — см. докстроку `Stamp`.
    Stamp {
        year: t.wYear as i32,
        month: t.wMonth as u32,
        day: t.wDay as u32,
        weekday: (t.wDayOfWeek as u32 + 6) % 7,
        hour: t.wHour as u32,
        minute: t.wMinute as u32,
    }
}

#[cfg(not(windows))]
pub fn day_stamp() -> Stamp {
    let secs = std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0);
    let days = (secs / 86400) as i64;
    let (year, month, day) = civil_from_days(days);
    Stamp {
        year,
        month,
        day,
        // Эпоха (1970-01-01) — четверг, то есть индекс 3 при неделе с понедельника (0); отсюда и смещение `+3` ниже.
        weekday: (((days + 3) % 7 + 7) % 7) as u32,
        hour: ((secs / 3600) % 24) as u32,
        minute: ((secs / 60) % 60) as u32,
    }
}

/// Обратное действие алгоритма Хауарда Хиннанта (`days_from_civil` в `gui::log`, он зовёт этот алгоритм в обратную сторону для `group_label`) — нужно только запасному пути `day_stamp` вне Windows: там нет `GetLocalTime`, который отдаёт дату сам, только секунды с эпохи. Новый зависимый пакет (`chrono`/`time`) под арифметику дат не заводим — это десяток строк известного кода, без часовых поясов и календарей, которые здесь и не нужны.
#[cfg(not(windows))]
fn civil_from_days(z: i64) -> (i32, u32, u32) {
    let z = z + 719468;
    let era = if z >= 0 { z } else { z - 146096 } / 146097;
    let doe = z - era * 146097;
    let yoe = (doe - doe / 1460 + doe / 36524 - doe / 146096) / 365;
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = (if mp < 10 { mp + 3 } else { mp - 9 }) as u32;
    (if m <= 2 { (y + 1) as i32 } else { y as i32 }, m, d)
}

/// Строка журнала на диск: значок и пробел перед строкой, добитые до двух знаков (у `Say` — два пробела вместо значка), у заголовка раздела (`Kind::Head`) — пустая строка перед ним и без значка. Ошибки записи (диск занят, прав нет) молча игнорируются — журнал на диске не обязателен для работы. Единственный путь строки на диск — и для окна (`gui::note_line` зовёт отсюда), и для командной строки без него (`say` ниже).
pub fn write(kit: &Kit, kind: Kind, text: &str) {
    use std::io::Write;
    let path = kit.state_path(LOG_FILE);
    // Каталог состояния создаёт `ops_host::ensure_state` на запуске; здесь на всякий случай ещё раз — журнал открывается напрямую, без `kit::write_text`, который родителя создаёт сам.
    if let Some(d) = path.parent() {
        let _ = std::fs::create_dir_all(d);
    }
    let Ok(mut f) = std::fs::OpenOptions::new().append(true).create(true).open(&path) else { return };
    let line = if kind == Kind::Head { format!("\n{text}\n") } else { format!("{:<2}{text}\n", kind.mark()) };
    let _ = f.write_all(line.as_bytes());
}

/// Удобство для бека, который держит в руках `common::Event`, а не `Kind`: переводит одно в другое и зовёт `write`. Разбор — тот же, что `gui::line_of` делает для экрана (второй мере на один вопрос здесь не бывать): `Command`/`Output` в журнал на диске не идут — это журнал команд (`Kit::journal`, `setup.log`), не этот файл, — а фаза долгой операции (`Progress`) идёт `Kind::Say` её названием.
pub fn say(kit: &Kit, e: &common::Event) {
    let (kind, text) = match e {
        common::Event::Ok(t) => (Kind::Ok, t.clone()),
        common::Event::Warn(t) => (Kind::Warn, t.clone()),
        common::Event::Fail(t) => (Kind::Fail, t.clone()),
        common::Event::Say(t) => (Kind::Say, t.clone()),
        common::Event::Progress(p) => (Kind::Say, p.phase.title().into()),
        common::Event::Command(_) | common::Event::Output { .. } => return,
    };
    write(kit, kind, &text);
}

/// «Рабочего стола у этого сеанса нет» — ОДНИМ начертанием на всю программу.
///
/// Утверждение это человеку говорят двое: отказ при подъёме (`no_place_for_a_window` ниже) и предупреждение о неудавшемся значке у
/// `serve` (`gui::launched`). До круга 3 они были написаны своими словами каждый — два начертания одной строки, прямо против
/// правила, записанного в докстроке ниже. Звучать одновременно они не могут, но разошлись бы при первой правке одной из них, а
/// разряд этот ветке уже стоил шести кругов.
pub const NO_DESKTOP: &str = "рабочего стола у этого сеанса нет";

/// Беку негде показать окно: он говорит об этом словами и уходит — вместо того, чтобы занять место окна молча (закон 5 спеки).
///
/// Отказ подъёма окна не бывает временным: окно не открылось не потому, что сейчас что-то не сложилось, а потому, что показывать
/// его здесь негде — у этого сеанса нет рабочего стола (ssh, служба, планировщик). Процесс, который после такого отказа продолжает
/// жить, держит единственный на комплект замок (`single_instance`), и настоящее окно на этой машине не открывается уже вовсе и
/// молча. Это и есть отказ, сжёгший владельцу день 15.11: строка «окно не открылось» в журнал ложилась, а процесс оставался.
///
/// **Текст один на все поводы, и верность его держит УСТРОЙСТВО, а не редактура.** Зовущий у этой функции ровно один —
/// `gui::doom::refuse`, — и зовёт он её только на дороге `RefusalRoad::Journal`, которую `refusal_road` отдаёт лишь при
/// `holder::place_for_a_window() == false`. Значит утверждение «рабочего стола у этого сеанса нет» не надежда, а посылка той ветви,
/// в которой строка рождается.
///
/// Куплено это двумя кругами. Круг 22.11 снял из прежней строки две лжи: «показать его на ЭТОЙ МАШИНЕ негде» (на машине стол есть,
/// его нет у ЭТОГО СЕАНСА — при живом держателе в сеансе человека первое прямо ложно) и «пока она жива, окно не откроется и у того,
/// кто придёт следом» (на дороге не давшегося замка она замка и не брала, уходит сразу, и мешать некому). Круг 3 снял причину, по
/// которой лжи заводились: третий повод — отказ оконной системы в `gui::window::show_window` — звал эту функцию НАПРЯМУЮ, мимо
/// факта машины, а зовут `show_window` четырнадцать раз, почти все во время работы по щелчку в меню значка. Там рабочий стол есть,
/// человек видит значок глазами, и программа говорила ему неправду, уходя. Теперь и этот повод идёт через `refuse`.
///
/// Второй выход — два разных текста на разные поводы — отвергнут: разошлись бы они при первой же правке, а правда у них общая.
///
/// Совет про `serve` верен у всех поводов как ОБЩИЙ ответ на «как работать без рабочего стола», а не как обещание, что именно
/// сейчас он пройдёт: конкретную помеху человек уже прочёл в `{why}` первым же словом. У повода, заведённого 23.11, — не
/// открывшегося ключа узла (`peer::start`) — помеха как раз такая, которую `serve` не обходит, и это сказано В САМИХ его словах
/// (`node::foreign_key_words`, ветвь сетевого входа): они стоят здесь выше общего совета, и читает человек их первыми.
///
/// **Слова идут и в `stderr`, и печатает их эта функция, а не зовущий.** У запуска по ssh `stderr` настоящий — его читает человек в
/// своём терминале, — а до 17.11 слова ложились только в журнал, и стоящий в ssh видел пустоту при живом канале (замер живого
/// прогона 17.11). Форма строки одна на оба места — та же, что у файла журнала (`Kind::mark`), то же правило, что у
/// `gui::say_aloud`: двух начертаний одной строки у программы быть не должно, и держится это тем, что начертание здесь одно.
/// Удвоения на пути `serve` отсюда не бывает: ни один зовущий своих слов об этом отказе не печатает.
///
/// Отдаёт код возврата, а не зовёт `std::process::exit` сам: решение «показывать негде — значит на выход» проверяется тестом без
/// живого GPUI, а уводит процесс `gui::doom::refuse` — один на все три дороги. Замок освобождать отдельно нечему: на Windows это
/// объект ядра, на Linux дескриптор с `flock`, и оба снимает система вместе с процессом.
pub fn no_place_for_a_window(kit: &Kit, why: &str) -> i32 {
    let text = format!(
        "Окно не открылось: {why}. Слова здесь — в журнале и в stderr, — а не сообщением на экране: {NO_DESKTOP} (вход по ssh, \
         служба, задача планировщика), и прочесть сообщение было бы некому. Программа уходит, а не остаётся висеть невидимой. Связь \
         без рабочего стола держат подкомандой «1c-connect serve»: она окна не показывает и рабочего стола не требует."
    );
    write(kit, Kind::Fail, &text);
    eprintln!("{:<2}{text}", Kind::Fail.mark());
    1
}

/// Паника — в журнал на диске, а не в никуда.
///
/// Релиз окна собран `windows_subsystem = "windows"` (`main.rs`): консоли нет, и всё, что паника печатает в `stderr`, пропадает. Для человека это выглядит как «окно замерло и вылетело», а для нас — как пустое место там, где должна быть причина: обвал 12.11 на home-gpu пришлось доставать из системного журнала Windows по коду `c0000409`, и имени виноватой строки там нет вовсе.
///
/// Прежний обработчик зовётся следом, а не заменяется: он печатает то же самое в `stderr`, и под консолью (отладка, `--console`) человек по-прежнему видит привычное сообщение.
pub fn record_panics(kit: &Kit) {
    let path = kit.state_path(LOG_FILE);
    let was = std::panic::take_hook();
    std::panic::set_hook(Box::new(move |info| {
        use std::io::Write;
        let trace = std::backtrace::Backtrace::force_capture();
        let text = format!("\n!! обвал {} — {info}\n{trace}\n", clock());
        if let Ok(mut f) = std::fs::OpenOptions::new().append(true).create(true).open(&path) {
            let _ = f.write_all(text.as_bytes());
        }
        was(info);
    }));
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::project::tempdir::Dir;

    /// Журнал один: строка, записанная беком без окна, ложится в тот же файл и тем же видом.
    #[test]
    fn the_journal_is_one_and_the_back_writes_to_it_without_a_window() {
        let dir = Dir::new();
        let kit = Kit::at(dir.path());
        say(&kit, &common::Event::Fail("не дозвонился".into()));
        write(&kit, Kind::Head, "Проверка");
        let text = std::fs::read_to_string(kit.state_path(LOG_FILE)).unwrap();
        // `say` — значок `Kind::Fail` и тот же текст; `write(Head, ..)` — прежняя форма заголовка: пустая строка, без значка.
        assert_eq!(text, "✗ не дозвонился\n\nПроверка\n");
    }

    /// Бек, которому негде показать окно, не занимает место окна: он говорит об этом словами и отпускает замок.
    #[test]
    fn a_back_that_cannot_show_a_window_says_so_and_does_not_squat() {
        let dir = Dir::new();
        let kit = Kit::at(dir.path());
        let code = no_place_for_a_window(&kit, "cannot open windows while headless");
        // Ноль — это «всё в порядке, работаю дальше», то самое молчаливое продолжение с удержанным замком.
        assert_ne!(code, 0, "отказ окна — исход, а не рабочее состояние");
        let text = std::fs::read_to_string(kit.state_path(LOG_FILE)).expect("слова об отказе ложатся в журнал");
        assert!(text.contains("cannot open windows while headless"), "причину называем, а не прячем: {text}");
        assert!(text.contains("рабочего стола"), "человек должен понять, в чём дело: {text}");
        assert!(text.contains("serve"), "и что делать вместо этого: {text}");
    }
}
