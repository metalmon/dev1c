//! Отказы 1С человеческими словами: что это было и что с этим делать.
//!
//! Зачем. Платформа отвечает своим текстом, и в журнале все её отказы
//! выглядят одинаково страшно: «Пользователь ИБ не идентифицирован»,
//! «Превышено количество сеансов», «Конфигурация базы данных не соответствует
//! сохранённой». Человеку же нужно с первого взгляда отличать «упёрлись в
//! ограничение по числу сеансов» — то есть ничего не сломано, надо закрыть
//! лишнее окно 1С — от настоящей поломки. Решение заказчика 25.10.2026.
//!
//! **Исходный текст никогда не прячется.** Распознаём по подстрокам, а
//! формулировки платформы меняются от версии к версии и от локализации к
//! локализации. Не узнали — человек читает ровно то, что читал бы без нас, и
//! ничего не потерял; узнали — получает строку сверху. Поэтому ошибиться
//! здесь можно только в сторону «не добавили подсказку», и ни одна строка
//! таблицы не стоит ему ничего, даже если платформа такого текста уже не
//! говорит.
//!
//! Чистая функция от строки: вся таблица проверяется тестами, без платформы,
//! базы и Конфигуратора.

/// Распознанная причина отказа.
#[derive(Debug)]
pub struct Cause {
    /// Что это, одной короткой строкой. Её же показывает подвал окна вместо
    /// сырого текста: тот длинный и в двух строках подвала режется.
    pub what: &'static str,
    /// Что делать. Пустым не бывает: причина без совета человеку не нужна —
    /// он и так видит, что не получилось.
    pub fix: &'static str,
}

/// Та самая причина, ради которой всё заведено: ограничение по числу сеансов.
/// Названа константой, потому что её читает не только человек — проба базы
/// (`ops_host::version_once`) по ней отличает «занято» от поломки, и исход
/// факта от этого разный: жёлтый, а не красный.
///
/// Занятость базы устанавливает САМА БАЗА своим отказом, а не мы догадкой по
/// списку процессов (решение владельца 26.10: «если открытая 1С не блокирует
/// доступ — другая база например — то жёлтый не нужен»). Открытый сеанс 1С на
/// машине ничего не доказывает: человек мог открыть в 1С другую базу.
pub const SESSION_LIMIT: &str = "это ограничение по числу сеансов, а не поломка";

/// Это «занято», а не «сломано»: база жива и ответила, просто сеанс занят.
pub fn is_busy(cause: &Cause) -> bool {
    cause.what == SESSION_LIMIT
}

/// Таблица причин. Внутри группы подстроки соединены И, группы между собой —
/// ИЛИ: «превышен» вместе с «сеанс» в одной строке, либо готовая фраза
/// целиком. Все подстроки в нижнем регистре — сравнение идёт по приведённому
/// тексту.
///
/// Порядок важен: узкие причины выше общих, первое совпадение побеждает.
/// Ограничение по сеансам стоит первым намеренно — это самый частый отказ на
/// учебной платформе и ровно тот, который человек не должен путать с поломкой.
#[allow(clippy::type_complexity)]
const TABLE: &[(&[&[&str]], Cause)] = &[
    (
        &[&["превышен", "сеанс"], &["превышен", "количество пользовател"], &["превышено допустимое количество"], &["учебн", "сеанс"]],
        Cause { what: SESSION_LIMIT, fix: "закройте лишние сеансы 1С и повторите: у учебной платформы допустим один, у боевой упирается в лицензии" },
    ),
    (
        &[&["ключ защиты"], &["лицензи"]],
        Cause { what: "платформа не нашла лицензию", fix: "проверьте ключ защиты или сервер лицензий — к самой операции это не относится" },
    ),
    (
        &[&["пользователь иб не идентифицирован"], &["пользователь не идентифицирован"]],
        Cause {
            what: "база не приняла пользователя",
            fix: "проверьте «Пользователь базы» и пароль в «Параметрах»: публикация отвечает и анониму, поэтому её зелёный факт об этом молчит",
        },
    ),
    (
        &[&["конфигурация базы данных не соответствует"], &["не соответствует сохранённой"], &["не соответствует сохраненной"]],
        Cause {
            what: "в базе осталась незавершённая правка конфигурации",
            fix: "в Конфигураторе: Конфигурация → Вернуться к конфигурации БД, затем повторите",
        },
    ),
    (
        &[&["информационная база заблокирована"], &["заблокирована для"], &["блокировка установки соединений"]],
        Cause {
            what: "база заблокирована для соединений",
            fix: "снимите блокировку в Конфигураторе (Администрирование → Блокировка установки соединений) и повторите",
        },
    ),
    (
        &[&["уже используется"], &["занят другим процессом"], &["не удалось заблокировать файл"]],
        Cause {
            what: "файл базы держит другой процесс",
            fix: "закройте 1С на этой машине и проверьте, не висит ли 1cv8 в диспетчере задач",
        },
    ),
    (
        &[&["нарушение целостности"], &["ошибка формата потока"]],
        Cause {
            what: "база или файл повреждены",
            fix: "Конфигуратор → Администрирование → Тестирование и исправление информационной базы",
        },
    ),
];

/// Узнаём причину в сыром тексте отказа. `None` — не узнали, и это нормально:
/// вызывающий показывает сырой текст, как и раньше.
pub fn explain(raw: &str) -> Option<&'static Cause> {
    let text = raw.to_lowercase();
    TABLE.iter().find(|(groups, _)| groups.iter().any(|needles| needles.iter().all(|n| text.contains(n)))).map(|(_, cause)| cause)
}

/// Готовая строка для журнала: причина и совет через тире. Отдельной функцией,
/// чтобы окно и командная строка писали одно и то же.
pub fn hint_line(cause: &Cause) -> String {
    format!("{} — {}", cause.what, cause.fix)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Главное, зачем всё заведено: ограничение по сеансам человек должен
    /// узнать с первого взгляда, а не вычитывать из текста платформы.
    #[test]
    fn a_session_limit_is_named_as_a_limit_not_a_breakage() {
        for raw in [
            "Ошибка при выполнении: Превышено количество сеансов",
            "превышено максимальное количество сеансов работы с информационной базой",
            "Программа лицензирования: превышено допустимое количество пользователей",
            "Учебная версия: допускается только один сеанс",
        ] {
            let c = explain(raw).unwrap_or_else(|| panic!("не узнали: {raw}"));
            assert!(c.what.contains("ограничение"), "{raw} → {}", c.what);
            assert!(!c.fix.is_empty());
        }
    }

    #[test]
    fn the_known_platform_refusals_each_get_their_own_advice() {
        let cases = [
            ("Пользователь ИБ не идентифицирован", "пользовател"),
            ("Конфигурация базы данных не соответствует сохраненной конфигурации", "правка конфигурации"),
            ("Информационная база заблокирована: выполняется обновление", "заблокирована"),
            ("Файл базы данных уже используется другим процессом", "файл базы"),
            ("Обнаружено нарушение целостности структур базы данных", "повреждены"),
            ("Не обнаружен ключ защиты программы", "лицензию"),
        ];
        for (raw, mark) in cases {
            let c = explain(raw).unwrap_or_else(|| panic!("не узнали: {raw}"));
            assert!(c.what.contains(mark), "{raw} → {}", c.what);
        }
    }

    /// Не узнали — молчим. Это не отказ функции, а её нормальный ответ:
    /// сырой текст человек всё равно прочтёт.
    #[test]
    fn an_unknown_refusal_adds_nothing() {
        assert!(explain("git push: не найден репозиторий").is_none());
        assert!(explain("").is_none());
        assert!(explain("Готово за 3 с").is_none());
    }

    /// Регистр не важен: платформа пишет по-разному, а в журнал приходит и
    /// хвост stderr с заглавными.
    #[test]
    fn matching_ignores_case() {
        assert!(explain("ПРЕВЫШЕНО КОЛИЧЕСТВО СЕАНСОВ").is_some());
        assert!(explain("пользователь иб не идентифицирован").is_some());
    }

    #[test]
    fn the_journal_line_carries_both_the_cause_and_the_advice() {
        let c = explain("Превышено количество сеансов").unwrap();
        let line = hint_line(c);
        assert!(line.contains(c.what) && line.contains(c.fix), "{line}");
    }
}
