//! У рабочего места один владелец (спека): окно (`--tray`/без аргументов),
//! `connect` и `serve` держат порты, замок проекта (`project::hold`, по папке
//! с задачи 7 плана «Модель соединений») и, с недавнего, свою публикацию
//! базы — второй долгоживущий процесс не должен отнимать их у первого.
//! Разовые команды (`status`, `export`, `import`, `check`, `install`,
//! `example` и прочие) этот замок не трогают: они и так serialised через
//! `project::hold`, а задержать их здесь означало бы поломать обычную работу
//! человека.
//!
//! **Единица замка — одна копия на УЧЁТНУЮ ЗАПИСЬ в пределах машины.** Ни
//! комплект, ни сеанс в неё не входят: терминальный сервер, где у одной
//! учётной записи несколько сеансов, — обычный случай, и два комплекта у
//! одного человека — тоже. Поведение одно на всех осях; разной бывает только
//! опора под ним, и она живёт в одном названном месте — в адресе
//! управляющей двери (`door::pipe_path` на Windows, `door::sock_path` на
//! Linux). Выше этого адреса про платформу не знает ни замок, ни его тесты.
//!
//! **Замок — это и есть управляющая дверь (`door`), второго механизма нет**
//! (задача 14). Взять замок — открыть дверь: на Windows
//! `first_pipe_instance(true)` ручается, что имени не держит никто, а
//! именованный канал живёт в ОБЩЕМ пространстве имён машины и сеансом не
//! ограничен; на Linux то же делает `bind` сокета в каталоге времени
//! выполнения учётной записи, с пробой живого перед тем, как снять остаток
//! прошлого запуска. Спросить, жив ли держатель, — постучать (`is_held`):
//! ответила дверь, значит за ней кто-то есть. Это строже прежнего, где
//! открывшийся дескриптор объекта доказывал лишь существование объекта.
//!
//! Переживаемость краха остаётся главным свойством: имя канала система
//! снимает вместе с процессом, даже убитым (`taskkill /F`, обрыв питания), а
//! осиротевший файл сокета `door::open_at` отличает от живого пробой и
//! снимает сам.
//!
//! **Чего здесь больше нет и почему.** Замок держал именованный МЬЮТЕКС
//! (`CreateMutexW` без префикса), а объект ядра без префикса виден только в
//! сеансе создателя — то есть единицей он считал «сеанс × учётку». На этом
//! сгорел день 15.11: вход по ssh под той же учётной записью, под которой на
//! рабочем столе жило окно, завёл отдельный сеанс, получил свой мьютекс,
//! поднял вторую копию — показать окно она не смогла, но осталась жить и
//! заняла место, после чего настоящее окно не открывалось вовсе и молча.
//! `Global\` мьютексу не помог бы: его создание требует привилегии
//! `SeCreateGlobalPrivilege`, которой у обычного пользователя терминального
//! сервера нет. Советный `flock` на каталоге состояния тоже ушёл: он считал
//! единицей комплект. Признак «этот процесс обслуживает данный комплект»
//! отдельным объектом больше не держится вовсе — его спрашивают у той же
//! двери (`serves_our_kit`), и вместе с комплектом, который она называет
//! сама (круг правок 2 и 3).
//!
//! Вторая копия не умирает молча. На Windows она ПРОСИТ первую показать своё
//! окно (`request_show` → `serve_show_requests`, именованное событие ядра) и
//! уходит; просьбу некому принять (голова `serve`, `connect`, сборка без
//! окна, первая копия в ДРУГОМ сеансе) — говорит причину (`TAKEN`, а при
//! держателе в чужом сеансе ещё и `OTHER_SESSION`) и выходит с ошибкой. На
//! Linux — только вторая половина: просить там нечем, сразу сообщение и
//! отказ.
//!
//! Слова обязаны ДОЙТИ, а не просто сложиться: у запуска с окном консоли нет
//! (`windows_subsystem = "windows"`), и отказ ему показывают тем способом,
//! какой на этой машине доходит, — сообщением ОС там, где есть рабочий стол,
//! и словами в журнал и `stderr` там, где его нет (правка 17.11: на невидимой
//! оконной станции `MessageBoxW` ждал «ОК» вечно, и не давшийся замок стоял в
//! нём молча, держа сам себя). Выбирает способ `gui::doom::refuse` — один на все
//! отказы при старте, — а судьбу отказа ПОДЪЁМА решает
//! `gui::seen_by_the_person`, единственное место, через которое проходят ОБА
//! входа в подъём (круг правок 1 задачи 8).
//!
//! **Просьба показать окно — не управляющая дверь, и путать их нельзя.**
//! Событие ядра без атрибутов безопасности видно только внутри сеанса
//! создателя, и для разговора между сеансами одной учётной записи не годится
//! вовсе. Поэтому замком оно и не стало: отказ второй копии из чужого сеанса
//! выходит словами, а не молчаливым подъёмом. Разговор команд с живым
//! экземпляром идёт дверью (`door`, задача 5 плана «Сопряжение переезжает в
//! бек»); эта просьба осталась тем, чем была, — одним сигналом «покажи окно»
//! от второй копии к первой, и только в пределах одного сеанса.

use common::kit::Kit;

/// Без символов, опасных для имени объекта ядра или файла (пробелы,
/// кириллица, `\`/`/`) — они гасятся в `_`. Чистят ею ПУТЬ, и только его:
/// ключ файлового замка проекта (`file_lock`) — единственный оставшийся
/// зовущий. Из ключа ЗАМКА она ушла задачей 14 — гашение теряет различия, и
/// две разные учётные записи могли дать один ключ (см. `account`); у пути
/// потери безобиднее, потому что путь к тому же моменту назван нами самими.
///
/// `cfg(windows)` — потому что единственный зовущий, `file_lock`, тоже под
/// ним: на Linux замок проекта это `flock` на файле по пути как есть, и
/// чистить там нечего. Без этой оговорки линуксовый гейт CI падал
/// `function clean is never used` (замер 17.11) — отказ прятался за
/// `sysinfo`, починенным тем же днём.
#[cfg(windows)]
fn clean(s: &str) -> String {
    s.chars().map(|c| if c.is_ascii_alphanumeric() || c == '-' { c } else { '_' }).collect()
}

/// Ключ замка — учётная запись ТЕМ, что различает её без потерь: SID на
/// Windows, uid на Linux. Это и есть «учётная запись» из спеки, а не её
/// приблизительный пересказ.
///
/// **Чем был плох пересказ.** Прежде ключ строился как `clean(USERNAME)`:
/// всё, кроме латиницы и цифр, гасилось в `_` ради имени мьютекса. Значит
/// «Пользователь 1» и «Пользователь_1» давали ОДИН ключ — одна учётная
/// запись запирала другую, а человек читал «уже запущен» и шёл искать свой
/// процесс, которого нет. SID и uid терять нечего: у SID в записи только
/// латиница, цифры и дефис, у uid — цифры, и оба годятся и в имя канала, и в
/// имя файла как есть.
///
/// Рабочее место в ключе не участвует с задачи 6 (имя из toml человек меняет
/// на ходу — замок на него смотреть не вправе), сеанс — с задачи 14: одна
/// копия на учётную запись в пределах МАШИНЫ, сколько бы сеансов человек ни
/// открыл и сколько бы баз ни обслуживал внутри (контракт подключения:
/// несколько баз живут карточками в одном приложении, а не копиями
/// программы).
///
/// Не узнали — это отказ, а не запасной ключ: замок с общим «не знаю» в
/// ключе запирал бы разные учётные записи друг о друга, то есть делал бы
/// ровно ту беду, против которой заведён.
///
/// **Спрашивается тем же, чем продукт уже отвечает на «чей это процесс»** —
/// `holder::current_owner` (SID на Windows, десятичный uid из `/proc/<pid>`
/// на Linux). Своего способа узнать себя здесь нет и быть не должно: им
/// сверяют держателя порта (`publication`), им же дверь проверяет
/// собеседника (`door::server_is_ours`), и третий ответ на тот же вопрос
/// разошёлся бы с первыми двумя молча — ровно то, из-за чего эта задача и
/// завелась.
pub fn account() -> std::io::Result<String> {
    crate::holder::current_owner()
        .ok_or_else(|| std::io::Error::other("не удалось узнать вашу учётную запись — замок и управляющая дверь без неё не заводятся"))
}

#[cfg(windows)]
pub struct Guard(windows_sys::Win32::Foundation::HANDLE);

#[cfg(windows)]
impl Drop for Guard {
    fn drop(&mut self) {
        // SAFETY: `self.0` — дескриптор, полученный этим же `Guard` из
        // `CreateMutexW` и ещё не закрытый (второй раз `Drop` не зовут).
        unsafe { windows_sys::Win32::Foundation::CloseHandle(self.0) };
    }
}

// Дескриптор мьютекса — просто ссылка на объект ядра, переносить его между
// потоками безопасно (как и `Job` в job.rs).
#[cfg(windows)]
unsafe impl Send for Guard {}
#[cfg(windows)]
unsafe impl Sync for Guard {}

/// Приём замка ПРОЕКТА на Windows: `CreateMutexW` по имени, построенному из
/// пути (`file_lock` ниже — единственный зовущий). Замок рабочего места сюда
/// больше не ходит: он держится дверью, а признак обслуживания спрашивается
/// у неё же (задача 14).
///
/// ponytail: объект создаётся без префикса, то есть виден только в сеансе
/// создателя — два редактора в РАЗНЫХ сеансах одного человека замка проекта
/// друг у друга не увидят. Потолок известен и остался от прежнего устройства;
/// замку рабочего места он был смертелен (на нём сгорел день 15.11) и потому
/// снят переездом на дверь, а здесь ждёт своей задачи: папку проекта правят
/// с одного рабочего места, и второго сеанса у неё обычно нет.
#[cfg(windows)]
fn acquire_mutex(name: &str) -> std::io::Result<Option<Guard>> {
    use std::ffi::OsStr;
    use std::os::windows::ffi::OsStrExt;
    use windows_sys::Win32::Foundation::{CloseHandle, GetLastError, ERROR_ALREADY_EXISTS};
    use windows_sys::Win32::System::Threading::CreateMutexW;
    let wide: Vec<u16> = OsStr::new(name).encode_wide().chain(std::iter::once(0)).collect();
    // SAFETY: обычный вызов kernel32 с нуль-терминированной строкой, живущей
    // на стеке этого вызова; без атрибутов безопасности — то есть объект
    // виден только в сеансе вызывающего (потолок назван выше, довод «зато
    // отделяет пользователей» снят вместе с замком, который на нём стоял).
    let h = unsafe { CreateMutexW(std::ptr::null(), 1, wide.as_ptr()) };
    if h.is_null() {
        // Та же причина, что и у файлового замка на Linux ниже (`lock_error`):
        // голый `Permission denied (os error N)` без единого слова о том, что
        // вообще делалось, ничего человеку не говорит.
        let e = std::io::Error::last_os_error();
        return Err(std::io::Error::new(e.kind(), format!("не удалось взять замок (системный мьютекс {name}): {e}")));
    }
    // `GetLastError` — первым же следующим вызовом, до любого другого Win32
    // API: иначе он рассказал бы не про `CreateMutexW`.
    let already = unsafe { GetLastError() } == ERROR_ALREADY_EXISTS;
    if already {
        unsafe { CloseHandle(h) };
        return Ok(None);
    }
    Ok(Some(Guard(h)))
}

/// Замок проекта (`project::file_lock`) на Windows: тот же приём, что у
/// замка рабочего места — именованный мьютекс, живущий, пока жив процесс,
/// независимо от того, как он кончился. Ключ строится из пути, а не из
/// пользователя и рабочего места: файл замка и так свой на каждую папку
/// проекта (`<state>/project-<ключ>.lock`), второй ключ не добавил бы
/// ничего, а собственный префикс (`1c-connect-file-`) не даёт случайно
/// столкнуться именам из двух разных целей. Замок рабочего места имени
/// ядра себе больше не строит вовсе — он держится дверью (задача 14).
/// ponytail: ключ — путь, прогнанный через `clean`, без канонизации; два
/// разных пути, отличающихся только заменяемыми символами, теоретически
/// могли бы совпасть. Другого пути к файлу замка, кроме как из
/// `set_lock_target`, у программы нет, так что потолок не достигается.
#[cfg(windows)]
pub(crate) fn file_lock(path: &std::path::Path) -> std::io::Result<Option<Guard>> {
    acquire_mutex(&format!("1c-connect-file-{}", clean(&path.display().to_string())))
}

/// Замок живёт, пока жив дескриптор: файл здесь держат, а не читают —
/// `flock` снимается закрытием. Поэтому поле и не читается никем.
#[cfg(not(windows))]
pub struct Guard(#[allow(dead_code)] std::fs::File);

/// Оборачивает отказ открыть замок в читаемую причину: по какому пути, и
/// голый текст системной ошибки в хвосте — для диагностики, не для первого
/// взгляда. Зовущий один — `file_lock` ниже: он создаёт свой файл и пишет в
/// него, и отказ обычно значит, что каталога состояния нет (его заводит
/// `ops_host::ensure_state`) либо писать в него нечем.
#[cfg(not(windows))]
fn lock_error(path: &std::path::Path, e: std::io::Error) -> std::io::Error {
    std::io::Error::new(e.kind(), format!("не удалось взять замок: {} — файл не открылся: {e}", path.display()))
}

/// Приём замка ПРОЕКТА на Linux: советный `flock` на уже открытом
/// дескрипторе. Зовущий один — `file_lock` ниже; вторым был замок рабочего
/// места, но он держится дверью (задача 14), и файловой системы не трогает
/// вовсе.
#[cfg(not(windows))]
fn acquire_flock(file: std::fs::File) -> std::io::Result<Option<Guard>> {
    use std::os::unix::io::AsRawFd;
    // SAFETY: обычный вызов libc на дескрипторе только что открытого файла;
    // LOCK_NB не блокирует поток — занято, значит просто отказ, а не ожидание.
    let r = unsafe { libc::flock(file.as_raw_fd(), libc::LOCK_EX | libc::LOCK_NB) };
    if r == 0 {
        return Ok(Some(Guard(file)));
    }
    let err = std::io::Error::last_os_error();
    if err.raw_os_error() == Some(libc::EWOULDBLOCK) {
        Ok(None)
    } else {
        Err(err)
    }
}

/// Замок проекта (`project::file_lock`) на Linux: `flock` на файле
/// `<state>/project-<ключ>.lock` — своём, не на каталоге состояния целиком:
/// заперев им весь каталог, две папки проекта у одного человека спорили бы
/// за один замок. Файл создаём, если его ещё нет: каталог состояния
/// гарантирован `ops_host::ensure_state`, а этот файл — нет, его первым
/// создаёт первый же процесс, который взял замок.
#[cfg(not(windows))]
pub(crate) fn file_lock(path: &std::path::Path) -> std::io::Result<Option<Guard>> {
    let file =
        std::fs::OpenOptions::new().create(true).truncate(false).read(true).write(true).open(path).map_err(|e| lock_error(path, e))?;
    acquire_flock(file)
}

/// Имя события «покажи окно» — единственное место, где оно строится (тот же довод, что у `door::door_name`: вторая формулировка имени смотрела бы не на тот объект ядра). Ключ тот же, что у замка: просят ровно ту копию, которая этот замок и держит.
#[cfg(windows)]
fn show_event_name(key: &str) -> String {
    format!("1c-connect-show-{key}")
}

/// Нуль-терминированная широкая строка — её хочет каждый именованный объект ядра здесь. `pub(crate)`: того же требуют права управляющей двери (`door::Rights`, SDDL строкой), а второй такой же перевод рядом был бы ровно «две меры на один вопрос».
#[cfg(windows)]
pub(crate) fn wide(s: &str) -> Vec<u16> {
    use std::os::windows::ffi::OsStrExt;
    std::ffi::OsStr::new(s).encode_wide().chain(std::iter::once(0)).collect()
}

/// Попросить первую копию показать своё окно: `true` — просьба принята (событие есть, сигнал послан), `false` — принять её некому.
///
/// **Почему просьба, а не подъём чужого окна своими руками.** До этой правки вторая копия искала окно первой сама: `EnumWindows`, первое попавшееся верхнеуровневое окно процесса с тем же образом, `ShowWindow(SW_RESTORE)`. Замер 10.11 на релизной сборке: верхнеуровневых окон у процесса ЧЕТЫРЕ, и когда флайаут закрыт — а это обычное состояние программы, живущей значком в трее, — настоящего окна среди них нет вовсе, зато первым перечисление отдаёт скрытое служебное окно библиотеки значка (класс `tray_icon_app`, 1920x1010). `ShowWindow` делал его видимым: человек, запустивший программу второй раз, получал чёрный прямоугольник во весь экран вместо окна, а вторая копия уходила через `exit(0)`, считая, что окно показала.
///
/// Угадывать чужое окно нечем и не нужно: нарисовать его умеет только GPUI внутри первой копии, значит просить надо ПРОГРАММУ, а не Windows, — и поднимает она его тем же путём (`gui::window::show_window`), которым поднимает по щелчку значка.
///
/// `OpenEventW`, а не `CreateEventW`: события нет — значит просьбу никто не слушает (`serve_show_requests` не заведена: голова `serve`/`connect`, сборка без окна; либо первая копия в ЧУЖОМ сеансе — там событие есть, но нам его не видно), и честный отказ словами лучше молчаливого выхода в никуда. Последний случай получает к отказу ещё и объяснение, почему окна не видно (`other_session_words`).
#[cfg(windows)]
fn request_show(key: &str) -> bool {
    use windows_sys::Win32::Foundation::CloseHandle;
    use windows_sys::Win32::System::Threading::{OpenEventW, SetEvent, EVENT_MODIFY_STATE};
    let name = wide(&show_event_name(key));
    // SAFETY: обычный вызов kernel32 с нуль-терминированной строкой, живущей на стеке этого вызова.
    let h = unsafe { OpenEventW(EVENT_MODIFY_STATE, 0, name.as_ptr()) };
    if h.is_null() {
        return false;
    }
    // SAFETY: `h` только что получен от `OpenEventW` и ещё не закрыт.
    let ok = unsafe { SetEvent(h) };
    unsafe { CloseHandle(h) };
    ok != 0
}

/// Принимать просьбы «покажи окно» от вторых копий — свой поток на всё время работы, `show` зовётся на каждую просьбу. `false` — событие не завелось, и вторая копия тогда честно откажет словами, а не промолчит.
///
/// Событие с АВТОСБРОСОМ (`manual_reset = 0`): сигнал снимает сам ждущий, и две просьбы подряд дают два показа, а не один залипший навсегда.
///
/// Дескриптор заводится ЗДЕСЬ, до возврата, а не внутри потока: иначе просьба, пришедшая в ту долю секунды, пока поток ещё не завёл событие, пришла бы в пустоту — и человек прочёл бы отказ там, где должно было открыться окно. В поток он уезжает `Guard`-ом — тем же, что носит дескриптор замка, и ровно затем, что `Guard` `Send` и закрывает дескриптор за собой.
///
/// Полностью эту щель заводом здесь не закрыть: замок берётся раньше, чем строится значок (`gui::tray::build` — единственный зовущий), и вторая копия, запущенная между ними, получит честный отказ словами. Это и есть верный исход: окна в этот миг нет ни у кого, показывать нечего.
#[cfg(windows)]
pub fn serve_show_requests(show: impl Fn() + Send + 'static) -> bool {
    match account() {
        Ok(key) => serve_show_requests_with(&key, show),
        // Учётную запись не узнали — но сюда мы и не дошли бы: тем же вопросом её спрашивает замок (`acquire`), и его отказ приходит раньше. Молчать всё равно нельзя, а просьбы принимать нечем.
        Err(e) => {
            eprintln!("просьбы «покажи окно» от второй копии приниматься не будут: {e}");
            false
        }
    }
}

/// То же, но ключ даёт вызывающий — им проверяется тест: на машине может идти настоящая копия, и тест, занявший её имя события, отнимал бы у неё приём просьб.
#[cfg(windows)]
fn serve_show_requests_with(key: &str, show: impl Fn() + Send + 'static) -> bool {
    use windows_sys::Win32::Foundation::WAIT_OBJECT_0;
    use windows_sys::Win32::System::Threading::{CreateEventW, WaitForSingleObject, INFINITE};
    let name = show_event_name(key);
    let w = wide(&name);
    // SAFETY: обычный вызов kernel32 с нуль-терминированной строкой на стеке; без атрибутов безопасности — именованный объект виден только в сеансе вызывающего (замок рабочего места на этом и сгорел 15.11 и потому держится дверью — задача 14; у просьбы это осталось, и ровно поэтому вторая копия из чужого сеанса получает слова, а не окно).
    let h = unsafe { CreateEventW(std::ptr::null(), 0, 0, w.as_ptr()) };
    if h.is_null() {
        eprintln!(
            "просьбы «покажи окно» от второй копии приниматься не будут: событие {name} не заведено — {}",
            std::io::Error::last_os_error()
        );
        return false;
    }
    let guard = Guard(h);
    std::thread::spawn(move || {
        // Замыкание обязано утащить `Guard` ЦЕЛИКОМ, а не поле `guard.0`: захват по частям (edition 2021) взял бы голый дескриптор, который не `Send` сам по себе, — `Send` обещан именно обёртке. Эта строка и есть то обещание, иначе сборка отказывает.
        let guard = guard;
        loop {
            // SAFETY: дескриптор жив всё время потока — его держит `guard`, переехавший сюда вместе с замыканием.
            if unsafe { WaitForSingleObject(guard.0, INFINITE) } != WAIT_OBJECT_0 {
                return;
            }
            show();
        }
    });
    true
}

