# Каталоги системных программ в пути рабочего места.
#
# Debian отдаёт /usr/sbin и /sbin только root (см. /etc/profile и ENV_PATH в
# /etc/login.defs): у dev<N> путь /usr/local/bin:/usr/bin:/bin и две игровые
# папки. Для обычной многопользовательской машины это разумно — там рядовой
# пользователь админом не является. Здесь не так: каждое рабочее место стенда
# само себе администратор, с sudo без пароля, и системные программы ему нужны
# ровно так же, как root.
#
# Что ломалось без этого: apache2 лежит в /usr/sbin, 1c-connect зовёт его по
# имени из $PATH — и публикация базы при входе по RDP не поднималась, хотя
# пакет стоял. Отдельно в образе есть ссылка /usr/local/bin/apache2: она не
# лишняя, потому что от путей сеанса программа зависеть не должна вовсе.
# Этот файл — про человека в терминале, которому нужны ещё и usermod, ss,
# a2enmod и всё остальное из sbin.
#
# Файл читается из /etc/profile (он перебирает /etc/profile.d/*.sh после того,
# как сам выставил PATH). Сессия RDP приходит сюда через /etc/xrdp/startwm.sh,
# который /etc/profile тоже читает, а zsh в терминале наследует путь от неё:
# свой /etc/profile zsh на Debian не читает (/etc/zsh/zprofile пуст).

case ":$PATH:" in
    *:/usr/sbin:*) ;;
    *) PATH="$PATH:/usr/local/sbin:/usr/sbin:/sbin"; export PATH ;;
esac
