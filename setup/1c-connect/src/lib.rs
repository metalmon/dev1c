/// Предмет, который включает выключатель, — одним словом на все поверхности: трей, карточка, журнал, подсказки, имена фактов, проверки готовности (`verify`). Сокращения «MCP» на экране больше нет: у 1С-разработчика оно ещё отзовётся, у бухгалтера — нет (находка 12 осмотра 10.11). И это именно ПРЕДМЕТ, а не объяснение отказа: подпись у выключателя обязана называть то, что включается, а причина живёт в подсказке и в журнале (находка 13).
///
/// **Почему в корне, а не в окне.** Это слово ПРОДУКТА, а не слово экрана: теми же знаками его пишет `verify` — код, который работает и в сборке без окна. Пока константа жила в `gui`, бек повторял её литералом, и сходились две записи только потому, что пока совпадали. Две меры на один вопрос — главный разряд дефектов этого дерева; здесь мера одна, и видят её обе стороны.
///
/// Сокращение остаётся во внутренних именах кода (`EDITOR_MCP`, `mcp_exe`, `mcp-1c`) — там оно точнее любого перевода и человеку не показывается.
pub const SUBJECT: &str = "доступ к 1С";

/// Сколько ждём, пока работа опустится сама, на любом выходе: сеанс, прощание зачисленным сторонам, потоки щелчка по агенту.
///
/// **Почему в корне, а не в окне.** Выход бывает не только из окна: Ctrl+C у `connect`/`serve` — тот же выход, и ждёт он того же
/// (`main.rs::say_goodbye`). Пока число жило в `gui`, сборка без окна повторила бы его литералом — две меры на один вопрос. Срок
/// конечен нарочно: застрявшее прощание или зависший `stop` не должны держать выход навсегда.
///
/// Это срок ВЫХОДА и только его. Другие ожидания в программе носят свои имена, даже когда число у них совпадает:
/// `publication::PORT_FREE_WAIT` — пока прежний веб-сервер отпустит порт, `publication::START_WAIT` — пока поднятый отзовётся.
pub const STOP_WAIT: std::time::Duration = std::time::Duration::from_secs(5);
