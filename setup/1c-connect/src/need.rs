//! Чего не хватает, чтобы сделать. Одна мера заполненности полей на весь продукт.
//!
//! Основание — спека «Все сочетания соединения» (`docs/superpowers/specs/connection-combinations.md`): пять сочетаний осей «это соединение»
//! × «где база», состав полей каждого и обязательное по каждому действию. Своей таблицы сочетаний этот модуль НЕ держит и держать не
//! вправе: он берёт нужное действию и пересекает с тем, что в сочетании показано (`shown_fields`). Закон оттуда одной строкой:
//! **обязательным может быть только то, что показано** — поля, которого человеку не показывают, требовать нельзя никогда.
//!
//! Правило выведено из путей человека (спека «Пути человека», раздел «Что из этого следует для проверки заполненности») и звучит так:
//! **обязательность принадлежит ДЕЙСТВИЮ, а не полю**. Поле не бывает обязательным само по себе — оно обязательно для того, что человек
//! собирается сделать. Поэтому здесь нет списка «обязательные поля карточки»: есть `Deed` и ответ на вопрос «что мешает именно ему».
//!
//! Решение выражено ТИПОМ нарочно (приём этой ветки, сработал семь раз): ответ `Field` — не строка причины, а само поле формы, и
//! подсветить то, чего в форме нет, становится невыразимо. Строка причины годится подсказке и журналу, но не годится подсветке — именно
//! из-за неё `gate::cold_gate` не мог служить валидатором, хотя проверял то же самое.
//!
//! Модуль не за фичей `gui`: условия не зависят от окна, а подкоманде `1c-connect mcp` (`ops_host::run_mcp`) нужны ровно те же — тот самый
//! довод, по которому вынесен из `gui` и `gate`.
//!
//! Функции чистые: ни сети, ни диска. Существование каталога базы здесь не спрашивается вовсе — это не заполненность, а факт
//! (`verify::base_fact`), и ходить за ним на диск с главного потока окна нельзя (таймаут SMB, довод `gate::wants_directory`).

use crate::cfg;
use crate::cfg::Connection;

/// Поле карточки, без которого действие не делается.
///
/// Имя (`Field::key`) — ТО ЖЕ, каким поле зовут форма и запись (`panel::field_value`, `panel::field_states`, `panel::shown_fields`): иначе
/// подсветке нечего искать, а у состава формы завелось бы второе мнение.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Field {
    /// «База» — путь к базе 1С.
    BasePath,
    /// «Пользователь базы».
    DbUser,
    /// «Адрес публикации» — только у чужой публикации.
    BaseUrl,
    /// «Папка документов».
    Project,
}

impl Field {
    /// Ключ поля — то же имя, которым поле зовут форма и запись.
    pub fn key(self) -> &'static str {
        match self {
            Field::BasePath => "base_path",
            Field::DbUser => "db_user",
            Field::BaseUrl => "base_url",
            Field::Project => "project",
        }
    }

    /// Пусто ли это поле у карточки. Для «Пользователя базы» — та же мера, что у факта проверки (`verify::db_user_is_set`).
    ///
    /// **Известное расхождение, которое здесь НЕ лечится.** Адрес публикации, совпавший с нашей догадкой от каталога базы, окно
    /// показывает пустым (`panel::shown_base_url`), а эта мера считает заполненным. То есть человек может ВПИСАТЬ адрес, увидеть поле
    /// пустым и не понять, почему замок открыт. Лечить это надо со стороны показа — поле не вправе прятать то, что человек набрал, —
    /// а не здесь: сочти мы такой адрес пустым, запертой оказалась бы карточка с честно вписанным адресом. Долг записан в спеке
    /// сочетаний.
    pub fn empty_in(self, c: &Connection) -> bool {
        match self {
            Field::BasePath => c.base_path.trim().is_empty(),
            Field::DbUser => !crate::verify::db_user_is_set(&c.db_user),
            Field::BaseUrl => c.base_url.trim().is_empty(),
            Field::Project => c.project.trim().is_empty(),
        }
    }

    /// Чего не хватает — словами человека, без имён полей файла настроек.
    ///
    /// Говорит про ПРЕДМЕТ («не указана база»), а не про поле («base_path пустой») и не про себя («поле не заполнено»): человеку важно,
    /// чего недостаёт делу, а не какой орган окна пуст.
    pub fn said(self) -> &'static str {
        match self {
            Field::BasePath => "не указана база",
            Field::DbUser => "не указан пользователь базы",
            Field::BaseUrl => "не указан адрес публикации",
            Field::Project => "не указана папка документов",
        }
    }
}

/// Что человек собирается сделать.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Deed {
    /// Включить обслуживание: агент работает с базой.
    Serve,
    /// Выдать код, по которому подключится другая сторона.
    IssueCode,
    /// Подключиться по коду, выданному другой стороной.
    Connect,
    /// Выгрузить из 1С в папку документов.
    Dump,
    /// Загрузить в 1С из папки документов.
    Load,
    /// Поставить расширение в базу или снять его оттуда.
    ///
    /// Одно дело на два действия, а не два имени для одних требований: и установка, и снятие зовут Конфигуратор ключом базы
    /// (`ops_host::ib_switch`), и больше им от карточки ничего не нужно. Два дела с одинаковым `wanted` разошлись бы при первой же
    /// правке — ровно тот разряд, которым это дерево и болеет.
    ///
    /// Пользователя базы здесь нет нарочно: без пути Конфигуратор получает `/F` и ПУСТОТУ вместо базы (замер чтением,
    /// `Extension::apply`), то есть программа сама подставляет бессмыслицу. Нужен ли вход под кем-то — решает платформа на этой
    /// базе, и об этом она говорит своими словами; выдумывать за неё требование мы не станем.
    Extension,
}

/// Что нужно самому ДЕЙСТВИЮ, без оглядки на сочетание. Пересечение с показанным делает `missing`.
fn wanted(deed: Deed) -> &'static [Field] {
    match deed {
        // Работа с базой: где она, под кем входить и по какому адресу её спрашивать, если публикуем не мы.
        Deed::Serve => &[Field::BasePath, Field::DbUser, Field::BaseUrl],
        // **Выдача кода не требует НИЧЕГО** — решение владельца 1.11, записанное в замысле интерфейса дословно: «код следует из первого
        // ответа сам». Код — знакомство двух машин, и только: он говорит «это я, и я тебя жду». Человек выдаёт его и уносит в мессенджер
        // РАНЬШЕ, чем садится заполнять поля, — сперва договорились, потом настроили, и запертая выдача не дала бы даже начать разговор.
        // База с него спросится, если она у него есть, но на другом шаге — когда он включает доступ к 1С (`Deed::Serve`).
        Deed::IssueCode => &[],
        // Код живёт в поле экрана, а не в настройках карточки: его заполненность смотрит тот, кто его читает, той же мерой «пусто или
        // нет». Карточке для подключения по коду не нужно ничего — база на той стороне.
        Deed::Connect => &[],
        Deed::Dump | Deed::Load => &[Field::BasePath, Field::Project],
        // Расширение ставится В базу: без её пути звать Конфигуратор нечем.
        Deed::Extension => &[Field::BasePath],
    }
}

/// Чего не хватает действию у ЭТОЙ карточки. Пусто — можно делать.
///
/// **Своей таблицы сочетаний здесь нет и быть не может.** Состав полей сочетания посчитан один раз (`cfg::shown_fields`, оси замысла
/// 1.11: «это соединение» × «где база» × «кто публикует»), и мера заполненности его только ПЕРЕСЕКАЕТ с тем, что нужно действию.
/// Отсюда закон спеки сочетаний: **обязательным может быть только то, что показано.** Именно его нарушение годами держало замок на
/// карточке, которой полей базы не показывают.
///
/// Спрашивается у КАРТОЧКИ, а не у текущего соединения: поля правятся у любой карточки (решение владельца 10.11), и мера, умеющая
/// отвечать только про текущую, снова развела бы два закона на одном экране.
///
/// Порядок ответа — порядок показа полей: подсветка ставит курсор в первое поле списка, и человек идёт по карточке сверху вниз.
pub fn missing(deed: Deed, c: &Connection) -> Vec<Field> {
    let shown = cfg::shown_fields(c);
    let mut out: Vec<Field> = wanted(deed).iter().copied().filter(|f| shown.contains(&f.key()) && f.empty_in(c)).collect();
    out.sort_by_key(|f| shown.iter().position(|k| *k == f.key()));
    out
}

/// Чего не хватает — одной строкой для подсказки кнопки и строки журнала. `None` — можно делать.
///
/// Одна дорога к словам на все поверхности: подсказка кнопки, подсветка и журнал берут их здесь и не формулируют своими словами.
pub fn said(deed: Deed, c: &Connection) -> Option<String> {
    let m = missing(deed, c);
    if m.is_empty() {
        return None;
    }
    Some(m.iter().map(|f| f.said()).collect::<Vec<_>>().join(", "))
}

/// Отказ ДЕЛУ, которому не хватает полей, — одной строкой на все поверхности, где дело начинается без окна рядом: набранная
/// команда и работа по кнопке. `None` — можно делать.
///
/// Зачем сверх `said`. `said` годится подсказке кнопки, которая висит у поля и ничего человеку не велит; а команде и работе нужно
/// сказать, что делать дальше, — и сказать ОДНИМИ словами на обеих поверхностях. Второй суффикс «заполните и повторите», написанный
/// на месте, развёл бы один отказ на два текста (Important ревью целого 24.11: мера была, а спрашивали её три дела из пяти, и
/// каждое отказывало бы по-своему).
///
/// Имени поля настроек в словах нет и быть не может — закон окна, раздел «Журнал»: человеку называют ПРЕДМЕТ (`Field::said`), а
/// место, где его заполняют, — карточку соединения.
pub fn refusal(deed: Deed, c: &Connection) -> Option<String> {
    said(deed, c).map(|what| format!("{what} — заполните это в настройках соединения и повторите"))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn card() -> Connection {
        crate::cfg::filled_for_test().current().clone()
    }

    #[test]
    fn a_filled_card_needs_nothing() {
        let c = card();
        for d in [Deed::Serve, Deed::IssueCode, Deed::Connect, Deed::Dump, Deed::Load, Deed::Extension] {
            assert_eq!(missing(d, &c), Vec::new(), "{d:?}");
        }
    }

    /// Обязательность принадлежит действию: одно и то же пустое поле мешает одному делу и не мешает другому.
    #[test]
    fn the_same_empty_field_stops_one_deed_and_not_another() {
        let mut c = card();
        c.project = String::new();
        assert_eq!(missing(Deed::Dump, &c), vec![Field::Project]);
        assert_eq!(missing(Deed::Serve, &c), Vec::new());
    }

    /// У карточки, которая зовёт чужую базу, путь к базе не спрашивается вовсе — заполнять его нечем.
    #[test]
    fn a_card_calling_a_base_elsewhere_is_not_asked_for_a_path() {
        let mut c = card();
        c.base_here = false;
        c.mode = "tunnel".into();
        c.base_path = String::new();
        c.db_user = String::new();
        assert_eq!(missing(Deed::Serve, &c), Vec::new());
        assert_eq!(missing(Deed::Connect, &c), Vec::new());
    }

    /// Решение владельца 1.11, закреплённое тестом, потому что я уже один раз его нарушил: **выдача кода не требует ничего**. Человек
    /// договаривается с той стороной РАНЬШЕ, чем заполняет поля, и запертая выдача не дала бы ему даже начать.
    #[test]
    fn issuing_a_code_asks_for_nothing_at_all() {
        let mut c = card();
        c.base_path = String::new();
        c.db_user = String::new();
        c.db_password = String::new();
        c.project = String::new();
        c.base_url = String::new();
        c.publication = "webserver".into();
        assert_eq!(missing(Deed::IssueCode, &c), Vec::new(), "код выдаётся до того, как заполнены поля, — так решено 1.11");
    }

    /// Адрес публикации обязателен только чужой публикации.
    #[test]
    fn only_a_foreign_publication_wants_an_address() {
        let mut c = card();
        c.base_url = String::new();
        c.publication = "auto".into();
        assert_eq!(missing(Deed::Serve, &c), Vec::new());
        c.publication = "webserver".into();
        assert_eq!(missing(Deed::Serve, &c), vec![Field::BaseUrl]);
    }

    /// **У каждого дела есть, кто его спрашивает** — и это проверяется списком, потому что молчанием оно уже один раз и
    /// завелось: `Deed::Dump` и `Deed::Load` простояли без единого потребителя в продукте (Important ревью целого 24.11), а мера
    /// при этом была зелёной — её звали только тесты.
    ///
    /// Сторож текстовый нарочно: «кто спрашивает» — это факт ДЕРЕВА, а не значение, и ни один тип его не держит. Порог каждого
    /// дела назван здесь по имени, и новое дело без порога краснеет на первом же прогоне.
    #[test]
    fn every_deed_has_someone_who_asks_it() {
        let asked: Vec<(&str, &str, &str)> = vec![
            ("Deed::Serve", "gate.rs", include_str!("gate.rs")),
            ("Deed::IssueCode", "gui/panel.rs", include_str!("gui/panel.rs")),
            ("Deed::Connect", "gui/panel.rs", include_str!("gui/panel.rs")),
            ("Deed::Dump", "flow.rs", include_str!("flow.rs")),
            ("Deed::Load", "flow.rs", include_str!("flow.rs")),
            ("Deed::Extension", "ops_host.rs", include_str!("ops_host.rs")),
        ];
        for (deed, who, src) in asked {
            // Зов в ПРОДУКТЕ, а не в тесте: тело файла до его `mod tests`. Резать по `#[cfg(test)]` нельзя — им помечены и
            // одиночные подмены внутри продукта (`ops_host` и `node` так разводят хранилище секретов), и срез кончался бы на первой
            // из них, далеко до настоящих зовов. Красный прогон это и сказал: `Deed::Extension` «никто не спрашивает» при живом зове.
            let product = src.split_once("mod tests {").map_or(src, |(before, _)| before);
            assert!(product.contains(deed), "{deed} никто не спрашивает в {who} — мера есть, а дела у неё нет");
        }
    }

    /// Порядок — порядок решений человека: база раньше того, что про неё спрашивают, потому что курсор уедет в первое поле списка.
    #[test]
    fn the_base_comes_before_what_is_asked_about_it() {
        let mut c = card();
        c.base_path = String::new();
        c.db_user = String::new();
        c.publication = "webserver".into();
        c.base_url = String::new();
        assert_eq!(missing(Deed::Serve, &c), vec![Field::BasePath, Field::DbUser, Field::BaseUrl]);
    }
}
