    #[test]
    fn a_talk_whose_permission_is_already_gone_is_not_held() {
        assert!(keep_holding(Some(true)), "разрешение на месте — держим");
        assert!(!keep_holding(Some(false)), "разрешение сняли в щель — не держим");
        // «Не знаю» на вопросе о допуске значит «нет»: неопознанную карточку
        // `enrolled_to` спросить нечем.
        assert!(!keep_holding(None));
    }

    /// Книга живых разговоров: разложены по СТОРОНЕ, снимаются по своему
    /// номеру, и отзыв уносит их с учёта — второй отзыв резать уже нечего.
    ///
    /// Прежний тест с этим именем `Live` не трогал вовсе: он брал список имён,
    /// сам звал `cut_these` и сам же повторял у себя удаление с конца. То
    /// есть проверял КОПИЮ решения, а не решение — и подмена в самой книге
    /// оставляла его зелёным. Здесь поднимаются два настоящих узла: вожжи
    /// иначе не завести, за ними задача письма в рантайме.
    #[tokio::test]
    async fn the_live_book_keeps_talks_under_the_party_not_the_card() {
        use crate::channel::{reins, Channels};
        use crate::node::Node;
        use crate::wire::{Frame, Msg};
        use iroh::EndpointAddr;
        use std::net::{Ipv4Addr, SocketAddr};
        use std::time::Duration;

        let dir = |name: &str| {
            let d = std::env::temp_dir().join(format!("peer-live-{name}-{}", std::process::id()));
            let _ = std::fs::remove_dir_all(&d);
            std::fs::create_dir_all(&d).unwrap();
            d
        };
        let (da, db) = (dir("a"), dir("b"));
        let caller = Node::start(&da).await.unwrap();
        let base = Node::start(&db).await.unwrap();
        // Звонок по петле, а не по адресу в локальной сети: иначе тест
        // проверял бы брандмауэр Windows (тот же довод, что в `channel.rs`).
        let port = base
            .endpoint()
            .bound_sockets()
            .into_iter()
            .find_map(|s| if s.is_ipv4() { Some(s.port()) } else { None })
            .expect("узел обязан был занять порт IPv4");
        let to = EndpointAddr::new(base.id()).with_ip_addr(SocketAddr::new(Ipv4Addr::LOCALHOST.into(), port));

        // Та сторона принимает три управляющих потока — по одному на карточку.
        let (listening, there) = (base.clone(), Channels::default());
        let answered = tokio::spawn(async move {
            let conn = listening.accept().await.unwrap().unwrap();
            let channel = there.keep(conn);
            let mut got = Vec::new();
            for _ in 0..3 {
                got.push(channel.answer().await.unwrap());
            }
            (channel, got)
        });
        let channel = tokio::time::timeout(Duration::from_secs(20), Channels::default().to(&caller, to))
            .await
            .expect("дозвон не уложился в срок")
            .unwrap();
        let mut ours = Vec::new();
        for _ in 0..3 {
            let mut c = channel.call().await.unwrap();
            // Поток, в который не написали, та сторона не увидит вовсе — QUIC
            // заводит его на первом байте.
            Frame::write(c.says(), &Msg::EnrollWait).await.unwrap();
            ours.push(c);
        }
        let (_their_channel, got) =
            tokio::time::timeout(Duration::from_secs(20), answered).await.expect("та сторона не приняла три потока в срок").unwrap();

        // Три живых разговора ОДНОЙ стороны: две названные карточки и один
        // безымянный — тот, чью карточку сопоставить не удалось.
        let live = super::Live::default();
        let peer = caller.id();
        let mut ids = Vec::new();
        let mut ears = Vec::new();
        for (control, card) in got.into_iter().zip([Some("Ромашка"), None, Some("Василёк")]) {
            let (held, ear) = reins(control);
            ears.push(ear);
            ids.push(live.remember(peer, card.map(CardId::from), held));
        }
        assert!(ids.iter().all(|id| live.alive(peer, *id)), "все три на учёте");

        // Отзыв по СОСЕДНЕЙ стороне не трогает ничего: ключ стороны подделать
        // нельзя, его доказал сам iroh.
        assert!(live.cut(base.id(), &"Ромашка".into()).is_empty(), "отзыв у соседней стороны режет её разговоры, не наши");
        assert!(ids.iter().all(|id| live.alive(peer, *id)));

        // Отзыв «Ромашки» режет её разговор и безымянный — и уносит оба с
        // учёта: второй отзыв той же карточки резать уже нечего.
        assert_eq!(live.cut(peer, &"Ромашка".into()).len(), 2, "своя карточка и безымянный");
        assert!(!live.alive(peer, ids[0]) && !live.alive(peer, ids[1]), "снятые ушли с учёта");
        assert!(live.alive(peer, ids[2]), "сосед той же стороны остался цел");
        assert!(live.cut(peer, &"Ромашка".into()).is_empty(), "второй отзыв резать нечего");

        // Присмотр кончился — разговор снимается по СВОЕМУ номеру, и дважды
        // не снимается.
        assert!(live.forget(peer, ids[2]).is_some());
        assert!(live.forget(peer, ids[2]).is_none(), "уже снятого здесь нет, и это не беда");
        assert!(live.drain().is_empty(), "книга опустела вместе с последним разговором");

        // Свои половины потоков роняем раньше узлов: их `Drop` досылает
        // написанное, а дослать его в уже закрытый узел нечем.
        drop(ours);
        caller.close().await;
        base.close().await;
    }

    /// Код предъявляется ОДИН раз, и дальше карточка звонит возвратом, называя
    /// себя.
    ///
    /// Обе половины решения зовущей стороны — чем звонить и что остаётся на
    /// руках — не были покрыты ничем, а ошибиться в них есть чем: второй круг
    /// с тем же кодом получает «код не найден», то есть переподключение
    /// кончается на первом же обрыве, а недозвон, съевший код, оставляет
    /// человека без второй попытки.
    #[test]
    fn a_card_presents_its_code_once_and_names_itself_from_then_on() {
        use crate::channel::{Gone, Round};
        use crate::enroll::Call;
        use crate::wire::{code, Refuse};

        let mut hand = super::InHand { code: " КОД ".into(), card: None };
        assert_eq!(hand.call(), Call::Enroll("КОД"), "код на руках — заявка, и без краёв строки");

        // Круг дошёл до «подключено» и оборвался; та сторона успела назвать
        // карточку.
        assert!(hand.after(&Round::Held(Gone::Broken(Refuse::new(code::BROKEN, "обрыв"))), Some("b1".into())));
        let b1 = CardId::from("b1");
        assert_eq!(hand.call(), Call::Return(Some(&b1)), "дальше возврат называет карточку: код одноразовый");

        // Недозвон до зачисления код НЕ расходует: предъявить его не успели, и
        // карточка остаётся «подключается», а не «подключается снова».
        let mut fresh = super::InHand { code: "КОД".into(), card: None };
        assert!(!fresh.after(&Round::Failed("не дозвонились".into()), None), "до зачисления это «подключается», а не «снова»");
        assert_eq!(fresh.call(), Call::Enroll("КОД"), "недозвон код не расходует");

        // А карточка, которой кода не давали и чья карточка не названа, идёт
        // возвратом без имени — так выглядит первый круг после перезапуска.
        assert_eq!(super::InHand::default().call(), Call::Return(None));
    }

    /// Куда звонить этой карточкой — по вставленному коду либо по
    /// запомненному партнёру, а без того и другого словами, а не молчаливым
    /// бездействием кнопки.
    ///
    /// Продуктовая развилка звонка не была покрыта ничем, а ошибиться в ней
    /// есть чем: пустой код без партнёра — это разговор с человеком, а не
    /// беда программы.
    #[test]
    fn where_to_dial_comes_from_the_code_or_from_the_remembered_partner() {
        use crate::enrolled::{Partner, Partners};
        use crate::ticket::Ticket;
        let them = iroh::SecretKey::generate().public();
        let dir = std::env::temp_dir().join(format!("peer-target-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let kit = super::Kit::at(dir.clone());

        // Ни кода, ни партнёра: подключаться действительно некуда, и это
        // сказано словами с советом.
        let (romashka, vasilek) = (CardId::from("Ромашка"), CardId::from("Василёк"));
        let no = super::target(&kit, &romashka, "").expect_err("без кода и без партнёра звонить некуда");
        assert!(no.contains("Вставьте код"), "человеку сказано, что сделать: {no}");

        // Код на руках — звоним по нему, и ключ берётся из него же.
        let ticket = Ticket::issue(them, Some("https://relay.example/".into()), vec!["10.0.0.1:1234".parse().unwrap()]).unwrap();
        let addr = super::target(&kit, &romashka, &ticket.to_code()).expect("по коду звонить есть куда");
        assert_eq!(addr.id, them, "ключ той стороны — из кода, а не выдуманный");

        // Кода нет, зато партнёр записан: так выглядит возврат после
        // перезапуска, и подсказки адресов берутся из записи.
        Partners::open(kit.state())
            .unwrap()
            .remember(
                &"Ромашка".into(),
                &Partner { key: them, relay: Some("https://relay.example/".into()), direct: vec!["10.0.0.2:4321".into()] },
            )
            .unwrap();
        let addr = super::target(&kit, &romashka, "").expect("партнёр записан — звонить есть куда");
        assert_eq!(addr.id, them);
        assert!(addr.ip_addrs().any(|a| a.to_string() == "10.0.0.2:4321"), "подсказки адресов берутся из записи о партнёре");
        // А у СОСЕДНЕЙ карточки партнёра нет, и ей по-прежнему говорят
        // словами: запись принадлежит карточке, а не машине.
        assert!(super::target(&kit, &vasilek, "").is_err(), "запись о партнёре принадлежит карточке, а не машине");

        // И карточка, о которой договорились, переживает перезапуск: её
        // признак пишется вместе с партнёром и читается обратно.
        assert_eq!(super::known_card(&kit, &romashka), None, "пока не договаривались — не знаем, и выдумывать нельзя");
        let (tx, _rx) = futures::channel::mpsc::unbounded();
        let addr = iroh::EndpointAddr::new(them);
        super::remember(&kit, &tx, &romashka, them, &addr, Some(&CardId::from("b1")));
        assert_eq!(super::known_card(&kit, &romashka), Some("b1".into()), "признак базы обязан пережить перезапуск");
        assert_eq!(super::known_card(&kit, &vasilek), None, "признак принадлежит карточке, а не машине");

        let _ = std::fs::remove_dir_all(&dir);
    }

    /// «Выход» не держится прощанием, когда прощаться не с кем.
    ///
    /// Потока узла может не быть вовсе — его не подняли (нет сети, не открылся
    /// ключ) или он кончился. Приказ тогда никуда не уходит, ответа не будет
    /// НИКОГДА, и выход, который ждёт ответа по сроку, стоил бы человеку
    /// полного срока ожидания на каждом закрытии программы. Поэтому мёртвый
    /// канал приказов — это успех: прощаться не с кем.
    #[test]
    fn quitting_is_not_held_by_a_farewell_to_nobody() {
        let (cmd, rx) = tokio::sync::mpsc::unbounded_channel();
        // Поток узла кончился: получателя приказов больше нет.
        drop(rx);
        let peer = super::Peer { cmd, reach: std::sync::Arc::new(std::sync::Mutex::new(None)) };
        let wait = std::time::Duration::from_secs(5);
        let started = std::time::Instant::now();
        assert!(peer.bye_all(wait), "прощаться не с кем — это успех, а не отказ");
        assert!(started.elapsed() < wait / 2, "выход обязан вернуться сразу, а не выстоять срок впустую");
    }

    /// Только что заведённая принимающая карточка обязана быть видна приёмной
    /// стороне.
    ///
    /// Падало так: `cards_of` читала настройки СТРОГО (`load` с `validate`), а
    /// окно — терпимо. Карточка, заведённая в окне минуту назад, полузаполнена
    /// всегда (`mode = "tunnel"`, адрес среды и рабочее место пусты), строгое
    /// чтение отвергало весь файл — и приёмная сторона отвечала той машине
    /// «карточку удалили» про карточку, которая лежит на диске и по которой
    /// окно только что выдало код. Живая проверка двумя машинами 9.11: путь не
    /// проходился вовсе, диалог с отпечатком не показывался ни разу.
    ///
    /// Текст ниже — буква в букву то, что окно пишет на диск при ответе
    /// «Принимаю подключения».
    #[test]
    fn a_half_filled_accepting_card_is_still_seen_by_the_peer() {
        use crate::cfg::Cfg;
        use crate::secrets;
        let text = "current = \"\"\n\n[[connection]]\nname = \"Соединение 1\"\nserver = \"\"\ngitea = \"\"\npassword = \"\"\n\
                    workstation = \"\"\nmode = \"tunnel\"\nbase_path = \"\"\nbase_here = true\nrole = \"accept\"\n";
        let dir = std::env::temp_dir().join(format!("peer-cards-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join(crate::cfg::FILE), text).unwrap();
        let kit = super::Kit::at(dir.clone());
        // Подложка секретов — файловая: DPAPI из тестов не зовём (спека).
        let store = secrets::Store::file(&dir);

        // Первая половина проверки: строгое чтение этот файл ОТВЕРГАЕТ. Без
        // неё правка «читать терпимо» стерегла бы пустоту — файл мог бы
        // проходить обе меры одинаково, и тест был бы зелен сам по себе.
        assert!(Cfg::load_with(&kit, &store).is_err(), "строгое чтение обязано отвергать полузаполненную карточку");

        // Вторая: приёмная сторона видит ровно одну принимающую карточку —
        // ту самую, по имени. Спрашивается та самая функция, которая читает
        // диск на каждый входящий разговор.
        let cards = super::Machine::read_with(&kit, &store).cards;
        let cards = cards.accepting();
        assert_eq!(cards.len(), 1, "карточка на диске есть — значит, и у приёмной стороны она есть");
        assert_eq!(cards[0].name, "Соединение 1");
    }

    /// Две карточки без заполненной базы — это ДВЕ разные карточки и на
    /// проводе, а поток числится за той, о которой договорились.
    ///
    /// Падало так: признак базы считался от одного `base_path`, а пустой путь
    /// у двух карточек разрешён нарочно — обе получали один признак.
    /// Обратное сопоставление отдавало ОБА имени, проверка допуска требовала
    /// зачисления по обоим, и только что разрешённый поток резался
    /// собственным «разрешение снято» при уже сожжённом коде: тупик, из
    /// которого человеку не выйти без нового кода. Путь живой — именно так
    /// выглядит машина нового человека, у которой базу ещё не вписали (живая
    /// проверка двумя машинами 9.11).
    #[test]
    fn two_cards_without_a_base_path_are_still_two_cards_on_the_wire() {
        let card = |name: &str, base_path: &str| {
            format!(
                "\n[[connection]]\nname = \"{name}\"\nserver = \"\"\ngitea = \"\"\npassword = \"\"\nworkstation = \"\"\nmode = \
                 \"tunnel\"\nbase_path = \"{base_path}\"\nbase_here = true\nrole = \"accept\"\n"
            )
        };
        let dir = std::env::temp_dir().join(format!("peer-baseid-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            dir.join(crate::cfg::FILE),
            format!("current = \"Ромашка\"\n{}{}{}", card("Ромашка", ""), card("Василёк", ""), card("Пион", "C:\\\\Bases\\\\Pion")),
        )
        .unwrap();
        let kit = super::Kit::at(dir.clone());
        let cards = super::Machine::read_with(&kit, &crate::secrets::Store::file(&dir)).cards;
        let cards = cards.accepting();
        assert_eq!(cards.len(), 3, "все три принимающие карточки на месте");

        let ids: Vec<CardId> = cards.iter().map(|c| c.id().clone()).collect();
        assert_ne!(ids[0], ids[1], "две карточки без базы обязаны отличаться: иначе отзыв одной рвёт обе");
        assert_ne!(ids[1], ids[2]);
        assert!(ids.iter().all(|id| !id.as_str().is_empty()), "признак есть у каждой: карточку без признака та сторона не назовёт никак");

        // И обратное сопоставление отдаёт РОВНО ту карточку, о которой
        // договорились, а не всех однопризнаковых соседей.
        let name_of = |agreed: &CardId| super::serving(cards, agreed).map(|c| c.name);
        assert_eq!(name_of(&ids[0]).as_deref(), Some("Ромашка"));
        assert_eq!(name_of(&ids[1]).as_deref(), Some("Василёк"));
        // Чужой признак не находит никого — и это не пустое имя, а `None`:
        // неопознанный разговор отличается от названного.
        assert_eq!(name_of(&"чужое".into()), None);

        let _ = std::fs::remove_dir_all(&dir);
    }

    /// Выпасть из ВСЕХ куч карточка не может: каждая либо принимает, либо
    /// отложена с объяснением.
    ///
    /// Падало тремя дорогами, и все три кончались одной ложью — «карточку, для
    /// которой выдали этот код, на том компьютере удалили» про карточку, которая
    /// лежит на диске.
    ///
    /// Первая: отбор смотрел вид соединения и роль, а `base_here` не спрашивал
    /// вовсе — карточка, чья база на ТОЙ стороне, объявляла себя базой на
    /// проводе (уезжала в `hello_ok` своими полями, зачисляла к себе стороны и
    /// обслуживала их), а человек с базой отпечатка не видел и ничего не
    /// разрешал. Это случай второй спеки, которого эта сборка не умеет.
    ///
    /// Вторая и третья: отбор принимающих стоял ФИЛЬТРОМ перед раскладкой, и
    /// карточка, переключённая в «Подключаюсь сам» (`role = "dial"`) или в «Всё
    /// на одной машине» (`mode = "local"`), выпадала молча — в том числе
    /// карточка, по которой человек минуту назад выдал код. Зачисления по ней
    /// при этом оставались в книге, но назвать их было нечем.
    ///
    /// Поэтому проверяются все три кучи целиком, а не одна: пропавшую карточку
    /// видно только по тому, что её нет НИ В ОДНОЙ.
    #[test]
    fn every_card_lands_in_a_pile_and_none_is_lost() {
        let card = |name: &str, mode: &str, role: &str, base_here: &str| {
            format!(
                "\n[[connection]]\nname = \"{name}\"\nserver = \"\"\ngitea = \"\"\npassword = \"\"\nworkstation = \"\"\nmode = \
                 \"{mode}\"\nbase_path = \"\"\nbase_here = {base_here}\nrole = \"{role}\"\n"
            )
        };
        let dir = std::env::temp_dir().join(format!("peer-piles-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(
            dir.join(crate::cfg::FILE),
            format!(
                "current = \"Ромашка\"\n{}{}{}{}",
                card("Ромашка", "tunnel", "accept", "true"),
                // Принимающая карточка с базой на ДРУГОМ компьютере: сегодня все
                // прочие заготовки идут с `base_here = true`, и дыра жила именно
                // поэтому.
                card("Василёк", "tunnel", "accept", "false"),
                card("Пион", "tunnel", "dial", "true"),
                card("Лютик", "local", "accept", "true")
            ),
        )
        .unwrap();
        let kit = super::Kit::at(dir.clone());
        let seen = super::Machine::read_with(&kit, &crate::secrets::Store::file(&dir));
        let crate::enroll::Cards::Read { accepting, base_elsewhere, not_accepting } = &seen.cards else {
            panic!("настройки на диске есть и читаются: {:?}", seen.cards)
        };
        let named = |cards: &[crate::enroll::Card]| cards.iter().map(|c| c.name.clone()).collect::<Vec<String>>();
        assert_eq!(named(accepting), vec!["Ромашка".to_string()], "принимает только та, у которой база здесь и роль принимающая");
        assert_eq!(named(base_elsewhere), vec!["Василёк".to_string()], "эта отложена, а не выброшена: по её коду есть что сказать");
        assert_eq!(
            named(not_accepting),
            vec!["Пион".to_string(), "Лютик".to_string()],
            "и эти две тоже отложены: «Подключаюсь сам» и «Всё на одной машине» — не повод терять карточку молча"
        );
        let all = accepting.len() + base_elsewhere.len() + not_accepting.len();
        assert_eq!(all, 4, "сколько карточек в файле, столько и в кучах: потерянную видно только так");

        let _ = std::fs::remove_dir_all(&dir);
    }

    /// Потолок записи меряется той же мерой, что карточки, и он — свойство
    /// МАШИНЫ, а не выбранной карточки.
    ///
    /// Падало двумя способами разом. Первый: потолок читался строго (`Cfg::
    /// load` с `validate`), а карточки терпимо — у нового человека настройки
    /// полузаполнены всегда, значит на провод уезжало «только чтение», пока в
    /// меню стояло «Полный». Второй, и он жил даже при терпимом чтении:
    /// сравнение было с `"full"`, а настройки такого слова не знают вовсе
    /// (`read_write`/`read_only`) — то есть запись не давалась НИКОГДА и
    /// причину не называл никто. Плюс потолок не складывался с правом записи
    /// нетекущей карточки: объявленное на проводе право зависело от того,
    /// какая карточка выбрана.
    #[test]
    fn the_write_ceiling_is_read_by_the_same_measure_as_the_cards() {
        use crate::cfg::Cfg;
        use crate::secrets;
        use crate::wire::Ceiling;
        // Два полузаполненных принимающих соединения: текущее и соседнее, оба
        // с разрешённой записью. Текущее названо нарочно — потолок машины
        // сегодня хранится полем текущей карточки, и без `current` тест
        // проверял бы умолчание, а не выбор человека.
        let card = |name: &str, write: &str| {
            format!(
                "\n[[connection]]\nname = \"{name}\"\nserver = \"\"\ngitea = \"\"\npassword = \"\"\nworkstation = \"\"\nmode = \
                 \"tunnel\"\nbase_path = \"\"\nbase_here = true\nrole = \"accept\"\nwrite = \"{write}\"\n"
            )
        };
        let dir = std::env::temp_dir().join(format!("peer-ceiling-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        let kit = super::Kit::at(dir.clone());
        let store = secrets::Store::file(&dir);
        let write_cfg = |text: String| std::fs::write(dir.join(crate::cfg::FILE), text).unwrap();

        // Первая половина проверки: строгое чтение этот файл ОТВЕРГАЕТ. Без
        // неё правка «читать терпимо» стерегла бы пустоту.
        write_cfg(format!("current = \"Ромашка\"\n{}{}", card("Ромашка", "read_write"), card("Василёк", "read_write")));
        assert!(Cfg::load_with(&kit, &store).is_err(), "строгое чтение обязано отвергать полузаполненные карточки");

        let seen = super::Machine::read_with(&kit, &store);
        assert_eq!(seen.ceiling, Ceiling::Full, "в меню «Полный» — значит и на проводе «Полный», а не молчаливое «только чтение»");
        assert_eq!(seen.cards.accepting().len(), 2);
        assert!(seen.cards.accepting().iter().all(|c| c.base.write), "обе карточки разрешают запись — потолок машины их не запрещает");

        // А теперь человек щёлкнул потолок машины в «только чтение». Право
        // записи обязано пропасть у ОБЕИХ карточек, не только у текущей:
        // потолок — свойство машины и действует на все разом.
        write_cfg(format!("current = \"Ромашка\"\n{}{}", card("Ромашка", "read_only"), card("Василёк", "read_write")));
        let seen = super::Machine::read_with(&kit, &store);
        assert_eq!(seen.ceiling, Ceiling::ReadOnly);
        assert!(
            seen.cards.accepting().iter().all(|c| !c.base.write),
            "потолок машины не сложился с правом нетекущей карточки — объявленное на проводе право зависело бы от того, какая карточка \
             выбрана"
        );

        let _ = std::fs::remove_dir_all(&dir);
    }
