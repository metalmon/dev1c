#!/bin/sh
# Заплата 0002 к стенду: агент в терминале (`pi`) не знает, как звать инструменты
# 1С, выдумывает свой способ и подвешивает вызов.
#
# КАК ЗАПУСТИТЬ. Либо в терминале внутри стенда:
#
#     sh patch.sh
#
# либо с машины, где поднят контейнер, одной строкой:
#
#     docker exec -i dev1c sh -s < patch.sh
#
# (если контейнер назван иначе, поставьте его имя вместо dev1c).
#
# ЧТО ЭТО ДЕЛАЕТ. Дописывает три абзаца в правила агента — файл `AGENTS.md`
# каждого рабочего места (он один и тот же для панели редактора и для `pi`).
# Больше ничего: ни сети, ни загрузок, ни докера, ни паролей. Копия файла до
# правки остаётся рядом под именем `AGENTS.md.before-0002`. Повторный запуск
# безвреден: заплата видит свою работу и не делает её дважды.
#
# ЧТО БЫЛО СЛОМАНО. В `pi` серверы MCP объявлены иначе, чем в панели: их
# инструменты не перечислены, они за `codemode`, и зовут их оттуда методом
# `tools` по имени. В правилах про это не было сказано, и модель выводила
# способ сама: собирала JSON-RPC руками и слала его через `nc`. Такой вызов
# повисает — протокол MCP требует сперва рукопожатия, а `nc` без `-N` не
# закрывает свою половину и ждёт сервера, который ждёт его. На экране это
# выглядит как «агент думает» без конца и без ответа.
#
# Инструменты при этом на месте и работают: беда только в том, каким путём к
# ним идти.
#
# ОТМЕНИТЬ: вернуть сохранённую копию файла.
#
# ПОСЛЕ ЗАПУСКА перезапустите `pi` и панель агента в редакторе: правила
# читаются на старте разговора, в уже открытом они не подхватятся.
set -eu

ID=0002
# Строка, после которой встаёт добавка: в правилах это абзац про `pi`. Нет её
# (правила старше) — дописываем в конец, смысл от места не меняется.
# Без обратных кавычек нарочно: строку подставляют в команду для `su -c`, и
# кавычки там выполнились бы как команда.
ANCHOR='^Спросят про'
# По этой строке заплата узнаёт свою работу.
MARK='mcp__1c__get_object_structure'

[ -x /usr/local/bin/1c-stand ] || {
    echo "Это не стенд: /usr/local/bin/1c-stand не найден." >&2
    echo "Запустите заплату внутри контейнера стенда — см. заголовок файла." >&2
    exit 1
}

snippet=$(mktemp)
trap 'rm -f "$snippet"' EXIT
# Читать его будет рабочее место, а mktemp отдаёт файл только хозяину.
chmod 644 "$snippet"
cat >"$snippet" <<'TEXT'

**Следующие два абзаца — только для `pi`.** Работаешь в панели редактора — пропусти их: там инструменты объявлены тебе напрямую, и зовёшь ты их как обычно, по имени инструмента. Отличить просто: видишь в своём списке `get_object_structure` — ты в панели, не видишь — ты в `pi`.

В `pi` серверы MCP объявлены иначе: их инструменты не перечислены, они за `codemode`. Зовут их оттуда методом `tools` по имени — `await tools.mcp__1c__get_object_structure({ type: "Catalog", name: "Номенклатура" })`, так же `mcp__bsl_reference__*` и `mcp__vrunner__*`. Какие есть, смотрят внутри скрипта: `ALL_TOOLS.filter(t => t.name.startsWith("mcp__1c"))` — это **массив** `{name, description}`, а не объект, `Object.keys` по нему даёт номера, а не имена; есть ещё `searchTools("структура объекта")` и `describeNamespace("mcp__1c")`.

Собирать JSON-RPC руками и слать его через `nc` **нельзя**: так вызов и повисает — MCP требует сперва `initialize` и `notifications/initialized`, а `nc` без `-N` не закрывает свою половину, и сервер ждёт продолжения, которого не будет. Инструмент есть, ищи его имя — обхода нет.
TEXT

# Правит файл его владелец: в домах это рабочее место, в /etc/skel — root.
# Иначе у файла сменился бы хозяин, и точка входа при обновлении образа уже не
# смогла бы его переписать.
patch_file() { # путь, владелец ("" — править от себя)
    f=$1; owner=$2
    [ -f "$f" ] || return 0
    if grep -q "$MARK" "$f"; then
        echo "  уже дописано: $f"
        return 0
    fi
    cmd="cp -p '$f' '$f.before-$ID'"
    if grep -q "$ANCHOR" "$f"; then
        cmd="$cmd && sed -i '/$ANCHOR/r $snippet' '$f'"
    else
        cmd="$cmd && cat '$snippet' >> '$f'"
    fi
    if [ -n "$owner" ] && [ "$(id -u)" = 0 ]; then
        su - "$owner" -c "$cmd"
    else
        sh -c "$cmd"
    fi
    echo "  дописано: $f (копия: $f.before-$ID)"
}

if [ "$(id -u)" = 0 ]; then
    users=$(ls /home)
else
    users=$(id -un)
fi

done_any=0
for u in $users; do
    [ -d "/home/$u" ] || continue
    echo "$u:"
    for f in "/home/$u/.config/zed/AGENTS.md" "/home/$u/.pi/agent/AGENTS.md"; do
        [ -f "$f" ] || continue
        done_any=1
        patch_file "$f" "$u"
    done
    if [ "$done_any" = 1 ]; then
        d=/home/$u/.local/share/dev1c
        [ -d "$d" ] && su - "$u" -c "grep -q '^$ID\$' '$d/patches.applied' 2>/dev/null || echo '$ID' >> '$d/patches.applied'" 2>/dev/null || true
    fi
done

# Образец, с которого рождается новое рабочее место: пока контейнер жив, новый
# дом получит правила уже с добавкой. Пересоздадут контейнер — образец придёт
# из образа заново, и заплату надо приложить ещё раз (до сборки с правкой).
if [ "$(id -u)" = 0 ]; then
    echo "образец новых рабочих мест:"
    for f in /etc/skel/.config/zed/AGENTS.md /etc/skel/.pi/agent/AGENTS.md; do
        patch_file "$f" ""
    done
fi

[ "$done_any" = 1 ] || { echo "Правил агента не нашлось — это не стенд?" >&2; exit 1; }

echo
echo "Готово. Перезапустите pi и панель агента: правила читаются на старте разговора."
