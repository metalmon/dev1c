/// Версия протокола, на которой эта сборка говорит. Диапазон пока из одного
/// номера: `proto_min == proto_max == PROTO`. Сторона обязана уметь говорить
/// по каждому номеру, который объявила (спека, «Версии»), — объявлять больше
/// одного раньше, чем второй номер существует, значит соврать.
pub const PROTO: u32 = 1;

/// Сколько ждём МАШИНУ: кадр, который та сторона уже решила отправить.
///
/// Тридцати секунд хватает на медленное рукопожатие через релей и не хватает
/// на то, чтобы человек счёл программу зависшей. Больше здесь брать незачем:
/// на этих шагах человека нет ни на одном конце, и ждать нечего, кроме сети.
pub const PATIENCE: Duration = Duration::from_secs(30);

/// Сколько ждём ЧЕЛОВЕКА после `enroll_wait`.
///
/// Пять минут — это «отошёл к телефону сверить отпечаток», а не «ушёл на
/// обед»: ушедший на обед закроет диалог сам, и колбэк ответит «не решил».
/// Предел нужен не человеку, а задаче: без него незакрытый диалог держал бы
/// поток и запись в книге открытыми бесконечно.
///
/// Принимающая сторона отмеряет ровно `DECISION`, зовущая — `DECISION +
/// PATIENCE`. Разница нарочная: слово всегда остаётся за стороной с базой, и
/// зовущая получает `bye` словами, а не тишину по своему же сроку.
pub const DECISION: Duration = Duration::from_secs(5 * 60);

/// Карточка соединения глазами зачисления: своё локальное имя плюс поля базы,
/// которые по проводу и уедут.
///
/// Имя карточки — локальное и по каналу не ездит (спека, «По каналу никогда
/// не едут»); держится оно здесь ради СЛОВ человеку в наш журнал («по
/// карточке «Ромашка» подключено»), а сопоставляется карточка ключом
/// (`id()`). Полного `cfg::Connection` здесь не берём: зачислению нужны
/// четыре поля, а не вся карточка с паролями.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Card {
    /// База этой карточки — на ЭТОЙ машине.
    ///
    /// **Без этого поля разрешение пары B давало бы право открыть вызовы к НАШЕЙ машине** (находка проверки безопасности 11.11,
    /// вторая волна). Человек в паре B разрешает обратное — «присылайте сюда свою базу, мои агенты будут звать её инструменты», — а
    /// допуск к потокам вызовов спрашивался по тому же живому управляющему потоку, что и в паре A. Куча карточек на этот вопрос не
    /// отвечает: в «не принимает» лежат и карточки без базы (сочетание 5), и карточки с базой (сочетание 4).
    pub base_here: bool,
    pub name: String,
    /// Ключ карточки в НАШЕМ пространстве имён — тот, которым её называют книга допуска и партнёры.
    ///
    /// **Хранится именно он, а не проводный вид** (шаг 2 плана пары B). Прежде здесь лежали готовые `BaseFields`, то есть кадр, и ключ
    /// карточки брался из него же. Пока ключ был один на оба пространства имён, это экономило поле; с расколом (`wire::CardRef`) оно
    /// стало бы местом, где наш ключ незаметно подменяется чужим. Проводный вид строится на отправку (`on_wire`) и нигде не хранится.
    pub id: crate::cfg::CardId,
    /// Имя базы — как эта сторона называет её той: чужие слова для неё, свои для нас.
    pub base_name: crate::wire::SaysName,
    /// ДЕЙСТВУЮЩЕЕ право записи этой карточки на этой машине (`cfg::Cfg::may_write`).
    pub write: bool,
}

impl Card {
    /// Ключ карточки — тот, которым её называют книга допуска и партнёры (`cfg::CardId`).
    pub fn id(&self) -> &crate::cfg::CardId {
        &self.id
    }

    /// Как эта карточка выглядит НА ПРОВОДЕ. Единственное место, где наш ключ превращается в проводный (`CardId::on_wire`).
    pub fn on_wire(&self) -> BaseFields {
        BaseFields { base_id: self.id.on_wire(), base_name: self.base_name.clone(), write: self.write }
    }
}

/// Принимающие карточки этой машины — ИЛИ признание, что настроек мы не прочитали. ТИП, а не список с оговоркой.
///
/// **Чем куплено.** Прежде в `accept_side` ехал `&[Card]`, и нечитаемые настройки приезжали сюда ПУСТЫМ СПИСКОМ — тем же значением, каким
/// выглядит законно пустой список карточек у человека, который ещё ни одной не завёл. Дальше по коду разницы между ними не было уже нигде, и
/// той стороне уезжало «карточку, для которой выдали этот код, на той машине удалили»: беда ЗДЕСЬ, а человека на ТОЙ стороне посылали
/// просить новую карточку и новый код, которые не помогут. Себе мы при этом не говорили ничего — ни строки в журнал. Образец правильного
/// устройства лежал в сорока строках ниже (`BOOK_UNREADABLE`: «беда на стороне базы, а не с вашим кодом… новый код не поможет»), и разница
/// между ним и ложью была ровно в том, что про книгу мы знали `Err`, а про настройки — пустой `Vec`.
///
/// **Почему типом, а не вторым полем «прочиталось ли».** Два значения разрешали бы себе противоречить — «не прочиталось» с полным списком
/// внутри, — и первый же автор, забывший спросить флаг, вернул бы ту же ложь. Здесь спрашивать нечего: списка вне `Read` не существует, и
/// пути, на котором нечитаемые настройки притворяются пустыми, в программе нет.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Cards {
    /// Настройки прочитаны. Пустой `accepting` законен и означает ровно себя: карточек, принимающих подключения, на этой машине нет.
    ///
    /// **Куч три, и четвёртой дороги — «выпасть из всех» — у карточки нет.** Прежде отбор принимающих стоял ФИЛЬТРОМ, и карточка,
    /// переключённая в «Подключаюсь сам» или «Всё на одной машине», выпадала из обеих куч молча: по её живому коду та сторона слышала
    /// «карточку, для которой выдали этот код, на том компьютере удалили», а карточка лежала на диске. Эту ложь на ветке чинили трижды, и
    /// каждый раз корнем был не текст, а потерянная карточка. Теперь `Machine::of` раскладывает КАЖДУЮ, и о каждой куче есть что сказать
    /// словами.
    Read {
        /// Карточки, которые ПРИНИМАЮТ: база здесь, роль принимающая, и нам есть что предъявить той стороне.
        accepting: Vec<Card>,
        /// Карточки, чья база — на ТОЙ стороне: случай второй спеки, он же ПАРА B, и это куча, из которой зачисление и берёт
        /// карточку, когда звонящая сторона назвалась `Side::WithBase` (`Cards::pile`). Отложенной она зовётся по старой памяти —
        /// отложена она была от принимающих, а не от работы.
        ///
        /// Сюда, а не в мусор, — иначе код, выданный для такой карточки, получал бы «карточку удалили»: та же ложь, что чинится
        /// вариантом `Unreadable`, другой дорогой.
        base_elsewhere: Vec<Card>,
        /// Карточки, которые есть, но подключений не принимают: роль зовущая («Подключаюсь сам») либо всё на одной машине («Всё на одной
        /// машине»). Человек мог переключить карточку ПОСЛЕ того, как выдал по ней код, — и тогда та сторона обязана прочитать, что
        /// случилось на самом деле, а не про удалённую карточку.
        not_accepting: Vec<Card>,
    },
    /// Настройки не прочитались. Внутри — НАШИ слова для НАШЕГО журнала (пути к файлу, причина разбора): той стороне они не уезжают никогда
    /// (`ours_to_blame`), ей достаются три строки без устройства этой машины.
    Unreadable(String),
}

impl Cards {
    /// Настройки прочитались, и все карточки принимают: ничего не отложено.
    ///
    /// Для тех, кому вторая половина безразлична, — а это все проверки, кроме одной. Иначе каждая из девяти писала бы пустой список второй
    /// раз, и смысл «тут отложенных нет» растворился бы в обвязке.
    pub fn here(accepting: Vec<Card>) -> Cards {
        Cards::Read { accepting, base_elsewhere: Vec::new(), not_accepting: Vec::new() }
    }

    /// Карточки, которые принимают, — для тех читателей, кому нужен только список, а отказывать словами не их дело (учёт живых разговоров,
    /// обратное сопоставление имён).
    ///
    /// Нечитаемые настройки отдают здесь пустой срез, и это не возврат к прежней лжи: решение «что сказать той стороне» принимается в
    /// `accept_side` по самому типу и ДО того, как кто-нибудь спросит список.
    pub fn accepting(&self) -> &[Card] {
        match self {
            Cards::Read { accepting, .. } => accepting,
            Cards::Unreadable(_) => &[],
        }
    }

    /// Карточка есть, но подключений по ней не будет — и вот три строки, которые об этом говорят той стороне.
    ///
    /// `None` — такой карточки на машине нет вовсе (её и правда удалили), и слова на это другие (`NO_CARD_TEXT`).
    ///
    /// Одним местом на оба случая отказа — заявку по коду и возврат по названной карточке: прежде случай «база на той стороне» был расписан
    /// в двух ветках по отдельности, и третий случай («не принимает») добавился бы третьей парой. Отбор по куче — решение, а не поиск, и
    /// жить ему положено там, где лежат сами кучи.
    /// НАША карточка, названную которой та сторона повторила нам (эхо `Why::Return`).
    ///
    /// Единственная дорога от проводного ключа к нашей карточке, и она названа по-своему нарочно: перевода `CardRef → CardId` нет
    /// вовсе (довод в докстроке `wire::CardRef`), а есть поиск среди СВОИХ. Законно это только там, где список уже сужен допуском той
    /// стороны: совпадение ключей, выведенных из одинаковых имён карточек на разных машинах, доступа тогда не даёт.
    /// Карточка, по которой эта машина может ОБСЛУЖИВАТЬ вызовы, — то есть та, чья база ЗДЕСЬ.
    ///
    /// Единственная дорога к обслуживанию (`peer::serve_calls`), и узкая она нарочно: разрешение у карточки без базы значит
    /// «присылайте свою базу моим агентам», а не «берите мою». Карточки без базы здесь не находятся вовсе, и отказ той стороне —
    /// тот же, что на выдуманный признак базы: «такой базы здесь нет».
    pub fn serving_named(&self, r: &crate::wire::CardRef) -> Option<&Card> {
        self.mine_named(r).filter(|c| c.base_here)
    }

    pub fn mine_named(&self, r: &crate::wire::CardRef) -> Option<&Card> {
        let Cards::Read { accepting, base_elsewhere, not_accepting } = self else { return None };
        accepting.iter().chain(base_elsewhere).chain(not_accepting).find(|c| &c.id().on_wire() == r)
    }

    /// Куча карточек, к которым этот разговор может зачислить, — по той стороне, какой она себя назвала в `hello`.
    ///
    /// **Это и есть вся разница пар в зачислении.** `WithAgents` — у той стороны агенты, база здесь: зачисляем к карточкам, которые
    /// принимают (пара A). `WithBase` — база у ТОЙ стороны, здесь агенты: зачисляем к карточкам, у которых база на другом компьютере
    /// (пара B). Разрешение у такой карточки значит «этому ключу разрешено прислать сюда свою базу и получить от моих агентов вызовы
    /// её инструментов» — пускают не к данным этой машины, их тут нет, а к агентам.
    ///
    /// `Err` — настройки не прочитались, и внутри НАШИ слова для нашего журнала: той стороне из них не уходит ничего.
    pub fn pile(&self, side: Side) -> Result<&[Card], &str> {
        match self {
            Cards::Read { accepting, base_elsewhere, .. } => Ok(match side {
                Side::WithAgents => accepting,
                Side::WithBase => base_elsewhere,
            }),
            Cards::Unreadable(ours) => Err(ours),
        }
    }

    /// Эта карточка у нас есть, но она на ОДНОЙ стороне с собеседником — значит база либо у обоих, либо ни у кого.
    ///
    /// **Пары проверяются на стыке** (спека сочетаний, «что из этого следует для кода», пункт 3). Прежде оба случая отвечались
    /// общими словами «подходящей карточки нет» — симптомом вместо причины, и человеку некуда было идти чинить. Спрашивается это
    /// ПОСЛЕ годного тикета: причину слышит тот, кто предъявил код, а не всякий, кто дозвонился.
    ///
    /// Две другие невозможности закона — «обе принимают» и «обе звонят» — сюда не доходят вовсе: при них соединение не
    /// устанавливается, и этого разговора не бывает. Их не лечит ничто, кроме догадки, а догадки сняты решением владельца 10.11.
    pub fn mismatch_of(&self, id: &CardId, theirs: Side) -> Option<crate::cfg::Mismatch> {
        // Кому эта карточка годится — спрашивается у `pile`, и только у него: раскладка по кучам и есть ответ на «где её база», а
        // второе место счёта (признак у самой карточки) однажды с ним разойдётся. На этом и поймано: прибор теста кладёт карточку
        // в кучу «база на той стороне», оставив ей признак «база здесь», — две меры дали разные ответы.
        let suits = [Side::WithBase, Side::WithAgents]
            .into_iter()
            .find(|s| self.pile(*s).map(|p| p.iter().any(|c| c.id() == id)).unwrap_or(false))?;
        // Карточка годится стороне `suits` — значит НАША сторона ей противоположна. Дальше судит общая мера: совпали стороны —
        // несовпадение, разошлись — законная пара и отказывать не о чем.
        crate::cfg::Mismatch::of_sides(suits.other(), theirs)
    }

    fn aside(&self, id: &CardId) -> Option<&'static str> {
        let Cards::Read { not_accepting, .. } = self else { return None };
        not_accepting.iter().any(|c| c.id() == id).then_some(NOT_ACCEPTING)
    }
}

/// Что показывается человеку в диалоге разрешения (спека, шаг четвёртый):
/// к какой карточке и базе стучатся, ключ той стороны — его короткий
/// отпечаток сверяют голосом по телефону — и как сторона себя назвала.
///
/// `says_name` — её слова, а не проверенный факт, и в окне он помечается
/// именно так. Отпечаток из `peer` считает окно: вид отпечатка — дело
/// показа, а не провода.
#[derive(Debug, Clone)]
pub struct Request {
    /// Имя карточки — ТОЛЬКО чтобы назвать её человеку в вопросе о разрешении. Сопоставляется заявка ключом (`card()`): имя человек правит когда хочет, и очередь заявок, ключёванная именем, теряла бы их при переименовании.
    pub card_name: String,
    /// Ключ карточки в НАШЕМ пространстве имён: заявка пришла к нам, и отвечает на неё наша книга допуска.
    pub card: crate::cfg::CardId,
    /// Как эта карточка выглядела на проводе — то, что мы показываем человеку в вопросе о разрешении.
    pub base: BaseFields,
    pub peer: EndpointId,
    /// Чужие слова — и тип это держит: показать невычищенное нельзя, потому
    /// что невычищенного `SaysName` не бывает (см. `wire::SaysName`).
    pub says_name: SaysName,
}

impl Request {
    /// К какой карточке эта заявка — КЛЮЧОМ в нашем пространстве имён.
    ///
    /// Своё поле под него появилось с расколом ключа (шаг 2 плана пары B): прежде он брался из `base.base_id`, а тот стал проводным
    /// (`wire::CardRef`). Книга допуска ключуется нашим ключом, и подставить в неё проводный больше не выходит по типу.
    pub fn card(&self) -> &CardId {
        &self.card
    }
}

/// Чем звонит зовущая сторона — и это ОДНА мера на обе стороны разговора.
///
/// **Чем куплено.** Прежде «придёт ли заявка» решалось дважды и по-разному:
/// зовущая смотрела, пуста ли строка кода, а принимающая — есть ли на машине
/// хоть один непогашенный тикет. Выдали код второй карточке — и
/// переподключение первой, которой просить нечего, висело до срока терпения;
/// вожжей на поток за это время нет, то есть отзыв в это окно переставал быть
/// немедленным, а в живой поток уезжал мусорный отказ о стороне, которая
/// ответила всё, что должна. Мера одна: эта, и уезжает она на провод
/// (`wire::Why`).
///
/// Строка кода превращается в это решение РОВНО ОДИН раз — в `Call::of`.
/// Дальше по программе ездит уже решение, и переспрашивать «а пуст ли код»
/// больше негде.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Call<'a> {
    /// Заявка: вот код подключения, вставленный человеком.
    Enroll(&'a str),
    /// Возврат по уже данному допуску: вот признак базы той карточки, которой
    /// этот поток, если мы его помним, — то есть КЛЮЧ той карточки на ТОЙ
    /// машине (`cfg::CardId`, решение владельца 10.11).
    Return(Option<&'a crate::wire::CardRef>),
}

impl<'a> Call<'a> {
    /// Единственная дорога от строк: код на руках — заявка, кода нет — возврат
    /// по карточке, которую помним.
    pub fn of(code: &'a str, card: Option<&'a crate::wire::CardRef>) -> Call<'a> {
        let code = code.trim();
        if code.is_empty() {
            Call::Return(card)
        } else {
            Call::Enroll(code)
        }
    }

    /// Что из этого едет на провод. Код не едет НИКОГДА: на проводе от него
    /// бывает только секрет тикета, и то в `enroll`.
    fn why(&self) -> Why {
        match self {
            Call::Enroll(_) => Why::Enroll,
            Call::Return(card) => Why::Return(card.cloned()),
        }
    }
}

/// Решение человека.
///
/// `NoAnswer` — не вежливость, а обязательный третий ответ: человек может
/// закрыть диалог, не решив, и это НЕ разрешение и НЕ отказ. Будь ответов
/// два, автор колбэка вынужден был бы соврать одним из них — а оба вранья
/// дорогие: «разрешил» пускает незачисленного, «отказал» сжигает код и
/// ставит карточке исход, которого человек не выбирал.
///
/// Решение ездит и по управляющей двери (`door::Ask::Answer`): набранные `1c-connect allow` и `decline` отвечают на заявку у ЖИВОГО
/// экземпляра, а не у своего (задача 7 плана). Отсюда и serde.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Decision {
    /// Пускаю.
    ///
    /// **Права записи здесь нет, и это не упущение.** Поле `write` здесь стояло и было ЧЕТВЁРТОЙ мерой того же самого: на вопрос «можно ли
    /// этой стороне писать в эту базу» отвечают потолок этой машины, слово карточки и потолок той машины, а разрешение записи по контракту
    /// принадлежит СОЕДИНЕНИЮ («Разрешение записи в базу — у соединения, в пределах потолка каждой стороны»), не отдельной зачисленной
    /// стороне. Диалог разрешения спрашивает не это: он показывает карточку, базу, отпечаток ключа и самоназвание, а отвечают ему «да» или
    /// «нет» (спека протокола, шаг четвёртый). Единственный живой зовущий и передавал сюда `write: true` всегда — то есть мера была
    /// постоянной, но выглядела решением, и первый, кто завёл бы ей флажок в окне, развёл бы право записи на четыре места вместо трёх.
    Allow,
    /// Не пускаю. Исход, а не ошибка.
    Deny,
    /// Закрыл диалог, не решив.
    NoAnswer,
}

/// Заявка, ждущая решения человека, вместе с дорогой, по которой решение
/// уедет обратно в этот самый разговор: `accept_side` висит на `decide` и
/// держит ту сторону сообщением `enroll_wait`, пока кто-то не позовёт
/// здешний `answer`.
///
/// **Канал на одну посылку, а не поле «ответ записан».** Пока ответа нет,
/// держать его негде, кроме самого ожидания, и выдумывать для этого второе
/// место (флаг, за которым кто-то должен подглядывать) значило бы заводить
/// опрос там, где есть прямая дорога.
///
/// **`answer` — приватное поле, и это закрывает дыру, а не просто прячет
/// её.** Публичным оно позволяло отвечать дважды: канал брали руками
/// (`answer.take()`), и второе такое взятие тихо возвращало `None` —
/// решение терялось молча, а не отказывалось словами. Метод `answer` ниже
/// — единственная дверь к каналу, и берёт его тем же `Option::take`, но на
/// пустом месте отказывает СЛОВАМИ (`ALREADY_ANSWERED`), а не молчанием.
///
/// Тип живёт здесь, а не в окне: заявка (`Request`) и решение (`Decision`)
/// — уже здешние, и канал между ними — третья деталь того же разговора, а
/// не словарь экрана. Окно — один из клиентов бека (закон 1 спеки
/// «Сопряжение переезжает в бек»), и это ровно то, из-за чего у типа нет
/// гейта на фичу окна: командная строка умеет всё, что окно (закон 3 той же
/// спеки), и канал ответа обязан существовать и без `gui`.
///
/// `Debug` — не для показа человеку (его тут и не ждут), а затем, что
/// `peer_out::Out` оборачивает заявку в свой вариант и обязан выводиться
/// целиком: тест формирует `{out:?}` на ветке, до которой доходить не
/// должен, и без `Debug` здесь это не собралось бы вовсе.
///
/// Канал — `tokio::sync::oneshot`, а не `futures::channel::oneshot`: вторая
/// зависимость в этом дереве под фичей `gui` (`Cargo.toml`), а `tokio` с
/// `sync` — безусловная, и та же идиома уже живёт в `channel.rs`/`session.rs`.
/// Вести здесь второй канал на том же вопросе значило бы заводить вторую
/// меру, а не только лишнюю зависимость.
#[derive(Debug)]
pub struct Pending {
    pub request: Request,
    /// `None` — ответить уже некуда: разговор кончился (сорвалась связь,
    /// вышел срок `DECISION`) либо ответ уже уехал методом `answer`. Заявка
    /// при этом со списка окна снимается, а не висит немым напоминанием
    /// (`gui::save::prune_enrollment`).
    answer: Option<tokio::sync::oneshot::Sender<Decision>>,
    /// Когда заявка пришла — ТОЛЬКО чтобы сказать человеку, сколько у него
    /// осталось (`left`). Решать по этой отметке, жива ли заявка, нельзя: на
    /// это есть `reachable`, и второй меры «жива ли» здесь нет (см. `left`).
    at: std::time::Instant,
}

impl Pending {
    /// Заявка со своим каналом ответа. Конструктор, а не литерал структуры —
    /// поле `answer` приватно, и это единственная дверь извне.
    ///
    /// Отметка времени ставится здесь, и это то же мгновение, с которого
    /// `accept_side` отмеряет `DECISION`: заявка рождается внутри его
    /// `timeout`, в том самом вызове (`peer::answering`, замыкание `ask`).
    pub fn new(request: Request, answer: tokio::sync::oneshot::Sender<Decision>) -> Pending {
        Pending { request, answer: Some(answer), at: std::time::Instant::now() }
    }

    /// Сколько у человека осталось на ответ — ДЛЯ СЛОВ, а не для решений.
    ///
    /// Своего срока здесь не заводится: мера одна, `DECISION`, и отмеряет её
    /// `accept_side`. Эта строка только рассказывает, сколько от неё
    /// осталось, — отсюда и `saturating_sub`: ноль значит «срок вышел, а
    /// канал ещё не закрылся», и даже тогда показывать или нет решает
    /// `reachable`, а не это число. Второго счётчика, по которому заявка
    /// умирала бы, в программе нет.
    pub fn left(&self) -> Duration {
        self.left_at(std::time::Instant::now())
    }

    /// То же самое на названный миг — им меряет уборка, и им же её проверяет тест: ждать пять минут настоящего срока прогон не станет,
    /// а снять срок из уборки значило бы оставить её половину непроверенной. Мера одна и та же, второго выражения у неё нет.
    pub fn left_at(&self, now: std::time::Instant) -> Duration {
        DECISION.saturating_sub(now.saturating_duration_since(self.at))
    }

    /// Ответ по этой заявке уже ушёл (`answer` взял канал). Отличается от
    /// `reachable` тем, ЧЕМ кончилась заявка: ответом человека или сроком и
    /// обрывом. Уборке это нужно для слов — об отвеченной заявке говорить
    /// «ответа слишком долго не было» было бы неправдой, а сами слова ответа
    /// человек уже прочитал (`gui::save::prune_enrollment`).
    pub fn answered(&self) -> bool {
        self.answer.is_none()
    }

    /// Есть ли ещё кому отвечать. `false` — разговор кончился: сорвалась
    /// связь, вышел срок `DECISION`, зовущая бросила трубку, — либо ответ
    /// уже ушёл.
    ///
    /// Чистая проверка, и ответ она берёт у самого канала
    /// (`Sender::is_closed` — приёмник уронен), а не у своего срока: срок
    /// держит `accept_side`, и второй счётчик здесь разошёлся бы с ним на
    /// первой же правке.
    ///
    /// Спрашивается ДО всего, что человек увидит: заявка, на которую нельзя
    /// ответить, не поднимает строку первой, не зажигает «Разрешить» и не
    /// открывает диалог (Important 2 ревью задач 6 и 7). Иначе выходило
    /// так: заявка пришла при закрытом окне, пять минут вышли, человек
    /// открывает окно, видит первую строку, снимает трубку, сверяет
    /// отпечаток голосом — и получает «отправить не удалось».
    pub fn reachable(&self) -> bool {
        self.answer.as_ref().is_some_and(|tx| !tx.is_closed())
    }

    /// Ответить на заявку. Канал берётся `Option::take` — отсюда и «один
    /// раз»: второй вызов находит `None`, а не чужой ответ, который можно
    /// было бы случайно перезаписать.
    ///
    /// Тот же отказ достаётся и честному первому ответу, которому некуда
    /// уехать (приёмник уронен между тем, как заявку показали, и тем, как
    /// на неё ответили, — разговор кончился своим путём): вызывающему всё
    /// равно, какая из двух причин, — отличить их он не может, не
    /// заглядывая внутрь канала, а человеку отличать их словами незачем:
    /// обе значат ровно одно — эта заявка решений больше не принимает.
    pub fn answer(&mut self, d: Decision) -> Result<(), &'static str> {
        let tx = self.answer.take().ok_or(ALREADY_ANSWERED)?;
        tx.send(d).map_err(|_| ALREADY_ANSWERED)
    }
}

/// Заявки, ждущие решения человека, — у держателя управляющей двери, а не в окне.
///
/// Переехали сюда задачей 7 плана `2026-11-15-pairing-to-the-back.md` тем же законом и тем же приёмом, каким задача 6 перевезла запас
/// кодов (`codes::Codes`): «окно не вправе быть единственным держателем чего бы то ни было» (закон 4 спеки). Окно теперь ЧИТАЕТ этот
/// список, а не владеет им, и набранные `1c-connect requests`/`allow`/`decline` видят ровно то же, что человек видит на экране.
///
/// Общий держатель (`Arc<Mutex<..>>`), а не поле окна: читателей двое — отрисовка списка на главном потоке GPUI и управляющая дверь
/// своим потоком, — и спрашивают они ОДИН список. Замок берётся на доли микросекунды (проход по списку длиной в число ждущих заявок).
///
/// **Ответ заявку со списка не снимает, и это одно правило на оба пути.** Со списка её снимает уборка (`prune` ниже; зовут её и
/// окно тиком, и дверь — на каждый вопрос о заявках), а показывают только те, кому ещё можно ответить (`Pending::reachable`) — то
/// есть отвеченная заявка исчезает с экрана в ту же секунду. Снимай её сам ответ — второй набранный `allow` по тому же отпечатку
/// читал бы «такой заявки нет» вместо «на неё уже ответили», а это разные беды: первая про опечатку в отпечатке, вторая про гонку
/// двух окон.
#[derive(Clone, Default)]
pub struct Requests(std::sync::Arc<std::sync::Mutex<Vec<Pending>>>);

/// Что сталось с заявкой, когда на неё ответили, — для слов вызывающему: карточка (ей гасят код) и её имя.
#[derive(Debug)]
pub struct Answered {
    pub card: CardId,
    pub name: String,
    /// Ответ правда уехал в разговор. `false` — заявка найдена, а послать
    /// решение уже некуда; человеку это говорится словами (`answered`).
    pub sent: bool,
}

impl Requests {
    /// Сам список — вызывающий ищет и роняет записи сам (тот же приём, что у `codes::Codes::lock`).
    ///
    /// Отравленный замок — не повод валить ответ: внутри только заявки, и прочитать их после чужой паники не опаснее, чем до.
    pub fn lock(&self) -> std::sync::MutexGuard<'_, Vec<Pending>> {
        self.0.lock().unwrap_or_else(|e| e.into_inner())
    }

    /// Уборка списка — ДЕЛО ДЕРЖАТЕЛЯ, а не окна (замечание ревью круга правок 2: жила она в `gui::save` и в сборке без окна не
    /// звалась никогда, то есть отвеченные и мёртвые заявки копились до конца процесса, а партнёр, постучавшийся за сеанс в две
    /// карточки, переставал отвечаться одним отпечатком).
    ///
    /// Роняется двое. Первые — заявки, которым ответить нельзя и на которые НЕ ответили (разговор кончился сам: сорвалась связь,
    /// вышел срок, зовущая бросила трубку); их имена возвращаются наружу, потому что о них человеку говорят словами, и каждый
    /// зовущий говорит их туда, где его слушают: окно строкой журнала, бек — журналом на диске. Вторые — отвеченные, у которых
    /// вышел их срок (`Pending::left`); эти уходят МОЛЧА: слова ответа человек уже прочитал, а сказать им вслед «ответа слишком
    /// долго не было» было бы прямой неправдой.
    ///
    /// **Отвеченная переживает ответ ровно на свой срок, а не до первой уборки.** Столько она прожила бы, не ответь на неё никто, —
    /// и ровно столько второй набранный `allow` по тому же отпечатку обязан читать «уже ответили», а не «такой заявки нет»: это
    /// разные беды, и человеку они говорятся разными словами.
    pub fn prune(&self, now: std::time::Instant) -> Vec<String> {
        let mut held = self.lock();
        let gone = held.iter().filter(|p| !p.reachable() && !p.answered()).map(|p| p.request.card_name.clone()).collect();
        held.retain(|p| p.reachable() || (p.answered() && p.left_at(now) > Duration::ZERO));
        gone
    }

    /// Принять пришедшую заявку. `true` — по этой же карточке уже ждёт ДРУГАЯ сторона, то есть заявка встала в очередь; об этом
    /// человеку говорят словами (`gui::save::take_request`), потому что строка карточки одна и очереди по ней не видно.
    ///
    /// Вытесняется только заявка ТОГО ЖЕ ключа и ТОЙ ЖЕ стороны — то есть повтор, у которого отпечаток на экране ровно тот же (HIGH 1
    /// проверки безопасности: «ответ человека применяется не к той заявке, которую ему показали»). Правило живёт здесь, а не в окне:
    /// заявки кладут оба пути подъёма, и разойтись им негде.
    pub fn take(&self, pending: Pending) -> bool {
        let (card, peer) = (pending.request.card().clone(), pending.request.peer);
        let mut held = self.lock();
        held.retain(|p| !(p.request.card() == &card && p.request.peer == peer));
        let queued = held.iter().any(|p| p.request.card() == &card && p.reachable());
        held.push(pending);
        queued
    }

    /// Ответить заявке, найденной по ОТПЕЧАТКУ той стороны: его человек видит в списке и его же сверяет голосом по телефону. Номер в
    /// списке для этого не годится — он сдвигается между двумя набранными командами, а отпечаток не меняется (спека, раздел 5, пункт 5).
    ///
    /// Сверка — по ПОЛНОМУ ключу (`names`), и это не мелочь: короткое сокращение подбирается перебором за секунды (см. `short_key`),
    /// и сверка «кончается на эти знаки» отдавала бы ответ тому, кто подогнал себе хвост, — ровно та беда, от которой закрывался
    /// HIGH 1 («ответ человека применяется не к той заявке, которую ему показали»). Совпало больше одной — отказ СЛОВАМИ
    /// (`AMBIGUOUS_FINGERPRINT`), а не выбор первой: подогнанный хвост превращается этим в видимый отказ, после которого человек
    /// отвечает полным ключом, а не в тихую подмену.
    ///
    /// Ищется среди ВСЕХ заявок, а не только тех, кому можно ответить: отвеченная остаётся в списке до уборки нарочно — иначе второй
    /// `allow` по тому же отпечатку прочёл бы «такой заявки нет» (см. докстроку `Requests`).
    /// `card` — имя карточки, если человек его назвал. Нужно оно затем, что ОДНА сторона законно стучится в НЕСКОЛЬКО карточек (по
    /// карточке на базу у одного партнёра), и ключ у этих заявок один: отпечаток их не различает вовсе, даже полный. Ключ заявки —
    /// пара (отпечаток, карточка), и без второй половины командная строка не умела бы того, что умеет окно, — против закона 3
    /// спеки. Имя, а не ключ карточки: человек набирает то, что видит в списке.
    pub fn answer(&self, fingerprint: &str, card: Option<&str>, d: Decision) -> Result<Answered, &'static str> {
        let mut held = self.lock();
        let hits: Vec<usize> = held
            .iter()
            .enumerate()
            .filter(|(_, p)| names(&p.request.peer, fingerprint) && card.is_none_or(|c| p.request.card_name == c))
            .map(|(i, _)| i)
            .collect();
        let [one] = hits[..] else {
            return Err(if hits.is_empty() { NO_SUCH_REQUEST } else { AMBIGUOUS_FINGERPRINT });
        };
        let p = &mut held[one];
        let (card, name) = (p.request.card().clone(), p.request.card_name.clone());
        // Отказ самого канала наружу не едет: его слова писаны тому, кто правит вызов, а не тому, кто набрал команду. Человеку обе
        // причины («уже ответили», «разговор кончился») говорятся одними словами — теми же, что говорит окно (`answered`).
        let sent = p.answer(d).is_ok();
        Ok(Answered { card, name, sent })
    }
}

/// Называет ли ЭТА сторона себя тем, что набрал человек.
///
/// Принимается ровно два вида, и оба — те, что напечатаны в списке: полный ключ (им и отвечают однозначно) и короткое сокращение
/// (`short_key`, его сверяют голосом), с многоточием впереди или без него. Сравнение — РАВЕНСТВО с одним из этих двух видов, а не
/// «кончается на»: случайная подстрока адресом быть не вправе, иначе половина набранного впопыхах отпечатка назвала бы чужую заявку
/// (обзор безопасности 16.11; прежде здесь стоял `ends_with` по голому хвосту).
///
/// Пустая строка не называет никого — «ответить всем сразу» этой дверью не набирается (закон 6 спеки: человек решает, и решает он
/// про одну заявку).
///
/// **Зовущих двое, и второго сличителя у них нет** (задача 9). Отпечатком адресуют и заявку (`Requests::answer`), и уже выданное
/// разрешение (`door::revoke_for`): строка у человека перед глазами одна и та же, набирает он её одинаково, и правило «что считается
/// названным» обязано быть у обоих одно — иначе подогнанный хвост, отвергнутый на заявке, прошёл бы на отзыве.
pub(crate) fn names(peer: &EndpointId, typed: &str) -> bool {
    let typed = typed.trim().trim_start_matches('…').trim();
    if typed.is_empty() {
        return false;
    }
    let full = peer.to_string();
    typed == full || typed == short_key(&full).trim_start_matches('…')
}

/// Два РАЗНЫХ ключа с ОДИНАКОВЫМ коротким отпечатком — фикстура для прогонов, и одна на оба пути, где сличитель применяется: заявки
/// (`Requests::answer`) и уже выданные разрешения (`door::revoke_for`). Записанная дважды, она разошлась бы при первой же правке
/// `short_key`, а сторожит она как раз находку обзора безопасности.
///
/// Ищутся перебором семян: сокращение — четыре знака, то есть шестнадцать бит, и парадокс дней рождения даёт пару на второй-третьей
/// тысяче за доли секунды. Ровно так же дёшево она достаётся и тому, кто подгоняет себе хвост нарочно, — в этом вся беда, от которой
/// закрывается равенство вместо `ends_with`. Случайности здесь нет: семена идут подряд, и находка у каждого прогона одна и та же.
#[cfg(test)]
pub(crate) fn two_keys_that_end_alike() -> (EndpointId, EndpointId) {
    let key_of = |n: u32| {
        let mut seed = [0u8; 32];
        seed[..4].copy_from_slice(&n.to_le_bytes());
        iroh::SecretKey::from_bytes(&seed).public()
    };
    let mut seen: std::collections::HashMap<String, u32> = std::collections::HashMap::new();
    let (first, second) = (0..60_000)
        .find_map(|n| {
            let tail = short_key(&key_of(n).to_string());
            seen.insert(tail, n).map(|was| (was, n))
        })
        .expect("два ключа с одинаковым окончанием обязаны найтись задолго до этого предела");
    let (a, b) = (key_of(first), key_of(second));
    assert_eq!(short_key(&a.to_string()), short_key(&b.to_string()), "фикстура: окончания совпали");
    assert_ne!(a, b, "а ключи разные — иначе прогон проверяет не то");
    (a, b)
}

/// Заявки с таким отпечатком нет — отказ про ОПЕЧАТКУ, и он нарочно другой, чем «на неё уже ответили» (решение ведущего, задача 7):
/// первое человек чинит, набрав отпечаток заново, второе значит, что заявку увели из-под него.
///
/// Назван и второй живой случай: пока человек набирал, у заявки вышел срок (`DECISION`). Молчать о нём значило бы послать его искать
/// опечатку там, где опечатки нет.
pub const NO_SUCH_REQUEST: &str = "Заявки с таким отпечатком сейчас нет — проверьте отпечаток; может быть, у неё вышел срок.\nСписок \
                                   тех, на которые ещё можно ответить: 1c-connect requests.";

/// Описанию отвечает НЕ ОДНА заявка. Выбирать за человека нельзя: он сверял голосом одну из них, а ответ ушёл бы наугад — та же
/// беда, что HIGH 1 проверки безопасности («ответ применяется не к той заявке, которую показали»).
///
/// **Этот отказ — лекарство от подбора, а не досада** (обзор безопасности 16.11). Четыре знака сокращения подбираются за секунды, и
/// тот, кто подогнал себе такой же хвост, рассчитывает на тихую подмену. Здесь он получает видимый отказ, а человек — совет
/// назвать отпечаток целиком, который не подбирается.
///
/// Случай второй, и он не про подбор, а про обычную жизнь: одна сторона стучится в несколько карточек, и полный ключ у таких
/// заявок один. Различает их имя карточки, и совет ведёт к нему — иначе человек, прочитав «назовите целиком», набрал бы то же
/// самое и получил тот же отказ.
pub const AMBIGUOUS_FINGERPRINT: &str = "Этому описанию отвечает сразу несколько заявок — которая из них ваша, отсюда не видно.\nНазовите \
                                         отпечаток ЦЕЛИКОМ, а если и с ним их несколько — добавьте имя карточки вторым словом: обе \
                                         строки печатает 1c-connect requests.";

/// Заявка ушла, не дождавшись ответа, — ОДНИ слова на окно и на журнал бека.
///
/// **Чужой вины в них нет, и это правка задачи 6.** Прежде говорилось «тот компьютер больше не на связи» — догадка, и притом самая
/// редкая: `Pending::reachable` отвечает по уронённому приёмнику, а роняет его ЛЮБОЙ конец разговора, и чаще всего это наш
/// собственный срок на решение (`DECISION`) — та сторона в это время жива и ждёт. Поэтому говорится ровно то, что известно
/// наверняка, и говорится, что делать.
pub fn request_gone(card: &str) -> String {
    format!("Просьба подключиться к «{card}» отменилась: ответа слишком долго не было. Попросите позвонить снова и ответьте сразу.")
}

/// Что сказать человеку об ответе на заявку — ОДНИ слова на окно и на командную строку (решение 7 задачи 7: второго словаря на то же
/// самое не заводим).
///
/// Разряд строки здесь же, а не у каждого зовущего: разряд и текст — один ответ на один вопрос, и разведи их — окно показало бы
/// «разрешено» значком беды. `journal::Kind` знает и бек, и экран (`gui::log` его реэкспортирует), а `Line` остаётся вещью окна —
/// закон 8 спеки.
///
/// `sent` — дошло ли решение до разговора. Не дошло — причин две (на заявку уже ответили; разговор кончился сам), и человеку они
/// говорятся одними словами нарочно: отличить их он не может, а делать ему в обоих случаях одно и то же (см. `Pending::answer`).
pub fn answered(name: &str, d: Decision, sent: bool) -> (crate::journal::Kind, String) {
    use crate::journal::Kind;
    match (d, sent) {
        // Закрыл диалог не решив — заявка никуда не делась, и молчать об этом нельзя.
        (Decision::NoAnswer, _) => {
            (Kind::Warn, format!("Просьба подключиться к «{name}» никуда не делась — ответить можно в любой момент"))
        }
        (_, false) => (Kind::Warn, format!("Ответ по «{name}» отправить не удалось: там уже не ждут ответа. Попросите позвонить снова")),
        (Decision::Allow, true) => (Kind::Ok, format!("Подключение к «{name}» разрешено")),
        (Decision::Deny, true) => (Kind::Say, format!("Подключение к «{name}» отклонено")),
    }
}

/// Чем кончился разговор. Один тип на обе стороны: вопрос «зачислены ли мы»
/// у них общий, а расходятся они только в том, кто спрашивал человека.
///
/// `Err` из `accept_side`/`dial_side` остаётся за тем, что разговором не
/// является вовсе: оборванная связь, неразобравшийся кадр, не та версия.
/// Исход ездит и по управляющей двери (`door::Ask::Dial`), а не только внутри процесса: `1c-connect dial` ждёт его у ЖИВОГО экземпляра и читает теми же словами (задача 6 плана). Отсюда и serde — все три полезные нагрузки его уже умеют, они проводные.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum Outcome {
    /// Разрешили сейчас, и база — у ТОЙ стороны (пара A): вот её поля, они приехали в `enroll_ok` от машины, у которой база.
    Enrolled(BaseFields),
    /// Разрешили сейчас, и база — у НАС (пара B): вот её поля, наши собственные, те самые, что мы объявили в `enroll`.
    ///
    /// **Второй случай, а не `Option` внутри первого** (круг правок задачи 7, и число здесь замерено, а не выбрано). Полей базы в
    /// `enroll_ok` пары B не бывает вовсе — у принимающей стороны базы нет, и `accept_side` шлёт их `None` нарочно, — но `None`
    /// значит не «ничего не известно»: право записи, которое та сторона получила К НАШЕЙ базе, сложили и объявили мы сами
    /// (`wire::folded_write`), и зовущей оно нужно по существу — им она ставит потолок разговору в учёте (`peer::one_round`,
    /// строка с `live.remember`), а по этому потолку мост и пускает вызовы к нашей базе. `Option<BaseFields>` потерял бы его молча
    /// вместе с полями.
    ///
    /// Чего здесь НЕТ и не нужно: ключа карточки той стороны. Он нужен ровно затем, чтобы сказать ей, какую базу открыть
    /// (`Msg::McpOpen`), а в паре B вызовы идут в обратную сторону — шлёт его та сторона, у которой базы нет. Отзыв делает та,
    /// которая разрешала, и наш ключ у неё есть; для возврата довольно адреса партнёра.
    EnrolledHere(BaseFields),
    /// Зачисление уже было: вот база этого потока из `hello_ok`, человека не
    /// спрашивали. Личность доказана самим iroh, и ничего сверх этого не
    /// предъявляется (спека, «Второе и дальнейшие подключения человека не
    /// спрашивают»).
    ///
    /// **База ОДНА, и это тип, а не соглашение.** Прежде здесь ехал список, и
    /// возврат, не назвавший карточку, приносил все базы партнёра сразу: поток
    /// числился за всеми ними, и отзыв ОДНОЙ карточки резал его целиком — прямо
    /// против спеки («отзыв одной карточки не должен рвать связь по четырём
    /// остальным»), а у человека с пятью карточками к одному партнёру резал все
    /// пять потоков разом, потому что каждый из них был «за всеми». Поток у
    /// карточки свой (спека, «Потоки»), значит и база у него одна; возврат,
    /// который не может её назвать однозначно, получает отказ СЛОВАМИ, а не
    /// список, из которого потом никто не выберет (`UNNAMED_RETURN`).
    Already(BaseBrief),
    /// Не зачислены, и это исход: человек отклонил (`code::DECLINED` — сама
    /// не повторяй, код сгорел), человек ушёл, не решив, или звонящий бросил
    /// трубку. У двух последних один код, `code::CLOSED`, а судьба кода
    /// подключения разная — по правилу «чья рука прервала» (шаг пятый
    /// `accept_side`).
    ///
    /// Один код на два случая двусмысленности не создаёт: до зовущей
    /// стороны `CLOSED` доезжает только в одном из них (сообщением `bye`,
    /// когда человек не решил), потому что в другом её поток уже мёртв и
    /// слова ей не доходят вовсе. Для журнала принимающей стороны разницу
    /// говорит текст.
    ///
    /// **Сюда же — отказ МАШИНЫ** (код сгорел, версии не сошлись, база не названа): он тоже произнесён и тоже окончателен.
    /// Живой прогон 15.11 показал, чего стоило обратное: такой отказ возвращался как `Err`, то есть тем же видом, что и
    /// несложившаяся связь, — а её `keep_calling` повторяет молча и бесконечно. Человек нажал «Подключиться», увидел
    /// очистившееся поле и больше ничего, а слова «по этому коду подключиться нельзя» остались в журнале ДРУГОЙ машины.
    /// Комментарий над той строкой обещал ровно нужное — «это человеку исправлять, а не нам повторять», — и один `Err` на
    /// два разных смысла это обещание съедал.
    NotEnrolled(Refuse),
}

/// Первый кадр потока — ОТДЕЛЬНО от разговора о зачислении.
///
/// У потока в канале два законных начала: `Hello` управляющего разговора и `McpOpen` потока вызовов (шаг 4 плана пары B). Кто их
/// различает, тот и читает первый кадр; `accept_side_with` получает его уже прочитанным.
///
/// Отказ уходит той стороне словами тем же `heard`, что и раньше: срок, обрыв и непонятый кадр отвечают одинаково.
pub async fn first_frame<W: AsyncWrite + Unpin, R: AsyncRead + Unpin>(w: &mut W, r: &mut R) -> Result<Msg, String> {
    heard(w, r, PATIENCE).await.map_err(|e| e.text.to_string())
}

/// Принять разговор о зачислении, прочитав первый кадр самостоятельно.
///
/// Остаётся ради тестов и ради тех мест, где у потока одно законное начало: разбор первого кадра живёт в `first_frame`, а всё, что
/// дальше, — в `accept_side_with`.
#[allow(clippy::too_many_arguments)]
pub async fn accept_side<W, R, F, Fut>(
    w: &mut W,
    r: &mut R,
    peer: EndpointId,
    book: &mut Book,
    cards: &Cards,
    ours: Ceiling,
    decide: F,
) -> Result<Outcome, String>
where
    W: AsyncWrite + Unpin,
    R: AsyncRead + Unpin,
    F: FnOnce(Request) -> Fut,
    Fut: Future<Output = Decision>,
{
    let first = first_frame(w, r).await?;
    accept_side_with(first, w, r, peer, book, cards, ours, decide).await
}

/// То же, но первый кадр уже на руках. Здесь и живёт весь разговор принимающей стороны.
///
/// **Принимающая — та, кому позвонили, и та, где спрашивают человека. Где при этом база — другой вопрос**, и отвечает на него
/// названная той стороной `side`: в паре A база здесь, в паре B — у звонящего, и `Cards::pile` выбирает по этому слову кучу
/// карточек. (Прежде этот абзац утверждал обратное — «принимающая та, у которой база», — и стоял осиротевшим над `first_frame`,
/// описывая не ту функцию; оба — находка ревью круга правок 2.)
///
/// `peer` берётся у соединения (`Connection::remote_id`), а не у сообщения: ключ узла — это то, что доказал сам iroh, и соврать о
/// нём в `hello` нельзя. `cards` — карточки этого рабочего места; `decide` — вопрос человеку (в окне диалог, в командной строке
/// `1c-connect requests`/`allow`, в тестах подставной).
///
/// Поток не закрывается здесь нарочно: на зачислении он остаётся жить под присмотром (`channel::hold`), а на отказе его закрывает
/// тот, кто его открывал и кто знает, что ещё по этому соединению висит.
#[allow(clippy::too_many_arguments)]
pub async fn accept_side_with<W, R, F, Fut>(
    first: Msg,
    w: &mut W,
    r: &mut R,
    peer: EndpointId,
    book: &mut Book,
    cards: &Cards,
    ours: Ceiling,
    decide: F,
) -> Result<Outcome, String>
where
    W: AsyncWrite + Unpin,
    R: AsyncRead + Unpin,
    F: FnOnce(Request) -> Fut,
    Fut: Future<Output = Decision>,
{
    // Шаг второй: та сторона открыла поток и представилась. Кадр уже прочитан тем, кто различает два законных начала потока.
    let (proto_min, proto_max, ceiling, why, side) = match first {
        Msg::Hello { proto_min, proto_max, ceiling, why, side, .. } => (proto_min, proto_max, ceiling, why, side),
        other => return refuse_and_fail(w, Refuse::new(code::UNKNOWN_MESSAGE, out_of_turn("hello", &other))).await,
    };
    // Наименьший из двух максимумов (спека, «Версии») — и сверка в ОБЕ
    // стороны. Диапазон этой сборки пока из одного номера, поэтому
    // пересечение есть ровно тогда, когда выбранное равно нашему: ниже —
    // та сторона не доросла до единственной версии, которую мы умеем (или
    // объявила диапазон наизнанку, или нуль, которого не существует); выше
    // не бывает по самому `min`. Когда номеров станет два, здесь встанет
    // сравнение с `PROTO_MIN`, а не с одним числом.
    let proto = proto_max.min(PROTO);
    if proto != PROTO || proto < proto_min {
        return refuse_and_fail(w, Refuse::new(code::VERSION, version_gap(proto_min, proto_max))).await;
    }

    // Настройки не прочитались — и это беда ЗДЕСЬ, а не с её кодом. Говорится
    // о ней обеим сторонам: той — три строки без путей и без совета просить
    // новый код, себе — `Err`, чтобы журнал покраснел. Прежде здесь не было
    // развилки вовсе: нечитаемые настройки приезжали пустым списком карточек,
    // и ниже их ждал отказ «карточку удалили» — ложь про ту машину вместо
    // правды про эту, и ни строки себе (находка 2 живого прогона 9.11 — ровно
    // эта беда, только с мерой чтения).
    let pile = match cards.pile(side) {
        Ok(pile) => pile,
        Err(ours) => return ours_to_blame(w, Refuse::new(code::LOCK, SETTINGS_UNREADABLE), ours.to_string()).await,
    };

    // Что этот ключ уже может: список считается ДО заявки, потому что он же и
    // есть ответ на второе подключение.
    //
    // `enrolled_to`, а не `of`: это решение о ДОПУСКЕ, и читать его из
    // снимка в памяти нельзя. Человек в окне успевает нажать «Отозвать
    // разрешение», пока этот процесс держит книгу открытой, и по снимку
    // отозванная сторона вошла бы как зачисленная — то есть отзыв перестал
    // бы действовать немедленно, как того требует спека.
    let mut bases: Vec<BaseBrief> = Vec::new();
    for c in pile {
        let seen = match book.enrolled_to(c.id(), peer) {
            Ok(seen) => seen,
            // Книгу не прочитать — наша беда, не её: короткие слова на провод,
            // подробность с путями остаётся нам (Important 5).
            Err(why) => return ours_to_blame(w, Refuse::new(code::LOCK, BOOK_UNREADABLE), why).await,
        };
        // **Разрешение годится только для той пары, для которой его дали.** Иначе ключ, которому разрешили присылать свою
        // базу (пара B), после переключения карточки на «База здесь» назвался бы стороной с агентами и получил бы НАШУ базу — без
        // нового вопроса человеку.
        if let Some(p) = seen.filter(|p| p.side == side) {
            // Складываются ЖИВЫЕ половины, и обе: право этой машины по этой
            // карточке (`c.base.write` — его положил `Cfg::may_write`, читая
            // настройки под этот самый разговор) и потолок той машины, только
            // что названный в `hello`. Спека обещает про это поле
            // «складывается оно на каждом подключении» — вот здесь оно и
            // складывается.
            //
            // Снимка из книги (`p.peer_write` в прежнем своём смысле — итог,
            // замороженный в миг зачисления) в этом счёте больше нет, и это
            // Critical повторного ревью: потолок ЭТОЙ машины в него попасть не
            // мог, то есть человек щёлкал у себя «Только чтение», а зачисленная
            // сторона на КАЖДОМ переподключении слышала «разрешено читать и
            // записывать» — и получала отказ от моста. Обратная половина той же
            // беды: зачислили при закрытом потолке, и запись не возвращалась
            // никогда, пока не выдадут новый код.
            let write = crate::wire::folded_write(c.write, ceiling);
            // Чужой потолок — единственное, чего нам неоткуда взять заново, и
            // книга держит его затем, что о нём спрашивает карточка в окне
            // («итог с указанием, какая сторона ограничила» — контракт).
            // Поэтому он обновляется здесь: карточка, говорящая о той машине
            // то, что было месяц назад, — это та же ложь, только в окне.
            //
            // Запись идёт лишь когда значение переменилось: обычное
            // переподключение книгу не трогает вовсе. И правит она ТОЛЬКО
            // существующую запись (`refresh_peer_write`, там и довод): `enroll`
            // здесь был бы вставкой-или-обновлением, то есть воскрешал бы
            // разрешение, стёртое отзывом ровно в эту щель, — человек видел бы
            // опустевший список и отозванную сторону в нём на следующем круге.
            // Отказ записи — наша беда, и говорится она тем же порядком, что все
            // остальные отказы книги в этой функции: короткие слова на провод,
            // подробность с путями нам.
            if p.peer_write != ceiling.allows() {
                match book.refresh_peer_write(c.id(), peer, ceiling.allows()) {
                    Ok(true) => {}
                    // Разрешения больше нет: человек нажал «Отозвать» между
                    // нашим чтением и этой правкой. Отзыв сильнее — карточка в
                    // ответ не идёт, и ниже её ждёт тот же отказ, что всякую
                    // незачисленную.
                    Ok(false) => continue,
                    Err(why) => return ours_to_blame(w, Refuse::new(code::NOT_ALLOWED, NOT_WRITTEN), why).await,
                }
            }
            bases.push(BaseBrief { id: c.id().on_wire(), write });
        }
    }
    // Возврат — и заявки не будет: так сказала сама зовущая сторона, и это
    // единственная мера на обе (`wire::Why`). Прежде здесь спрашивался
    // непогашенный тикет НА ВСЕЙ МАШИНЕ, и возврат первой карточки висел
    // тридцать секунд, пока ждали заявку по коду, выданному для второй.
    if let Why::Return(named) = &why {
        // Назвала карточку — в списке остаётся ОНА ОДНА. Поток у каждой
        // карточки свой (спека, «Потоки»), и числить его за всеми базами
        // партнёра значит рвать отзывом одной карточки связь по остальным —
        // прямо против `revoked`: «отзыв одной карточки не должен рвать связь
        // по четырём остальным».
        //
        // Не назвала (`None`) — так выглядит партнёр от прежней сборки или
        // неудавшаяся запись признака базы (с 10.11 зовущая сторона хранит его
        // рядом с партнёром, `Partners::base_id_of`, и после первого удачного
        // круга называет карточку сама). Отвечаем ей, только если выбора нет:
        // ровно одна зачисленная база — она и есть база этого потока, зовущая
        // её запомнит и дальше назовёт сама. Несколько — выбирать нечем, и
        // прежний ответ «вот весь список» был худшим из возможных: поток
        // числился за всеми базами сразу, и отзыв одной карточки резал связь по
        // остальным.
        let mine: Option<BaseBrief> = match named {
            Some(id) => bases.into_iter().find(|b| &b.id == id),
            None if bases.len() == 1 => bases.into_iter().next(),
            None if !bases.is_empty() => return said_and_not_enrolled(w, Refuse::new(code::NO_BASE, UNNAMED_RETURN)).await,
            None => None,
        };
        let Some(mine) = mine else {
            // Вернулись по карточке, которую человек здесь ПЕРЕКЛЮЧИЛ, пока той
            // стороны не было: база теперь на той стороне, или подключений эта
            // карточка больше не принимает вовсе. Своими словами, а не
            // «разрешение отозвали»: отзыва не было, и просить разрешить заново
            // нечего — по переключённой карточке не получится ничего, пока её не
            // переключат обратно.
            //
            // Но ТОЛЬКО тому, кто к этой карточке зачислен, и допуск
            // спрашивается у КНИГИ, а не выводится из списка, собранного мимо
            // неё (находка проверки безопасности). Признак базы знает и
            // отозванная сторона — она сама его называла, пока была
            // зачислена, — и по разнице в ответах узнавала бы, что карточка
            // жива и что человек переключил у неё базу. Отзыв обязан быть
            // молчанием, а не источником сведений о том, что здесь
            // происходит; незачисленному ответ тот же, что на выдуманный
            // признак, и разницы между «такой карточки здесь нет» и «есть, но
            // она не ваша» по нему не видно.
            // От проводного ключа — к НАШЕЙ карточке (`mine_named`), и только потом к книге: книга ключуется нашим ключом, и чужой
            // в неё не попадает даже по совпадению.
            let aside = named
                .as_ref()
                .and_then(|r| cards.mine_named(r))
                .and_then(|card| cards.aside(card.id()).map(|words| (card.id().clone(), words)));
            if let Some((id, words)) = aside {
                match book.enrolled_to(&id, peer) {
                    Ok(Some(_)) => return said_and_not_enrolled(w, Refuse::new(code::NO_BASE, words)).await,
                    Ok(None) => {}
                    // Книгу не прочитать — наша беда, не её, и здесь по тому же
                    // правилу, что выше: короткие слова на провод, подробность с
                    // путями остаётся нам.
                    Err(why) => return ours_to_blame(w, Refuse::new(code::LOCK, BOOK_UNREADABLE), why).await,
                }
            }
            // Вернулись туда, куда больше не пускают: карточку отозвали,
            // удалили или переименовали. Отказ СЛОВАМИ, а не пустой список:
            // пустой список зовущая прочитала бы как «нечего предъявить» и
            // сказала бы человеку о своей беде вместо нашей причины.
            return said_and_not_enrolled(w, Refuse::new(code::NOT_ALLOWED, NOT_ENROLLED_TEXT)).await;
        };
        write_msg(w, &Msg::HelloOk { proto, bases: vec![mine.clone()], ceiling: ours }).await?;
        // Второе и дальнейшие подключения человека не спрашивают: личность
        // доказана самим iroh. Разговор зачисления кончен.
        return Ok(Outcome::Already(mine));
    }
    write_msg(w, &Msg::HelloOk { proto, bases, ceiling: ours }).await?;

    // Шаг второй, конец: заявка с секретом тикета. Ждём её безусловно — та
    // сторона сказала, что идёт с заявкой, и молчание на этом месте уже не
    // «ей было не о чем просить», а настоящий обрыв.
    //
    // Зачисленная сторона с кодом на руках — это человек, заводящий ВТОРУЮ
    // карточку тому же партнёру, и её заявку обязано разобрать как всякую
    // другую: по той карточке, к которой выдан код, а не отбить словами про
    // первую.
    let (ticket_secret, says_name, their_base) = match heard(w, r, PATIENCE).await {
        Ok(Msg::Enroll { ticket_secret, says_name, base }) => (ticket_secret, says_name, base),
        Ok(other) => return refuse_and_fail(w, Refuse::new(code::UNKNOWN_MESSAGE, out_of_turn("enroll", &other))).await,
        Err(no) => return refuse_and_fail(w, no).await,
    };

    // Шаг третий: проверка МОЛЧА. Человека здесь нет и быть не должно.
    let Some(secret) = decode_secret(&ticket_secret) else {
        return said_and_not_enrolled(w, Refuse::new(code::TICKET_FOREIGN, FOREIGN_TEXT)).await;
    };
    let card_key = match book.verdict(&secret) {
        Ok(Verdict::Card(key)) => key,
        Ok(Verdict::Expired) => return said_and_not_enrolled(w, Refuse::new(code::TICKET_EXPIRED, EXPIRED_TEXT)).await,
        Ok(Verdict::Unknown) => return said_and_not_enrolled(w, Refuse::new(code::TICKET_SPENT, UNKNOWN_TEXT)).await,
        // Третий случай, и он НЕ про код: книгу не удалось прочитать. Той
        // стороне — короткие слова без путей, нам — `Err`, чтобы журнал
        // покраснел: советовать человеку просить новый код, когда беда в
        // нашем файле, значит послать его за тем, что не поможет.
        Err(why) => return ours_to_blame(w, Refuse::new(code::LOCK, BOOK_UNREADABLE), why).await,
    };
    let Some(card) = pile.iter().find(|c| c.id() == &card_key) else {
        // Карточка на месте, а в выбранной куче её нет: либо её переключили в
        // «Подключаюсь сам» или «Всё на одной машине» уже после того, как
        // выдали код, либо стороны не сложились в пару (база у обоих или ни у
        // кого — разбирает `mismatch_of` ниже). Говорится это словами, а не
        // «карточку удалили»: карточку никто не удалял, и заводить её заново
        // незачем.
        if let Some(words) = cards.aside(&card_key) {
            return said_and_not_enrolled(w, Refuse::new(code::NO_BASE, words)).await;
        }
        // Карточка есть, но она на одной стороне с собеседником: база у обоих либо ни у кого. Это разные беды с разными словами,
        // и обе чинятся одним щелчком у человека — а общий отказ «подходящей карточки нет» не говорил, у кого и каким.
        if let Some(no) = cards.mismatch_of(&card_key, side) {
            return said_and_not_enrolled(w, Refuse::new(code::NO_BASE, no.text())).await;
        }
        return said_and_not_enrolled(w, Refuse::new(code::NO_BASE, NO_CARD_TEXT)).await;
    };

    // Оговорка: по одному коду идёт один разговор.
    //
    // Без неё «один тикет — одна заявка» держится только на гонке записи:
    // `verdict` не портит, `spend` зовётся после решения, и два соединения с
    // одним секретом приносят человеку ДВА диалога об одном и том же — то
    // самое дёрганье, от которого секрет и заведён.
    let Some(_claim) = claim(&secret) else {
        return said_and_not_enrolled(w, Refuse::new(code::BUSY, ALREADY_TALKING)).await;
    };

    // **Чья база в вопросе о разрешении** — та же ось, что выбрала кучу выше. В паре A база наша, её держит сама карточка. В паре B
    // база у ТОЙ стороны, и приехать её поля обязаны в заявке: без них человеку нечего показать, и это отказ словами, а не пустая
    // строка в диалоге.
    let shown_base = match side {
        Side::WithAgents => card.on_wire(),
        Side::WithBase => match their_base {
            Some(base) => base,
            None => return said_and_not_enrolled(w, Refuse::new(code::MALFORMED, BASE_NOT_SAID)).await,
        },
    };

    // Шаг четвёртый: человек. `enroll_wait` уходит ДО диалога — иначе зовущая
    // сторона просидит минуты в тишине и сочтёт её обрывом.
    write_msg(w, &Msg::EnrollWait).await?;
    let request = Request { card_name: card.name.clone(), card: card.id().clone(), base: shown_base, peer, says_name: says_name.clone() };
    let decision = tokio::time::timeout(DECISION, async {
        tokio::select! {
            d = decide(request) => Some(d),
            _ = interrupted(r) => None,
        }
    })
    .await;
    let decision = match decision {
        Ok(Some(d)) => d,
        // Трубку бросил ЗВОНЯЩИЙ — и тикет гасится. Правило здесь не про
        // таймер, а про то, ЧЬЯ РУКА прервала разговор (круг починки 1,
        // MEDIUM 2). Звонящий получил свою одну заявку и распорядился ею
        // сам: оставь код живым — и он бросает трубку сразу после того, как
        // диалог показан, столько раз, сколько захочет, пока человек не
        // нажмёт «да». Ровно от этого секрет и заводился.
        //
        // Говорить в мёртвый поток нечего, поэтому слова никуда не уходят —
        // но исход записывается тот же, что у любого непрошедшего
        // зачисления.
        Ok(None) => {
            let _ = book.spend(&secret);
            return Ok(Outcome::NotEnrolled(Refuse::new(code::CLOSED, HUNG_UP)));
        }
        // Истёк срок решения — прервал не звонящий, а наш собственный
        // таймер, то есть рука человека так и не дошла до кнопки. Это тот же
        // случай, что закрытое окно, и наказывать человека отменой кода не
        // за что.
        Err(_) => Decision::NoAnswer,
    };

    // Шаг пятый.
    match decision {
        Decision::Allow => {
            // Гасим ДО записи ключа: обратный порядок оставил бы живой код у
            // человека на руках после сбоя записи, то есть позволил бы
            // подключиться по нему второй раз. Сгоревший код при сбое — всего
            // лишь просьба выдать новый.
            //
            // Отказ книги здесь — не наш `Err`, а отказ СЛОВАМИ той стороне:
            // молчаливый выход оставил бы зовущую ждать ответа до конца её
            // собственного срока, то есть пять с лишним минут тишины вместо
            // одной строки, которую человек прочитает сразу.
            if let Err(why) = book.spend(&secret) {
                return ours_to_blame(w, Refuse::new(code::TICKET_SPENT, UNKNOWN_TEXT), why).await;
            }
            // Складываются ТРИ меры, и ровно те же, что на возврате выше:
            // потолок этой машины и слово карточки (сложены в `card.base.write`
            // одной `Cfg::may_write`) да потолок той машины из `hello`. Запрет
            // любой стороны сильнее разрешения другой (решение владельца 1.11)
            // — иначе машина, объявившая у себя «только чтение», получает от
            // нас `enroll_ok{write:true}`, то есть разрешение, которое сама же
            // у себя запретила.
            //
            // В книгу уходит ОДНА из трёх — чужой потолок: две свои она
            // спросит у настроек, когда ответ понадобится (`Party::peer_write`,
            // там и довод).
            let write = crate::wire::folded_write(card.write, ceiling);
            // Сторона уезжает в книгу вместе с разрешением: человек разрешил ЭТО, а не похожее. Переключит он потом «Где
            // база» у карточки — и прежнее разрешение заговорило бы о другом (находка проверки безопасности 11.11, вторая волна).
            if let Err(why) = book.enroll(card.id(), peer, says_name.as_str(), ceiling.allows(), side) {
                return ours_to_blame(w, Refuse::new(code::NOT_ALLOWED, NOT_WRITTEN), why).await;
            }
            // Исход несёт НАШУ карточку проводным ключом в обеих парах: по нему принимающая сторона числит поток за карточкой
            // (`peer::answering` → `Cards::mine_named`), и отзыв этой карточки рвёт именно его.
            let base = BaseFields { write, ..card.on_wire() };
            // А на провод наша база уезжает только там, где она у нас есть: в паре B её тут нет вовсе, и поле пустое — той стороне
            // неоткуда узнать о базе, которой не бывает.
            let said = match side {
                Side::WithAgents => Some(base.clone()),
                Side::WithBase => None,
            };
            write_msg(w, &Msg::EnrollOk { base: said }).await?;
            Ok(Outcome::Enrolled(base))
        }
        Decision::Deny => {
            // Код гасится и на отказе: «один тикет — одна заявка» (спека,
            // «Зачем в тикете секрет»). Оставь его живым — и отклонённый
            // звонящий дёргает человека тем же кодом, пока тот не нажмёт
            // «да»; ровно от этого секрет и заведён. Сбоя сети здесь нет:
            // человек ответил, решение состоялось.
            let _ = book.spend(&secret);
            let no = Refuse::new(code::DECLINED, DECLINED_TEXT);
            write_msg(w, &Msg::EnrollNo(no.clone())).await?;
            Ok(Outcome::NotEnrolled(no))
        }
        Decision::NoAnswer => {
            // Тикет НЕ гасим: прервал человек, а не звонящий, и он ничего не
            // выбрал — сжигать ему код за закрытое окно не за что.
            let no = Refuse::new(code::CLOSED, NO_ANSWER_TEXT);
            write_msg(w, &Msg::Bye(no.clone())).await?;
            Ok(Outcome::NotEnrolled(no))
        }
    }
}

/// Зовущая сторона — та, что вставила код.
///
/// Чем она звонит — заявкой по коду или возвратом по уже данному допуску —
/// говорит `Call`, и это же уезжает на провод (`wire::Why`): принимающая
/// сторона не гадает об этом по своим признакам. Заявка уходит ВСЕГДА, когда
/// код на руках, даже если зачисление к какой-то карточке уже есть, — иначе
/// законный код второй карточки не сработал бы никогда.
///
/// Возврат НАЗЫВАЕТ свою карточку, если помнит её (`Call::Return(Some)`), и
/// получает в ответ её одну: поток у каждой карточки свой, и числить его за
/// всеми базами партнёра значит рвать отзывом одной связь по остальным.
/// Безымянный возврат получает одну базу, если выбора нет вовсе, и отказ
/// словами, если баз несколько, — выдумывать за него карточку нельзя.
#[allow(clippy::too_many_arguments)]
pub async fn dial_side<W, R>(
    w: &mut W,
    r: &mut R,
    call: Call<'_>,
    says_name: &str,
    ceiling: Ceiling,
    side: Side,
    base: Option<BaseFields>,
) -> Result<Outcome, String>
where
    W: AsyncWrite + Unpin,
    R: AsyncRead + Unpin,
{
    // Сторону звонящая НАЗЫВАЕТ, а не выводит её принимающая по своим признакам: от этого слова зависит, к какой куче карточек
    // пойдёт зачисление на той стороне (`Cards::pile`). Поля базы едут с заявкой там, где база у звонящего (пара B).
    let hello = Msg::Hello { proto_min: PROTO, proto_max: PROTO, side, says_name: says_name.into(), ceiling, why: call.why() };
    write_msg(w, &hello).await?;

    let (bases, theirs) = match heard(w, r, PATIENCE).await.map_err(|e| e.text)? {
        Msg::HelloOk { proto, bases, ceiling: theirs } => {
            // Выбранную версию обязана СМОТРЕТЬ и зовущая. Та сторона
            // выбирает её сама, и ошибиться может не только злой умысел:
            // старая сборка с другим правилом выбора объявит номер, которого
            // мы не умеем, и дальше весь разговор пойдёт по чужим правилам,
            // внешне исправно.
            if proto != PROTO {
                return refuse_and_fail(w, Refuse::new(code::VERSION, version_chosen(proto))).await;
            }
            (bases, theirs)
        }
        // Отказ, произнесённый ДО заявки (версия протокола, нечитаемые настройки той стороны), — такой же исход, как и
        // отказ после неё: повторять его нечем, а сказать человеку обязаны.
        Msg::Refuse(no) => return Ok(Outcome::NotEnrolled(no)),
        other => return refuse_and_fail(w, Refuse::new(code::UNKNOWN_MESSAGE, out_of_turn("hello_ok", &other))).await,
    };
    // Решает `Call`, а не длина строки и не список баз: решение принято один
    // раз, при звонке, и здесь только исполняется.
    let shown = match call {
        Call::Return(_) => {
            // Зачисление есть, кода нет — предъявлять нечего: второе и
            // дальнейшие подключения человека не спрашивают. База в ответе
            // обязана быть РОВНО ОДНА: поток у карточки свой, и числить его за
            // несколькими базами значит рвать отзывом одной связь по остальным.
            let mut bases = bases;
            return match bases.len() {
                // Сюда доходит только та сторона, которая ответила пустым
                // списком вместо отказа: наша принимающая половина на возврат
                // без допуска говорит словами (`NOT_ENROLLED_TEXT`). Своих
                // слов здесь всё равно не миновать — промолчать значило бы
                // вернуть человеку пустой исход без причины.
                0 => Err("Подключиться не удалось: нечего предъявить.\nКода подключения нет, а подключаться к ней вам ещё не \
                          разрешали.\nПопросите код на компьютере, к которому подключаетесь."
                    .to_string()),
                1 => Ok(Outcome::Already(bases.remove(0))),
                // И эта сторона тоже отвечает не по нашим правилам: наша
                // принимающая половина на возврат присылает одну базу либо
                // отказ словами (`UNNAMED_RETURN`).
                several => Err(format!(
                    "Подключиться не удалось: тот компьютер ответил не про одну базу.\nПоток этой карточки ведёт к одной базе, а в \
                     ответе их {several}.\nОбновите комплект на том компьютере."
                )),
            };
        }
        Call::Enroll(code) => code,
    };

    let ticket = Ticket::from_code(shown)?;
    // Поля НАШЕЙ базы, если она у нас: их же мы объявим той стороне и ими же назовём исход в паре B — второй раз складывать
    // право записи негде, и разойтись объявленному с тем, что мы потом скажем человеку, тоже негде.
    let mine = base.map(|b| BaseFields { write: crate::wire::folded_write(b.write, theirs), ..b });
    let enroll = Msg::Enroll {
        // Секрет уезжает hex-ом — тем же видом, в каком он лежал в коде
        // тикета. Сам `Msg::Enroll` в журнал не пишется НИКОГДА: его `Debug`
        // напечатал бы секрет целиком.
        ticket_secret: hex::encode(&*ticket.secret),
        says_name: says_name.into(),
        // Поля базы едут от той стороны, у которой база: в паре A это принимающая, и сказать нам нечего (`None`); в паре B база
        // здесь, и её поля — единственное, откуда та сторона их узнает (`Cards::pile`, ветка `WithBase`).
        //
        // Право записи складывается ЗДЕСЬ, потому что складывать его может только сторона с базой: свои две меры уже сложены в
        // поле (`Cfg::may_write`), третья — потолок той машины из `hello_ok`. Выражение одно на обе пары (`wire::folded_write`).
        base: mine.clone(),
    };
    write_msg(w, &enroll).await?;

    // Первый ответ: либо сразу исход, либо «ждите» — и тогда ждём человека.
    let answered = match heard(w, r, PATIENCE).await.map_err(|e| e.text)? {
        Msg::EnrollWait => heard(w, r, DECISION + PATIENCE).await.map_err(|e| e.text)?,
        first => first,
    };
    match answered {
        // **Бывают ли поля базы в ответе — решает ПАРА, и та же, что судит законность сочетания** (`cfg::Pair`, один закон на
        // десять клеток; второй оси «где база» в продукте нет). Звонящая сторона называет пару одна: позвонил тот, у кого база, —
        // пара B, позвонили агенты — пара A.
        //
        // Чем куплено (замер круга пары B на двух узлах, 16.11). Прежде эта ветка была одна на обе пары и читала `base: None` как
        // беду чужого комплекта. В паре B принимающая сторона базы НЕ ИМЕЕТ и шлёт `None` нарочно и верно — а человек с базой,
        // позвонивший ей, читал «Обновите комплект на нём и подключитесь заново» про машину, которая только что его зачислила.
        Msg::EnrollOk { base } => Ok(match (crate::cfg::Pair::of_caller(side), mine, base) {
            // Пара B: договорились о НАШЕЙ базе, её поля мы же и объявили. Что бы та сторона ни прислала о базе, нашей она не
            // знает и знать не может — берём своё.
            (crate::cfg::Pair::B, Some(ours), _) => Outcome::EnrolledHere(ours),
            // Пара A: база у принимающей, и её поля — единственное, откуда зовущая их узнаёт.
            (crate::cfg::Pair::A, _, Some(theirs)) => Outcome::Enrolled(theirs),
            // Пара A без полей базы — беда той стороны, и слова остаются ровно здесь. Пара B без НАШИХ полей сюда не доходит:
            // назвавшись стороной с базой и не дав её полей, мы получили бы отказ `BASE_NOT_SAID` ещё до `enroll_wait`.
            //
            // Исход, а не сбой: повтор не починит чужой комплект, а молчаливый повтор спрячет причину (прогон 15.11).
            _ => Outcome::NotEnrolled(Refuse::new(code::NO_BASE, NO_BASE_IN_OK)),
        }),
        // Исход, а не ошибка: сами не повторяем.
        Msg::EnrollNo(no) => Ok(Outcome::NotEnrolled(no)),
        // Человек ушёл, не решив, — тоже исход, но код ещё жив.
        Msg::Bye(no) => Ok(Outcome::NotEnrolled(no)),
        // Отказ машины: код негодный, версии не сошлись. Это человеку исправлять, а не нам повторять — и теперь так и выражено:
        // ИСХОД, который зовущая сторона скажет словами и на котором остановится. `Err` здесь значил «связь не сложилась», и
        // повтор по нему был молчаливым и вечным (живой прогон 15.11).
        Msg::Refuse(no) => Ok(Outcome::NotEnrolled(no)),
        other => refuse_and_fail(w, Refuse::new(code::UNKNOWN_MESSAGE, out_of_turn("enroll_ok", &other))).await,
    }
}

/// Читает кадр со СВОИМ сроком.
///
/// `Frame::read` без срока нарочно (см. его докстроку): срок — за
/// вызывающим, потому что у каждого потока он свой. Здесь он есть всюду, и
/// это ровно тот случай, под который правило и писалось: разговор зачисления
/// не бывает «пока тихо, значит думают» — думают только за `enroll_wait`, и
/// у этого ожидания свой срок (`DECISION`).
async fn next<R: AsyncRead + Unpin>(r: &mut R, within: Duration) -> Result<Msg, Refuse> {
    match tokio::time::timeout(within, Frame::read(r)).await {
        Ok(got) => got,
        Err(_) => Err(Refuse::new(code::BROKEN, silent_for(within))),
    }
}

/// `next`, но отказ чтения не проглатывается молча — он УЕЗЖАЕТ той стороне.
///
/// Спека прямо: «отказывает на незнакомое сообщение… проглотить молча значит
/// соврать отправителю, что оно исполнено». Без этого зовущая сторона,
/// прислав сообщение не из нашей версии, получала бы вместо причины свою
/// собственную тишину и, через срок, слова «та сторона не ответила» — худший
/// из возможных отчётов, потому что он указывает не туда.
///
/// Отправляется и на обрыв, и на срок: писать в мёртвый поток бесполезно, но
/// не вредно, а отличить «мёртвый» от «живого, но непонятного» здесь нечем —
/// и именно во втором случае слова нужны.
async fn heard<W: AsyncWrite + Unpin, R: AsyncRead + Unpin>(w: &mut W, r: &mut R, within: Duration) -> Result<Msg, Refuse> {
    match next(r, within).await {
        Ok(msg) => Ok(msg),
        Err(no) => {
            let _ = Frame::write(w, &Msg::Refuse(no.clone())).await;
            Err(no)
        }
    }
}

/// Ждёт, не прервёт ли разговор ЗВОНЯЩИЙ: скажет что-нибудь, закроет поток
/// или оборвётся. Завершается — значит прервал.
///
/// **Один байт, а не `Frame::read`, и это про отменяемость.** Это ожидание
/// живёт в `select!` против диалога человека, то есть его бросают
/// недождавшимся — и `Frame::read` в таком месте опасен: он читает заголовок
/// и тело по очереди, и брошенный между ними съедает четыре байта заголовка
/// НАВСЕГДА. Дальше поток живёт под присмотром, и всё, что по нему пойдёт,
/// разберётся как мусор — человек увидит обрыв сразу после успешного
/// зачисления, в худшую для этого минуту.
///
/// Чтение одного байта такого промежутка не имеет: `poll_read` либо вернул
/// байт (и тогда ждавшая ветка `select!` завершилась, разговор кончен и
/// съеденный байт никому не нужен), либо не вернул ничего и не тронул поток.
/// Правило «либо не начиналось, либо довелось до конца» выполняется само.
async fn interrupted<R: AsyncRead + Unpin>(r: &mut R) {
    let mut one = [0u8; 1];
    let _ = r.read(&mut one).await;
}

/// Сколько разговоров идёт прямо сейчас по каждому выданному коду.
///
/// Ключ — sha256 от секрета, а не сам секрет: держать секреты в глобальной
/// памяти дольше, чем нужно, незачем, а сравнивать отпечатки так же удобно.
///
/// Потолок: оговорка живёт в ПАМЯТИ ПРОЦЕССА. Этого ровно хватает, потому
/// что узел на машине один и входящие соединения принимает один процесс;
/// второй процесс с той же книгой (окно и подкоманда `mcp`) заявок не
/// принимает. Когда начнёт — оговорка переедет в книгу, как и всё, что
/// обязано быть видно обоим.
static TALKING: std::sync::Mutex<Option<std::collections::HashSet<[u8; 32]>>> = std::sync::Mutex::new(None);

/// Оговорка на один разговор по одному коду, снимаемая сама (`Drop`).
///
/// `Drop`, а не снятие руками: путей выхода из разговора девять, и девятый
/// забудут. Снятие на `Drop` работает и на отмене всей задачи.
struct Claim([u8; 32]);

impl Drop for Claim {
    fn drop(&mut self) {
        if let Ok(mut held) = TALKING.lock() {
            if let Some(set) = held.as_mut() {
                set.remove(&self.0);
            }
        }
    }
}

/// Занимает код под разговор. `None` — по нему уже говорят.
fn claim(secret: &[u8; 32]) -> Option<Claim> {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(secret);
    let key: [u8; 32] = h.finalize().into();
    // Отравленный замок — беда настолько своя, что отказывать по нему
    // человеку не за что: `unwrap_or_else` берёт данные из паники, и хуже,
    // чем лишний диалог, уже не станет.
    let mut held = TALKING.lock().unwrap_or_else(|e| e.into_inner());
    if held.get_or_insert_with(Default::default).insert(key) {
        Some(Claim(key))
    } else {
        None
    }
}

/// Сказать той стороне КОРОТКО, а подробность оставить себе.
///
/// Для беды, которая наша, а не её: книга не прочиталась, замок не взялся,
/// запись не удалась. Слова книги на провод отдавать нельзя — в них лежат
/// пути вида `C:\Users\…\enrolled.toml`, то есть и утечка устройства этой
/// машины чужой стороне, и нарушение правила трёх строк из раздела
/// «Ошибки». А `Err` наружу нужен затем, что в нашем журнале это обязано
/// краснеть: советовать человеку просить новый код, когда беда в нашем
/// файле, значит послать его за тем, что не поможет.
async fn ours_to_blame<W: AsyncWrite + Unpin>(w: &mut W, wire: Refuse, ours: String) -> Result<Outcome, String> {
    let _ = Frame::write(w, &Msg::Refuse(wire)).await;
    Err(ours)
}

/// Отправка в позиции `?`: слова отказа кадрирования уже написаны в
/// `wire.rs`, здесь остаётся только взять из него текст для человека, а не
/// `Display` — тот подмешивает код внутрь строки, чего раздел «Ошибки»
/// спеки не разрешает.
async fn write_msg<W: AsyncWrite + Unpin>(w: &mut W, msg: &Msg) -> Result<(), String> {
    Frame::write(w, msg).await.map_err(|e| e.text.into())
}

/// Сказать словами и провалиться: отказ уходит той стороне, а нам остаётся
/// `Err` — разговора не было вовсе, зачислять некого и исхода нет. Так
/// кончаются только поломки самого разговора: не та версия, сообщение не в
/// свой черёд.
async fn refuse_and_fail<W: AsyncWrite + Unpin>(w: &mut W, no: Refuse) -> Result<Outcome, String> {
    // Отказ отправки проглатываем: сказать о ней всё равно нечем, а нести
    // наружу надо ту беду, из-за которой мы отказали, а не вторичную.
    let _ = Frame::write(w, &Msg::Refuse(no.clone())).await;
    Err(no.text.into())
}

/// Сказать словами и вернуть ИСХОД: разговор состоялся, зачисления нет.
///
/// Отличается от `refuse_and_fail` тем, чья это беда. Здесь принимающая
/// сторона отработала правильно — негодный код, удалённая карточка, сбой
/// записи, — и журнал этой машины не должен краснеть там, где замок на
/// дверном звонке просто сработал.
async fn said_and_not_enrolled<W: AsyncWrite + Unpin>(w: &mut W, no: Refuse) -> Result<Outcome, String> {
    write_msg(w, &Msg::Refuse(no.clone())).await?;
    Ok(Outcome::NotEnrolled(no))
}

/// Разбирает hex секрета в ровно 32 байта. `Option`, а не `Result` со
/// словами: что именно не так с чужим секретом, человеку не рассказывают —
/// отказ тут один на все случаи, и подсказывать подбирающему, насколько он
/// близок, незачем.
fn decode_secret(hexed: &str) -> Option<[u8; 32]> {
    hex::decode(hexed).ok()?.as_slice().try_into().ok()
}

/// «Пришло не то, чего ждали на этом шаге.»
///
/// Имя пришедшего сообщения берётся из `named`, а НЕ из `{other:?}`:
/// `Msg::Enroll` в `Debug` несёт секрет тикета, и одно такое форматирование
/// в тексте отказа или в журнале выдало бы его целиком.
pub(crate) fn out_of_turn(expected: &str, got: &Msg) -> String {
    format!(
        "Разговор о подключении пошёл не по порядку.\nЖдали «{expected}», а пришло «{}».\nОбновите комплект на обоих компьютерах: скорее всего, \
         они разошлись версиями.",
        named(got)
    )
}

/// Имя сообщения на проводе. Serde имён вариантов наружу не отдаёт, а
/// `Debug` брать нельзя (см. `out_of_turn`), поэтому перебор здесь. Полноту
/// держит сам компилятор: перебор без заглушки, и новое сообщение в `Msg`
/// уронит сборку здесь, а не напечатает «неизвестно» в журнале.
fn named(msg: &Msg) -> &'static str {
    match msg {
        Msg::Hello { .. } => "hello",
        Msg::HelloOk { .. } => "hello_ok",
        Msg::Enroll { .. } => "enroll",
        Msg::EnrollWait => "enroll_wait",
        Msg::EnrollOk { .. } => "enroll_ok",
        Msg::EnrollNo(_) => "enroll_no",
        Msg::Revoked { .. } => "revoked",
        Msg::Refuse(_) => "refuse",
        Msg::Bye(_) => "bye",
        Msg::McpOpen { .. } => "mcp_open",
        Msg::McpOk => "mcp_ok",
    }
}

fn version_gap(their_min: u32, their_max: u32) -> String {
    format!(
        "Версии не сошлись: здесь {PROTO}, там от {their_min} до {their_max}.\nЭтот компьютер не понимает ни одной версии, которую \
         понимает тот.\nОбновите комплект там, где он старше."
    )
}

/// Та сторона выбрала номер, которого мы не умеем. Отдельные слова от
/// `version_gap`: там диапазоны не пересеклись честно, здесь пересечение
/// было, а выбор из него сделан не тот — и это чужая ошибка, а не возраст
/// комплекта.
fn version_chosen(theirs: u32) -> String {
    format!(
        "Версии не сошлись: та сторона выбрала {theirs}, а эта говорит по {PROTO}.\nВыбор версии делает компьютер с базой, и этот номер нам \
         не подходит.\nОбновите комплект на обоих компьютерах."
    )
}

fn silent_for(within: Duration) -> String {
    format!(
        "Тот компьютер не ответил.\nЖдали {} с и не дождались ни слова.\nПроверьте, запущена ли программа там, и подключитесь заново.",
        within.as_secs()
    )
}

