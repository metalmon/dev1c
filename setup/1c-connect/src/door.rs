    /// **Сроки вокруг звонка идут строго по возрастанию: дело, дверь, клиент** (находка ревью круга 1, Major 1).
    ///
    /// Сравняйся любые два — наружный истекал бы ПЕРВЫМ и всегда: внутренний заводится на миллисекунды позже (чтение настроек, `spawn_blocking`). А истёкший срок двери — это оборванный разговор, и человек читает «живой экземпляр не ответил (причина: closed)» вместо настоящей причины, которую как раз дописывает живой: «ответа так и не было, проверьте, запущена ли программа на том компьютере». Диагноз о своём беке там, где виновата та машина.
    #[test]
    fn the_three_waits_around_a_call_grow_strictly_outward() {
        assert_eq!(Ask::Status.wait(), ASK_WAIT);
        assert_eq!(Ask::Code { card: None }.wait(), ASK_WAIT);
        assert_eq!(DIAL_WAIT, crate::enroll::DECISION + crate::enroll::PATIENCE, "мера дела — та же, что у самого разговора");
        let at_the_door = Ask::Dial { code: String::new(), card: None }.wait();
        // Клиент считает свой срок тем же выражением, что и `ask_at`, — порядок проверяется на том, что там и стоит.
        let at_the_client = at_the_door + ASK_WAIT;
        assert!(DIAL_WAIT < at_the_door, "срок двери обязан пережить само дело: {DIAL_WAIT:?} против {at_the_door:?}");
        assert!(at_the_door < at_the_client, "срок клиента обязан пережить дверь: {at_the_door:?} против {at_the_client:?}");
        assert_eq!(at_the_door - DIAL_WAIT, ASK_WAIT, "запас взят не на глазок, а обычным сроком обмена");
    }

    /// **Чем платят за истёкший срок двери** — и почему запас выше не роскошь. Дело не уложилось в срок, который отмерила ему дверь: ответа она не пишет вовсе, и клиент читает не причину, а оборванный разговор. Проверяется на обычном вопросе (`Code`, срок `ASK_WAIT`) — у звонка то же самое стоило бы тесту пяти с половиной минут.
    ///
    /// Тест и держит довод Major 1: пока сроки идут по возрастанию, этим путём звонок не ходит; сравняй их — и человек на живом прогоне прочтёт вот эту строку вместо настоящей.
    #[test]
    fn a_deed_that_outlives_the_door_loses_its_words() {
        let (_dir, kit) = kit_for_test();
        let name = test_door("overrun");
        let door = open_at(&name, &kit).expect("дверь открылась");
        let late = Answer::Code(Err("эти слова человек не увидит".into()));
        door.answers(a_doer(late, ASK_WAIT + Duration::from_secs(1)));
        let no = ask_at(&name, &kit, Ask::Code { card: None }).expect_err("ответа не будет вовсе");
        assert!(no.contains("не ответил"), "клиент читает оборванный разговор, а не причину: {no}");
    }

    /// Исход звонка словами: зачислили — успех, отказали — «не сделано» с ПРИЧИНОЙ. Слова берутся у зачисления (`Refuse::text`) и здесь не сочиняются: второй словарь исходов — ровно то, против чего эта ветка и воюет.
    #[test]
    fn the_outcome_of_a_call_is_said_in_the_words_of_enrolment() {
        let up = dialled_words("Ромашка", &an_outcome()).expect("зачислённый возврат — успех");
        assert!(up.contains("Ромашка") && up.contains("подключено"), "{up}");
        let no = crate::enroll::Outcome::NotEnrolled(wire::Refuse::new(wire::code::TICKET_SPENT, "Код устарел.\nСовсем.\nВыдайте новый."));
        let said = dialled_words("Ромашка", &no).expect_err("незачисление — это «не сделано», и код возврата не ноль");
        assert!(said.contains("Код устарел"), "причина — словами той стороны, а не нашим пересказом: {said}");
    }

    /// «О связи пока не сообщает» и «связей нет» — РАЗНЫЕ слова человеку, а не одна пустота на оба случая. Тест и держит это различие: пропади оно, `status` отвечал бы молчанием там, где обязан отвечать словами.
    #[test]
    fn not_telling_and_nothing_connected_are_different_words() {
        let unknown = status_lines(&StatusView { serving: true, cards: None });
        let none = status_lines(&StatusView { serving: true, cards: Some(vec![]) });
        let one = status_lines(&StatusView {
            serving: true,
            cards: Some(vec![CardState { name: "Ромашка".into(), word: "подключено".into() }]),
        });
        assert_ne!(unknown, none, "незнание и отсутствие связей не одно и то же");
        assert!(unknown[1].contains("не сообщает"), "{:?}", unknown);
        assert!(none[1].contains("не связана"), "{:?}", none);
        assert!(one[1].contains("Ромашка") && one[1].contains("подключено"), "{:?}", one);
        assert!(one[0].contains(crate::SUBJECT), "предмет назван общим словом: {:?}", one);
        assert!(status_lines(&StatusView { serving: false, cards: None })[0].contains("выключен"));
    }
