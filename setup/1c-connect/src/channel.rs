//! Канал: соединение iroh на пару машин и управляющие потоки внутри него.
//!
//! Нижний слой — узел и провод — в `node.rs`; разговор зачисления — в
//! `enroll.rs`. Здесь то, что между ними: кто принимает входящие, кто звонит,
//! как долго живёт поток и чем его конец отличается от обрыва.
//!
//! **Управляющий поток — на СОЕДИНЕНИЕ, а не на канал** (решение владельца
//! 1.11, спека, раздел «Потоки»). У каждой карточки свой управляющий поток, и
//! открывает его та сторона, которая по ЭТОЙ карточке зовущая. Канал при этом
//! остаётся один на пару машин: внутри него уживается по одному управляющему
//! потоку на живую карточку, и направления у них бывают разные. Довод спеки:
//! иначе машина, у которой с одним и тем же партнёром соединения обоих
//! направлений (аутсорсер звонит по базе заказчика и сам принимает звонок того
//! же заказчика к своей тестовой базе), нарушала бы правило «принимающая не
//! звонит» самим фактом своего существования.
//!
//! **Закрытие управляющего потока — конец ЭТОГО соединения, а не канала.**
//! Соседние карточки в том же канале живут дальше. Канал закрывается сам,
//! когда в нём не осталось ни одного живого управляющего потока ни в каком
//! направлении, — и считает их `Hold`, снимаемый `Drop`, а не пересчёт по
//! запросу: путей выхода из разговора много, и последний забудут.
//!
//! **Своего пинга нет** (решение спеки). Жив ли путь — знает iroh, и второй
//! таймер поверх его таймера дал бы только два разных мнения о том, когда
//! считать связь потерянной. Поэтому `hold` ждёт кадр БЕЗ своего срока: на
//! управляющем потоке молчание законно часами (у человека на той стороне может
//! не меняться ничего), и срок здесь означал бы «разорвать живое».
//!
//! **`bye` отличает намеренный уход от обрыва.** Выключили обслуживание,
//! закрыли окно, снимается машина — человек на той стороне обязан прочитать
//! причину, а не «связь пропала». Поэтому конец потока — не одно событие, а
//! два разных (`Gone`), и перепутать их нечем.
//!
//! Спека: `docs/superpowers/specs/2026-11-01-protocol-design.md`, разделы
//! «Один канал на машину, а не на базу», «Потоки», «Обрыв и переподключение».

use crate::node::Node;
use crate::wire::{code, Frame, Msg, Refuse};
use iroh::endpoint::{Connection, RecvStream, SendStream, VarInt};
use iroh::{EndpointAddr, EndpointId};
use std::collections::HashMap;
use std::future::Future;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::{Arc, Mutex};
use std::time::Duration;
use tokio::io::AsyncRead;

/// Код закрытия канала на проводе QUIC — ноль, «закрыли нарочно и без жалоб».
///
/// Причина, если она есть, уже сказана словами в `bye` по управляющему потоку;
/// второй её экземпляр числом не прочитает никто, а разные числа тут
/// означали бы второе мнение о том же событии.
const CLOSED_BY_US: u32 = 0;

/// Предел задержки переподключения — минута (спека, «Обрыв и
/// переподключение»: «секунда, две, четыре и так до минуты, дальше раз в
/// минуту бесконечно»). Сдаваться незачем: сервер заказчика может быть
/// выключен на ночь.
pub const LONGEST_WAIT: Duration = Duration::from_secs(60);

/// Сколько уходящий ждёт, пока написанное им признают доехавшим (`settle`).
/// Пять секунд — это «провод жив, просто далеко»; больше брать нечего: не
/// доехало за них, значит той стороне и так достанется обрыв, а держать
/// закрытие окна человека дольше незачем.
///
/// **Цена, которую надо знать: это пять секунд НА КАРТОЧКУ.** Выход
/// (`Control::end`, `Reins::bye`) — фьючер, и у человека с пятью карточками
/// пять таких фьючеров подряд дают двадцать пять секунд незакрывающегося
/// окна. Прощаться надо ЗАЛПОМ (`JoinSet`, `join_all`), и делать это
/// вызывающему: здесь неизвестно, сколько карточек он закрывает и закрывает
/// ли их все. Своего залпа этот модуль не заводит ровно потому, что залп —
/// свойство выхода ПРОГРАММЫ, а не одного соединения.
const FAREWELL_PATIENCE: Duration = Duration::from_secs(5);

/// Чем кончился управляющий поток.
///
/// Два случая, а не один, и это главное, что знает этот модуль: человеку в
/// них говорят РАЗНОЕ. Намеренный уход несёт причину («обслуживание
/// выключили», «окно закрыли»), обрыв — совет подключиться заново. Свести их
/// в один `Refuse` со кодом внутри значило бы отдать различение на
/// сравнение строк, то есть потерять его при первой же правке текста.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Gone {
    /// Та сторона ушла НАРОЧНО и сказала почему: `bye` (выключили
    /// обслуживание, закрыли окно, снимается машина) или `revoked` (сняли
    /// разрешение). Повторять звонок по своей воле нечего — причина у
    /// человека на руках, и дальше ход его.
    Farewell(Refuse),
    /// Поток кончился без слов: связь пропала, или та сторона закрыла его
    /// молча. Это повторяется (`keep_calling`).
    Broken(Refuse),
}

/// Управляющий поток одного СОЕДИНЕНИЯ (карточки) внутри канала.
///
/// Половины держатся в `Option` не ради необязательности, а ради выхода:
/// уйти из соединения — дело АСИНХРОННОЕ (дописать, закрыть свою половину,
/// дождаться подтверждения), а `Drop` ничего ждать не умеет. Поэтому выход
/// вынимает половины наружу — в `settle`, и `Drop` их туда же отдаёт задачей,
/// когда про выход забыли.
///
/// Пока эта вещь жива — жив и канал: последний снятый `Hold` закрывает его.
pub struct Control {
    send: Option<SendStream>,
    recv: Option<RecvStream>,
    hold: Option<Hold>,
}

/// Половины вынимаются ровно один раз — в `end`, `reins` или `Drop`, — и
/// после этого `Control` уже не существует как значение, которым можно
/// что-то сделать. Паника здесь невозможна по построению, а не по
/// соглашению.
const TAKEN: &str = "половины управляющего потока вынимаются один раз, вместе с самим Control";

impl Control {
    /// Обе половины сразу — для разговора, который пишет и читает по очереди
    /// (`enroll::accept_side`, `enroll::dial_side`).
    ///
    /// Одним вызовом, а не двумя: второй занял бы `Control` целиком, и
    /// компилятор не дал бы держать обе половины разом.
    pub fn halves(&mut self) -> (&mut SendStream, &mut RecvStream) {
        (self.send.as_mut().expect(TAKEN), self.recv.as_mut().expect(TAKEN))
    }

    /// Пишущая половина — когда только говорят.
    pub fn says(&mut self) -> &mut SendStream {
        self.send.as_mut().expect(TAKEN)
    }

    /// Читающая половина — для присмотра (`hold`).
    pub fn ear(&mut self) -> &mut RecvStream {
        self.recv.as_mut().expect(TAKEN)
    }

    /// **Единственный выход из соединения.** Дописать прощание, если есть что
    /// сказать, закрыть свою половину и ДОЖДАТЬСЯ, пока написанное признают
    /// доехавшим.
    ///
    /// Через него обязаны идти ВСЕ пути — не только прощание. Довод стоил
    /// одного найденного тупика: человек жмёт «Отклонить», `accept_side`
    /// пишет `enroll_no` и возвращается, задача отпускает поток, канал
    /// закрывается — и **неподтверждённый `enroll_no` выбрасывается**, потому
    /// что закрытие QUIC выбрасывает всё, что не признано доехавшим. Зовущая
    /// сторона получает ошибку чтения вместо исхода «отклонено», звонит
    /// вечно и показывает «подключается снова», а код уже погашен, значит
    /// второго диалога человек не увидит никогда: тупик без единого слова
    /// человеку. То же самое случилось бы с `enroll_ok` и с `bye`.
    ///
    /// Поэтому `bye` — частный случай этого выхода, а не отдельный путь.
    ///
    /// Забирает себя целиком (`self`): после выхода по этому потоку говорить
    /// нечего, и возможность сказать ещё что-то — ровно та возможность, от
    /// которой намеренный уход и отличает обрыв.
    pub async fn end(mut self, why: Option<Refuse>) {
        let (Some(mut send), Some(hold)) = (self.send.take(), self.hold.take()) else { return };
        if let Some(why) = why {
            let _ = Frame::write(&mut send, &Msg::Bye(why)).await;
        }
        settle(send, hold).await;
    }

    /// Прощание — частный случай выхода: уходим нарочно и говорим почему.
    pub async fn bye(self, why: Refuse) {
        self.end(Some(why)).await
    }
}

/// Про выход забыли — значит досылаем сами, задачей.
///
/// Это не вежливость, а последний рубеж: путей выхода из разговора много
/// (отказ книги, отказ человека, обрыв, срок решения, паника задачи,
/// брошенная задача при выключении обслуживания), и забыть `end` на одном из
/// них проще всего там, где он нужнее — на отказе. Без этого рубежа правило
/// «все пути через один выход» держалось бы на внимательности автора, а
/// цена невнимательности — тупик из докстроки `end`.
///
/// **Цена рубежа: закрытие канала становится не мгновенным.** Снятие
/// последнего потока закрывает канал не в тот же миг, а когда дошлётся
/// написанное (или выйдет `FAREWELL_PATIENCE`). Иначе и быть не может: либо
/// мгновенное закрытие, либо не выброшенный последний кадр, и выбор между
/// ними очевиден. Кто ждёт закрытия, тот его и ждёт (`Channel::is_open` в
/// опросе), а не считает случившимся сразу.
impl Drop for Control {
    fn drop(&mut self) {
        let (Some(send), Some(hold)) = (self.send.take(), self.hold.take()) else { return };
        match tokio::runtime::Handle::try_current() {
            Ok(rt) => {
                rt.spawn(settle(send, hold));
            }
            // Рантайма нет — досылать нечем и некому; канал закрывается
            // прямо здесь, снятием `Hold`.
            Err(_) => drop(hold),
        }
    }
}

/// Конец своей половины потока: закрыть и дождаться, пока та сторона
/// признает написанное доехавшим, и только ПОТОМ снять счёт — то есть
/// позволить каналу закрыться.
///
/// Порядок здесь и есть вся суть: `drop(hold)` раньше ожидания выбросил бы
/// то, чего ждали. `stopped` после `finish` завершается тогда, когда та
/// сторона дочитала поток.
async fn settle(mut send: SendStream, hold: Hold) {
    let _ = send.finish();
    let _ = tokio::time::timeout(FAREWELL_PATIENCE, send.stopped()).await;
    drop(hold);
}

/// Счёт живых управляющих потоков канала.
///
/// `Drop`, а не снятие руками: разговор кончается девятью путями (отказ
/// книги, отказ человека, обрыв, срок, паника задачи), и девятый забудут.
/// Снятие на `Drop` работает и на отмене всей задачи — а задачу бросают
/// именно так, когда человек выключает обслуживание или закрывает окно.
pub struct Hold {
    conn: Connection,
    live: Arc<AtomicUsize>,
}

impl Drop for Hold {
    fn drop(&mut self) {
        // `fetch_sub` вернул единицу — снятый был последним, и канал держать
        // больше нечем. Закрытие синхронное (`Connection::close` не `async`),
        // и это единственная причина, по которой правило спеки «канал
        // закрывается сам» вообще выразимо в `Drop`.
        if self.live.fetch_sub(1, Ordering::SeqCst) == 1 {
            self.conn.close(VarInt::from_u32(CLOSED_BY_US), b"");
        }
    }
}

/// Канал — ОДНО соединение iroh на пару машин (спека, «Один канал на машину,
/// а не на базу»).
///
/// Клонируется дёшево: `Connection` внутри за `Arc`, счёт потоков — общий
/// нарочно, иначе две копии канала считали бы «живых потоков не осталось»
/// каждая по-своему.
#[derive(Debug, Clone)]
pub struct Channel {
    conn: Connection,
    live: Arc<AtomicUsize>,
}

impl Channel {
    /// Кто на том конце. Ключ узла — то, что доказал сам iroh, а не то, что
    /// сказали в `hello`.
    pub fn peer(&self) -> EndpointId {
        self.conn.remote_id()
    }

    /// Жив ли канал прямо сейчас. Нужно не протоколу (он узнаёт о конце из
    /// потока), а тому, кто спрашивает «закрылся ли он сам»: окну в журнал и
    /// тесту про последний поток.
    pub fn is_open(&self) -> bool {
        self.conn.close_reason().is_none()
    }

    /// Открыть управляющий поток: по ЭТОЙ карточке зовущая — эта сторона.
    ///
    /// Счёт берётся ДО открытия потока нарочно: между `fetch_add` и первым
    /// кадром канал не должен считаться опустевшим, иначе соседний поток,
    /// кончившийся в этот самый миг, закрыл бы канал у нас под руками.
    pub async fn call(&self) -> Result<Control, String> {
        let hold = self.hold();
        let (send, recv) =
            self.conn.open_bi().await.map_err(|e| format!("не удалось начать разговор: {e}. Проверьте связь и подключитесь заново."))?;
        Ok(Control { send: Some(send), recv: Some(recv), hold: Some(hold) })
    }

    /// Принять управляющий поток, который открыла та сторона: по этой
    /// карточке зовущая — она.
    pub async fn answer(&self) -> Result<Control, String> {
        let hold = self.hold();
        let (send, recv) = self.conn.accept_bi().await.map_err(|e| format!("входящий разговор не начался: {e}"))?;
        Ok(Control { send: Some(send), recv: Some(recv), hold: Some(hold) })
    }

    fn hold(&self) -> Hold {
        self.live.fetch_add(1, Ordering::SeqCst);
        Hold { conn: self.conn.clone(), live: self.live.clone() }
    }
}

/// Живые каналы этой машины — по одному на партнёра.
///
/// Нужен затем, чтобы вторая карточка к тому же партнёру ехала ПОТОКОМ в уже
/// живом канале, а не вторым соединением: второй канал к тому же узлу — это
/// второй проход пробивания NAT, второй разговор с релеем и второе состояние
/// перегрузки, и ничего из этого он не покупает (спека, «Один канал на
/// машину»). Правило «канал закрывается, когда не осталось живых потоков ни
/// в каком направлении» без этой книги не выразимо вовсе: без неё у каждого
/// направления был бы свой канал и свой счёт.
///
/// Потолок: два одновременных звонка к одному и тому же партнёру могут
/// успеть завести два канала — проверка и звонок не под одним замком
/// нарочно, держать замок через `await` дозвона значило бы запереть на это
/// время все остальные карточки. Последствие безвредное: в книге остаётся
/// последний, прежний живёт своими потоками и закрывается, когда они
/// кончатся. Выйдет это из разряда «безвредно» тогда, когда карточек к
/// одному партнёру станет много и человек начнёт подключать их залпом; тогда
/// здесь встанет замок на партнёра (`tokio::sync::Mutex` на запись), а не
/// на всю книгу.
#[derive(Clone, Default)]
pub struct Channels(Arc<Mutex<HashMap<EndpointId, Channel>>>);

impl Channels {
    /// Канал к этому партнёру: живой — тот же самый, нет такого — новый
    /// звонок.
    pub async fn to(&self, node: &Node, whom: EndpointAddr) -> Result<Channel, String> {
        if let Some(live) = self.live(whom.id) {
            return Ok(live);
        }
        Ok(self.keep(node.dial(whom).await?))
    }

    /// Запомнить канал — входящий или только что набранный.
    ///
    /// Отравленный замок не повод отказывать: данные берутся из паники
    /// (`into_inner`), и хуже лишнего канала от этого не станет — тот же
    /// приём и тот же довод, что у оговорки кода в `enroll::claim`.
    pub fn keep(&self, conn: Connection) -> Channel {
        let peer = conn.remote_id();
        let channel = Channel { conn, live: Arc::new(AtomicUsize::new(0)) };
        let mut held = self.0.lock().unwrap_or_else(|e| e.into_inner());
        held.retain(|_, ch| ch.is_open());
        held.insert(peer, channel.clone());
        channel
    }

    /// Живой канал к этому партнёру, если он есть. Нового звонка не делает: кому нечем звонить, тому и отвечают словами.
    pub fn of(&self, peer: EndpointId) -> Option<Channel> {
        self.live(peer)
    }

    fn live(&self, peer: EndpointId) -> Option<Channel> {
        let mut held = self.0.lock().unwrap_or_else(|e| e.into_inner());
        held.retain(|_, ch| ch.is_open());
        held.get(&peer).cloned()
    }
}

/// Держит управляющий поток, пока та сторона говорит.
///
/// Возвращается ровно тогда, когда это соединение кончилось, — и говорит,
/// кончилось оно словами или молча.
///
/// `heard` зовётся на каждое сообщение, которое не кончает поток: `refuse`
/// (та сторона отказала в чём-то, что мы просили), всё прочее этой версии.
/// Своего разбора здесь нет нарочно: что делать со сказанным, знает окно, а
/// не провод.
///
/// **Срока ожидания здесь НЕТ**, и это решение спеки, а не недосмотр: своего
/// пинга протокол не держит, молчание на управляющем потоке законно часами,
/// и срок означал бы разорвать живое по своему таймеру, поссорив его с
/// таймером iroh.
///
/// `revoked` кончает поток прощанием, а не обрывом: разрешение снял человек,
/// и той стороне положено прочитать его слова. Поле `base_id` при этом не
/// читается — на потоке, который и есть одна карточка, оно повторяет то, что
/// читающий уже знает; разбирать его значило бы заводить случай «отозвали
/// чужую базу по нашему потоку», которого в протоколе нет.
pub async fn hold<R: AsyncRead + Unpin>(r: &mut R, mut heard: impl FnMut(Msg)) -> Gone {
    loop {
        match Frame::read(r).await {
            Ok(Msg::Bye(why)) => return Gone::Farewell(why),
            Ok(Msg::Revoked { text, .. }) => return Gone::Farewell(Refuse::new(code::REVOKED, text)),
            Ok(msg) => heard(msg),
            Err(no) => return Gone::Broken(no),
        }
    }
}

/// Сколько приказов окна ждут своей очереди на запись. Восьми хватает с
/// запасом: по управляющему потоку окно говорит по событию человека
/// (переключил обслуживание, снял разрешение), а не потоком. Предел здесь
/// вместо «без предела» затем, что очередь без предела — это память, которую
/// съедает тот, кто перестал читать.
const REINS_QUEUE: usize = 8;

/// Вожжи живого соединения: то, чем окно говорит в управляющий поток, не
/// владея им.
///
/// Нужны затем, что присмотр за потоком (`hold`) висит в своей задаче и
/// держит ЧИТАЮЩУЮ половину, а сказать той стороне надо по своей воле:
/// `revoked` — когда человек снял разрешение, `bye` — когда программа уходит
/// нарочно. Спека про отзыв говорит «отправляется и тут же рвёт потоки этой
/// базы»: отзыв, который подействует при следующем обрыве, — не отзыв вовсе,
/// а обещание.
///
/// **Почему две задачи, а не один `select!`** на чтение кадра и приказ окна:
/// `Frame::read` читает заголовок и тело по очереди, и брошенный между ними
/// съедает заголовок НАВСЕГДА — дальше по потоку всё разберётся как мусор, и
/// человек увидит обрыв сразу после успешного зачисления. Тот же довод, по
/// которому `enroll::interrupted` читает один байт, а не кадр. Половины
/// потока независимы, и двум задачам ссориться не на чем.
///
/// Брошенные вожжи — тоже конец соединения, и конец опрятный: отправитель
/// закрывается, задача письма доходит до `settle`, написанное дошлётся, а
/// канал закроется, если этот поток был последним. Отдельного «отключись»
/// для этого не нужно.
pub struct Reins {
    say: tokio::sync::mpsc::Sender<Msg>,
    writer: tokio::task::JoinHandle<()>,
}

impl Reins {
    /// Сказать той стороне. `false` — поток уже кончился; это не беда и не
    /// повод шуметь: о конце соединения окно узнаёт своим путём, от присмотра
    /// (`Gone`), и второе сообщение об одном событии ему не нужно. Поэтому
    /// `revoke` и `bye` ответ и не смотрят: сказать о мёртвом потоке всё равно
    /// нечего, а уйти надо в любом случае.
    pub async fn say(&self, msg: Msg) -> bool {
        self.say.send(msg).await.is_ok()
    }

    /// Отзыв: сказать словами и тут же снять поток ЭТОЙ карточки.
    ///
    /// Соседние карточки того же канала не трогаются вовсе — у них свои
    /// управляющие потоки (спека, `revoked`: «рвёт потоки этой базы; если
    /// других зачисленных баз в канале не осталось — закрывается и канал»).
    /// Вторая половина этого правила исполняется сама: канал закрывается,
    /// когда снят последний `Hold`, и считать зачисленные базы для этого не
    /// нужно.
    ///
    /// **Теперь это правда, а прежде докстрока утверждала обратное тому, что
    /// делал код.** Поток, за которым числилось несколько карточек, снимался
    /// отзывом любой из них целиком — а числилось так за каждым потоком
    /// партнёра, вернувшегося без имени карточки. У человека с пятью карточками
    /// к одному партнёру отзыв одной резал все пять. Правда держится не здесь, а
    /// типом: `enroll::Outcome::Already` несёт ОДНУ базу, то есть у потока её
    /// больше одной не бывает (`gui::peer::Talk`).
    pub async fn revoke(self, base_id: &crate::wire::CardRef, text: &str) {
        self.say(Msg::Revoked { base_id: base_id.clone(), text: text.into() }).await;
        self.finish().await;
    }

    /// Уйти нарочно: прощание словами и конец соединения.
    pub async fn bye(self, why: Refuse) {
        self.say(Msg::Bye(why)).await;
        self.finish().await;
    }

    /// Дождаться, пока задача письма дошлёт написанное и снимет поток.
    ///
    /// Ждать обязательно: без этого окно, закрывшись, уронило бы рантайм
    /// раньше, чем прощание доедет, — то есть вернуло бы ровно тот дефект,
    /// от которого заведён `settle`.
    async fn finish(self) {
        let Reins { say, writer } = self;
        drop(say);
        let _ = writer.await;
    }
}

/// Раздать соединение надвое: вожжи — окну, читающую половину — задаче
/// присмотра (`hold`).
///
/// Задача письма заводится здесь же и живёт, пока живы вожжи. Поэтому
/// `reins` зовётся из потока с рантаймом (`tokio::spawn`), а не с главного
/// потока окна.
/// Отдать ОБЕ половины потока наружу вместе с держателем канала: дальше по этому потоку идёт не наш разговор, а чужие байты
/// (json-rpc моста, шаг 4 плана пары B).
///
/// Держатель уезжает вместе с половинами и живёт, пока жив поток: без него канал счёл бы себя опустевшим и закрылся бы под работающим
/// мостом. `control` после этого падает пустым — его `Drop` видит вынутые половины и ничего не досылает.
pub fn into_pipe(mut control: Control) -> (SendStream, RecvStream, Hold) {
    let send = control.send.take().expect(TAKEN);
    let recv = control.recv.take().expect(TAKEN);
    let hold = control.hold.take().expect(TAKEN);
    (send, recv, hold)
}

pub fn reins(mut control: Control) -> (Reins, RecvStream) {
    let recv = control.recv.take().expect(TAKEN);
    let send = control.send.take().expect(TAKEN);
    let hold = control.hold.take().expect(TAKEN);
    // `control` дальше падает пустым: его `Drop` увидит вынутые половины и не
    // станет ни досылать, ни закрывать — поток теперь за задачей письма.
    let (say, mut orders) = tokio::sync::mpsc::channel::<Msg>(REINS_QUEUE);
    let writer = tokio::spawn(async move {
        let mut send = send;
        while let Some(msg) = orders.recv().await {
            // Отказ записи — конец письма: поток мёртв, и говорить в него
            // больше нечего. Жаловаться некому и незачем — присмотр на той же
            // карточке скажет окну `Gone` сам.
            if Frame::write(&mut send, &msg).await.is_err() {
                break;
            }
        }
        settle(send, hold).await;
    });
    (Reins { say, writer }, recv)
}

/// Приём входящих: на каждый канал — свой присмотр, на каждый управляющий
/// поток в нём — свой разговор.
///
/// Возвращается, когда узел закрыт и принимать больше нечего, — это конец
/// работы, а не беда (`Node::accept`).
///
/// Три задачи, а не одна, и это не щедрость: канал живёт дольше любого
/// своего потока, а поток — дольше разговора по нему. Один цикл на всё
/// означал бы, что вторая карточка ждёт, пока человек ответит по первой.
///
/// `note` — строка в журнал о беде, которая никому больше не достанется:
/// входящее подключение, не состоявшееся на рукопожатии, сказать некому —
/// того конца у нас уже нет.
///
/// **Разговору отдаётся и ключ той стороны**, а не только поток. Он нужен
/// всякому, кто решает допуск (`enroll::accept_side`), и взять его можно
/// только здесь: `Control` о канале не знает ничего, а то, что сторона сказала
/// о себе в `hello`, — её слова, а не доказанный факт. Пока ключ сюда не
/// передавался, у продукта жил второй такой же цикл (`gui::peer::accepting`),
/// то есть два места с одним правилом — и правило пришлось бы править дважды.
///
/// **Своего предела на число управляющих потоков в канале здесь НЕТ**, и это
/// решение, а не упущение: предел держит сам QUIC (`max_concurrent_bi_streams`
/// у соединения), и второй предел поверх него дал бы два разных мнения о
/// том, когда отказывать, — та же беда, от которой протокол отказался
/// заводить свой пинг поверх таймера iroh. Решение 8 спеки ограничивает
/// потоки ОБМЕНА (восемь) и прямо не ограничивает управляющие: их в канале
/// ровно столько, сколько у человека карточек к этому партнёру, а предел
/// числу карточек назначает лицензия 1С, не программа (решение владельца
/// 1.11). Когда перебор управляющих потоков станет возможен не по ошибке в
/// своём же коде, отказ на него уже назван — `code::OVERFLOW`, «слишком
/// много потоков».
pub async fn accept_all<T, Fut>(node: &Node, channels: &Channels, note: impl Fn(String), talk: T)
where
    T: Fn(Control, EndpointId) -> Fut + Clone + Send + 'static,
    Fut: Future<Output = ()> + Send + 'static,
{
    while let Some(incoming) = node.accept().await {
        let conn = match incoming {
            Ok(conn) => conn,
            Err(why) => {
                note(why);
                continue;
            }
        };
        let channel = channels.keep(conn);
        let talk = talk.clone();
        tokio::spawn(async move {
            // Ключ берётся у КАНАЛА, а не у сообщения: это то, что доказал сам
            // iroh.
            let peer = channel.peer();
            // Поток за потоком, пока канал жив: `accept_bi` отказывает ровно
            // тогда, когда он закрылся, и этого отказа ждать не надо — он и
            // есть конец присмотра.
            while let Ok(control) = channel.answer().await {
                tokio::spawn(talk(control, peer));
            }
        });
    }
}

/// Чем кончился один круг звонка зовущей стороны.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Round {
    /// Дошли до «подключено» и держали поток; вот чем он кончился.
    Held(Gone),
    /// Разговор зачисления кончился исходом: человек отклонил, человек не
    /// ответил, код сгорел. Сами не повторяем — повтор и есть то дёрганье, от
    /// которого заведён секрет тикета (спека, «Зачисление»).
    NotEnrolled(Refuse),
    /// Не дозвонились, или разговор сорвался на полуслове. Это повторяется.
    Failed(String),
}

/// Почему зовущая сторона перестала звонить. Третьего случая нет: всё
/// остальное повторяется бесконечно, и возврата из `keep_calling` у него не
/// бывает.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Stopped {
    /// Та сторона простилась словами или сняла разрешение.
    Farewell(Refuse),
    /// Исход зачисления.
    NotEnrolled(Refuse),
}

/// Задержка перед попыткой номер `attempt`. Нулевая попытка — первая, она
/// идёт сразу: ждать там нечего.
///
/// Секунда, две, четыре и так до минуты, дальше раз в минуту бесконечно
/// (спека, «Обрыв и переподключение»). Сдаваться незачем: сервер заказчика
/// может быть выключен на ночь, и человек не должен нажимать «подключиться»
/// утром.
///
/// `checked_pow`: номер попытки растёт без предела, и переполнение степени
/// здесь — не выдуманный случай, а неделя без связи.
pub fn backoff(attempt: u32) -> Duration {
    if attempt == 0 {
        return Duration::ZERO;
    }
    let seconds = 2u64.checked_pow(attempt - 1).unwrap_or(u64::MAX);
    Duration::from_secs(seconds.min(LONGEST_WAIT.as_secs()))
}

/// Зовёт, пока звать есть смысл: круг за кругом с нарастающей задержкой.
///
/// **Зовёт всегда одна и та же сторона** — та, что вставляла код при
/// заведении (спека). Принимающая не звонит никогда, даже зная адрес: иначе
/// «кто кого зовёт» переставало бы быть свойством заведения и становилось
/// гонкой. Поэтому у этой функции нет ни развилки по роли, ни признака
/// направления: её зовёт только зовущая сторона, и роль записана в карточке.
///
/// Один круг — дело вызывающего (`round`): дозвониться, открыть управляющий
/// поток, провести зачисление, держать. Так здесь остаётся ровно правило
/// повтора, а всё, что к нему не относится, — снаружи; и так же тест может
/// подставить свой круг, не поднимая узлов.
///
/// **Ладка сбрасывается после удачного круга.** Соединение, прожившее часы и
/// оборвавшееся, возвращается через секунду, а не через минуту: нарастание
/// задержек защищает от бесплодного долбления в выключенную машину, а не
/// наказывает за прошлые обрывы.
///
/// **Признака остановки здесь нет.** Человек, выключивший обслуживание или
/// закрывший окно, роняет саму задачу — а вместе с ней `Control` и `Hold`,
/// то есть канал закрывается тем же `Drop`, что и всегда. Второй путь
/// остановки (флаг, за которым надо подглядывать) означал бы два разных
/// мнения о том, звоним ли мы ещё.
pub async fn keep_calling<F, Fut>(mut round: F) -> Stopped
where
    F: FnMut() -> Fut,
    Fut: Future<Output = Round>,
{
    let mut attempt = 0u32;
    loop {
        match round().await {
            Round::Held(Gone::Farewell(why)) => return Stopped::Farewell(why),
            Round::NotEnrolled(no) => return Stopped::NotEnrolled(no),
            // Круг дошёл до «подключено» — ладка начинается заново.
            Round::Held(Gone::Broken(_)) => attempt = 0,
            Round::Failed(_) => {}
        }
        attempt = attempt.saturating_add(1);
        tokio::time::sleep(backoff(attempt)).await;
    }
}

