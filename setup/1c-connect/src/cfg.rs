/// `Copy`: три `u16` — `cfg.ports()` считается один раз и используется по
/// значению столько раз, сколько нужно (`ops_host::run_mcp` — находка ревью
/// задачи 3, Minor 7), без второго вызова ради второго владельца.
#[derive(Clone, Copy)]
pub struct Ports {
    pub mcp: u16,
    pub vrunner: u16,
    pub web: u16,
}

impl Cfg {
    /// Боевой путь: подложка системы (DPAPI на Windows, файл ключа на
    /// Linux) строится здесь же, а не раньше — узнать, что её не завести
    /// (`Store::system`), негде и не нужно до первого реального чтения.
    pub fn load(kit: &Kit) -> Result<Cfg> {
        let store = secrets::Store::system(kit.state()).map_err(anyhow::Error::msg)?;
        Self::load_with(kit, &store)
    }

    /// То же, но подложку даёт вызывающий — ей проверяются тесты (спека,
    /// «Ловушки»: DPAPI в тестах не зовём, а `load` его строит сам).
    /// Непустой список `undecryptable` — отказ словами: без него
    /// `serve`/`connect`/подкоманда `mcp` поехали бы с пустым паролем
    /// молча, а `validate` пароли не проверяет (анти-цель спеки). Отказ
    /// проверяется раньше `validate`: человеку нужен один понятный диагноз,
    /// а не жалоба на незаполненный `workstation` вместо настоящей причины.
    pub fn load_with(kit: &Kit, store: &secrets::Store) -> Result<Cfg> {
        let (cfg, existed) = Self::load_raw(kit, store)?;
        // Файла параметров нет вовсе — это умолчание без отказа (поведение
        // `connect`/`serve`, не этой задачи): пустой каталог состояния не
        // имеет паролей, которые могли бы не открыться, и жаловаться на
        // незаполненный `workstation` здесь настолько же неверно, как и
        // прежде, когда `validate` тут вовсе не звался. `existed` — одним
        // флагом из `load_raw`, не вторым отдельным `exists()` (ревью
        // задачи 2, Minor 5): файл на диске спрашивается ровно раз.
        if !existed {
            return Ok(cfg);
        }
        // Находки разбора — отказ, и раньше паролей: вид файла идёт перед его
        // содержимым, и человеку, у которого в настройках и `[host]`, и
        // `[[connection]]`, бесполезно слышать про пароль не того соединения.
        // Окно эти же находки ТЕРПИТ (`load_unchecked`, там же и строка
        // журнала): запереть единственное место, где они исправляются, —
        // ровно то, чего эта развилка не делает (круг починки 1, находки A и
        // D).
        anyhow::ensure!(cfg.read_notes.is_empty(), "{FILE}: {}", cfg.read_notes.join(" "));
        let blocking = blocking_undecryptable(&cfg.current().mode, &cfg.undecryptable);
        if !blocking.is_empty() {
            let blocking: Vec<String> = blocking.into_iter().map(str::to_string).collect();
            anyhow::bail!("{}", undecryptable_message(&blocking));
        }
        cfg.validate()?;
        Ok(cfg)
    }

    /// То же, но БЕЗ проверки заполненности (`validate`) — для окна.
    ///
    /// Окно обязано открыться на незаполненном файле: в нём человек поля и
    /// заполняет. Пока `load` валидировал всё и для окна тоже, комплект
    /// приходилось отдавать с выдуманными значениями («192.168.1.10:3393»,
    /// «C:\Bases\Buh»), иначе программа не стартовала вовсе — и человек
    /// правил чужие выдумки вместо пустых полей с подсказками (решение
    /// владельца 26.10).
    ///
    /// Сломанный toml (не разбирается) остаётся отказом и здесь: это не «не
    /// заполнено», а «не прочитать». Чего не хватает в разобранном файле —
    /// говорит набор фактов, у него на это есть свои слова и свои советы.
    pub fn load_unchecked(kit: &Kit) -> Result<Cfg> {
        let store = secrets::Store::system(kit.state()).map_err(anyhow::Error::msg)?;
        Self::load_unchecked_with(kit, &store)
    }

    /// То же, но подложку даёт вызывающий. Нерасшифрованное поле становится
    /// пустым — готовым к новому вводу, а не мусором с диска, — и его имя
    /// уходит в `undecryptable`; окно (задача 4) читает этот список и
    /// говорит человеку, что пароль нужно ввести заново, а не тихо
    /// подставляет то, что не открылось.
    pub fn load_unchecked_with(kit: &Kit, store: &secrets::Store) -> Result<Cfg> {
        Ok(Self::load_raw(kit, store)?.0)
    }

    /// Общее тело `load_unchecked_with`/`load_with`: читает файл не больше
    /// одного раза и говорит, существовал ли он вовсе — `load_with` решает
    /// по этому флагу, звать ли `validate`, не трогая диск второй раз
    /// (ревью задачи 2, Minor 5).
    fn load_raw(kit: &Kit, store: &secrets::Store) -> Result<(Cfg, bool)> {
        let p = kit.state_path(crate::cfg::FILE);
        if !p.exists() {
            return Ok((Cfg::default(), false));
        }
        let text = std::fs::read_to_string(&p).with_context(|| format!("не прочитать {}", p.display()))?;
        let mut cfg: Cfg = toml::from_str(&text).with_context(|| format!("{FILE}: ошибка в файле параметров"))?;
        // Пароли КАЖДОГО соединения — и настоящих `[[connection]]`-блоков, и
        // того единственного, в которое превратилась прежняя секция `[host]`
        // при разборе (`From<CfgFile>`). Отдельного прохода по `[host]` здесь
        // больше нет и быть не может: секция стала соединением РАНЬШЕ, чем
        // чтение дошло до этой строки, — то есть порядок «открыть до клона»
        // (круг починки 1, находка 1: иначе клон уносил в `connections`
        // шифртекст, который ждут открытым текстом) теперь не правило
        // функции, а свойство типа, и нарушить его нечем.
        let mut bad = Vec::new();
        for c in cfg.connections.iter_mut() {
            c.password = open_or_mark(store, "password", &c.password, &mut bad);
            c.db_password = open_or_mark(store, "db_password", &c.db_password, &mut bad);
        }
        // `current`, называющий то, чего нет, здесь больше не разбирается:
        // это находка разбора (`From<CfgFile>` — там и фраза человеку), а
        // отказывает на ней `load_with`. Отказ стоял ЗДЕСЬ, то есть и на
        // пути окна, и закрывал единственное место, где опечатку правят
        // (круг починки 1, находка D).
        cfg.undecryptable = bad;
        Ok((cfg, true))
    }

    /// ТЕКУЩЕЕ соединение — то, которое назвал `current`, из списка
    /// `connections`. Отдельного поля `host` рядом нет: два хранилища одного
    /// понятия разошлись бы первым же сохранением (задача 3), поэтому всё,
    /// что раньше читало `cfg.host.*`, читает это.
    ///
    /// Имя не нашлось — ПЕРВОЕ соединение списка: пустой `current` при
    /// непустом списке — законный вид файла (блоки `[[connection]]` без
    /// строки `current` в корне), и выбирать там нечего, кроме первого.
    /// Непустое имя, которого в списке нет, сюда не доходит вовсе: это отказ
    /// словами ещё при чтении (`load_raw`) — человек правил файл руками и
    /// узнаёт, что опечатался, а не получает тихий выбор первого.
    ///
    /// Список пуст — пустое соединение, а не паника: так выглядит свежий
    /// комплект до первой настройки, и окно обязано на нём открыться. Ссылка
    /// на `OnceLock` (решение брифа задачи 3), а не на поле структуры:
    /// пустому соединению негде жить в `&self`, а отдавать значение вместо
    /// ссылки значило бы переписать все 600 обращений на клон.
    pub fn current(&self) -> &Connection {
        static EMPTY: std::sync::OnceLock<Connection> = std::sync::OnceLock::new();
        self.connections
            .iter()
            .find(|c| c.name == self.current)
            .or_else(|| self.connections.first())
            .unwrap_or_else(|| EMPTY.get_or_init(Connection::default))
    }

    /// То же соединение на правку — ссылка В СПИСОК, не копия рядом с ним:
    /// правка текущего обязана менять сам список, иначе сохранение уносило
    /// бы на диск одно, а окно показывало другое.
    ///
    /// Пустой список — правка создаёт ПЕРВОЕ соединение (`FIRST_CONNECTION_NAME`),
    /// а не теряется молча: так выглядит настройка свежего комплекта — окно
    /// или `install` заполняют поля там, где соединений ещё нет вовсе, и это
    /// и есть первое. Безымянным оно остаться не может: `validate()` отказал
    /// бы на безымянном соединении, и настройка свежего комплекта обрывалась
    /// бы отказом про имя, которого человек не вводил.
    pub fn current_mut(&mut self) -> &mut Connection {
        if self.connections.is_empty() {
            self.current = FIRST_CONNECTION_NAME.to_string();
            self.connections.push(Connection { name: FIRST_CONNECTION_NAME.to_string(), ..Default::default() });
        }
        let at = self.connections.iter().position(|c| c.name == self.current).unwrap_or(0);
        &mut self.connections[at]
    }

    /// Переключить текущее соединение по имени (задача 8 плана «Модель
    /// соединений»). Сравнение ТОЧНОЕ, без `trim` — тем же приёмом, что
    /// `current()` выше и проверка повтора имён в `validate()`: там и там
    /// имя ищется посимвольно. Если бы здесь сравнение прощало хвостовой
    /// пробел, человек мог бы «переключиться» командой на имя, которого в
    /// файле буквально нет («Buh» при живом «Buh »): команда отчиталась бы
    /// успехом, а `current()` тем же точным поиском это имя не нашёл бы и
    /// молча откатился на первое соединение списка — переключение, соврашее
    /// об успехе. Поэтому отказ здесь говорит прямо и перечисляет имена ТАК,
    /// как они записаны в файле (без `trim`) — на хвостовом пробеле человек
    /// увидит лишний пробел перед закрывающей кавычкой и поймёт, в чём
    /// опечатка.
    pub fn switch_current(&mut self, name: &str) -> std::result::Result<(), String> {
        // Пустой список — свежий комплект до первой настройки: `names` ниже
        // был бы пуст, а отказ оборвался бы на «…нет — есть » без точки
        // (долг задачи 8). Фраза та же, что уже говорит `connections_overview`
        // для того же случая.
        if self.connections.is_empty() {
            return Err(format!("{FILE}: соединений пока нет — настройте первое в окне (1c-connect gui)"));
        }
        if !self.connections.iter().any(|c| c.name == name) {
            let names: Vec<String> = self.connections.iter().map(|c| format!("«{}»", c.name)).collect();
            return Err(format!("{FILE}: соединения «{name}» нет — есть {}", names.join(", ")));
        }
        self.current = name.to_string();
        Ok(())
    }

    /// Соединения для человека: `1c-connect use` без имени показывает этот
    /// текст, текущее отмечено звёздочкой. Обращением к читателю, без
    /// жаргона кода — ни слова про блоки toml, имена полей или индексы.
    /// Текущее ищется тем же приёмом, что `current_mut()` (позиция по имени
    /// `self.current`, первое — если не нашлось): список и значок в трее
    /// обязаны отмечать то же соединение, что реально вернёт `current()`.
    pub fn connections_overview(&self) -> String {
        if self.connections.is_empty() {
            return "Соединений пока нет — настройте первое в окне (1c-connect gui).".to_string();
        }
        let cur = self.connections.iter().position(|c| c.name == self.current).unwrap_or(0);
        let mut lines = vec!["Соединения (звёздочкой отмечено текущее):".to_string()];
        for (i, c) in self.connections.iter().enumerate() {
            lines.push(format!("{} {}", if i == cur { "*" } else { " " }, c.name));
        }
        lines.push("Переключиться: 1c-connect use <имя>.".to_string());
        lines.join("\n")
    }

    /// `Cfg` из ОДНОГО соединения — оно же и текущее. Ровно то, что до
    /// задачи 3 писалось как `Cfg { host, ..Default::default() }`: окно
    /// собирает из полей формы одно соединение и проверяет его отдельно от
    /// того, что сейчас в `ui.cfg` (`gui::save`), а тесты — свой набор полей.
    pub fn of_one(connection: Connection) -> Cfg {
        Cfg { current: connection.name.clone(), connections: vec![connection], ..Default::default() }
    }

    pub fn number(&self) -> Option<u16> {
        number_of(&self.current().workstation)
    }

    /// Годность настроек: сперва список как список (имена), затем КАЖДОЕ
    /// соединение по отдельности.
    ///
    /// Проверяются ВСЕ соединения, не только текущее (решение координатора,
    /// задача 3). Негодное поле во втором `[[connection]]`, проходящее
    /// проверку молча, — молчаливо неверный результат: человек переключится
    /// на это соединение и получит отказ не там, где ошибся, а посреди
    /// работы, причём у `serve`/`connect` — без окна, в котором это видно.
    /// Цена выбора названа вслух: негодный блок, которым сейчас никто не
    /// пользуется, обрывает чтение целиком. Это ровно то же решение, что уже
    /// принято задачей 1 про `current`, называющий несуществующее соединение
    /// (отказ словами, не тихий выбор первого), и та же мерка проекта:
    /// громкий отказ лучше тихо неверной работы. Поэтому и отказ обязан
    /// называть, У КАКОГО соединения беда — иначе человек с тремя
    /// соединениями читал бы «base_path — путь к базе» и не знал, где его
    /// править.
    ///
    /// Имена проверяются ПЕРВЫМИ, хотя до задачи 3 стояли последними: именем
    /// подписан каждый отказ ниже, и у безымянного соединения подпись вышла
    /// бы пустой («соединение «»: base_path …») — сперва имя, потом всё
    /// остальное.
    pub fn validate(&self) -> Result<()> {
        // `current` указывает соединение именем (решение плана, 2.11) — два
        // одинаковых имени делают текущее неопределённым: от какого из
        // совпавших блоков его тогда брать. Отдельная проверка, не слитая с
        // проверкой пустого имени ниже: соседние задачи плана (5 — «одна
        // база — одна карточка», 6 — «папка принадлежит одному соединению»)
        // добавляют СВОИ проверки списка соединений рядом, а не вместо
        // (решение координатора).
        {
            let mut seen: Vec<&str> = Vec::new();
            for c in &self.connections {
                anyhow::ensure!(
                    !seen.contains(&c.name.as_str()),
                    "[[connection]]: имя «{}» встречается у нескольких соединений — имена обязаны быть уникальными",
                    c.name
                );
                seen.push(&c.name);
            }
        }
        // Безымянное соединение нечем показать в списке (окно, команда
        // переключения — обе читают имя, не номер блока).
        anyhow::ensure!(
            self.connections.iter().all(|c| !c.name.trim().is_empty()),
            "[[connection]]: у соединения нет имени — его нечем показать в списке"
        );
        // Задача 5 плана «Модель соединений», решение владельца 8: учебная
        // лицензия 1С даёт ОДИН сеанс на базу, и вторая карточка к той же
        // базе получила бы отказ ПЛАТФОРМЫ, не нашей программы, — человек
        // не понял бы, откуда беда. Сравнение по смыслу (`same_base`), а не
        // по строке: та же база, записанная с хвостовым разделителем,
        // другим регистром (на Windows) или `\.` в конце, — та же самая, и
        // запрет обязан её узнать, иначе он обходится пробелом в конце
        // (ревью плана). Отказ подписан именем карточки, что встретилась
        // ПОЗЖЕ в списке — та же мерка, что у проверки имён выше.
        for i in 0..self.connections.len() {
            for j in (i + 1)..self.connections.len() {
                let (a, b) = (&self.connections[i], &self.connections[j]);
                // Круг починки 1, Important: пустой `base_path` НЕ сравниваем
                // вовсе — `same_base("", "")` иначе признал бы «той же базой»
                // ЛЮБУЮ пару незаполненных блоков, и эта проверка (стоящая
                // ДО `c.validate()?` ниже) заслонила бы собой понятное «base_path
                // — путь к базе», подменив его сбивающим «эта же база уже
                // занята». Достижимо только правкой toml руками (окно такую
                // пару не даёт создать, там отдельный такой же guard в
                // `gui::save::same_base_conflict`), но бриф прямо заботится о
                // человеке, который правил файл руками и должен узнать, что
                // опечатался (ревью круга 1).
                if a.base_path.trim().is_empty() || b.base_path.trim().is_empty() {
                    continue;
                }
                anyhow::ensure!(
                    !same_base(&a.base_path, &b.base_path),
                    "соединение «{}»: эта же база уже занята соединением «{}» — одна база, одна карточка",
                    b.name,
                    a.name
                );
            }
        }
        // Задача 6 плана «Модель соединений», решение владельца 1: у
        // документов нет истории, и затирание файлов в чужой папке —
        // молчаливая их потеря, а не неудобство. Отдельный блок, рядом с
        // парным запретом задачи 5 выше, а не слитый с ним: это РАЗНЫЕ поля
        // (`project`, не `base_path`) и разная причина отказа. Сравнение по
        // смыслу (`folder_conflict`), не по строке — вложенность в обе
        // стороны запрещена так же твёрдо, как совпадение.
        for i in 0..self.connections.len() {
            for j in (i + 1)..self.connections.len() {
                let (a, b) = (&self.connections[i], &self.connections[j]);
                // Та же защита, что у пустого `base_path` выше: пустой
                // `project` — это «папка не задана» (свой, понятный отказ
                // ниже, у `Connection::validate`), а не «папка уже занята»
                // чужим столь же незаполненным полем.
                if a.project.trim().is_empty() || b.project.trim().is_empty() {
                    continue;
                }
                anyhow::ensure!(
                    !folder_conflict(&a.project, &b.project),
                    "соединение «{}»: папка проекта уже занята соединением «{}» — папка принадлежит одному соединению",
                    b.name,
                    a.name
                );
            }
        }
        // Ни одного соединения в ПРОЧИТАННОМ файле — работать не по чему, и
        // раньше это говорил отказ про пустой `base_path` (поле жило в
        // `[host]`, которого теперь нет). Свежий комплект этого отказа не
        // видит: файла параметров там нет вовсе, и `load_with` отдаёт
        // умолчание не доходя до проверки; окно читает `load_unchecked`,
        // которая не проверяет ничего, и открывается на пустой «Связи».
        anyhow::ensure!(!self.connections.is_empty(), "{FILE}: ни одного соединения — заполните «Связь» в окне (1c-connect gui)");
        for c in &self.connections {
            c.validate()?;
        }
        Ok(())
    }

    /// Вид конфигурации базы ТЕКУЩЕГО соединения — разбор и доводы живут у
    /// самого соединения (`Connection::configuration`), сюда он вынесен
    /// только затем, чтобы `cfg.configuration()` у вызывающих читалось как
    /// раньше.
    pub fn configuration(&self) -> Result<&str, String> {
        self.current().configuration()
    }

    /// Набор инструментов ТЕКУЩЕГО соединения — тем же приёмом, что
    /// `configuration()` выше.
    pub fn toolset(&self) -> Result<&str, String> {
        self.current().toolset()
    }
}

impl Connection {
    /// Годность ОДНОГО соединения. Каждый отказ подписан именем соединения:
    /// у человека их может быть несколько, и «base_path — путь к базе» без
    /// подписи не говорит, какую карточку править (решение координатора,
    /// задача 3). Прежняя подпись `[host]:` ушла вместе с полем: секции с
    /// таким именем в файле с несколькими соединениями нет, а имя карточки
    /// человек видит и в окне.
    pub fn validate(&self) -> Result<()> {
        let at = format!("соединение «{}»", self.name);
        // «Логин в среде» — понятие туннельного режима: три рабочих места
        // (`dev1`-`dev3`) прибиты в контейнере среды, и там это настоящий
        // логин человека. В локальном режиме никакой среды нет, спрашивать
        // логин в ней не у кого, и требование оборачивалось красной строкой
        // «workstation — dev1, dev2 или dev3 (ваш логин в среде)» у человека,
        // который всё держит на одной машине (наблюдение владельца 30.10).
        // Оговорка та же и по той же причине, что у `server` ниже. Пустое
        // поле в локальном режиме работает: с задачи 6 плана «тонкий срез
        // ценности» номер рабочего места не нужен ни портам (`Cfg::ports`),
        // ни замку (`single_instance::guard_key`) — оба больше не читают
        // это поле вовсе. Единственное, что здесь ещё спрашивает номер, —
        // туннельный режим сам по себе: там это настоящий логин человека в
        // среде, а не имя, из которого что-то считается.
        anyhow::ensure!(
            !mode_needs_env(&self.mode) || number_of(&self.workstation).is_some(),
            "{at}: workstation — dev1, dev2 или dev3 (ваш логин в среде)"
        );
        // Адрес среды спрашиваем только там, где по нему ходят. В локальном
        // режиме базы лежат рядом, туннеля нет, и поле не заполняет никто —
        // ни стенд, ни программа (`a_local_workstation_gets_no_made_up_environment_address`).
        // Пока умолчанием служил образец «192.168.1.10:3393», проверка его и
        // пропускала; 26.10 умолчания опустели (`adce1c6`) — и с этого дня на
        // стенде этим отказом обрывалась ЛЮБАЯ установка, включая ту, что
        // стенд делает сам при первом старте. Рабочее место оставалось без
        // проекта, публикации и расширения в базе, то есть агент в редакторе
        // оставался без инструментов 1С (живой стенд, 27.10.2026).
        anyhow::ensure!(
            !mode_needs_env(&self.mode) || self.server.contains(':'),
            "{at}: server — адрес и порт через двоеточие, например 192.168.1.10:3393"
        );
        let g = self.gitea.trim();
        anyhow::ensure!(
            g.is_empty() || g.starts_with("http://") || g.starts_with("https://"),
            "{at}: gitea — полный адрес Gitea среды, например http://localhost:3000 (пусто — адрес не задан, его пишет 1c-connect install)"
        );
        anyhow::ensure!(
            matches!(self.mode.as_str(), "tunnel" | "local"),
            "{at}: mode — \"tunnel\" (агент в среде, туда идёт туннель) или \"local\" (всё на одной машине)"
        );
        anyhow::ensure!(
            matches!(self.publication.as_str(), "auto" | "webserver"),
            "{at}: publication — \"auto\" (публикует сама программа) или \"webserver\" (уже опубликовано на Apache/IIS)"
        );
        // Тот же приём, что у mode/publication выше: именованное, но
        // неизвестное значение — отказ словами здесь, а не молчаливый откат
        // на auto внутри mcp_command (там это уже было бы маскировкой
        // опечатки человека — `Cfg::configuration`).
        if let Err(e) = self.configuration() {
            anyhow::bail!("{at}: {e}");
        }
        // Тот же приём и тот же довод: `mcp_command` не возвращает `Result`,
        // и без проверки здесь опечатка в наборе инструментов тихо стала бы
        // `business` только внутри сборщика команды (`Cfg::toolset`).
        if let Err(e) = self.toolset() {
            anyhow::bail!("{at}: {e}");
        }
        // `access()` сам не отказывает (возвращает `&str`, не `Result`) —
        // ровно потому, что к его вызову это уже проверено здесь: названный,
        // но неизвестный потолок записи — отказ со списком допустимых, а не
        // молчаливый откат на `read_only` внутри сборщика команды.
        anyhow::ensure!(
            matches!(self.write.trim(), "" | "read_write" | "read_only"),
            "{at}: write — неизвестный потолок записи «{}»; допустимые значения: read_write, read_only",
            self.write.trim()
        );
        // Пустой `base_url` — не ошибка, а «не задан»: поля для него в окне
        // нет вовсе, умолчание выводится из каталога базы
        // (`derived_base_url`), и требовать его руками значило бы заставлять
        // человека вписывать в toml то, что программа считает сама. Пустым
        // он и приходит в комплекте (решение владельца 26.10). Написанный —
        // проверяем как раньше: он берётся из поля `base_url` в режиме
        // `webserver`, и опечатка в нём стоит человеку часа.
        let u = &self.base_url;
        if !u.is_empty() {
            anyhow::ensure!(
                u.starts_with("http://localhost") || u.starts_with("http://127.0.0.1"),
                "{at}: адрес публикации — база на ЭТОЙ машине, адрес начинается с http://localhost (поле base_url)"
            );
            anyhow::ensure!(u.contains(SERVICE_PATH), "{at}: адрес публикации должен заканчиваться на /hs/mcp-1c (поле base_url)");
            anyhow::ensure!(
                u.chars().all(|c| c.is_ascii_alphanumeric() || "-._~:/".contains(c)),
                "{at}: адрес публикации — только латиница, цифры и -._~:/ (путь без пробелов и спецсимволов)"
            );
        }
        anyhow::ensure!(!self.base_path.is_empty(), "{at}: base_path — путь к базе или сервер\\база");
        // У набора `business` каталога исходников нет и быть не может: по
        // замыслу контракта подключения смысл этой папки задаёт профиль
        // («Папка исходников» у разработчика, «Папка документов» у бизнес-
        // пользователя), а не фиксированное поле `project`. Требовать от
        // бухгалтера полный путь к исходникам, которых у неё нет, — ровно та
        // помеха, ради снятия которой контракт завёл два набора инструментов
        // (круг исправления финального ревью, Б1: шаг 3 `БУХГАЛТЕРУ.md`
        // прямо велит поле не трогать, а `validate()` до этой правки на
        // пустом поле отказывала). У `developer` поведение не меняется —
        // там каталог исходников нужен по делу. Непустое значение проверяем
        // как раньше при ЛЮБОМ наборе: вписал — обязано быть годным.
        let p = &self.project;
        if !(p.is_empty() && self.toolset().unwrap_or("business") == "business") {
            let full = p.len() > 2 && (p.as_bytes()[1] == b':' || p.starts_with('/') || p.starts_with("\\\\"));
            anyhow::ensure!(
                full && !p.contains('"') && !p.contains('%'),
                "{at}: project — полный путь к каталогу проекта без кавычек и %, например C:\\proj\\Buh"
            );
        }
        Ok(())
    }

    /// Вид конфигурации базы для дочернего `mcp-1c` — `auto`, `generic` или
    /// `buh_3_0` (Бухгалтерия 3.0). У ребёнка это ключ `--profile`, не
    /// `--configuration`: имя здесь нарочно другое — слово «профиль» в этом
    /// продукте уже занято контрактом подключения («Разработчик»/«Бизнес-
    /// пользователь», `2026-11-01-connection-contract.md`), и назвать тем же
    /// словом вид конфигурации базы значило бы заставить одно слово в toml и
    /// в окне значить два разных факта. Замер владельца
    /// (`docs/research/2026-11-02-measured-tool-lists.md`) показал: `generic`
    /// и `buh_3_0` отдают ОДИНАКОВЫЕ имена инструментов — вид меняет не
    /// список, а то, что стоит за именами (какие объекты и реквизиты 1С
    /// адресуются), и по списку эту пользу не найти.
    ///
    /// Пусто — `auto`, а не отказ: ребёнок сам угадывает вид по составу
    /// конфигурации. Названное, но неизвестное значение — отказ словами со
    /// списком допустимых: молчаливый откат на `auto` для опечатки человека
    /// скрыл бы её — список инструментов у неё не меняется (см. замер выше),
    /// и иначе узнать о ней просто не из чего.
    pub fn configuration(&self) -> Result<&str, String> {
        const ALLOWED: [&str; 3] = ["auto", "generic", "buh_3_0"];
        let c = self.configuration.trim();
        if c.is_empty() {
            return Ok("auto");
        }
        if ALLOWED.contains(&c) {
            Ok(c)
        } else {
            Err(format!("configuration — неизвестный вид конфигурации «{c}»; допустимые значения: {}", ALLOWED.join(", ")))
        }
    }

    /// Какой набор инструментов поднимает дочерний `mcp-1c` — `developer`
    /// или `business`. У ребёнка это ключ `--toolset` (замер владельца,
    /// `docs/research/2026-11-02-measured-tool-lists.md`: `developer` даёт
    /// 8 инструментов, `business` — свои, с потолком записи поверх, см.
    /// `access()`).
    ///
    /// Читает `profile` — так контракт подключения называет это поле
    /// карточки (решение владельца 7, задача 9 плана «Модель соединений»):
    /// профиль действует на ТЕКУЩЕЕ соединение, не на машину целиком.
    /// Старое имя `toolset` сюда уже не заглядывает: `From<CfgFile>`
    /// переносит его значение в `profile` при разборе файла (круг починки
    /// 1/5 задачи 9) — одно понятие, один живой ключ, как и у
    /// `configuration()`.
    ///
    /// Пусто — `business`, а не отказ: бухгалтеров, которые будут
    /// открывать коннектор, больше, чем 1С-разработчиков, и им опаснее
    /// получить разработческий набор по умолчанию. Названное, но
    /// неизвестное значение — отказ словами со списком допустимых: тот же
    /// приём, что у `configuration()`, и по той же причине — молчаливый
    /// откат скрыл бы опечатку человека.
    pub fn toolset(&self) -> Result<&str, String> {
        const ALLOWED: [&str; 2] = ["developer", "business"];
        let t = self.profile.trim();
        if t.is_empty() {
            return Ok("business");
        }
        if ALLOWED.contains(&t) {
            Ok(t)
        } else {
            Err(format!("toolset — неизвестный набор инструментов «{t}»; допустимые значения: {}", ALLOWED.join(", ")))
        }
    }
}

impl Cfg {
    /// Потолок записи у дочернего `mcp-1c` — `read_write` или `read_only`. У
    /// ребёнка это ключ `--access`, и потолок у него не формальность: замер
    /// владельца показал, что при `read_only` пишущие инструменты вообще не
    /// регистрируются (`server/server.go` форка — `RegisterReadTools`, и
    /// `return` до `RegisterWriteTools`), то есть их нет и в `tools/list`, а
    /// не «мы их спрятали» фильтром на своей стороне.
    ///
    /// Пусто — `read_only` (решение владельца 1.11: по умолчанию
    /// инструментов, пишущих в базу, нет). Возвращает `&str`, не `Result`:
    /// именованное, но неизвестное значение отсекает `validate()` ещё при
    /// чтении настроек (см. его тело) — к моменту вызова этого метода `Cfg`
    /// уже проверен, и откат на `read_only` здесь для пустой строки — тип-
    /// безопасный синоним уже проверенного значения, не маскировка
    /// опечатки.
    pub fn access(&self) -> &str {
        let w = self.current().write.trim();
        if w.is_empty() {
            "read_only"
        } else {
            w
        }
    }

    /// Можно ли писать — отказ по умолчанию, не разрешение по умолчанию
    /// (круг исправления, находка владельца 2.11): сравнение «равно
    /// `read_only`» разрешало бы запись на любое неожиданное значение
    /// (опечатку, иной регистр, пустую строку после негодного файла —
    /// случай, которого сравнение с `access()` не ждёт, раз сам `access()`
    /// такую строку уже превратил в `"read_only"`, но следующий, кто решит
    /// сравнивать `self.current().write` напрямую, на эту же мину наступит
    /// снова). Поэтому здесь наоборот: разрешает писать ТОЛЬКО точное
    /// `"read_write"`, всё прочее — нет. Один метод, а не сравнение по
    /// месту — чтобы в `bridge.rs` (потолок канала vrunner) и в журнале при
    /// подъёме канала спрашивали одно и то же, а не два текста одной мысли,
    /// которые однажды разойдутся.
    pub fn allows_write(&self) -> bool {
        self.current().write.trim() == "read_write"
    }

    /// Клон `self` с подменённым одним полем — потолком записи, остальные
    /// поля не трогает. Для того, кто хочет перенести потолок на уже
    /// проверенный `Cfg` (живая ячейка сеанса, `Session::cfg_now`, или
    /// последний удачно прочитанный снимок в `ops_host::watch_mcp`), не
    /// толкая туда непроверенный целиком — круг исправления 2 задачи 3
    /// плана «тонкий срез ценности» (`gui::tray::apply_access`): остальные
    /// поля могли не пройти `validate()`, а ужесточение (или смена) потолка
    /// записи всё равно обязано дойти до сеанса.
    ///
    /// Соединений нет вовсе — не меняет ничего и ничего не создаёт (круг
    /// починки 1, находка C). Это ПЕРЕНОС одного поля на существующее
    /// соединение, а не первая настройка: придумать здесь соединение значило
    /// бы положить человеку в список карточку, которой он не заводил, —
    /// карточку без базы, которую первая же запись унесла бы на диск, да ещё
    /// и негодную для `validate()` (пустой путь к базе). Зовущий это видит:
    /// список так и остался пуст, а потолок читается как «только чтение»
    /// (`access`/`allows_write` на пустом списке — отказ по умолчанию,
    /// правило потолка записи в этом проекте), то есть потерянный перенос
    /// `read_write` ошибается в сторону запрета, а не разрешения.
    pub fn with_access(mut self, access: &str) -> Self {
        if !self.connections.is_empty() {
            self.current_mut().write = access.into();
        }
        self
    }

    /// Адрес Gitea среды — только то, что написано в поле `gitea`; пусто —
    /// `None`. Вывода здесь нет: адрес смотрит наружу этой машины, и
    /// ошибиться в нём легко, поэтому его выводят один раз при настройке
    /// (`ops_host::derived_gitea`) и записывают в toml.
    pub fn gitea_url(&self) -> Option<&str> {
        let explicit = self.current().gitea.trim().trim_end_matches('/');
        (!explicit.is_empty()).then_some(explicit)
    }

    /// Свой каталог выгрузки для `mcp-1c` — только когда человек выбрал его
    /// сам: поле непусто и отличается от выведенного `<project>/src`.
    /// Записанное настройкой умолчание ключ `--dump` не включает: иначе наша
    /// запись молча сменила бы агенту корень поиска по коду на уже
    /// настроенной машине, где поле было пустым (находка ревью задачи 35).
    pub fn dump_override(&self) -> Option<&str> {
        let d = self.current().dump.trim();
        (!d.is_empty() && d != derived_dump(&self.current().project)).then_some(d)
    }

    /// Каталог выгрузки для поиска mcp-1c: `dump`, а пусто — `<project>/src`.
    pub fn dump_dir(&self) -> String {
        if self.current().dump.is_empty() {
            derived_dump(&self.current().project)
        } else {
            self.current().dump.clone()
        }
    }

    /// Порты моста для МЕСТНОЙ работы: `mcp`/`vrunner`/`web` — с задачи 6
    /// плана «тонкий срез ценности» константы, те же числа, что раньше
    /// давало ПУСТОЕ имя рабочего места (`7771`/`7781`/`7791`). Имя рабочего
    /// места их больше не считает вовсе: `mcp` и `vrunner` — номера, которые
    /// человек своей рукой вписал в агентский харнес (Zed, Codex, Claude
    /// Code) на ЭТОЙ машине, и смена числа увела бы их у всех живых местных
    /// установок разом (решение владельца 2.11). Настоящего подбора при
    /// занятости эта тройка пока не получила (задача 1 плана «тонкий срез
    /// ценности» вяжет только `http` — `publication::Paths::of`) — это дело
    /// `ports::choose`, когда до него дойдёт очередь.
    ///
    /// Для ТУННЕЛЬНОГО режима эта функция не годится — рядом `tunnel_ports()`,
    /// и граница между ними в сигнатуре, не в комментарии: эта всегда
    /// константа, та всегда считает от рабочего места. Перепутать их молча
    /// нельзя — это ровно находка Б3 круга исправления финального ревью:
    /// задача 6 сделала константой и местную работу, и туннель разом, а
    /// туннель читает чужое поле (`current().workstation`), которое с константой
    /// не согласовано.
    pub fn ports(&self) -> Ports {
        Ports { mcp: 7771, vrunner: 7781, web: 7791 }
    }

    /// Порты моста для ТУННЕЛЬНОГО режима: считаются от номера рабочего
    /// места — `dev1` → `7771`/`7781`/`7791`, `dev2` → `7772`/`7782`/`7792`,
    /// `dev3` → `7773`/`7783`/`7793`. Та же формула, что действовала до
    /// задачи 6 (`git show 23a0487^:setup/1c-connect/src/cfg.rs:569-572`), и
    /// возвращена сюда не случайно: эта же тройка идёт среде как список
    /// ПРОБРАСЫВАЕМЫХ портов (`tunnel::run` → `Tunnel::connect`), а сторона
    /// среды настроена ПО РАБОЧИМ МЕСТАМ (`dev1c-setup/verify.rs` слушает
    /// именно `7770 + n`) — константа здесь увела бы порты у живых
    /// установок `dev2`/`dev3` (круг исправления финального ревью, Б3).
    ///
    /// Местная работа (`ports()` выше) эту функцию не зовёт и не обязана:
    /// цель задачи 6 — её независимость от пилотного поля — этим не
    /// отменяется, уточняется только туннельная половина, которая поле и
    /// так читает (`project.rs`, `gate.rs`). Функция уедет вместе с
    /// туннельным режимом и SSH.
    pub fn tunnel_ports(&self) -> Ports {
        let n = self.number().unwrap_or(1);
        Ports { mcp: 7770 + n, vrunner: 7780 + n, web: 7790 + n }
    }

    /// ПРЕДПОЧТЕНИЕ порта публикации — то, чего человек хочет сейчас (явный
    /// `current().http_port` или выведенный из имени рабочего места — умолчание
    /// пилота, которое контракт подключения уже вычёркивает,
    /// `docs/superpowers/specs/2026-11-01-connection-contract.md`; поле
    /// уйдёт, предпочтение как понятие — нет), а не то, что уже досталось
    /// (`resolved`). Порты моста (`ports()`) сюда больше не идут: их никто
    /// не подбирает — см. докстроку `ports::Chosen`, находка 7 ревью круга
    /// 3. Круг исправления 3, находка ведущего: раньше здесь
    /// стоял `self.http_port()` — УЖЕ улаженный порт, и вход `ports::choose`
    /// замыкался сам на себя (запомненный выбор кормил себя же как
    /// «предпочтение», и новое предпочтение человека — например, явный
    /// `http_port` — до подбора не доходило никогда). `http_port()`-а эта
    /// функция НЕ зовёт больше: её
    /// дело — явный порт или вывод, не то, что выбрал `ports::choose`.
    ///
    /// Одна сборка на обоих вызывающих (`publication::Paths::of`,
    /// `ops_host::settle_chosen_http_port`) — врозь они дважды повторяли бы
    /// одно и то же правило «явный порт человека, иначе выведенный».
    pub fn first_attempt_ports(&self) -> crate::ports::Chosen {
        crate::ports::Chosen { http: self.current().http_port.unwrap_or_else(derived_http_port) }
    }

    /// Порт веб-сервера из действующего адреса публикации (`base_url()`, не
    /// хранимое поле `current().base_url`); 80, если не указан. В режиме `auto`
    /// действующий адрес считается от `http_port()` — читать хранимое поле
    /// напрямую означало форвардить веб-канал туннеля не туда (шестой
    /// читатель адреса публикации из спеки — см. тест ниже).
    pub fn web_port(&self) -> u16 {
        let url = self.base_url();
        let rest = url.trim_start_matches("http://");
        let hostport = rest.split('/').next().unwrap_or("");
        hostport.split_once(':').and_then(|(_, p)| p.parse().ok()).unwrap_or(80)
    }

    /// Порт своего httpd в режиме `auto`: ВЫБРАННЫЙ в этом сеансе
    /// (`resolved_http_port`), если его уже проставили, — тот же порт, что
    /// достался httpd (`publication::Paths::of`/`ports::choose`), а иначе
    /// явный `http_port` человека, иначе `derived_http_port` — умолчание
    /// ПЕРВОЙ попытки подбора. Эта функция сама подбор никогда не запускает
    /// (это сеть и диск, а не чистое чтение полей) — только читает то, что
    /// в `resolved_http_port` уже положил `ops_host::settle_chosen_http_port`.
    pub fn http_port(&self) -> u16 {
        self.resolved_http_port.unwrap_or_else(|| self.current().http_port.unwrap_or_else(derived_http_port))
    }

    /// Адрес публикации: в режиме `auto` считает от своего httpd (`http_port`),
    /// в `webserver` отдаёт хранимое поле `base_url` как есть.
    ///
    /// `127.0.0.1`, а не `localhost` — круг исправления 2, находка
    /// автоматической проверки безопасности: свой httpd слушает именно
    /// `127.0.0.1` (`Listen 127.0.0.1:{port}`, `windows_httpd_conf`/
    /// `linux_httpd_conf`), а на Windows `localhost` резолвится в `::1`
    /// РАНЬШЕ, чем в `127.0.0.1`. Сосед по терминальному серверу мог занять
    /// `[::1]:{тот же порт}` одновременно с нашим httpd на `127.0.0.1` — это
    /// разные сокеты, подбор порта (`ports::pick`) конфликта не увидел бы, а
    /// клиент ушёл бы на `::1` к соседу вместе с паролем базы, пока страж
    /// (`publication::guard_own_listener`) смотрел бы таблицу `127.0.0.1` и
    /// говорил «свой». Называя адрес прибитым к семейству, которое слушает
    /// httpd и проверяет страж, закрываем весь класс одной правкой — этот
    /// адрес (`base_url()`) — единственный голос к базе (`verify.rs`, мост),
    /// других дорог нет. `webserver` не трогаем: там адрес пишет человек.
    pub fn base_url(&self) -> String {
        if self.current().publication == "auto" {
            format!("http://127.0.0.1:{}{SERVICE_PATH}", self.http_port())
        } else if self.publication_address_missing() {
            String::new()
        } else {
            // Поле для адреса в окне теперь есть («Связь», видно только в
            // этом режиме), и пустое значит «не задан». Выведенная догадка
            // `http://localhost/<папка базы>/hs/mcp-1c` отсюда убрана: она
            // отправляла бы пробу, проверку и третий канал туннеля на чужой
            // Apache по выдуманному адресу — и человек читал бы отказ про
            // адрес, которого сам не писал.
            self.current().base_url.clone()
        }
    }

    /// Адрес чужой публикации не задан — работать не по чему. В режиме `auto`
    /// адрес считается сам, и «не задан» там не бывает.
    ///
    /// Пусто — значит не задан, и только пусто: что в поле написано, то и
    /// адрес. Выведенная догадка сюда не попадает — её снимает переключение
    /// режима (`is_derived_address`, `gui::tray::apply_publication`), а
    /// судить уже записанное по виду строки нельзя: `http://localhost/Buh`
    /// это и наша догадка, и законный адрес человека.
    pub fn publication_address_missing(&self) -> bool {
        self.current().publication != "auto" && self.current().base_url.trim().is_empty()
    }

    /// Печатает параметры в виде toml, пароли — ЧЕРЕЗ `store`: это
    /// единственное место, где пароль превращается из строки в памяти в
    /// шифртекст на диске (замысел 29.10, `secrets::Store::seal`). Пустой
    /// пароль не шифруется (`seal` отдаёт его пустым как есть) — иначе
    /// случайный nonce сделал бы печать недетерминированной, и два
    /// существующих теста образца (пустые пароли, сравнение строки
    /// дословно) упали бы правильно, но об это незачем биться каждый раз.
    ///
    /// Печатается ВЕСЬ список соединений и корневой `current` (задача 4): до
    /// неё печаталось одно текущее соединение, без имени и без `current`, —
    /// то есть файл с двумя блоками терял второй при первом же сохранении, а
    /// решение плана «текущее хранится именем в корне toml» на диск не
    /// попадало вовсе.
    pub fn render(&self, store: &secrets::Store) -> std::result::Result<String, String> {
        // Образец делится на две половины ровно по первому `[[connection]]`:
        // шапка (объяснения полей человеку и корневой `current`) печатается
        // ОДИН раз, а всё, что ниже, — образец ОДНОГО блока, по которому
        // печатается каждое соединение (решение плана 4: повторять
        // объяснения в каждом блоке нельзя, а оставить их только в первом
        // значило бы сделать первый блок особенным). Нет блока в образце —
        // отказ словами, а не молчаливая печать файла без соединений: такой
        // файл при следующем чтении потерял бы их все.
        // Шапка — всё до первой СТРОКИ-заголовка блока, и узнаёт её то же
        // правило, что у правки и чтения (`toml_render::section_of`): имя
        // блока названо и в объяснениях человеку выше него, так что поиск
        // подстроки разрезал бы шапку посреди предложения.
        // `split_inclusive` оставляет перевод строки на месте — сумма длин и
        // есть граница в байтах.
        let at: usize =
            EXAMPLE.split_inclusive('\n').take_while(|l| common::toml_render::section_of(l) != Some(CONNECTION)).map(str::len).sum();
        if at == EXAMPLE.len() {
            return Err(format!("{FILE}: в образце нет блока {CONNECTION} — печатать соединения не по чему"));
        }
        let (head, block) = EXAMPLE.split_at(at);
        let mut text = common::toml_render::render(head, |s, k| {
            // Корень файла: секции у `current` нет вовсе.
            (s.is_empty() && k == "current").then(|| format!("{:?}", self.current))
        });
        for h in &self.connections {
            // Пароли сеются ДО самого рисования и у КАЖДОГО соединения:
            // `common::toml_render::render` берёт обычный (безотказный) `Fn`,
            // и протаскивать `Result` через его замыкание было бы сложнее,
            // чем сосчитать два значения заранее и отказать через `?` здесь.
            let password = store.seal("password", &h.password)?;
            let db_password = store.seal("db_password", &h.db_password)?;
            text.push_str(&common::toml_render::render(block, |s, k| {
                if s != CONNECTION {
                    return None;
                }
                Some(match k {
                    "name" => format!("{:?}", h.name),
                    "server" => format!("{:?}", h.server),
                    "gitea" => format!("{:?}", h.gitea),
                    "password" => format!("{:?}", password),
                    "workstation" => format!("{:?}", h.workstation),
                    "base_path" => format!("{:?}", h.base_path),
                    "base_here" => h.base_here.to_string(),
                    "platform" => format!("{:?}", h.platform),
                    "configuration" => format!("{:?}", h.configuration),
                    "profile" => format!("{:?}", h.profile),
                    "write" => format!("{:?}", h.write),
                    "db_user" => format!("{:?}", h.db_user),
                    "db_password" => format!("{:?}", db_password),
                    "base_url" => format!("{:?}", h.base_url),
                    "dump" => format!("{:?}", h.dump),
                    "project" => format!("{:?}", h.project),
                    "tools" => format!("[{}]", h.tools.iter().map(|t| format!("{t:?}")).collect::<Vec<_>>().join(", ")),
                    "mode" => format!("{:?}", h.mode),
                    "publication" => format!("{:?}", h.publication),
                    "http_port" => h.http_port.unwrap_or(0).to_string(),
                    _ => return None,
                })
            }));
        }
        Ok(text)
    }
}

/// Заголовок блока соединения в файле — одно написание на печать (`render`),
/// на адресацию правки одного ключа (`set_current`) и на узнавание нового
/// вида файла. Три своих копии этой строки по файлам разошлись бы молча:
/// промах в одной из них — это ключ, записанный туда, где его никто не
/// читает (находка безопасности задачи 4).
pub const CONNECTION: &str = "[[connection]]";

/// Правка ОДНОГО ключа ТЕКУЩЕГО соединения в тексте файла человека — один
/// адрес на всех писателей одного ключа: переключатели меню значка
/// (`gui::save::save_tray_key` — `mode`, `publication`, `write`), дописанные
/// при настройке выведенные поля (`ops_host::write_derived_fields` —
/// `gitea`, `dump`, `http_port`) и подстановка прежнего шифртекста
/// (`write_checked`).
///
/// Зачем он есть (находка безопасности задачи 4). Все эти писатели звали
/// `toml_render::set(text, "[host]", ..)`, а `set` при отсутствии секции
/// ДОПИСЫВАЕТ её в конец файла. На файле с блоками `[[connection]]` это
/// давало сразу две беды: записанное не читал никто (чтение берёт список, а
/// `[host]` рядом с ним не читается вовсе), и файл с обеими половинами стал
/// с задачи 3 отказом — то есть один щелчок в трее делал настройки
/// нечитаемыми. Хуже всего это было у потолка записи: человек видел
/// ужесточение, а перезапуск его тихо откатывал, хотя в этом проекте правило
/// обратное — честный отказ вместо живого ужесточения.
///
/// Прежний файл (`[host]` и ни одного блока) правится там, где соединение и
/// лежит, — в самой `[host]`: дописать блок рядом с ней значило бы своей же
/// рукой сделать файл человека отказом. Блоки в файле есть — ключ идёт в
/// блок, который НАЗЫВАЕТ СЕБЯ текущим соединением (`current_block_in`).
pub fn set_current(text: &str, cfg: &Cfg, key: &str, value: &str) -> std::result::Result<String, String> {
    if common::toml_render::count(text, CONNECTION) == 0 {
        return Ok(common::toml_render::set(text, "[host]", key, value));
    }
    let nth = current_block_in(text, cfg)?;
    common::toml_render::set_in(text, CONNECTION, nth, key, value).ok_or_else(|| stale_file(&cfg.current))
}

/// Номер блока текущего соединения В ТЕКСТЕ файла — найденный по ключу
/// `name` внутри блоков, а не по месту соединения в `cfg.connections`.
///
/// Почему по имени (круг починки 1 задачи 4, находка 1). Текст писатель
/// перечитывает с диска, а `cfg` у него от загрузки — между ними человек
/// успевает правку руками, и образец теперь прямо приглашает её сделать
/// («скопируйте блок целиком»). Вставленный или переставленный блок сдвигает
/// номер, и потолок записи уехал бы в блок ЧУЖОГО соединения МОЛЧА: по
/// номеру такая запись выглядит удачной, отказ срабатывал бы только если
/// блоков стало меньше. Имя же — то самое, чем план (решение 1) и называет
/// текущее соединение, и оно переживает перестановку блоков.
///
/// Пустой `current` — ноль: блоки без строки `current` в корне — законный
/// вид файла, и текущее там первое по определению (то же правило, что у
/// `Cfg::current()`). Имя не нашлось ни в одном блоке — отказ словами: файл
/// на диске разошёлся с тем, что в памяти, и писать наугад нельзя.
pub fn current_block_in(text: &str, cfg: &Cfg) -> std::result::Result<usize, String> {
    if cfg.current.is_empty() {
        return Ok(0);
    }
    (0..common::toml_render::count(text, CONNECTION))
        .find(|nth| common::toml_render::get_in(text, CONNECTION, *nth, "name").as_deref() == Some(cfg.current.as_str()))
        .ok_or_else(|| stale_file(&cfg.current))
}

/// Одна фраза на оба случая, в которых писатель не нашёл своего блока: имени
/// нет ни в одном блоке и блока с таким номером нет вовсе. Причина у них
/// одна — файл на диске не тот, из которого читали, — и слов для неё хватает
/// одних.
fn stale_file(current: &str) -> String {
    format!("{FILE}: в файле нет блока соединения «{current}» — настройки на диске изменились, перечитайте их и повторите")
}

/// Открывает одно поле паролем; не получилось — пустая строка и имя поля в
/// `bad`. `OpenError::Foreign` и `OpenError::Broken` здесь не различаются
/// нарочно: отдельной структуры-ошибки у задачи 2 нет (список имён в `Cfg`
/// достаточен), а снаружи обе причины читаются одинаково — «пароль не
/// открылся, введите заново» (окно, задача 4), а не «файл битый, зовите
/// админа». Пустую строку (открытый текст или незаполненное поле)
/// `Store::open` возвращает как есть, в `bad` она не попадает.
fn open_or_mark(store: &secrets::Store, field: &str, value: &str, bad: &mut Vec<String>) -> String {
    match store.open(field, value) {
        Ok(v) => v,
        Err(_) => {
            bad.push(field.to_string());
            String::new()
        }
    }
}

