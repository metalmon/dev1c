    /// «О связи пока не сообщает» и «связей нет» — РАЗНЫЕ слова человеку, а не одна пустота на оба случая. Тест и держит это различие: пропади оно, `status` отвечал бы молчанием там, где обязан отвечать словами.
    #[test]
    fn not_telling_and_nothing_connected_are_different_words() {
        let (_dir, kit) = kit_for_test();
        // Комплект — СВОЙ: иначе первой же строкой встанет «обслуживает
        // другой комплект», и тест смотрел бы не на то, ради чего заведён.
        let mine = || Some(kit_mark(&kit));
        let unknown = status_lines(&StatusView { serving: true, cards: None, kit: mine() }, &kit);
        let none = status_lines(&StatusView { serving: true, cards: Some(vec![]), kit: mine() }, &kit);
        let one = status_lines(
            &StatusView {
                serving: true, cards: Some(vec![CardState { name: "Ромашка".into(), word: "подключено".into() }]), kit: mine()
            },
            &kit,
        );
        assert_ne!(unknown, none, "незнание и отсутствие связей не одно и то же");
        assert!(unknown[1].contains("не сообщает"), "{:?}", unknown);
        assert!(none[1].contains("не связана"), "{:?}", none);
        assert!(one[1].contains("Ромашка") && one[1].contains("подключено"), "{:?}", one);
        assert!(one[0].contains(crate::SUBJECT), "предмет назван общим словом: {:?}", one);
        assert!(status_lines(&StatusView { serving: false, cards: None, kit: mine() }, &kit)[0].contains("выключен"));
        // А сборка по ту сторону, не сказавшая комплекта, молчания не
        // получает: у моста тот же случай — `Served::Another`, и две меры на
        // один вопрос здесь были бы ровно той бедой, против которой вся
        // ветка. Снимок здесь набран руками нарочно: СВОЯ дверь такого не
        // отдаёт никогда (см. ниже), а чужая версия — отдаст.
        let silent = status_lines(&StatusView { serving: true, cards: Some(vec![]), kit: None }, &kit);
        assert!(silent.iter().any(|l| l.contains(ANOTHER_KIT)), "о неназванном комплекте сказано словами: {silent:?}");
    }

    /// **Дверь называет свой комплект с первой миллисекунды, а не с первого снимка** — Important 2 ревью всей работы, и красный тест на него.
    ///
    /// Чем куплен. `Door::new` клал `StatusView::default()`, то есть `kit: None`, а приём стуков поднимается до возврата из `open_at` — `show` же случается только после полного холодного набора фактов. `status`, набранный в эту щель, печатал про живого «обслуживает другой комплект — какой именно, не сообщает (похоже, он другой версии)». Ложь ОТ ЖИВОГО, и ей верят больше, чем диску. Прежняя докстрока объявляла эту ветку недостижимой — а она достигалась на каждом запуске.
    ///
    /// Сторож смотрит в ту самую щель: дверь открыта, `show` не звали НИ РАЗУ. Снимите подстановку комплекта в `Door::new` — тест краснеет здесь (проба сделана, ветка `another_kit` возвращает `Some`).
    ///
    /// `Served::No`, а не `Mine`, — потому что обслуживание в этот миг ещё не объявлено; важно, что это честное «нет», а не «чужой комплект».
    #[test]
    fn a_door_names_its_kit_before_the_holder_shows_anything() {
        let (_dir, kit) = kit_for_test();
        let name = test_door("kit-at-birth");
        let _door = open_at(&name, &kit).expect("дверь открылась");
        let Ok(Answer::Status(v)) = ask_at(&name, Ask::Status) else {
            panic!("дверь отвечает на `status` с первого мига")
        };
        assert_eq!(v.kit.as_deref(), Some(kit_mark(&kit).as_str()), "комплект назван до первого `show`: {v:?}");
        assert_eq!(another_kit(&v, &kit), None, "свой комплект не объявляется чужим");
        assert_eq!(served_at(&name, &kit), Served::No, "обслуживание ещё не объявлено — это «нет», а не чужой комплект");
        let lines = status_lines(&v, &kit);
        assert!(!lines.iter().any(|l| l.contains(ANOTHER_KIT)), "и человеку про чужой комплект не сказано ни слова: {lines:?}");
    }

    /// **Сверка комплекта стоит у `ask`, а не у семи команд** — Critical 1 ревью всей работы.
    ///
    /// Чем куплен. `code`, `dial`, `requests`, `allow`, `decline`, `peers`, `revoke` комплекта не сверяли вовсе: человек с двумя копиями комплекта набирал `--kit B code` при живом коннекторе на A и получал код, выданный карточке из A, под именем карточки из B.
    ///
    /// Проверяется через `another_kit` — тот самый единственный сторож, которым `ask` и отказывает: поднять в тесте вторую живую копию под чужим комплектом нечем (дверь одна на учётную запись), а вот решение «наш или не наш» и слова отказа проверяются целиком. Снимите сверку из `ask` — краснеть будет не этот тест, а тот, что ниже: он читает САМ ТЕКСТ `ask`.
    #[test]
    fn the_kit_check_has_one_place_and_it_refuses_in_the_shared_words() {
        let (_mine_dir, mine) = kit_for_test();
        let (_other_dir, other) = kit_for_test();
        let shown = |k: &Kit| StatusView { serving: true, cards: Some(vec![]), kit: Some(kit_mark(k)) };
        assert_eq!(another_kit(&shown(&mine), &mine), None, "свой комплект пропускается молча");
        let why = another_kit(&shown(&other), &mine).expect("чужой комплект — отказ словами");
        assert!(why.contains(ANOTHER_KIT) && why.contains(&kit_mark(&other)), "назван и случай, и чей комплект держат: {why}");
        // И что ДЕЛАТЬ — правило ветки: отказ без действия оставляет человека у терминала гадать. Ожидание литералом нарочно: подставь
        // сюда ту же строку, из которой слова собраны, и тест перестал бы проверять что бы то ни было.
        assert!(
            why.ends_with("Работайте с тем комплектом, который он обслуживает, либо остановите живой экземпляр и запустите нужный."),
            "{why}"
        );
        // Та же фраза и у случая, когда комплекта живой не назвал вовсе: выходов у человека те же два, а пути в сообщении нет.
        let unnamed = another_kit(&StatusView { serving: true, cards: None, kit: None }, &mine).expect("безымянный комплект — отказ");
        assert!(unnamed.contains("остановите живой экземпляр и запустите нужный"), "{unnamed}");
        // Тот же вердикт и те же слова у моста и у строки человеку — иначе мер стало бы снова несколько.
        assert_eq!(
            Served::Another(why.clone()),
            match another_kit(&shown(&other), &mine) {
                Some(w) => Served::Another(w),
                None => Served::Mine,
            }
        );
        assert!(status_lines(&shown(&other), &mine).iter().any(|l| l.trim() == why), "status говорит те же слова: {why}");
    }

