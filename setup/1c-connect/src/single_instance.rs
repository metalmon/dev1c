    /// именованный канал Windows живёт в общем пространстве имён машины, а
    /// не в сеансовом, и это замер, а не рассуждение (`door::pipe_path`);
    /// межпроцессную половину проверяет `door::tests::
    /// a_door_opened_by_another_process_answers_this_one`.
    #[test]
    fn one_copy_per_account_not_per_kit_and_not_per_session() {
        let (_one, first_kit) = kit_for_test();
        let (_two, other_kit) = kit_for_test();
        let user = unique("one-copy");
        let _held = acquire_at(&user, &first_kit, false).expect("первая копия берёт замок");
        assert!(acquire_at(&user, &other_kit, false).is_err(), "другой комплект той же учётной записи — та же единица");
        let someone_else = unique("one-copy-other");
        assert!(acquire_at(&someone_else, &other_kit, false).is_ok(), "другая учётная запись — другая единица");
    }

