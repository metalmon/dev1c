pub fn short_key(full: &str) -> String {
    let tail: String = full.chars().rev().take(4).collect::<Vec<_>>().into_iter().rev().collect();
    format!("…{tail}")
}

/// Как та сторона себя назвала — ОДНИ слова на диалог разрешения и на список заявок в командной строке.
