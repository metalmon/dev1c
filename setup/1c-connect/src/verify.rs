//
// Шесть имён — `pub`: по ним вкладка «Инструменты» отбирает факты своего предмета
// (`gui::panel::project_facts`) и выбирает главную кнопку
// (`gui::project_primary`). Отбор идёт по именам-константам, а не по текстам:
// переименованный факт тогда ломает сборку, а не тихо исчезает со вкладки.
const PARAMS: &str = "параметры";
const PLATFORM: &str = "платформа 1С";
const DISPLAY: &str = "экран для конфигуратора";
const ANALYZER: &str = "платформа для анализатора";
const KIT: &str = "mcp-1c в комплекте";
pub const TOOLS: &str = "инструменты комплекта";
