#!/bin/sh
# Запуск приложения с распахнутым на весь экран окном.
#
# Ни Zed, ни Firefox не умеют открываться распахнутыми сами: у Zed такой
# настройки нет вовсе (есть `restore_on_startup`, но он про содержимое, а не
# про окно), у Firefox нет ключа командной строки. Геометрию оба запоминают,
# но ПОСЛЕ первого раза — а на стенде дома создаются заново, и гость, который
# приходит на час, первого раза не переживает.
#
# Поэтому окно распахивает оконный менеджер: `wmctrl` в образе уже есть.
#
# Новое окно опознаётся сравнением списка окон до и после запуска. Так скрипт
# не знает ни про класс окна (у Zed в его `.desktop` нет даже
# StartupWMClass), ни про PID (`_NET_WM_PID` ставят далеко не все приложения,
# о чём честно предупреждает справка самого wmctrl) — и годится для любого
# приложения, которое добавят потом.
set -u

[ $# -gt 0 ] || {
    echo "launch-maximized: нужна команда — launch-maximized <команда> [аргументы]" >&2
    exit 2
}

# Нет X или нет wmctrl — распахивать нечего и нечем. Запускаем как есть:
# остаться без приложения хуже, чем остаться без распахнутого окна.
if [ -z "${DISPLAY:-}" ] || ! command -v wmctrl >/dev/null 2>&1; then
    exec "$@"
fi

before=$(mktemp) || exec "$@"
trap 'rm -f "$before"' EXIT INT TERM
wmctrl -l 2>/dev/null | awk '{print $1}' >"$before"

"$@" &
app=$!

# До двадцати секунд: Firefox на первом запуске создаёт профиль, Zed поднимает
# языковые серверы. Приложение умерло — ждать нечего.
i=0
while [ "$i" -lt 100 ]; do
    # Пустой список «до» — значит новыми будут все: grep -f с пустым файлом
    # не исключает ничего, и это ровно то поведение, которое нужно.
    new=$(wmctrl -l 2>/dev/null | awk '{print $1}' | grep -vxF -f "$before" | head -1)
    if [ -n "$new" ]; then
        wmctrl -i -r "$new" -b add,maximized_vert,maximized_horz 2>/dev/null
        break
    fi
    kill -0 "$app" 2>/dev/null || break
    sleep 0.2
    i=$((i + 1))
done

# Код возврата — приложения, а не наш: ярлык запускает его, а не нас.
wait "$app"
