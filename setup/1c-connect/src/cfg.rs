/// Путь HTTP-сервиса нашего расширения внутри публикации. Одно место на всех,
/// кто его дописывает или ищет: выведенный адрес, приведение введённого
/// человеком и свой адрес в режиме `auto`.
pub const SERVICE_PATH: &str = "/hs/mcp-1c";

/// Адрес публикации по умолчанию: имя последней папки `base_path`. Это наша
/// догадка, а не ответ человека: в режиме «публикует коннектор» адрес
/// считается сам, а в режиме «публикует платформа 1С» его вписывают в окне
/// (`panel::shown_base_url` показывает эту догадку пустым полем, а
/// переключение режима её снимает — `is_derived_address`). Имя, которое
/// `validate` не пропустит (пусто, «C:», кириллица), заменяется на `Buh`.
/// Имя базы: что стоит после последнего разделителя. Путь к базе бывает не
/// путём — `Срв\Бухгалтерия` это строка соединения с сервером, — поэтому
/// разделителем считаем и `\`, и `/`, а резать берёмся сами: на Linux
/// `Path::file_name` обратный слэш разделителем не считает, и из `сервер\база`
/// имя не выделилось бы вовсе (нашлось, когда тесты окна впервые пошли на
/// Linux, CI 21.10.2026).
///
/// Правило одно на трёх потребителей — заголовок карточки, имя в диалоге
/// подтверждения, выведенный адрес публикации, — а вот что показать, когда
/// имени нет, каждый решает сам: карточка говорит словами «База не указана»,
/// диалог показывает путь целиком, адрес подставляет `Buh`. Поэтому здесь
/// пустое остаётся пустым, без умолчаний за них.
pub fn base_name(base_path: &str) -> &str {
    let name = base_path.trim().trim_end_matches(['\\', '/']).rsplit(['\\', '/']).next().unwrap_or("");
    // Буква диска именем базы не бывает: `C:\` — корень, а не база, и
    // «C:» в заголовке карточки или в диалоге подтверждения ничего человеку
    // не говорит. Правило то же, что у `is_server_base` выше: ровно `X:`.
    let drive = name.len() == 2 && name.ends_with(':') && name.starts_with(|c: char| c.is_ascii_alphabetic());
    if drive {
        ""
    } else {
        name
    }
}

pub fn derived_base_url(base_path: &str) -> String {
    let name = base_name(base_path);
    let ok = !name.is_empty() && name.chars().all(|c| c.is_ascii_alphanumeric() || "-._~".contains(c));
    format!("http://localhost/{}{SERVICE_PATH}", if ok { name } else { "Buh" })
}

/// Наша ли это догадка, а не адрес человека. Спрашивается ровно в одном
/// месте и ровно в один момент — когда человек переключает публикацию на
/// «уже опубликована» (`gui::tray::apply_publication`): в обычном режиме
/// `carried_base_url` держит в toml выведенный от каталога базы адрес, и
/// принять его за ответ человека нельзя — в этом режиме он ничего не
/// вписывал.
///
/// Сравнением строк это решается только здесь. Дальше — никогда: человек, у
/// которого база и правда опубликована как `http://localhost/<папка>`,
/// вписывает ровно такую строку, и выбрасывать её как «догадку» значило бы
/// ломать самый частый случай.
pub fn is_derived_address(host: &Host) -> bool {
    host.base_url.trim() == derived_base_url(&host.base_path)
}

/// Полный адрес HTTP-сервиса из того, что человек вписал в окне. Свою
/// публикацию он знает как `http://localhost/Buh` — именно её он открывает в
/// браузере, — а `/hs/mcp-1c` это имя нашего сервиса в расширении, и слышать
/// про него человек не должен (решение владельца 26.10). Схему дописываем,
/// хвостовой слэш снимаем, хвост сервиса добавляем, если его ещё нет.
///
/// Пустое остаётся пустым: «адрес не задан» — состояние, которое видит замок
/// (`gui::gate::cold_gate`), а не ошибка ввода и не повод что-то выдумать.
pub fn full_base_url(typed: &str) -> String {
    let t = typed.trim().trim_end_matches('/');
    if t.is_empty() {
        return String::new();
    }
    let with_scheme = if t.contains("://") { t.to_string() } else { format!("http://{t}") };
    // Именно в конце, а не где-нибудь: `/hs/mcp-1c` посреди пути — это часть
    // имени публикации, а не наш сервис, и хвост ему всё равно нужен.
    if with_scheme.ends_with(SERVICE_PATH) {
        with_scheme
    } else {
        format!("{with_scheme}{SERVICE_PATH}")
    }
}

/// Клиент-серверная ли база: `сервер\база` против файловой — `C:\Bases\Buh`
/// или сетевой `\\сервер\шара\база`.
///
/// Правило одно на всех, кто про это спрашивает: ключ Конфигуратора
/// (`ops_host::ib_switch` — `/S` против `/F`) и строка подключения в
/// дескрипторе публикации (`publication::vrd` — `Srvr`/`Ref` против `File`).
/// Прежде оно жило копией только у ключа, а дескриптор о клиент-серверных
/// базах не знал вовсе и писал им `File="сервер\база"` — платформа такую
/// публикацию не открывает (находка владельца 26.10).
///
/// Различаем по тому, что стоит ДО первого обратного слэша: буква диска
/// (`C:`) — файловая база, что угодно другое — имя сервера. Двоеточие само
/// по себе признаком быть не может: `сервер:1541\база` — законная форма с
/// портом кластера, и прежняя копия правила относила её к файловым.
///
/// Сетевой путь — ФАЙЛОВАЯ база, хоть и без буквы диска: та же копия этого
/// не различала и отдавала ему `/S`.
pub fn is_server_base(base_path: &str) -> bool {
    if base_path.starts_with("\\\\") {
        return false;
    }
    let Some((head, _)) = base_path.split_once('\\') else { return false };
    // Буква диска: ровно `X:` перед первым слэшем.
    let drive = head.len() == 2 && head.ends_with(':') && head.starts_with(|c: char| c.is_ascii_alphabetic());
    !drive && !head.is_empty()
}

/// Номер рабочего места: `dev1`, `dev2` или `dev3`. С задачи 6 плана «тонкий
/// срез ценности» и до круга исправления финального ревью у функции был
/// РОВНО один потребитель — правило `validate()`, что в туннельном режиме
/// имя обязано разбираться в номер (`!mode_needs_env(...) || self.number().is_some()`).
/// Круг исправления (Б3) добавил второго: `Cfg::tunnel_ports()` считает от
/// этого номера порты моста для среды — там же объяснение, почему местная
/// `Cfg::ports()` (константы, те же числа, что раньше давало ПУСТОЕ имя)
/// этот номер по-прежнему не читает. Обе функции уедут вместе с туннельным
/// режимом и SSH — до этого момента номер жив для них обеих.
pub fn number_of(workstation: &str) -> Option<u16> {
    workstation.strip_prefix("dev")?.parse::<u16>().ok().filter(|n| (1..=3).contains(n))
}

/// Умолчание ПЕРВОЙ попытки подбора: `8081` — не окончательный порт httpd.
/// Поля в окне нет, правку переносит сохранённое в toml значение как есть.
/// Настоящий порт публикации нащупывается от этого числа при занятости и
/// запоминается в каталоге состояния (`ports::choose`, `publication::Paths::of`)
/// — вторая бухгалтерка на том же терминальном сервере (то же предпочтение)
/// садится не на занятый этой константой порт, а на следующий свободный,
/// вместо того чтобы не стартовать вовсе (план «тонкий срез ценности»,
/// задача 1).
///
/// До задачи 6 это была формула `8080 + N` номера рабочего места — ПУСТОЕ
/// имя (`unwrap_or(1)`) давало `8081`, и именно это число остаётся
/// константой сейчас: `mcp` и `vrunner` (см. `Cfg::ports`) — номера, которые
/// человек своей рукой вписал в агентский харнес (Zed, Codex, Claude Code),
/// а после задачи 1 изменившееся предпочтение честно запускает переподбор —
/// значит смена константы увела бы порты у всех живых установок разом, и ни
/// одна настройка агента больше не попала бы в коннектор (решение владельца
/// 2.11). Имя рабочего места эту функцию больше не читает вовсе — оно
/// осталось полем туннельной половины (`Host::workstation`).
pub fn derived_http_port() -> u16 {
    8081
}

/// Каталог выгрузки по умолчанию: `<project>/src`. Поля в окне нет —
/// умолчание идёт за каталогом проекта, а правку переносит
/// `gui::carried_dump` (тот же приём, что у адреса публикации).
pub fn derived_dump(project: &str) -> String {
    format!("{}{}src", project.trim_end_matches(['\\', '/']), std::path::MAIN_SEPARATOR)
}

#[derive(Clone, Default, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Cfg {
    pub host: Host,
    /// Список соединений. Прежний файл с одной секцией `[host]` и без
    /// единого `[[connection]]` — законный вид настроек (так выглядят все
    /// уехавшие комплекты, включая эталонный): при чтении он становится
    /// списком из одного элемента (`load_raw`), а сама секция `[host]`
    /// остаётся как есть — её читает весь остальной код до задачи 3.
    #[serde(rename = "connection")]
    pub connections: Vec<Host>,
    /// Имя ТЕКУЩЕГО соединения из списка `connections` — имя, а не номер:
    /// оно читаемо человеком и переживает перестановку блоков (решение
    /// плана, 2.11). Имя, которого нет среди `connections`, — отказ при
    /// чтении (`load_raw`): человек правил файл руками и должен узнать, что
    /// опечатался, а не получить тихий выбор первого соединения.
    pub current: String,
    /// Имена полей, которые не открылись при чтении (`"password"`,
    /// `"db_password"`) — считается заново при каждом `load_unchecked_with`
    /// и в файл не идёт: это не настройка, а диагноз текущего чтения.
    /// `load` при непустом списке отказывает словами (анти-цель спеки:
    /// «serve»/«connect»/«mcp» не имеют права уехать молча с пустым
    /// паролем — `validate` пароли не проверяет); `load_unchecked` (её
    /// зовёт окно) отдаёт список как есть — человек должен ввести пароль
    /// заново, а не прочитать отказ там, где раньше открывалось окно.
    #[serde(skip)]
    pub undecryptable: Vec<String>,
    /// Порт, выбранный в ЭТОМ сеансе (`ports::choose`), а не выведенный из
    /// рабочего места, — `None`, пока его никто не проставил. `#[serde(skip)]`,
    /// как `undecryptable`: это не настройка человека, а выбор программы на
    /// сегодня, и `render`/`write_checked` сюда не заглядывают — печатают
    /// только `host.http_port`. Нарочно НЕ `host.http_port`: то поле читает
    /// `write_derived_fields`, решая по `is_none()`, писать ли туда умолчание
    /// один раз при настройке (установка пишет сюда `derived_http_port()`, и
    /// дальше это чужое поле, которое программа не трогает) — подставь туда
    /// подобранный порт, и эта проверка сочла бы его уже заполненным, а
    /// `render`/`write_checked` при следующем случайном смешении полей
    /// заморозили бы сегодняшний сеансовый подбор в toml навсегда (а поля
    /// для http_port в окне нет вовсе — человек не увидел бы, что
    /// подписывает). `Cfg::http_port()`
    /// ниже предпочитает это поле, когда оно есть.
    #[serde(skip)]
    pub resolved_http_port: Option<u16>,
}

/// Производный `Debug` печатал бы пароль полем как есть, а этот журнал
/// прикладывают к обращению в поддержку — значит, `{c:?}` должен уходить
/// наружу безопасным.
impl std::fmt::Debug for Cfg {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Cfg")
            .field("host", &self.host)
            .field("connections", &self.connections)
            .field("current", &self.current)
            .field("undecryptable", &self.undecryptable)
            .field("resolved_http_port", &self.resolved_http_port)
            .finish()
    }
}

#[derive(Clone, PartialEq, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Host {
    /// Имя соединения в списке `Cfg::connections` — то, чем его называет
    /// `current` и чем его различает человек. У прежнего файла `[host]`
    /// имени взять негде — его даёт `base_name(base_path)` при чтении
    /// (`load_raw`), пусто — «Соединение 1».
    pub name: String,
    pub server: String,
    /// Адрес Gitea среды целиком. Пусто — адрес не задан, и программа его не
    /// выдумывает: вывод «порт SSH минус два» верен только в туннеле, а в
    /// образе давал мёртвый адрес, о котором человек читал «Gitea не
    /// отвечает». Поле записывают один раз при настройке, и только там, где
    /// вывод верен: `1c-connect install` в туннельном режиме (из `server`,
    /// см. `ops_host::gitea_to_write`) либо `seed` стенда (настоящий адрес
    /// Gitea образа). В локальном режиме пусто так и остаётся, пока человек
    /// не задаст адрес сам.
    pub gitea: String,
    pub password: String,
    /// Логин человека в среде туннельного режима: `dev1`-`dev3`
    /// (`number_of`) — собственность туннельной половины, не местной. С
    /// задачи 6 плана «тонкий срез ценности» поле не влияет ни на МЕСТНЫЕ
    /// порты моста (`Cfg::ports`, `derived_http_port` — константы с 2.11), ни
    /// на замок одного коннектора (`single_instance::guard_key` — по
    /// пользователю ОС, а не по рабочему месту): обе половины сняты нарочно.
    /// Круг исправления финального ревью (Б3) вернул полю одного читателя:
    /// `Cfg::tunnel_ports()` считает от него порты, которые коннектор просит
    /// ПРОБРОСИТЬ среде — та сторона настроена по рабочим местам
    /// (`dev1c-setup/verify.rs`), и константа увела бы их у `dev2`/`dev3`.
    /// Совсем убрать поле нельзя (измерение владельца 2.11 показало почему):
    /// его читают `project.rs` (имя ветки git и логин) и `gate.rs:96`
    /// (проверка непустоты в туннельном режиме). Поле остаётся в структуре
    /// — иначе `deny_unknown_fields` отверг бы существующие комплекты со
    /// строкой `workstation = "dev1"`, включая эталонный, который
    /// переписывать запрещено, — и уедет целиком вместе с SSH на
    /// иroh-этапе, когда уйдёт и туннельный режим.
    pub workstation: String,
    pub base_path: String,
    /// Топология соединения: `true` — база на этой машине, `false` — на той
    /// стороне. Булево, а не строка с третьим состоянием: ровно два случая
    /// контракта, третьего нет (решение плана, 2.11). Умолчание `true`
    /// ставится рукописным `impl Default` ниже, не `#[serde(default)]` на
    /// `bool`: отсутствующий ключ дал бы `false` — ровно ту ловушку, что
    /// назначает Default через значение всего `Host::default()`, а не тип
    /// поля (так выглядят и прежний `[host]`, и локальный режим).
    pub base_here: bool,
    /// Версия платформы 1С или её маска (`8.3`), которой работать. Пусто —
    /// версию выбирает лестница `platform::resolve` (пин базы, общий пин,
    /// самая новая). Названная, но не установленная версия — отказ со
    /// словами, а не молчаливый откат на новейшую.
    #[serde(default)]
    pub platform: String,
    /// Вид конфигурации базы для дочернего `mcp-1c` — `auto`, `generic` или
    /// `buh_3_0` (Бухгалтерия 3.0). Разбор, допустимые значения и довод,
    /// почему это не `profile`, — в `Cfg::configuration()`.
    #[serde(default)]
    pub configuration: String,
    /// Какой набор инструментов поднимает дочерний `mcp-1c` — `developer`
    /// или `business`. Разбор, допустимые значения и довод умолчания — в
    /// `Cfg::toolset()`.
    #[serde(default)]
    pub toolset: String,
    /// Профиль соединения в контракте подключения — «Разработчик» или
    /// «Бизнес-пользователь» (таблица полей спеки). Одно понятие — одно
    /// имя: у прежнего `toolset` та же роль, но под машинным именем, и при
    /// появлении аксессоров (задача 3) значение переезжает сюда. Здесь —
    /// только поле; разбор и перенос значения — не эта задача.
    #[serde(default)]
    pub profile: String,
    /// Потолок записи у дочернего `mcp-1c` — `read_write` или `read_only`.
    /// Разбор, допустимые значения и довод умолчания — в `Cfg::access()`.
    /// Поля в окне нет: потолок правит пункт меню значка «Запись в базу»
    /// (`gui::tray`), тем же приёмом, что `mode`/`publication`.
    #[serde(default)]
    pub write: String,
    pub db_user: String,
    pub db_password: String,
    pub base_url: String,
    pub dump: String,
    pub project: String,
    pub tools: Vec<String>,
    /// Режим работы: `tunnel` — база на этой машине, агент на удалённой
    /// стороне в контейнере среды, туда идёт туннель; `local` — всё на одной
    /// машине: база, агенты, мост и проект, никакой среды нет вовсе. Чем
    /// режимы отличаются для кода — одной функцией, `mode_needs_env`.
    pub mode: String,
    /// Кто публикует базу: `auto` — сама программа своим httpd (адрес считает
    /// `Cfg::base_url`), `webserver` — уже опубликовано вручную на Apache/IIS
    /// (адрес берётся из `base_url`).
    pub publication: String,
    /// Порт своего httpd в режиме `auto`; `None` — умолчание ПЕРВОЙ попытки
    /// подбора (`derived_http_port()`, с задачи 6 — константа `8081` для
    /// всех, не формула от рабочего места). Настоящий порт нащупывается при
    /// занятости и запоминается в каталоге состояния (`ports::choose`). В
    /// toml хранится как число, `0` значит «не задан».
    #[serde(deserialize_with = "http_port_de", skip_serializing_if = "Option::is_none")]
    pub http_port: Option<u16>,
}

/// Поля перечислены как у производного `Debug`, кроме `password` и
/// `db_password`: журнал коннектора прикладывают к обращению в поддержку, и
/// одна отладочная строка не должна обнулять шифрование паролей.
