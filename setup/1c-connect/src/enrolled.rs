//! Хранилище зачислений и выданных тикетов.
//!
//! Живое состояние программы, а не настройки человека: `1c-connect.toml`
//! хранит пароли и поля карточек, которые человек заводит руками, а здесь —
//! то, что программа запомнила сама про допуск (кто зачислен, какие тикеты
//! ещё не погашены). Разные по природе данные, разные файлы — смешивать их
//! значило бы, что бэкап параметров тащит за собой чужие ключи, а чистка
//! зачислений рискует задеть пароль базы. Файл лежит в каталоге состояния
//! (`Kit::state`), пишется при каждом изменении, читается при старте; формат
//! — тот же `toml`, что у параметров, но свой файл.
//!
//! Спека: `docs/superpowers/specs/2026-11-01-protocol-design.md`, раздел
//! «Зачисление»; `docs/superpowers/specs/2026-11-01-connection-contract.md`,
//! раздел «Что хранится после».

use crate::cfg::CardId;
use crate::secrets::hex;
use crate::single_instance;
use iroh::EndpointId;
use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};
use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

/// Имя файла в каталоге состояния — рядом с `node.key`, `allow`, `install.state`.
const FILE: &str = "enrolled.toml";

/// Одна зачисленная сторона: открытый ключ и то, что о ней решено.
///
/// Зачисленных сторон на одну карточку может быть сколько угодно (решение
/// владельца 1.11) — предел назначает лицензия 1С на одновременные
/// сеансы, а не мы; поэтому это список, а не одно поле у карточки.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Party {
    pub key: EndpointId,
    /// Для какой пары дано разрешение (`Enrolled::side`, там и довод). Сверяет его зачисление: разрешение одной пары не годится
    /// вместо разрешения другой.
    pub side: crate::wire::Side,
    /// Как сторона назвала себя при заявке (протокол, `says_name`) — в окне
    /// это помечается «её слова, не проверено».
    ///
    /// Чужая строка, и сюда она попадает уже вычищенной — без управляющих и
    /// невидимых знаков, обрезанной по длине (`enroll::as_said`). Чистит
    /// зачисление, а не книга: чистить надо ОДИН раз и до всего остального,
    /// иначе показанное человеку и записанное здесь разойдутся, а спор между
    /// ними разрешать нечем.
    pub says_name: String,
    /// Потолок записи ТОЙ машины, как она объявила его СВОИМ ПОСЛЕДНИМ подключением (`wire::Ceiling` в `hello`). Одна вещь, один писатель, одно значение.
    ///
    /// **Чем куплено (Critical и Important повторного ревью всей ветки).** Прежде здесь лежал ИТОГ, сложенный в миг зачисления: решение человека, потолок этой машины и потолок той — всё вместе и навсегда. Из этого выходили две беды, зеркальные друг другу. Возврат складывал потолок только ТОЙ машины, а запрет ЭТОЙ, щёлкнутый человеком после зачисления, в это замороженное значение попасть уже не мог — зачисленная сторона на каждом переподключении читала «разрешено читать и записывать», пока мост отказывал ей по живому праву. Наоборот — зачислили при закрытом потолке, и запись не возвращалась никогда, сколько бы человек ни щёлкал: снимок говорил «нет», и новый код был единственным выходом. И карточка в окне спрашивала у этого же снимка, то есть показывала не действующее право, а историю.
    ///
    /// Теперь ЗДЕСЬ хранится ровно то, чего мы не можем пересчитать сами, — чужой потолок, — а свои две половины спрашиваются у настроек в тот миг, когда ответ нужен (`cfg::Cfg::may_write`). Записывается он при зачислении и обновляется на каждом возврате (`enroll::accept_side`): иначе карточка снова говорила бы о той машине то, что было, а не то, что есть.
    ///
    /// В файле поле по-прежнему зовётся `write` (`Enrolled`) — переименовывать ключ значило бы осиротить книги, лежащие у людей на диске. Старое значение читается как потолок той машины и ошибается в сторону ЗАПРЕТА: сложенный итог никогда не был шире чужого потолка.
    pub peer_write: bool,
}

/// Запись о зачислении внутри файла — то же, что `Party`, плюс карточка, к
/// которой это зачисление относится: файл один на все карточки рабочего
/// места, `Party` наружу отдаётся уже отфильтрованной по карточке (`of`).
///
/// **Карточка названа КЛЮЧОМ, а не именем** (решение владельца 10.11, `cfg::CardId`). Имя человек правит когда хочет, и книга, ключёванная
/// именем, осиротляла все зачисления карточки при первом же переименовании. Ключ человек не правит — везти за ним нечего.
#[derive(Debug, Clone, Serialize, Deserialize)]
struct Enrolled {
    card: CardId,
    key: EndpointId,
    says_name: String,
    /// Для какой ПАРЫ выдано разрешение — сторона, какой та себя назвала, когда человек нажал «разрешить».
    ///
    /// **Разрешение относится к тому, что человек видел** (находка проверки безопасности 11.11). В паре A он разрешил «пустите этот
    /// ключ к МОЕЙ базе», в паре B — «пусть этот ключ присылает СВОЮ базу моим агентам». Это два разных разрешения, и одно не годится
    /// вместо другого.
    ///
    /// Умолчание — `WithAgents`: все разрешения, записанные до 11.11, выдавались в паре A, другой тогда не было.
    #[serde(default = "pair_a")]
    side: crate::wire::Side,
    /// Ключ в файле остаётся прежним, а смысл его назван у `Party::peer_write`: переименование ключа осиротило бы книги, лежащие у людей на диске.
    #[serde(rename = "write")]
    peer_write: bool,
}

/// Пара A — та, в которой выдавались все разрешения до 11.11: функция нужна `serde` как умолчание ушедшего поля.
fn pair_a() -> crate::wire::Side {
    crate::wire::Side::WithAgents
}

/// Выданный, но ещё не погашенный тикет.
///
/// **Секрета здесь нет — есть `fingerprint`, sha256 от него (решение
/// ведущего по замечанию проверки безопасности).** Хранящей стороне секрет
/// самой не нужен: ей нужно уметь проверить ПРЕДЪЯВЛЕННЫЙ секрет, а не
/// предъявить свой, — а это ровно то, что умеет отпечаток: посчитать тот же
/// хэш от пришедшего и сравнить. Украсть файл тогда бессмысленно: из
/// отпечатка секрет не собрать обратно никак — это сильнее, чем запечатать
/// секрет через `secrets::Store` (как ключ узла в `node.rs`), потому что
/// запечатанное открывается той же учётной записью, а отпечаток не
/// открывается вообще. Это и точнее ложится на спеку: «тикет не хранится
/// нигде после погашения» теперь верно и ДО погашения тоже.
///
/// `until` — unix-секунды, та же точность, с которой тикет и был выдан
/// (`Ticket::issue`), так что сравнение со сроком не теряет и не находит
/// лишней секунды.
#[derive(Debug, Clone, Serialize, Deserialize)]
struct IssuedTicket {
    card: CardId,
    fingerprint: String,
    until: u64,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
struct BookFile {
    #[serde(default)]
    enrolled: Vec<Enrolled>,
    #[serde(default)]
    tickets: Vec<IssuedTicket>,
}

/// Хранилище: зачисления и выданные тикеты одного рабочего места.
///
/// `data` — отражение диска НА МОМЕНТ последнего своего чтения или записи
/// этим объектом, не единственная правда: окно и отдельный процесс
/// `1c-connect mcp` держат РАЗНЫЕ `Book` на один файл одновременно (замок
/// рабочего места — `single_instance` — на пользователя, не на этот файл),
/// поэтому каждая мутация (`mutate`) перечитывает файл заново под замком
/// файла, а не доверяет этому снимку (круг починки 1, Important 4).
pub struct Book {
    path: PathBuf,
    data: BookFile,
}

impl Book {
    /// Читает файл состояния или заводит пустую книгу, если его ещё нет —
    /// нет файла значит нет истории, а не беда (первый запуск).
    ///
    /// Просроченные тикеты выбрасываются сразу при чтении: держать то, что
    /// уже не сработает, незачем, а если что-то успели выбросить — тут же
    /// перезаписываем файл, чтобы старый хвост не пережил ещё один
    /// перезапуск без единого изменения.
    pub fn open(state_dir: &Path) -> Result<Book, String> {
        let path = state_dir.join(FILE);
        let _guard = lock(&path)?;
        let mut data = load_raw(&path)?;
        if prune_expired(&mut data) {
            write_book(&path, &data)?;
        }
        Ok(Book { path, data })
    }

    /// Проверяет тикет БЕЗ записи и отвечает ВЕРДИКТОМ: к какой карточке код,
    /// либо «не знаю такого», либо «устарел».
    ///
    /// Нужно тому, кто обязан различать три разных случая, а не два (круг
    /// починки 2 задачи 5, Important 6). `check` сводит «кода нет»,
    /// «код устарел» и «книга не прочиталась» к одному `Err` со строкой, и
    /// разобрать их обратно можно только по тексту — то есть по совпадению
    /// слов, которое переживёт ровно до первой правки формулировки. А разница
    /// между ними не косметическая: первые два — обычная жизнь замка на
    /// дверном звонке, им место в спокойном отказе той стороне; третий — НАША
    /// беда, и он обязан краснеть в нашем журнале и не выдавать той стороне
    /// ни путей, ни подробностей.
    ///
    /// Поэтому здесь `Err` значит ровно одно: книгу не удалось прочитать.
    /// Любой вердикт по самому коду — это `Ok`.
    pub fn verdict(&self, secret: &[u8; 32]) -> Result<Verdict, String> {
        let _guard = lock(&self.path)?;
        let data = load_raw(&self.path)?;
        Ok(match locate(&data, secret) {
            Found::At(pos) => Verdict::Card(data.tickets[pos].card.clone()),
            Found::Expired => Verdict::Expired,
            Found::Unknown => Verdict::Unknown,
        })
    }

    /// Запоминает выданный тикет: отпечаток секрета (не сам секрет — см.
    /// докстроку `IssuedTicket`), к какой карточке он относится и когда он
    /// умирает. Пишет на диск сразу же — без этого второй процесс (или этот
    /// же после перезапуска) не увидел бы код, который уже отдали человеку.
    pub fn issue(&mut self, card: &CardId, ticket: &crate::ticket::Ticket) -> Result<(), String> {
        self.write_ticket(card, ticket, false)
    }

    /// Перевыпуск: новый код карточки ГАСИТ все прежние её коды, и гасит в
    /// одной записи с появлением нового.
    ///
    /// Так читает «Выдать новый код» человек, и читает он верно — особенно
    /// когда нажимает это именно потому, что прежняя строка куда-то утекла:
    /// «новый» без «старый больше не работает» оставляет утёкший код живым
    /// ещё на сутки (`ticket::LIFETIME`), и нажавший об этом не узнает.
    ///
    /// Одна `mutate`, а не «погасить, потом выдать»: между двумя записями
    /// может оборваться питание, и карточка осталась бы либо без кода вовсе
    /// (погасили, выдать не успели), либо с двумя живыми (выдали, погасить
    /// не успели) — второе ровно то, от чего перевыпуск и заводится.
    ///
    /// Отличается от `issue` только этим. `issue` оставлена как есть: одна
    /// карточка С ДВУМЯ живыми кодами — законное состояние хранилища (так
    /// проверяется, что `spend` гасит ровно один), и запрещать его в самом
    /// нижнем слое незачем. Выдаёт код человеку только окно, и оно зовёт
    /// `reissue` всегда (`codes::issue`).
    pub fn reissue(&mut self, card: &CardId, ticket: &crate::ticket::Ticket) -> Result<(), String> {
        self.write_ticket(card, ticket, true)
    }

    fn write_ticket(&mut self, card: &CardId, ticket: &crate::ticket::Ticket, douse_old: bool) -> Result<(), String> {
        let now = now_secs();
        let until = ticket.until.duration_since(UNIX_EPOCH).unwrap_or(Duration::ZERO).as_secs();
        if until < now {
            // Круг починки 1, Минор 6: раньше выдача уже просроченного
            // тикета тихо возвращала успех, а первая же запись (чистка
            // просрочки внутри `persist`) выбрасывала его обратно — человек
            // получал на руки код, которого в хранилище уже не было. Лучше
            // отказать здесь словами, чем соврать об успехе. Гашение прежних
            // при таком отказе тоже не идёт: карточка не должна остаться без
            // кода из-за попытки выдать негодный.
            return Err("Этот тикет уже просрочен — выдавать его некому.".to_string());
        }
        let card = card.clone();
        let fingerprint = fingerprint(&ticket.secret);
        self.mutate(move |data| {
            if douse_old {
                data.tickets.retain(|t| t.card != card);
            }
            data.tickets.push(IssuedTicket { card, fingerprint, until })
        })
    }

    /// Гасит тикет по секрету и отдаёт имя карточки, к которой он выдан.
    ///
    /// Зовётся ровно тогда, когда человек на стороне базы РАЗРЕШИЛ заявку —
    /// не раньше (шаг пятый спеки; шаг третий — непортящая проверка,
    /// `check`, выше). Тикет после погашения не хранится нигде (спека, «Что
    /// хранится после») — запись УДАЛЯЕТСЯ, а не помечается «потрачен»: как
    /// следствие, повторная попытка по тому же секрету получает тот же
    /// отказ, что и секрет, которого никогда не было. Это сознательно: раз
    /// хранить «потрачен» запрещено, различить два случая снаружи нечем, и
    /// спека это допускает.
    pub fn spend(&mut self, secret: &[u8; 32]) -> Result<CardId, String> {
        let secret = *secret;
        self.mutate(move |data| match locate(data, &secret) {
            Found::At(pos) => Ok(data.tickets.remove(pos).card),
            Found::Expired => Err(EXPIRED_TICKET.to_string()),
            Found::Unknown => Err(UNKNOWN_TICKET.to_string()),
        })?
    }

    /// Зачисляет ключ к карточке. Повторная заявка того же ключа заменяет
    /// старую запись, а не плодит дубликат — у ключа на карточке одно
    /// решение, а не история решений.
    ///
    /// Этим же вызовом возврат обновляет потолок ТОЙ машины (`Party::peer_write`, там и довод): замена записи — ровно то, что нужно, когда
    /// та сторона объявила свой потолок заново.
    pub fn enroll(
        &mut self,
        card: &CardId,
        key: EndpointId,
        says_name: &str,
        peer_write: bool,
        side: crate::wire::Side,
    ) -> Result<(), String> {
        let card = card.clone();
        let says_name = says_name.to_string();
        self.mutate(move |data| {
            data.enrolled.retain(|p| !(p.card == card && p.key == key));
            data.enrolled.push(Enrolled { card, key, says_name, peer_write, side });
        })
    }

    /// Правит потолок ТОЙ машины у СУЩЕСТВУЮЩЕЙ записи — и ничего не вставляет. `false` — записи нет: эта сторона к этой карточке не
    /// зачислена, и возврат по ней не состоится.
    ///
    /// **Почему отдельный метод, а не `enroll` с новым значением** (находка проверки безопасности на эту правку). `enroll` — это
    /// вставка-или-обновление, и на пути возврата она открывает щель ровно в том обещании, ради которого на этой ветке книга перечитывается
    /// с диска на каждое подключение: между чтением допуска и записью замок отпускается, а человек в окне успевает нажать «Отозвать
    /// разрешение». Отзыв стирает запись — и `enroll` тут же возвращает её обратно, с тем же ключом, тем же именем и тем же правом. Человек
    /// видит, что список опустел, а на следующем круге отозванная сторона снова в нём, и узнать об этом ему неоткуда.
    ///
    /// Здесь поиск и правка — ОДИН шаг под ОДНИМ замком (`mutate` берёт его и перечитывает файл заново), и воскресить стёртую запись
    /// нечем: вставки в этом методе нет как пути, а не как запрета. На пути, где решается допуск, «прочитал — подумал — записал» без одного
    /// замка неверно всегда, даже когда записывается мелочь вроде чужого потолка.
    pub fn refresh_peer_write(&mut self, card: &CardId, key: EndpointId, peer_write: bool) -> Result<bool, String> {
        let card = card.clone();
        self.mutate(move |data| match data.enrolled.iter_mut().find(|p| p.card == card && p.key == key) {
            Some(p) => {
                p.peer_write = peer_write;
                true
            }
            None => false,
        })
    }

    /// Отзывает ОДНУ сторону у карточки. Зачисленных сторон бывает сколько
    /// угодно (решение владельца 1.11) — отзыв стирает запись только этого
    /// ключа, остальные зачисления той же карточки не трогает вовсе.
    pub fn revoke(&mut self, card: &CardId, key: EndpointId) -> Result<(), String> {
        let card = card.clone();
        self.mutate(move |data| data.enrolled.retain(|p| !(p.card == card && p.key == key)))
    }

    /// Карточку удалили — её зачисления и её непогашенные коды уходят вместе с
    /// ней, одной записью.
    ///
    /// Остаться они не могут: спросить о них больше нечем (ключа карточки в
    /// настройках нет), а код, выданный удалённой карточке, по книге живёт ещё
    /// сутки — то есть `verdict` признал бы его годным и назвал карточку,
    /// которой в настройках уже нет. Пусть и не допуск (дальше заявку некуда
    /// приложить), но ровно тот разряд, от которого лечится весь проект:
    /// хранилище утверждает то, чего нет.
    ///
    /// Нет записей — не беда, забывать нечего (как у `Partners::forget`).
    pub fn forget(&mut self, card: &CardId) -> Result<(), String> {
        let card = card.clone();
        self.mutate(move |data| {
            data.enrolled.retain(|p| p.card != card);
            data.tickets.retain(|t| t.card != card);
        })
    }

    /// Зачислен ли ЭТОТ ключ к ЭТОЙ карточке — вопрос допуска, и ответ на
    /// него читается с диска, под замком, а не из снимка в памяти.
    ///
    /// **Правило, которое держит этот метод: решение о допуске никогда не
    /// принимается по `of`** (круг починки 1 задачи 5, HIGH 1). Снимок в
    /// памяти годится для ПОКАЗА — списка в окне, который и так
    /// перерисовывается, — но не для «пускать ли». Между тем, как процесс
    /// открыл книгу, и тем, как по этой книге кого-то пустили, человек в
    /// окне успевает нажать «Отозвать разрешение», и отзыв пишет другой
    /// `Book` на тот же файл. Спека про отзыв говорит «отправляется и тут же
    /// рвёт потоки этой базы» — отзыв, который не действует немедленно, не
    /// отзыв вовсе, а по устаревшему снимку отозванная сторона входила бы
    /// ровно как зачисленная.
    ///
    /// Под замком, но без перезаписи, — как и `check`: `write_atomic`
    /// заменяет файл переименованием, и читатель увидит либо целый старый,
    /// либо целый новый, никогда половину.
    pub fn enrolled_to(&self, card: &CardId, key: EndpointId) -> Result<Option<Party>, String> {
        let _guard = lock(&self.path)?;
        let data = load_raw(&self.path)?;
        Ok(data.enrolled.iter().find(|p| &p.card == card && p.key == key).map(|p| Party {
            key: p.key,
            side: p.side,
            says_name: p.says_name.clone(),
            peer_write: p.peer_write,
        }))
    }

    /// Кто зачислен к этой карточке прямо сейчас — из снимка, обновлённого
    /// последним чтением или записью ЭТОГО объекта (см. докстроку `Book`).
    ///
    /// Для ПОКАЗА. Решать по нему, пускать ли кого-то, нельзя — на это есть
    /// `enrolled_to`, читающий диск (см. его докстроку).
    pub fn of(&self, card: &CardId) -> Vec<Party> {
        self.data
            .enrolled
            .iter()
            .filter(|p| &p.card == card)
            .map(|p| Party { key: p.key, side: p.side, says_name: p.says_name.clone(), peer_write: p.peer_write })
            .collect()
    }

    /// Карточки, у которых в книге есть хоть одно разрешение, — из того же
    /// снимка и тоже ДЛЯ ПОКАЗА.
    ///
    /// Нужно затем, что книга ключуется ключом карточки, а ключ человек
    /// может у карточки отнять: строку `id` в файле настроек правят руками,
    /// он весь для этого и написан. Разрешения тогда остаются в книге, а
    /// карточки, к которой они выданы, в списке больше нет — и из окна их не
    /// видно и не отозвать. Молчаливая потеря выданного человеком доступа —
    /// ровно то, от чего лечится весь проект, поэтому окну нужен способ
    /// СПРОСИТЬ, за кем числятся разрешения, а не только «кто у этой
    /// карточки».
    pub fn cards(&self) -> Vec<CardId> {
        let mut out: Vec<CardId> = Vec::new();
        for p in &self.data.enrolled {
            if !out.contains(&p.card) {
                out.push(p.card.clone());
            }
        }
        out
    }

    /// Единственное место, которое меняет файл: берёт межпроцессный замок,
    /// перечитывает файл заново (а не доверяет `self.data` — круг починки 1,
    /// Important 4: другой `Book`, живущий в соседнем процессе на тот же
    /// файл, мог дописать его между нашим предыдущим чтением и этим
    /// вызовом), даёт вызывающему изменить свежий снимок, чистит просрочку и
    /// пишет. `self.data` обновляется ТОЛЬКО после успешной записи — если
    /// запись не удалась, в памяти остаётся прежнее (совпадающее с диском)
    /// состояние, а не та правка, которая на диск не попала (иначе
    /// `spend`, доложивший об ошибке записи, вернул бы тикет к жизни в
    /// памяти этого процесса, а на следующем перезапуске — и на диске).
    fn mutate<T>(&mut self, f: impl FnOnce(&mut BookFile) -> T) -> Result<T, String> {
        let _guard = lock(&self.path)?;
        let mut fresh = load_raw(&self.path)?;
        let result = f(&mut fresh);
        prune_expired(&mut fresh);
        write_book(&self.path, &fresh)?;
        self.data = fresh;
        Ok(result)
    }
}

/// Имя файла партнёров — рядом с книгой зачислений, но СВОЙ.
const PARTNERS_FILE: &str = "partners.toml";

/// Партнёр зовущей карточки: к кому эта карточка ходит и как его найти.
///
/// `key` — ключ узла той стороны; он и есть адресат переподключения
/// (`Node::dial` принимает один `EndpointId`). `relay`/`direct` — подсказки
/// того же вида, что ездят в коде подключения (`Ticket::addr`): пробуются
/// первыми и тихо забываются, когда не сработали, — значит устареть
/// безвредно, а польза от них та же, что от петли в коде: две копии на одной
/// машине находят друг друга без интернета и после перезапуска.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Partner {
    pub key: EndpointId,
    #[serde(default)]
    pub relay: Option<String>,
    #[serde(default)]
    pub direct: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct PartnerRow {
    /// Карточка — КЛЮЧОМ, не именем, по тому же доводу, что у `Enrolled` выше (`cfg::CardId`).
    card: CardId,
    key: EndpointId,
    #[serde(default)]
    relay: Option<String>,
    #[serde(default)]
    direct: Vec<String>,
    /// Признак базы той карточки, за которой числится поток этой зовущей
    /// карточки, — как его назвала та сторона в `enroll_ok` (`BaseFields::base_id`).
    ///
    /// **Чей это ключ.** С 10.11 признак базы на проводе — это ключ карточки (`cfg::CardId`), но ключ ТОЙ стороны: он назван на другой
    /// машине, в наших настройках его нет, и сравнивать его с нашими ключами не за что. Поле `card` выше — НАШ ключ, этот — ИХ, и путать
    /// их нельзя: наш отвечает на «кому это разрешено», их — на «чем назвать себя при возврате». Тип один (разные типы на одно понятие
    /// поставили бы преобразование строки на каждую границу, а преобразование — место, где подставляют не то), поэтому различие держат
    /// имена полей и эта докстрока.
    ///
    /// **Зачем он на диске.** В памяти он уже живёт (`peer::InHand::card`)
    /// и со второго круга возврат называет карточку сам, так что отзыв одной
    /// карточки не рвёт связь по остальным (спека контракта). Но живёт он
    /// ровно до перезапуска: после него зовущая сторона снова не называет
    /// карточку, та сторона отвечает всем списком своих баз, поток числится за
    /// всеми сразу — и отзыв любой из них его режет. Пережить перезапуск он
    /// может только тут, рядом с партнёром, по тому же доводу, по которому
    /// здесь лежит сам ключ: код одноразовый, и после перезапуска связь с той
    /// машиной держится только тем, что записано.
    ///
    /// **Почему не поле `Partner`.** `Partner` собирают литералом структуры в
    /// `peer::remember` — файле соседней работы, правка в котором была бы
    /// затёрта; новое поле там не скомпилировалось бы вовсе. Поэтому признак
    /// живёт в самой записи, а спрашивают и пишут его отдельной парой
    /// (`base_id_of`/`remember_base_id`) — и `remember` его БЕРЕЖЁТ, чтобы
    /// переподключение не стирало то, что писал другой писатель той же строки.
    ///
    /// `None` — не знаем: партнёра записали, а карточку ещё не назвали, либо
    /// файл от прежней версии программы (`serde(default)`, старый
    /// `partners.toml` читается без отказа).
    #[serde(default)]
    /// Ключ карточки ТОЙ машины — проводный (`wire::CardRef`): в наше пространство имён он не переводится никогда, у нас он только
    /// хранится и уезжает обратно при возврате.
    base_id: Option<crate::wire::CardRef>,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
struct PartnersFile {
    #[serde(default)]
    partners: Vec<PartnerRow>,
}

/// Куда ходят ЗОВУЩИЕ карточки этого рабочего места — по одному партнёру на
/// карточку.
///
/// **Почему это не в книге зачислений.** Книга (`Book` выше) — про тех, кого
/// пустил Я: кому выдан код, кто предъявил секрет, кому человек разрешил
/// доступ к МОЕЙ базе. Это — про того, к кому хожу Я: ни разрешения, ни
/// тикета, ни решения человека здесь нет вовсе, и спрашивают это в
/// противоположную минуту (не «пускать ли», а «куда звонить»). Сложить их в
/// один файл значило бы, что чистка зачислений рвёт зовущей стороне
/// переподключение, а строка «кого я пустил» и строка «к кому я хожу» идут
/// одним списком, в котором их уже не различить глазом.
///
/// **Почему это не в `1c-connect.toml`.** Там настройки, которые человек
/// заводит руками (решение, с которого начинается докстрока модуля); сюда
/// пишет программа, сама, после зачисления. Писать в файл человека из
/// фонового потока значило бы переписывать настройки у него под руками.
///
/// **Почему без этого места зовущая не вернётся никогда.** Код подключения
/// одноразовый (`Book::spend`) и живёт сутки: второй раз он не сработает.
/// После зачисления единственное, что связывает карточку с той машиной, —
/// ключ её узла, и если его не записать, перезапуск программы стирает
/// подключение насовсем, хотя человек ничего не отзывал (спека контракта,
/// «Что хранится после»).
pub struct Partners {
    path: PathBuf,
    data: PartnersFile,
}

impl Partners {
    /// Читает файл или заводит пустой — нет файла значит зовущих карточек
    /// ещё не зачисляли, а не беда.
    ///
    /// Непонятный файл откладывается рядом тем же `quarantine`, что у книги,
    /// и список продолжает жить пустым: подсказки здесь восстановимы (человек
    /// подключится кодом ещё раз), и терять из-за них запуск программы не за
    /// что.
    pub fn open(state_dir: &Path) -> Result<Partners, String> {
        let path = state_dir.join(PARTNERS_FILE);
        let _guard = lock(&path)?;
        let data = load_partners(&path)?;
        Ok(Partners { path, data })
    }

    /// К кому ходит эта карточка. `None` — зачисления ещё не было, и звонить
    /// некуда: нужен код.
    pub fn of(&self, card: &CardId) -> Option<Partner> {
        self.data.partners.iter().find(|p| &p.card == card).map(|p| Partner {
            key: p.key,
            relay: p.relay.clone(),
            direct: p.direct.clone(),
        })
    }

    /// Все зовущие карточки с партнёрами — тем, кто поднимает звонки при
    /// запуске: без этого списка он не знал бы, кому звонить до первого
    /// щелчка человека.
    pub fn all(&self) -> Vec<(CardId, Partner)> {
        self.data
            .partners
            .iter()
            .map(|p| (p.card.clone(), Partner { key: p.key, relay: p.relay.clone(), direct: p.direct.clone() }))
            .collect()
    }

    /// Запомнить партнёра карточки (или обновить его подсказки). Партнёр у
    /// карточки один: карточка — это одно соединение с одной той стороной, и
    /// второй партнёр у неё означал бы, что звонить надо наугад.
    ///
    /// Запись ПРАВИТСЯ, а не заменяется целиком: у строки два писателя — этот и
    /// `remember_base_id`, — и прежнее «вырезать и дописать заново» стирало бы
    /// признак базы на каждом переподключении, то есть ровно там, где он и
    /// нужен. Сменился ключ той стороны (человек подключился кодом к ДРУГОЙ
    /// машине) — признак снимается: он про базы прежней машины, и на новой не
    /// значит ничего, а соврать им значило бы числить поток за карточкой, о
    /// которой с этой стороной не договаривались.
    pub fn remember(&mut self, card: &CardId, partner: &Partner) -> Result<(), String> {
        self.mutate(|data| match data.partners.iter_mut().find(|p| &p.card == card) {
            Some(row) => {
                if row.key != partner.key {
                    row.base_id = None;
                }
                row.key = partner.key;
                row.relay = partner.relay.clone();
                row.direct = partner.direct.clone();
            }
            None => data.partners.push(PartnerRow {
                card: card.clone(),
                key: partner.key,
                relay: partner.relay.clone(),
                direct: partner.direct.clone(),
                base_id: None,
            }),
        })
    }

    /// Чем эта зовущая карточка назовёт себя при возврате — признак базы, о
    /// которой с той стороной договорились (довод и разбор — у поля
    /// `PartnerRow::base_id`).
    ///
    /// `None` — не знаем, и выдумывать нельзя: возврат тогда идёт без имени
    /// карточки, та сторона отвечает всем списком своих баз, и так это и было
    /// до появления этого поля. Из снимка, как и `of`: решение «куда звонить»
    /// и так читает файл сам (`peer::target`).
    pub fn base_id_of(&self, card: &CardId) -> Option<crate::wire::CardRef> {
        self.data.partners.iter().find(|p| &p.card == card).and_then(|p| p.base_id.clone())
    }

    /// Запомнить, за какой карточкой та сторона числит наш поток. Зовётся,
    /// когда ответ однозначен, — и только тогда: `Option` здесь не принимается
    /// нарочно, «не знаю» записывать некуда и незачем.
    ///
    /// Партнёра ещё нет — отказ СЛОВАМИ, а не тихое ничто: цеплять признак не
    /// к чему, и молчание об этом выглядело бы как записанный признак, который
    /// потом необъяснимо не читается. На деле этот порядок не встречается —
    /// партнёра записывает тот же круг и раньше (`peer::one_round`).
    pub fn remember_base_id(&mut self, card: &CardId, base_id: &crate::wire::CardRef) -> Result<(), String> {
        let base_id = base_id.clone();
        self.mutate(move |data| match data.partners.iter_mut().find(|p| &p.card == card) {
            Some(row) => {
                row.base_id = Some(base_id);
                Ok(())
            }
            None => Err(format!("партнёра карточки {card} ещё нет — признак базы цеплять не к чему")),
        })?
    }

    /// Забыть партнёра: карточку удалили, или человек подключается кодом к
    /// другой машине. Нет записи — не беда, забывать нечего.
    pub fn forget(&mut self, card: &CardId) -> Result<(), String> {
        self.mutate(|data| data.partners.retain(|p| &p.card != card))
    }

    /// Тем же приёмом и по тому же доводу, что `Book::mutate`: замок, свежее
    /// чтение, запись через переименование. Снимок в памяти обновляется
    /// только после удачной записи.
    ///
    /// Чтение — тем же `load_partners`, что у `open`, и это не отделка (задача
    /// 2 плана починки по двум ревью, находка 2). Своё чтение здесь мерило
    /// один файл ДВУМЯ мерами: `open` на непонятном файле кладёт его в
    /// карантин и говорит словами, а здешнее `unwrap_or_default` считало тот
    /// же файл пустым МОЛЧА — и следующая же запись печатала этот «пустой»
    /// список поверх всех партнёров, то есть зовущие карточки теряли, куда им
    /// возвращаться, без единого слова и без отложенной копии, по которой это
    /// можно было бы разобрать. Отказ диска (не `NotFound`) тем же чтением
    /// стал отказом СЛОВАМИ до какой-либо записи, а не тихой заменой файла на
    /// пустой.
    fn mutate<T>(&mut self, f: impl FnOnce(&mut PartnersFile) -> T) -> Result<T, String> {
        let _guard = lock(&self.path)?;
        let mut fresh = load_partners(&self.path)?;
        let result = f(&mut fresh);
        let text = toml::to_string_pretty(&fresh).map_err(|e| format!("партнёры не собрались в toml: {e}"))?;
        write_atomic(&self.path, &text)?;
        self.data = fresh;
        Ok(result)
    }
}

fn now_secs() -> u64 {
    SystemTime::now().duration_since(UNIX_EPOCH).unwrap_or(Duration::ZERO).as_secs()
}

/// Общий поиск для `verdict` и `spend`: по секрету — за постоянное
/// время (`constant_time_eq`) — и по сроку. `spend` после успеха
/// дополнительно удаляет найденную запись сам; здесь только позиция и
/// решение, жива ли она.
///
/// Отдаёт ВЕРДИКТ, а не `Result<usize, String>`: слова отказа — дело
/// вызывающего (`spend` их и пишет), а здесь они только мешали бы — тому,
/// кому нужен не текст, а различие (`verdict`), пришлось бы разбирать текст
/// обратно.
fn locate(data: &BookFile, secret: &[u8; 32]) -> Found {
    let want = fingerprint(secret);
    let now = now_secs();
    match data.tickets.iter().position(|t| constant_time_eq(&t.fingerprint, &want)) {
        None => Found::Unknown,
        Some(pos) if data.tickets[pos].until < now => Found::Expired,
        Some(pos) => Found::At(pos),
    }
}

/// Что нашлось по секрету — внутренний вид `Verdict`, с позицией записи для
/// `spend`. Наружу позиция не ездит: она верна только под тем же замком, под
/// которым читалась.
enum Found {
    At(usize),
    Expired,
    Unknown,
}

/// Вердикт по предъявленному коду. Три случая, а не два, — см. `verdict`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Verdict {
    /// Код настоящий и жив; вот карточка, к которой он выдан.
    Card(CardId),
    /// Срок кода вышел.
    Expired,
    /// Такого кода в книге нет: его либо не выдавали, либо уже погасили.
    /// Различить эти два снаружи нечем нарочно — хранить «потрачен» спека
    /// запрещает («тикет не хранится нигде после погашения»).
    Unknown,
}

/// Слова `spend` на два вердикта из трёх. Константами, а не строками по месту:
/// текст отказа — предмет, который правят, и два писателя одного текста
/// разошлись бы на первой же правке.
const UNKNOWN_TICKET: &str = "Код не найден или уже погашен.\nПопросите новый на той машине, которая его выдала.";
const EXPIRED_TICKET: &str = "Код устарел.\nПопросите новый на той машине, которая его выдала.";

/// Выбрасывает тикеты, срок которых уже прошёл. Возвращает `true`, если
/// что-то выбросили, — `open` отличает этим «надо дописать файл» от «файл и
/// так в порядке».
fn prune_expired(data: &mut BookFile) -> bool {
    let now = now_secs();
    let before = data.tickets.len();
    data.tickets.retain(|t| t.until >= now);
    before != data.tickets.len()
}

/// sha256 от секрета — то, что лежит в файле вместо самого секрета (см.
/// докстроку `IssuedTicket`). Hex, а не сырые байты: тот же вид, что у
/// остального в этом toml, читается в журнале разбора беды без расшифровщика.
fn fingerprint(secret: &[u8; 32]) -> String {
    use sha2::{Digest, Sha256};
    let mut h = Sha256::new();
    h.update(secret);
    hex::encode(h.finalize().as_slice())
}

/// Сравнение двух отпечатков за постоянное время: без единого раннего
/// выхода внутри цикла по содержимому, только по длине. Длина отпечатка не
/// секрет (у sha256 она всегда одна), так что выход по ней ничего не выдаёт
/// — в отличие от выхода по первому несовпавшему байту, который и выдаёт,
/// сколько байт угадано верно.
fn constant_time_eq(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a.len() != b.len() {
        return false;
    }
    let mut diff = 0u8;
    for i in 0..a.len() {
        diff |= a[i] ^ b[i];
    }
    diff == 0
}

/// Путь файла межпроцессного замка — ОТДЕЛЬНЫЙ от `enrolled.toml`, никогда
/// не переименовываемый. `write_atomic`/`write_book` заменяют данные
/// переименованием: замок на САМОМ `enrolled.toml` держался бы за старый
/// инод уже после первой же записи, защищая файл, которого под этим путём
/// больше нет, — ровно та ошибка, по которой `single_instance.rs` запирает
/// замком КАТАЛОГ состояния, а не файл, который держит `acquire`.
fn lock_path(path: &Path) -> PathBuf {
    path.with_extension("toml.lock")
}

/// Берёт межпроцессный замок с короткими повторами (круг починки 1,
/// Important 4): окно и подкоманда `mcp` живут одновременно и оба держат
/// свой `Book` на один файл — голый один `try` отказывал бы человеку на
/// совпадении в доли миллисекунды, которое само пройдёт. Предел — не
/// вечность: зависший держатель называет себя отказом словами, а не тихим
/// бесконечным ожиданием.
fn lock(path: &Path) -> Result<single_instance::Guard, String> {
    let lock_path = lock_path(path);
    let deadline = Instant::now() + Duration::from_millis(500);
    loop {
        match single_instance::file_lock(&lock_path) {
            Ok(Some(guard)) => return Ok(guard),
            Ok(None) => {
                if Instant::now() >= deadline {
                    return Err(format!(
                        "Файл состояния занят другим процессом дольше полсекунды.\nПовторите действие.\nЕсли это повторяется, сообщите нам, \
                         назвав файл {}.",
                        lock_path.display()
                    ));
                }
                std::thread::sleep(Duration::from_millis(5));
            }
            Err(e) => return Err(format!("не удалось взять замок {}: {e}", lock_path.display())),
        }
    }
}

/// Читает файл в структуру или заводит пустую (файла нет — не беда, первый
/// запуск).
///
/// Непонятный файл — не повод терять ВСЕ зачисления сразу (круг починки 1,
/// Important 5): он откладывается рядом (`enrolled.toml.broken`) для
/// разбора беды, а книга продолжает жить пустой — отказ не возвращается
/// вызывающему, только слово в журнал через `quarantine`. Это касается и
/// файла от прежнего коммита ветки (с полем `secret` вместо `fingerprint`):
/// он тоже не разберётся новой схемой и уйдёт тем же путём — с той
/// разницей, что `quarantine` вычищает из отложенной копии узнаваемое поле
/// `secret`, а не сохраняет голый секрет под новым именем навсегда, и
/// говорит об этой вычистке словами в тот же журнал (круг починки 2):
/// человек может открыть отложенный файл сам и сравнить его с прежним, и
/// молчание о том, что мы его сами изменили, было бы тем самым «молчаливо
/// неверным», от которого лечится весь проект.
///
/// **Решение владельца (круг починки 2, спорить не предложено): карантин —
/// «всё или ничего», частичного спасения читаемых записей из непонятного
/// файла НЕТ.** Наполовину разобранный файл опаснее целого карантина:
/// человек считал бы кого-то зачисленным, а записи о нём на самом деле уже
/// нет, и узнал бы об этом в самый неподходящий момент. Зачисления
/// восстанавливаются тем же способом, каким выдавались, — заново зачислить
/// дешевле, чем жить с недоверенной серединой файла.
fn load_raw(path: &Path) -> Result<BookFile, String> {
    match std::fs::read_to_string(path) {
        Ok(text) => match toml::from_str(&text) {
            Ok(data) => Ok(data),
            Err(e) => {
                quarantine(path, &text, "зачислений", &e.to_string());
                Ok(BookFile::default())
            }
        },
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(BookFile::default()),
        Err(e) => Err(format!("не удалось прочитать {}: {e}", path.display())),
    }
}

/// То же для файла партнёров — ОДНО чтение на оба его читателя (`open` и
/// `mutate`): две меры одного файла и были находкой 2 задачи 2 (см. докстроку
/// `Partners::mutate`).
///
/// Непонятный файл откладывается рядом тем же `quarantine`, и список
/// продолжает жить пустым: подсказки здесь восстановимы — человек подключается
/// кодом ещё раз, — и терять из-за них запуск программы не за что. Отказ
/// чтения, который не «файла нет», возвращается вызывающему: он значит, что
/// файл есть и мы его не прочли, а печатать поверх непрочитанного нельзя.
fn load_partners(path: &Path) -> Result<PartnersFile, String> {
    match std::fs::read_to_string(path) {
        Ok(text) => match toml::from_str(&text) {
            Ok(data) => Ok(data),
            Err(e) => {
                quarantine(path, &text, "партнёров", &e.to_string());
                Ok(PartnersFile::default())
            }
        },
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(PartnersFile::default()),
        Err(e) => Err(format!("не удалось прочитать {}: {e}", path.display())),
    }
}

/// Откладывает непонятный файл рядом и говорит об этом словами в журнал
/// (`eprintln!` — тот же приём, что у `single_instance::serve_show_requests`
/// для похожих «не вышло, но не фатально» случаев). Переименование, а не
/// копирование: тогда исходный путь освобождается, и следующая же запись
/// честно заводит там свежий файл, а не натыкается на тот же разбитый
/// текст по кругу.
///
/// Когда `redact_legacy_secret` и правда что-то вычистила — это отдельная
/// правка отложенной копии, и о ней нельзя молчать (круг починки 2):
/// человек может открыть `enrolled.toml.broken` сам, сравнить с тем, что
/// было, и увидеть не то, что мы туда отложили, а то, что мы это ещё и
/// переписали. Вторая строка журнала называет это прямо — что секрет
/// прежнего образца был и его вычистили, а не просто что файл отложен.
fn quarantine(path: &Path, text: &str, what: &str, why: &str) {
    let broken = path.with_extension("toml.broken");
    let safe = redact_legacy_secret(text);
    let redacted = safe != text;
    let renamed = std::fs::rename(path, &broken).is_ok();
    if !renamed || redacted {
        let _ = std::fs::write(&broken, &safe);
    }
    // Чей это файл — словом вызывающего (`what`): в карантин ходят оба файла
    // каталога состояния, и строка «файл зачислений не разобрался» про
    // `partners.toml` была бы неверной ровно там, где человек читает журнал,
    // чтобы понять, что у него сломалось.
    eprintln!("{}: файл {what} не разобрался ({why}) — отложен как {}, начинаю с пустого", path.display(), broken.display());
    if redacted {
        eprintln!(
            "{}: в отложенной копии был секрет тикета прежнего образца (поле `secret`) — он вычищен, хранить его незачем",
            broken.display()
        );
    }
}

/// Вычищает значение поля `secret` — единственное узнаваемое отличие
/// формата ДО перехода на отпечаток (коммит с заголовком про sha256-отпечаток
/// секрета тикета). Карантинная копия нужна для разбора беды (структура,
/// число записей, имена карточек), а не для того, чтобы голый секрет из
/// файла прежней версии продолжил лежать на диске открытым текстом под
/// новым именем бесконечно.
fn redact_legacy_secret(text: &str) -> String {
    text.lines()
        .map(|line| {
            let trimmed = line.trim_start();
            if trimmed.starts_with("secret ") || trimmed.starts_with("secret=") || trimmed.starts_with("secret\t") {
                "secret = \"<вычищено при карантине>\"".to_string()
            } else {
                line.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn write_book(path: &Path, data: &BookFile) -> Result<(), String> {
    let text = toml::to_string_pretty(data).map_err(|e| format!("зачисления не собрались в toml: {e}"))?;
    write_atomic(path, &text)
}

/// Через временный файл и переименование — тот же приём, что у `node::write_sealed`:
/// этот файл несёт зачисления ВСЕХ карточек рабочего места, и обрыв питания
/// посреди прямой записи стёр бы их все разом, а не только то одно
/// изменение, ради которого шла запись.
///
/// На Unix временный файл создаётся с правами 0600 сразу при создании, одним
/// системным вызовом (требование 3 замечания безопасности) — так между
/// появлением файла на диске и ограничением прав не остаётся окна, в которое
/// файл мог бы прочитать кто-то кроме владельца; переименование права не
/// меняет, так что итоговый файл получает их тем же путём. На Windows
/// отдельного пути сузить права ФАЙЛА этот крейт не заводит ни для одного
/// файла состояния (приватность секретов там несёт DPAPI — `secrets.rs` —
/// а не ACL файла): файл наследует права каталога состояния (`Kit::state`),
/// и если своего пути нет — то нет, и это стоит сказать прямо, а не
/// промолчать.
#[cfg(unix)]
fn write_atomic(path: &Path, text: &str) -> Result<(), String> {
    use std::io::Write;
    use std::os::unix::fs::OpenOptionsExt;
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("не удалось создать {}: {e}", dir.display()))?;
    }
    let tmp = path.with_extension("toml.tmp");
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(true)
        .mode(0o600)
        .open(&tmp)
        .map_err(|e| format!("не удалось записать {}: {e}", tmp.display()))?;
    f.write_all(text.as_bytes()).map_err(|e| format!("не удалось записать {}: {e}", tmp.display()))?;
    drop(f);
    std::fs::rename(&tmp, path).map_err(|e| {
        let _ = std::fs::remove_file(&tmp);
        format!("не удалось переименовать {} в {}: {e}", tmp.display(), path.display())
    })
}

#[cfg(not(unix))]
fn write_atomic(path: &Path, text: &str) -> Result<(), String> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("не удалось создать {}: {e}", dir.display()))?;
    }
    let tmp = path.with_extension("toml.tmp");
    std::fs::write(&tmp, text).map_err(|e| format!("не удалось записать {}: {e}", tmp.display()))?;
    std::fs::rename(&tmp, path).map_err(|e| {
        let _ = std::fs::remove_file(&tmp);
        format!("не удалось переименовать {} в {}: {e}", tmp.display(), path.display())
    })
}

